/**
 * НАТИВНЫЙ ПУТЬ v3: frontend v3 → AST v2 → (общий проход разрешения) → regcodegen →
 * регистровая VM. Две вещи, которые ревью назвало блокерами:
 *
 *   1. `длина` — один узел, реализацию выбирает СЕМАНТИКА по типу операнда:
 *      `длина "абв"` → `система.строка.длина`, `длина [1,2,3]` → `система.массив.длина`.
 *      Проверяется ЗНАЧЕНИЕМ на обеих VM, а не только видом AST: строковая длина
 *      раньше была недостижима, и AST-проверка этого не ловила.
 *   2. Счётный цикл `для i от a до b` доходит до `regcodegen` без отказа —
 *      он разворачивается во фронтенде в существующие узлы (`пусть` + `пока`).
 */
import { describe, expect, it } from "vitest";
import { validateNamedTypesAndRewrite } from "../compiler/compiler";
import { compile } from "../compiler/codegen";
import { compileToReg } from "../compiler/regcodegen";
import { createDefaultInvokeHandler, VM } from "../runtime/vm/interpreter";
import { RegVM } from "../runtime/vm/reginterpreter";
import { parseV3 } from "./index";
import type { Module } from "../compiler/ast";

const ФАЙЛ = "нативный.osnova";

/** v3-исходник → AST, доведённый до вида, который ждут кодогены. */
function модульV3(источник: string): Module {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `v3 не разобрал: ${р.errors.join("; ")}`).toEqual([]);
  const м = р.program!.modules[0]!;
  const ошибки = validateNamedTypesAndRewrite(м);
  expect(ошибки, `проход разрешения: ${ошибки.join("; ")}`).toEqual([]);
  return м;
}

/** Стековая VM: эталон поведения (байткод из того же AST). */
async function стековая(м: Module): Promise<unknown> {
  const байткод = compile(м);
  const vm = new VM(байткод, { invoke: createDefaultInvokeHandler(), maxSteps: 200_000 });
  return vm.runProcedure(vm.findProcedureIndex("главная"), []);
}

/** Регистровая VM: нативная цель. */
async function регистровая(м: Module): Promise<unknown> {
  const reg = compileToReg(м);
  const vm = new RegVM(reg, { invoke: createDefaultInvokeHandler(), maxSteps: 200_000 });
  return vm.runProcedure(vm.findProcedureIndex("главная"), []);
}

describe("v3 → нативный путь (regcodegen), без второго рантайма", () => {
  it("`длина` строки и списка: реализацию выбирает семантика по типу", async () => {
    const м = модульV3(`действие главная()
  пусть строка = "абв"
  пусть числа = [1, 2, 3, 4]
  вернуть длина строка * 100 + длина числа
конец главная
`);
    // 3 * 100 + 4 — на обеих VM одно и то же число.
    expect(await стековая(м)).toBe(304);
    expect(await регистровая(м)).toBe(304);
  });

  it("`длина` по аннотации параметра: Строка против Списка", async () => {
    const м = модульV3(`процедура сколько(с: Строка) -> Число
  вернуть длина с
конец сколько
действие главная()
  вернуть сколько("абвгд")
конец главная
`);
    expect(await стековая(м)).toBe(5);
    expect(await регистровая(м)).toBe(5);
  });

  it("счётный цикл доходит до регистров: сумма 1..10", async () => {
    const м = модульV3(`действие главная()
  пусть сумма = 0
  для номер от 1 до 10
    сумма = сумма + номер
  конец для
  вернуть сумма
конец главная
`);
    expect(await стековая(м)).toBe(55);
    expect(await регистровая(м)).toBe(55);
  });

  it("счётный цикл с шагом и убыванием", async () => {
    const м = модульV3(`действие главная()
  пусть нечётных = 0
  для номер от 1 до 10 шаг 3
    нечётных = нечётных + 1
  конец для
  пусть обратно = 0
  для номер от 5 до 1 шаг 0 - 1
    обратно = обратно * 10 + номер
  конец для
  вернуть нечётных * 100000 + обратно
конец главная
`);
    // шагов 1,4,7,10 → 4; обратно = 54321
    expect(await стековая(м)).toBe(4 * 100000 + 54321);
    expect(await регистровая(м)).toBe(4 * 100000 + 54321);
  });

  it("`повторять N раза` — разворот в существующие узлы, не отказ", async () => {
    const м = модульV3(`действие главная()
  пусть счёт = 0
  повторять 3 раза
    счёт = счёт + 1
  конец повторять
  вернуть счёт
конец главная
`);
    expect(await стековая(м)).toBe(3);
    expect(await регистровая(м)).toBe(3);
  });

  it("`повторять` с вложенным перебором: 2 × 3 = 6", async () => {
    const м = модульV3(`действие главная()
  пусть пар = 0
  повторять 2 раза
    для каждого число в [1, 2, 3]
      пар = пар + 1
    конец для
  конец повторять
  вернуть пар
конец главная
`);
    expect(await стековая(м)).toBe(6);
    expect(await регистровая(м)).toBe(6);
  });

  it("`шаг` принимает литерал и его запись через `0 - 1`, но не выражение", () => {
    const ок = (шаг: string) =>
      parseV3(`действие главная()\n  для н от 5 до 1 ${шаг}\n    вывести н\n  конец для\n  вернуть 0\nконец главная\n`, ФАЙЛ);
    expect(ок("шаг 3").errors).toEqual([]);
    expect(ок("шаг -1").errors).toEqual([]);
    expect(ок("шаг 0 - 1").errors).toEqual([]);
    // Вычисляемый шаг — НАЗВАННЫЙ отказ: иначе фронтенд держал бы свёртку констант.
    const плохо = ок("шаг 2 + 1");
    expect(плохо.errors.join(" ")).toContain("шаг — литерал");
    const ноль = ок("шаг 0");
    expect(ноль.errors.join(" ")).toContain("шаг не может быть нулём");
  });

  it("`длина` без выведенного типа — НАЗВАННЫЙ ОТКАЗ, а не догадка", () => {
    // Неаннотированный параметр: тип невыводим, и молчаливая массивная длина
    // вернула бы на строке неверное число — та самая тихая ложь.
    const р = parseV3(`процедура сколько(что) -> Число\n  вернуть длина что\nконец сколько\nдействие главная()\n  вернуть сколько([1, 2])\nконец главная\n`, ФАЙЛ);
    expect(р.errors).toEqual([]);
    const ошибки = validateNamedTypesAndRewrite(р.program!.modules[0]!);
    expect(ошибки.join(" ")).toContain("требует известного типа операнда");
    // А с аннотацией — разрешено: отказ не про слово, а про неизвестный тип.
    const сТипом = parseV3(`действие главная()\n  пусть имена: Список Строка = ["а", "б"]\n  вернуть длина имена\nконец главная\n`, ФАЙЛ);
    expect(validateNamedTypesAndRewrite(сТипом.program!.modules[0]!)).toEqual([]);
  });

  it("контроль: `длина` разрешена в РАЗНЫЕ вызовы, а не в один", () => {
    const м = модульV3(`действие главная()
  пусть строка = "аб"
  пусть числа = [1, 2, 3]
  вернуть длина строка + длина числа
конец главная
`);
    const вид = JSON.stringify(м).match(/система\.(строка|массив)\.длина/g) ?? [];
    expect(new Set(вид)).toEqual(new Set(["система.строка.длина", "система.массив.длина"]));
  });

  /**
   * `подстрока` — ВСТРОЕННОЕ СЛОВО v3 (добавлено 2026-10-23).
   *
   * Зачем слово: решение владельца 2026-10-10 сделало `с[и]` ЧИСЛОМ (код Unicode), и после этого у
   * v3 не осталось ни одного способа получить из исходника ТЕКСТ: три сегмента в v3 не пишутся
   * (долг §3.105.3), а `с[и]` даёт число. Без среза self-host-лексер (`src/self-host/lexer.osnova`)
   * не выразим: пять его проверок краснели «ожидалось Строка, получено Число».
   *
   * Проверка — ЗНАЧЕНИЕМ на ОБЕИХ VM, а не видом AST: AST-проверка не поймала бы «слово разобралось,
   * а вызов ушёл не тот» (ровно так `длина` однажды уезжала в массивную). Второй аргумент — контроль:
   * срез НЕ пустой и НЕ целая строка, то есть границы учтены.
   */
  it("`подстрока` — слово v3: срез по кодовым точкам, значение на обеих VM", async () => {
    const м = модульV3(`действие главная()
  вернуть длина подстрока("абвг", 1, 3) * 10 + длина подстрока("абвг", 0, 1)
конец главная
`);
    // 2 * 10 + 1: срез «бв» и срез «а».
    expect(await стековая(м)).toBe(21);
    expect(await регистровая(м)).toBe(21);
    expect(JSON.stringify(м)).toContain("система.строка.подстрока");
  });

  it("`подстрока` без трёх аргументов — НАЗВАННЫЙ ОТКАЗ, а не кодоген", () => {
    const р = parseV3(`действие главная()\n  вернуть длина подстрока("абв", 0)\nконец главная\n`, ФАЙЛ);
    expect(р.errors.join(" ")).toContain("«подстрока» требует трёх аргументов");
  });
});
