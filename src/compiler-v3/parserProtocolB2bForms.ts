/** Все 40 форм подряд: `[имя_подэтапа, тело]`, порядок — как в ките. */
export function всеФормыB2b(): ReadonlyArray<readonly [string, string]> {
  const итог: Array<readonly [string, string]> = [];
  for (const этап of ['b2b1', 'b2b2', 'b2b3', 'b2b4', 'b2b5'] as const) {
    for (const тело of ПРОГРАММЫ_B2B[этап]) итог.push([этап, тело] as const);
  }
  return итог;
}
