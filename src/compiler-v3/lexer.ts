/** Ошибка разбора в формате публичной точки v3: `файл:строка: текст`. */
export function formatV3Error(filename: string, line: number, message: string): string {
  return `${filename}:${line}: ${message}`;
}

/**
 * Буква — латиница и кириллица (с `ё`/`Ё`). Цифры и `_` буквами не считаются:
 * имя может начинаться только с буквы или `_`.
 */
function isLetter(c: string): boolean {
  if (c === "") return false;
  const k = c.charCodeAt(0);
  return (
    (k >= 0x41 && k <= 0x5a) ||
    (k >= 0x61 && k <= 0x7a) ||
    (k >= 0x410 && k <= 0x44f) ||
    k === 0x401 ||
    k === 0x451
  );
}

/**
 * Разобрать исходник v3 на токены.
 *
 * Последний токен всегда `конец_файла` — парсеру не нужны проверки на пустой
 * поток. Ошибки собираются, а не бросаются; после ошибки лексирование
 * продолжается, поэтому в `errors` их может быть несколько.
 */
export function tokenizeV3(source: string, filename: string = DEFAULT_V3_FILENAME): V3LexResult {
  const tokens: V3Token[] = [];
  const errors: string[] = [];
  let i = 0;
  let line = 1;
  const push = (kind: V3TokenKind, lexeme: string, value?: number | string): void => {
    tokens.push(value === undefined ? { kind, lexeme, line } : { kind, lexeme, value, line });
  };

  while (i < source.length) {
    const c = source[i]!;
    if (c === " " || c === "\t" || c === "\r") {
      i++;
      continue;
    }
    if (c === "\n") {
      push("новая_строка", "\n");
      i++;
      line++;
      continue;
    }
    // Комментарии: `//` до конца строки, `/* */` — до закрытия (вложенности нет).
    if (c === "/" && source[i + 1] === "/") {
      while (i < source.length && source[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && source[i + 1] === "*") {
      const at = line;
      i += 2;
      while (i < source.length && !(source[i] === "*" && source[i + 1] === "/")) {
        if (source[i] === "\n") line++;
        i++;
      }
      if (i >= source.length) {
        errors.push(formatV3Error(filename, at, "незакрытый комментарий /*"));
        break;
      }
      i += 2;
      continue;
    }
    if (c === '"') {
      const at = line;
      i++;
      let value = "";
      while (i < source.length && source[i] !== '"' && source[i] !== "\n") {
        if (source[i] === "\\") {
          const e = source[i + 1];
          value += e === "n" ? "\n" : e === "t" ? "\t" : e === '"' ? '"' : e === "\\" ? "\\" : (e ?? "");
          i += 2;
          continue;
        }
        value += source[i];
        i++;
      }
      if (i >= source.length) errors.push(formatV3Error(filename, at, "незакрытая строка"));
      else if (source[i] === "\n") errors.push(formatV3Error(filename, at, "строка не закрыта до конца строки"));
      else i++; // закрывающая кавычка
      push("строка", value, value);
      continue;
    }
    if (c >= "0" && c <= "9") {
      let n = "";
      while (i < source.length && source[i]! >= "0" && source[i]! <= "9") n += source[i++];
      if (source[i] === "." && source[i + 1] !== undefined && source[i + 1]! >= "0" && source[i + 1]! <= "9") {
        n += source[i++];
        while (i < source.length && source[i]! >= "0" && source[i]! <= "9") n += source[i++];
      }
      push("число", n, Number(n));
      continue;
    }
    if (isLetter(c) || c === "_") {
      let w = "";
      while (i < source.length && (isLetter(source[i]!) || source[i] === "_" || (source[i]! >= "0" && source[i]! <= "9"))) {
        w += source[i++];
      }
      push(KEYWORDS[w] ?? "имя", w);
      continue;
    }
    const two = source.slice(i, i + 2);
    if (two === ":=") {
      errors.push(formatV3Error(filename, line, "«:=» в языке нет: присваивание — только «=»"));
      i += 2;
      continue;
    }
    if (two === "==" || two === "!=" || two === "<=" || two === ">=") {
      push(two, two);
      i += 2;
      continue;
    }
    if (c === "→") {
      push("→", "→");
      i++;
      continue;
    }
    if ("()[]{},:.?".includes(c)) {
      push(c as V3TokenKind, c);
      i++;
      continue;
    }
    if ("+-*/%<>=;|".includes(c)) {
      push(c as V3TokenKind, c);
      i++;
      continue;
    }
    errors.push(formatV3Error(filename, line, `в языке нет символа ${JSON.stringify(c)}`));
    i++;
  }

  push("конец_файла", "<конец файла>");
  return { tokens, errors };
}
