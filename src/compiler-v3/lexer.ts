export interface V3Token {
  kind: V3TokenKind;
  lexeme: string;
  /** Значение литерала: число у `число`, содержимое у `строка`. */
  value?: number | string;
  /** Номер строки, с 1. Колонки нет намеренно: формат ошибки v3 — «файл:строка: текст». */
  line: number;
}

export interface V3LexResult {
  tokens: V3Token[];
  errors: string[];
}

