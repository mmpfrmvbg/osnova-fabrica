/**
 * ЛЕКСЕР СИНТАКСИСА v3 (проект).
 *
 * Отличие от v2 — не «другой язык», а другое НАПИСАНИЕ: составные слова пишутся
 * через пробел (`конец если`, `для каждого`, `при ошибке`), а не через `_`.
 * Виды токенов намеренно совпадают с v2 (`TokenKind` из `src/compiler/lexer.ts`):
 * парсер v3 строит AST формы v2, и общий кодоген не должен знать, чем разобран
 * исходник. См. `docs/compiler-v3-plan.md`.
 */

import type { TokenKind } from "../compiler/lexer";

export interface V3Token {
  readonly kind: TokenKind;
  /** Лексема как в исходнике (для диагностики); для составных — с пробелом. */
  readonly lexeme: string;
  readonly value?: number | string;
  readonly line: number;
  readonly column: number;
}

export interface V3LexResult {
  readonly tokens: V3Token[];
  readonly errors: string[];
}

/**
 * Одиночные ключевые слова: слово исходника → вид токена.
 *
 * Виды — ИЗ v2 (`TokenKind`), новых не заводится: v3 отличается НАПИСАНИЕМ, а не
 * набором понятий. Слова, которых в v2 нет (`действие`, `разбор`, `защита`,
 * `при`, `как`, `от`, `до`, `шаг`, `повторять`, `каждого`, `Может`, `Список`,
 * `Словарь`), получают вид `идентификатор` и разбираются парсером v3 по ЛЕКСЕМЕ —
 * так граница между v2 и v3 проходит ровно в одном месте, во фронтенде.
 */
const KEYWORDS: Record<string, TokenKind> = {
  процедура: "процедура", тип: "тип", пусть: "пусть",
  экспорт: "экспорт", чистый: "чистый",
  если: "если", иначе: "иначе", пока: "пока", для: "для", в: "в",
  вернуть: "вернуть", прервать: "прервать", продолжить: "продолжить",
  конец: "конец", есть: "есть",
  да: "истина", нет: "ложь", пусто: "пусто", и: "и", или: "или", не: "не",
  нацело: "div",
};

/** Слова, которые могут стоять после `конец`: имя закрываемого блока. */
const CLOSER_NAMES = new Set(["если", "пока", "для", "разбор", "защита", "повторять", "цикл", "типа"]);

/**
 * Составной токен → вид токена v2. Ключ — фраза с пробелом.
 *
 * Здесь и живёт главное отличие v3: раньше эти понятия склеивались `_`
 * (`конец_если`, `для_каждого`, `иначе_попытка`), и замер показал, что склейка
 * дороже вдвое (`docs/token-cost-report.md`).
 */
const PHRASES: Record<string, TokenKind> = {
  "конец если": "конец_если",
  "конец пока": "конец_пока",
  "конец для": "конец_для",
  "конец цикла": "конец_цикла",
  "конец разбор": "конец_когда",
  "конец защита": "конец_попробовать",
  "конец повторять": "конец_пока",
  "конец типа": "конец_модуля",
  "иначе если": "иначе_если",
  "при ошибке": "поймать",
};

/** Встроенные операции: слово-действие v3 → канонический системный вызов v2. */
export const BUILTIN_CALLS: Record<string, string> = {
  вывести: "система.лог.вывести",
  поднять: "выбросить",
  длина: "система.массив.длина",
  добавить: "система.массив.добавить",
  удалить: "система.массив.удалить",
  создать: "система.массив.создать",
  корень: "система.математика.корень",
  округлить: "система.математика.округлить",
  остаток: "система.математика.остаток",
  обрезать: "система.строка.обрезать",
  содержит: "система.строка.содержит",
  найти: "система.строка.найти",

  выделить: "система.память.выделить",
};

function буква(c: string): boolean {
  if (!c) return false;
  const k = c.charCodeAt(0);
  return (
    (k >= 0x41 && k <= 0x5a) || (k >= 0x61 && k <= 0x7a) ||
    (k >= 0x410 && k <= 0x44f) || k === 0x401 || k === 0x451
  );
}

function цифра(c: string): boolean {
  return c >= "0" && c <= "9";
}

function продолжение(c: string): boolean {
  return буква(c) || цифра(c) || c === "_";
}

const ДВУХЗНАЧНЫЕ: Record<string, TokenKind> = {
  "==": "==", "!=": "!=", "<=": "<=", ">=": ">=",
  "+=": "+=", "-=": "-=", "*=": "*=", "/=": "/=",
  ":=": "=",
};

/** Однословные знаки: `→` и `:=` в v3 нет, `:` остаётся только в аннотациях и записях. */
const ОДНОЗНАЧНЫЕ: Record<string, TokenKind> = {
  "=": "=", "<": "<", ">": ">", "+": "+", "-": "-", "*": "*", "/": "/",
  "%": "%", "(": "(", ")": ")", "[": "[", "]": "]", "{": "{", "}": "}",
  ":": ":", ",": ",", ".": ".", "?": "?",
};

export function tokenizeV3(source: string): V3LexResult {
  const tokens: V3Token[] = [];
  const errors: string[] = [];
  let i = 0;
  let line = 1;
  let column = 1;

  const здесь = (): string => source[i] ?? "";

  const шаг = (): string => {
    const c = source[i++];
    if (c === "\n") {
      line++;
      column = 1;
    } else {
      column++;
    }
    return c ?? "";
  };

  const положить = (kind: TokenKind, lexeme: string, value?: number | string, loc?: { line: number; column: number }): void => {
    tokens.push({
      kind,
      lexeme,
      value,
      line: loc?.line ?? line,
      column: loc?.column ?? column - lexeme.length,
    });
  };

  while (i < source.length) {
    const c = здесь();

    if (c === " " || c === "\t" || c === "\r") { шаг(); continue; }

    // Комментарии: `//` до конца строки (деление нацело — слово `нацело`) и `/* */`.
    if (c === "/" && source[i + 1] === "/") {
      while (здесь() && здесь() !== "\n") шаг();
      continue;
    }
    if (c === "/" && source[i + 1] === "*") {
      const с = line;
      шаг(); шаг();
      let закрыт = false;
      while (здесь()) {
        if (здесь() === "*" && source[i + 1] === "/") { шаг(); шаг(); закрыт = true; break; }
        шаг();
      }
      if (!закрыт) errors.push(`строка ${с}: незакрытый комментарий /*`);
      continue;
    }

    if (c === "\n") {
      положить("новая_строка", "\n", undefined, { line, column });
      шаг();
      continue;
    }

    if (c === '"') {
      const с = line, к = column;
      шаг();
      let value = "";
      while (здесь() && здесь() !== '"') {
        if (здесь() === "\\") {
          шаг();
          const e = шаг();
          if (e === "n") value += "\n";
          else if (e === "r") value += "\r";
          else if (e === "t") value += "\t";
          else if (e === '"') value += '"';
          else if (e === "\\") value += "\\";
          else { value += e; errors.push(`строка ${line}: неизвестный escape \\${e}`); }
          continue;
        }
        if (здесь() === "\n") { errors.push(`строка ${line}: строка не закрыта до конца строки`); break; }
        value += шаг();
      }
      if (здесь() === '"') шаг();
      else errors.push(`строка ${с}: незакрытая строка`);
      положить("строка", '"' + value + '"', value, { line: с, column: к });
      continue;
    }

    if (цифра(c)) {
      const с = line, к = column;
      let текст = "";
      while (цифра(здесь())) текст += шаг();
      if (здесь() === "." && цифра(source[i + 1] ?? "")) {
        текст += шаг();
        while (цифра(здесь())) текст += шаг();
        положить("число", текст, Number.parseFloat(текст), { line: с, column: к });
      } else {
        положить("число", текст, Number.parseInt(текст, 10), { line: с, column: к });
      }
      continue;
    }

    if (буква(c) || c === "_") {
      const с = line, к = column;
      let слово = "";
      while (продолжение(здесь())) слово += шаг();

      // Составные слова: сначала `конец <имя блока>`, затем прочие фразы, затем
      // `для каждого`. Порядок важен: `конец для каждого` невозможно, а
      // `для каждого` — возможно.
      if (слово === "конец") {
        const save = i;
        let пробел = "";
        while (здесь() === " " || здесь() === "\t") пробел += шаг();
        if (пробел) {
          let второй = "";
          while (продолжение(здесь())) второй += шаг();
          if (CLOSER_NAMES.has(второй)) {
            const фраза = `конец ${второй}`;
            положить(PHRASES[фраза]!, фраза, undefined, { line: с, column: к });
            continue;
          }
          if (второй === "процедуры" || второй === "процедура" || второй === "модуля" || второй === "модуль") {
            // В v3 закрытий с именем процедуры и модуля НЕТ: у процедуры просто
            // «конец», файл — сам модуль и закрывать его нечем.
            errors.push(`строка ${с}: «конец ${второй}» в v3 нет: у процедуры закрытие — просто «конец»`);
            continue;
          }
          i = save;
        }
        положить("конец", "конец", undefined, { line: с, column: к });
        continue;
      }

      if (слово === "для" || слово === "иначе" || слово === "при") {
        const save = i;
        let пробел = "";
        while (здесь() === " " || здесь() === "\t") пробел += шаг();
        let второй = "";
        while (продолжение(здесь())) второй += шаг();
        const фраза = `${слово} ${второй}`;
        if (пробел && PHRASES[фраза] !== undefined) {
          положить(PHRASES[фраза]!, фраза, undefined, { line: с, column: к });
          continue;
        }
        if (слово === "при") {
          errors.push(`строка ${с}: «${фраза}» не существует: обработка пишется «при ошибке как <имя>»`);
        }
        i = save;
      }

      const вид = KEYWORDS[слово];
      if (вид !== undefined) {
        положить(вид, слово, undefined, { line: с, column: к });
        continue;
      }
      положить("идентификатор", слово, слово, { line: с, column: к });
      continue;
    }

    const два = source.slice(i, i + 2);
    if (два === ":=") {
      errors.push(`строка ${line}: «:=» в языке нет: присваивание — только «=»`);
      шаг(); шаг();
      continue;
    }
    if (ДВУХЗНАЧНЫЕ[два] !== undefined) {
      положить(ДВУХЗНАЧНЫЕ[два]!, два);
      шаг(); шаг();
      continue;
    }
    if (c === "→") {
      // Тип возврата: `процедура f() → Тип`. Вид токена — двоеточие: в AST v2
      // аннотация возврата хранится так же, и отдельный вид плодил бы развилку
      // в общем парсере без нужды.
      положить(":", "→");
      шаг();
      continue;
    }
    if (c === "|") {
      положить("|", "|");
      шаг();
      continue;
    }
    if (c === "!") {
      errors.push(`строка ${line}: «!» в языке нет: логическое НЕ пишется словом «не»`);
      шаг();
      continue;
    }
    if (c === "&") {
      errors.push(`строка ${line}: «&» в языке нет: логическое И пишется словом «и»`);
      шаг();
      continue;
    }
    if (ОДНОЗНАЧНЫЕ[c] !== undefined) {
      положить(ОДНОЗНАЧНЫЕ[c]!, c);
      шаг();
      continue;
    }
    errors.push(`строка ${line}: в языке нет символа ${JSON.stringify(c)}`);
    шаг();
  }

  положить("конец_файла", "<конец файла>");
  return { tokens, errors };
}
