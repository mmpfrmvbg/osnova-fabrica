/**
 * ЛЕКСЕР ЯЗЫКА ОСНОВА v3.
 *
 * Первая половина фронтенда v3: исходник → токены. Формы AST лексер не решает —
 * её задаёт v2 (`src/compiler/ast.ts`), и знает о ней только {@link ./parser}.
 *
 * Источник истины по синтаксису — `docs/osnova-spec.md` и его исполняемая
 * спецификация `src/spec/osnova-spec.ts` (функция `tokenize` того же контура).
 * Здесь повторён ТОТ ЖЕ состав ключевых слов и знаков, чтобы разбор v3 не разошёлся
 * со спецификацией. Отличия от прототипа названы, и их два:
 *
 *   1. Ошибка НЕ бросается: она попадает в `errors` (формат `файл:строка: текст`),
 *      лексирование продолжается со следующего символа. Требование к публичной
 *      точке `parseV3` — не бросать исключений на разборе; прототип бросает.
 *   2. `?` — обычный токен, а не «нет такого символа»: на нём парсер называет форму
 *      v2 (`?Тип`) и подсказывает `Может Тип`. Это диагностика перехода, нового
 *      синтаксиса она не открывает: тип `?Тип` парсер v3 отвергает.
 *
 * Чего в v3 нет (и лексер это подтверждает отказом): `:=`, английских алиасов,
 * `конец_X` через подчёркивание (такое слово лексируется как ИМЯ — отказ даёт
 * парсер, называя форму v2), `@`, `#`, `\` и прочих знаков вне списка языка.
 */

