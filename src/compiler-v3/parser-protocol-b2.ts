/**
 * B2: ПРОИЗВОЛЬНАЯ ЛЕНТА В ЦИКЛЕ — POST-ORDER, HARDWARE-ONLY (2026-11-12).
 *
 * `главная` строит ленту токенов и вызывает `обойти` ОДИН раз. `обойти` (глубина 1) идёт
 * циклом по произвольной ленте, держит явный стек вложенности в хвосте `лента` и вызывает
 * писателей-листьев; рекурсивного писателя нет. QEMU по-прежнему отказывает `#180` на записи
 * писателя из вызываемой (D12), железо — арбитр.
 */
import { КОД_ЛИТЕРАЛА } from './astFormat';
import { КОД_ВИДА, программаПротоколаB2aPerEvent, токеннаяЛента, токеныB1 } from './parser-protocol-probe';

const МАГИЯ = 20261108;
const МОДУЛЬ_ШАПКА = /^действие /mu;

function имяМодуля(файл: string): string {
  return (файл.split(/[\\/]/).pop() ?? файл).replace(/\.[^.]+$/u, '');
}

export function программаПротоколаB2(источник: string, файл = 'b2.osnova'): string {
  const база = программаПротоколаB2aPerEvent(источник, файл);
  const индексГлавной = база.search(МОДУЛЬ_ШАПКА);
  if (индексГлавной < 0) throw new Error('B2: B2a не отдал действие');
  const шапка = база.slice(0, индексГлавной);

  const лента = токеннаяЛента(источник, файл);
  const токены = токеныB1(источник, файл);
  const действие = токены.find((т) => т.лексема === 'действие');
  if (действие === undefined) throw new Error('B2: нет действия');
  const имя = токены[токены.findIndex((т) => т.индекс === действие.индекс) + 1]!;
  const тело = токены[токены.findIndex((т) => т.индекс === имя.индекс) + 1]!;
  // `тело` — `(` объявления, за ним `)` заголовка, и только ПОТОМ первый токен тела.
  const первый = токены[токены.findIndex((т) => т.индекс === тело.индекс) + 2]!;
  const модуль = имяМодуля(файл);
  const конецШапки = [...источник].length;
  const конецДействия = [...источник.trimEnd()].length;

  const строки: string[] = [шапка];
  const писать = (...с: string[]) => строки.push(...с);
  const к = КОД_ВИДА;

  // ── обойти: ЦИКЛ по произвольной ленте, POST-ORDER ───────────────────────────────────
  // Вложенность — ЯВНЫЙ стек `[токен_вызова, число_аргументов]` в клетках 1100+ `лента`.
  // Писатели — листья; `обойти` их только ВЫЗЫВАЕТ, а не разбирает.
  писать('процедура обойти(лента: Список Число, инд: Число, параметр: Число) -> Число');
  писать('  пусть предел = параметр нацело 65536');
  писать('  пусть т = параметр - предел * 65536');
  писать('  пусть верх = 0');
  писать('  пока т < предел');
  писать(`    если лента[т] == ${String(к['конец']!)}`);
  писать('      прервать');
  писать('    конец если');
  писать(`    если лента[т] == ${String(к['имя']!)}`);
  писать(`      если лента[т + 7 + лента[т + 5]] == ${String(к['(']!)}`);
  писать('        Списки.установить(лента, 1100 + верх, т)');
  писать('        Списки.установить(лента, 1101 + верх, 0)');
  писать('        верх = верх + 2');
  писать('        т = т + 7 + лента[т + 5]');
  писать('        т = т + 7 + лента[т + 5]');
  писать('      иначе');
  писать('        пусть р = разобрать_аргумент(лента, т)');
  писать('        если верх >= 2');
  писать('          инд = записать_имя_инд(лента, инд, т)');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 2] + лента[т + 4])');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 1])');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 3])');
  писать('          инд = записать_текст_из_инд(лента, инд, т)');
  писать('          Списки.установить(лента, 1100 + верх - 1, лента[1100 + верх - 1] + 1)');
  писать('        конец если');
  писать('        т = р нацело 65536');
  писать('      конец если');
  писать('    иначе');
  писать(`      если лента[т] == ${String(к['число']!)}`);
  писать('        пусть р = разобрать_аргумент(лента, т)');
  писать('        если верх >= 2');
  писать('          инд = записать_литерал_инд(лента, инд, т)');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 2] + лента[т + 4])');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 1])');
  писать('          инд = записать_число_инд(лента, инд, лента[т + 3])');
  писать(`          инд = записать_число_инд(лента, инд, ${String(КОД_ЛИТЕРАЛА.число)})`);
  писать('          инд = записать_текст_из_инд(лента, инд, т)');
  писать('          Списки.установить(лента, 1100 + верх - 1, лента[1100 + верх - 1] + 1)');
  писать('        конец если');
  писать('        т = р нацело 65536');
  писать('      иначе');
  писать(`        если лента[т] == ${String(к[')']!)}`);
  писать('          если верх >= 2');
  писать('            верх = верх - 2');
  писать('            пусть р = разобрать_вызов(лента, лента[1100 + верх])');
  писать('            инд = записать_начало_инд(лента, инд, лента[1100 + верх])');
  писать('            инд = записать_текст_из_инд(лента, инд, лента[1100 + верх])');
  писать('            инд = записать_конец_инд(лента, инд, (р - (р нацело 65536) * 65536) * 65536 + лента[т + 2] + лента[т + 4])');
  писать('            если верх == 0');
  писать('              инд = записать_оператор_инд(лента, инд, лента[1100 + верх])');
  писать('            иначе');
  писать('              Списки.установить(лента, 1100 + верх - 1, лента[1100 + верх - 1] + 1)');
  писать('            конец если');
  писать('          конец если');
  писать('          т = т + 7 + лента[т + 5]');
  писать('        иначе');
  писать('          т = т + 7 + лента[т + 5]');
  писать('        конец если');
  писать('      конец если');
  писать('    конец если');
  писать('  конец пока');
  писать('  вернуть инд');
  писать('конец обойти');
  писать('');

  // ── главная: лента + заголовок действия + один вызов `обойти` ─────────────────────────
  const шапкаЛенты = [3, 0, 1, [...модуль].length, ...[...модуль].map((с) => с.codePointAt(0)!), конецШапки];
  const числа = [...лента];
  while (числа.length % 100 !== 0) числа.push(0);
  const начало = числа.length + 1 + шапкаЛенты.length;

  писать('действие главная()');
  писать('  пусть лента: Список Число = []');
  писать('  пусть пт = 0');
  for (let и = 0; и < числа.length; и += 100) {
    const кусок = числа.slice(и, и + 100);
    const текст = кусок.map((число) => String.fromCodePoint(0x4e00 + число)).join('');
    писать(`  ${и === 0 ? 'пусть ' : ''}ч = ${JSON.stringify(текст)}`);
    писать('  пт = 0');
    писать(`  пока пт < ${String(текст.length)}`);
    писать('    Списки.добавить(лента, ч[пт] - 19968, 0)');
    писать('    пт = пт + 1');
    писать('  конец пока');
  }
  писать(`  Списки.добавить(лента, ${String(МАГИЯ)}, 0)`);
  for (const число of шапкаЛенты) писать(`  Списки.добавить(лента, ${String(число)}, 0)`);
  писать('  пт = 0');
  писать('  пока пт < 1400');
  писать('    Списки.добавить(лента, 0, 0)');
  писать('    пт = пт + 1');
  писать('  конец пока');
  писать(`  напечатать(лента, ${String(числа.length)}, ${String(начало)})`);
  писать(`  пусть инд = ${String(начало)}`);
  писать(`  инд = выписать_действие_начало_инд(лента, инд, ${String(действие.индекс)})`);
  писать(`  инд = записать_число_инд(лента, инд, ${String(действие.начало + 8)})`);
  писать(`  инд = записать_текст_из_инд(лента, инд, ${String(имя.индекс)})`);
  писать('  инд = записать_число_инд(лента, инд, 3)');
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать(`  инд = обойти(лента, инд, ${String(лента.length * 65536 + первый.индекс)})`);
  писать('  инд = записать_число_инд(лента, инд, 4)');
  писать(`  инд = записать_число_инд(лента, инд, ${String(конецДействия)})`);
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать(`  напечатать(лента, ${String(начало)}, инд)`);
  писать('конец главная');
  писать('');

  return строки.join('\n');
}

