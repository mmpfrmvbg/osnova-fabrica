/**
 * B2: ПРОИЗВОЛЬНАЯ ЛЕНТА В ЦИКЛЕ — POST-ORDER, HARDWARE-ONLY (2026-11-12).
 *
 * Форма отличается от B2a (статический разворот на СБОРКЕ): здесь `главная` в рантайме читает ленту
 * и рекурсивно выписывает события. Рекурсивный `выписать_вызов` — тот самый вызов, который на
 * глубине ≥ 2 ПИШЕТ (`Списки.установить`), поэтому сборка требует
 * `allowDeepArrayWrites: true` (D12: решение владельца, QEMU — названный отказ `#16`).
 *
 * Границы формы: один оператор-вызов в `главная` (аргументы — имена/литералы/вложенные вызовы).
 * Это не «весь парсер»: цикл по нескольким операторам, `пусть` и выражения — B2b.
 */
import { КОД_ЛИТЕРАЛА } from './astFormat';
import { КОД_ВИДА, программаПротоколаB2aPerEvent, токеннаяЛента, токеныB1 } from './parser-protocol-probe';

const МАГИЯ = 20261108;
const СДВИГ = 1048576;
const МОДУЛЬ_ШАПКА = /^действие /mu;

function имяМодуля(файл: string): string {
  return (файл.split(/[\\/]/).pop() ?? файл).replace(/\.[^.]+$/u, '');
}

export function программаПротоколаB2(источник: string, файл = 'b2.osnova'): string {
  const база = программаПротоколаB2aPerEvent(источник, файл);
  const индексГлавной = база.search(МОДУЛЬ_ШАПКА);
  if (индексГлавной < 0) throw new Error('B2: B2a не отдал действие');
  const шапка = база.slice(0, индексГлавной);

  const лента = токеннаяЛента(источник, файл);
  const токены = токеныB1(источник, файл);
  const действие = токены.find((т) => т.лексема === 'действие');
  if (действие === undefined) throw new Error('B2: нет действия');
  const имя = токены[токены.findIndex((т) => т.индекс === действие.индекс) + 1]!;
  const тело = токены[токены.findIndex((т) => т.индекс === имя.индекс) + 1]!;
  const модуль = имяМодуля(файл);
  const конецШапки = [...источник].length;
  const конецДействия = [...источник.trimEnd()].length;

  const строки: string[] = [шапка];
  const писать = (...с: string[]) => строки.push(...с);
  const к = КОД_ВИДА;

  // ── рекурсивный выписыватель: единственная запись — `Списки.установить` в `записать_*` ─────────
  // ОДНА рекурсивная процедура, без промежуточной `выписать_аргумент`: кадр на уровень меньше.
  // Для `ф(г(ч(х)))` писатель `х` стоит на глубине 3, а не 4 — это и проверяется железом.
  писать('процедура выписать_вызов(лента: Список Число, ток: Число, инд: Число) -> Число');
  писать('  пусть п = ток + 7 + лента[ток + 5]');
  писать('  п = п + 7 + лента[п + 5]');
  писать('  пусть арг = 0');
  писать(`  пока лента[п] != ${String(к[')']!)}`);
  писать('    пусть сл = п + 7 + лента[п + 5]');
  писать(`    если лента[п] == ${String(к['имя']!)} и лента[сл] == ${String(к['(']!)}`);
  писать('      пусть р = выписать_вызов(лента, п, инд)');
  писать(`      инд = р нацело ${String(СДВИГ)}`);
  писать(`      п = р - инд * ${String(СДВИГ)}`);
  писать('    иначе');
  писать(`      если лента[п] == ${String(к['имя']!)}`);
  писать('        инд = записать_имя_инд(лента, инд, п)');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 2] + лента[п + 4])');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 1])');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 3])');
  писать('        инд = записать_текст_из_инд(лента, инд, п)');
  писать('      иначе');
  писать('        инд = записать_литерал_инд(лента, инд, п)');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 2] + лента[п + 4])');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 1])');
  писать('        инд = записать_число_инд(лента, инд, лента[п + 3])');
  писать(`        инд = записать_число_инд(лента, инд, ${String(КОД_ЛИТЕРАЛА.число)})`);
  писать('        инд = записать_текст_из_инд(лента, инд, п)');
  писать('      конец если');
  писать('      п = сл');
  писать('    конец если');
  писать('    арг = арг + 1');
  писать(`    если лента[п] == ${String(к[',']!)}`);
  писать('      п = п + 7 + лента[п + 5]');
  писать('    конец если');
  писать('  конец пока');
  писать('  инд = записать_начало_инд(лента, инд, ток)');
  писать('  инд = записать_текст_из_инд(лента, инд, ток)');
  писать('  инд = записать_конец_инд(лента, инд, арг * 65536 + лента[п + 2] + лента[п + 4])');
  писать('  инд = записать_оператор_инд(лента, инд, ток)');
  писать(`  вернуть инд * ${String(СДВИГ)} + п + 7 + лента[п + 5]`);
  писать('конец выписать_вызов');
  писать('');

  const шапкаЛенты = [3, 0, 1, [...модуль].length, ...[...модуль].map((с) => с.codePointAt(0)!), конецШапки];
  писать('действие главная()');
  писать('  пусть лента: Список Число = []');
  писать('  пусть пт = 0');
  const числа = [...лента];
  while (числа.length % 100 !== 0) числа.push(0);
  for (let и = 0; и < числа.length; и += 100) {
    const кусок = числа.slice(и, и + 100);
    const текст = кусок.map((число) => String.fromCodePoint(0x4e00 + число)).join('');
    писать(`  пусть ч${String(и / 100)} = ${JSON.stringify(текст)}`);
    писать('  пт = 0');
    писать(`  пока пт < ${String(текст.length)}`);
    писать(`    Списки.добавить(лента, ч${String(и / 100)}[пт] - 19968, 0)`);
    писать('    пт = пт + 1');
    писать('  конец пока');
  }
  писать(`  Списки.добавить(лента, ${String(МАГИЯ)}, 0)`);
  for (const число of шапкаЛенты) писать(`  Списки.добавить(лента, ${String(число)}, 0)`);
  писать('  пт = 0');
  писать('  пока пт < 300');
  писать('    Списки.добавить(лента, 0, 0)');
  писать('    пт = пт + 1');
  писать('  конец пока');
  const начало = числа.length + 1 + шапкаЛенты.length;
  писать(`  пусть инд = ${String(начало)}`);
  писать(`  инд = выписать_действие_начало_инд(лента, инд, ${String(действие.индекс)})`);
  писать(`  инд = записать_число_инд(лента, инд, ${String(действие.начало + 8)})`);
  писать(`  инд = записать_текст_из_инд(лента, инд, ${String(имя.индекс)})`);
  писать('  инд = записать_число_инд(лента, инд, 3)');
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать(`  пусть R = выписать_вызов(лента, ${String(тело.индекс)}, инд)`);
  писать(`  инд = R нацело ${String(СДВИГ)}`);
  писать('  инд = записать_число_инд(лента, инд, 4)');
  писать(`  инд = записать_число_инд(лента, инд, ${String(конецДействия)})`);
  писать('  инд = записать_число_инд(лента, инд, 0)');
  писать(`  напечатать(лента, ${String(начало)}, инд)`);
  писать('конец главная');
  писать('');

  return строки.join('\n');
}
