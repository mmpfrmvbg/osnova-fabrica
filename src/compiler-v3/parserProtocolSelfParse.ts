/**
 * БЕЗ УПАКОВКИ (`безУпаковки`) — замена пары «инд, токен» клеткой состояния, для САМОРАЗБОРА (§7).
 *
 * ЗАЧЕМ. Сгенерированный разборщик возвращает из шага два числа, упакованные в одно:
 * `инд * 65536 + токен`. На цели `Число` — 32-битное (`docs/hardware-debt.md` §3.199: литерал
 * `40000 * 65536 + 5` даёт −1 673 527 291), поэтому при AST ≥ 32 768 клеток упаковка переполняется
 * МОЛЧА. Замер на живой E8C2 (2026-11-13): с упаковкой саморазбор завершается кодом 0, но печатает
 * только шапку AST (10 клеток из 45 532) — переполнение не падает, а теряет разбор.
 *
 * ЧТО ДЕЛАЕТСЯ. Замена чисто ТЕКСТОВАЯ и только в сборке саморазбора — байты кита не меняются
 * (иначе 107 образов пришлось бы перепроверять на железе ради эксперимента). До и после:
 *
 *   вернуть инд * 65536 + сл          →  Списки.установить(лента, С, сл)   +   вернуть инд
 *   вернуть п * 65536                 →  Списки.установить(лента, С, 0)    +   вернуть п
 *   инд = р нацело 65536              →  инд = р
 *   т = р - инд * 65536               →  т = лента[С]
 *   пусть след = р - инд * 65536      →  пусть след = лента[С]
 *   пусть п = р нацело 65536          →  пусть п = р
 *
 * `С` — адрес клетки состояния, его передаёт сборка: `раскладкаB2b(...).начало + astCells − 1`
 * (последняя клетка РЕЗЕРВА AST, до которой AST не дорастает). Отказ шага (`вернуть 0 - 1`)
 * остаётся отрицательным, вызывающий по-прежнему проверяет `р < 0`.
 *
 * ПОЧЕМУ `Списки.установить`, А НЕ `лента[С] = x`: присваивание по индексу язык v3 не разбирает
 * («слева от „=“ должно быть имя»), а чтение по индексу `лента[С]` — разбирает.
 *
 * ЧТО ЭТО НЕ ЛЕЧИТ (измерено, не закрыто): AST саморазбора расходится с эталоном на первом же узле
 * индексации внутри `пусть`/аргументов (`docs/hardware-debt.md` §3.205) — это НАЗВАННАЯ ГРАНИЦА
 * B2b, отдельный атом.
 */

export const ПРАВИЛА_БЕЗ_УПАКОВКИ: ReadonlyArray<{
  readonly шаблон: RegExp;
  readonly замена: (м: RegExpExecArray) => string;
}> = [
  {
    // вернуть <инд> * 65536 — хвост пары равен нулю (`разобрать_аргумент` в шапке B2a)
    шаблон: /^([ \t]*)вернуть[ \t]+([^\s*]+)[ \t]*\*[ \t]*65536$/u,
    замена: (м) => `${м[1]}Списки.установить(лента, %С%, 0)\n${м[1]}вернуть ${м[2]}`,
  },
  {
    // вернуть <инд> * 65536 + <выражение>
    шаблон: /^([ \t]*)вернуть[ \t]+([^\s*]+)[ \t]*\*[ \t]*65536[ \t]*\+[ \t]*(.+)$/u,
    замена: (м) => `${м[1]}Списки.установить(лента, %С%, ${м[3]})\n${м[1]}вернуть ${м[2]}`,
  },
  {
    шаблон: /^([ \t]*)пусть[ \t]+([^\s=]+)[ \t]*=[ \t]*([^\s]+)[ \t]+нацело[ \t]+65536$/u,
    замена: (м) => `${м[1]}пусть ${м[2]} = ${м[3]}`,
  },
  {
    шаблон: /^([ \t]*)пусть[ \t]+([^\s=]+)[ \t]*=[ \t]*([^\s]+)[ \t]*-[ \t]*([^\s]+)[ \t]*\*[ \t]*65536$/u,
    замена: (м) => `${м[1]}пусть ${м[2]} = лента[%С%]`,
  },
  {
    шаблон: /^([ \t]*)([^\s=]+)[ \t]*=[ \t]*([^\s]+)[ \t]+нацело[ \t]+65536$/u,
    замена: (м) => `${м[1]}${м[2]} = ${м[3]}`,
  },
  {
    шаблон: /^([ \t]*)([^\s=]+)[ \t]*=[ \t]*([^\s]+)[ \t]*-[ \t]*([^\s]+)[ \t]*\*[ \t]*65536$/u,
    замена: (м) => `${м[1]}${м[2]} = лента[%С%]`,
  },
];

/** Переписать пару «инд, токен» в клетку состояния. `клетка` — её адрес в списке AST. */
export function безУпаковки(текст: string, клетка: number): string {
  if (!Number.isSafeInteger(клетка) || клетка <= 0) throw new Error(`безУпаковки: плохая клетка ${String(клетка)}`);
  const итог: string[] = [];
  for (const строка of текст.split('\n')) {
    let сделано = false;
    for (const правило of ПРАВИЛА_БЕЗ_УПАКОВКИ) {
      const м = правило.шаблон.exec(строка);
      if (м === null) continue;
      итог.push(правило.замена(м).replaceAll('%С%', String(клетка)));
      сделано = true;
      break;
    }
    if (!сделано) итог.push(строка);
  }
  const остаток = итог.filter((строка) => строка.includes('* 65536') || строка.includes('нацело 65536'));
  if (остаток.length > 0) {
    throw new Error(`безУпаковки: не переписано ${String(остаток.length)} строк, первая: ${остаток[0]!.trim()}`);
  }
  return итог.join('\n');
}
