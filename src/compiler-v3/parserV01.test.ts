/**
 * Reference parser v0.1 на AST 3.0 (post-order в ленте): 12 валидных и 6 невалидных проверок.
 *
 * N = 13: откат версии парсера до 2.1 краснит ровно 13/19 (проверено замером). Каждый валидный
 * тест требует версию 3.0, разбирает форму и проходит байт-в-байт roundtrip (лента 3.0 =
 * post-order); каждый невалидный — конкретный названный код, а не «хоть какая-то ошибка».
 */
import { describe, expect, it } from 'vitest';
import { лентаИзAst, прочитатьЛенту } from './astFormat';
import { parseV01 } from './parserV01';

function разобрать(source: string) {
  // Каждый валидный вход несёт присваивание: иначе откат parserV01 до 2.0
  // оставил бы старые формы зелёными и N=18 не был бы проверен.
  const источник = source.replace(/\nконец ([^\n]+)\n?$/, '\n  маркер_21 = 0\nконец $1\n');
  const итог = parseV01(источник);
  if (!итог.ок) throw new Error(`ожидался разбор, получен ${итог.ошибка.код}: ${итог.ошибка.сообщение}`);
  const ast = итог.ast;
  expect(ast.версия).toBe('3.0');
  const обратно = прочитатьЛенту(лентаИзAst(ast));
  expect(обратно.ок).toBe(true);
  if (обратно.ок) expect(обратно.ast).toEqual(ast);
  return ast;
}

function отказ(source: string): string {
  const итог = parseV01(source);
  expect(итог.ок, 'ожидался названный отказ, а не AST').toBe(false);
  if (итог.ок) return '';
  return итог.ошибка.код;
}

describe('parserV01 / AST 3.0: 12 валидных', () => {
  it('1. приоритет: 1 + 2 * 3 → плюс(1, умножить(2, 3))', () => {
    const ast = разобрать(`процедура тест() -> Число
  вернуть 1 + 2 * 3
конец тест
`);
    const возврат = ast.процедуры[0]!.тело[0]!;
    expect(возврат.вид).toBe('вернуть');
    if (возврат.вид !== 'вернуть' || возврат.значение === undefined) return;
    expect(возврат.значение.вид).toBe('бинарное');
    if (возврат.значение.вид !== 'бинарное') return;
    expect(возврат.значение.оператор).toBe('+');
    expect(возврат.значение.правый.вид).toBe('бинарное');
    if (возврат.значение.правый.вид !== 'бинарное') return;
    expect(возврат.значение.правый.оператор).toBe('*');
  });

  it('2. унарные `-` и `не`', () => {
    const ast = разобрать(`процедура тест() -> Логическое
  вернуть -2 * 3
  вернуть не да
конец тест
`);
    const первый = ast.процедуры[0]!.тело[0]!;
    const второй = ast.процедуры[0]!.тело[1]!;
    expect(первый.вид).toBe('вернуть');
    expect(второй.вид).toBe('вернуть');
    if (первый.вид !== 'вернуть' || первый.значение?.вид !== 'бинарное') return;
    expect(первый.значение.левый.вид).toBe('унарное');
    if (второй.вид !== 'вернуть' || второй.значение?.вид !== 'унарное') return;
    expect(второй.значение.оператор).toBe('не');
  });

  it('3. сравнения, `и`, `или`', () => {
    const ast = разобрать(`процедура тест() -> Логическое
  вернуть 1 < 2 и 3 >= 3 или 4 != 5
конец тест
`);
    const возврат = ast.процедуры[0]!.тело[0]!;
    if (возврат.вид !== 'вернуть' || возврат.значение?.вид !== 'бинарное') return;
    expect(возврат.значение.оператор).toBe('или');
    expect(возврат.значение.левый.вид).toBe('бинарное');
    if (возврат.значение.левый.вид !== 'бинарное') return;
    expect(возврат.значение.левый.оператор).toBe('и');
  });

  it('4. список `[1, 2, 3]`', () => {
    const ast = разобрать(`действие тест()
  пусть а = [1, 2, 3]
конец тест
`);
    const пусть = ast.процедуры[0]!.тело[0]!;
    if (пусть.вид !== 'пусть') return;
    expect(пусть.значение.вид).toBe('список');
    if (пусть.значение.вид !== 'список') return;
    expect(пусть.значение.элементы).toHaveLength(3);
  });

  it('5. индексация `а[1]`', () => {
    const ast = разобрать(`действие тест()
  пусть а = [1, 2, 3]
  вернуть а[1]
конец тест
`);
    const возврат = ast.процедуры[0]!.тело[1]!;
    if (возврат.вид !== 'вернуть' || возврат.значение?.вид !== 'индексация') return;
    expect(возврат.значение.индекс.вид).toBe('литерал');
  });

  it('6. `иначе если` — одна цепочка, один `конец если`', () => {
    const ast = разобрать(`действие тест()
  если а == 1
    вернуть 1
  иначе если а == 2
    вернуть 2
  иначе
    вернуть 3
  конец если
конец тест
`);
    const если = ast.процедуры[0]!.тело[0]!;
    if (если.вид !== 'если') return;
    expect(если.иначе).toHaveLength(1);
    expect(если.иначе?.[0]?.вид).toBe('если');
    const лента = лентаИзAst(ast);
    expect(лента.filter((к) => к === 40).length).toBeGreaterThanOrEqual(1);
  });

  it('7. `нацело` — бинарный оператор', () => {
    const ast = разобрать(`процедура тест() -> Число
  вернуть 10 нацело 3
конец тест
`);
    const возврат = ast.процедуры[0]!.тело[0]!;
    if (возврат.вид !== 'вернуть' || возврат.значение?.вид !== 'бинарное') return;
    expect(возврат.значение.оператор).toBe('нацело');
  });

  it('8. `пока` с условием-оператором и explicit `конец пока`', () => {
    const ast = разобрать(`действие тест()
  пусть х = 0
  пока х < 3
    вернуть 1
  конец пока
конец тест
`);
    const пока = ast.процедуры[0]!.тело[1]!;
    expect(пока.вид).toBe('пока');
  });

  it('9. `поднять` — `вернуть Ошибка(...)`, один путь ошибок', () => {
    const ast = разобрать(`процедура получить(ч: Число) -> Результат<Число, Ошибка>
  если ч == 0
    поднять "беда"
  конец если
  вернуть Успех(1)
конец получить
`);
    const если = ast.процедуры[0]!.тело[0]!;
    if (если.вид !== 'если') return;
    const поднятие = если.тогда[0]!;
    expect(поднятие.вид).toBe('вернуть');
    if (поднятие.вид !== 'вернуть' || поднятие.значение?.вид !== 'вызов') return;
    expect(поднятие.значение.имя).toBe('Ошибка');
  });

  it('10. `Успех`/`Ошибка` — обычные вызовы, не особые узлы', () => {
    const ast = разобрать(`действие тест()
  вернуть Успех(1)
  вернуть Ошибка(1, "x")
конец тест
`);
    const успех = ast.процедуры[0]!.тело[0]!;
    const ошибка = ast.процедуры[0]!.тело[1]!;
    if (успех.вид !== 'вернуть' || успех.значение?.вид !== 'вызов') return;
    expect(успех.значение.имя).toBe('Успех');
    if (ошибка.вид !== 'вернуть' || ошибка.значение?.вид !== 'вызов') return;
    expect(ошибка.значение.имя).toBe('Ошибка');
    expect(ошибка.значение.аргументы).toHaveLength(2);
  });

  it('11. присваивание `имя = выражение` — событие 41, не путается с `==`', () => {
    const ast = разобрать(`процедура тест() -> Число
  пусть х = 1
  х = х + 1
  вернуть х
конец тест
`);
    const присв = ast.процедуры[0]!.тело[1]!;
    expect(присв.вид).toBe('присваивание');
    if (присв.вид !== 'присваивание') return;
    expect(присв.имя).toBe('х');
    expect(присв.значение.вид).toBe('бинарное');
    expect(лентаИзAst(ast)).toContain(41);
  });

  it('12a. D43a: `Списки.пустой(ар)` и `Списки.взять(с, и)` — квалифицированные вызовы', () => {
    const ast = разобрать(`действие тест()
  пусть ар = [0]
  пусть с = Списки.пустой(ар)
  пусть э = Списки.взять(с, 0)
конец тест
`);
    const создание = ast.процедуры[0]!.тело[1]!;
    const чтение = ast.процедуры[0]!.тело[2]!;
    if (создание.вид !== 'присваивание' || чтение.вид !== 'присваивание') return;
    expect(создание.значение.вид).toBe('квалифицированный_вызов');
    expect(чтение.значение.вид).toBe('квалифицированный_вызов');
    if (создание.значение.вид !== 'квалифицированный_вызов') return;
    if (чтение.значение.вид !== 'квалифицированный_вызов') return;
    expect([создание.значение.библиотека, создание.значение.функция]).toEqual(['Списки', 'пустой']);
    expect([чтение.значение.библиотека, чтение.значение.функция]).toEqual(['Списки', 'взять']);
    expect(создание.значение.аргументы).toHaveLength(1);
    expect(чтение.значение.аргументы).toHaveLength(2);
  });

  it('12. D43-вызовы: `Списки.добавить(с, э, ар)`, `Печать.число(Списки.длина(с))`', () => {
    const ast = разобрать(`действие тест()
  пусть с = [1, 2]
  пусть ар = [0]
  Списки.добавить(с, 3, ар)
  Печать.число(Списки.длина(с))
конец тест
`);
    const добавление = ast.процедуры[0]!.тело[2]!;
    const печать = ast.процедуры[0]!.тело[3]!;
    expect(добавление.вид).toBe('вызов');
    if (добавление.вид !== 'вызов') return;
    expect(добавление.вызов.вид).toBe('квалифицированный_вызов');
    if (добавление.вызов.вид !== 'квалифицированный_вызов') return;
    expect(добавление.вызов.библиотека).toBe('Списки');
    expect(добавление.вызов.функция).toBe('добавить');
    expect(добавление.вызов.аргументы).toHaveLength(3);
    if (печать.вид !== 'вызов' || печать.вызов.вид !== 'квалифицированный_вызов') return;
    expect(печать.вызов.библиотека).toBe('Печать');
    expect(печать.вызов.аргументы[0]?.вид).toBe('квалифицированный_вызов');
  });
});

describe('parserV01 / AST 3.0: 6 невалидных', () => {
  it('13. `5 = х` — 028: слева от `=` не имя', () => {
    expect(отказ(`действие тест()
  5 = х
конец тест
`)).toBe('OSN-PAR-028');
  });

  it('14. `х = у = 5` — 029: цепочка присваивания в 3.0', () => {
    expect(отказ(`действие тест()
  пусть х = 0
  пусть у = 0
  х = у = 5
конец тест
`)).toBe('OSN-PAR-029');
  });

  it('15. `вывести х` — 030: это библиотека, не языковая инструкция', () => {
    expect(отказ(`действие тест()
  вывести 1
конец тест
`)).toBe('OSN-PAR-030');
  });

  it('16. `МойМодуль.ф(1)` — 031: `.` только D43, модули — v0.2', () => {
    expect(отказ(`действие тест()
  МойМодуль.ф(1)
конец тест
`)).toBe('OSN-PAR-031');
  });

  it('17. `→` — 026; bare `конец` — 025', () => {
    expect(отказ(`процедура тест() → Число
  вернуть 1
конец тест
`)).toBe('OSN-PAR-026');
    expect(отказ(`действие тест()
  х = 0
  вернуть 1
конец
`)).toBe('OSN-PAR-025');
  });

  it('18. `Списки.добавить` без арены — 032: арена обязательна (D43)', () => {
    expect(отказ(`действие тест()
  пусть с = [1]
  пусть ар = [0]
  Списки.добавить(с, 2)
конец тест
`)).toBe('OSN-PAR-032');
  });
});
