  писать(`  если лента[след] == ${String(к[':']!)}`);
  писать('    пусть типт = след + 7 + лента[след + 5]');
  писать('    равно = типт + 7 + лента[типт + 5]');
  писать('  конец если');
  писать('  пусть знач = равно + 7 + лента[равно + 5]');
  писать('  пусть после = знач + 7 + лента[знач + 5]');
  писать(`  если ${операторыПослеЗначения}`);
  писать('    пусть прав = после + 7 + лента[после + 5]');
  писать('    после = прав + 7 + лента[прав + 5]');
