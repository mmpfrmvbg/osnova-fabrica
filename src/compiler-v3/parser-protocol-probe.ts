  писать('    пт = пт + 1');
  писать('  конец пока');
  // Состояние — ТРИ клетки: `[выходной курсор, курсор разбора, тело ветки]`. Тело `пусть`/
  // присваивания кладётся в третью клетку, чтобы не жить через вызовы писателей (пик входа 12/11).
  писать(`  пусть состояние: Список Число = [${String(индексНачало)}, 0, 0]`);
  писать(`  пока лента[состояние[1]] != ${String(к['конец_файла']!)}`);
