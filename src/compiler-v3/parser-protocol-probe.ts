/**
 * РАСКЛАДКА `R = value·2^29 + tag·2^24 + pos`.
 *
 * Предписанная `tag·2^47 + value·2^24 + pos` требует литерала `2^47`, а кодировщик e2k его не
 * принимает (§2.5 `docs/parser-protocol.md`). Эта раскладка — та же точность 5+23+24 и все
 * литералы в 32 битах; проверена круговым тестом P2.
 */
export const ВЕС_ТЕГА = 2 ** 24;
export const ВЕС_ЗНАЧЕНИЯ = 2 ** 29;
export const МОДУЛЬ_ЗНАЧЕНИЯ = 2 ** 23;
export const МОДУЛЬ_ТЕГА = 2 ** 5;
export const МОДУЛЬ_ПОЗИЦИИ = 2 ** 24;

/** Упаковать шаг `R = value·2^29 + tag·2^24 + pos` с проверкой границ. */
export function упаковатьШаг(тег: number, значение: number, позиция: number): number {
  if (!Number.isInteger(тег) || тег < 0 || тег >= МОДУЛЬ_ТЕГА) {
    throw new Error(`тег вне 5 бит: ${String(тег)}`);
  }
  if (!Number.isInteger(значение) || значение < 0 || значение >= МОДУЛЬ_ЗНАЧЕНИЯ) {
    throw new Error(`значение вне 23 бит: ${String(значение)}`);
  }
  if (!Number.isInteger(позиция) || позиция < 0 || позиция >= МОДУЛЬ_ПОЗИЦИИ) {
    throw new Error(`позиция вне 24 бит: ${String(позиция)}`);
  }
  const R = значение * ВЕС_ЗНАЧЕНИЯ + тег * ВЕС_ТЕГА + позиция;
  if (R > 2 ** 52 - 1) throw new Error(`R вне доказанного диапазона: ${String(R)}`);
  return R;
}

/** Распаковать шаг; обратна {@link упаковатьШаг}. */
export function распаковатьШаг(R: number): { тег: number; значение: number; позиция: number } {
  const позиция = R % МОДУЛЬ_ПОЗИЦИИ;
  const остаток = Math.floor(R / МОДУЛЬ_ПОЗИЦИИ);
  const тег = остаток % МОДУЛЬ_ТЕГА;
  const значение = Math.floor(остаток / МОДУЛЬ_ТЕГА);
  return { тег, значение, позиция };
}

