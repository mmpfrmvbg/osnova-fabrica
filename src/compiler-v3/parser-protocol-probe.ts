  писать('  пусть имя = ток + 7 + лента[ток + 5]');
  писать('  Списки.установить(лента, индекс + 1, лента[имя + 2] + лента[имя + 4])');
  писать('  вернуть индекс + 2');
  писать('конец');
  писать('');

  // Токен, стоящий ПЕРЕД данным: так `+`/`-` узнаёт СВОЙ оператор по границе групп, и точке
  // входа не нужен лишний живой отрезок «отложенный оператор» (замер: с ним 10 занятых из 10).
