  писать(`  пока пт < ${String(tapeСтрока.length)}`);
  писать('    Списки.добавить(лента, текст[пт] - 19968, 0)');
  писать('    пт = пт + 1');
  писать('  конец пока');
  писать('  Списки.добавить(лента, 20261108, 0)');
  писать(`  пусть шапка = ${JSON.stringify(шапкаСтрока)}`);
  писать('  пт = 0');
  писать(`  пока пт < ${String(шапкаСтрока.length)}`);
  писать('    Списки.добавить(лента, шапка[пт] - 19968, 0)');
  писать('    пт = пт + 1');
  писать('  конец пока');
  писать('  пт = 0');
  писать(`  пока пт < ${String(КЛЕТОК_ПОД_ЛЕНТУ_P3A)}`);
