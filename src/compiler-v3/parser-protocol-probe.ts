  писать('');

  писать('процедура поз_шага(р: Число) → Число');
  писать(`  вернуть р нацело ${В}`);
  писать('конец');
  писать('');

  // Печать — В ТОЧКЕ ВХОДА, а не в процедуре: `вывести` из выращенного кадра — названная
  // граница (`OSN-LOW-005`), модель/железо на ней падают. Вынос печати в `вывести_ленту`
  // дал ровно это падение на 0x10a078 (замер §23).
  // ── ТОЧКА ВХОДА: нарезает буфер, диспетчеризует по ВИДУ ТОКЕНА, писатели — глубины 1 ────────
  писать('действие главная()');
  const шапкаКоды = [3, 0, 1, имяКоды.length, ...имяКоды, конецМодуля];
