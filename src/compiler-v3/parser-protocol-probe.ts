/**
 * Сколько клеток заранее выделено под AST-ленту.
 *
 * БЫЛО 10000 — И ЭТО БЫЛО НЕВЫПОЛНИМО (139). Куча списков — ОДНА страница
 * (`src/e2k/elfMinimal.ts#IMAGE_TAIL_OFFSET` = `0x111000`), слот 8 байт, минус слово заголовка:
 * **511 слотов**. Проба просила 10000 — в двадцать раз больше страницы, и падала кодом 139 на
 * первом же `Списки.добавить` за границей (`ldd %db[15]` — чтение указателя кучи за пределами
 * отображённой страницы). Замер порога (`.tmp/p139-thr.ts`, `.tmp/p139-cap.ts`):
 * `n=508` — «7», `n=510` — «7», **`n=511` — исключение**; мелкие пробы с печатью в главной
 * проходят, то есть дефект не в печати, а в ёмкости.
 *
 * Сколько нужно НА САМОМ ДЕЛЕ: лента токенов + шапка модуля + AST (43 клетки по замеру
 * `эталоннаяЛента`) + место записи. Для P2a `индексНачало` = 139, при 43 клетках AST запись
 * кончается на 182 — запас 256 клеток покрывает это с двойным перекрытием и укладывается в 511.
 */
export const КЛЕТОК_ПОД_ЛЕНТУ = 256;

/**
 * Token tape по `docs/parser-protocol.md` §1: `[вид, строка, offset, колонка, длина, лекс_длина,
 * cp..., 0]`, переводы строк отфильтрованы, последний токен — `конец_файла`.
 */
export function токеннаяЛента(источник: string, файл: string): number[] {
  const лек = tokenizeV3(источник, файл);
  if (лек.errors.length > 0) throw new Error(`лексер отказал: ${лек.errors.join(' | ')}`);
  const лента: number[] = [];
  for (const токен of лек.tokens) {
    if (токен.kind === 'новая_строка') continue;
    const коды = [...токен.lexeme].map((символ) => символ.codePointAt(0)!);
    лента.push(
      КОД_ВИДА[токен.kind],
      токен.line,
      токен.offset,
      токен.column,
      токен.length,
      коды.length,
      ...коды,
      0,
    );
  }
  return лента;
}

/** Число кодовых точек в строке — «конец модуля» в ленте AST. */
function длинаВКодпоинтах(строка: string): number {
  return [...строка].length;
}

/**
 * Сгенерировать программу P2a на Основе.
 *
 * `главная` строит рабочую ленту (token tape + заголовок AST + 10000 нулей), затем в цикле зовёт
 * `разобрать_программу` и по тегу пишет поля события одним листовым писателем. Писатель возвращает
 * новый индекс; `главная` печатает `лента[начало .. индекс)`.
 */
export function программаПротоколаP2a(
  источник: string = ИСХОДНИК_P2A,
  файл: string = ФАЙЛ_P2A,
): string {
  const модуль = moduleNameFromFilename(файл);
  const имяКоды = [...модуль].map((символ) => символ.codePointAt(0)!);
  const tape = токеннаяЛента(источник, файл);
  const конецМодуля = длинаВКодпоинтах(источник);
  const к = КОД_ВИДА;
  const лентаНачало = tape.length;
  const заголовокДлина = 5 + имяКоды.length + 1;
  const индексНачало = лентаНачало + заголовокДлина;

  const строки: string[] = [];

  // Индексы трёх текстовых токенов, которые в P2a разворачиваются в константы.
  const индексИмени = 7 + tape[5]!; // после `процедура`
  const индексТипа = индексИмени + 7 + tape[индексИмени + 5]! + 32; // имя, `(`, `)`, `-`, `>`
  const индексЛитерала = (() => {
    for (let i = 0; i < tape.length; i += 7 + tape[i + 5]!) {
      if (tape[i] === КОД_ВИДА['число']) return i;
    }
    throw new Error('в источнике P2a нет числового литерала');
  })();

  // ── ПИСАТЕЛИ ГЛУБИНЫ 1: по одной записи, без арены и без Результата ─────────────────────────
  строки.push('процедура записать_число(лента: Список Число, з: Число, индекс: Число) → Число');
  строки.push('  Списки.установить(лента, индекс, з)');
  строки.push('  вернуть индекс + 1');
  строки.push('конец');
  строки.push('');

  // Читает токен САМ, на глубине 1: так `главная` не индексирует ленту и не плодит
  // `IR.invoke получить` (замер с прямой индексацией — 30 живых отрезков).
  строки.push('процедура записать_из(лента: Список Число, токен: Число, индекс: Число) → Число');
  строки.push('  Списки.установить(лента, индекс, лента[токен])');
  строки.push('  вернуть индекс + 1');
  строки.push('конец');
  строки.push('');

  строки.push('процедура записать_плюс9(лента: Список Число, токен: Число, индекс: Число) → Число');
  строки.push('  Списки.установить(лента, индекс, лента[токен] + 9)');
  строки.push('  вернуть индекс + 1');
  строки.push('конец');
  строки.push('');

  строки.push('процедура записать_сумму(лента: Список Число, токен: Число, индекс: Число) → Число');
  строки.push('  Списки.установить(лента, индекс, лента[токен] + лента[токен + 2])');
  строки.push('  вернуть индекс + 1');
  строки.push('конец');
  строки.push('');

  // ЧИТАТЕЛЬ для печати: `главная` не индексирует ленту сама.
  строки.push('процедура прочитать(лента: Список Число, индекс: Число) → Число');
  строки.push('  вернуть лента[индекс]');
  строки.push('конец');
  строки.push('');

  // ── ОБРАБОТЧИКИ ГЛУБИНЫ 2: читают токены, возвращают R, НЕ пишут и НЕ трогают арену ────────
  строки.push('процедура разобрать_процедуру(лента: Список Число, поз: Число) → Число');
  строки.push('  вернуть поз * 536870912 + (поз + 7 + лента[поз + 5])');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_заголовок(лента: Список Число, поз: Число) → Число');
  строки.push('  пусть т = поз + 39 + лента[поз + 5]');
  строки.push('  вернуть 33554432 + т * 536870912 + (т + 7 + лента[т + 5])');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_вернуть(лента: Список Число, поз: Число) → Число');
  строки.push('  вернуть 167772160 + поз * 536870912 + (поз + 7 + лента[поз + 5])');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_выражение(лента: Список Число, поз: Число) → Число');
  строки.push('  если лента[поз] == 1');
  строки.push('    вернуть 234881024 + поз * 536870912 + (поз + 7 + лента[поз + 5])');
  строки.push('  конец если');
  строки.push('  вернуть 251658240 + поз * 536870912 + (поз + 7 + лента[поз + 5])');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_конец_процедуры(лента: Список Число, поз: Число) → Число');
  строки.push('  пусть имя = поз + 7 + лента[поз + 5]');
  строки.push('  пусть кон = лента[имя + 2] + лента[имя + 4]');
  строки.push('  вернуть 50331648 + кон * 536870912 + (имя + 7 + лента[имя + 5])');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_конец(лента: Список Число, поз: Число) → Число');
  строки.push('  вернуть 385875968 + (поз + 1)');
  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_параметр(лента: Список Число, поз: Число) → Число');
  строки.push('  вернуть 16777216 + поз * 536870912 + (поз + 7 + лента[поз + 5])');
  строки.push('конец');
  строки.push('');

  // ── ДИСПЕТЧЕР ГЛУБИНЫ 1: ветвление по виду токена, без записи ───────────────────────────────
  //
  // Кадр здесь не переменная, а САМА позиция: `поз == 0` — процедура, `имя` — заголовок,
  // `вернуть` — оператор, `конец` — конец процедуры, `конец_файла` — конец модуля. Для P2a этого
  // достаточно; стек кадров появится в P3 вместе с вложенными конструкциями. Так с заголовка петли
  // уходит ещё одно живое значение — без него `главная` не влезала в восемь свободных регистров.
  строки.push('процедура разобрать_программу(лента: Список Число, поз: Число) → Число');
  строки.push(`  если лента[поз] == ${String(к['конец_файла']!)}`);
  строки.push('    вернуть разобрать_конец(лента, поз)');
  строки.push('  конец если');
  строки.push('  если поз == 0');
  строки.push('    вернуть разобрать_процедуру(лента, поз)');
  строки.push('  конец если');
  строки.push(`  если лента[поз] == ${String(к['имя']!)}`);
  строки.push('    вернуть разобрать_заголовок(лента, поз)');
  строки.push('  конец если');
  строки.push(`  если лента[поз] == ${String(к['вернуть']!)}`);
  строки.push('    вернуть разобрать_вернуть(лента, поз)');
  строки.push('  конец если');
  строки.push(`  если лента[поз] == ${String(к['конец']!)}`);
  строки.push('    вернуть разобрать_конец_процедуры(лента, поз)');
  строки.push('  конец если');
  строки.push('  вернуть разобрать_выражение(лента, поз)');
  строки.push('конец');
  строки.push('');

  // ── ГЛАВНАЯ: рабочая лента, предвыделение, петля диспетчера, печать ────────────────────────
  строки.push('действие главная()');
  // Арена не нужна: третьим аргументом `Списки.добавить` идёт литерал 0.
  // ВСЯ рабочая лента — две строки: token tape, затем магия (её код больше 0x10FFFF и в строку-
  // сдвиг не влезает), затем остаток заголовка и 10000 нулей. Так `Списки.добавить` имеет ДВА
  // сайта, а не десять: каждый вызов `добавить` оставляет приёмник живым, и десять приёмников
  // сами по себе давали пик выше предела D48.
  const tapeСтрока = tape.map((число) => String.fromCodePoint(0x4e00 + число)).join('');
  const шапкаКоды = [2, 1, 1, имяКоды.length, ...имяКоды, конецМодуля];
  const шапкаСтрока = шапкаКоды.map((число) => String.fromCodePoint(0x4e00 + число)).join('');
  строки.push(`  пусть текст = ${JSON.stringify(tapeСтрока)}`);
  строки.push('  пусть лента: Список Число = []');
  строки.push('  пусть пт = 0');
  строки.push('  пока пт < длина текст');
  строки.push('    Списки.добавить(лента, текст[пт] - 19968, 0)');
  строки.push('    пт = пт + 1');
  строки.push('  конец пока');
  строки.push('  Списки.добавить(лента, 20261108, 0)');
  строки.push(`  пусть шапка = ${JSON.stringify(шапкаСтрока)}`);
  строки.push('  пт = 0');
  строки.push('  пока пт < длина шапка');
  строки.push('    Списки.добавить(лента, шапка[пт] - 19968, 0)');
  строки.push('    пт = пт + 1');
  строки.push('  конец пока');
  // 10000 клеток под `Списки.установить`: нули ДОБАВЛЯЮТСЯ циклом, а не литералом строки, иначе
  // статическая строка на 10000 CJK-символов уводит код образа за 64 КиБ (замер: 984272 байта).
  строки.push('  пт = 0');
  строки.push(`  пока пт < ${String(КЛЕТОК_ПОД_ЛЕНТУ)}`);
  строки.push('    Списки.добавить(лента, 0, 0)');
  строки.push('    пт = пт + 1');
  строки.push('  конец пока');
  строки.push('  пусть r = 0');
  строки.push(`  пусть индекс = ${String(индексНачало)}`);
  // Петля идёт, пока тег не `КОНЕЦ` (23). `r` — единственный носитель и тега, и значения, и
  // позиции; `индекс` — единственный носитель места записи. Литеральные индексы НЕ годятся:
  // планировщик поднимает их все в заголовок петли, и замер дал 30 живых отрезков.
  строки.push(`  пока (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} < ${String(ТЕГИ.КОНЕЦ)}`);
  строки.push(`    r = разобрать_программу(лента, r % ${String(МОДУЛЬ_ПОЗИЦИИ)})`);

  const з = `(r нацело ${String(ВЕС_ЗНАЧЕНИЯ)})`;
  const выр = `(r % ${String(МОДУЛЬ_ПОЗИЦИИ)})`;
  const поля = (значение: string, отступ: string): string[] => [
    `${отступ}индекс = записать_число(лента, ${значение}, индекс)`,
  ];
  const из = (токен: string, отступ: string): string[] => [
    `${отступ}индекс = записать_из(лента, ${токен}, индекс)`,
  ];
  const плюс9 = (токен: string, отступ: string): string[] => [
    `${отступ}индекс = записать_плюс9(лента, ${токен}, индекс)`,
  ];
  const сумму = (токен: string, отступ: string): string[] => [
    `${отступ}индекс = записать_сумму(лента, ${токен}, индекс)`,
  ];
  const текстВ = (токен: number, отступ: string): string[] => {
    const длина = tape[токен + 5]!;
    const итог = [...поля(String(длина), отступ)];
    for (let i = 0; i < длина; i += 1) {
      итог.push(...поля(String(tape[токен + 6 + i]!), отступ));
    }
    return итог;
  };
  const тегРавен = (тег: number): string =>
    `    если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(тег)}`;

  // ПРОЦЕДУРА_НАЧАЛО: событие 1, позиции, имя (текст развёрнут).
  строки.push(тегРавен(ТЕГИ.ПРОЦЕДУРА_НАЧАЛО));
  строки.push(...поля('1', '      '));
  строки.push(...из(`${з} + 2`, '      '));
  строки.push(...из(`${з} + 1`, '      '));
  строки.push(...из(`${з} + 3`, '      '));
  строки.push(...плюс9(`${з} + 2`, '      '));
  строки.push(...текстВ(индексИмени, '      '));

  // ЗАГОЛОВОК: событие 3, paramCount=0, returnFlag=1, тип.
  строки.push(`    иначе если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(ТЕГИ.ЗАГОЛОВОК)}`);
  строки.push(...поля('3', '      '));
  строки.push(...поля('0', '      '));
  строки.push(...поля('1', '      '));
  строки.push(...поля('1', '      '));
  строки.push(...текстВ(индексТипа, '      '));

  // ВЕРНУТЬ: событие 8, позиции, конец выражения, флаг.
  строки.push(`    иначе если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(ТЕГИ.ВЕРНУТЬ)}`);
  строки.push(...поля('8', '      '));
  строки.push(...из(`${з} + 2`, '      '));
  строки.push(...из(`${з} + 1`, '      '));
  строки.push(...из(`${з} + 3`, '      '));
  строки.push(...сумму(`${выр} + 2`, '      '));
  строки.push(...поля('1', '      '));

  // ЛИТЕРАЛ: событие 12, позиции, вид, текст (развёрнут).
  строки.push(`    иначе если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(ТЕГИ.ЛИТЕРАЛ)}`);
  строки.push(...поля('12', '      '));
  строки.push(...из(`${з} + 2`, '      '));
  строки.push(...сумму(`${з} + 2`, '      '));
  строки.push(...из(`${з} + 1`, '      '));
  строки.push(...из(`${з} + 3`, '      '));
  строки.push(...поля('1', '      '));
  строки.push(...текстВ(индексЛитерала, '      '));

  // ПРОЦЕДУРА_КОНЕЦ: событие 4; конец процедуры уже посчитан обработчиком (R.value).
  строки.push(`    иначе если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(ТЕГИ.ПРОЦЕДУРА_КОНЕЦ)}`);
  строки.push(...поля('4', '      '));
  строки.push(...поля(з, '      '));
  строки.push(`    иначе если (r нацело ${String(ВЕС_ТЕГА)}) % ${String(МОДУЛЬ_ТЕГА)} == ${String(ТЕГИ.КОНЕЦ)}`);
  строки.push(...поля('0', '      '));
  строки.push('    конец если');
  строки.push('  конец пока');
  // ── ПЕЧАТЬ ЖИВЁТ В ГЛАВНОЙ, А НЕ В ПРОЦЕДУРЕ (§3.62, D5) ──────────────────────────────────
  //
  // Прежняя редакция выносила печать в `действие напечатать(лента, предел)` — и это был ПАТТЕРН,
  // ЗАПРЕЩЁННЫЙ ИМЕНЕМ: разделённая печать из вызываемой упирается в зафиксированную границу §3.62
  // («вызов скрытой процедуры «число → текст» из выращенного кадра модель не исполняет»), и сборка
  // уходила в названный отказ `IR.print_write`. Образ при этом получался БЕЗ восстановления блока
  // рантайма массивов на сайте печати, и проба падала кодом 139 на `0x105328` — то есть 139 был
  // ДЕФЕКТОМ ПРОБЫ, а не кодогенератора (docs/hardware-debt.md §3.193).
  //
  // Парсер v0.1 устроен иначе и правильно: обработчики ВОЗВРАЩАЮТ значения, ленту пишут писатели,
  // а печатает ОДНА точка — `главная`. Печать здесь же и стоит: счётчик петли — уже живой `пт`,
  // отдельной клетки под `i` не заводится (в окне главной тесно: `текст`, `лента`, `шапка`, `r`,
  // `индекс`, `пт`).
  строки.push('  пт = ' + String(лентаНачало));
  строки.push('  пока пт < индекс');
  строки.push('    вывести прочитать(лента, пт)');
  строки.push('    пт = пт + 1');
  строки.push('  конец пока');
  строки.push('конец');
  строки.push('');

  return строки.join('\n');
}

/** Эталон: token tape → parserV01 → AST 2.1 → лента. */
export function эталоннаяЛента(источник: string = ИСХОДНИК_P2A, файл: string = ФАЙЛ_P2A): number[] {
  const итог = parseV01(источник, файл);
  if (!итог.ок) throw new Error(`эталонный парсер отказал: ${итог.ошибка.сообщение}`);
  return лентаИзAst(итог.ast);
}
