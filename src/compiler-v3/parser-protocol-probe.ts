  писать('  вернуть поз');
  писать('конец');
  писать('');

  // ── ПИСАТЕЛЬ ГРУППЫ (глубина 1): листья и `*`/`/` одной группы, post-order ───────────────────
  //
  // `пара = начало_группы * 4096 + конец_группы`: у носителя вызова не больше ТРЁХ аргументов
  // (`MAX_CALL_ARGS`), поэтому два положения едут одним числом (лента пробы короче 4096 токенов).
  // Возврат — `индекс * 4096 + последний_лист`: точка входа по нему продолжает и ставит событие
  // `+`/`-` уже после обеих групп, как требует post-order.
  писать('процедура выписать_группу(лента: Список Число, пара: Число, индекс: Число) → Число');
  писать('  пусть гн = пара нацело 4096');
  писать('  пусть кон = пара % 4096');
  писать('  пусть т = гн');
  писать('  пусть посл = гн');
  писать('  пусть ждёт = 0');
  писать('  пусть место = 0');
  писать('  пока т < кон');
  писать(`    если лента[т] == ${умн} или лента[т] == ${дел}`);
  писать('      ждёт = т');
  писать('    иначе');
  писать('      пусть вид = лента[т]');
  // лист: событие литерала (12) или имени (13); 3.0 — начало, конец, строка, колонка, [вид], длина, текст
  писать(`      если вид == ${им}`);
  писать(`        Списки.установить(лента, индекс, ${String(КОД_СОБЫТИЯ.имя)})`);
