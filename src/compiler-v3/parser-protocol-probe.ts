  строки.push('  пусть след = токен + 7 + лента[токен + 5]');
  строки.push('  пусть вид = лента[след]');
  строки.push(
    `  если вид == ${String(к['+']!)} или вид == ${String(к['-']!)} или вид == ${String(к['*']!)} или вид == ${String(к['/']!)}`,
  );
  строки.push('    пусть прав = след + 7 + лента[след + 5]');
