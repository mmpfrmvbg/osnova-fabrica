  писать('        конец если');
  писать('        Списки.установить(лента, индекс + 1, лента[гн + 2])');
  писать('        Списки.установить(лента, индекс + 2, лента[т + 2] + лента[т + 4])');
  писать('        Списки.установить(лента, индекс + 3, лента[гн + 1])');
  писать('        Списки.установить(лента, индекс + 4, лента[гн + 3])');
  писать('        индекс = индекс + 5');
  писать('        ждёт = 0');
  писать('      конец если');
  писать('      посл = т');
  писать('    конец если');
  писать('    т = т + 7 + лента[т + 5]');
  писать('  конец пока');
  писать('  вернуть индекс * 4096 + посл');
  писать('конец');
  писать('');

  // ── ПИСАТЕЛЬ `+`/`-` (глубина 1): одно событие, span от начала выражения до правого листа ────
  //
  // Токен оператора не передаётся: он лежит ровно за последним листом — `посл + 7 + лента[посл + 5]`.
  писать('процедура выписать_плюс(лента: Список Число, пара: Число, индекс: Число) → Число');
  писать('  пусть нач = пара нацело 4096');
  писать('  пусть посл = пара % 4096');
  писать('  пусть оп = посл + 7 + лента[посл + 5]');
  писать(`  если лента[оп] == ${плюс}`);
  писать(`    Списки.установить(лента, индекс, ${String(КОД_СОБЫТИЯ.бинарный_плюс)})`);
  писать('  иначе');
  писать(`    Списки.установить(лента, индекс, ${String(КОД_СОБЫТИЯ.бинарный_минус)})`);
  писать('  конец если');
  писать('  Списки.установить(лента, индекс + 1, лента[нач + 2])');
  писать('  Списки.установить(лента, индекс + 2, лента[посл + 2] + лента[посл + 4])');
  писать('  Списки.установить(лента, индекс + 3, лента[нач + 1])');
  писать('  Списки.установить(лента, индекс + 4, лента[нач + 3])');
  писать('  вернуть индекс + 5');
  писать('конец');
  писать('');
  // ── Диспетчер: только чтение, глубина 1 ────────────────────────────────────────────────────
  писать('процедура разобрать_процедуру(лента: Список Число, поз: Число) → Число');
  писать('  пусть т = поз + 7 + лента[поз + 5]');
  писать(`  вернуть т * ${В}`);
  писать('конец');
  писать('');

  писать('процедура разобрать_заголовок(лента: Список Число, поз: Число) → Число');
  писать('  пусть т = поз + 39 + лента[поз + 5]');
  писать('  пусть сл = т + 7 + лента[т + 5]');
  писать(`  вернуть сл * ${В} + ${String(ТЕГИ_P3B.ЗАГОЛОВОК * ВЕС_ТЕГА)}`);
  писать('конец');
  писать('');

  писать('процедура разобрать_конец_процедуры(лента: Список Число, поз: Число) → Число');
  писать('  пусть имя = поз + 7 + лента[поз + 5]');
  писать('  пусть ин = лента[имя + 2]');
