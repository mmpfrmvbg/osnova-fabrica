  писать('');

  // `разобрать_присваивание`: имя `=` выражение. Цепочки/составные левые части НЕ поддержаны —
  // `OSN-PAR-029` (названная граница, а не «обошли молча»).
  писать('процедура разобрать_присваивание(лента: Список Число, поз: Число) → Число');
  писать('  пусть равно = поз + 7 + лента[поз + 5]');
  писать('  пусть знач = равно + 7 + лента[равно + 5]');
  писать('  пусть после = знач + 7 + лента[знач + 5]');
  писать(`  если ${операторыПослеЗначения}`);
  писать('    пусть прав = после + 7 + лента[после + 5]');
  писать('    после = прав + 7 + лента[прав + 5]');
  писать('  конец если');
  писать(`  вернуть после * ${В} + ${String(ТЕГИ_P4B.ПРИСВАИВАНИЕ * ВЕС_ТЕГА)} + поз`);
