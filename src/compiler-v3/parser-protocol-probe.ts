/**
 * РАСКЛАДКА `R = позиция·2^21 + тег·2^16 + значение` — 31 БИТ, НЕ 52 (§3.193.5).
 *
 * ПОЧЕМУ НЕ 52. Прежняя раскладка `value·2^29 + tag·2^24 + pos` давала R до `2^52−1`, а Число
 * цели — 32-битное ЗНАКОВОЕ. Уже шаг `поз = 4` даёт `4·2^29 = 2^31` → r отрицателен → индекс
 * `r % 2^24` = `0xFF000052` → адрес `8·0xFF000052 + база` = `0x7f8112a0`; железо падает 139, модель
 * петляет (`docs/hardware-debt.md` §3.193.4). Здесь максимум
 * `511·2^21 + 31·2^16 + 65535 = 1 075 838 975 < 2^31−1` — знак не переходит никогда.
 *
 * ПОЛЯ: позиция (9 бит, ≤ 511) — АРГУМЕНТ диспетчера, куда идти дальше; тег (5 бит) — вид события;
 * значение (16 бит, ≤ 65535) — полезная нагрузка (позиция токена / имя / конец). Тег читается как
 * `(R нацело 2^16) % 32`: `R нацело 2^16 = позиция·32 + тег`, а `позиция·32 % 32 = 0`.
 */
export const ВЕС_ПОЗИЦИИ = 2 ** 21;
export const ВЕС_ТЕГА = 2 ** 16;
export const МОДУЛЬ_ЗНАЧЕНИЯ = 2 ** 16;
export const МОДУЛЬ_ТЕГА = 2 ** 5;
export const МОДУЛЬ_ПОЗИЦИИ = 2 ** 9;
/** Предел упакованного шага: Число цели — 32-битное знаковое. */
export const ПРЕДЕЛ_R = 2 ** 31 - 1;

/** Упаковать шаг `R = позиция·2^21 + тег·2^16 + значение` с проверкой границ. */
export function упаковатьШаг(тег: number, значение: number, позиция: number): number {
  if (!Number.isInteger(тег) || тег < 0 || тег >= МОДУЛЬ_ТЕГА) {
    throw new Error(`тег вне 5 бит: ${String(тег)}`);
  }
  if (!Number.isInteger(значение) || значение < 0 || значение >= МОДУЛЬ_ЗНАЧЕНИЯ) {
    throw new Error(`значение вне 16 бит: ${String(значение)}`);
  }
  if (!Number.isInteger(позиция) || позиция < 0 || позиция >= МОДУЛЬ_ПОЗИЦИИ) {
    throw new Error(`позиция вне 9 бит: ${String(позиция)}`);
  }
  const R = позиция * ВЕС_ПОЗИЦИИ + тег * ВЕС_ТЕГА + значение;
  if (R > ПРЕДЕЛ_R) throw new Error(`R вне 31 бита: ${String(R)}`);
  return R;
}

/** Распаковать шаг; обратна {@link упаковатьШаг}. Отсечение к нулю, как `idiv`/`rem` VM. */
export function распаковатьШаг(R: number): { тег: number; значение: number; позиция: number } {
  const позиция = Math.trunc(R / ВЕС_ПОЗИЦИИ);
  const тег = Math.trunc((R % ВЕС_ПОЗИЦИИ) / ВЕС_ТЕГА);
  const значение = R % МОДУЛЬ_ЗНАЧЕНИЯ;
  return { тег, значение, позиция };
}

