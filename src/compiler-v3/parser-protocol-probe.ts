  // ВЕРНУТЬ
  строки.push(`    иначе если ${тег} == ${String(ТЕГИ_P3A.ВЕРНУТЬ)}`);
  строки.push(...поля('8', '      '));
  строки.push(...из(`${з} + 2`, '      '));
  строки.push(...из(`${з} + 1`, '      '));
