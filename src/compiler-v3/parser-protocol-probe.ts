  писать('      конец если');
  писать('      Списки.установить(лента, индекс + 1, лента[т + 2])');
  писать('      Списки.установить(лента, индекс + 2, лента[т + 2] + лента[т + 4])');
  писать('      Списки.установить(лента, индекс + 3, лента[т + 1])');
  писать('      Списки.установить(лента, индекс + 4, лента[т + 3])');
  писать('      индекс = индекс + 5');
  писать(`      если вид != ${им}`);
  писать(`        Списки.установить(лента, индекс, ${String(КОД_ЛИТЕРАЛА.число)})`);
  писать('        индекс = индекс + 1');
  писать('      конец если');
  писать('      Списки.установить(лента, индекс, лента[т + 5])');
  писать('      место = 0');
  писать('      пока место < лента[т + 5]');
  писать('        Списки.установить(лента, индекс + 1 + место, лента[т + 6 + место])');
  писать('        место = место + 1');
  писать('      конец пока');
  писать('      индекс = индекс + 1 + лента[т + 5]');
