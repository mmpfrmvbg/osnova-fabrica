/**
 * ПРОТОКОЛ ПАРСЕРА v0.1 — ФОРМА P2a: ДИСПЕТЧЕР + ПИСАТЕЛЬ ГЛУБИНЫ 1.
 *
 * # Что изменилось против P2 (красного)
 *
 * P2 писал AST-ленту ВНУТРИ той же петли, что разбирала токены. На заголовке петли жили значения
 * всех ветвей, и раскладка `главной` требовала пик **22** при пределе D48 ≤ 10
 * (`docs/parser-protocol.md` §8). P2a разносит это по плоскостям:
 *
 *   • `главная` (глубина 0) читает `R`, считает тег и ВЫЧИСЛЯЕТ ОДНО поле;
 *   • `записать_поле` (глубина 1, лист) делает РОВНО ОДНУ запись `Списки.установить` и возвращает
 *     `индекс + 1`;
 *   • `разобрать_X` (глубина 2+) только читают токены и возвращают `R` — без записи, без арены.
 *
 * # Почему писатель ОДИН и почему в нём одно `Списки.установить`
 *
 * Это измерение, а не стиль. Один `Списки.установить` в листовой процедуре даёт пик **7**;
 * два подряд — уже **11**, то есть выше предела D48 ≤ 10. Причина в понижении D43b: вызов
 * возвращает список, и приёмник каждого вызова (свежий vreg) живёт до конца процедуры, даже если
 * результат не используется; два таких приёмника вместе с аргументами дают 11. Поэтому «писатель
 * тега» с четырьмя-шестью записями в P2a **не раскладывается**, а писатель одного поля — да.
 *
 * Восемь тегов остаются в диспетчере; писатель у них общий, потому что запись в ленту — одна и та
 * же операция. Это названное расхождение с формулировкой «записать_X ×N»: N = 1, иначе D48
 * нарушается. Альтернатива (писатель тега на 6 записей) — измеренный пик 17, то есть красное.
 *
 * # Лента одна, но это НЕ случайно «токены + AST» в одном списке
 *
 * Писатель получает ТРИ аргумента (D2: максимум три, четвёртый — исключение): `лента`, `значение`,
 * `индекс`. Токены ему тоже нужны, поэтому `лента` — РАБОЧАЯ лента: сначала token tape, затем
 * заголовок AST, затем 10000 заранее выделенных нулевых клеток. `главная` читает токены по `знач`
 * и пишет AST по `индекс`; `Списки.установить` не расширяет список, поэтому клетки уже есть.
 *
 * # Восемь тегов, а не двадцать четыре
 *
 * P2a проверяет форму, а не грамматику. Теги: `процедура_начало`, `параметр`, `заголовок`,
 * `процедура_конец`, `вернуть`, `литерал`, `имя`, `конец`. `если`/`пока`/`пусть`/`присваивание`/
 * `квалификация`/`список`/`индексация`/`иначе если` — P3. Эталон — ровно одна программа:
 *
 *     процедура п() -> Число
 *       вернуть 42
 *     конец п
 *
 * Текст имени/типа/литерала в этой программе ЗАРАНЕЕ известен из token tape, поэтому он развёрнут
 * в последовательность `записать_поле` без петли по кодам: петля в листе давала пик 13–15, а
 * развёртка — ноль лишних живых значений. Для общего парсера это место — P3 (там нужен `записать_текст`
 * с бюджетом окна, а не D48-пик).
 *
 * # Чего здесь НЕТ
 *
 * Полной грамматики, backpatch, `Результат`-пары в точке входа (D49), `Списки.взять`.
 */

