  строки.push('конец');
  строки.push('');

  строки.push('процедура записать_текст_из(лента: Список Число, токен: Число, индекс: Число) → Число');
  строки.push('  пусть д = лента[токен + 5]');
  строки.push('  Списки.установить(лента, индекс, д)');
  строки.push('  пусть место = 0');
  строки.push('  пока место < д');
  строки.push('    Списки.установить(лента, индекс + 1 + место, лента[токен + 6 + место])');
  строки.push('    место = место + 1');
  строки.push('  конец пока');
  строки.push('  вернуть индекс + 1 + д');
  строки.push('конец');
  строки.push('');

  строки.push('процедура конец_выражения(лента: Список Число, токен: Число) → Число');
  строки.push('  пусть след = токен + 7 + лента[токен + 5]');
  строки.push('  пусть вид = лента[след]');
  строки.push(
    `  если вид == ${String(к['+']!)} или вид == ${String(к['-']!)} или вид == ${String(к['*']!)} или вид == ${String(к['/']!)}`,
  );
  строки.push('    пусть прав = след + 7 + лента[след + 5]');
  строки.push('    вернуть прав + 7 + лента[прав + 5]');
  строки.push('  конец если');
  строки.push('  вернуть след');
  строки.push('конец');
  строки.push('');

  строки.push('процедура конец_смещения(лента: Список Число, токен: Число) → Число');
  строки.push('  пусть след = токен + 7 + лента[токен + 5]');
  строки.push('  пусть вид = лента[след]');
  строки.push(
    `  если вид == ${String(к['+']!)} или вид == ${String(к['-']!)} или вид == ${String(к['*']!)} или вид == ${String(к['/']!)}`,
  );
  строки.push('    пусть прав = след + 7 + лента[след + 5]');
  строки.push('    пусть пн = лента[прав + 2]');
  строки.push('    пусть пк = лента[прав + 4]');
  строки.push('    вернуть пн + пк');
  строки.push('  конец если');
  строки.push('  пусть тн = лента[токен + 2]');
  строки.push('  пусть тк = лента[токен + 4]');
  строки.push('  вернуть тн + тк');
