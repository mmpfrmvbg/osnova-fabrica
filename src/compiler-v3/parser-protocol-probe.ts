  строки.push('конец');
  строки.push('');

  строки.push('процедура разобрать_присваивание(лента: Список Число, поз: Число) → Число');
  строки.push('  пусть равно = поз + 7 + лента[поз + 5]');
  строки.push('  пусть знач = равно + 7 + 1');
  строки.push('  пусть кон = конец_выражения(лента, знач)');
  строки.push('  пусть смещ = конец_смещения(лента, знач)');
  строки.push(
    `  вернуть кон * ${В} + ${String(ТЕГИ_P3B.ПРИСВАИВАНИЕ * ВЕС_ТЕГА)} + смещ`,
  );
  строки.push('конец');
  строки.push('');

