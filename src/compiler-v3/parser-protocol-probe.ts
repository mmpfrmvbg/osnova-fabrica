  строки.push(`    иначе если ${тег} == ${String(ТЕГИ_P3A.ПОКА_КОНЕЦ)}`);
  строки.push(`      индекс = записать_пока_конец(лента, ${з}, индекс)`);

  // ПРОЦЕДУРА_КОНЕЦ
