/**
 * СТОРОЖ ИМЁН РАЗВОРОТА: пользователь объявляет `__предел_н` сам.
 *
 * Прежде разворот объявлял вспомогательные имена как «такого не напишут» —
 * соглашение вместо гарантии. Теперь имя берётся первым свободным, и эта проба
 * держит именно столкновение: объявляем ровно те имена, которые разворот хотел
 * занять, и проверяем, что он взял другие и результат ВЕРНЫЙ.
 */
import { describe, expect, it } from "vitest";
import { validateNamedTypesAndRewrite } from "../compiler/compiler";
import { compile } from "../compiler/codegen";
import { createDefaultInvokeHandler, VM } from "../runtime/vm/interpreter";
import { parseV3 } from "./index";

const ФАЙЛ = "имена.osnova";

async function значение(src: string): Promise<unknown> {
  const р = parseV3(src, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join("; ")}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  const vm = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 100_000 });
  return vm.runProcedure(vm.findProcedureIndex("главная"), []);
}

describe("разворот не сталкивается с именами пользователя", () => {
  it("`__предел_н` объявлен пользователем — разворот берёт другое имя", async () => {
    // Если бы разворот занял `__предел_н`, пользовательская переменная была бы
    // затёрта, и сумма поехала бы. Здесь она должна уцелеть.
    const итог = await значение(`действие главная()
  пусть __предел_н = 100
  пусть сумма = 0
  для н от 1 до 3
    сумма = сумма + н
  конец для
  вернуть сумма + __предел_н
конец главная
`);
    expect(итог).toBe(6 + 100);
  });

  it("`__повтор` и `__предел_повтора` объявлены пользователем", async () => {
    const итог = await значение(`действие главная()
  пусть __повтор = 1000
  пусть __предел_повтора = 2000
  пусть счёт = 0
  повторять 3 раза
    счёт = счёт + 1
  конец повторять
  вернуть счёт + __повтор + __предел_повтора
конец главная
`);
    expect(итог).toBe(3 + 1000 + 2000);
  });

  it("контроль: без столкновения имена остаются прежними", () => {
    // Сторож не должен переименовывать всегда — только при занятости имени.
    const р = parseV3(`действие главная()\n  для н от 1 до 3\n    вывести н\n  конец для\n  вернуть 0\nконец главная\n`, ФАЙЛ);
    expect(JSON.stringify(р.program)).toContain("__предел_н");
  });

  it("ДВА ВЛОЖЕННЫХ `повторять` не берут одно имя (дыра, найденная вычиткой)", async () => {
    // Предварительный скан токенов знает только ПОЛЬЗОВАТЕЛЬСКИЕ имена. Пока выданные
    // имена не резервировались, оба вложенных разворота брали `__повтор` — замерено.
    // Здесь проверяются оба следствия: имена разные И результат верный.
    const src = `действие главная()
  пусть счёт = 0
  повторять 2 раза
    повторять 3 раза
      счёт = счёт + 1
    конец повторять
  конец повторять
  вернуть счёт
конец главная
`;
    const р = parseV3(src, ФАЙЛ);
    expect(р.errors).toEqual([]);
    const имена = (JSON.stringify(р.program).match(/"kind":"пусть","name":"([^"]*)"/g) ?? [])
      .map((с) => /"name":"([^"]*)"/.exec(с)![1]!)
      .filter((и) => и.includes("__") || и.includes("_1__"));
    // Два разных набора имён разворота, а не один и тот же дважды.
    expect(new Set(имена).size).toBe(имена.length);
    expect(имена.length).toBe(4);
    // И значение верное: 2 × 3 = 6.
    expect(await значение(src)).toBe(6);
  });

  it("вложенный разворот + пользовательское `_1__повтор`: займёт следующее", async () => {
    const итог = await значение(`действие главная()
  пусть _1__повтор = 500
  пусть счёт = 0
  повторять 2 раза
    повторять 3 раза
      счёт = счёт + 1
    конец повторять
  конец повторять
  вернуть счёт + _1__повтор
конец главная
`);
    expect(итог).toBe(6 + 500);
  });
});
