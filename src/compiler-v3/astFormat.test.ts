/**
 * AST 2.0/2.1: формат, а не парсер. Здесь дерево строится руками, чтобы проверять
 * ленту/JSON независимо от `parserV01`: откат формата краснит эти проверки,
 * даже если reference-парсер ещё не тронут.
 *
 * N = 6 новых проверок 2.1: присваивание, квалифицированный вызов, общий roundtrip,
 * 2.1-читатель+строка версии, 2.0-читатель→`OSN-AST-001`, writer 1.1 отвергает 2.1.
 * Проверки 1–8 — регрессия 2.0, они зелены на старом формате и в N не входят.
 */
import { describe, expect, it } from 'vitest';
import {
  ВЕРСИЯ_AST_СТРОКА,
  лентаИзAst,
  прочитатьЛенту,
  type AstФайл,
  type Выражение,
  type Оператор,
  type Позиция,
} from './astFormat';

const поз = (начало: number, конец: number): Позиция => ({ начало, конец, строка: 1, колонка: начало + 1 });
const лит = (текст: string, начало: number): Выражение =>
  ({ вид: 'литерал', литерал: { вид: 'число', текст }, позиция: поз(начало, начало + текст.length) }) as Выражение;
const имя = (значение: string, начало: number): Выражение =>
  ({ вид: 'имя', имя: значение, позиция: поз(начало, начало + значение.length) }) as Выражение;
const бинар = (оператор: string, левый: Выражение, правый: Выражение): Выражение =>
  ({
    вид: 'бинарное',
    оператор,
    левый,
    правый,
    позиция: поз(левый.позиция.начало, правый.позиция.конец),
  }) as unknown as Выражение;
const унар = (оператор: string, операнд: Выражение, начало: number): Выражение =>
  ({ вид: 'унарное', оператор, операнд, позиция: поз(начало, операнд.позиция.конец) }) as unknown as Выражение;
const список = (элементы: readonly Выражение[], начало: number): Выражение =>
  ({ вид: 'список', элементы, позиция: поз(начало, начало + 2) }) as unknown as Выражение;
const индексация = (база: Выражение, индекс: Выражение): Выражение =>
  ({
    вид: 'индексация',
    база,
    индекс,
    позиция: поз(база.позиция.начало, индекс.позиция.конец + 1),
  }) as unknown as Выражение;
const вернуть = (значение: Выражение): Оператор =>
  ({ вид: 'вернуть', значение, позиция: поз(0, значение.позиция.конец) }) as Оператор;
const присв = (имя: string, значение: Выражение, начало: number, конец: number): Оператор =>
  ({ вид: 'присваивание', имя, значение, позиция: поз(начало, конец) }) as Оператор;
const квал = (
  библиотека: string,
  функция: string,
  аргументы: readonly Выражение[],
  начало: number,
  конец: number,
): Выражение =>
  ({ вид: 'квалифицированный_вызов', библиотека, функция, аргументы, позиция: поз(начало, конец) }) as Выражение;
const если = (
  условие: Выражение,
  тогда: readonly Оператор[],
  иначе: readonly Оператор[] | undefined,
  начало: number,
  конец: number,
): Оператор =>
  ({
    вид: 'если',
    условие,
    тогда,
    ...(иначе === undefined ? {} : { иначе }),
    позиция: поз(начало, конец),
  }) as Оператор;

function файл(тело: readonly Оператор[], версия = '2.0', действие = true): AstФайл {
  return {
    формат: 'osnova-ast',
    версия,
    модуль: { имя: 'тест', позиция: поз(0, 100) },
    процедуры: [
      {
        id: 'p0',
        имя: 'тест',
        действие,
        параметры: [],
        возвращает: null,
        тело,
        контракт: { требует: [], обеспечивает: [], эффекты: [] },
        позиция: поз(0, 100),
      },
    ],
  } as AstФайл;
}

/** Дерево со всеми новыми видами 2.0 и цепочкой `иначе если`. */
function дерево(): AstФайл {
  const третья = если(имя('в', 70), [вернуть(лит('3', 72))], undefined, 66, 78);
  const вторая = если(имя('б', 55), [вернуть(лит('2', 57))], [третья], 51, 78);
  const первая = если(имя('а', 40), [вернуть(лит('1', 42))], [вторая], 36, 78);
  return файл([
    вернуть(бинар('+', лит('1', 10), бинар('*', лит('2', 14), лит('3', 18)))),
    вернуть(унар('-', лит('4', 24), 23)),
    вернуть(унар('не', имя('флаг', 28), 27)),
    вернуть(список([лит('1', 32), лит('2', 35)], 31)),
    вернуть(индексация(имя('а', 39), лит('0', 41))),
    вернуть(бинар('нацело', лит('10', 45), лит('3', 52))),
    первая,
  ]);
}

/** Короткая цепочка с позициями 1–4: в ней 40/7 не встречаются как полезная нагрузка. */
function миниЦепочка(): AstФайл {
  const третья = если(имя('в', 3), [вернуть(лит('3', 4))], undefined, 3, 4);
  const вторая = если(имя('б', 2), [вернуть(лит('2', 3))], [третья], 2, 4);
  const первая = если(имя('а', 1), [вернуть(лит('1', 2))], [вторая], 1, 4);
  return файл([первая]);
}

describe('AST 2.0/2.1: формат', () => {
  it('1. roundtrip 2.0: AST → лента → AST без потерь', () => {
    const ast = дерево();
    const итог = прочитатьЛенту(лентаИзAst(ast));
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });

  it('2. лента 2.0 побайтово устойчива к повторному roundtrip', () => {
    const ast = дерево();
    const лента = лентаИзAst(ast);
    const итог = прочитатьЛенту(лента);
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(лентаИзAst(итог.ast)).toEqual(лента);
  });

  it('3. `иначе если` — плоское событие 40, один `если_конец` 7', () => {
    const лента = лентаИзAst(миниЦепочка());
    expect(лента.filter((код) => код === 40)).toHaveLength(2);
    expect(лента.filter((код) => код === 7)).toHaveLength(1);
    expect(лента.filter((код) => код === 6)).toHaveLength(0);
  });

  it('4. writer 1.1 отвергает новые узлы, а не понижает их', () => {
    expect(() => лентаИзAst(файл([вернуть(бинар('+', лит('1', 1), лит('2', 4)))], '1.1'))).toThrow();
  });

  it('5. 1.1-лента читается 2.0', () => {
    const старый = файл([вернуть(лит('1', 1))], '1.1');
    const итог = прочитатьЛенту(лентаИзAst(старый));
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(старый);
  });

  it('6. 1.1-читатель отвергает 2.0 — OSN-AST-001', () => {
    const итог = (прочитатьЛенту as unknown as (ч: number[], в: { мажор: number; минор: number }) => ReturnType<typeof прочитатьЛенту>)(
      лентаИзAst(дерево()),
      { мажор: 1, минор: 1 },
    );
    expect(итог.ок).toBe(false);
    if (итог.ок) return;
    expect(итог.ошибка.код).toBe('OSN-AST-001');
  });

  it('7. 1.0-лента читается 2.0', () => {
    const старый = файл([вернуть(лит('1', 1))], '1.0', false);
    const итог = прочитатьЛенту(лентаИзAst(старый));
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(старый);
  });

  it('8. 1.1-вложенное `иначе`+`если` читается 2.0 и канонизируется в 40 без потерь', () => {
    const старый = файл([миниЦепочка().процедуры[0]!.тело[0]!], '1.1');
    const прочитано = прочитатьЛенту(лентаИзAst(старый));
    expect(прочитано.ок).toBe(true);
    if (!прочитано.ок) return;
    expect(прочитано.ast).toEqual(старый);
    const обновлённый: AstФайл = { ...прочитано.ast, версия: '2.0' };
    const лента2 = лентаИзAst(обновлённый);
    expect(лента2.filter((код) => код === 40)).toHaveLength(2);
    const обратно = прочитатьЛенту(лента2);
    expect(обратно.ок).toBe(true);
    if (!обратно.ок) return;
    expect(обратно.ast).toEqual(обновлённый);
  });

  it('9. присваивание 2.1: событие 41 и полный roundtrip', () => {
    const ast = файл([присв('х', лит('5', 4), 0, 5)], '2.1');
    const лента = лентаИзAst(ast);
    expect(лента).toContain(41);
    const итог = прочитатьЛенту(лента, { мажор: 2, минор: 1 });
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });

  it('10. квалифицированный вызов 2.1: события 42/43 и roundtrip', () => {
    const вызов = квал('Печать', 'число', [лит('2', 12)], 0, 13);
    const ast = файл([вернуть(вызов)], '2.1');
    const лента = лентаИзAst(ast);
    expect(лента).toContain(42);
    expect(лента).toContain(43);
    const итог = прочитатьЛенту(лента, { мажор: 2, минор: 1 });
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });

  it('11. общий roundtrip 2.1 байт-в-байт: присваивание + квалифицированный вызов', () => {
    const вызов = квал('Списки', 'длина', [имя('с', 10)], 6, 13);
    const ast = файл([присв('х', вызов, 0, 13)], '2.1');
    const лента = лентаИзAst(ast);
    const итог = прочитатьЛенту(лента, { мажор: 2, минор: 1 });
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(лентаИзAst(итог.ast)).toEqual(лента);
  });

  it('12. 2.1-читатель читает 2.0 и строка версии — 2.1', () => {
    expect(ВЕРСИЯ_AST_СТРОКА).toBe('2.1');
    const старый = дерево();
    const итог = прочитатьЛенту(лентаИзAst(старый), { мажор: 2, минор: 1 });
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(старый);
  });

  it('13. 2.0-читатель отвергает 2.1 — OSN-AST-001', () => {
    const ast = файл([присв('х', лит('5', 4), 0, 5)], '2.1');
    const итог = прочитатьЛенту(лентаИзAst(ast), { мажор: 2, минор: 0 });
    expect(итог.ок).toBe(false);
    if (итог.ок) return;
    expect(итог.ошибка.код).toBe('OSN-AST-001');
  });

  it('14. writer 1.1 отвергает 2.1, а не понижает узлы', () => {
    const ast = файл([присв('х', лит('5', 4), 0, 5)], '1.1');
    expect(() => лентаИзAst(ast)).toThrow(/2\.1/);
  });
});
