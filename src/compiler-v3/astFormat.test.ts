/**
 * AST 3.0: формат, а не парсер. Дерево строится руками, чтобы проверять ленту/JSON независимо
 * от `parserV01`: откат порядка событий краснит эти проверки, даже если reference-парсер цел.
 *
 * N = 8 проверок 3.0: roundtrip, устойчивость ленты, post-order `2 + 3 * 4`, индексация,
 * вызов, `если`, `иначе если` и два named refusal (`OSN-AST-002` для 2.1, `OSN-AST-001` для
 * старых читателей). Проверки 1–2, 9–12 — регрессия формы/границ, они не про порядок.
 */
import { describe, expect, it } from 'vitest';
import {
  ВЕРСИЯ_AST_СТРОКА,
  КОД_СОБЫТИЯ,
  лентаИзAst,
  прочитатьЛенту,
  type AstФайл,
  type Выражение,
  type Оператор,
  type Позиция,
} from './astFormat';

const поз = (начало: number, конец: number): Позиция => ({ начало, конец, строка: 1, колонка: начало + 1 });
const лит = (текст: string, начало: number): Выражение =>
  ({ вид: 'литерал', литерал: { вид: 'число', текст }, позиция: поз(начало, начало + текст.length) }) as Выражение;
const имя = (значение: string, начало: number): Выражение =>
  ({ вид: 'имя', имя: значение, позиция: поз(начало, начало + значение.length) }) as Выражение;
const бинар = (оператор: string, левый: Выражение, правый: Выражение): Выражение =>
  ({
    вид: 'бинарное',
    оператор,
    левый,
    правый,
    позиция: поз(левый.позиция.начало, правый.позиция.конец),
  }) as unknown as Выражение;
const унар = (оператор: string, операнд: Выражение, начало: number): Выражение =>
  ({ вид: 'унарное', оператор, операнд, позиция: поз(начало, операнд.позиция.конец) }) as unknown as Выражение;
const список = (элементы: readonly Выражение[], начало: number): Выражение =>
  ({ вид: 'список', элементы, позиция: поз(начало, начало + 2) }) as unknown as Выражение;
const индексация = (база: Выражение, индекс: Выражение): Выражение =>
  ({
    вид: 'индексация',
    база,
    индекс,
    позиция: поз(база.позиция.начало, индекс.позиция.конец + 1),
  }) as unknown as Выражение;
const вызов = (имяВызова: string, аргументы: readonly Выражение[], начало: number, конец: number): Выражение =>
  ({ вид: 'вызов', имя: имяВызова, аргументы, позиция: поз(начало, конец) }) as Выражение;
const вернуть = (значение: Выражение): Оператор =>
  ({ вид: 'вернуть', значение, позиция: поз(0, значение.позиция.конец) }) as Оператор;
const присв = (имяПеременной: string, значение: Выражение, начало: number, конец: number): Оператор =>
  ({ вид: 'присваивание', имя: имяПеременной, значение, позиция: поз(начало, конец) }) as Оператор;
const квал = (
  библиотека: string,
  функция: string,
  аргументы: readonly Выражение[],
  начало: number,
  конец: number,
): Выражение =>
  ({ вид: 'квалифицированный_вызов', библиотека, функция, аргументы, позиция: поз(начало, конец) }) as Выражение;
const если = (
  условие: Выражение,
  тогда: readonly Оператор[],
  иначе: readonly Оператор[] | undefined,
  начало: number,
  конец: number,
): Оператор =>
  ({
    вид: 'если',
    условие,
    тогда,
    ...(иначе === undefined ? {} : { иначе }),
    позиция: поз(начало, конец),
  }) as Оператор;

function файл(тело: readonly Оператор[], версия = '3.0', действие = true): AstФайл {
  return {
    формат: 'osnova-ast',
    версия,
    модуль: { имя: 'тест', позиция: поз(0, 100) },
    процедуры: [
      {
        id: 'p0',
        имя: 'тест',
        действие,
        параметры: [],
        возвращает: null,
        тело,
        контракт: { требует: [], обеспечивает: [], эффекты: [] },
        позиция: поз(0, 100),
      },
    ],
  } as AstФайл;
}

/** События без заголовка: `начало = 6 + длина имени модуля`. */
function события(лента: readonly number[]): number[] {
  return лента.slice(6 + (лента[4] ?? 0));
}

/** Дерево со всеми видами 3.0 и цепочкой `иначе если`. */
function дерево(): AstФайл {
  const третья = если(имя('в', 70), [вернуть(лит('3', 72))], undefined, 66, 78);
  const вторая = если(имя('б', 55), [вернуть(лит('2', 57))], [третья], 51, 78);
  const первая = если(имя('а', 40), [вернуть(лит('1', 42))], [вторая], 36, 78);
  return файл([
    вернуть(бинар('+', лит('1', 10), бинар('*', лит('2', 14), лит('3', 18)))),
    вернуть(унар('-', лит('4', 24), 23)),
    вернуть(унар('не', имя('флаг', 28), 27)),
    вернуть(список([лит('1', 32), лит('2', 35)], 31)),
    вернуть(индексация(имя('а', 39), лит('0', 41))),
    вернуть(бинар('нацело', лит('10', 45), лит('3', 52))),
    вернуть(вызов('ф', [лит('7', 60), имя('х', 63)], 58, 66)),
    вернуть(квал('Печать', 'число', [лит('2', 68)], 66, 80)),
    первая,
  ]);
}

describe('AST 3.0: post-order', () => {
  it('1. roundtrip 3.0: AST → лента → AST без потерь', () => {
    const ast = дерево();
    const итог = прочитатьЛенту(лентаИзAst(ast));
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });

  it('2. лента 3.0 побайтово устойчива к повторному roundtrip', () => {
    const лента = лентаИзAst(дерево());
    const итог = прочитатьЛенту(лента);
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(лентаИзAst(итог.ast)).toEqual(лента);
  });

  it('3. `2 + 3 * 4` — листья, затем `*`, затем `+`, затем `вернуть`', () => {
    const лента = лентаИзAst(файл([вернуть(бинар('+', лит('2', 0), бинар('*', лит('3', 4), лит('4', 8))))]));
    const с = события(лента);
    expect(с.indexOf(КОД_СОБЫТИЯ.литерал)).toBeLessThan(с.lastIndexOf(КОД_СОБЫТИЯ.бинарный_умножить));
    expect(с.lastIndexOf(КОД_СОБЫТИЯ.бинарный_умножить)).toBeLessThan(с.lastIndexOf(КОД_СОБЫТИЯ.бинарный_плюс));
    expect(с.lastIndexOf(КОД_СОБЫТИЯ.бинарный_плюс)).toBeLessThan(с.lastIndexOf(КОД_СОБЫТИЯ.вернуть));
  });

  it('4. индексация: база и индекс — до события 39', () => {
    const с = события(лентаИзAst(файл([вернуть(индексация(имя('а', 0), лит('0', 2)))])));
    expect(с.indexOf(КОД_СОБЫТИЯ.имя)).toBeLessThan(с.indexOf(КОД_СОБЫТИЯ.индексация));
    expect(с.indexOf(КОД_СОБЫТИЯ.литерал)).toBeLessThan(с.indexOf(КОД_СОБЫТИЯ.индексация));
  });

  it('5. вызов: аргументы — до события 10, имя и конец — после', () => {
    const с = события(лентаИзAst(файл([вернуть(вызов('ф', [лит('1', 0), лит('2', 3)], 0, 6))])));
    const первыйАргумент = с.indexOf(КОД_СОБЫТИЯ.литерал);
    const начало = с.indexOf(КОД_СОБЫТИЯ.вызов_начало);
    const конец = с.indexOf(КОД_СОБЫТИЯ.вызов_конец);
    expect(первыйАргумент).toBeLessThan(начало);
    expect(начало).toBeLessThan(конец);
  });

  it('6. `если`: условие — до события 5', () => {
    const с = события(лентаИзAst(файл([если(имя('а', 0), [], undefined, 0, 5)])));
    expect(с.indexOf(КОД_СОБЫТИЯ.имя)).toBeLessThan(с.indexOf(КОД_СОБЫТИЯ.если_начало));
  });

  it('7. `иначе если` — два события 40, один 7, ноль 6; roundtrip', () => {
    const третья = если(имя('в', 3), [вернуть(лит('3', 4))], undefined, 3, 4);
    const вторая = если(имя('б', 2), [вернуть(лит('2', 3))], [третья], 2, 4);
    const первая = если(имя('а', 1), [вернуть(лит('1', 2))], [вторая], 1, 4);
    const ast = файл([первая]);
    const лента = лентаИзAst(ast);
    expect(лента.filter((код) => код === КОД_СОБЫТИЯ.иначе_если)).toHaveLength(2);
    expect(лента.filter((код) => код === КОД_СОБЫТИЯ.если_конец)).toHaveLength(1);
    expect(лента.filter((код) => код === КОД_СОБЫТИЯ.иначе)).toHaveLength(0);
    const итог = прочитатьЛенту(лента);
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });

  it('8. 3.0-читатель отвергает 2.1 — OSN-AST-002, а не «попробуем»', () => {
    const итог = прочитатьЛенту([20261108, 2, 1]);
    expect(итог.ок).toBe(false);
    if (итог.ок) return;
    expect(итог.ошибка.код).toBe('OSN-AST-002');
  });

  it('9. 2.0/1.1-читатели отвергают 3.0 — OSN-AST-001', () => {
    const лента = лентаИзAst(файл([вернуть(лит('1', 0))]));
    for (const читатель of [
      { мажор: 2, минор: 0 },
      { мажор: 1, минор: 1 },
    ]) {
      const итог = прочитатьЛенту(лента, читатель);
      expect(итог.ок).toBe(false);
      if (!итог.ок) expect(итог.ошибка.код).toBe('OSN-AST-001');
    }
  });

  it('10. writer 3.0 отвергает AST 2.1, а не понижает узлы', () => {
    expect(() => лентаИзAst(файл([вернуть(лит('1', 0))], '2.1'))).toThrow(/3\.0/);
  });

  it('11. контракты D42 — AST 3.1: writer 3.0 их не пишет', () => {
    const ast = файл([вернуть(лит('1', 0))]);
    const сКонтрактом = {
      ...ast,
      процедуры: [{ ...ast.процедуры[0]!, контракт: { требует: [лит('1', 0)], обеспечивает: [], эффекты: [] } }],
    } as AstФайл;
    expect(() => лентаИзAst(сКонтрактом)).toThrow(/3\.1/);
  });

  it('12. присваивание и квалифицированный вызов остаются в 3.0', () => {
    const ast = файл([присв('х', квал('Списки', 'длина', [имя('с', 10)], 6, 13), 0, 13)]);
    const лента = лентаИзAst(ast);
    expect(лента).toContain(КОД_СОБЫТИЯ.присваивание);
    expect(лента).toContain(КОД_СОБЫТИЯ.квалифицированный_вызов);
    expect(ВЕРСИЯ_AST_СТРОКА).toBe('3.0');
    const итог = прочитатьЛенту(лента);
    expect(итог.ок).toBe(true);
    if (!итог.ок) return;
    expect(итог.ast).toEqual(ast);
  });
});
