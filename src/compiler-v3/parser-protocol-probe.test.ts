/**
 * УПАКОВКА ШАГА P2a — 31 БИТ, А НЕ 52 (§3.193.5 `docs/hardware-debt.md`).
 *
 * Прежняя раскладка `значение·2^29 + тег·2^24 + позиция` давала R до `2^52−1`, а Число цели —
 * 32-битное ЗНАКОВОЕ: уже `поз = 4` давало `4·2^29 = 2^31`, r становился отрицательным, индекс
 * `r % 2^24` = `0xFF000052`, и адрес `8·0xFF000052 + база` = `0x7f8112a0` валил железо кодом 139.
 * Здесь проверяется, что это НЕ вернётся: предел R строго меньше `2^31`, распаковка обратна
 * упаковке на границах полей, а генератор программы не содержит старых весов.
 */
import { describe, expect, it } from "vitest";
import {
  МОДУЛЬ_ЗНАЧЕНИЯ,
  МОДУЛЬ_ПОЗИЦИИ,
  МОДУЛЬ_ТЕГА,
  ПРЕДЕЛ_R,
  ВЕС_ПОЗИЦИИ,
  эталоннаяЛента,
  программаПротоколаP2a,
  распаковатьШаг,
  упаковатьШаг,
} from "./parser-protocol-probe";

describe("упаковка шага P2a: 31 бит", () => {
  it("границы полей: максимум упаковки < 2^31−1 и круг «туда-обратно»", () => {
    const максимум = упаковатьШаг(МОДУЛЬ_ТЕГА - 1, МОДУЛЬ_ЗНАЧЕНИЯ - 1, МОДУЛЬ_ПОЗИЦИИ - 1);
    expect(максимум).toBe((МОДУЛЬ_ПОЗИЦИИ - 1) * ВЕС_ПОЗИЦИИ + (МОДУЛЬ_ТЕГА - 1) * 2 ** 16 + (МОДУЛЬ_ЗНАЧЕНИЯ - 1));
    expect(максимум).toBe(1_073_741_823); // 2^30 − 1: 511·2^21 + 31·2^16 + 65535
    expect(максимум).toBeLessThan(ПРЕДЕЛ_R);
    expect(распаковатьШаг(максимум)).toEqual({
      тег: МОДУЛЬ_ТЕГА - 1,
      значение: МОДУЛЬ_ЗНАЧЕНИЯ - 1,
      позиция: МОДУЛЬ_ПОЗИЦИИ - 1,
    });
  });

  it("круг «туда-обратно» на реальных шагах P2a", () => {
    const шаги: [number, number, number][] = [
      [0, 0, 0],
      [0, 0, 16], // разобрать_процедуру: нагрузка 0, следующая позиция 16
      [2, 68, 107], // заголовок: нагрузка т, следующий токен
      [10, 82, 139], // вернуть: нагрузка — позиция токена
      [23, 0, 140], // конец модуля
    ];
    for (const [тег, значение, позиция] of шаги) {
      expect(распаковатьШаг(упаковатьШаг(тег, значение, позиция))).toEqual({ тег, значение, позиция });
    }
  });

  it("выход за поле — именованный отказ, а не тихое переполнение", () => {
    expect(() => упаковатьШаг(МОДУЛЬ_ТЕГА, 0, 0)).toThrow(/тег вне 5 бит/);
    expect(() => упаковатьШаг(0, МОДУЛЬ_ЗНАЧЕНИЯ, 0)).toThrow(/значение вне 16 бит/);
    expect(() => упаковатьШаг(0, 0, МОДУЛЬ_ПОЗИЦИИ)).toThrow(/позиция вне 9 бит/);
  });

  it("генератор программы использует новые веса и не содержит старых", () => {
    const источник = программаПротоколаP2a();
    expect(источник).toContain(`* ${String(ВЕС_ПОЗИЦИИ)}`);
    expect(источник).toContain(`r нацело ${String(ВЕС_ПОЗИЦИИ)}`);
    expect(источник).toContain(`r % ${String(МОДУЛЬ_ЗНАЧЕНИЯ)}`);
    expect(источник).not.toContain("536870912"); // 2^29 — старый вес значения
    expect(источник).not.toContain("33554432"); // старый тег ЗАГОЛОВОК·2^24
    expect(источник).not.toContain("167772160"); // старый тег ВЕРНУТЬ·2^24
  });

  it("эталонная лента P2a — 43 клетки (оракул AST v0.1)", () => {
    expect(эталоннаяЛента().length).toBe(43);
  });
});
