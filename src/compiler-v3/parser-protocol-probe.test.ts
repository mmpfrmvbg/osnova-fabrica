/**
 * УПАКОВКА ШАГА P2a — 31 БИТ, А НЕ 52 (§3.193.5 `docs/hardware-debt.md`).
 *
 * Прежняя раскладка `значение·2^29 + тег·2^24 + позиция` давала R до `2^52−1`, а Число цели —
 * 32-битное ЗНАКОВОЕ: уже `поз = 4` давало `4·2^29 = 2^31`, r становился отрицательным, индекс
 * `r % 2^24` = `0xFF000052`, и адрес `8·0xFF000052 + база` = `0x7f8112a0` валил железо кодом 139.
 * Здесь проверяется, что это НЕ вернётся: предел R строго меньше `2^31`, распаковка обратна
 * упаковке на границах полей, а генератор программы не содержит старых весов.
 */
import { describe, expect, it } from "vitest";
import { parseV3 } from "./index";
import { loweredProgram } from "../e2k/lowered";
import {
  ИСХОДНИК_P3A,
  ИСХОДНИК_P3A_ВЛОЖЕННЫЙ,
  ИСХОДНИК_P3A_ВЛОЖЕННЫЙ_3,
  ИСХОДНИК_P3B,
  ИСХОДНИК_P3B_V3,
  ИСХОДНИК_P3B_2_V3,
  ИСХОДНИК_P3B_3_V3,
  ТЕГИ_P2A,
  ТЕГИ_P3A,
  ТЕГИ_P3A_ВСЕ,
  ТЕГИ_P3B,
  ТЕГИ_P3B_ВСЕ,
  ФАЙЛ_P3B,
  программаПротоколаP3b,
  ФАЙЛ_P3A,
  МОДУЛЬ_ЗНАЧЕНИЯ,
  МОДУЛЬ_ПОЗИЦИИ,
  МОДУЛЬ_ТЕГА,
  ПРЕДЕЛ_R,
  ВЕС_ПОЗИЦИИ,
  эталоннаяЛента,
  программаПротоколаP2a,
  программаПротоколаP3a,
  распаковатьШаг,
  упаковатьШаг,
} from "./parser-protocol-probe";

describe("упаковка шага P2a: 31 бит", () => {
  it("границы полей: максимум упаковки < 2^31−1 и круг «туда-обратно»", () => {
    const максимум = упаковатьШаг(МОДУЛЬ_ТЕГА - 1, МОДУЛЬ_ЗНАЧЕНИЯ - 1, МОДУЛЬ_ПОЗИЦИИ - 1);
    expect(максимум).toBe((МОДУЛЬ_ПОЗИЦИИ - 1) * ВЕС_ПОЗИЦИИ + (МОДУЛЬ_ТЕГА - 1) * 2 ** 16 + (МОДУЛЬ_ЗНАЧЕНИЯ - 1));
    expect(максимум).toBe(1_073_741_823); // 2^30 − 1: 511·2^21 + 31·2^16 + 65535
    expect(максимум).toBeLessThan(ПРЕДЕЛ_R);
    expect(распаковатьШаг(максимум)).toEqual({
      тег: МОДУЛЬ_ТЕГА - 1,
      значение: МОДУЛЬ_ЗНАЧЕНИЯ - 1,
      позиция: МОДУЛЬ_ПОЗИЦИИ - 1,
    });
  });

  it("круг «туда-обратно» на реальных шагах P2a", () => {
    const шаги: [number, number, number][] = [
      [0, 0, 0],
      [0, 0, 16], // разобрать_процедуру: нагрузка 0, следующая позиция 16
      [2, 68, 107], // заголовок: нагрузка т, следующий токен
      [10, 82, 139], // вернуть: нагрузка — позиция токена
      [23, 0, 140], // конец модуля
    ];
    for (const [тег, значение, позиция] of шаги) {
      expect(распаковатьШаг(упаковатьШаг(тег, значение, позиция))).toEqual({ тег, значение, позиция });
    }
  });

  it("выход за поле — именованный отказ, а не тихое переполнение", () => {
    expect(() => упаковатьШаг(МОДУЛЬ_ТЕГА, 0, 0)).toThrow(/тег вне 5 бит/);
    expect(() => упаковатьШаг(0, МОДУЛЬ_ЗНАЧЕНИЯ, 0)).toThrow(/значение вне 16 бит/);
    expect(() => упаковатьШаг(0, 0, МОДУЛЬ_ПОЗИЦИИ)).toThrow(/позиция вне 9 бит/);
  });

  it("генератор программы использует новые веса и не содержит старых", () => {
    const источник = программаПротоколаP2a();
    expect(источник).toContain(`* ${String(ВЕС_ПОЗИЦИИ)}`);
    expect(источник).toContain(`r нацело ${String(ВЕС_ПОЗИЦИИ)}`);
    expect(источник).toContain(`r % ${String(МОДУЛЬ_ЗНАЧЕНИЯ)}`);
    expect(источник).not.toContain("536870912"); // 2^29 — старый вес значения
    expect(источник).not.toContain("33554432"); // старый тег ЗАГОЛОВОК·2^24
    expect(источник).not.toContain("167772160"); // старый тег ВЕРНУТЬ·2^24
  });

  it("эталонная лента P2a — 43 клетки (оракул AST v0.1)", () => {
    expect(эталоннаяЛента().length).toBe(43);
  });
});

/**
 * ШАГ P3a — `если / иначе / конец если` (шесть новых тегов, 14 из 32).
 *
 * Здесь фиксируется только то, что СОБИРАЕТСЯ без цели: таблица тегов, состав генератора и
 * эталонная лента. Исполняемость на модели — замер в отчёте атома, не в тесте: тест не имеет
 * права запускать QEMU (см. `vitest.qemu.config.ts`).
 */
describe("шаг P3a: если / иначе / конец если", () => {
  it("тегов 14 из 32, шаги P3 идут 4…9, P2a не сдвинут", () => {
    expect(ТЕГИ_P3A_ВСЕ.length).toBe(14);
    expect(ТЕГИ_P3A.ЕСЛИ_НАЧАЛО).toBe(4);
    expect(ТЕГИ_P3A.ИНАЧЕ).toBe(5);
    expect(ТЕГИ_P3A.ИНАЧЕ_ЕСЛИ).toBe(6);
    expect(ТЕГИ_P3A.ЕСЛИ_КОНЕЦ).toBe(7);
    expect(ТЕГИ_P3A.ПОКА_НАЧАЛО).toBe(8);
    expect(ТЕГИ_P3A.ПОКА_КОНЕЦ).toBe(9);
    expect(ТЕГИ_P2A.length).toBe(8);
    expect(ТЕГИ_P3A.КОНЕЦ).toBe(23);
  });

  it("все теги влезают в 5 бит — модуль 32 не превышен", () => {
    for (const тег of ТЕГИ_P3A_ВСЕ) expect(тег).toBeLessThan(МОДУЛЬ_ТЕГА);
  });

  it("генератор P3a содержит обработчики и писателей шага P3", () => {
    const источник = программаПротоколаP3a();
    for (const имя of [
      "разобрать_если",
      "разобрать_иначе",
      "разобрать_пока",
      "разобрать_конец_любой",
      "разобрать_конец_блока",
      "разобрать_конец_цикла",
      "записать_если_начало",
      "записать_иначе",
      "записать_если_конец",
      "записать_пока_начало",
      "записать_пока_конец",
      "записать_код_оператора",
      "записать_рамку",
    ]) {
      expect(источник).toContain(`процедура ${имя}(`);
    }
    // Условие пишут ОТДЕЛЬНЫЕ писатели: один большой писатель не оставлял клеток под блок.
    expect(источник).toContain("записать_вид_операнда");
    expect(источник).toContain("записать_тело_операнда");
    expect(источник).not.toContain("записать_условие(лента");
  });

  it("генератор P2a не тронут шагом P3a: 8 тегов и 43 клетки на месте", () => {
    expect(программаПротоколаP2a()).toContain("процедура разобрать_процедуру(");
    expect(программаПротоколаP2a()).not.toContain("разобрать_если");
    expect(эталоннаяЛента().length).toBe(43);
  });

  it("глубина 3 СОБИРАЕТСЯ: код пробы влезает в страницу кода (место расширено 2026-11-09)", () => {
    // Проверка держит не число клеток эталона (оно выше), а МЕСТО: до переезда страницы области
    // записи (0x110000 → 0x11F000) сборка глубины 3 отказывала — код 67 056 против потолка 65 536.
    const источник = программаПротоколаP3a(ИСХОДНИК_P3A_ВЛОЖЕННЫЙ_3, ФАЙЛ_P3A);
    const разбор = parseV3(источник, ФАЙЛ_P3A);
    expect(разбор.errors, "проба обязана разбираться").toEqual([]);
    const итог = loweredProgram(источник, {
      filename: ФАЙЛ_P3A,
      parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    });
    expect(итог.ок, итог.ок ? "" : String(итог.отказ?.причина)).toBe(true);
    if (!итог.ок) return;
    expect(итог.значение.bytes.length, "образ обязан быть ВЫШЕ прежнего потолка 64 КиБ").toBeGreaterThan(65536);
  });
  it("эталонная лента P3a: 86, 113 и 141 клетка для глубин 1–3", () => {
    expect(эталоннаяЛента(ИСХОДНИК_P3A, ФАЙЛ_P3A).length).toBe(86);
    expect(эталоннаяЛента(ИСХОДНИК_P3A_ВЛОЖЕННЫЙ, ФАЙЛ_P3A).length).toBe(113);
    expect(эталоннаяЛента(ИСХОДНИК_P3A_ВЛОЖЕННЫЙ_3, ФАЙЛ_P3A).length).toBe(141);
  });

  it("эталон глубины 1 несёт события 5/6/7, 12, 8 и 30 (если, иначе, конец если, литерал, вернуть, «>»)", () => {
    const лента = эталоннаяЛента(ИСХОДНИК_P3A, ФАЙЛ_P3A);
    expect(лента).toContain(5);
    expect(лента).toContain(6);
    expect(лента).toContain(7);
    expect(лента).toContain(12);
    expect(лента).toContain(8);
    expect(лента).toContain(30);
    expect(лента[0]).toBe(20261108);
    expect(лента[лента.length - 1]).toBe(0);
  });
});

/**
 * ШАГ P3b — `пусть`, присваивание и арифметика. 20 тегов из 32.
 *
 * Исполнение на модели — в `src/e2k/parserProtocolP3b.test.ts` (шлюз QEMU); здесь только
 * собираемость, таблица тегов и эталонная лента, чтобы полный прогон оставался детерминированным.
 */
describe("шаг P3b: пусть / присваивание / арифметика", () => {
  it("тегов 20 из 32; шаги P3b не сдвигают P3a и P2a", () => {
    expect(ТЕГИ_P3B_ВСЕ.length).toBe(20);
    expect(ТЕГИ_P2A.length).toBe(8);
    expect(ТЕГИ_P3A_ВСЕ.length).toBe(14);
    expect(ТЕГИ_P3B.ПУСТЬ).toBe(11);
    expect(ТЕГИ_P3B.ПРИСВАИВАНИЕ).toBe(12);
    expect(ТЕГИ_P3B.БИНАРНЫЙ_ПЛЮС).toBe(13);
    expect(ТЕГИ_P3B.БИНАРНЫЙ_МИНУС).toBe(16);
    expect(ТЕГИ_P3B.БИНАРНЫЙ_УМНОЖИТЬ).toBe(17);
    expect(ТЕГИ_P3B.БИНАРНЫЙ_ДЕЛИТЬ).toBe(18);
    expect(ТЕГИ_P3B.КОНЕЦ).toBe(23);
    for (const тег of ТЕГИ_P3B_ВСЕ) expect(тег).toBeLessThan(МОДУЛЬ_ТЕГА);
  });

  it("генератор P3b содержит обработчики и листовые писатели, но не многозаписный литерал", () => {
    const источник = программаПротоколаP3b();
    for (const имя of [
      "разобрать_пусть",
      "разобрать_присваивание",
      "разобрать_вернуть",
      "разобрать_конец_процедуры",
      "записать_число",
      "записать_из",
      "записать_текст_из",
      "прочитать",
    ]) {
      expect(источник).toContain(`процедура ${имя}(`);
    }
    // Один писатель — одно `Списки.установить`; иначе раскладка отказывает.
    expect(источник).not.toContain("записать_литерал(лента");
    expect(источник).not.toContain("записать_имя(лента");
    expect(источник).not.toContain("записать_заголовок_бинара(лента");
  });

  it("эталонная лента P3b: 85 клеток, конец модуля 69", () => {
    const лента = эталоннаяЛента(ИСХОДНИК_P3B, ФАЙЛ_P3B);
    expect(лента.length).toBe(85);
    expect(лента[0]).toBe(20261108);
    expect(лента[8]).toBe(69);
    expect(лента[лента.length - 1]).toBe(0);
    expect(лента).toContain(14); // пусть
    expect(лента).toContain(41); // присваивание
    expect(лента).toContain(21); // бинарный +
  });

  it("оба коротких образца P3b разбираются компилятором v3", () => {
    for (const источник of [ИСХОДНИК_P3B_V3, ИСХОДНИК_P3B_2_V3, ИСХОДНИК_P3B_3_V3]) {
      const разбор = parseV3(источник, ФАЙЛ_P3B);
      expect(разбор.errors, источник.split("\n")[0]).toEqual([]);
    }
  });
});
