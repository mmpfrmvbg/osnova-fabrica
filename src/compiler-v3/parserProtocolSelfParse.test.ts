/**
 * Сторож замены упаковки (§7): пара «инд, токен» → клетка состояния.
 *
 * Проверки держат ФОРМУ (что именно переписывается и что остаётся), потому что замена текстовая:
 * молча не переписанная строка = молча потерянный сдвиг индекса. Отдельно фиксируется, что
 * переписанный текст РАЗБИРАЕТСЯ эталоном (присваивание по индексу v3 не разбирает — замена обязана
 * идти через `Списки.установить`).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from './index';
import { программаПротоколаB2b } from './parser-protocol-b2b';
import { безУпаковки } from './parserProtocolSelfParse';

const ИСХОДНИК = 'действие главная()\n  пусть а = 5\n  а = 6\nконец главная\n';
const КЛЕТКА = 70_001;

describe('§7: возврат пары без упаковки (клетка состояния)', () => {
  it('переписанная программа разбирается эталоном (иначе смысл замены не проверяем)', () => {
    const с = безУпаковки(программаПротоколаB2b(ИСХОДНИК, 'self.osnova'), КЛЕТКА);
    const разобранный = parseV3(с, 'self-osnova.osnova');
    expect(разобранный.errors, разобранный.errors.slice(0, 3).join('; ')).toEqual([]);
    expect(разобранный.program).not.toBeNull();
  });

  it('упаковки не остаётся, а клетка состояния появляется в каждой точке возврата', () => {
    const базовый = программаПротоколаB2b(ИСХОДНИК, 'self.osnova');
    const с = безУпаковки(базовый, КЛЕТКА);
    expect(с).not.toContain('* 65536');
    expect(с).not.toContain('нацело 65536');
    const записей = с.split('\n').filter((л) => л.includes(`Списки.установить(лента, ${String(КЛЕТКА)},`)).length;
    const возвратов = базовый.split('\n').filter((л) => л.includes('вернуть') && л.includes('* 65536')).length;
    expect(записей).toBe(возвратов);
    expect(записей).toBeGreaterThan(20);
  });

  it('отказ шага остаётся отрицательным, и чтение токена идёт из клетки', () => {
    const с = безУпаковки(программаПротоколаB2b(ИСХОДНИК, 'self.osnova'), КЛЕТКА);
    expect(с).toContain('вернуть 0 - 1');
    expect(с).toContain(`= лента[${String(КЛЕТКА)}]`);
    // Распаковка пары идёт через клетку: сдвиг индекса больше не считается делением на 65536
    // (деление на 100 в шапке — законное, поэтому проверка узкая: только «нацело 65536»).
    expect(с.split('\n').filter((л) => л.includes('нацело 65536'))).toEqual([]);
  });
});
