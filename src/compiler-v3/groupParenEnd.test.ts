/**
 * СТОРОЖ КЛЕТКИ 53: СКОБКА-ГРУППА В `пусть`/`вернуть` — конец выражения берётся ПОСЛЕ `)`.
 *
 * # Что здесь закреплено
 *
 * До правки круга 26 лента B2b расходилась с эталоном ровно на ОДНОЙ клетке — `позиция.конец`
 * оператора `пусть` (или `вернуть`), если значение начиналось со скобки-группы:
 *
 *     пусть а = (1 + 2)   →  факт 37 / эталон 38
 *     пусть а = ((1))     →  факт 34 / эталон 36   (разность = ЧИСЛО скобок)
 *     вернуть (1 + 2)     →  факт 35 / эталон 36
 *
 * Причина названа по коду, а не угадана. Канон (`parserV01.ts`, `пусть`/`вернуть`) берёт конец как
 * `позицияОт(т, this.последний)` — конец ПОСЛЕДНЕГО съеденного токена, а последний у такой формы
 * это `)`. Машина же писала конец из клетки состояния `С2`, которую ставит только `операнд`;
 * `)` операндом не является, поэтому конец отставал ровно на длину закрывающей скобки.
 *
 * # Почему формы подобраны именно так
 *
 * Каждая форма краснеет по СВОЕЙ причине, и вместе они не дают правке «пройти по совпадению»:
 * глубина 1 (разность 1), глубина 2 (разность 2 — доказывает, что дело в СЧЁТЕ скобок, а не в
 * одной константе), `вернуть` (второй писатель ленты, своя ветвь), одиночная скобка (без оператора
 * внутри — проверяет, что конец берётся у `)`, а не у операнда).
 *
 * # Границы — названы, а не спрятаны
 *
 * `(1 + 2) * 3` в набор НЕ входит как красная: там выражение кончается операндом `3`, и форма была
 * зелёной ДО правки. Она стоит здесь контролем — правка не должна сломать то, что уже работало.
 * Скобка в аргументах вызова (`ф((1 + 2))`), в индексе (`лента[(1 + 2)]`) и в условии
 * (`если (1 + 2) > 0`) идут ДРУГИМ путём (своя запись, своя позиция) и остаются зелёными.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from './index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { createDefaultInvokeHandler, VM, type StackValue } from '../runtime/vm/interpreter';
import { прочитатьЛенту, сравнитьAst, type AstФайл } from './astFormat';
import { программаПротоколаB2b } from './parser-protocol-b2b';
import { эталоннаяЛента } from './parser-protocol-probe';

const ФАЙЛ = 'group-paren.osnova';

/** Лента, которую пишет СГЕНЕРИРОВАННАЯ программа B2b на стековой VM (не `лентаПротоколаB2b`). */
async function лентаПарсера(тело: string): Promise<number[]> {
  const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
  const сгенерирован = программаПротоколаB2b(исходник, ФАЙЛ);
  const разбор = parseV3(сгенерирован, 'b2b-программа.osnova');
  expect(разбор.errors, 'сгенерированная программа обязана разбираться').toEqual([]);
  const модуль = разбор.program?.modules[0];
  expect(модуль, 'у сгенерированной программы обязан быть модуль').toBeDefined();
  const ошибкиИмён = validateNamedTypesAndRewrite(модуль!);
  expect(ошибкиИмён, 'имена сгенерированной программы обязаны сходиться').toEqual([]);

  const лента: number[] = [];
  const базовый = createDefaultInvokeHandler();
  const vm = new VM(compile(модуль!), {
    invoke: async (имя: string, аргументы: StackValue[]): Promise<StackValue | null> => {
      if (имя === 'система.лог.вывести') {
        лента.push(Number(аргументы[0]));
        return null;
      }
      if (имя === 'Списки.пустой') return [];
      if (имя === 'Списки.добавить') {
        const с = аргументы[0];
        if (Array.isArray(с)) с.push(аргументы[1] as StackValue);
        return с as StackValue;
      }
      if (имя === 'Списки.установить') {
        const с = аргументы[0];
        if (Array.isArray(с)) (с as number[])[Number(аргументы[1])] = Number(аргументы[2]);
        return с as StackValue;
      }
      if (имя === 'Списки.длина') return Array.isArray(аргументы[0]) ? аргументы[0].length : 0;
      return базовый(имя, аргументы);
    },
    maxSteps: 50_000_000,
    extraInvokes: [
      { name: 'Списки.пустой', argc: 1 },
      { name: 'Списки.добавить', argc: 3 },
      { name: 'Списки.установить', argc: 3 },
      { name: 'Списки.длина', argc: 1 },
    ],
  });
  await vm.runProcedure(vm.findProcedureIndex('главная'), []);
  return лента;
}

/** Декод без исключения: лента группы-скобки читается обеими сторонами (проверено замером). */
function декод(клетки: readonly number[]): AstФайл {
  const итог = прочитатьЛенту(клетки);
  expect(итог.ок, итог.ок ? '' : `лента не читается: ${итог.ошибка.код}`).toBe(true);
  if (!итог.ок) throw new Error('недостижимо');
  return итог.аст ?? итог.ast;
}

/**
 * Красные до правки формы — по одной причине на форму.
 * `null` в третьем поле означает «проверяем только равенство лент клетка в клетку».
 */
const КРАСНЫЕ: ReadonlyArray<readonly [string, string]> = [
  ['глубина 1: пусть а = (1 + 2)', 'пусть а = (1 + 2)\n  а = а'],
  ['глубина 2: пусть а = ((1))', 'пусть а = ((1))'],
  ['второй писатель: вернуть (1 + 2)', 'вернуть (1 + 2)'],
  ['одиночная скобка: вернуть (1)', 'вернуть (1)'],
  ['глубина 1 с длинным операндом: пусть а = (100 + 200)', 'пусть а = (100 + 200)'],
  ['глубина 2 в вернуть: вернуть ((1 + 2))', 'вернуть ((1 + 2))'],
];

/** Контроли: были зелёными ДО правки и обязаны остаться — правка не должна ничего сдвинуть. */
const ЗЕЛЁНЫЕ: ReadonlyArray<readonly [string, string]> = [
  ['без скобок: пусть а = 1 + 2', 'пусть а = 1 + 2\n  а = а'],
  ['скобка не в конце: (1 + 2) * 3', 'пусть а = (1 + 2) * 3'],
  ['скобка в условии', 'если (1 + 2) > 0\n    а = 1\n  конец если'],
  ['скобка в индексе', 'пусть а = 5\n  пусть б = а[(1 + 2)]'],
];

describe('B2b, клетка 53: скобка-группа в `пусть`/`вернуть` — конец выражения берётся после `)`', () => {
  for (const [имя, тело] of [...КРАСНЫЕ, ...ЗЕЛЁНЫЕ]) {
    it(`${имя}: лента и AST совпадают с эталоном`, async () => {
      const источник = `действие главная()\n  ${тело}\nконец главная\n`;
      const эталон = эталоннаяЛента(источник, ФАЙЛ);
      const факт = await лентаПарсера(тело);

      // 1. Клетка в клетку — так падение сразу показывает МЕСТО, а не «AST разошёлся».
      expect(факт.length, 'длина ленты').toBe(эталон.length);
      expect(факт, 'лента клетка в клетку').toEqual(эталон);

      // 2. И по смыслу: декод обеих сторон, сравнение по ПУТИ. Именно этот шаг назвал класс —
      //    `$.процедуры[0].тело[0].позиция.конец: 37 ≠ 38`.
      expect(сравнитьAst(декод(факт), декод(эталон)), 'AST по путям').toEqual([]);
    });
  }
});
