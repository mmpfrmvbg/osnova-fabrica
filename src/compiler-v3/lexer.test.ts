/**
 * КОММЕНТАРИИ В ЭТАЛОННОМ ЛЕКСЕРЕ v3 — закреплены пробой (кусок 4, срез 7).
 *
 * # Зачем этот файл, если комментарии уже распознаны
 *
 * Разведка ДО КОДА (2026-11-07, `.tmp/lexer4-recon.ts`) измерила: `tokenizeV3` распознаёт
 * комментарии ОБОИХ видов с первого коммита фронтенда (`a46d8f4d`), и правила совпадают с
 * исполняемой спецификацией (`src/spec/osnova-spec.ts#tokenize`) и лексером компилятора v2
 * (`src/compiler/lexer.ts`) — 11 из 11 различающих случаев. Значит «реализации» в `compiler-v3/**`
 * кусок 4 не требует: закрепляется МЕРА правила, чтобы будущая правка не сломала его тихо, а
 * лексер куска 4 на ЦЕЛИ (программа на Основе) стережёт `src/e2k/lexerComments.test.ts`.
 *
 * # Осознанное расхождение с V2 self-host (D21)
 *
 * Reference `src/self-host/stage12.osnova` комментариев НЕ знает вовсе: `/` там — обычный токен
 * (`если с == "/"` → `система.массив.добавить(токены, { вид: "/", текст: "/" })`). Текущий парсер
 * v3 следует канону (`docs/language-v2.md`, раздел определений лексера: строчный комментарий до конца
 * строки и блочный — до закрытия), а не stage12. Это расхождение названо в коммите и записано в
 * `docs/decisions.md`.
 *
 * # Что здесь доказывается
 *
 * Поток токенов: содержимое комментария не становится НИ ОДНИМ токеном (число/строка/знак внутри
 * комментария отсутствуют), номера строк после блочного комментария верны, а `//` и `/*` внутри
 * строкового литерала — часть строки, а не комментарий. Незакрытый блочный комментарий — НАЗВАННАЯ
 * ошибка, а поток до него цел.
 */
import { describe, expect, it } from 'vitest';
import { tokenizeV3 } from './lexer';

/** Т1: строчный комментарий с литералами внутри и `//` внутри НАСТОЯЩЕЙ строки. */
const Т1 = ['пусть а = 1 // 999 "не число" 777', 'пусть б = "абв // не строка"', ''].join('\n');

/** Т2: блочный комментарий на двух строках, с эмодзи и с кавычкой-ловушкой без пары. */
const Т2 = ['/* 111 "не строка" 🙂 222', '   333 */ пусть в = 4', '/* " */ пусть г = 5', ''].join('\n');

const поток = (источник: string): string[] => tokenizeV3(источник, 'проба.osnova').tokens.map((t) => `${t.kind}|${t.lexeme}`);

const строки = (источник: string): number[] => tokenizeV3(источник, 'проба.osnova').tokens.map((t) => t.line);

describe('комментарии эталонного лексера v3: отброшены, а не токены', () => {
  it('СТРОЧНЫЙ: комментарий до конца строки отброшен целиком; `//` внутри литерала — не комментарий', () => {
    // Различающая деталь: в строке `"абв // не строка"` стоит `//`. Реализация, которая ищет
    // комментарии РАНЬШЕ строк, съела бы остаток строки и потеряла `пусть б = …`, — здесь литерал
    // стоит на месте, а число 999 и строка `"не число"` (обе внутри комментария) — НЕ токены.
    expect(поток(Т1)).toEqual([
      'пусть|пусть',
      'имя|а',
      '=|=',
      'число|1',
      'новая_строка|\n',
      'пусть|пусть',
      'имя|б',
      '=|=',
      'строка|абв // не строка',
      'новая_строка|\n',
      'конец_файла|<конец файла>',
    ]);
  });

  it('БЛОЧНЫЙ: содержимое отброшено, кавычка внутри не открывает строку, строки после — верны', () => {
    // `/* " */` — ловушка: наивный лексер (и программа куска 4 без блочной ветви) откроет строку на
    // кавычке и съест `пусть г = 5` до конца строки. Здесь после комментария видны `пусть в = 4` и
    // `пусть г = 5`, а эмодзи 🙂 (U+1F642) и числа 111/222/333 из комментария — нет.
    expect(поток(Т2)).toEqual([
      'пусть|пусть',
      'имя|в',
      '=|=',
      'число|4',
      'новая_строка|\n',
      'пусть|пусть',
      'имя|г',
      '=|=',
      'число|5',
      'новая_строка|\n',
      'конец_файла|<конец файла>',
    ]);
    // Позиции: блочный комментарий занял строку 1, поэтому первый токен кода — со строки 2, а не 1.
    expect(строки(Т2)).toEqual([2, 2, 2, 2, 2, 3, 3, 3, 3, 3, 4]);
  });

  it('пустой и «звёздный» блочный: `/***/` и `/**/` не оставляют ни одного токена', () => {
    expect(поток('a /***/ b /**/ c')).toEqual(['имя|a', 'имя|b', 'имя|c', 'конец_файла|<конец файла>']);
  });

  it('вложенности нет: `/* /* */` закрывается ПЕРВЫМ `*/` — с вложенностью `b` осталось бы в комментарии', () => {
    // Так же, как в спецификации: цикла по глубине нет. Увидев второй `/*`, лексер не копит уровень,
    // поэтому первый `*/` закрывает комментарий и `b` снова код. Это и различает два правила.
    expect(поток('a /* /* */ b')).toEqual(['имя|a', 'имя|b', 'конец_файла|<конец файла>']);
    // А `*/` без открытия — обычные знаки: комментарием не считается.
    expect(поток('a */ b')).toEqual(['имя|a', '*|*', '/|/', 'имя|b', 'конец_файла|<конец файла>']);
  });

  it('деление не спрятано: `10/3` — токены, `10 // 3` — число и комментарий', () => {
    expect(поток('10/3')).toEqual(['число|10', '/|/', 'число|3', 'конец_файла|<конец файла>']);
    expect(поток('10 // 3')).toEqual(['число|10', 'конец_файла|<конец файла>']);
  });

  it('`//` внутри блочного и `/*` внутри строчного — содержимое комментария, а не второй комментарий', () => {
    expect(поток('/* // */ пусть а = 1')).toEqual(['пусть|пусть', 'имя|а', '=|=', 'число|1', 'конец_файла|<конец файла>']);
    // Строчный комментарий поглощает `/*`: блок не открывается, и следующая строка цела.
    expect(поток('пусть а = 1 // /* не блок\nпусть б = 2\n')).toEqual([
      'пусть|пусть',
      'имя|а',
      '=|=',
      'число|1',
      'новая_строка|\n',
      'пусть|пусть',
      'имя|б',
      '=|=',
      'число|2',
      'новая_строка|\n',
      'конец_файла|<конец файла>',
    ]);
  });

  it('незакрытый блочный — НАЗВАННАЯ ошибка; поток до него цел, `конец_файла` на месте', () => {
    const итог = tokenizeV3('пусть а = 1 /* не закрыт\nпусть б = 2\n', 'x.osnova');
    expect(итог.errors).toEqual(['x.osnova:1: незакрытый комментарий /*']);
    expect(итог.tokens.map((t) => `${t.kind}|${t.lexeme}|${String(t.line)}`)).toEqual([
      'пусть|пусть|1',
      'имя|а|1',
      '=|=|1',
      'число|1|1',
      // Строка 2 комментария уже внутри него: `пусть б` токеном не стало, но номер строки учтён.
      'конец_файла|<конец файла>|3',
    ]);
  });

  it('файл ТОЛЬКО из комментариев: токенов нет вовсе — пустой модуль по канону (§«файл = модуль»)', () => {
    // Канон: пустой источник, одни переводы строк или одни комментарии — законный пустой модуль.
    // Переводы строк ВНЕ комментариев остаются токенами (они разделители инструкций), а
    // переводы строк ВНУТРИ блочного — только увеличивают номер строки.
    expect(поток('// a\n/* b\nc */\n')).toEqual(['новая_строка|\n', 'новая_строка|\n', 'конец_файла|<конец файла>']);
    expect(строки('// a\n/* b\nc */\n')).toEqual([1, 3, 4]);
  });
});
