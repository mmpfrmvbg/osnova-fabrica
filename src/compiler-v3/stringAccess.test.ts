/**
 * КАК v3 ДОСТАЁТ СТРОКОВЫЕ ОПЕРАЦИИ — и почему имя `Строка.*` до них НЕ доводит.
 *
 * Строки написаны ДО перехода на v3-синтаксис, поэтому канон у них трёхсегментный
 * (`система.строка.*`), а v3 несёт ровно одну точку (`Модуль.имя`). Решение владельца 2026-11-04
 * (D18) было: положить сверху тонкий слой имён `Строка.длина` / `Строка.символ` / `Строка.печать`
 * («одна строка реестра на алиас»).
 *
 * ЗАМЕР ЭТОГО ОРАКУЛА ОПРОВЕРГ ТАКОЙ ПУТЬ, и опроверг на уровне ЛЕКСЕРА, а не семантики: слово
 * `Строка` — КЛЮЧЕВОЕ (`src/compiler-v3/lexer.ts`: у него СВОЙ вид токена, как у `Число` и `Список`),
 * а ветвь квалифицированного вызова требует, чтобы левый сегмент был `имя`. Поэтому `Строка.длина(…)`
 * не разбирается ВООБЩЕ — «одной строкой реестра» этот слой не делается. То же у `Число.*` и
 * `Список.*`; `Матем.длина(1)` (обычное имя модуля) при этом разбирается — то есть ветвь есть, и
 * закрыта она именно видом токена.
 *
 * Вторая половина замера: все ТРИ операции v3 уже достаёт ВСТРОЕННЫМИ словами — `длина` (нейтральное
 * слово, разрешается по типу операнда), `с[и]` (семантика сводит к `система.строка.символ`) и
 * `вывести`. Это проверяется на ЦЕЛИ побайтово, а не только разбором.
 *
 * Стена при этом НАЗВАНА, а не замазана: проверка «`Строка.длина` не разбирается» стоит здесь сторожем,
 * чтобы никто не добавил строку в реестр синонимов и не решил, что имя заработало.
 */
import { describe, expect, it } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { parseV3 } from "./index";
import { compileSource } from "../compiler/compiler";
import { loweredProgram } from "../e2k/lowered";
import { buildElfFromCode, MINIMAL_BASE } from "../e2k/elfMinimal";
import { buildShim, runInQemu } from "../scripts/e2kQemuExec";
import { shimAvailable } from "../scripts/e2kProgramRun";

const ФАЙЛ = "доступ.osnova";

/** Фронтенд v3, подставленный в общий конвейер (см. `CompileOptions.parse`). */
const опцииV3 = (src: string) => {
  const р = parseV3(src, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

const обёртка = (тело: string): string => `действие главная()\n  ${тело}\nконец главная\n`;

function сообщенияРазбора(тело: string): string {
  const src = обёртка(тело);
  const собран = compileSource(src, опцииV3(src));
  return собран.parserErrors.map((e) => e.message).join(" | ");
}

describe("v3 достаёт строковые операции ВСТРОЕННЫМИ словами", () => {
  it("`длина с`, `с[и]` и `вывести с` разбираются", () => {
    expect(сообщенияРазбора('пусть с = "абв"\n  вернуть длина с'), "длина").toBe("");
    expect(сообщенияРазбора('пусть с = "абв"\n  вернуть с[1]'), "индекс").toBe("");
    expect(сообщенияРазбора('пусть с = "абв"\n  вывести с\n  вернуть 0'), "вывод").toBe("");
  });

  it("`длина` — НЕЙТРАЛЬНОЕ слово: строку и массив решает ТИП операнда, а не таблица имён", () => {
    // Если бы `длина` сводилась к строковой операции по имени, `длина [1,2,3]` стала бы строковой
    // и упала бы на типе. Разные байткоды здесь — это и есть «выбор по операнду».
    const байткод = (тело: string): string => {
      const src = обёртка(тело);
      const собран = compileSource(src, опцииV3(src));
      expect(собран.parserErrors, "разбор").toEqual([]);
      expect(собран.semanticErrors, "семантика").toEqual([]);
      return JSON.stringify(собран.module?.code ?? null);
    };
    expect(байткод('вернуть длина "привет"')).not.toBe(байткод("вернуть длина [1, 2, 3]"));
  });
});

describe("СТЕНА: имя `Строка.*` из v3 НЕ РАЗБИРАЕТСЯ — и это зафиксировано", () => {
  it("`Строка.длина(…)` отвергается РАЗБОРОМ (левый сегмент — ключевое слово, не имя)", () => {
    // Точный текст отказа: до ветви `Модуль.имя` дело не доходит — выражение вообще не начинается.
    expect(сообщенияРазбора('вернуть Строка.длина("привет")')).toContain("Строка");
    expect(сообщенияРазбора('Строка.печать("абв")\n  вернуть 0')).toContain("Строка");
  });

  it("ветвь `Модуль.имя(…)` при этом ЖИВА: с обычным именем модуля она разбирается", () => {
    // Отрицательная сторона границы: дело не в точке и не в разборе вызова, а именно в ВИДЕ ТОКЕНА.
    expect(сообщенияРазбора("вернуть Матем.длина(1)"), "обычное имя модуля обязано разбираться").toBe("");
  });

  it("то же у `Число.*` и `Список.*` — это свойство КЛЮЧЕВЫХ слов, а не строк", () => {
    expect(сообщенияРазбора("вернуть Число.размер(1)")).toContain("Число");
    expect(сообщенияРазбора("вернуть Список.длина([1])")).toContain("Список");
  });
});

/** Прогон v3-программы на модели: возвращает БАЙТЫ вывода — единственный широкий канал. */
function выводНаЦели(тело: string): string {
  const src = обёртка(тело);
  const итог = loweredProgram(src, опцииV3(src));
  expect(
    итог.ок,
    итог.ок ? "" : "отказы понижения: " + итог.отказ.отказы.map((запись) => запись.причина).join(" | "),
  ).toBe(true);
  if (!итог.ок) throw new Error(`понижение отказало: ${итог.отказ.причина}`);
  const elf = buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
    writable: true,
    extraMemory: итог.значение.arena.extraMemory,
  }).bytes;
  const файл = path.join(process.cwd(), ".tmp", "v3-доступ-к-строкам.elf");
  fs.writeFileSync(файл, elf);
  buildShim();
  return runInQemu(файл, { shim: true, timeoutMs: 30_000 })?.output ?? "";
}

describe("достижимость строковых операций на ЦЕЛИ (модель)", () => {
  // Канал наблюдения — БАЙТЫ вывода, а не код возврата: `includes`/`trim` не различили бы «10» и «100»
  // (`docs/hardware-debt.md` §3.43).
  //
  // ПРОГРАММЫ ЗДЕСЬ НАМЕРЕННО КОРОТКИЕ — по ДВЕ инструкции, и это не стиль, а измерение. Между
  // строковыми операциями НЕ должно стоять печати числа: замер (`.tmp/v3-индекс.ts`, случай 71 реестра
  // долгов) показал, что после печати ЧИСЛА следующая строковая операция на цели врёт (индекс даёт −1
  // или 9647, а в цепочке из трёх операций вывод строки пропадает ВОВСЕ) при верных обеих VM и НУЛЕ
  // отказов. Проба длиннее двух операций была бы красной по ЧУЖОЙ причине — а зелёная там была бы
  // случайной. Пока случай 71 открыт, строковый оракул обязан называть, что стоит между операциями.
  it.skipIf(!shimAvailable())("печать строки, затем код символа: `вывести с`, затем `вывести с[1]`", () => {
    // 1073 — код «б» (U+0431) по канону §13.6: `с[и]` — ЧИСЛО в кодовых точках, а не строка и не байт.
    expect(выводНаЦели(['пусть с = "абв"', "вывести с", "вывести с[1]"].join("\n  "))).toBe("абв\n1073\n");
  });

  it.skipIf(!shimAvailable())("длина строки: `вывести длина с` — РАЗНЫМИ пробами, а не цепочкой", () => {
    // Отдельная проба, а не третья инструкция предыдущей: см. правило о цепочках выше.
    expect(выводНаЦели(['пусть с = "абв"', "вывести длина с"].join("\n  "))).toBe("3\n");
  });
});
