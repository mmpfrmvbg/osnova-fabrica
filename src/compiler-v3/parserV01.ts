/**
 * ПАРСЕР v0.1 ЯЗЫКА ОСНОВА (V3) — ПРОДАКШЕН-МОДУЛЬ, ПОДМНОЖЕСТВО И НАЗВАННЫЙ ОТКАЗ.
 *
 * # Место в контуре (D50)
 *
 * Вход — `Результат<Список<Токен>, Ошибка>` от полного лексера v3 (`tokenizeV3`). Выход —
 * `Результат<AstФайл, ОшибкаПарсера>` по формату 1.0 (`src/compiler-v3/astFormat.ts`,
 * `docs/ast-format.md`). Это не parse tree и не AST v2: это AST, который пойдёт в чекер фазы 1
 * (D42) и в AST-embedding Phase 0.
 *
 * # Подмножество v0.1 (и что им НЕ является)
 *
 * Разбираются ровно:
 *   • `процедура имя(параметр: Тип, …) [→ Тип] … конец`;
 *   • операторы `вернуть [выражение]`, `если условие … [иначе …] конец [если]`, вызов-оператор;
 *   • выражения — литерал (`число`, `строка`, `да`, `нет`, `пусто`), имя, вызов, скобки;
 *   • типы — имена (`Число`, `Строка`, `Логическое`, `Пусто`, `Ошибка`, …), `Список Т`,
 *     `Результат<Т, Е>`.
 *
 * Всё прочее — НАЗВАННЫЙ отказ с кодом `OSN-PAR-*`, а не пустой AST и не тихое «пропустим»:
 * `пусть`, `пока`, `для`, `тип`, `действие`, `Успех`/`Неудача`, операторы (`+`, `=`, `и`, …),
 * вложенные конструкции вне списка. Код ошибки — её личность; текст строится из кода и токена
 * (`сообщениеОшибки`), поэтому тот же отказ воспроизводит и программа на цели e2k, печатающая
 * только числа.
 *
 * # Почему это «продакшен», а не тестовая проба
 *
 * Публичные точки — {@link parseV01} и {@link parseV01Tokens}; ошибки не бросаются наружу, а
 * возвращаются в `Результат`. Позиции — В КОДОВЫХ ТОЧКАХ (не в байтах и не в UTF-16): их даёт
 * лексер полями `offset`/`length`/`column`, и те же числа уходят в ленту AST.
 *
 * # Границы (названы, а не сглажены)
 *
 *  * Контракты (`требует`/`обеспечивает`/`эффекты`) — ЗАРЕЗЕРВИРОВАННЫЕ поля и в v0.1 ПУСТЫ:
 *    синтаксиса контрактов в подмножестве нет, и делать вид, что он разобран, нельзя.
 *  * Операторы и `пусть` — названный отказ, а не «парсер не заметил».
 *  * `Список Т` — канон v3 (префиксная форма); `Список<Т>` в v0.1 отвергается как тип вне
 *    подмножества, чтобы не заводить второй синтаксис.
 */
import type { V3LexResult, V3Token, V3TokenKind } from './lexer';
import { DEFAULT_V3_FILENAME, tokenizeV3 } from './lexer';
import { moduleNameFromFilename } from './parser';
import {
  ВЕРСИЯ_AST,
  КОДЫ_ОШИБОК,
  ФОРМАТ_AST,
  пустойКонтракт,
  сообщениеОшибки,
  type AstФайл,
  type Выражение,
  type КодОшибки,
  type Оператор,
  type ОшибкаПарсера,
  type Позиция,
  type Параметр,
  type Процедура,
  type Тип,
} from './astFormat';

/** Результат разбора v0.1: либо AST, либо названный отказ. */
export type ИтогПарсераV01 =
  | { readonly ок: true; readonly ast: AstФайл }
  | { readonly ок: false; readonly ошибка: ОшибкаПарсера };

/** Внутренний сигнал отказа: наружу не выходит (публичная точка ловит его). */
class ОтказПарсера extends Error {
  constructor(readonly ошибка: ОшибкаПарсера) {
    super(ошибка.сообщение);
    this.name = 'ОтказПарсера';
  }
}

function позицияТокена(т: V3Token): Позиция {
  return { начало: т.offset, конец: т.offset + т.length, строка: т.line, колонка: т.column };
}

function позицияОт(начало: V3Token, конец: V3Token): Позиция {
  return {
    начало: начало.offset,
    конец: конец.offset + конец.length,
    строка: начало.line,
    колонка: начало.column,
  };
}

const ОПЕРАТОРЫ: ReadonlySet<V3TokenKind> = new Set(['+', '-', '*', '/', '%', '==', '!=', '<', '<=', '>', '>=', '=', 'и', 'или']);

class ПарсерV01 {
  private и = 0;
  private последний: V3Token;

  constructor(
    private readonly токены: readonly V3Token[],
    private readonly модуль: string,
  ) {
    this.последний = токены[0]!;
  }

  файл(): AstФайл {
    const процедуры: Процедура[] = [];
    while (true) {
      const т = this.пик();
      if (т.kind === 'конец_файла') break;
      if (т.kind === 'процедура') {
        процедуры.push(this.процедура());
        continue;
      }
      throw this.ошибка(процедуры.length === 0 ? 'OSN-PAR-015' : 'OSN-PAR-010', т);
    }
    const конецФайла = this.токены[this.токены.length - 1]!;
    return {
      формат: ФОРМАТ_AST,
      версия: `${String(ВЕРСИЯ_AST.мажор)}.${String(ВЕРСИЯ_AST.минор)}`,
      модуль: { имя: this.модуль, позиция: { начало: 0, конец: конецФайла.offset, строка: 1, колонка: 1 } },
      процедуры,
    };
  }

  // ── движение по потоку ──────────────────────────────────────────────────────────────────────

  private пик(): V3Token {
    while (this.токены[this.и]?.kind === 'новая_строка') this.и++;
    return this.токены[Math.min(this.и, this.токены.length - 1)]!;
  }

  private эт(kind: V3TokenKind): boolean {
    return this.пик().kind === kind;
  }

  private взять(): V3Token {
    const т = this.пик();
    if (т.kind !== 'конец_файла') this.и++;
    this.последний = т;
    return т;
  }

  private ждать(kind: V3TokenKind, код: КодОшибки): V3Token {
    const т = this.пик();
    if (т.kind === 'конец_файла' && kind !== 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind !== kind) throw this.ошибка(код, т);
    return this.взять();
  }

  private ждатьИмя(): V3Token {
    const т = this.пик();
    if (т.kind === 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind !== 'имя') throw this.ошибка('OSN-PAR-002', т);
    return this.взять();
  }

  private ошибка(код: КодОшибки, т: V3Token): ОтказПарсера {
    const лексема = т.kind === 'конец_файла' ? null : т.lexeme;
    return new ОтказПарсера({
      код,
      сообщение: сообщениеОшибки(код, лексема),
      позиция: позицияТокена(т),
      видТокена: т.kind,
      лексема,
    });
  }

  // ── процедуры и типы ────────────────────────────────────────────────────────────────────────

  private процедура(): Процедура {
    const начало = this.ждать('процедура', 'OSN-PAR-015');
    const имя = this.ждатьИмя();
    this.ждать('(', 'OSN-PAR-004');
    const параметры: Параметр[] = [];
    if (!this.эт(')')) {
      while (true) {
        const имяПараметра = this.ждатьИмя();
        this.ждать(':', 'OSN-PAR-006');
        const тип = this.тип();
        параметры.push({ имя: имяПараметра.lexeme, тип, позиция: позицияОт(имяПараметра, this.последний) });
        if (!this.эт(',')) break;
        this.взять();
      }
    }
    this.ждать(')', 'OSN-PAR-005');
    let возвращает: Тип | null = null;
    if (this.эт('→')) {
      this.взять();
      возвращает = this.тип();
    }
    const тело = this.блок(new Set<V3TokenKind>(['конец']));
    const конец = this.ждать('конец', 'OSN-PAR-009');
    return {
      id: `p0`, // заменится на стабильный id в `файл()`
      имя: имя.lexeme,
      параметры,
      возвращает,
      тело,
      контракт: пустойКонтракт(),
      позиция: позицияОт(начало, конец),
    };
  }

  private тип(): Тип {
    const т = this.пик();
    switch (т.kind) {
      case 'Число':
      case 'Строка':
      case 'Логическое':
      case 'Пусто':
        this.взять();
        return { вид: 'имя', имя: т.lexeme };
      case 'имя':
        this.взять();
        if (т.lexeme === 'Результат' && this.эт('<')) {
          this.взять();
          const успех = this.тип();
          this.ждать(',', 'OSN-PAR-012');
          const ошибка = this.тип();
          this.ждать('>', 'OSN-PAR-012');
          return { вид: 'результат', успех, ошибка };
        }
        return { вид: 'имя', имя: т.lexeme };
      case 'Список': {
        this.взять();
        return { вид: 'список', элемент: this.тип() };
      }
      case 'конец_файла':
        throw this.ошибка('OSN-PAR-001', т);
      default:
        throw this.ошибка('OSN-PAR-008', т);
    }
  }

  // ── операторы ───────────────────────────────────────────────────────────────────────────────

  private блок(стоп: ReadonlySet<V3TokenKind>): Оператор[] {
    const операторы: Оператор[] = [];
    while (true) {
      const т = this.пик();
      if (т.kind === 'конец_файла') {
        if (стоп.has('конец_файла')) break;
        throw this.ошибка('OSN-PAR-001', т);
      }
      if (стоп.has(т.kind)) break;
      операторы.push(this.оператор());
    }
    return операторы;
  }

  private оператор(): Оператор {
    const т = this.пик();
    if (т.kind === 'вернуть') {
      this.взять();
      const следующий = this.пик();
      const безЗначения =
        следующий.kind === 'конец' || следующий.kind === 'иначе' || следующий.kind === 'конец_файла';
      const значение = безЗначения ? undefined : this.выражение();
      return значение === undefined
        ? { вид: 'вернуть', позиция: позицияОт(т, this.последний) }
        : { вид: 'вернуть', значение, позиция: позицияОт(т, this.последний) };
    }
    if (т.kind === 'если') {
      this.взять();
      const условие = this.выражение();
      const тогда = this.блок(new Set<V3TokenKind>(['иначе', 'конец']));
      let иначе: Оператор[] | undefined;
      if (this.эт('иначе')) {
        this.взять();
        иначе = this.блок(new Set<V3TokenKind>(['конец']));
      }
      this.ждать('конец', 'OSN-PAR-009');
      // Форма v3: `конец если` и просто `конец` — оба законны, как у лексера/парсера v3.
      if (this.эт('если')) this.взять();
      const позиция = позицияОт(т, this.последний);
      return иначе === undefined
        ? { вид: 'если', условие, тогда, позиция }
        : { вид: 'если', условие, тогда, иначе, позиция };
    }
    if (т.kind === 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind === 'конец' || т.kind === 'иначе') throw this.ошибка('OSN-PAR-003', т);

    // Вызов-оператор: начинается с имени; всё остальное в роли оператора — названный отказ.
    if (т.kind === 'имя') {
      const выражение = this.выражение();
      if (выражение.вид !== 'вызов') throw this.ошибка('OSN-PAR-013', т);
      return { вид: 'вызов', вызов: выражение, позиция: выражение.позиция };
    }
    throw this.ошибка('OSN-PAR-003', т);
  }

  // ── выражения ───────────────────────────────────────────────────────────────────────────────

  private выражение(): Выражение {
    const т = this.пик();
    let выражение: Выражение;
    switch (т.kind) {
      case 'число':
        this.взять();
        выражение = { вид: 'литерал', литерал: { вид: 'число', текст: т.lexeme }, позиция: позицияТокена(т) };
        break;
      case 'строка':
        this.взять();
        выражение = {
          вид: 'литерал',
          литерал: { вид: 'строка', значение: typeof т.value === 'string' ? т.value : т.lexeme },
          позиция: позицияТокена(т),
        };
        break;
      case 'да':
      case 'нет':
        this.взять();
        выражение = {
          вид: 'литерал',
          литерал: { вид: 'логическое', значение: т.kind === 'да' },
          позиция: позицияТокена(т),
        };
        break;
      case 'пусто':
        this.взять();
        выражение = { вид: 'литерал', литерал: { вид: 'пусто' }, позиция: позицияТокена(т) };
        break;
      case 'имя': {
        this.взять();
        if (this.эт('(')) {
          this.взять();
          const аргументы: Выражение[] = [];
          if (!this.эт(')')) {
            while (true) {
              аргументы.push(this.выражение());
              if (!this.эт(',')) break;
              this.взять();
            }
          }
          const закрывающая = this.ждать(')', 'OSN-PAR-005');
          выражение = {
            вид: 'вызов',
            имя: т.lexeme,
            аргументы,
            позиция: позицияОт(т, закрывающая),
          };
        } else {
          выражение = { вид: 'имя', имя: т.lexeme, позиция: позицияТокена(т) };
        }
        break;
      }
      case '(': {
        this.взять();
        выражение = this.выражение();
        this.ждать(')', 'OSN-PAR-005');
        break;
      }
      case 'конец_файла':
        throw this.ошибка('OSN-PAR-001', т);
      default:
        throw this.ошибка('OSN-PAR-003', т);
    }

    // Операторы — ВНЕ подмножества v0.1, но отказ обязан быть названным, а не «пропуском».
    const следующий = this.пик();
    if (ОПЕРАТОРЫ.has(следующий.kind)) throw this.ошибка('OSN-PAR-003', следующий);
    return выражение;
  }
}

/**
 * Разобрать поток токенов полного лексера. Публичная точка для чекера: ошибки не бросаются.
 *
 * @param tokens поток `tokenizeV3(...).tokens`; последний обязан быть `конец_файла`
 * @param moduleName имя модуля (файл = модуль, как в v3)
 */
export function parseV01Tokens(tokens: readonly V3Token[], moduleName: string): ИтогПарсераV01 {
  if (tokens.length === 0 || tokens[tokens.length - 1]!.kind !== 'конец_файла') {
    const последний = tokens[tokens.length - 1];
    return {
      ок: false,
      ошибка: {
        код: 'OSN-PAR-001',
        сообщение: сообщениеОшибки('OSN-PAR-001', null),
        позиция: последний === undefined ? { начало: 0, конец: 0, строка: 1, колонка: 1 } : позицияТокена(последний),
        видТокена: последний?.kind ?? null,
        лексема: null,
      },
    };
  }
  const парсер = new ПарсерV01(tokens, moduleName);
  try {
    const ast = парсер.файл();
    // Стабильные id — в порядке объявления, а не «уникальные во вселенной» (Phase 0).
    return { ок: true, ast: { ...ast, процедуры: ast.процедуры.map((п, и) => ({ ...п, id: `p${String(и)}` })) } };
  } catch (е) {
    if (е instanceof ОтказПарсера) return { ок: false, ошибка: е.ошибка };
    throw е;
  }
}

/** Разобрать исходник v3: лексер + парсер v0.1. Лексерский отказ — тоже названный. */
export function parseV01(source: string, filename: string = DEFAULT_V3_FILENAME): ИтогПарсераV01 {
  const лек: V3LexResult = tokenizeV3(source, filename);
  if (лек.errors.length > 0) {
    const первая = лек.errors[0]!;
    return {
      ок: false,
      ошибка: {
        код: КОДЫ_ОШИБОК.лексер,
        сообщение: `${сообщениеОшибки(КОДЫ_ОШИБОК.лексер, null)} (${первая})`,
        позиция: { начало: 0, конец: 0, строка: 1, колонка: 1 },
        видТокена: null,
        лексема: null,
      },
    };
  }
  return parseV01Tokens(лек.tokens, moduleNameFromFilename(filename));
}
