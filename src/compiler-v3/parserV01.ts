/**
 * ПАРСЕР v0.1 ЯЗЫКА ОСНОВА (V3) — AST 2.1, ПОДМНОЖЕСТВО И НАЗВАННЫЙ ОТКАЗ.
 *
 * # Место в контуре (D50)
 *
 * Вход — `Результат<Список<Токен>, Ошибка>` от полного лексера v3 (`tokenizeV3`). Выход —
 * `Результат<AstФайл, ОшибкаПарсера>` по формату **2.1** (`src/compiler-v3/astFormat.ts`,
 * `docs/ast-format.md` §13). Это не parse tree и не AST v2: это AST, который пойдёт в чекер
 * фазы 1 (D42) и в AST-embedding Phase 0.
 *
 * # Подмножество v0.1 (2.1)
 *
 * Разбираются ровно:
 *   • `процедура имя(параметр: Тип, …) [-> Тип] … конец имя`;
 *   • `действие имя(параметр: Тип, …) … конец имя` — без возврата;
 *   • операторы `вернуть [выражение]`, `если … [иначе если …] [иначе …] конец если`,
 *     вызов-оператор, `пусть имя [: Тип] = выражение`, `пока условие … конец пока`,
 *     простое `имя = выражение` (2.1);
 *   • выражения — литералы, имена, вызовы, скобки, списки `[1, 2]`, индексация `а[i]`,
 *     бинарные `+ - * / % == != < <= > >= и или нацело`, унарные `-` и `не`,
 *     D43-вызовы `Печать.число(…)`, `Списки.длина(…)`, `Списки.добавить(с, э, ар)`;
 *   • типы — имена (`Число`, `Строка`, `Логическое`, `Пусто`, `Ошибка`, …), `Список Т`,
 *     `Результат<Т, Е>`.
 *
 * Всё прочее — НАЗВАННЫЙ отказ с кодом `OSN-PAR-*`, а не пустой AST и не тихое «пропустим»:
 * `для`, `тип`, `разбор`, `защита`, `поля`, `структуры`. Код ошибки — её личность; текст
 * строится из кода и токена (`сообщениеОшибки`), поэтому тот же отказ воспроизводит и
 * программа на цели e2k, печатающая только числа.
 *
 * # Границы, названные явно
 *
 *  * `конец` — explicit: `конец имя`, `конец если`, `конец пока`; bare `конец` — `OSN-PAR-025`.
 *  * `->` — ASCII; `→` — `OSN-PAR-026`.
 *  * `защита` — `OSN-PAR-021`, финальный отказ (D59).
 *  * `поднять` — сахар `вернуть Ошибка(<выражение>)`; вне `Результат` — `OSN-PAR-020`.
 *  * `Успех`/`Ошибка` — ОБЫЧНЫЕ вызовы по факту этого парсера, а не особые события AST.
 *    Это названное расхождение D59 с будущими конструкторами пары; закрывает A4a после L2.
 *  * `.` — только D43-библиотеки; модуль пользователя/поле — `OSN-PAR-031`, AST 3.0/v0.2.
 *  * `вывести`/`длина`/`добавить` — библиотека D43, не языковые инструкции: `OSN-PAR-030`.
 *  * `Списки.добавить` без явной арены — `OSN-PAR-032` (D43).
 *  * `Неудача` в 2.1 нет. Struct literal, `.` как поле, модули/структуры — AST 3.0 / v0.2.
 */
