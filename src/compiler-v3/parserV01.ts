/** Внутренний сигнал отказа: наружу не выходит (публичная точка ловит его). */
class ОтказПарсера extends Error {
  constructor(readonly ошибка: ОшибкаПарсера) {
    super(ошибка.сообщение);
    this.name = 'ОтказПарсера';
  }
}

function позицияТокена(т: V3Token): Позиция {
  return { начало: т.offset, конец: т.offset + т.length, строка: т.line, колонка: т.column };
}

function позицияОт(начало: V3Token, конец: V3Token): Позиция {
  return {
    начало: начало.offset,
    конец: конец.offset + конец.length,
    строка: начало.line,
    колонка: начало.column,
  };
}

/** Позиция с началом уже разобранного узла и известным концом. */
function позицияДо(начало: Позиция, конец: number): Позиция {
  return { начало: начало.начало, конец, строка: начало.строка, колонка: начало.колонка };
}

type УзелЕсли = Extract<Оператор, { readonly вид: 'если' }>;

class ПарсерV01 {
  private индекс = 0;
  private последний: V3Token;
  /** Тип возврата текущей процедуры: нужен только для `поднять` (A1). */
  private текущийВозврат: Тип | null = null;

  constructor(
    private readonly токены: readonly V3Token[],
    private readonly модуль: string,
  ) {
    this.последний = токены[0]!;
  }

  файл(): AstФайл {
    const процедуры: Процедура[] = [];
    while (true) {
      const т = this.пик();
      if (т.kind === 'конец_файла') break;
      if (т.kind === 'защита') throw this.ошибка('OSN-PAR-021', т);
      if (т.kind === 'процедура' || т.kind === 'действие') {
        процедуры.push(this.процедура(т.kind === 'действие'));
        continue;
      }
      throw this.ошибка(процедуры.length === 0 ? 'OSN-PAR-018' : 'OSN-PAR-010', т);
    }
    const конецФайла = this.токены[this.токены.length - 1]!;
    return {
      формат: ФОРМАТ_AST,
      версия: ВЕРСИЯ_AST_СТРОКА,
      модуль: { имя: this.модуль, позиция: { начало: 0, конец: конецФайла.offset, строка: 1, колонка: 1 } },
      процедуры,
    };
  }

  // ── движение по потоку ──────────────────────────────────────────────────────────────────────

  private пик(): V3Token {
    while (this.токены[this.индекс]?.kind === 'новая_строка') this.индекс++;
    return this.токены[Math.min(this.индекс, this.токены.length - 1)]!;
  }

  private эт(kind: V3TokenKind): boolean {
    return this.пик().kind === kind;
  }

  /** Токен сразу после текущего (с пропуском переводов строк), без сдвига курсора. */
  private послеПика(): V3Token {
    let и = this.индекс + 1;
    while (this.токены[и]?.kind === 'новая_строка') и++;
    return this.токены[Math.min(и, this.токены.length - 1)]!;
  }

  /** Первый `=` до конца текущей строки; нужен, чтобы назвать LHS-не-имя (028). */
  private равноДоКонцаСтроки(): V3Token | undefined {
    let и = this.индекс;
    while (и < this.токены.length) {
      const т = this.токены[и]!;
      if (т.kind === 'новая_строка' || т.kind === 'конец_файла') return undefined;
      if (т.kind === '=') return т;
      и++;
    }
    return undefined;
  }

  private взять(): V3Token {
    const т = this.пик();
    if (т.kind !== 'конец_файла') this.индекс++;
    this.последний = т;
    return т;
  }

  private ждать(kind: V3TokenKind, код: КодОшибки): V3Token {
    const т = this.пик();
    if (т.kind === 'конец_файла' && kind !== 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind !== kind) throw this.ошибка(код, т);
    return this.взять();
  }

  private ждатьИмя(): V3Token {
    const т = this.пик();
    if (т.kind === 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind !== 'имя') throw this.ошибка('OSN-PAR-002', т);
    return this.взять();
  }

  private ошибка(код: КодОшибки, т: V3Token): ОтказПарсера {
    const лексема = т.kind === 'конец_файла' ? null : т.lexeme;
    return new ОтказПарсера({
      код,
      сообщение: сообщениеОшибки(код, лексема),
      позиция: позицияТокена(т),
      видТокена: т.kind,
      лексема,
    });
  }

  /**
   * ASCII `->`. Лексер не знает составного знака, поэтому это ДВА соседних токена `-` и `>`.
   * `→` — отдельный токен и всегда названный отказ 026, даже если за ним есть тип.
   */
  private стрелка(): boolean {
    const т = this.пик();
    if (т.kind === '→') throw this.ошибка('OSN-PAR-026', т);
    if (т.kind !== '-') return false;
    const следующий = this.токены[this.индекс + 1];
    if (следующий === undefined || следующий.kind !== '>') return false;
    if (т.offset + т.length !== следующий.offset) return false;
    this.индекс += 2;
    this.последний = следующий;
    return true;
  }

  /** Закрывающее слово блока: explicit, иначе `OSN-PAR-025`. */
  private ждатьКонец(блок: 'процедура' | 'если' | 'пока', имя?: string): V3Token {
    const конец = this.ждать('конец', 'OSN-PAR-025');
    if (блок === 'процедура') {
      const т = this.пик();
      if (т.kind !== 'имя' || (имя !== undefined && т.lexeme !== имя)) {
        throw this.ошибка('OSN-PAR-025', конец);
      }
      return this.взять();
    }
    const слово: V3TokenKind = блок === 'если' ? 'если' : 'пока';
    if (!this.эт(слово)) throw this.ошибка('OSN-PAR-025', конец);
    return this.взять();
  }

  // ── процедуры и типы ────────────────────────────────────────────────────────────────────────

  private процедура(действие: boolean): Процедура {
    const начало = this.ждать(действие ? 'действие' : 'процедура', 'OSN-PAR-015');
    const имя = this.ждатьИмя();
    this.ждать('(', 'OSN-PAR-004');
    const параметры: Параметр[] = [];
    if (!this.эт(')')) {
      while (true) {
        const имяПараметра = this.ждатьИмя();
        this.ждать(':', 'OSN-PAR-006');
        const тип = this.тип();
        параметры.push({ имя: имяПараметра.lexeme, тип, позиция: позицияОт(имяПараметра, this.последний) });
        if (!this.эт(',')) break;
        this.взять();
      }
    }
    this.ждать(')', 'OSN-PAR-005');
    let возвращает: Тип | null = null;
    if (this.стрелка()) {
      if (действие) throw this.ошибка('OSN-PAR-016', this.последний);
      возвращает = this.тип();
    }
    const сохранённый = this.текущийВозврат;
    this.текущийВозврат = возвращает;
    const тело = this.блок(new Set<V3TokenKind>(['конец']));
    const конец = this.ждатьКонец('процедура', имя.lexeme);
    this.текущийВозврат = сохранённый;
    return {
      id: `p0`, // заменится на стабильный id в `файл()`
      имя: имя.lexeme,
      действие,
      параметры,
      возвращает,
      тело,
      контракт: пустойКонтракт(),
      позиция: позицияОт(начало, конец),
    };
  }

  private тип(): Тип {
    const т = this.пик();
    switch (т.kind) {
      case 'Число':
      case 'Строка':
      case 'Логическое':
      case 'Пусто':
        this.взять();
        return { вид: 'имя', имя: т.lexeme };
      case 'имя':
        this.взять();
        if (т.lexeme === 'Результат' && this.эт('<')) {
          this.взять();
          const успех = this.тип();
          this.ждать(',', 'OSN-PAR-012');
          const ошибка = this.тип();
          this.ждать('>', 'OSN-PAR-012');
          return { вид: 'результат', успех, ошибка };
        }
        return { вид: 'имя', имя: т.lexeme };
      case 'Список': {
        this.взять();
        return { вид: 'список', элемент: this.тип() };
      }
      case 'конец_файла':
        throw this.ошибка('OSN-PAR-001', т);
      default:
        throw this.ошибка('OSN-PAR-008', т);
    }
  }

  // ── операторы ───────────────────────────────────────────────────────────────────────────────

  private блок(стоп: ReadonlySet<V3TokenKind>): Оператор[] {
    const операторы: Оператор[] = [];
    while (true) {
      const т = this.пик();
      if (т.kind === 'конец_файла') {
        if (стоп.has('конец_файла')) break;
        throw this.ошибка('OSN-PAR-001', т);
      }
      if (стоп.has(т.kind)) break;
      операторы.push(this.оператор());
    }
    return операторы;
  }

  private оператор(): Оператор {
    const т = this.пик();
    if (т.kind === 'вернуть') {
      this.взять();
      const следующий = this.пик();
      const безЗначения =
        следующий.kind === 'конец' || следующий.kind === 'иначе' || следующий.kind === 'конец_файла';
      const значение = безЗначения ? undefined : this.выражение();
      return значение === undefined
        ? { вид: 'вернуть', позиция: позицияОт(т, this.последний) }
        : { вид: 'вернуть', значение, позиция: позицияОт(т, this.последний) };
    }
    if (т.kind === 'если') {
      this.взять();
      const узел = this.еслиПосле(т);
      const конец = this.ждатьКонец('если');
      return { ...узел, позиция: позицияОт(т, конец) };
    }
    if (т.kind === 'пусть') {
      this.взять();
      const имя = this.ждатьИмя();
      let тип: Тип | undefined;
      if (this.эт(':')) {
        this.взять();
        тип = this.тип();
      }
      if (!this.эт('=')) throw this.ошибка('OSN-PAR-017', this.пик());
      this.взять();
      const значение = this.выражение();
      return {
        вид: 'пусть',
        имя: имя.lexeme,
        ...(тип === undefined ? {} : { тип }),
        значение,
        позиция: позицияОт(т, this.последний),
      };
    }
    if (т.kind === 'пока') {
      this.взять();
      const условие = this.выражение();
      const тело = this.блок(new Set<V3TokenKind>(['конец']));
      const конец = this.ждатьКонец('пока');
      return { вид: 'пока', условие, тело, позиция: позицияОт(т, конец) };
    }
    if (т.kind === 'поднять') {
      this.взять();
      if (this.текущийВозврат?.вид !== 'результат') throw this.ошибка('OSN-PAR-020', т);
      const значение = this.выражение();
      const обёрнутое: Выражение =
        значение.вид === 'вызов' && значение.имя === 'Ошибка'
          ? значение
          : {
              вид: 'вызов',
              имя: 'Ошибка',
              аргументы: [значение],
              позиция: позицияОт(т, this.последний),
            };
      return { вид: 'вернуть', значение: обёрнутое, позиция: позицияОт(т, this.последний) };
    }
    if (т.kind === 'защита') throw this.ошибка('OSN-PAR-021', т);
    if (т.kind === 'конец_файла') throw this.ошибка('OSN-PAR-001', т);
    if (т.kind === 'конец') throw this.ошибка('OSN-PAR-025', т);
    if (т.kind === 'иначе') throw this.ошибка('OSN-PAR-003', т);

    // `5 = х`, `(х) = 1`: слева от `=` не имя. `а[i] = 1` ловится ниже в ветви имени.
    if (т.kind !== 'имя') {
      const равно = this.равноДоКонцаСтроки();
      if (равно !== undefined) throw this.ошибка('OSN-PAR-028', равно);
    }

    // Вызов-оператор или присваивание: начинается с имени; всё остальное — названный отказ.
    if (т.kind === 'имя') {
      const после = this.послеПика();
      const равно = this.равноДоКонцаСтроки();
      if (равно !== undefined && после.kind !== '=') throw this.ошибка('OSN-PAR-028', равно);

      if (после.kind === '=') {
        this.взять(); // имя
        this.взять(); // =
        if (this.эт('имя') && this.послеПика().kind === '=') {
          throw this.ошибка('OSN-PAR-029', this.пик());
        }
        const значение = this.выражение();
        if (this.эт('=')) throw this.ошибка('OSN-PAR-029', this.пик());
        return {
          вид: 'присваивание',
          имя: т.lexeme,
          значение,
          позиция: позицияОт(т, this.последний),
        };
      }

      // `вывести х`/`длина х`/`добавить …` — это библиотека D43, а не языковая инструкция.
      if (т.lexeme === 'вывести' || т.lexeme === 'длина' || т.lexeme === 'добавить') {
        throw this.ошибка('OSN-PAR-030', т);
      }

      const выражение = this.выражение();
      if (выражение.вид !== 'вызов' && выражение.вид !== 'квалифицированный_вызов') {
        throw this.ошибка('OSN-PAR-013', т);
      }
      return { вид: 'вызов', вызов: выражение, позиция: выражение.позиция };
    }
    throw this.ошибка('OSN-PAR-003', т);
  }

  /**
   * `если` после уже съеденного ключевого слова. `конец если` НЕ ест: он один на всю цепочку
   * `иначе если`, и его закрывает внешний `оператор()`.
   */
  private еслиПосле(начало: V3Token): УзелЕсли {
    const условие = this.выражение();
    const тогда = this.блок(new Set<V3TokenKind>(['иначе', 'конец']));
    let иначе: Оператор[] | undefined;
    if (this.эт('иначе')) {
      this.взять();
      if (this.эт('если')) {
        const токЕсли = this.взять();
        иначе = [this.еслиПосле(токЕсли)];
      } else {
        иначе = this.блок(new Set<V3TokenKind>(['конец']));
      }
    }
    return иначе === undefined
      ? { вид: 'если', условие, тогда, позиция: позицияОт(начало, this.последний) }
      : { вид: 'если', условие, тогда, иначе, позиция: позицияОт(начало, this.последний) };
  }

  // ── выражения ───────────────────────────────────────────────────────────────────────────────

  private выражение(): Выражение {
    return this.или();
  }

  private или(): Выражение {
    let левый = this.и();
    while (this.эт('или')) {
      this.взять();
      const правый = this.и();
      левый = this.бинарное('или', левый, правый);
    }
    return левый;
  }

  private и(): Выражение {
    let левый = this.равенство();
    while (this.эт('и')) {
      this.взять();
      const правый = this.равенство();
      левый = this.бинарное('и', левый, правый);
    }
    return левый;
  }

  private равенство(): Выражение {
    let левый = this.сравнение();
    while (this.эт('==') || this.эт('!=')) {
      const оператор = this.взять().kind === '==' ? '==' : '!=';
      const правый = this.сравнение();
      левый = this.бинарное(оператор, левый, правый);
    }
    return левый;
  }

  private сравнение(): Выражение {
    let левый = this.сложение();
    while (this.эт('<') || this.эт('<=') || this.эт('>') || this.эт('>=')) {
      const оператор = this.взять().kind as '<' | '<=' | '>' | '>=';
      const правый = this.сложение();
      левый = this.бинарное(оператор, левый, правый);
    }
    return левый;
  }

  private сложение(): Выражение {
    let левый = this.умножение();
    while (this.эт('+') || this.эт('-')) {
      const оператор = this.взять().kind as '+' | '-';
      const правый = this.умножение();
      левый = this.бинарное(оператор, левый, правый);
    }
    return левый;
  }

  private умножение(): Выражение {
    let левый = this.унарное();
    while (this.эт('*') || this.эт('/') || this.эт('%') || this.эт('нацело')) {
      const оператор = this.взять().kind as '*' | '/' | '%' | 'нацело';
      const правый = this.унарное();
      левый = this.бинарное(оператор, левый, правый);
    }
    return левый;
  }

  private унарное(): Выражение {
    if (this.эт('-')) {
      const оператор = this.взять();
      const операнд = this.унарное();
      return {
        вид: 'унарное',
        оператор: '-',
        операнд,
        позиция: позицияОт(оператор, this.последний),
      };
    }
    if (this.эт('не')) {
      const оператор = this.взять();
      const операнд = this.унарное();
      return {
        вид: 'унарное',
        оператор: 'не',
        операнд,
        позиция: позицияОт(оператор, this.последний),
      };
    }
    return this.постфикс();
  }

  private постфикс(): Выражение {
    let выражение = this.первичное();
    while (this.эт('[')) {
      this.взять();
      const индекс = this.выражение();
      const закрывающая = this.ждать(']', 'OSN-PAR-003');
      выражение = {
        вид: 'индексация',
        база: выражение,
        индекс,
        позиция: позицияДо(выражение.позиция, закрывающая.offset + закрывающая.length),
      };
    }
    return выражение;
  }

  private первичное(): Выражение {
    const т = this.пик();
    switch (т.kind) {
      case 'число':
        this.взять();
        return { вид: 'литерал', литерал: { вид: 'число', текст: т.lexeme }, позиция: позицияТокена(т) };
      case 'строка':
        this.взять();
        return {
          вид: 'литерал',
          литерал: { вид: 'строка', значение: typeof т.value === 'string' ? т.value : т.lexeme },
          позиция: позицияТокена(т),
        };
      case 'да':
      case 'нет':
        this.взять();
        return {
          вид: 'литерал',
          литерал: { вид: 'логическое', значение: т.kind === 'да' },
          позиция: позицияТокена(т),
        };
      case 'пусто':
        this.взять();
        return { вид: 'литерал', литерал: { вид: 'пусто' }, позиция: позицияТокена(т) };
      case 'имя': {
        if (т.lexeme === 'вывести' || т.lexeme === 'длина' || т.lexeme === 'добавить') {
          throw this.ошибка('OSN-PAR-030', т);
        }
        this.взять();
        if (т.lexeme === 'Ошибка' && this.эт('{')) throw this.ошибка('OSN-PAR-024', this.пик());
        if (this.эт('.')) {
          this.взять();
          const функция = this.ждатьИмя();
          if (!(БИБЛИОТЕКИ_D43 as readonly string[]).includes(т.lexeme)) {
            throw this.ошибка('OSN-PAR-031', т);
          }
          if (!this.эт('(')) throw this.ошибка('OSN-PAR-031', функция);
          this.взять();
          const аргументы: Выражение[] = [];
          if (!this.эт(')')) {
            while (true) {
              аргументы.push(this.выражение());
              if (!this.эт(',')) break;
              this.взять();
            }
          }
          const закрывающая = this.ждать(')', 'OSN-PAR-005');
          if (т.lexeme === 'Списки' && функция.lexeme === 'добавить' && аргументы.length !== 3) {
            throw this.ошибка('OSN-PAR-032', функция);
          }
          return {
            вид: 'квалифицированный_вызов',
            библиотека: т.lexeme,
            функция: функция.lexeme,
            аргументы,
            позиция: позицияОт(т, закрывающая),
          };
        }
        if (this.эт('(')) {
          this.взять();
          const аргументы: Выражение[] = [];
          if (!this.эт(')')) {
            while (true) {
              аргументы.push(this.выражение());
              if (!this.эт(',')) break;
              this.взять();
            }
          }
          const закрывающая = this.ждать(')', 'OSN-PAR-005');
          return {
            вид: 'вызов',
            имя: т.lexeme,
            аргументы,
            позиция: позицияОт(т, закрывающая),
          };
        }
        return { вид: 'имя', имя: т.lexeme, позиция: позицияТокена(т) };
      }
      case '(': {
        this.взять();
        const выражение = this.выражение();
        this.ждать(')', 'OSN-PAR-005');
        return выражение;
      }
      case '[': {
        this.взять();
        const элементы: Выражение[] = [];
        if (!this.эт(']')) {
          while (true) {
            элементы.push(this.выражение());
            if (!this.эт(',')) break;
            this.взять();
          }
        }
        const закрывающая = this.ждать(']', 'OSN-PAR-003');
        return {
          вид: 'список',
          элементы,
          позиция: позицияОт(т, закрывающая),
        };
      }
      case 'конец_файла':
        throw this.ошибка('OSN-PAR-001', т);
      case '→':
        throw this.ошибка('OSN-PAR-026', т);
      case 'защита':
        throw this.ошибка('OSN-PAR-021', т);
      default:
        throw this.ошибка('OSN-PAR-003', т);
    }
  }

  private бинарное(оператор: БинарныйОператор, левый: Выражение, правый: Выражение): Выражение {
    return {
      вид: 'бинарное',
      оператор,
      левый,
      правый,
      позиция: {
        начало: левый.позиция.начало,
        конец: правый.позиция.конец,
        строка: левый.позиция.строка,
        колонка: левый.позиция.колонка,
      },
    };
  }
}

/**
 * Разобрать поток токенов полного лексера. Публичная точка для чекера: ошибки не бросаются.
 *
 * @param tokens поток `tokenizeV3(...).tokens`; последний обязан быть `конец_файла`
 * @param moduleName имя модуля (файл = модуль, как в v3)
 */
export function parseV01Tokens(tokens: readonly V3Token[], moduleName: string): ИтогПарсераV01 {
  if (tokens.length === 0 || tokens[tokens.length - 1]!.kind !== 'конец_файла') {
    const последний = tokens[tokens.length - 1];
    return {
      ок: false,
      ошибка: {
        код: 'OSN-PAR-001',
        сообщение: сообщениеОшибки('OSN-PAR-001', null),
        позиция: последний === undefined ? { начало: 0, конец: 0, строка: 1, колонка: 1 } : позицияТокена(последний),
        видТокена: последний?.kind ?? null,
        лексема: null,
      },
    };
  }
  const парсер = new ПарсерV01(tokens, moduleName);
  try {
    const ast = парсер.файл();
    // Стабильные id — в порядке объявления, а не «уникальные во вселенной» (Phase 0).
    return { ок: true, ast: { ...ast, процедуры: ast.процедуры.map((п, и) => ({ ...п, id: `p${String(и)}` })) } };
  } catch (е) {
    if (е instanceof ОтказПарсера) return { ок: false, ошибка: е.ошибка };
    throw е;
  }
}

/** Разобрать исходник v3: лексер + парсер v0.1. Лексерский отказ — тоже названный. */
export function parseV01(source: string, filename: string = DEFAULT_V3_FILENAME): ИтогПарсераV01 {
  const лек: V3LexResult = tokenizeV3(source, filename);
  if (лек.errors.length > 0) {
    const первая = лек.errors[0]!;
    return {
      ок: false,
      ошибка: {
        код: КОДЫ_ОШИБОК.лексер,
        сообщение: `${сообщениеОшибки(КОДЫ_ОШИБОК.лексер, null)} (${первая})`,
        позиция: { начало: 0, конец: 0, строка: 1, колонка: 1 },
        видТокена: null,
        лексема: null,
      },
    };
  }
  return parseV01Tokens(лек.tokens, moduleNameFromFilename(filename));
}
