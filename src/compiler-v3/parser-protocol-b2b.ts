/**
 * B2b: `пусть`, присваивание, простые выражения, `если`/`пока` — POST-ORDER на ленте.
 *
 * Форма: `главная` строит token tape и вызывает `обойти` ОДИН раз. `обойти` идёт циклом по
 * произвольной ленте и на каждый оператор зовёт свой шаг (`шаг_пусть`, `шаг_если`, …).
 * Выражения разбираются итеративным shunting-yard: явный стек операторов в хвосте `лента`,
 * никакой рекурсии-писателя. Писатели — листья, QEMU по-прежнему отказывает `#180` (D12),
 * железо — арбитр.
 *
 * Чего здесь НЕТ и это названо: `прервать`/`продолжить` (в AST v0.1 их нет), escape-последовательностей
 * в строках (простая строка без `\"`/`\\` поддержана), заголовков `процедура` (B2b разбирает
 * `действие`), УНАРНОГО оператора в начале аргумента (`ф(-1 + 2)`: `шаг_вызов` не выставляет
 * «ждём операнд», поэтому `-` читается как бинарный — эта граница закреплена негативным контролем).
 * Вызов-оператор, вложенные вызовы-аргументы, вызов-выражение (`пусть х = ф(1)`), индексация и
 * списки в выражениях и АРГУМЕНТ-ВЫРАЖЕНИЕ (`ф(1 + 2)`, `ф(1) * ф(2 + 1)`) поддержаны.
 *
 * L2 (2026-11-13): добавлены `%`/`нацело`, `и`/`или`, унарные `-`/`не`, `: Тип` у `пусть`, простые
 * строки, многострочные выражения и вызов-выражение; каждая форма проверена на E8C2
 * (AST = эталон, код 0).
 *
 * L2 (2026-11-14, случай 103): АРГУМЕНТ-ВЫРАЖЕНИЕ снят по ТРАССЕ, а не догадкой. Три редакции до неё
 * падали `Max steps exceeded`, потому что звали `выразить` из аргумента: он обнуляет стек операторов
 * и состояние внешнего выражения. Трасса `ф(1 + 2)` показала три отдельные причины, и правились они
 * по одной: (1) на `+` цикл вызова выходил (`иначе → идёт = 0`), `)` не потреблялся и события 10/11
 * не писались — теперь операторы и `[`/`]` идут в аргументах через дно-маркер `шаг_скобка`, который
 * `свернуть` не пробивает; (2) операнд не клал позиции в `С[1..4]`, поэтому узел `+` писался нулями
 * (`21 0 38 0 0` вместо `21 33 38 2 15`) — теперь кладёт; (3) счётчик аргументов рос на КАЖДОМ
 * операнде (`11 2 39` вместо `11 1 39`) — теперь растёт по началу аргумента, флаг в `С[8]`.
 */
import { КОД_ВИДА, программаПротоколаB2aPerEvent, токеннаяЛента, токеныB1 } from './parser-protocol-probe';
import { КОД_СОБЫТИЯ, КОД_ТИПА } from './astFormat';

const МАГИЯ = 20261108;
const МОДУЛЬ_ШАПКА = /^действие /mu;

/** Сколько нулевых клеток добавляется после шапки AST: хвост под стеки и состояние. */
const ХВОСТ = 1900;
/** Смещение состояния относительно начала AST-записи. */
const СМЕЩЕНИЕ_СОСТОЯНИЯ = 1200;
/** Смещение стека операторов выражения (5 клеток на запись). */
const СМЕЩЕНИЕ_ОПЕРАТОРОВ = 1300;
/** Смещение стека вызовов (2 клетки на запись). */
const СМЕЩЕНИЕ_ВЫЗОВОВ = 1700;
/** Маркер `(` в стеке операторов. */
const МАРКЕР_СКОБКИ = 99;
/** Маркер литерала списка `[…]` в стеке операторов (§41). */
const МАРКЕР_СПИСКА = 98;
/** Маркер индексации `а[…]` в стеке операторов (§41); под ним лежит запись события 39. */
const МАРКЕР_ИНДЕКСА = 97;
/**
 * Маркер скобки-ГРУППЫ ВНУТРИ аргументов вызова (клетка 14 181, круг 25).
 *
 * Дно аргументов и группа — обе `(`, но закрываются они по-разному: дно снимает
 * `шаг_вызов_закрыть` вместе с записью вызова, а группу он же снимает отдельной ветвью, не трогая
 * запись. Пока маркер был один (99), различить их было нечем, поэтому `)` всегда закрывал ВЫЗОВ — и
 * группа не разбиралась вовсе. Значение обязано быть ≥ `ГРАНИЦА_МАРКЕРОВ`, иначе `свернуть` пройдёт
 * сквозь неё.
 */
const МАРКЕР_ГРУППЫ = 100;
/** Ниже этого числа маркеров нет: операторы нумеруются 21…43 (`КОД_СОБЫТИЯ`). */
const ГРАНИЦА_МАРКЕРОВ = 97;

function имяМодуля(файл: string): string {
  return (файл.split(/[\\/]/).pop() ?? файл).replace(/\.[^.]+$/u, '');
}

/** Точная строка шапки, которую заменяет §40. Одна: вхождений должно быть ровно одно. */
const ВЫВЕСТИ_В_НАПЕЧАТАТЬ = 'вывести лента[пт]';
/** Чем заменяется: каноническое D43-имя печати, которое эталон ПРИНИМАЕТ (§1, `parseV01`). */
const ПЕЧАТЬ_ЧИСЛА = 'Печать.число(лента[пт])';

/**
 * Заменить ЕДИНСТВЕННОЕ `вывести` шапки на `Печать.число` — с падением, если вхождений не одно.
 *
 * Проверка «ровно одно» — не украшение: при нуле исходник B2b молча остался бы неразбираемым
 * эталоном, а при двух замена одной строки оставила бы вторую и дала бы ровно тот же молчащий
 * дефект. Оба случая — падение сборки, а не тихий проход (правило «доказательство, а не
 * обещание»: §39 уже стоил одного прогона из-за `report[0]`).
 */
function заменитьПечать(шапка: string): string {
  const вхождений = шапка.split(ВЫВЕСТИ_В_НАПЕЧАТАТЬ).length - 1;
  if (вхождений !== 1) {
    throw new Error(`B2b: «${ВЫВЕСТИ_В_НАПЕЧАТАТЬ}» в шапке ${String(вхождений)} раз, ожидалось ровно одно`);
  }
  return шапка.replace(ВЫВЕСТИ_В_НАПЕЧАТАТЬ, ПЕЧАТЬ_ЧИСЛА);
}

