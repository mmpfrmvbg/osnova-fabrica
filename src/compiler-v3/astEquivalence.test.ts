/** Модуль по фронтенду v2 — эталон. Посредников нет: это выход `parse`. */
function модульV2(источник: string, файл: string): Module {
  const разбор = parse(tokenize(источник).tokens, { filename: файл });
  expect(разбор.errors, `v2 не разобрал эталон: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  const модуль = разбор.ast?.modules[0];
  expect(модуль, "у эталона v2 нет модуля").toBeDefined();
  return модуль!;
}

/**
 * Пути всех ключей, значение которых ОПРЕДЕЛЕНО (не `undefined`).
 *
 * `toEqual` игнорирует ключи со значением `undefined` — здесь это проверено явно,
 * чтобы совпадение не держалось на неявном правиле сравнения. Плюс длина набора
 * показывает, что сравниваются не два пустых дерева.
 */
function путиКлючей(значение: unknown, путь = ""): string[] {
  if (Array.isArray(значение)) {
    return значение.flatMap((элемент, i) => путиКлючей(элемент, `${путь}[${i}]`));
  }
  if (значение !== null && typeof значение === "object") {
    const итог: string[] = [];
    for (const [ключ, з] of Object.entries(значение as Record<string, unknown>)) {
      if (з === undefined) continue;
      const полный = путь === "" ? ключ : `${путь}.${ключ}`;
      итог.push(полный, ...путиКлючей(з, полный));
    }
    return итог;
  }
  return [];
}

describe("оракул AST: v3 против v2 на источниках корпуса", () => {
  for (const пара of ПАРЫ) {
    const файл = ФАЙЛ(пара.имя);

    it(`${пара.имя}: источник v2 компилируется`, () => {
      const собран = compileSource(пара.v2, { filename: файл });
      expect(собран.lexerErrors).toEqual([]);
      expect(собран.parserErrors).toEqual([]);
      expect(собран.module, "у v2 нет собранного модуля").toBeTruthy();
      expect(собран.compilerSuccess, "v2 не собрал эталон").toBe(true);
    });

    it(`${пара.имя}: AST v3 равен AST v2`, () => {
      const разбор3 = parseV3(пара.v3, файл);
      expect(разбор3.errors, `v3 не разобрал: ${разбор3.errors.join("; ")}`).toEqual([]);
      expect(разбор3.program?.modules).toHaveLength(1);

      const факт = разбор3.program!.modules[0]!;
      const эталон = модульV2(пара.v2, файл);

      // Главное утверждение шага: модуль ЦЕЛИКОМ, сравнение деревьев.
      expect(факт).toEqual(эталон);
      expect(new Set(путиКлючей(факт))).toEqual(new Set(путиКлючей(эталон)));
      expect(путиКлючей(эталон).length).toBeGreaterThan(20);
    });
  }

  it("в наборе пять пар — иначе оракул сторожит одну ветвь грамматики", () => {
    expect(ПАРЫ).toHaveLength(5);
  });
});

describe("эталон v2 и что именно с ним сравнивается", () => {
  it("`origin` и `moduleClosedAt` во фронтенде v2 НЕ проставляются", () => {
    for (const пара of ПАРЫ) {
      const файл = ФАЙЛ(пара.имя);
      const эталон = модульV2(пара.v2, файл);
      expect(эталон.moduleClosedAt, "у источника без шапки модуль закрывать нечем").toBeUndefined();
      expect(эталон.procedures.length).toBeGreaterThan(0);
      for (const п of эталон.procedures) expect(п.origin).toBeUndefined();

      // А `compileSource` отдаёт AST ПОСЛЕ разворачивания импортов — там `origin`
      // уже стоит. Это различие слоёв, и оно измерено, а не замазано: если бы
      // эталон брался из `moduleAst`, v3-парсеру пришлось бы врать про `origin`.
      const собран = compileSource(пара.v2, { filename: файл });
      expect(собран.moduleAst?.procedures.map((п) => п.origin)).toEqual(эталон.procedures.map(() => файл));
    }
  });
});

describe("негативные контроли: оракул обязан краснеть", () => {
  const ПЕРЕБОР = ПАРЫ[1]!; // 07-сумма-массива
  const УСЛОВИЯ = ПАРЫ[3]!; // 19-вложенные-условия

  it("`для эл в` (форма v2) отвергается: слово «каждого» обязательно", () => {
    const без = ПЕРЕБОР.v3.replace("для каждого число в числа", "для число в числа");
    const разбор = parseV3(без, ФАЙЛ(ПЕРЕБОР.имя));
    expect(разбор.errors.join(" ")).toContain("«каждого» обязательно");
    expect(разбор.program).toBeUndefined();
  });

  it("склейка `конец_пока` отвергается: в v3 закрытие пишется через пробел", () => {
    const склейка = УСЛОВИЯ.v3.replace("  конец пока", "  конец_пока");
    const разбор = parseV3(склейка, ФАЙЛ(УСЛОВИЯ.имя));
    expect(разбор.errors.join(" ")).toContain("конец_пока");
    expect(разбор.program).toBeUndefined();
  });

  it("`=` в условии отвергается (в v2 он молча читался как `==`)", () => {
    const сРавно = УСЛОВИЯ.v3.replace("если значение > 10", "если значение = 10");
    const разбор = parseV3(сРавно, ФАЙЛ(УСЛОВИЯ.имя));
    expect(разбор.errors.join(" ")).toContain("в условии нужно «==»");
    expect(разбор.program).toBeUndefined();
  });

  it("`?Тип` (форма v2) отвергается: пишется «Может Тип»", () => {
    const разбор = parseV3("процедура f(а: ?Число) → Число\n  вернуть 1\nконец\n", "проба.osnova");
    expect(разбор.errors.join(" ")).toContain("«Может Тип»");
    expect(разбор.program).toBeUndefined();
  });

  it("`система.массив.получить(а, 0)` отвергается: цепочка имён запрещена", () => {
    const разбор = parseV3("действие f(а: Список Число)\n  пусть х = система.массив.получить(а, 0)\nконец\n", "проба.osnova");
    expect(разбор.errors.join(" ")).toContain("цепочка имён");
    expect(разбор.program).toBeUndefined();
  });

  it("подмена ОДНОГО слова ломает РАВЕНСТВО деревьев (то есть `toEqual` краснеет)", () => {
    // Программа разбирается, но AST другой. Это и есть проверка, что оракул
    // сравнивает деревья, а не зеленеет от факта успешного разбора.
    const подмена = ПЕРЕБОР.v3.replace("сумма = сумма + число", "сумма = сумма - число");
    const разбор3 = parseV3(подмена, ФАЙЛ(ПЕРЕБОР.имя));
    expect(разбор3.errors).toEqual([]);
    const эталон = модульV2(ПЕРЕБОР.v2, ФАЙЛ(ПЕРЕБОР.имя));
    expect(() => expect(разбор3.program!.modules[0]!).toEqual(эталон)).toThrow();
    expect(разбор3.program!.modules[0]!).not.toEqual(эталон);
  });

  it("имя модуля входит в сравнение: другой файл — другое дерево", () => {
    const пара = ПАРЫ[0]!;
    const разбор3 = parseV3(пара.v3, "другое/имя.osnova");
    expect(разбор3.errors).toEqual([]);
    const эталон = модульV2(пара.v2, ФАЙЛ(пара.имя));
    expect(() => expect(разбор3.program!.modules[0]!).toEqual(эталон)).toThrow();
  });
});
