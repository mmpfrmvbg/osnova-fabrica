/**
 * ОРАКУЛ v3: AST, собранный фронтендом v3, РАВЕН AST, собранным фронтендом v2.
 *
 * Почему равенство ДЕРЕВЬЕВ, а не «оба разобрались». Проверка «программа
 * разобралась» зеленеет от любого разбора и не отличает верный AST от неверного —
 * это класс дефекта из `docs/verification-debt.md`. Здесь сверяется СТРУКТУРА:
 * лишний узел, подменённый операнд, другое имя системного вызова или потерянное
 * поле краснеют немедленно, на уровне фронтенда, а не через байткод и VM.
 *
 * Эталон — выход ФРОНТЕНДА v2 (`parse(tokenize(...))`), а не `moduleAst` из
 * `compileSource`: `moduleAst` уже прошёл разворачивание импортов и проставляет
 * `origin` каждой процедуре — это работа другого слоя, и подделывать её в
 * v3-парсере, чтобы сравнение сошлось, было бы подгонкой. Различие названо
 * отдельной пробой ниже.
 *
 * Источники v2 взяты ИЗ КОРПУСА (`examples/<имя>/main.osnova`) и положены в тест
 * строками: тест обязан быть воспроизводим без чтения файлов с диска. Пара
 * «источник корпуса ↔ та же программа в написании v3» — это и есть содержание
 * шага: так проверяется каждое соответствие синтаксисов, включая те, что ни один
 * пример не использует в одиночку.
 */
