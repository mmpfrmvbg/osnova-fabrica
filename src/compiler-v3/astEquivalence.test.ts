/**
 * AST главного модуля по v2-компилятору.
 *
 * Ключи со значением `undefined` выбрасываются с ОБЕИХ сторон. Это часть
 * контракта, а не поблажка: v2-парсер объявляет необязательные поля
 * (`returnType`, `paramTypes`, `elseBody`, `elseIfClauses`) как `undefined`,
 * v3-парсер их не заводит вовсе. Значение при этом одно и то же — «поля нет»,
 * и кодоген такие ключи не различает. Всё, что имеет ЗНАЧЕНИЕ, сравнивается
 * строго: подмена операнда, лишний узел или другой порядок — красное.
 */
function безПустых(значение: unknown): unknown {
  if (Array.isArray(значение)) return значение.map(безПустых);
  if (значение !== null && typeof значение === "object") {
    const итог: Record<string, unknown> = {};
    for (const [к, з] of Object.entries(значение as Record<string, unknown>)) {
      if (з === undefined) continue;
      итог[к] = безПустых(з);
    }
    return итог;
  }
  return значение;
}

function модульV2(источник: string): Module {
  const р = compileSource(источник, { filename: ФАЙЛ });
  expect(р.parserErrors, `v2 не разобрал программу: ${JSON.stringify(р.parserErrors)}`).toEqual([]);
  const м = р.moduleAst;
  expect(м, "v2 не дал AST").toBeTruthy();
  return м!;
}

describe("v3-фронтенд: AST совпадает с v2", () => {
  for (const пара of ПРОГРАММЫ) {
    it(`${пара.имя}: деревья равны`, () => {
      const в2 = модульV2(пара.v2);
      const р3 = parseV3(пара.v3, ФАЙЛ);
      expect(р3.errors, `v3 не разобрал: ${р3.errors.join("; ")}`).toEqual([]);
      const в3 = р3.program!.modules[0]!;
      expect(безПустых(в3)).toEqual(безПустых(в2));
    });
  }

  it("в наборе не меньше пяти пар — иначе оракул сторожит одну ветвь", () => {
    expect(ПРОГРАММЫ.length).toBeGreaterThanOrEqual(5);
  });

  // НЕГАТИВНЫЙ КОНТРОЛЬ: оракул обязан краснеть, если различие синтаксиса убрать.
  // Иначе он зелен по построению: «оба разобрались» — не утверждение о форме AST.
  it("негативный контроль: `для эл в` (без «каждого») — ошибка разбора", () => {
    const без = ПРОГРАММЫ[1]!.v3.replace("для каждого число в числа", "для число в числа");
    const р = parseV3(без, ФАЙЛ);
    expect(р.errors.length, "v3 принял форму, которой в языке нет").toBeGreaterThan(0);
  });

  it("негативный контроль: `=` в условии v3 не прощает", () => {
    const сРавно = ПРОГРАММЫ[2]!.v3.replace("если х > 3", "если х = 3");
    const р = parseV3(сРавно, ФАЙЛ);
    expect(р.errors.join(" "), "v3 принял `=` в условии").toContain("в условии нужно «==»");
  });

  it("негативный контроль: цепочка сравнений запрещена", () => {
    const цепь = ПРОГРАММЫ[2]!.v3.replace("если х > 3 и не (х == 4)", "если 1 < х < 4");
    const р = parseV3(цепь, ФАЙЛ);
    expect(р.errors.join(" ")).toContain("цепочка сравнений запрещена");
  });

  it("негативный контроль: подмена операнда ломает РАВЕНСТВО деревьев, а не разбор", () => {
    // Программа разбирается, но AST другой — значит сравнение деревьев работает,
    // а не «зеленеет от факта успешного разбора».
    const подмена = ПРОГРАММЫ[0]!.v3.replace("вернуть х + у + остаток", "вернуть х + у");
    const р3 = parseV3(подмена, ФАЙЛ);
    expect(р3.errors).toEqual([]);
    const в2 = модульV2(ПРОГРАММЫ[0]!.v2);
    expect(безПустых(р3.program!.modules[0]!)).not.toEqual(безПустых(в2));
  });
});
