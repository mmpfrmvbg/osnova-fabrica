// ── Каноническая JSON-форма (Phase 0: детерминизм) ───────────────────────────────────────────

type JSONЗначение = string | number | boolean | null | JSONЗначение[] | { [ключ: string]: JSONЗначение };

/** Позиция в фиксированном порядке ключей. */
function позицияJSON(п: Позиция): JSONЗначение {
  return { начало: п.начало, конец: п.конец, строка: п.строка, колонка: п.колонка };
}

/** Тип в фиксированном порядке ключей. */
function типJSON(т: Тип): JSONЗначение {
  switch (т.вид) {
    case 'имя':
      return { вид: 'имя', имя: т.имя };
    case 'список':
      return { вид: 'список', элемент: типJSON(т.элемент) };
    case 'результат':
      return { вид: 'результат', успех: типJSON(т.успех), ошибка: типJSON(т.ошибка) };
  }
}

function литералJSON(л: Литерал): JSONЗначение {
  switch (л.вид) {
    case 'число':
      return { вид: 'число', текст: л.текст };
    case 'строка':
      return { вид: 'строка', значение: л.значение };
    case 'логическое':
      return { вид: 'логическое', значение: л.значение };
    case 'пусто':
      return { вид: 'пусто' };
  }
}

/** Выражение в фиксированном порядке ключей. */
function выражениеJSON(в: Выражение): JSONЗначение {
  switch (в.вид) {
    case 'литерал':
      return { вид: 'литерал', литерал: литералJSON(в.литерал), позиция: позицияJSON(в.позиция) };
    case 'имя':
      return { вид: 'имя', имя: в.имя, позиция: позицияJSON(в.позиция) };
    case 'вызов':
      return {
        вид: 'вызов',
        имя: в.имя,
        аргументы: в.аргументы.map(выражениеJSON),
        позиция: позицияJSON(в.позиция),
      };
    case 'бинарное':
      return {
        вид: 'бинарное',
        оператор: в.оператор,
        левый: выражениеJSON(в.левый),
        правый: выражениеJSON(в.правый),
        позиция: позицияJSON(в.позиция),
      };
    case 'унарное':
      return {
        вид: 'унарное',
        оператор: в.оператор,
        операнд: выражениеJSON(в.операнд),
        позиция: позицияJSON(в.позиция),
      };
    case 'список':
      return { вид: 'список', элементы: в.элементы.map(выражениеJSON), позиция: позицияJSON(в.позиция) };
    case 'индексация':
      return {
        вид: 'индексация',
        база: выражениеJSON(в.база),
        индекс: выражениеJSON(в.индекс),
        позиция: позицияJSON(в.позиция),
      };
    case 'квалифицированный_вызов':
      return {
        вид: 'квалифицированный_вызов',
        библиотека: в.библиотека,
        функция: в.функция,
        аргументы: в.аргументы.map(выражениеJSON),
        позиция: позицияJSON(в.позиция),
      };
  }
}

function операторJSON(о: Оператор): JSONЗначение {
  switch (о.вид) {
    case 'вернуть':
      return о.значение === undefined
        ? { вид: 'вернуть', позиция: позицияJSON(о.позиция) }
        : { вид: 'вернуть', значение: выражениеJSON(о.значение), позиция: позицияJSON(о.позиция) };
    case 'если':
      return {
        вид: 'если',
        условие: выражениеJSON(о.условие),
        тогда: о.тогда.map(операторJSON),
        ...(о.иначе === undefined ? {} : { иначе: о.иначе.map(операторJSON) }),
        позиция: позицияJSON(о.позиция),
      };
    case 'вызов':
      return { вид: 'вызов', вызов: выражениеJSON(о.вызов), позиция: позицияJSON(о.позиция) };
    case 'пусть':
      return {
        вид: 'пусть',
        имя: о.имя,
        ...(о.тип === undefined ? {} : { тип: типJSON(о.тип) }),
        значение: выражениеJSON(о.значение),
        позиция: позицияJSON(о.позиция),
      };
    case 'пока':
      return {
        вид: 'пока',
        условие: выражениеJSON(о.условие),
        тело: о.тело.map(операторJSON),
        позиция: позицияJSON(о.позиция),
      };
    case 'присваивание':
      return {
        вид: 'присваивание',
        имя: о.имя,
        значение: выражениеJSON(о.значение),
        позиция: позицияJSON(о.позиция),
      };
  }
}

/**
 * Каноническое представление AST: массив/объект с ФИКСИРОВАННЫМ порядком ключей.
 * `JSON.stringify` такого значения детерминирован; сортировать ключи не нужно, потому что
 * порядок задан схемой, а не алфавитом.
 */
export function канонизировать(ast: AstФайл): JSONЗначение {
  return {
    формат: ast.формат,
    версия: ast.версия,
    модуль: { имя: ast.модуль.имя, позиция: позицияJSON(ast.модуль.позиция) },
    процедуры: ast.процедуры.map((п) => ({
      id: п.id,
      имя: п.имя,
      действие: п.действие,
      параметры: п.параметры.map((пар) => ({
        имя: пар.имя,
        тип: типJSON(пар.тип),
        позиция: позицияJSON(пар.позиция),
      })),
      возвращает: п.возвращает === null ? null : типJSON(п.возвращает),
      тело: п.тело.map(операторJSON),
      контракт: {
        требует: п.контракт.требует.map(выражениеJSON),
        обеспечивает: п.контракт.обеспечивает.map(выражениеJSON),
        эффекты: [...п.контракт.эффекты],
      },
      позиция: позицияJSON(п.позиция),
    })),
  };
}

/** Канонический JSON AST: без таймстампов, порядок ключей фиксирован схемой. */
export function каноническийJSON(ast: AstФайл): string {
  return JSON.stringify(канонизировать(ast), null, 2) + '\n';
}

// ── Лента: плоская числовая запись AST/отказа ────────────────────────────────────────────────

const коды = (с: string): number[] => [...с].map((символ) => символ.codePointAt(0)!);

/** Заголовок ленты: магия, версия, вид, имя модуля. */
function заголовок(вид: number, модуль: string, конецМодуля: number, версия = `${ВЕРСИЯ_AST.мажор}.${ВЕРСИЯ_AST.минор}`): number[] {
  const [мажор, минор] = версия.split('.').map(Number);
  if (!Number.isInteger(мажор) || !Number.isInteger(минор)) throw new Error(`неверная версия ленты «${версия}»`);
  const точки = коды(модуль);
  return [МАГИЯ_ЛЕНТЫ, мажор!, минор!, вид, точки.length, ...точки, конецМодуля];
}

function типВЛенту(т: Тип, в: number[]): void {
  switch (т.вид) {
    case 'имя': {
      const точки = коды(т.имя);
      в.push(КОД_ТИПА.имя, точки.length, ...точки);
      return;
    }
    case 'список':
      в.push(КОД_ТИПА.список);
      типВЛенту(т.элемент, в);
      return;
    case 'результат':
      в.push(КОД_ТИПА.результат);
      типВЛенту(т.успех, в);
      типВЛенту(т.ошибка, в);
      return;
  }
}

function литералВЛенту(л: Литерал, в: number[]): void {
  switch (л.вид) {
    case 'число': {
      const точки = коды(л.текст);
      в.push(КОД_ЛИТЕРАЛА.число, точки.length, ...точки);
      return;
    }
    case 'строка': {
      const точки = коды(л.значение);
      в.push(КОД_ЛИТЕРАЛА.строка, точки.length, ...точки);
      return;
    }
    case 'логическое':
      в.push(КОД_ЛИТЕРАЛА.логическое, л.значение ? 1 : 0);
      return;
    case 'пусто':
      в.push(КОД_ЛИТЕРАЛА.пусто);
      return;
  }
}

function имяВЛенту(имя: string, в: number[]): void {
  const точки = коды(имя);
  в.push(точки.length, ...точки);
}

function выражениеВЛенту(в: Выражение, л: number[]): void {
  switch (в.вид) {
    case 'литерал':
      л.push(КОД_СОБЫТИЯ.литерал, в.позиция.начало, в.позиция.конец, в.позиция.строка, в.позиция.колонка);
      литералВЛенту(в.литерал, л);
      return;
    case 'имя':
      л.push(КОД_СОБЫТИЯ.имя, в.позиция.начало, в.позиция.конец, в.позиция.строка, в.позиция.колонка);
      имяВЛенту(в.имя, л);
      return;
    case 'вызов':
      // POST-ORDER: аргументы, затем событие вызова (имя и конец — после детей, без backpatch).
      for (const аргумент of в.аргументы) выражениеВЛенту(аргумент, л);
      л.push(КОД_СОБЫТИЯ.вызов_начало, в.позиция.начало, в.позиция.строка, в.позиция.колонка);
      имяВЛенту(в.имя, л);
      л.push(КОД_СОБЫТИЯ.вызов_конец, в.аргументы.length, в.позиция.конец);
      return;
    case 'бинарное':
      выражениеВЛенту(в.левый, л);
      выражениеВЛенту(в.правый, л);
      л.push(
        КОД_БИНАРНОГО[в.оператор],
        в.позиция.начало,
        в.позиция.конец,
        в.позиция.строка,
        в.позиция.колонка,
      );
      return;
    case 'унарное':
      выражениеВЛенту(в.операнд, л);
      л.push(
        КОД_УНАРНОГО[в.оператор],
        в.позиция.начало,
        в.позиция.конец,
        в.позиция.строка,
        в.позиция.колонка,
      );
      return;
    case 'список':
      for (const элемент of в.элементы) выражениеВЛенту(элемент, л);
      л.push(КОД_СОБЫТИЯ.список_начало, в.позиция.начало, в.позиция.строка, в.позиция.колонка);
      л.push(КОД_СОБЫТИЯ.список_конец, в.элементы.length, в.позиция.конец);
      return;
    case 'индексация':
      // `[база, индекс]`: база и индекс — дети, событие индексации — после них.
      выражениеВЛенту(в.база, л);
      выражениеВЛенту(в.индекс, л);
      л.push(
        КОД_СОБЫТИЯ.индексация,
        в.позиция.начало,
        в.позиция.конец,
        в.позиция.строка,
        в.позиция.колонка,
      );
      return;
    case 'квалифицированный_вызов':
      // POST-ORDER: аргументы, затем событие; число аргументов — в событии.
      for (const аргумент of в.аргументы) выражениеВЛенту(аргумент, л);
      л.push(
        КОД_СОБЫТИЯ.квалифицированный_вызов,
        в.позиция.начало,
        в.позиция.конец,
        в.позиция.строка,
        в.позиция.колонка,
        в.аргументы.length,
        КОД_СОБЫТИЯ.квалификация,
      );
      имяВЛенту(в.библиотека, л);
      имяВЛенту(в.функция, л);
      return;
  }
}

function операторВЛенту(о: Оператор, л: number[]): void {
  switch (о.вид) {
    case 'вернуть':
      // POST-ORDER: значение — ребёнок, событие возврата — после него.
      if (о.значение !== undefined) выражениеВЛенту(о.значение, л);
      л.push(
        КОД_СОБЫТИЯ.вернуть,
        о.позиция.начало,
        о.позиция.строка,
        о.позиция.колонка,
        о.значение === undefined ? о.позиция.начало + 7 : о.позиция.конец,
        о.значение === undefined ? 0 : 1,
      );
      return;
    case 'если': {
      // Условие — ребёнок: пишется ДО `если_начало`; тело — рамка начало/конец.
      выражениеВЛенту(о.условие, л);
      л.push(КОД_СОБЫТИЯ.если_начало, о.позиция.начало, о.позиция.строка, о.позиция.колонка, о.позиция.начало + 4);
      for (const оператор of о.тогда) операторВЛенту(оператор, л);
      let текущее: ВеткаЕсли = о;
      for (;;) {
        const следующее = единственныйИначеЕсли(текущее.иначе);
        if (следующее === undefined) break;
        // 3.0: конец ветви не пишется (он ещё не известен) — читатель берёт конец из `если_конец`.
        выражениеВЛенту(следующее.условие, л);
        л.push(КОД_СОБЫТИЯ.иначе_если, следующее.позиция.начало, следующее.позиция.строка, следующее.позиция.колонка);
        for (const оператор of следующее.тогда) операторВЛенту(оператор, л);
        текущее = следующее;
      }
      if (текущее.иначе !== undefined) {
        л.push(КОД_СОБЫТИЯ.иначе);
        for (const оператор of текущее.иначе) операторВЛенту(оператор, л);
      }
      л.push(КОД_СОБЫТИЯ.если_конец, о.позиция.конец);
      return;
    }
    case 'вызов':
      выражениеВЛенту(о.вызов, л);
      л.push(КОД_СОБЫТИЯ.вызов_оператор, о.позиция.начало, о.позиция.строка, о.позиция.колонка);
      return;
    case 'пусть':
      // POST-ORDER: значение, затем событие с именем/типом; `конец` известен — backpatch не нужен.
      выражениеВЛенту(о.значение, л);
      л.push(
        КОД_СОБЫТИЯ.пусть,
        о.позиция.начало,
        о.позиция.строка,
        о.позиция.колонка,
        о.позиция.конец,
        о.тип === undefined ? 0 : 1,
      );
      имяВЛенту(о.имя, л);
      if (о.тип !== undefined) типВЛенту(о.тип, л);
      return;
    case 'пока':
      // Условие — ребёнок: пишется ДО `пока_начало`; тело закрывается `пока_конец`.
      выражениеВЛенту(о.условие, л);
      л.push(КОД_СОБЫТИЯ.пока_начало, о.позиция.начало, о.позиция.строка, о.позиция.колонка);
      for (const оператор of о.тело) операторВЛенту(оператор, л);
      л.push(КОД_СОБЫТИЯ.пока_конец, о.позиция.конец);
      return;
    case 'присваивание':
      выражениеВЛенту(о.значение, л);
      л.push(
        КОД_СОБЫТИЯ.присваивание,
        о.позиция.начало,
        о.позиция.конец,
        о.позиция.строка,
        о.позиция.колонка,
      );
      имяВЛенту(о.имя, л);
      return;
  }
}

/** Ветка `если` (без `вернуть`/`вызов`/циклов) — для канонизации `иначе если`. */
type ВеткаЕсли = Extract<Оператор, { readonly вид: 'если' }>;

/**
 * `иначе` ровно из одного `если` — это `иначе если`. Возвращается вложенный узел, иначе `undefined`;
 * вызывающий пишет `иначе_если` и продолжает цепочку. Другие формы остаются вложенными.
 */
function единственныйИначеЕсли(иначе: readonly Оператор[] | undefined): ВеткаЕсли | undefined {
  if (иначе === undefined || иначе.length !== 1) return undefined;
  const только = иначе[0]!;
  return только.вид === 'если' ? только : undefined;
}

/**
 * Лента AST: заголовок, события в порядке обхода, `0`-терминатор.
 * Точный порядок — часть формата; оракул сравнивает числа побайтово.
 */
export function лентаИзAst(ast: AstФайл): number[] {
  if (ast.версия !== ВЕРСИЯ_AST_СТРОКА) {
    throw new Error(`версия AST «${ast.версия}» не поддерживается писателем ${ВЕРСИЯ_AST_СТРОКА}`);
  }
  for (const п of ast.процедуры) {
    if (п.контракт.требует.length > 0 || п.контракт.обеспечивает.length > 0 || п.контракт.эффекты.length > 0) {
      throw new Error('контракты D42 — AST 3.1: формат 3.0 их не пишет');
    }
  }
  const л = заголовок(ВИД_ЛЕНТЫ_AST, ast.модуль.имя, ast.модуль.позиция.конец, ast.версия);
  for (const п of ast.процедуры) {
    const код = п.действие ? КОД_СОБЫТИЯ.действие_начало : КОД_СОБЫТИЯ.процедура_начало;
    const ключ = п.действие ? 8 : 9;
    л.push(код, п.позиция.начало, п.позиция.строка, п.позиция.колонка, п.позиция.начало + ключ);
    имяВЛенту(п.имя, л);
    for (const параметр of п.параметры) {
      л.push(КОД_СОБЫТИЯ.параметр, параметр.позиция.начало, параметр.позиция.строка, параметр.позиция.колонка);
      имяВЛенту(параметр.имя, л);
      типВЛенту(параметр.тип, л);
      л.push(параметр.позиция.конец);
    }
    л.push(КОД_СОБЫТИЯ.процедура_заголовок, п.параметры.length, п.возвращает === null ? 0 : 1);
    if (п.возвращает !== null) типВЛенту(п.возвращает, л);
    for (const оператор of п.тело) операторВЛенту(оператор, л);
    л.push(КОД_СОБЫТИЯ.процедура_конец, п.позиция.конец);
  }
  л.push(КОД_СОБЫТИЯ.конец);
  return л;
}

/** Лента названного отказа: код, позиция, вид и лексема токена. */
export function лентаОшибки(ошибка: ОшибкаПарсера, модуль: string, конецМодуля = 0): number[] {
  const л = заголовок(ВИД_ЛЕНТЫ_ОШИБКА, модуль, конецМодуля);
  const код = коды(ошибка.код);
  л.push(код.length, ...код);
  л.push(ошибка.позиция.начало, ошибка.позиция.конец, ошибка.позиция.строка, ошибка.позиция.колонка);
  const вид = ошибка.видТокена === null ? [] : коды(ошибка.видТокена);
  л.push(вид.length, ...вид);
  const лексема = ошибка.лексема === null ? [] : коды(ошибка.лексема);
  л.push(лексема.length, ...лексема, КОД_СОБЫТИЯ.конец);
  return л;
}

