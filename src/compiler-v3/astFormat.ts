/**
 * ТИПИЗИРОВАННЫЙ AST ЯЗЫКА ОСНОВА, ФОРМАТ 1.1 — И ЕГО ДЕТЕРМИНИРОВАННАЯ ЛЕНТА.
 *
 * Формат 1.1 — расширение 1.0 (D58): `пусть`, `пока`, `действие`, зарезервированные события
 * контрактов D42. Читатель 1.1 понимает и 1.0, и 1.1; писатель 1.1 пишет 1.1. Лента 1.1 с
 * новыми событиями НЕ читается читателем 1.0 — это названный отказ по версии, а не тихая ложь.
 *
 * # Зачем отдельный модуль
 *
 * Это НЕ AST парсера v2 (`src/compiler/ast.ts`) и не parse tree. Это форма, в которой AST
 * уходит в три адресата сразу (решение владельца D50):
 *
 *   1. статический чекер фазы 1 (D42): контракты, типы, регион-дисциплина;
 *   2. AST-embedding в бинарь (Phase 0): секция, версия, детерминизм;
 *   3. recompile (Phase 1): достаточно информации, чтобы собрать программу заново.
 *
 * Поэтому здесь зафиксированы ТРИ вещи, и каждая проверяется оракулом:
 *
 *   • СТРУКТУРА (`AstФайл`) — типизированные узлы, а не токены и не «сырое дерево»;
 *   • ПОЗИЦИИ — в КОДОВЫХ ТОЧКАХ (не в байтах и не в UTF-16): `начало`, `конец`, `строка`,
 *     `колонка`, все 1-based там, где это номер;
 *   • ЛЕНТА (`лентаИзAst`) — плоская числовая запись, пригодная для встраивания в бинарь и для
 *     печати на цели e2k, где записей/структур нет вовсе.
 *
 * # Детерминизм (Phase 0)
 *
 * В формате НЕТ таймстампов, случайных id, путей и хэшей. Порядок процедур — порядок объявления;
 * параметры и аргументы — порядок исходника; поля объектов записываются в фиксированном порядке
 * (см. `канонизировать`), поэтому `каноническийJSON` одного AST побайтово одинаков на любой машине.
 * Стабильный id процедуры — `p<индекс>` в порядке объявления: он детерминирован для модуля, а не
 * «уникален во вселенной» (для межмодульных ссылок будет отдельная таблица, Phase 1).
 *
 * # Контракты — ЗАРЕЗЕРВИРОВАННЫЕ поля и события
 *
 * `требует` / `обеспечивает` / `эффекты` есть у каждой процедуры и пусты в v0.1: парсер их не
 * разбирает (D42: «заложено, не реализовано»). В 1.1 для них зарезервированы события ленты
 * `требует` / `обеспечивает` / `эффекты`; v0.1 их не пишет. Пустое поле — это НЕ «контракта нет»,
 * а «парсер v0.1 его не прочитал»; различие названо в `docs/ast-format.md`.
 *
 * # Версия
 *
 * `версия` в заголовке — `мажор.минор`. Мажор меняется при несовместимой правке структуры,
 * минор — при добавлении полей/видов без ломки читателя. Лента несёт те же числа (`1`, `1`),
 * поэтому читатель не обязан разбирать JSON, чтобы узнать версию.
 */

