/**
 * Позиция узла в КОДОВЫХ ТОЧКАХ.
 *
 * `начало` — смещение первой кодовой точки узла в исходнике (0-based);
 * `конец` — смещение СРАЗУ ЗА последней кодовой точкой (исключающая граница);
 * `строка` и `колонка` — 1-based, колонка тоже в кодовых точках.
 */
export interface Позиция {
  readonly начало: number;
  readonly конец: number;
  readonly строка: number;
  readonly колонка: number;
}

/**
 * Тип в AST. Имена (`Число`, `Строка`, `Логическое`, `Пусто`, `Ошибка`, пользовательские) —
 * отдельным видом `имя`; конструкторы `Список Т` и `Результат<Т, Е>` — своими видами, потому
 * что чекеру нужны их аргументы, а не строка.
 */
export type Тип =
  | { readonly вид: 'имя'; readonly имя: string }
  | { readonly вид: 'список'; readonly элемент: Тип }
  | { readonly вид: 'результат'; readonly успех: Тип; readonly ошибка: Тип };

/** Литерал: значение хранится ТОЧНО так, как его прочитал лексер. */
export type Литерал =
  | { readonly вид: 'число'; readonly текст: string }
  | { readonly вид: 'строка'; readonly значение: string }
  | { readonly вид: 'логическое'; readonly значение: boolean }
  | { readonly вид: 'пусто' };

