class Курсор {
  constructor(
    readonly числа: readonly number[],
    public и = 0,
  ) {}

  взять(что: string): number {
    if (this.и >= this.числа.length) throw new Error(`лента оборвалась: нужно ${что}, позиция ${String(this.и)}`);
    return this.числа[this.и++]!;
  }

  пик(): number {
    if (this.и >= this.числа.length) throw new Error('лента оборвалась: нужен пик');
    return this.числа[this.и]!;
  }

  строка(): string {
    const длина = this.взять('длину строки');
    if (длина < 0) throw new Error(`отрицательная длина строки ${String(длина)}`);
    const точки: number[] = [];
    for (let к = 0; к < длина; к++) точки.push(this.взять('кодовую точку'));
    return String.fromCodePoint(...точки);
  }

  позиция(): Позиция {
    return {
      начало: this.взять('начало позиции'),
      конец: this.взять('конец позиции'),
      строка: this.взять('строку позиции'),
      колонка: this.взять('колонку позиции'),
    };
  }

  /** Начало позиции составного узла: смещение, строка, колонка (конец придёт отдельно). */
  начало(): Omit<Позиция, 'конец'> {
    return {
      начало: this.взять('начало позиции'),
      строка: this.взять('строку позиции'),
      колонка: this.взять('колонку позиции'),
    };
  }
}

function типИзЛенты(к: Курсор): Тип {
  const вид = к.взять('вид типа');
  if (вид === КОД_ТИПА.имя) return { вид: 'имя', имя: к.строка() };
  if (вид === КОД_ТИПА.список) return { вид: 'список', элемент: типИзЛенты(к) };
  if (вид === КОД_ТИПА.результат) return { вид: 'результат', успех: типИзЛенты(к), ошибка: типИзЛенты(к) };
  throw new Error(`неизвестный вид типа ${String(вид)}`);
}

function литералИзЛенты(к: Курсор): Литерал {
  const вид = к.взять('вид литерала');
  if (вид === КОД_ЛИТЕРАЛА.число) return { вид: 'число', текст: к.строка() };
  if (вид === КОД_ЛИТЕРАЛА.строка) return { вид: 'строка', значение: к.строка() };
  if (вид === КОД_ЛИТЕРАЛА.логическое) return { вид: 'логическое', значение: к.взять('значение логического') === 1 };
  if (вид === КОД_ЛИТЕРАЛА.пусто) return { вид: 'пусто' };
  throw new Error(`неизвестный вид литерала ${String(вид)}`);
}

/** Событие выражения 3.0: значение кладётся на стек, а не читается рекурсией. */
function событиеВыражения(вид: number): boolean {
  return (
    вид === КОД_СОБЫТИЯ.литерал ||
    вид === КОД_СОБЫТИЯ.имя ||
    вид === КОД_СОБЫТИЯ.вызов_начало ||
    вид === КОД_СОБЫТИЯ.список_начало ||
    вид === КОД_СОБЫТИЯ.квалифицированный_вызов ||
    вид === КОД_СОБЫТИЯ.индексация ||
    БИНАРНЫЙ_ПО_КОДУ[вид] !== undefined ||
    УНАРНЫЙ_ПО_КОДУ[вид] !== undefined
  );
}

function взятьВыражение(стек: Выражение[], что: string): Выражение {
  const значение = стек.pop();
  if (значение === undefined) throw new Error(`лента 3.0: для «${что}» нет выражения на стеке`);
  return значение;
}

function взятьВыражений(стек: Выражение[], сколько: number, что: string): Выражение[] {
  if (стек.length < сколько) {
    throw new Error(`лента 3.0: «${что}» обещает ${String(сколько)} детей, на стеке ${String(стек.length)}`);
  }
  return стек.splice(стек.length - сколько, сколько);
}

/**
 * Один шаг стека выражений 3.0: лист кладёт значение, оператор снимает детей со стека.
 * Никакой рекурсии по ленте — дети уже прочитаны, потому что идут раньше родителя.
 */
function обработатьВыражение(к: Курсор, стек: Выражение[]): void {
  const вид = к.взять('вид выражения');
  if (вид === КОД_СОБЫТИЯ.литерал) {
    const позиция = к.позиция();
    стек.push({ вид: 'литерал', литерал: литералИзЛенты(к), позиция });
    return;
  }
  if (вид === КОД_СОБЫТИЯ.имя) {
    const позиция = к.позиция();
    стек.push({ вид: 'имя', имя: к.строка(), позиция });
    return;
  }
  if (вид === КОД_СОБЫТИЯ.вызов_начало) {
    const начало = к.начало();
    const имя = к.строка();
    if (к.взять('конец вызова') !== КОД_СОБЫТИЯ.вызов_конец) throw new Error('ожидался конец вызова');
    const объявлено = к.взять('число аргументов');
    const конец = к.взять('конец позиции вызова');
    const аргументы = взятьВыражений(стек, объявлено, `вызов «${имя}»`);
    стек.push({ вид: 'вызов', имя, аргументы, позиция: { ...начало, конец } });
    return;
  }
  if (вид === КОД_СОБЫТИЯ.список_начало) {
    const начало = к.начало();
    if (к.взять('конец списка') !== КОД_СОБЫТИЯ.список_конец) throw new Error('ожидался конец списка');
    const объявлено = к.взять('число элементов списка');
    const конец = к.взять('конец позиции списка');
    const элементы = взятьВыражений(стек, объявлено, 'список');
    стек.push({ вид: 'список', элементы, позиция: { ...начало, конец } });
    return;
  }
  if (вид === КОД_СОБЫТИЯ.квалифицированный_вызов) {
    const позиция = к.позиция();
    const объявлено = к.взять('число аргументов квалифицированного вызова');
    if (к.взять('квалификация') !== КОД_СОБЫТИЯ.квалификация) throw new Error('ожидалась квалификация');
    const библиотека = к.строка();
    const функция = к.строка();
    const аргументы = взятьВыражений(стек, объявлено, `вызов «${библиотека}.${функция}»`);
    стек.push({ вид: 'квалифицированный_вызов', библиотека, функция, аргументы, позиция });
    return;
  }
  if (вид === КОД_СОБЫТИЯ.индексация) {
    const позиция = к.позиция();
    const индекс = взятьВыражение(стек, 'индекс индексации');
    const база = взятьВыражение(стек, 'база индексации');
    стек.push({ вид: 'индексация', база, индекс, позиция });
    return;
  }
  const бинарный = БИНАРНЫЙ_ПО_КОДУ[вид];
  if (бинарный !== undefined) {
    const позиция = к.позиция();
    const правый = взятьВыражение(стек, `правый операнд «${бинарный}»`);
    const левый = взятьВыражение(стек, `левый операнд «${бинарный}»`);
    стек.push({ вид: 'бинарное', оператор: бинарный, левый, правый, позиция });
    return;
  }
  const унарный = УНАРНЫЙ_ПО_КОДУ[вид];
  if (унарный !== undefined) {
    const позиция = к.позиция();
    const операнд = взятьВыражение(стек, `операнд «${унарный}»`);
    стек.push({ вид: 'унарное', оператор: унарный, операнд, позиция });
    return;
  }
  throw new Error(`неизвестный вид выражения ${String(вид)}`);
}

/**
 * Блок 3.0: события читаются подряд, выражения копятся на стеке, операторы снимают своих детей.
 * `стек` передаётся снаружи: условие `иначе если` набирается в теле предыдущей ветви и снимается
 * событием `иначе_если`.
 */
function блокИзЛенты(к: Курсор, стоп: readonly number[], стек: Выражение[] = []): Оператор[] {
  const операторы: Оператор[] = [];
  while (!стоп.includes(к.пик())) {
    const вид = к.пик();
    if (событиеВыражения(вид)) {
      обработатьВыражение(к, стек);
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.вернуть) {
      к.взять('вид возврата');
      const начало = к.начало();
      const конецТокена = к.взять('конец токена возврата');
      const есть = к.взять('признак значения возврата');
      const значение = есть === 1 ? взятьВыражение(стек, 'значение возврата') : undefined;
      const конец = значение === undefined ? конецТокена : Math.max(конецТокена, значение.позиция.конец);
      операторы.push(
        значение === undefined
          ? { вид: 'вернуть', позиция: { ...начало, конец } }
          : { вид: 'вернуть', значение, позиция: { ...начало, конец } },
      );
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.если_начало) {
      const условие = взятьВыражение(стек, 'условие если');
      к.взять('если_начало');
      const начало = к.начало();
      к.взять('конец токена «если»');
      const стопВетви = [КОД_СОБЫТИЯ.иначе, КОД_СОБЫТИЯ.иначе_если, КОД_СОБЫТИЯ.если_конец] as const;
      const тогда = блокИзЛенты(к, стопВетви, стек);
      const ветви: {
        позиция: { начало: number; строка: number; колонка: number };
        условие: Выражение;
        тогда: Оператор[];
      }[] = [];
      while (к.пик() === КОД_СОБЫТИЯ.иначе_если) {
        const условиеВетви = взятьВыражение(стек, 'условие иначе если');
        к.взять('иначе если');
        const позицияВетви = к.начало();
        const телоВетви = блокИзЛенты(к, стопВетви, стек);
        ветви.push({ позиция: позицияВетви, условие: условиеВетви, тогда: телоВетви });
      }
      let иначе: Оператор[] | undefined;
      if (к.пик() === КОД_СОБЫТИЯ.иначе) {
        if (стек.length !== 0) throw new Error('лента 3.0: перед «иначе» остались выражения');
        к.взять('иначе');
        иначе = блокИзЛенты(к, [КОД_СОБЫТИЯ.если_конец], стек);
      }
      if (к.взять('конец если') !== КОД_СОБЫТИЯ.если_конец) throw new Error('ожидался конец «если»');
      const конец = к.взять('конец позиции «если»');
      if (стек.length !== 0) throw new Error('лента 3.0: после «конец если» остались выражения');
      let вложенноеИначе = иначе;
      for (let и = ветви.length - 1; и >= 0; и--) {
        const ветвь = ветви[и]!;
        const узел: Оператор =
          вложенноеИначе === undefined
            ? { вид: 'если', условие: ветвь.условие, тогда: ветвь.тогда, позиция: { ...ветвь.позиция, конец } }
            : {
                вид: 'если',
                условие: ветвь.условие,
                тогда: ветвь.тогда,
                иначе: вложенноеИначе,
                позиция: { ...ветвь.позиция, конец },
              };
        вложенноеИначе = [узел];
      }
      операторы.push(
        вложенноеИначе === undefined
          ? { вид: 'если', условие, тогда, позиция: { ...начало, конец } }
          : { вид: 'если', условие, тогда, иначе: вложенноеИначе, позиция: { ...начало, конец } },
      );
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.вызов_оператор) {
      const вызов = взятьВыражение(стек, 'вызов-оператор');
      к.взять('вызов_оператор');
      const начало = к.начало();
      if (вызов.вид !== 'вызов' && вызов.вид !== 'квалифицированный_вызов') {
        throw new Error('вызов-оператор обязан содержать вызов');
      }
      операторы.push({ вид: 'вызов', вызов, позиция: { ...начало, конец: вызов.позиция.конец } });
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.пусть) {
      const значение = взятьВыражение(стек, 'значение «пусть»');
      к.взять('пусть');
      const начало = к.начало();
      const конец = к.взять('конец локальной');
      const естьТип = к.взять('признак типа локальной');
      const имя = к.строка();
      const тип = естьТип === 1 ? типИзЛенты(к) : undefined;
      операторы.push({
        вид: 'пусть',
        имя,
        ...(тип === undefined ? {} : { тип }),
        значение,
        позиция: { ...начало, конец },
      });
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.пока_начало) {
      const условие = взятьВыражение(стек, 'условие «пока»');
      к.взять('пока_начало');
      const начало = к.начало();
      const тело = блокИзЛенты(к, [КОД_СОБЫТИЯ.пока_конец], стек);
      if (к.взять('конец пока') !== КОД_СОБЫТИЯ.пока_конец) throw new Error('ожидался конец «пока»');
      const конец = к.взять('конец позиции «пока»');
      if (стек.length !== 0) throw new Error('лента 3.0: после «конец пока» остались выражения');
      операторы.push({ вид: 'пока', условие, тело, позиция: { ...начало, конец } });
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.присваивание) {
      const значение = взятьВыражение(стек, 'значение присваивания');
      к.взять('присваивание');
      const позиция = к.позиция();
      const имя = к.строка();
      операторы.push({ вид: 'присваивание', имя, значение, позиция });
      continue;
    }
    throw new Error(`неизвестный вид оператора ${String(вид)}`);
  }
  return операторы;
}

function прочитатьAst(к: Курсор, модуль: string, конецМодуля: number, версия: string): AstФайл {
  const процедуры: Процедура[] = [];
  while (к.пик() !== КОД_СОБЫТИЯ.конец) {
    const код = к.взять('начало процедуры');
    if (код !== КОД_СОБЫТИЯ.процедура_начало && код !== КОД_СОБЫТИЯ.действие_начало) {
      throw new Error('ожидалось начало процедуры');
    }
    const действие = код === КОД_СОБЫТИЯ.действие_начало;
    const начало = к.начало();
    к.взять(действие ? 'конец токена «действие»' : 'конец токена «процедура»');
    const имя = к.строка();
    const параметры: Параметр[] = [];
    while (к.пик() === КОД_СОБЫТИЯ.параметр) {
      к.взять('параметр');
      const началоПараметра = к.начало();
      const имяПараметра = к.строка();
      const тип = типИзЛенты(к);
      const конец = к.взять('конец параметра');
      параметры.push({ имя: имяПараметра, тип, позиция: { ...началоПараметра, конец } });
    }
    if (к.взять('заголовок процедуры') !== КОД_СОБЫТИЯ.процедура_заголовок) throw new Error('ожидался конец заголовка');
    const объявлено = к.взять('число параметров');
    const естьВозврат = к.взять('признак возврата');
    if (действие && естьВозврат === 1) throw new Error('«действие» не возвращает значение (D53)');
    const возвращает = естьВозврат === 1 ? типИзЛенты(к) : null;
    if (параметры.length !== объявлено) {
      throw new Error(`процедура «${имя}»: обещано ${String(объявлено)} параметров, разобрано ${String(параметры.length)}`);
    }
    const стек: Выражение[] = [];
    const тело = блокИзЛенты(к, [КОД_СОБЫТИЯ.процедура_конец], стек);
    if (стек.length !== 0) throw new Error(`процедура «${имя}»: в теле остались выражения без оператора`);
    if (к.взять('конец процедуры') !== КОД_СОБЫТИЯ.процедура_конец) throw new Error('ожидался конец процедуры');
    const конец = к.взять('конец позиции процедуры');
    процедуры.push({
      id: `p${String(процедуры.length)}`,
      имя,
      действие,
      параметры,
      возвращает,
      тело,
      контракт: пустойКонтракт(),
      позиция: { ...начало, конец },
    });
  }
  к.взять('конец ленты');
  return {
    формат: ФОРМАТ_AST,
    версия,
    модуль: { имя: модуль, позиция: { начало: 0, конец: конецМодуля, строка: 1, колонка: 1 } },
    процедуры,
  };
}

/** Версия читателя: 3.0 читает только 3.0; 2.x/1.1 — только свои (история формата). */
export interface ВерсияФормата {
  readonly мажор: number;
  readonly минор: number;
}

/** Лента 3.0 не читается читателем 2.x — это названный отказ, а не «попробуем». */
function поддерживаетВерсию(мажор: number, минор: number, читатель: ВерсияФормата): boolean {
  if (читатель.мажор === 3) return мажор === 3 && минор === 0;
  if (читатель.мажор === 2) {
    return (мажор === 1 && минор >= 0 && минор <= 1) || (мажор === 2 && минор >= 0 && минор <= читатель.минор);
  }
  if (читатель.мажор === 1) return мажор === 1 && минор >= 0 && минор <= 1;
  return false;
}

/** Чтение ленты: либо AST, либо названный отказ, либо исключение на битой ленте. */
export function прочитатьЛенту(
  числа: readonly number[],
  читатель: ВерсияФормата = ВЕРСИЯ_AST,
): { readonly ок: true; readonly ast: AstФайл } | { readonly ок: false; readonly ошибка: ОшибкаПарсера } {
  const к = new Курсор(числа);
  if (к.взять('магию') !== МАГИЯ_ЛЕНТЫ) throw new Error('лента не начинается с магии формата');
  const мажор = к.взять('мажор');
  const минор = к.взять('минор');
  if (!поддерживаетВерсию(мажор, минор, читатель)) {
    const код =
      мажор < 3 && читатель.мажор >= 3 ? КОДЫ_ОШИБОК.версияAstБезКонвертации : КОДЫ_ОШИБОК.версияAst;
    return {
      ок: false,
      ошибка: {
        код,
        сообщение: сообщениеОшибки(код, null),
        позиция: { начало: 0, конец: 0, строка: 1, колонка: 1 },
        видТокена: null,
        лексема: null,
      },
    };
  }
  const версия = `${String(мажор)}.${String(минор)}`;
  const вид = к.взять('вид ленты');
  const модуль = к.строка();
  const конецМодуля = к.взять('конец модуля');
  if (вид === ВИД_ЛЕНТЫ_AST) return { ок: true, ast: прочитатьAst(к, модуль, конецМодуля, версия) };
  if (вид === ВИД_ЛЕНТЫ_ОШИБКА) {
    const код = к.строка() as КодОшибки;
    const позиция = к.позиция();
    const видТокена = к.строка();
    const лексема = к.строка();
    if (к.взять('конец ошибки') !== КОД_СОБЫТИЯ.конец) throw new Error('лента ошибки не закрыта');
    return {
      ок: false,
      ошибка: {
        код,
        сообщение: сообщениеОшибки(код, лексема === '' ? null : лексема),
        позиция,
        видТокена: видТокена === '' ? null : видТокена,
        лексема: лексема === '' ? null : лексема,
      },
    };
  }
  throw new Error(`неизвестный вид ленты ${String(вид)}`);
}

/** Глубокое сравнение AST: первое расхождение названо путём, а не «не равно». */
export function сравнитьAst(факт: AstФайл, эталон: AstФайл): string[] {
  const расхождения: string[] = [];
  const сравнить = (а: unknown, б: unknown, путь: string): void => {
    if (расхождения.length >= 20) return;
    if (Array.isArray(а) && Array.isArray(б)) {
      if (а.length !== б.length) расхождения.push(`${путь}: длина ${String(а.length)} ≠ ${String(б.length)}`);
      const дл = Math.min(а.length, б.length);
      for (let и = 0; и < дл; и++) сравнить(а[и], б[и], `${путь}[${String(и)}]`);
      return;
    }
    if (а !== null && б !== null && typeof а === 'object' && typeof б === 'object') {
      const ао = а as Record<string, unknown>;
      const бо = б as Record<string, unknown>;
      const ключи = new Set([...Object.keys(ао), ...Object.keys(бо)]);
      for (const ключ of ключи) {
        if (!(ключ in ао)) расхождения.push(`${путь}.${ключ}: в факте нет`);
        else if (!(ключ in бо)) расхождения.push(`${путь}.${ключ}: в эталоне нет`);
        else сравнить(ао[ключ], бо[ключ], `${путь}.${ключ}`);
      }
      return;
    }
    if (а !== б) расхождения.push(`${путь}: ${JSON.stringify(а)} ≠ ${JSON.stringify(б)}`);
  };
  сравнить(канонизировать(факт), канонизировать(эталон), '$');
  return расхождения;
}
