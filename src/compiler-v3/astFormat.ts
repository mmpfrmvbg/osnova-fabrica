const коды = (с: string): number[] => [...с].map((символ) => символ.codePointAt(0)!);

/** Заголовок ленты: магия, версия, вид, имя модуля. */
function заголовок(вид: number, модуль: string, конецМодуля: number, версия = `${ВЕРСИЯ_AST.мажор}.${ВЕРСИЯ_AST.минор}`): number[] {
  const [мажор, минор] = версия.split('.').map(Number);
  if (!Number.isInteger(мажор) || !Number.isInteger(минор)) throw new Error(`неверная версия ленты «${версия}»`);
  const точки = коды(модуль);
  return [МАГИЯ_ЛЕНТЫ, мажор!, минор!, вид, точки.length, ...точки, конецМодуля];
}

function типВЛенту(т: Тип, в: number[]): void {
  switch (т.вид) {
    case 'имя': {
      const точки = коды(т.имя);
      в.push(КОД_ТИПА.имя, точки.length, ...точки);
      return;
    }
    case 'список':
      в.push(КОД_ТИПА.список);
      типВЛенту(т.элемент, в);
      return;
    case 'результат':
      в.push(КОД_ТИПА.результат);
      типВЛенту(т.успех, в);
      типВЛенту(т.ошибка, в);
      return;
  }
}

function литералВЛенту(л: Литерал, в: number[]): void {
  switch (л.вид) {
    case 'число': {
      const точки = коды(л.текст);
      в.push(КОД_ЛИТЕРАЛА.число, точки.length, ...точки);
      return;
    }
    case 'строка': {
      const точки = коды(л.значение);
      в.push(КОД_ЛИТЕРАЛА.строка, точки.length, ...точки);
      return;
    }
    case 'логическое':
      в.push(КОД_ЛИТЕРАЛА.логическое, л.значение ? 1 : 0);
      return;
    case 'пусто':
      в.push(КОД_ЛИТЕРАЛА.пусто);
      return;
  }
}

function имяВЛенту(имя: string, в: number[]): void {
  const точки = коды(имя);
  в.push(точки.length, ...точки);
}

function выражениеВЛенту(в: Выражение, л: number[]): void {
  switch (в.вид) {
    case 'литерал':
      л.push(КОД_СОБЫТИЯ.литерал, в.позиция.начало, в.позиция.конец, в.позиция.строка, в.позиция.колонка);
      литералВЛенту(в.литерал, л);
      return;
    case 'имя':
      л.push(КОД_СОБЫТИЯ.имя, в.позиция.начало, в.позиция.конец, в.позиция.строка, в.позиция.колонка);
      имяВЛенту(в.имя, л);
      return;
    case 'вызов':
      л.push(КОД_СОБЫТИЯ.вызов_начало, в.позиция.начало, в.позиция.строка, в.позиция.колонка);
      имяВЛенту(в.имя, л);
      for (const аргумент of в.аргументы) выражениеВЛенту(аргумент, л);
      л.push(КОД_СОБЫТИЯ.вызов_конец, в.аргументы.length, в.позиция.конец);
      return;
  }
}

function операторВЛенту(о: Оператор, л: number[]): void {
  switch (о.вид) {
    case 'вернуть':
      л.push(
        КОД_СОБЫТИЯ.вернуть,
        о.позиция.начало,
        о.позиция.строка,
        о.позиция.колонка,
        о.значение === undefined ? о.позиция.начало + 7 : о.позиция.конец,
        о.значение === undefined ? 0 : 1,
      );
      if (о.значение !== undefined) выражениеВЛенту(о.значение, л);
      return;
    case 'если':
      л.push(КОД_СОБЫТИЯ.если_начало, о.позиция.начало, о.позиция.строка, о.позиция.колонка, о.позиция.начало + 4);
      выражениеВЛенту(о.условие, л);
      for (const оператор of о.тогда) операторВЛенту(оператор, л);
      if (о.иначе !== undefined) {
        л.push(КОД_СОБЫТИЯ.иначе);
        for (const оператор of о.иначе) операторВЛенту(оператор, л);
      }
      л.push(КОД_СОБЫТИЯ.если_конец, о.позиция.конец);
      return;
    case 'вызов':
      л.push(КОД_СОБЫТИЯ.вызов_оператор, о.позиция.начало, о.позиция.строка, о.позиция.колонка);
      выражениеВЛенту(о.вызов, л);
      return;
    case 'пусть':
      // `конец` локальной = конец выражения/типа. В потоке это pre-order, поэтому target-парсер
      // обязан поставить заглушку и пропатчить её (см. `docs/parser-protocol.md` §3).
      л.push(
        КОД_СОБЫТИЯ.пусть,
        о.позиция.начало,
        о.позиция.строка,
        о.позиция.колонка,
        о.позиция.конец,
        о.тип === undefined ? 0 : 1,
      );
      имяВЛенту(о.имя, л);
      if (о.тип !== undefined) типВЛенту(о.тип, л);
      выражениеВЛенту(о.значение, л);
      return;
    case 'пока':
      // У `пока_начало` НЕТ конца условия: иначе он был бы ещё одним pre-order полем и требовал
      // бы третьего backpatch. Условие несёт свою позицию, тело закрывается `пока_конец`.
      л.push(КОД_СОБЫТИЯ.пока_начало, о.позиция.начало, о.позиция.строка, о.позиция.колонка);
      выражениеВЛенту(о.условие, л);
      for (const оператор of о.тело) операторВЛенту(оператор, л);
      л.push(КОД_СОБЫТИЯ.пока_конец, о.позиция.конец);
      return;
  }
}

function контрактВЛенту(к: Контракт, л: number[]): void {
  if (к.требует.length > 0) {
    л.push(КОД_СОБЫТИЯ.требует, к.требует.length);
    for (const выражение of к.требует) выражениеВЛенту(выражение, л);
  }
  if (к.обеспечивает.length > 0) {
    л.push(КОД_СОБЫТИЯ.обеспечивает, к.обеспечивает.length);
    for (const выражение of к.обеспечивает) выражениеВЛенту(выражение, л);
  }
  if (к.эффекты.length > 0) {
    л.push(КОД_СОБЫТИЯ.эффекты, к.эффекты.length);
    for (const эффект of к.эффекты) имяВЛенту(эффект, л);
  }
}

/**
 * Лента AST: заголовок, события в порядке обхода, `0`-терминатор.
 * Точный порядок — часть формата; оракул сравнивает числа побайтово.
 */
export function лентаИзAst(ast: AstФайл): number[] {
  if (ast.версия !== '1.0' && ast.версия !== '1.1') {
    throw new Error(`версия AST «${ast.версия}» не поддерживается писателем 1.1`);
  }
  const имеетНовое =
    ast.процедуры.some((п) => п.действие || п.контракт.требует.length > 0 || п.контракт.обеспечивает.length > 0 || п.контракт.эффекты.length > 0) ||
    ast.процедуры.some((п) => п.тело.some(содержитНовое));
  if (ast.версия === '1.0' && имеетНовое) {
    throw new Error('AST 1.0 не представляет `пусть`/`пока`/`действие`/контракты: нужна версия 1.1');
  }
  const л = заголовок(ВИД_ЛЕНТЫ_AST, ast.модуль.имя, ast.модуль.позиция.конец, ast.версия);
  for (const п of ast.процедуры) {
    const код = п.действие ? КОД_СОБЫТИЯ.действие_начало : КОД_СОБЫТИЯ.процедура_начало;
    const ключ = п.действие ? 8 : 9;
    л.push(код, п.позиция.начало, п.позиция.строка, п.позиция.колонка, п.позиция.начало + ключ);
    имяВЛенту(п.имя, л);
    for (const параметр of п.параметры) {
      л.push(КОД_СОБЫТИЯ.параметр, параметр.позиция.начало, параметр.позиция.строка, параметр.позиция.колонка);
      имяВЛенту(параметр.имя, л);
      типВЛенту(параметр.тип, л);
      л.push(параметр.позиция.конец);
    }
    л.push(КОД_СОБЫТИЯ.процедура_заголовок, п.параметры.length, п.возвращает === null ? 0 : 1);
    if (п.возвращает !== null) типВЛенту(п.возвращает, л);
    контрактВЛенту(п.контракт, л);
    for (const оператор of п.тело) операторВЛенту(оператор, л);
    л.push(КОД_СОБЫТИЯ.процедура_конец, п.позиция.конец);
  }
  л.push(КОД_СОБЫТИЯ.конец);
  return л;
}

/** Есть ли в операторе новое для 1.1 событие (для запрета writer 1.0). */
function содержитНовое(о: Оператор): boolean {
  switch (о.вид) {
    case 'пусть':
    case 'пока':
      return true;
    case 'если':
      return о.тогда.some(содержитНовое) || (о.иначе?.some(содержитНовое) ?? false);
    case 'вернуть':
      return false;
    case 'вызов':
      return false;
  }
}

/** Лента названного отказа: код, позиция, вид и лексема токена. */
export function лентаОшибки(ошибка: ОшибкаПарсера, модуль: string, конецМодуля = 0): number[] {
  const л = заголовок(ВИД_ЛЕНТЫ_ОШИБКА, модуль, конецМодуля);
  const код = коды(ошибка.код);
  л.push(код.length, ...код);
  л.push(ошибка.позиция.начало, ошибка.позиция.конец, ошибка.позиция.строка, ошибка.позиция.колонка);
  const вид = ошибка.видТокена === null ? [] : коды(ошибка.видТокена);
  л.push(вид.length, ...вид);
  const лексема = ошибка.лексема === null ? [] : коды(ошибка.лексема);
  л.push(лексема.length, ...лексема, КОД_СОБЫТИЯ.конец);
  return л;
}

// ── Чтение ленты ───────────────────────────────────────────────────────────────────────────────

class Курсор {
  constructor(
    readonly числа: readonly number[],
    public и = 0,
  ) {}

  взять(что: string): number {
    if (this.и >= this.числа.length) throw new Error(`лента оборвалась: нужно ${что}, позиция ${String(this.и)}`);
    return this.числа[this.и++]!;
  }

  пик(): number {
    if (this.и >= this.числа.length) throw new Error('лента оборвалась: нужен пик');
    return this.числа[this.и]!;
  }

  строка(): string {
    const длина = this.взять('длину строки');
    if (длина < 0) throw new Error(`отрицательная длина строки ${String(длина)}`);
    const точки: number[] = [];
    for (let к = 0; к < длина; к++) точки.push(this.взять('кодовую точку'));
    return String.fromCodePoint(...точки);
  }

  позиция(): Позиция {
    return {
      начало: this.взять('начало позиции'),
      конец: this.взять('конец позиции'),
      строка: this.взять('строку позиции'),
      колонка: this.взять('колонку позиции'),
    };
  }

  /** Начало позиции составного узла: смещение, строка, колонка (конец придёт отдельно). */
  начало(): Omit<Позиция, 'конец'> {
    return {
      начало: this.взять('начало позиции'),
      строка: this.взять('строку позиции'),
      колонка: this.взять('колонку позиции'),
    };
  }
}

function типИзЛенты(к: Курсор): Тип {
  const вид = к.взять('вид типа');
  if (вид === КОД_ТИПА.имя) return { вид: 'имя', имя: к.строка() };
  if (вид === КОД_ТИПА.список) return { вид: 'список', элемент: типИзЛенты(к) };
  if (вид === КОД_ТИПА.результат) return { вид: 'результат', успех: типИзЛенты(к), ошибка: типИзЛенты(к) };
  throw new Error(`неизвестный вид типа ${String(вид)}`);
}

function литералИзЛенты(к: Курсор): Литерал {
  const вид = к.взять('вид литерала');
  if (вид === КОД_ЛИТЕРАЛА.число) return { вид: 'число', текст: к.строка() };
  if (вид === КОД_ЛИТЕРАЛА.строка) return { вид: 'строка', значение: к.строка() };
  if (вид === КОД_ЛИТЕРАЛА.логическое) return { вид: 'логическое', значение: к.взять('значение логического') === 1 };
  if (вид === КОД_ЛИТЕРАЛА.пусто) return { вид: 'пусто' };
  throw new Error(`неизвестный вид литерала ${String(вид)}`);
}

function выражениеИзЛенты(к: Курсор): Выражение {
  const вид = к.взять('вид выражения');
  if (вид === КОД_СОБЫТИЯ.литерал) {
    const позиция = к.позиция();
    return { вид: 'литерал', литерал: литералИзЛенты(к), позиция };
  }
  if (вид === КОД_СОБЫТИЯ.имя) {
    const позиция = к.позиция();
    return { вид: 'имя', имя: к.строка(), позиция };
  }
  if (вид === КОД_СОБЫТИЯ.вызов_начало) {
    const начало = к.начало();
    const имя = к.строка();
    const аргументы: Выражение[] = [];
    while (к.пик() !== КОД_СОБЫТИЯ.вызов_конец) аргументы.push(выражениеИзЛенты(к));
    к.взять('конец вызова');
    const объявлено = к.взять('число аргументов');
    const конец = к.взять('конец позиции вызова');
    if (объявлено !== аргументы.length) {
      throw new Error(`вызов «${имя}»: обещано ${String(объявлено)} аргументов, разобрано ${String(аргументы.length)}`);
    }
    return { вид: 'вызов', имя, аргументы, позиция: { ...начало, конец } };
  }
  throw new Error(`неизвестный вид выражения ${String(вид)}`);
}

function блокИзЛенты(к: Курсор, стоп: readonly number[], минор: number): Оператор[] {
  const операторы: Оператор[] = [];
  while (!стоп.includes(к.пик())) операторы.push(операторИзЛенты(к, минор));
  return операторы;
}

function операторИзЛенты(к: Курсор, минор: number): Оператор {
  const вид = к.взять('вид оператора');
  if (вид === КОД_СОБЫТИЯ.вернуть) {
    const начало = к.начало();
    const конецТокена = к.взять('конец токена возврата');
    const есть = к.взять('признак значения возврата');
    const значение = есть === 1 ? выражениеИзЛенты(к) : undefined;
    const конец = значение === undefined ? конецТокена : Math.max(конецТокена, значение.позиция.конец);
    return значение === undefined
      ? { вид: 'вернуть', позиция: { ...начало, конец } }
      : { вид: 'вернуть', значение, позиция: { ...начало, конец } };
  }
  if (вид === КОД_СОБЫТИЯ.если_начало) {
    const начало = к.начало();
    к.взять('конец токена «если»');
    const условие = выражениеИзЛенты(к);
    const тогда = блокИзЛенты(к, [КОД_СОБЫТИЯ.иначе, КОД_СОБЫТИЯ.если_конец], минор);
    let иначе: Оператор[] | undefined;
    if (к.пик() === КОД_СОБЫТИЯ.иначе) {
      к.взять('иначе');
      иначе = блокИзЛенты(к, [КОД_СОБЫТИЯ.если_конец], минор);
    }
    if (к.взять('конец если') !== КОД_СОБЫТИЯ.если_конец) throw new Error('ожидался конец «если»');
    const конец = к.взять('конец позиции «если»');
    return иначе === undefined
      ? { вид: 'если', условие, тогда, позиция: { ...начало, конец } }
      : { вид: 'если', условие, тогда, иначе, позиция: { ...начало, конец } };
  }
  if (вид === КОД_СОБЫТИЯ.вызов_оператор) {
    const начало = к.начало();
    const вызов = выражениеИзЛенты(к);
    if (вызов.вид !== 'вызов') throw new Error('вызов-оператор обязан содержать вызов');
    return { вид: 'вызов', вызов, позиция: { ...начало, конец: вызов.позиция.конец } };
  }
  if (вид === КОД_СОБЫТИЯ.пусть) {
    if (минор < 1) throw new Error('событие `пусть` требует формата 1.1');
    const начало = к.начало();
    const конец = к.взять('конец локальной');
    const естьТип = к.взять('признак типа локальной');
    const имя = к.строка();
    const тип = естьТип === 1 ? типИзЛенты(к) : undefined;
    const значение = выражениеИзЛенты(к);
    return { вид: 'пусть', имя, ...(тип === undefined ? {} : { тип }), значение, позиция: { ...начало, конец } };
  }
  if (вид === КОД_СОБЫТИЯ.пока_начало) {
    if (минор < 1) throw new Error('событие `пока` требует формата 1.1');
    const начало = к.начало();
    const условие = выражениеИзЛенты(к);
    const тело = блокИзЛенты(к, [КОД_СОБЫТИЯ.пока_конец], минор);
    if (к.взять('конец пока') !== КОД_СОБЫТИЯ.пока_конец) throw new Error('ожидался конец «пока»');
    const конец = к.взять('конец позиции «пока»');
    return { вид: 'пока', условие, тело, позиция: { ...начало, конец } };
  }
  throw new Error(`неизвестный вид оператора ${String(вид)}`);
}

function контрактИзЛенты(к: Курсор): Контракт {
  const контракт = { требует: [] as Выражение[], обеспечивает: [] as Выражение[], эффекты: [] as string[] };
  for (;;) {
    const вид = к.пик();
    if (вид === КОД_СОБЫТИЯ.требует) {
      к.взять('требует');
      const число = к.взять('число «требует»');
      for (let и = 0; и < число; и++) контракт.требует.push(выражениеИзЛенты(к));
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.обеспечивает) {
      к.взять('обеспечивает');
      const число = к.взять('число «обеспечивает»');
      for (let и = 0; и < число; и++) контракт.обеспечивает.push(выражениеИзЛенты(к));
      continue;
    }
    if (вид === КОД_СОБЫТИЯ.эффекты) {
      к.взять('эффекты');
      const число = к.взять('число эффектов');
      for (let и = 0; и < число; и++) контракт.эффекты.push(к.строка());
      continue;
    }
    return контракт;
  }
}

function прочитатьAst(к: Курсор, модуль: string, конецМодуля: number, версия: string, минор: number): AstФайл {
  const процедуры: Процедура[] = [];
  while (к.пик() !== КОД_СОБЫТИЯ.конец) {
    const код = к.взять('начало процедуры');
    if (код !== КОД_СОБЫТИЯ.процедура_начало && код !== КОД_СОБЫТИЯ.действие_начало) {
      throw new Error('ожидалось начало процедуры');
    }
    if (код === КОД_СОБЫТИЯ.действие_начало && минор < 1) {
      throw new Error('событие `действие_начало` требует формата 1.1');
    }
    const действие = код === КОД_СОБЫТИЯ.действие_начало;
    const начало = к.начало();
    к.взять(действие ? 'конец токена «действие»' : 'конец токена «процедура»');
    const имя = к.строка();
    const параметры: Параметр[] = [];
    while (к.пик() === КОД_СОБЫТИЯ.параметр) {
      к.взять('параметр');
      const началоПараметра = к.начало();
      const имяПараметра = к.строка();
      const тип = типИзЛенты(к);
      const конец = к.взять('конец параметра');
      параметры.push({ имя: имяПараметра, тип, позиция: { ...началоПараметра, конец } });
    }
    if (к.взять('заголовок процедуры') !== КОД_СОБЫТИЯ.процедура_заголовок) throw new Error('ожидался конец заголовка');
    const объявлено = к.взять('число параметров');
    const естьВозврат = к.взять('признак возврата');
    if (действие && естьВозврат === 1) throw new Error('«действие» не возвращает значение (D53)');
    const возвращает = естьВозврат === 1 ? типИзЛенты(к) : null;
    if (параметры.length !== объявлено) {
      throw new Error(`процедура «${имя}»: обещано ${String(объявлено)} параметров, разобрано ${String(параметры.length)}`);
    }
    const контракт = минор >= 1 ? контрактИзЛенты(к) : пустойКонтракт();
    const тело = блокИзЛенты(к, [КОД_СОБЫТИЯ.процедура_конец], минор);
    if (к.взять('конец процедуры') !== КОД_СОБЫТИЯ.процедура_конец) throw new Error('ожидался конец процедуры');
    const конец = к.взять('конец позиции процедуры');
    процедуры.push({
      id: `p${String(процедуры.length)}`,
      имя,
      действие,
      параметры,
      возвращает,
      тело,
      контракт,
      позиция: { ...начало, конец },
    });
  }
  к.взять('конец ленты');
  return {
    формат: ФОРМАТ_AST,
    версия,
    модуль: { имя: модуль, позиция: { начало: 0, конец: конецМодуля, строка: 1, колонка: 1 } },
    процедуры,
  };
}

/** Чтение ленты: либо AST, либо названный отказ, либо исключение на битой ленте. */
export function прочитатьЛенту(
  числа: readonly number[],
): { readonly ок: true; readonly ast: AstФайл } | { readonly ок: false; readonly ошибка: ОшибкаПарсера } {
  const к = new Курсор(числа);
  if (к.взять('магию') !== МАГИЯ_ЛЕНТЫ) throw new Error('лента не начинается с магии формата');
  const мажор = к.взять('мажор');
  const минор = к.взять('минор');
  if (мажор !== ВЕРСИЯ_AST.мажор || минор < МИНОР_СОВМЕСТИМЫЙ || минор > ВЕРСИЯ_AST.минор) {
    throw new Error(`версия ленты ${String(мажор)}.${String(минор)} не поддерживается (читатель 1.1 понимает 1.0 и 1.1)`);
  }
  const версия = `${String(мажор)}.${String(минор)}`;
  const вид = к.взять('вид ленты');
  const модуль = к.строка();
  const конецМодуля = к.взять('конец модуля');
  if (вид === ВИД_ЛЕНТЫ_AST) return { ок: true, ast: прочитатьAst(к, модуль, конецМодуля, версия, минор) };
  if (вид === ВИД_ЛЕНТЫ_ОШИБКА) {
    const код = к.строка() as КодОшибки;
    const позиция = к.позиция();
    const видТокена = к.строка();
    const лексема = к.строка();
    if (к.взять('конец ошибки') !== КОД_СОБЫТИЯ.конец) throw new Error('лента ошибки не закрыта');
    return {
      ок: false,
      ошибка: {
        код,
        сообщение: сообщениеОшибки(код, лексема === '' ? null : лексема),
        позиция,
        видТокена: видТокена === '' ? null : видТокена,
        лексема: лексема === '' ? null : лексема,
      },
    };
  }
  throw new Error(`неизвестный вид ленты ${String(вид)}`);
}

/** Глубокое сравнение AST: первое расхождение названо путём, а не «не равно». */
export function сравнитьAst(факт: AstФайл, эталон: AstФайл): string[] {
  const расхождения: string[] = [];
  const сравнить = (а: unknown, б: unknown, путь: string): void => {
    if (расхождения.length >= 20) return;
    if (Array.isArray(а) && Array.isArray(б)) {
      if (а.length !== б.length) расхождения.push(`${путь}: длина ${String(а.length)} ≠ ${String(б.length)}`);
      const дл = Math.min(а.length, б.length);
      for (let и = 0; и < дл; и++) сравнить(а[и], б[и], `${путь}[${String(и)}]`);
      return;
    }
    if (а !== null && б !== null && typeof а === 'object' && typeof б === 'object') {
      const ао = а as Record<string, unknown>;
      const бо = б as Record<string, unknown>;
      const ключи = new Set([...Object.keys(ао), ...Object.keys(бо)]);
      for (const ключ of ключи) {
        if (!(ключ in ао)) расхождения.push(`${путь}.${ключ}: в факте нет`);
        else if (!(ключ in бо)) расхождения.push(`${путь}.${ключ}: в эталоне нет`);
        else сравнить(ао[ключ], бо[ключ], `${путь}.${ключ}`);
      }
      return;
    }
    if (а !== б) расхождения.push(`${путь}: ${JSON.stringify(а)} ≠ ${JSON.stringify(б)}`);
  };
  сравнить(канонизировать(факт), канонизировать(эталон), '$');
  return расхождения;
}
