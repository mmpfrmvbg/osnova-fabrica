/**
 * ОРАКУЛ P4a (Part A): лексика v3 — `parseV3` и эталон `parserV01` понимают один диалект.
 *
 * # Что проверяется
 *
 * `parseV3` (`src/compiler-v3/parser.ts`) — фронтенд v3, который потребляет весь конвейер
 * (`src/e2k/**`). До правки он понимал СТАРЫЙ диалект: bare `конец` и стрелка `→`.
 * Эталон `parserV01` (`src/compiler-v3/parserV01.ts`) понимает КАНОН v3
 * (`docs/v3-spec.md` §5–§6): `конец <имя>`, `конец если`/`конец пока`, стрелка `->` (ASCII).
 *
 * Проверяется ИНВАРИАНТ, а не один случай: для набора программ оба фронтенда обязаны
 * дать ОДИН И ТОТ ЖЕ смысл — одну и ту же структуру (процедуры, операторы, выражения)
 * и ОДИН И ТОТ ЖЕ отказ там, где отказ есть.
 *
 * Формы AST у них разные (у `parseV3` — v2 с `kind`, у `parserV01` — 3.0 с `вид`),
 * поэтому сравнение идёт через ПРИВЕДЕНИЕ к общему виду: `смысл()` строит
 * одинаковую структуру `{ вид, … }` из обеих форм. Позиции не сравниваются:
 * они в разных системах отсчёта и не являются частью проверки.
 *
 * N = 5 программ (не самопокрашение: эталон `parserV01` — независимая реализация).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from './index';
import { parseV01 } from './parserV01';

const ФАЙЛ = 'оракул-p4a.osnova';

// ─────────────────────────── приведение к общему виду ───────────────────────────

type Смысл = unknown;

function типыV2(t: unknown): Смысл {
  if (t === undefined || t === null) return t;
  const з = t as { name?: string; nullable?: boolean; element?: unknown; success?: unknown; failure?: unknown };
  if (з.name !== undefined) {
    return з.nullable === true
      ? { вид: 'может', имя: з.name }
      : { вид: 'имя', имя: з.name };
  }
  if (з.element !== undefined) return { вид: 'список', элемент: типыV2(з.element) };
  if (з.success !== undefined) {
    return { вид: 'результат', успех: типыV2(з.success), ошибка: типыV2(з.failure) };
  }
  return t;
}

function типыV30(t: unknown): Смысл {
  if (t === undefined || t === null) return t;
  const з = t as { вид?: string; имя?: string; элемент?: unknown; успех?: unknown; ошибка?: unknown };
  if (з.вид === 'имя') return { вид: 'имя', имя: з.имя };
  if (з.вид === 'список') return { вид: 'список', элемент: типыV30(з.элемент) };
  if (з.вид === 'результат') return { вид: 'результат', успех: типыV30(з.успех), ошибка: типыV30(з.ошибка) };
  return t;
}

function выражениеV2(e: unknown): Смысл {
  if (e === undefined || e === null) return e;
  const з = e as Record<string, unknown>;
  switch (з['kind']) {
    case 'число':
      return { вид: 'число', текст: String(з['value']) };
    case 'строка':
      return { вид: 'строка', значение: з['value'] };
    case 'логическое':
      return { вид: 'логическое', значение: з['value'] };
    case 'переменная':
      return { вид: 'имя', имя: з['name'] };
    case 'бинарное':
      return {
        вид: 'бинарное',
        оператор: з['op'],
        левый: выражениеV2(з['left']),
        правый: выражениеV2(з['right']),
      };
    case 'унарное':
      return { вид: 'унарное', оператор: з['op'], операнд: выражениеV2(з['operand']) };
    case 'список':
      return { вид: 'список', элементы: (з['elements'] as unknown[]).map(выражениеV2) };
    case 'вызов':
      return {
        вид: 'вызов',
        имя: з['name'],
        аргументы: (з['args'] as unknown[]).map(выражениеV2),
      };
    default:
      return e;
  }
}

function выражениеV30(e: unknown): Смысл {
  if (e === undefined || e === null) return e;
  const з = e as Record<string, unknown>;
  switch (з['вид']) {
    case 'литерал': {
      const л = з['литерал'] as Record<string, unknown>;
      if (л['вид'] === 'число') return { вид: 'число', текст: л['текст'] };
      if (л['вид'] === 'строка') return { вид: 'строка', значение: л['значение'] };
      if (л['вид'] === 'логическое') return { вид: 'логическое', значение: л['значение'] };
      return e;
    }
    case 'имя':
      return { вид: 'имя', имя: з['имя'] };
    case 'бинарное':
      return {
        вид: 'бинарное',
        оператор: з['оператор'],
        левый: выражениеV30(з['левый']),
        правый: выражениеV30(з['правый']),
      };
    case 'унарное':
      return { вид: 'унарное', оператор: з['оператор'], операнд: выражениеV30(з['операнд']) };
    case 'список':
      return { вид: 'список', элементы: (з['элементы'] as unknown[]).map(выражениеV30) };
    case 'вызов':
      return {
        вид: 'вызов',
        имя: з['имя'],
        аргументы: (з['аргументы'] as unknown[]).map(выражениеV30),
      };
    default:
      return e;
  }
}

function операторыV2(тело: unknown): Смысл {
  if (!Array.isArray(тело)) return тело;
  return тело.map((о) => {
    const з = о as Record<string, unknown>;
    switch (з['kind']) {
      case 'пусть':
        return { вид: 'пусть', имя: з['name'], значение: выражениеV2(з['init']) };
      case 'присвоить':
        return { вид: 'присваивание', имя: з['name'], значение: выражениеV2(з['value']) };
      case 'вернуть':
        return { вид: 'вернуть', значение: з['value'] === undefined ? null : выражениеV2(з['value']) };
      case 'если':
        return {
          вид: 'если',
          условие: выражениеV2(з['condition']),
          тогда: операторыV2(з['body']),
          иначе: з['elseBody'] === undefined ? null : операторыV2(з['elseBody']),
        };
      case 'пока':
        return {
          вид: 'пока',
          условие: выражениеV2(з['condition']),
          тело: операторыV2(з['body']),
        };
      case 'вызов':
        return {
          вид: 'вызов',
          имя: з['name'],
          аргументы: (з['args'] as unknown[]).map(выражениеV2),
        };
      default:
        return о;
    }
  });
}

function операторыV30(тело: unknown): Смысл {
  if (!Array.isArray(тело)) return тело;
  return тело.map((о) => {
    const з = о as Record<string, unknown>;
    switch (з['вид']) {
      case 'пусть':
        return { вид: 'пусть', имя: з['имя'], значение: выражениеV30(з['значение']) };
      case 'присваивание':
        return { вид: 'присваивание', имя: з['имя'], значение: выражениеV30(з['значение']) };
      case 'вернуть':
        return { вид: 'вернуть', значение: з['значение'] === undefined ? null : выражениеV30(з['значение']) };
      case 'если': {
        const тогда = з['тогда'] as unknown;
        const иначе = з['иначе'];
        return {
          вид: 'если',
          условие: выражениеV30(з['условие']),
          тогда: операторыV30(тогда),
          иначе: иначе === undefined ? null : операторыV30(иначе),
        };
      }
      case 'пока':
        return {
          вид: 'пока',
          условие: выражениеV30(з['условие']),
          тело: операторыV30(з['тело']),
        };
      default:
        return о;
    }
  });
}

/** Смысл программы по форме v2 (`parseV3`). */
function смыслV2(ast: unknown): Смысл {
  const модули = (ast as { modules: Array<Record<string, unknown>> }).modules;
  return модули.map((м) => ({
    имя: м['name'],
    процедуры: (м['procedures'] as Array<Record<string, unknown>>).map((п) => {
      // В форме v2 имена параметров лежат в `params`, а их типы — в `paramTypes`
      // (по позиции); в форме 3.0 — в одном списке `параметры`.
      const имена = (п['params'] as string[]) ?? [];
      const типы = (п['paramTypes'] as unknown[]) ?? [];
      return {
        имя: п['name'],
        параметры: имена.map((имя, i) => ({
          имя,
          тип: типыV2(типы[i]) ?? null,
        })),
        типВозврата: типыV2(п['returnType']) ?? null,
        тело: операторыV2(п['body']),
      };
    }),
  }));
}

/** Смысл программы по форме 3.0 (`parserV01`). */
function смыслV30(ast: unknown): Смысл {
  const файл = ast as { модуль: Record<string, unknown>; процедуры: Array<Record<string, unknown>> };
  return [
    {
      имя: файл.модуль['имя'],
      процедуры: файл.процедуры.map((п) => ({
        имя: п['имя'],
        параметры: ((п['параметры'] as Array<Record<string, unknown>>) ?? []).map((а) => ({
          имя: а['имя'],
          тип: типыV30(а['тип']),
        })),
        типВозврата: типыV30(п['возвращает']),
        тело: операторыV30(п['тело']),
      })),
    },
  ];
}

// ─────────────────────────── программы-пробы ───────────────────────────

interface Проба {
  readonly имя: string;
  readonly текст: string;
}

const ПРОБЫ: readonly Проба[] = [
  {
    имя: 'P1: `конец <имя>` у действия, без стрелки',
    текст: 'действие главная()\n  пусть х = 1\n  х = х + 1\nконец главная\n',
  },
  {
    имя: 'P2: стрелка ASCII `->` у процедуры',
    текст: 'процедура главная() -> Число\n  вернуть 42\nконец главная\n',
  },
  {
    имя: 'P3: `конец если` с веткой `иначе`',
    текст:
      'процедура главная() -> Число\n' +
      '  пусть х = 5\n' +
      '  если х > 3\n' +
      '    вернуть х\n' +
      '  иначе\n' +
      '    вернуть 0\n' +
      '  конец если\n' +
      'конец главная\n',
  },
  {
    имя: 'P4: `конец пока` и вычисляемое условие',
    текст:
      'процедура главная() -> Число\n' +
      '  пусть сч = 0\n' +
      '  пока сч < 3\n' +
      '    сч = сч + 1\n' +
      '  конец пока\n' +
      '  вернуть сч\n' +
      'конец главная\n',
  },
  {
    имя: 'P5: параметры, тип возврата и вложенный `если`',
    текст:
      'процедура сложить(а: Число, б: Число) -> Число\n' +
      '  пусть сумма = а + б\n' +
      '  если сумма > 0\n' +
      '    вернуть сумма\n' +
      '  конец если\n' +
      '  вернуть 0\n' +
      'конец сложить\n' +
      'действие главная()\n' +
      '  вернуть 0\n' +
      'конец главная\n',
  },
];

/** Пять программ покрывают: `конец <имя>`, `->`, `конец если`, `конец пока`, `иначе`. */
describe('P4a Part A: лексика v3 — `parseV3` и эталон `parserV01` понимают один диалект', () => {
  it('N = 5 программ: структура у обоих фронтендов совпадает', () => {
    expect(ПРОБЫ.length).toBe(5);
    for (const проба of ПРОБЫ) {
      const v3 = parseV3(проба.текст, ФАЙЛ);
      const v01 = parseV01(проба.текст, ФАЙЛ);
      expect(v3.errors, `${проба.имя}: parseV3 отказал: ${v3.errors.join('; ')}`).toEqual([]);
      expect(v01.ок, `${проба.имя}: parserV01 отказал: ${v01.ок ? '' : v01.ошибка.сообщение}`).toBe(true);
      const a = смыслV2(v3.program);
      const b = смыслV30(v01.ast);
      expect(b, `${проба.имя}: смысл расходится`).toEqual(a);
    }
  });

  it('ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: тот же набор без правки давал разные отказы', () => {
    // Диалект, который разошёлся: bare `конец` и стрелка `→`.
    const старый = 'процедура главная() → Число\n  вернуть 42\nконец\n';
    const v3 = parseV3(старый, ФАЙЛ);
    const v01 = parseV01(старый, ФАЙЛ);
    // Эталон отвергает оба отклонения канона.
    expect(v01.ок).toBe(false);
    expect(v01.ок ? '' : v01.ошибка.код).toBe('OSN-PAR-026');
    // И `parseV3` теперь тоже: стрелка `→` — не канон v3.
    expect(v3.errors.join(' ')).toContain('только ASCII');
  });
});
