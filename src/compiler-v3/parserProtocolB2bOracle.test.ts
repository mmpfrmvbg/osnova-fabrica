/** Имя файла — часть ленты (имя модуля): одно и то же у программы и у эталона. */
const ФАЙЛ = 'b2b-оракул.osnova';

/**
 * Обработчик вызовов VM: `вывести` складывает числа в массив, `Списки.*` — те же операции, что у
 * цели (`D43_LIST_ALIASES`), остальное — обработчик по умолчанию. `вывести` у VM по умолчанию
 * только пишет в лог, а ленте нужно ЗНАЧЕНИЕ, поэтому перехват, а не запись лога.
 *
 * Возврат — `Promise<StackValue | null>`: обработчик по умолчанию бывает асинхронным, и «превратить
 * его ответ в `null`» (первая редакция) означало потерять значение — лента обрывалась на 28 клетках.
 */
function обработчик(лента: number[]): (имя: string, аргументы: StackValue[]) => Promise<StackValue | null> {
  const базовый = createDefaultInvokeHandler();
  return async (имя, аргументы) => {
    if (имя === 'система.лог.вывести') {
      лента.push(Number(аргументы[0]));
      return null;
    }
    if (имя === 'Списки.пустой') return [];
    if (имя === 'Списки.добавить') {
      const список = аргументы[0];
      if (Array.isArray(список)) список.push(аргументы[1] as StackValue);
      return список as StackValue;
    }
    if (имя === 'Списки.установить') {
      const список = аргументы[0];
      if (Array.isArray(список)) список[Number(аргументы[1])] = аргументы[2] as StackValue;
      return список as StackValue;
    }
    if (имя === 'Списки.длина') {
      const список = аргументы[0];
      return Array.isArray(список) ? список.length : 0;
    }
    return базовый(имя, аргументы);
  };
}

/** Прогнать B2b на теле формы и вернуть ленту, которую он напечатал (или названную причину). */
async function лентаПарсера(тело: string): Promise<{ ок: true; лента: number[] } | { ок: false; причина: string }> {
  const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
  const сгенерирован = программаПротоколаB2b(исходник, ФАЙЛ);
  const разобранный = parseV3(сгенерирован, 'b2b-оракул-программа.osnova');
  if (разобранный.program === null) {
    return { ок: false, причина: `сгенерированная программа не разобрана: ${разобранный.errors.slice(0, 2).join('; ')}` };
  }
  const модуль = разобранный.program.modules[0];
  if (модуль === undefined) return { ок: false, причина: 'в сгенерированной программе нет модуля' };
  const ошибки = validateNamedTypesAndRewrite(модуль);
  if (ошибки.length > 0) return { ок: false, причина: `разрешение имён: ${ошибки.slice(0, 2).join('; ')}` };
  const лента: number[] = [];
  const vm = new VM(compile(модуль), {
    invoke: обработчик(лента),
    maxSteps: 50_000_000,
    extraInvokes: [
      { name: 'Списки.пустой', argc: 1 },
      { name: 'Списки.добавить', argc: 3 },
      { name: 'Списки.установить', argc: 3 },
      { name: 'Списки.длина', argc: 1 },
    ],
  });
  try {
    await vm.runProcedure(vm.findProcedureIndex('главная'), []);
  } catch (ошибка) {
    return { ок: false, причина: `прогон: ${String(ошибка).slice(0, 200)}` };
  }
  return { ок: true, лента };
}

describe('B2b: обход `прервать` в исходнике писателя', () => {
  for (const [этап, тело] of всеФормыB2b()) {
    it(`${этап}: 0 \`прервать\`, 47 \`процедура\` — «${тело.split('\n')[0] ?? ''}»`, () => {
      const сгенерирован = программаПротоколаB2b(`действие главная()\n  ${тело}\nконец главная\n`, ФАЙЛ);
      const прерываний = сгенерирован.split('\n').filter((строка) => /^\s*прервать\s*$/u.test(строка)).length;
      const процедур = сгенерирован.split('\n').filter((строка) => /^процедура /u.test(строка)).length;
      expect(прерываний).toBe(0);
      // 41 было до §41: шесть процедур добавили скобки — `шаг_индекс_открыть`,
      // `шаг_список_открыть`, `шаг_запятая`, `шаг_квадрат_закрыть`, `шаг_индекс_закрыть`,\n      // `шаг_список_закрыть`.
      expect(процедур).toBe(47);
    });
  }
});

describe('B2b: AST = эталон (стековая VM)', () => {
  const формы = всеФормыB2b();

  it('49 форм кита: лента парсера совпадает с эталоном клетка в клетку', async () => {
    const расхождения: string[] = [];
    for (const [этап, тело] of формы) {
      const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
      const эталон = эталоннаяЛента(исходник, ФАЙЛ);
      const получено = await лентаПарсера(тело);
      if (!получено.ок) {
        расхождения.push(`${этап} «${тело}»: ${получено.причина}`);
        continue;
      }
      if (получено.лента.length !== эталон.length) {
        расхождения.push(`${этап} «${тело}»: длина ${String(получено.лента.length)} против ${String(эталон.length)}`);
        continue;
      }
      const клетка = эталон.findIndex((число, индекс) => число !== получено.лента[индекс]);
      if (клетка >= 0) {
        расхождения.push(
          `${этап} «${тело}»: клетка ${String(клетка)} = ${String(получено.лента[клетка])}, эталон ${String(эталон[клетка])}`,
        );
      }
    }
    expect(расхождения).toEqual([]);
    expect(формы.length).toBe(49);
  });

  /**
   * Негативный контроль: сравнение обязано уметь краснеть. Форма ЛЕГАЛЬНА для эталона и НЕ
   * разбирается писателем — `Списки.установить(…)` как ОПЕРАТОР (кластер 2, ещё не снят).
   */
  it('негативный контроль: `Списки.установить(…)` оператором расходится (кластер 2)', async () => {
    const тело = 'пусть а = 5\n  Списки.установить(а, 0, 5)';
    const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
    const эталон = эталоннаяЛента(исходник, ФАЙЛ);
    const получено = await лентаПарсера(тело);
    expect(эталон.length).toBeGreaterThan(0);
    expect(получено.ок).toBe(true);
    if (получено.ок) expect(получено.лента).not.toEqual(эталон);
  });
});

/**
 * §41: кластеры 1 и 3 — ИНДЕКСАЦИЯ и `Список T` (с литералом `[…]`).
 *
 * До среза: `а[0]` в выражении писатель не разбирал вовсе (лента обрывалась на имени `а`), а
 * `: Список Число` писал типом `Список` — эталон ждёт `[КОД_ТИПА.список, элемент]`.
 * Проверяется не «зелено», а ЛЕНТА: те же формы, что в §41, сверяются с `эталоннаяЛента` клетка
 * в клетку. Негативный контроль — выше, на неснятом кластере 2.
 */
describe('B2b: индексация и `Список T` = эталон (кластеры 1 и 3)', () => {
  const формы: ReadonlyArray<readonly [string, string]> = [
    ['пусть б = а[0]', 'пусть а = 5\n  пусть б = а[0]'],
    ['пусть б = а[0] + 1', 'пусть а = 5\n  пусть б = а[0] + 1'],
    ['пусть б = 1 + а[0]', 'пусть а = 5\n  пусть б = 1 + а[0]'],
    ['индексация в условии', 'пусть а = 5\n  если а[0] > 1\n    а = 2\n  конец если'],
    ['присваивание из индекса', 'пусть а = 5\n  а = а[0]'],
    ['пусть Список Число = []', 'пусть а: Список Число = []'],
    ['пусть Список Число = [1, 2]', 'пусть а: Список Число = [1, 2]'],
    ['пусть Список Строка = []', 'пусть а: Список Строка = []'],
    ['пусть список: Список Число = []', 'пусть список: Список Число = []'],
  ];

  for (const [имя, тело] of формы) {
    it(`${имя}: лента = эталон`, async () => {
      const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
      const эталон = эталоннаяЛента(исходник, ФАЙЛ);
      const получено = await лентаПарсера(тело);
      expect(получено.ок, получено.ок ? '' : получено.причина).toBe(true);
      if (!получено.ок) return;
      expect(получено.лента).toEqual(эталон);
    });
  }
});

/**
 * §40: `вывести` → `Печать.число` — и ЗАЧЕМ это нужно.
 *
 * `вывести` — библиотечное слово D43, а не языковая инструкция: эталон (`parseV01`) его
 * ОТВЕРГАЕТ (`OSN-PAR-030`). Пока шапка B2b печатала им, СВОЙ исходник был для эталона
 * неразбираем, а значит self-parse невозможен по определению — B2b не может разобрать
 * программу, которой эталон не разбирает.
 *
 * Замена — на `Печать.число(…)`: это то же имя печати в КАНОНИЧЕСКОМ виде, оно сведено к
 * `система.лог.вывести` (`SYSCALL_ALIASES`), поэтому на цели печать остаётся той же печатью.
 * Проверяется не «строка найдена», а ОБА конца: в исходнике ноль `вывести`, и эталон этот
 * исходник ПРИНИМАЕТ — по каждой из 49 форм кита (у форм разные тела, шапка общая).
 */
describe('B2b: `вывести` заменён на `Печать.число` (L2 §40)', () => {
  const формы = всеФормыB2b();

  /** Слово целиком: `вывести_строку` не должно засчитываться за `вывести`. */
  function вхождений(текст: string, слово: string): number {
    return (текст.match(new RegExp(`(?<![\\p{L}\\p{N}_])${слово}(?![\\p{L}\\p{N}_])`, 'gu')) ?? []).length;
  }

  it('в сгенерированном исходнике 0 `вывести` и ровно 1 `Печать.число` — по каждой форме', () => {
    const расхождения: string[] = [];
    for (const [этап, тело] of формы) {
      const сгенерирован = программаПротоколаB2b(`действие главная()\n  ${тело}\nконец главная\n`, ФАЙЛ);
      const вывести = вхождений(сгенерирован, 'вывести');
      const печать = вхождений(сгенерирован, 'Печать\\.число');
      if (вывести !== 0 || печать !== 1) расхождения.push(`${этап}: вывести ${String(вывести)}, Печать.число ${String(печать)}`);
    }
    expect(расхождения).toEqual([]);
    expect(формы.length).toBe(49);
  });

  it('эталон AST v0.1 ПРИНИМАЕТ исходник B2b — по каждой из 40 форм', () => {
    const отказы: string[] = [];
    for (const [этап, тело] of формы) {
      const сгенерирован = программаПротоколаB2b(`действие главная()\n  ${тело}\nконец главная\n`, ФАЙЛ);
      const итог = parseV01(сгенерирован, ФАЙЛ);
      // ОТКАЗ ОБЯЗАН БЫТЬ НАЗВАН: молчаливое «не ок» не отличимо от падения самого эталона.
      if (!итог.ок) отказы.push(`${этап}: ${итог.ошибка.код} — ${итог.ошибка.сообщение.slice(0, 160)}`);
    }
    expect(отказы).toEqual([]);
  });

  it('негативный контроль: без замены эталон отказывает ровно на `вывести`', () => {
    // Исходник с ОДНИМ `вывести` — то, что было в шапке до §40. Отказ обязан быть `OSN-PAR-030`
    // и обязан называть именно это слово; иначе «эталон принимает» ничего не доказывает.
    const без = `действие главная()\n  пусть лента: Список Число = []\n  вывести лента[0]\nконец главная\n`;
    const итог = parseV01(без, ФАЙЛ);
    expect(итог.ок).toBe(false);
    if (итог.ок) return;
    expect(итог.ошибка.код).toBe('OSN-PAR-030');
    expect(итог.ошибка.сообщение).toContain('вывести');
  });
});
