/**
 * B2b: ОРАКУЛ AST БЕЗ ЖЕЛЕЗА — «ЛЕНТА, КОТОРУЮ ВЫДАЁТ ПАРСЕР», ПРОТИВ ЭТАЛОНА.
 *
 * # Что здесь проверяется и почему именно так
 *
 * Писатель B2b — программа на Основе: она читает ленту токенов и печатает ленту AST числами.
 * Значит проверять её можно ДВУМЯ разными способами, и путать их нельзя:
 *
 * | способ | что исполняется | где живёт |
 * |---|---|---|
 * | понижение в ELF | наши байты e2k | `src/e2k/parserProtocolB2bHardware.test.ts` (сборка), кит и `gate:hardware` (прогон) |
 * | **оракул AST** (этот файл) | сама программа Основы на стековой VM | `npm test` |
 *
 * Второй способ — единственный, который в `npm test` отвечает на вопрос «а правильную ли ленту
 * печатает парсер», потому что первый проверяет только сборку (длина образа, форма). Железо
 * арбитр по §36, но оно не в каждом прогоне, и отказ раскладки выглядел бы как «оракул не
 * запускался».
 *
 * # Закреплённые числа (L2-final, §38)
 *
 *   • в сгенерированном исходнике **0** `прервать` и **47** `процедура` — ранний выход из `пока`
 *     сделан флагом, иначе B2b не разберёт свой же исходник (узла `прервать` в AST v0.1 нет);
 *   • **40 из 40** форм кита: лента программы = `эталоннаяЛента` (AST v0.1) клетка в клетку;
 *   • негативный контроль: форма с индексацией `лента[и]` в выражении **обязана** разойтись —
 *     писатель её не разбирает (`src/compiler-v3/parser-protocol-b2b.ts`, шапка: «индексации и
 *     списков в выражениях нет»). Если этот контроль позеленеет, значит сравнение перестало
 *     сравнивать: оно — часть оракула, а не украшение.
 *
 * # Чего здесь НЕТ
 *
 * Исполнитель — стековая VM, а не модель: глубина вызовов ≥ 2 зацикливает модель (стена `#180`),
 * а у B2b вызовы вложенные. Поэтому «зелено здесь» НЕ значит «зелено на цели»: за цель отвечает
 * `gate:hardware`.
 */
