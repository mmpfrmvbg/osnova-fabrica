/**
 * 22 048: `иначе` + `если` — ОРАКУЛ ДО КОДА (§3.1).
 *
 * # Что здесь зафиксировано
 *
 * Машина (`шаг_иначе`, `parser-protocol-b2b.ts`) решает «цепочка» только по СЛЕДУЮЩЕМУ токену
 * `если`. Канон требует трёх условий:
 *   1. следующий токен — `если`;
 *   2. `если` стоит на той же строке, что `иначе` (`parserV01.ts`);
 *   3. в блоке `иначе` ровно один оператор — этот `если` (`astFormat.ts#единственныйИначеЕсли`).
 *
 * Форма `РАСХОЖДЕНИЕ` нарушает (2) и (3): `если` с новой строки, а в блоке ещё и присваивание.
 * Канон пишет `иначе`(6) и вложенный `если` отдельным оператором; машина склеивает `иначе_если`(40)
 * и съедает `конец если` как конец цепочки — лента расходится, отказа нет. Это D4.
 *
 * # Что тест требует ПОСЛЕ правки
 *
 * Не «именно D5 любой ценой»: если три условия выразимы чтением ленты (скан без записи), правильный
 * ответ — AST = эталон. Если нет — парсер обязан НАЗВАТЬ отказ (D5), а не выдать чужую форму.
 * Запрещён ровно один исход: успешная лента, не равная эталону (D4). Поэтому тест принимает
 * `ок + лента == эталон` ИЛИ `не ок + причина вида OSN-PAR-NNN`.
 *
 * Контроли: однострочная цепочка (`иначе если`) и блок ровно из одного вложенного `если` — обе
 * канон тоже канонизирует в `40`; они обязаны остаться зелёными и до, и после правки.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from './index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { createDefaultInvokeHandler, VM, type StackValue } from '../runtime/vm/interpreter';
import { программаПротоколаB2b } from './parser-protocol-b2b';
import { эталоннаяЛента } from './parser-protocol-probe';

const ФАЙЛ = 'b2b-иначе-оракул.osnova';

function обработчик(лента: number[]): (имя: string, аргументы: StackValue[]) => Promise<StackValue | null> {
  const базовый = createDefaultInvokeHandler();
  return async (имя, аргументы) => {
    if (имя === 'система.лог.вывести') {
      лента.push(Number(аргументы[0]));
      return null;
    }
    if (имя === 'Списки.пустой') return [];
    if (имя === 'Списки.добавить') {
      const список = аргументы[0];
      if (Array.isArray(список)) список.push(аргументы[1] as StackValue);
      return список as StackValue;
    }
    if (имя === 'Списки.установить') {
      const список = аргументы[0];
      if (Array.isArray(список)) список[Number(аргументы[1])] = аргументы[2] as StackValue;
      return список as StackValue;
    }
    if (имя === 'Списки.длина') {
      const список = аргументы[0];
      return Array.isArray(список) ? список.length : 0;
    }
    return базовый(имя, аргументы);
  };
}

async function лентаПарсера(тело: string): Promise<{ ок: true; лента: number[] } | { ок: false; причина: string }> {
  const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
  const сгенерирован = программаПротоколаB2b(исходник, ФАЙЛ);
  const разобранный = parseV3(сгенерирован, 'b2b-иначе-программа.osnova');
  if (разобранный.program === null) {
    return { ок: false, причина: `сгенерированная программа не разобрана: ${разобранный.errors.slice(0, 2).join('; ')}` };
  }
  const модуль = разобранный.program.modules[0];
  if (модуль === undefined) return { ок: false, причина: 'в сгенерированной программе нет модуля' };
  const ошибки = validateNamedTypesAndRewrite(модуль);
  if (ошибки.length > 0) return { ок: false, причина: `разрешение имён: ${ошибки.slice(0, 2).join('; ')}` };
  const лента: number[] = [];
  const vm = new VM(compile(модуль), {
    invoke: обработчик(лента),
    maxSteps: 50_000_000,
    extraInvokes: [
      { name: 'Списки.пустой', argc: 1 },
      { name: 'Списки.добавить', argc: 3 },
      { name: 'Списки.установить', argc: 3 },
      { name: 'Списки.длина', argc: 1 },
    ],
  });
  try {
    await vm.runProcedure(vm.findProcedureIndex('главная'), []);
  } catch (ошибка) {
    return { ок: false, причина: `прогон: ${String(ошибка).slice(0, 200)}` };
  }
  return { ок: true, лента };
}

/**
 * Проверка одного случая. Успех — ТОЛЬКО лента, равная эталону; отказ — ТОЛЬКО названный
 * (`OSN-PAR-NNN`). Всё остальное — D4 и обязано краснеть.
 */
async function проверить(тело: string): Promise<void> {
  const исходник = `действие главная()\n  ${тело}\nконец главная\n`;
  const эталон = эталоннаяЛента(исходник, ФАЙЛ);
  const получено = await лентаПарсера(тело);
  if (!получено.ок) {
    expect(получено.причина).toMatch(/OSN-PAR-\d{3}/u);
    return;
  }
  expect(получено.лента).toEqual(эталон);
}

describe('22 048: `иначе`/`если` — три условия канона, а не один следующий токен', () => {
  it('РАСХОЖДЕНИЕ: `если` с новой строки и второй оператор в блоке — эталон, не тихая подмена', async () => {
    await проверить(
      [
        'если а > 0',
        '  а = 1',
        'иначе',
        '  если б > 0',
        '    а = 2',
        '  конец если',
        '  а = 3',
        'конец если',
      ].join('\n'),
    );
  });

  it('КОНТРОЛЬ: `иначе если` в одной строке — цепочка остаётся цепочкой', async () => {
    await проверить(['если а > 0', '  а = 1', 'иначе если б > 0', '  а = 2', 'конец если'].join('\n'));
  });

  it('КОНТРОЛЬ: блок ровно из одного вложенного `если` — канон тоже пишет `40`', async () => {
    await проверить(
      ['если а > 0', '  а = 1', 'иначе', '  если б > 0', '    а = 2', '  конец если', 'конец если'].join('\n'),
    );
  });
});
