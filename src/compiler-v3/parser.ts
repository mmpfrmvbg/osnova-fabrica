/**
 * ПАРСЕР ЯЗЫКА ОСНОВА v3 → AST ФОРМЫ v2.
 *
 * Смысл шага (`docs/compiler-v3-plan.md`): фронтендов два, дальше путь один.
 * Здесь строится ровно тот `Program` из `src/compiler/ast.ts`, что и у v2-парсера,
 * поэтому кодоген, VM, кодировщик e2k и планировщик о написании исходника не знают
 * ничего.
 *
 * Источник истины по синтаксису — `docs/osnova-spec.md` и `src/spec/osnova-spec.ts`
 * (лексер + парсер прототипа). Решения прототипа перенесены, но два его дефекта —
 * нет, и оба названы:
 *
 *   1. НАБОР СЛОВ-ЗАВЕРШИТЕЛЕЙ БЛОКА. В прототипе в стоп-набор тела `если` входит
 *      слово `если`, поэтому ВЛОЖЕННОЕ условие обрывает внешнее тело:
 *      `если … / если … / конец если / конец если` прототип отвергает
 *      («ожидается «конец», получено «если»» — замерено). Здесь тело кончается
 *      только на слове-разделителе СВОЕЙ конструкции (`иначе`, `есть`, `при`)
 *      или на `конец`: вложенные `если`/`пока`/`для`/`цикл` разбираются.
 *   2. `?` и склейки через `_` (`конец_пока`, `для_каждого`) не «нет такого
 *      символа», а НАЗВАННЫЙ отказ с указанием написания v3: это диагностика
 *      перехода, а не второй синтаксис.
 *
 * Что перенесено дословно и почему:
 *   • аргумент ВСТРОЕННОЙ ОПЕРАЦИИ — операнд (`длина числа - 1` = `(длина числа) - 1`),
 *     аргумент ДЕЙСТВИЯ (`вывести`, `вывести_строку`) — выражение
 *     (`вывести "а" + счёт` склеивает строку). Счётчики `плоскийАргумент` /
 *     `глубинаАргумента` — те же, что в прототипе;
 *   • `=` в условии — ошибка (в v2 он молча читался как `==`);
 *   • цепочка сравнений запрещена, цепочка ПОЛЕЙ разрешена, вызов — `имя(…)`
 *     или `Модуль.имя(…)` ровно с одной точкой;
 *   • модуль — это файл целиком, имя берётся из имени файла.
 */

