/** Имя модуля, когда шапки нет и имени файла тоже нет: то же слово, что у v2. */
export const DEFAULT_MODULE_NAME = "вход";

/**
 * Имя модуля из имени файла: `привет.osnova` → `привет`.
 *
 * Повторяет правило v2 (`moduleNameFromFilename` в `src/compiler/parser.ts`)
 * дословно: снимается только каталог (и `/`, и `\`) и только расширение
 * `.osnova`; прочие точки остаются частью имени. Дублирование намеренное: v3 —
 * отдельный фронтенд и не тянет за собой v2-парсер целиком; совпадение поведения
 * проверяет оракул (`astEquivalence.test.ts`), а не обещание в комментарии.
 */
export function moduleNameFromFilename(filename: string | undefined): string {
  if (filename === undefined || filename === "") return DEFAULT_MODULE_NAME;
  const normalized = filename.replace(/\\/g, "/");
  const base = normalized.slice(normalized.lastIndexOf("/") + 1);
  const withoutExt = base.replace(/\.osnova$/i, "");
  return withoutExt === "" ? DEFAULT_MODULE_NAME : withoutExt;
}

