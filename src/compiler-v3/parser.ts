class ОшибкаРазбора extends Error {}

/**
 * Разобрать поток токенов v3 в `Program` формы v2.
 *
 * Исключений наружу не бросает: ошибка разбора возвращается в `errors`.
 */
export function parseV3Tokens(tokens: readonly V3Token[], filename: string): V3Result {
  try {
    return { program: new Разбор(tokens, filename).программа(), errors: [] };
  } catch (e) {
    if (e instanceof ОшибкаРазбора) return { errors: [e.message] };
    // Неожиданная внутренняя ошибка тоже не выходит наружу: контракт публичной
    // точки — «не бросает», и нарушать его из-за дефекта в самом парсере нельзя.
    const сообщение = e instanceof Error ? e.message : String(e);
    return { errors: [formatV3Error(filename, 1, `внутренняя ошибка разбора v3: ${сообщение}`)] };
  }
}

