class ОшибкаРазбора extends Error {}

/**
 * Разобрать поток токенов v3 в `Program` формы v2.
 *
 * Исключений наружу не бросает: ошибка разбора возвращается в `errors`.
 */
export function parseV3Tokens(tokens: readonly V3Token[], filename: string): V3Result {
  try {
    return { program: new Разбор(tokens, filename).программа(), errors: [] };
  } catch (e) {
    if (e instanceof ОшибкаРазбора) return { errors: [e.message] };
    // Неожиданная внутренняя ошибка тоже не выходит наружу: контракт публичной
    // точки — «не бросает», и нарушать его из-за дефекта в самом парсере нельзя.
    const сообщение = e instanceof Error ? e.message : String(e);
    return { errors: [formatV3Error(filename, 1, `внутренняя ошибка разбора v3: ${сообщение}`)] };
  }
}

class Разбор {
  private p = 0;
  /** Сколько аргументов операций разбирается сейчас: там сравнение не начинается. */
  private глубинаАргумента = 0;
  /** Сколько ПЛОСКИХ аргументов: там знаки арифметики не продолжают операнд. */
  private плоскийАргумент = 0;
  /** Глубина условия: здесь `=` — почти наверняка забытое `==`. */
  private глубинаУсловия = 0;

  constructor(
    private readonly токены: readonly V3Token[],
    private readonly файл: string,
  ) {}

  // ─────────────────────────── опорные ───────────────────────────

  private пик(сдвиг = 0): V3Token {
    return this.токены[Math.min(this.p + сдвиг, this.токены.length - 1)]!;
  }

  private съесть(): V3Token {
    return this.токены[this.p++]!;
  }

  private эт(вид: V3TokenKind): boolean {
    return this.пик().kind === вид;
  }

  private лексемаЭт(слово: string): boolean {
    return this.пик().lexeme === слово;
  }

  private ошибка(сообщение: string): ОшибкаРазбора {
    return new ОшибкаРазбора(formatV3Error(this.файл, this.пик().line, сообщение));
  }

  private ждём(вид: V3TokenKind, что: string): V3Token {
    if (!this.эт(вид)) throw this.ошибка(`ожидается ${что}, получено «${this.пик().lexeme}»`);
    return this.съесть();
  }

  /** Служебное слово, которое лексируется как обычное имя (`в`, `элемент`, `из`). */
  private ждёмСлово(слово: string, сообщение: string): void {
    if (!this.лексемаЭт(слово)) throw this.ошибка(сообщение);
    this.съесть();
  }

  private пустые(): void {
    while (this.эт("новая_строка") || this.эт(";")) this.съесть();
  }

  private конецИнструкции(): void {
    if (this.эт("новая_строка") || this.эт("конец_файла") || this.эт(";")) return;
    if (this.эт("конец")) {
      const имя = this.имяЗакрытия();
      throw this.ошибка(
        `после инструкции ожидается конец строки: закрытие «конец${имя === "" ? "" : " " + имя}» пишется с новой строки`,
      );
    }
    if (/^конец_/.test(this.пик().lexeme)) throw this.ошибкаЗакрытия();
    throw this.ошибка(`после инструкции ожидается конец строки, получено «${this.пик().lexeme}»`);
  }

  /** Необязательное имя закрываемого блока: `конец если` → «если». */
  private имяЗакрытия(): string {
    const л = this.пик(1).lexeme;
    return СЛОВА_ЗАКРЫТИЯ.includes(л) ? л : "";
  }

  /** Отказ на закрытии: называет и написание v2, если слово склеено через `_`. */
  private ошибкаЗакрытия(): ОшибкаРазбора {
    const t = this.пик();
    if (/^конец_/.test(t.lexeme)) {
      const блок = t.lexeme.slice("конец_".length);
      if (блок.startsWith("процедур")) {
        return this.ошибка("«конец_процедуры» — написание v2: у процедуры и действия закрытие — просто «конец»");
      }
      if (блок.startsWith("модул")) {
        return this.ошибка("«конец_модуля» — написание v2: в v3 файл сам является модулем, закрывать нечего");
      }
      return this.ошибка(`«${t.lexeme}» — написание v2: в v3 закрытие пишется через пробел — «конец ${блок}»`);
    }
    return this.ошибка(`ожидается «конец», получено «${t.lexeme}»`);
  }

  /** Закрытие блока: обязательное `конец` и необязательное имя блока. */
  private закрытие(ожидается: string): void {
    if (!this.эт("конец")) throw this.ошибкаЗакрытия();
    this.съесть();
    const имя = this.пик();
    if (СЛОВА_ЗАКРЫТИЯ.includes(имя.lexeme)) {
      this.съесть();
      if (!созвучно(имя.lexeme, ожидается)) {
        throw this.ошибка(`блок «${ожидается}» закрывается «конец ${ожидается}», а не «конец ${имя.lexeme}»`);
      }
    }
  }

  /** У процедуры и действия закрытие — просто `конец`: тело не блок внутри блока. */
  private закрытиеПроцедуры(): void {
    if (!this.эт("конец")) throw this.ошибкаЗакрытия();
    this.съесть();
    const имя = this.пик();
    if (СЛОВА_ЗАКРЫТИЯ.includes(имя.lexeme)) {
      throw this.ошибка(`процедура и действие закрываются просто «конец», а не «конец ${имя.lexeme}»`);
    }
  }

  // ──────────────────────────── модуль ────────────────────────────

  /** Модуль — это файл целиком: шапки `модуль Имя` нет, имя берётся из имени файла. */
  программа(): Program {
    const имя = moduleNameFromFilename(this.файл);
    const imports: ImportDeclaration[] = [];
    const typeDeclarations: TypeDeclaration[] = [];
    const procedures: Procedure[] = [];

    this.пустые();
    if (this.лексемаЭт("модуль") && this.эт("имя")) {
      throw this.ошибка("шапки «модуль Имя» в v3 нет: файл сам является модулем, имя берётся из имени файла");
    }
    while (this.эт("подключить")) {
      imports.push(this.подключение());
      this.пустые();
    }
    while (this.эт("тип")) {
      typeDeclarations.push(this.объявлениеТипа());
      this.пустые();
    }
    while (!this.эт("конец_файла")) {
      if (this.эт("тип")) throw this.ошибка("объявления «тип» идут до процедур");
      if (this.эт("экспорт") || this.эт("процедура") || this.эт("действие")) {
        procedures.push(this.процедура());
      } else if (/^конец_/.test(this.пик().lexeme)) {
        throw this.ошибкаЗакрытия();
      } else {
        throw this.ошибка(`здесь ожидается «тип», «процедура» или «действие», получено «${this.пик().lexeme}»`);
      }
      this.пустые();
    }
    const модуль: Module = { name: имя, imports, typeDeclarations, procedures };
    return { modules: [модуль] };
  }

  private подключение(): ImportDeclaration {
    this.съесть(); // подключить
    const path = String(this.ждём("строка", "путь в кавычках").value);
    let alias: string | undefined;
    if (this.эт("как")) {
      this.съесть();
      alias = String(this.ждём("имя", "имя модуля").lexeme);
    }
    this.конецИнструкции();
    return { module: alias ?? moduleNameFromFilename(path), path };
  }

  // ───────────────────────────── типы ─────────────────────────────

  private объявлениеТипа(): TypeDeclaration {
    this.съесть(); // тип
    const имя = String(this.ждём("имя", "имя типа").lexeme);
    if (this.эт("=")) {
      // Перечень: `тип Имя = a | b` и `тип Имя = один из { a, b }`.
      this.съесть();
      this.пустые();
      const варианты: string[] = [];
      if (this.эт("имя") && this.лексемаЭт("один")) {
        this.съесть();
        this.ждёмСлово("из", `ожидается «из», получено «${this.пик().lexeme}»`);
        this.ждём("{", "«{»");
        this.пустые();
        while (!this.эт("}")) {
          варианты.push(String(this.ждём("имя", "имя варианта").lexeme));
          this.пустые();
          if (this.эт(",")) {
            this.съесть();
            this.пустые();
          }
        }
        this.ждём("}", "«}»");
      } else {
        варианты.push(String(this.ждём("имя", "имя варианта").lexeme));
        while (this.эт("|")) {
          this.съесть();
          this.пустые();
          варианты.push(String(this.ждём("имя", "имя варианта").lexeme));
        }
      }
      this.конецИнструкции();
      return { kind: "TypeDeclaration", name: имя, fields: [], variants: варианты };
    }
    this.ждём("{", "«{» или «=»");
    this.пустые();
    const fields: TypeField[] = [];
    while (!this.эт("}")) {
      const имяПоля = String(this.ждём("имя", "имя поля").lexeme);
      this.ждём(":", "«:» после имени поля");
      fields.push({ name: имяПоля, type: this.типСсылка() });
      this.пустые();
      if (this.эт(",")) {
        this.съесть();
        this.пустые();
      }
    }
    this.ждём("}", "«}»");
    this.конецИнструкции();
    return { kind: "TypeDeclaration", name: имя, fields };
  }

  /**
   * Ссылка на тип. Формы v3 → форма v2 (`TypeRef` = имя + `?` + `[…]`):
   *   `Т` → `{name: Т}`; `Может Т` → `{name: Т, nullable: true}`;
   *   `Список Т` → `{name: Т, array: true}`; `Может Список Т` → `{name: Т, nullable: true, array: true}`.
   * Всё, что в эту форму не укладывается (`Словарь К → З`, вложенный список),
   * названо отказом, а не выдуманным именем типа.
   */
  private типСсылка(): TypeRef {
    if (this.эт("?")) throw this.ошибка("«?Тип» — написание v2: в v3 это «Может Тип»");
    let nullable = false;
    if (this.эт("Может")) {
      this.съесть();
      if (this.эт("Может")) throw this.ошибка("«Может Может Т» — ошибка: тип и так допускает пусто");
      nullable = true;
    }
    if (this.эт("Список")) {
      this.съесть();
      if (this.эт("Может") || this.эт("Список") || this.эт("Словарь")) {
        throw this.ошибка(
          "вложенный список («Список Список Т», «Список Может Т») не выражается в AST v2: у типа там есть только имя, «?» и «[…]»",
        );
      }
      return { name: this.имяТипа("тип элемента списка"), nullable, array: true };
    }
    if (this.эт("Словарь")) {
      throw this.ошибка("«Словарь» не выражается в AST v2: у типа v2 есть только имя, «?» и «[…]»");
    }
    const имя = this.имяТипа("имя типа");
    if (nullable && имя === "Пусто") throw this.ошибка("«Может Пусто» — ошибка: тип не несёт значения");
    return { name: имя, nullable };
  }

  private имяТипа(что: string): string {
    const t = this.пик();
    if (t.kind === "Число" || t.kind === "Строка" || t.kind === "Логическое" || t.kind === "Пусто") {
      return this.съесть().lexeme;
    }
    return String(this.ждём("имя", что).lexeme);
  }

  // ─────────────────────────── процедуры ───────────────────────────

  /**
   * `процедура f(а: Тип) → Тип` и `действие f(а: Тип)`.
   *
   * В AST v2 это ОДНА сущность `Procedure`: слово `действие` даёт ту же форму, что
   * `процедура` без аннотации возврата (поле `returnType` не заводится).
   */
  private процедура(): Procedure {
    let exported = false;
    if (this.эт("экспорт")) {
      this.съесть();
      exported = true;
    }
    const действие = this.эт("действие");
    if (!this.эт("процедура") && !this.эт("действие")) throw this.ошибка("ожидается «процедура» или «действие»");
    this.съесть();
    const name = String(this.ждём("имя", "имя процедуры").lexeme);
    this.ждём("(", "«(»");
    const params: string[] = [];
    const paramTypes: Array<TypeRef | undefined> = [];
    while (!this.эт(")")) {
      params.push(String(this.ждём("имя", "имя параметра").lexeme));
      paramTypes.push(this.эт(":") ? (this.съесть(), this.типСсылка()) : undefined);
      if (this.эт(",")) {
        this.съесть();
        continue;
      }
      break;
    }
    this.ждём(")", "«)»");
    let returnType: TypeRef | undefined;
    if (this.эт("→")) {
      this.съесть();
      returnType = this.типСсылка();
    }
    if (действие && returnType) throw this.ошибка("«действие» не возвращает значение: уберите «→»");
    if (!действие && !returnType) {
      throw this.ошибка("«процедура» возвращает значение: укажите «→ Тип», а без возврата пишите «действие»");
    }
    this.пустые();
    const body = this.блок(new Set<V3TokenKind>(["конец"]));
    this.закрытиеПроцедуры();
    const hasParamTypes = paramTypes.some((t) => t !== undefined);
    return {
      name,
      params,
      body,
      exported,
      pure: false,
      paramTypes: hasParamTypes ? paramTypes : undefined,
      returnType,
    };
  }

  // ──────────────────────────── блоки ────────────────────────────

  /**
   * Тело блока до слова-разделителя своей конструкции или до `конец`.
   *
   * В стоп-наборе НЕТ слов, которыми начинается инструкция (`если`, `пока`, `для`,
   * `цикл`, `повторять`, `разбор`, `защита`): иначе вложенный блок обрывал бы
   * внешний. Именно этот дефект есть в прототипе (`src/spec/osnova-spec.ts`) —
   * вложенное `если` он отвергает, — и он сюда не перенесён.
   */
  private блок(стоп: ReadonlySet<V3TokenKind>): Stmt[] {
    const тело: Stmt[] = [];
    this.пустые();
    for (;;) {
      const k = this.пик().kind;
      if (k === "конец_файла") throw this.ошибка("блок не закрыт: дошли до конца файла");
      if (стоп.has(k)) return тело;
      тело.push(this.инструкция());
      this.конецИнструкции();
      this.пустые();
    }
  }

  // ────────────────────────── инструкции ──────────────────────────

  private инструкция(): Stmt {
    const k = this.пик().kind;
    if (k === "конец") throw this.ошибка("лишнее «конец»: этот блок не открыт");
    if (
      k === "(" ||
      k === ")" ||
      k === "[" ||
      k === "]" ||
      k === "{" ||
      k === "}" ||
      k === "," ||
      k === ":" ||
      k === "." ||
      k === "→" ||
      k === "|" ||
      k === "?"
    ) {
      throw this.ошибка(`в начале инструкции не может стоять «${this.пик().lexeme}»: закрытие блока — только словом «конец»`);
    }
    if (/^конец_/.test(this.пик().lexeme)) throw this.ошибкаЗакрытия();
    const склейка = СКЛЕЙКИ_V2[this.пик().lexeme];
    if (склейка !== undefined) {
      throw this.ошибка(`«${this.пик().lexeme}» — написание v2: в v3 «${склейка}» (через пробел)`);
    }

    switch (k) {
      case "пусть":
        return this.пусть();
      case "вернуть":
        return this.вернуть();
      case "если":
        return this.если();
      case "пока":
        return this.пока();
      case "для":
        return this.дляКаждого();
      case "цикл":
        return this.цикл();
      case "разбор":
        return this.разбор();
      case "защита":
        return this.защита();
      case "поднять": {
        this.съесть();
        return { kind: "выбросить", value: this.выражение() };
      }
      case "прервать":
        this.съесть();
        return { kind: "прервать" };
      case "продолжить":
        this.съесть();
        return { kind: "продолжить" };
      case "повторять":
        throw this.ошибка(
          "«повторять N раз» не выражается в AST v2: счётного повтора там нет — пишите «пока» или «для каждого»",
        );
      default:
        break;
    }

    // `проверить` — конструкция со своей грамматикой, но формы в AST v2 у неё нет,
    // и системного вызова проверки в реестре тоже нет. Отказ называет это прямо:
    // выдуманное имя вызова («проверить») упало бы позже и в чужом месте.
    if (this.лексемаЭт("проверить")) {
      throw this.ошибка("«проверить» не выражается в AST v2: конструкции проверки там нет (и системного вызова тоже)");
    }

    // Инструкция-выражение либо присваивание. Ведущее имя разбирается как обычное
    // выражение: благодаря этому `длина = 5` остаётся присваиванием имени `длина`,
    // а `длина числа` — операцией (см. `первичное`).
    const л = this.выражение();
    if (this.эт("=")) {
      this.съесть();
      return this.присваивание(л, this.выражение());
    }
    if (л.kind !== "вызов") {
      throw this.ошибка("инструкция ничего не делает: нужен вызов, действие или присваивание");
    }
    return { kind: "выражение", expr: л };
  }

  /** Присваивание в форме AST v2: имя, поле или запись по индексу. */
  private присваивание(цель: Expr, значение: Expr): Stmt {
    if (цель.kind === "переменная") return { kind: "присвоить", name: цель.name, value: значение };
    if (цель.kind === "поле") {
      return { kind: "поле_присвоить", object: цель.object, field: цель.field, value: значение };
    }
    // `числа[0] = 9`: чтение по индексу — это `система.массив.получить`, запись —
    // ТОТ ЖЕ узел с третьим аргументом. Так делает и v2-парсер: форма AST одна.
    if (цель.kind === "вызов" && цель.name === ПОЛУЧИТЬ && цель.args.length === 2) {
      return {
        kind: "выражение",
        expr: { kind: "вызов", name: УСТАНОВИТЬ, args: [цель.args[0]!, цель.args[1]!, значение] },
      };
    }
    throw this.ошибка("слева от «=» должно быть имя, поле или элемент");
  }

  private пусть(): Stmt {
    this.съесть();
    const name = String(this.ждём("имя", "имя переменной").lexeme);
    let typeAnnotation: TypeRef | undefined;
    if (this.эт(":")) {
      this.съесть();
      typeAnnotation = this.типСсылка();
    }
    if (!this.эт("=")) throw this.ошибка("у «пусть» нет значения: объявление всегда с «= значение»");
    this.съесть();
    return { kind: "пусть", name, init: this.выражение(), typeAnnotation };
  }

  private вернуть(): Stmt {
    this.съесть();
    // Скобок вокруг значения в v3 нет: `вернуть(x)` — это написание v2.
    if (this.эт("(")) throw this.ошибка("возврат пишется «вернуть x», без скобок вокруг значения");
    if (!this.можетНачатьОперанд(0)) return { kind: "вернуть" };
    return { kind: "вернуть", value: this.выражение() };
  }

  private пока(): Stmt {
    this.съесть();
    const condition = this.условие();
    this.пустые();
    const body = this.блок(new Set<V3TokenKind>(["конец"]));
    this.закрытие("пока");
    return { kind: "пока", condition, body };
  }

  private если(): Stmt {
    this.съесть();
    const ветви: Array<{ condition: Expr; body: Stmt[] }> = [];
    ветви.push({ condition: this.условие(), body: this.блок(new Set<V3TokenKind>(["иначе", "конец"])) });
    while (this.эт("иначе") && this.пик(1).kind === "если") {
      this.съесть();
      this.съесть();
      ветви.push({ condition: this.условие(), body: this.блок(new Set<V3TokenKind>(["иначе", "конец"])) });
    }
    let elseBody: Stmt[] | undefined;
    if (this.эт("иначе")) {
      this.съесть();
      this.пустые();
      elseBody = this.блок(new Set<V3TokenKind>(["конец"]));
    }
    this.закрытие("если");
    const первая = ветви[0]!;
    return {
      kind: "если",
      condition: первая.condition,
      body: первая.body,
      elseIfClauses: ветви.length > 1 ? ветви.slice(1) : undefined,
      elseBody,
    };
  }

  /**
   * Перебор — ОДНА форма: `для каждого эл в списке`.
   *
   * Счётный цикл v3 (`для i от 1 до 10 шаг 3`) в AST v2 не выражается: там есть
   * только `для_каждого`, `пока` и бесконечный `цикл`. Разворачивать его здесь
   * значило бы писать семантику во фронтенде, поэтому это названный отказ.
   */
  private дляКаждого(): Stmt {
    this.съесть(); // для
    if (!this.эт("каждого")) {
      if (this.эт("имя") && this.пик(1).lexeme === "в") {
        throw this.ошибка("перебор пишется «для каждого <элемент> в <список>»: слово «каждого» обязательно");
      }
      throw this.ошибка(
        "«для … от … до …» (счётный цикл) не выражается в AST v2: там только перебор «для каждого»; счётный цикл пишите через «пока»",
      );
    }
    this.съесть();
    const item = String(this.ждём("имя", "имя элемента").lexeme);
    let index: string | undefined;
    if (this.эт(",")) {
      this.съесть();
      index = String(this.ждём("имя", "имя индекса").lexeme);
    }
    this.ждёмСлово("в", `ожидается «в», получено «${this.пик().lexeme}»`);
    const source = this.выражение();
    this.пустые();
    const body = this.блок(new Set<V3TokenKind>(["конец"]));
    this.закрытие("для");
    return { kind: "для_каждого", item, index, source, body, variable: item, collection: source };
  }

  private цикл(): Stmt {
    this.съесть();
    this.пустые();
    const body = this.блок(new Set<V3TokenKind>(["конец"]));
    this.закрытие("цикл");
    return { kind: "цикл", body };
  }

  /**
   * `защита` … `при ошибке как причина` … `конец защита` → `попробовать`/`поймать`.
   *
   * Форма БЕЗ приёмника (`защита` без `при ошибке`) в AST v2 не выражается:
   * у `попробовать` переменная-приёмник обязательна. Подставить туда выдуманное
   * имя значило бы МОЛЧА перехватывать сбой, который обязан идти сквозь, —
   * поэтому это отказ, а не подстановка.
   */
  private защита(): Stmt {
    this.съесть();
    this.пустые();
    const body = this.блок(new Set<V3TokenKind>(["при", "конец"]));
    this.пустые();
    if (!this.эт("при")) {
      throw this.ошибка(
        "«защита» без «при ошибке как <имя>» не выражается в AST v2: у «попробовать» приёмник обязателен",
      );
    }
    this.съесть();
    this.ждём("ошибке", "«ошибке»");
    if (!this.эт("как")) {
      throw this.ошибка("обработка пишется «при ошибке как <имя>»: в AST v2 у «попробовать» приёмник обязателен");
    }
    this.съесть();
    const catchVar = String(this.ждём("имя", "имя причины").lexeme);
    this.пустые();
    const catchBody = this.блок(new Set<V3TokenKind>(["конец"]));
    this.закрытие("защита");
    return { kind: "попробовать", body, catchVar, catchBody };
  }

  /** `разбор` (v3) → `когда` (v2). Ветка — блоком либо короткой формой через `→`. */
  private разбор(): Stmt {
    this.съесть();
    const scrutinee = this.выражение();
    this.пустые();
    const arms: Array<{ variant: Expr; body: Stmt[] }> = [];
    let elseBody: Stmt[] | undefined;
    let форма: "стрелка" | "блок" | undefined;
    while (this.эт("есть")) {
      this.съесть();
      const тип = String(this.ждём("имя", "имя перечня").lexeme);
      this.ждём(".", "«.»");
      const вариант = String(this.ждём("имя", "имя варианта").lexeme);
      const variant: Expr = { kind: "поле", object: { kind: "переменная", name: тип }, field: вариант };
      if (this.эт("→")) {
        if (форма === "блок") throw this.ошибка("в одном «разбор» нельзя смешивать обе формы веток");
        форма = "стрелка";
        this.съесть();
        const тело: Stmt[] = [this.инструкция()];
        while (this.эт(";")) {
          this.съесть();
          тело.push(this.инструкция());
        }
        arms.push({ variant, body: тело });
        this.пустые();
      } else {
        if (форма === "стрелка") throw this.ошибка("в одном «разбор» нельзя смешивать обе формы веток");
        форма = "блок";
        this.пустые();
        arms.push({ variant, body: this.блок(new Set<V3TokenKind>(["есть", "иначе", "конец"])) });
      }
    }
    if (this.эт("иначе")) {
      this.съесть();
      if (форма === "стрелка") {
        this.ждём("→", "«→»");
        const тело: Stmt[] = [this.инструкция()];
        while (this.эт(";")) {
          this.съесть();
          тело.push(this.инструкция());
        }
        elseBody = тело;
        this.пустые();
      } else {
        this.пустые();
        elseBody = this.блок(new Set<V3TokenKind>(["конец"]));
      }
    }
    this.закрытие("разбор");
    if (arms.length === 0) throw this.ошибка("в «разбор» нет ни одной ветки «есть»");
    return { kind: "когда", scrutinee, arms, elseBody };
  }

  // ─────────────────────────── выражения ───────────────────────────

  private выражение(): Expr {
    return this.или();
  }

  private или(): Expr {
    let л = this.и();
    while (this.эт("или")) {
      this.съесть();
      л = { kind: "бинарное", op: "или", left: л, right: this.и() };
    }
    return л;
  }

  private и(): Expr {
    let л = this.не();
    while (this.эт("и")) {
      this.съесть();
      л = { kind: "бинарное", op: "и", left: л, right: this.не() };
    }
    return л;
  }

  private не(): Expr {
    if (this.эт("не") && this.можетНачатьОперанд(1)) {
      this.съесть();
      return { kind: "унарное", op: "не", arg: this.не() };
    }
    return this.сравнение();
  }

  /**
   * Сравнение. Внутри аргумента операции оно НЕ начинается: аргумент операции —
   * операнд, поэтому `длина числа == 3` читается как `(длина числа) == 3`.
   */
  private сравнение(): Expr {
    const л = this.слагаемое();
    if (this.глубинаАргумента > 0) return л;
    const k = this.пик().kind;
    if (k === "=" && this.глубинаУсловия > 0) throw this.ошибка("в условии нужно «==», а не «=»");
    if (СРАВНЕНИЯ.includes(k)) {
      if (!this.можетНачатьОперанд(1)) {
        throw this.ошибка(`после знака «${k}» ожидается выражение, получено «${this.пик(1).lexeme}»`);
      }
      this.съесть();
      const п = this.слагаемое();
      if (СРАВНЕНИЯ.includes(this.пик().kind)) {
        throw this.ошибка("цепочка сравнений запрещена: напишите «a < b и b < c»");
      }
      return { kind: "бинарное", op: k, left: л, right: п };
    }
    return л;
  }

  /**
   * Слагаемое. В плоском аргументе операции `+` и `-` НЕ продолжают операнд —
   * за счёт этого `длина числа - 1` читается как `(длина числа) - 1`, а не
   * `длина(числа - 1)`.
   */
  private слагаемое(): Expr {
    let л = this.множитель();
    while (this.плоскийАргумент === 0 && (this.эт("+") || this.эт("-"))) {
      this.отказНаСоставное();
      const op = this.съесть().kind;
      л = { kind: "бинарное", op, left: л, right: this.множитель() };
    }
    return л;
  }

  private множитель(): Expr {
    let л = this.унарный();
    for (;;) {
      const k = this.пик().kind;
      if (this.плоскийАргумент === 0 && (k === "*" || k === "/" || k === "%" || k === "нацело")) {
        this.отказНаСоставное();
        this.съесть();
        // `нацело` — написание v3, `div` — канон AST v2: та же операция, одно дерево.
        л = { kind: "бинарное", op: k === "нацело" ? "div" : k, left: л, right: this.унарный() };
        continue;
      }
      break;
    }
    return л;
  }

  /** `х += 1` — составного присваивания в языке нет; отказ называет причину. */
  private отказНаСоставное(): void {
    if (this.пик(1).kind === "=") {
      throw this.ошибка(`составного присваивания «${this.пик().lexeme}=» в языке нет: пишите «x = x …»`);
    }
  }

  private унарный(): Expr {
    if (this.эт("-") && this.можетНачатьОперанд(1)) {
      this.съесть();
      // В AST v2 унарный минус — это `0 - x`; отдельного узла там нет.
      return { kind: "бинарное", op: "-", left: { kind: "число", value: 0 }, right: this.унарный() };
    }
    return this.первичное();
  }

  /** Может ли токен со сдвигом начать ОПЕРАНД. */
  private можетНачатьОперанд(сдвиг: number): boolean {
    return НАЧАЛО_ОПЕРАНДА.includes(this.пик(сдвиг).kind);
  }

  private первичное(): Expr {
    const t = this.пик();
    if (t.kind === "число") {
      this.съесть();
      return { kind: "число", value: Number(t.value) };
    }
    if (t.kind === "строка") {
      this.съесть();
      return { kind: "строка", value: String(t.value) };
    }
    if (t.kind === "да") {
      this.съесть();
      return { kind: "булево", value: true };
    }
    if (t.kind === "нет") {
      this.съесть();
      return { kind: "булево", value: false };
    }
    if (t.kind === "пусто") {
      this.съесть();
      return { kind: "пусто" };
    }
    if (t.kind === "(") {
      // Скобки снимают ограничение операнда: внутри — полное выражение.
      this.съесть();
      const былаГлубина = this.глубинаАргумента;
      const былПлоский = this.плоскийАргумент;
      this.глубинаАргумента = 0;
      this.плоскийАргумент = 0;
      try {
        this.пустые();
        const в = this.выражение();
        this.пустые();
        this.ждём(")", "«)»");
        return this.хвосты(в);
      } finally {
        this.глубинаАргумента = былаГлубина;
        this.плоскийАргумент = былПлоский;
      }
    }
    if (t.kind === "[") {
      this.съесть();
      this.пустые();
      const elements: Expr[] = [];
      while (!this.эт("]")) {
        elements.push(this.выражение());
        this.пустые();
        if (this.эт(",")) {
          this.съесть();
          this.пустые();
        }
      }
      this.ждём("]", "«]»");
      return this.хвосты({ kind: "массив", elements });
    }
    if (t.kind === "{") {
      this.съесть();
      this.пустые();
      const entries: Array<{ key: string; value: Expr }> = [];
      while (!this.эт("}")) {
        // Ключом записи может быть имя поля, словаря — строка: `{ "хлеб": 40 }`.
        const key = this.эт("строка")
          ? String(this.съесть().value)
          : String(this.ждём("имя", "имя поля или строку-ключ").lexeme);
        this.ждём(":", "«:» после ключа");
        this.пустые();
        entries.push({ key, value: this.выражение() });
        this.пустые();
        if (this.эт(",")) {
          this.съесть();
          this.пустые();
        }
      }
      this.ждём("}", "«}»");
      return this.хвосты({ kind: "объект", entries });
    }
    if (t.kind === "имя") {
      const имя = t.lexeme;
      // Написания v2, которые иначе молча стали бы ИМЕНАМИ: `истина`/`ложь`
      // в v3 не существуют, булевы значения — `да`/`нет`.
      if (имя === "истина" || имя === "ложь") {
        throw this.ошибка(`«${имя}» — написание v2: булевы значения в v3 — «да» и «нет»`);
      }
      // Встроенная операция словами: `длина а`, `добавить в а элемент х`.
      // Признак — слово из таблицы И следующий токен, которым может начаться
      // операнд: поэтому `длина = 5` остаётся именем, а `длина числа` — вызовом.
      if (ОПЕРАЦИИ[имя] !== undefined && this.можетНачатьОперанд(1)) {
        return this.операция(имя);
      }
      this.съесть();
      // Квалифицированный вызов модуля: `Модуль.имя(…)` — ровно одна точка.
      if (this.эт(".") && this.пик(1).kind === "имя" && this.пик(2).kind === "(") {
        this.съесть(); // .
        const метод = this.съесть().lexeme;
        this.съесть(); // (
        const args = this.списокАргументов();
        if (this.эт(".")) {
          throw this.ошибка("после «Модуль.имя(…)» точка запрещена: это имя процедуры, а не значение");
        }
        return { kind: "вызов", name: resolveSyscallAlias(`${имя}.${метод}`), args };
      }
      if (this.эт("(")) {
        this.съесть();
        return this.хвосты({ kind: "вызов", name: resolveSyscallAlias(имя), args: this.списокАргументов() });
      }
      const значение = this.хвосты({ kind: "переменная", name: имя });
      if (this.эт("(")) {
        throw this.ошибка("цепочка имён перед вызовом запрещена: вызов пишется «имя(…)» или «Модуль.имя(…)»");
      }
      return значение;
    }
    throw this.ошибка(`ожидается выражение, получено «${t.lexeme}»`);
  }

  /** Хвосты значения: `.поле` (цепочка полей любой глубины) и `[индекс]`. */
  private хвосты(база: Expr): Expr {
    let в = база;
    for (;;) {
      if (this.эт(".")) {
        this.съесть();
        const field = String(this.ждём("имя", "имя поля").lexeme);
        в = { kind: "поле", object: в, field };
        continue;
      }
      if (this.эт("[")) {
        this.съесть();
        this.пустые();
        const и = this.выражение();
        this.пустые();
        this.ждём("]", "«]»");
        в = { kind: "вызов", name: ПОЛУЧИТЬ, args: [в, и] };
        continue;
      }
      break;
    }
    return в;
  }

  private списокАргументов(): Expr[] {
    const арг: Expr[] = [];
    this.пустые();
    while (!this.эт(")")) {
      арг.push(this.выражение());
      this.пустые();
      if (this.эт(",")) {
        this.съесть();
        this.пустые();
      }
    }
    this.ждём(")", "«)»");
    return арг;
  }

  /**
   * Аргумент встроенной операции — ОПЕРАНД.
   *
   * Счётчики сохраняются и восстанавливаются, поэтому ограничение действует
   * ровно на аргумент: `длина числа - 1` — это `(длина числа) - 1`.
   */
  private аргументОперанд(имя: string): Expr {
    if (!this.можетНачатьОперанд(0)) {
      throw this.ошибка(`у операции «${имя}» не хватает аргумента, получено «${this.пик().lexeme}»`);
    }
    const былПлоский = this.плоскийАргумент;
    const былаГлубина = this.глубинаАргумента;
    this.плоскийАргумент++;
    this.глубинаАргумента++;
    try {
      return this.слагаемое();
    } finally {
      this.плоскийАргумент = былПлоский;
      this.глубинаАргумента = былаГлубина;
    }
  }

  /** Аргумент действия — ВЫРАЖЕНИЕ: `вывести "а" + счёт` склеивает строку. */
  private аргументВыражение(имя: string): Expr {
    if (!this.можетНачатьОперанд(0)) {
      throw this.ошибка(`у действия «${имя}» не хватает аргумента, получено «${this.пик().lexeme}»`);
    }
    const былаГлубина = this.глубинаАргумента;
    this.глубинаАргумента++;
    try {
      return this.выражение();
    } finally {
      this.глубинаАргумента = былаГлубина;
    }
  }

  /** Встроенная операция словами: фразовые формы и разворот в системный вызов v2. */
  private операция(имя: string): Expr {
    this.съесть(); // слово-операция
    const канон = ОПЕРАЦИИ[имя]!;
    const вызвать = (арг: Expr[]): Expr => ({ kind: "вызов", name: канон, args: арг });

    if (ДЕЙСТВИЯ.has(имя)) return вызвать([this.аргументВыражение(имя)]);

    switch (имя) {
      case "добавить": {
        this.ждёмСлово("в", "нужно «добавить в <список> элемент <значение>»");
        const список = this.аргументОперанд(имя);
        this.ждёмСлово("элемент", "нужно «добавить в <список> элемент <значение>»");
        return вызвать([список, this.аргументОперанд(имя)]);
      }
      case "удалить": {
        this.ждёмСлово("из", "нужно «удалить из <список> индекс <i>»");
        const список = this.аргументОперанд(имя);
        this.ждёмСлово("индекс", "нужно «удалить из <список> индекс <i>»");
        return вызвать([список, this.аргументОперанд(имя)]);
      }
      case "содержит":
      case "найти": {
        const что = this.аргументОперанд(имя);
        this.ждёмСлово("в", `нужно «${имя} <что> в <где>»`);
        return вызвать([что, this.аргументОперанд(имя)]);
      }
      case "остаток": {
        const делимое = this.аргументОперанд(имя);
        if (!this.лексемаЭт("при")) throw this.ошибка("нужно «остаток <a> при делении на <b>»");
        this.съесть();
        this.ждёмСлово("делении", "нужно «остаток <a> при делении на <b>»");
        this.ждёмСлово("на", "нужно «остаток <a> при делении на <b>»");
        return вызвать([делимое, this.аргументОперанд(имя)]);
      }
      default:
        return вызвать([this.аргументОперанд(имя)]);
    }
  }

  /** Условие: здесь `=` — ошибка, а не молчаливое `==` (в v2 он читался как `==`). */
  private условие(): Expr {
    this.глубинаУсловия++;
    try {
      return this.выражение();
    } finally {
      this.глубинаУсловия--;
    }
  }
}
