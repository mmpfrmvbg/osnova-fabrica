/**
 * ПАРСЕР СИНТАКСИСА v3 → AST ФОРМЫ v2.
 *
 * Смысл шага (`docs/compiler-v3-plan.md`): фронтендов два, дальше путь один.
 * Здесь строится ровно тот `Program` из `src/compiler/ast.ts`, что и у v2-парсера,
 * поэтому кодоген, VM, кодировщик e2k и планировщик о v3 не знают ничего.
 *
 * Отличия v3, которые видны именно здесь:
 *   • у процедуры без возврата слово `действие`, у процедуры с возвратом — `процедура`
 *     с `→ Тип`; в AST это одна сущность `Procedure`;
 *   • `разбор` вместо `когда`, `защита`/`при ошибке как e` вместо
 *     `попробовать`/`поймать`, `поднять` вместо `выбросить`;
 *   • встроенные операции — СЛОВАМИ (`длина а`, `добавить в а элемент х`), и они
 *     разворачиваются в те же системные вызовы, что канон v2;
 *   • `=` в условии — ошибка (в v2 он молча читался как `==`).
 */

import type {
  Expr, Module, Procedure, Program, Stmt, TypeDeclaration, TypeField, TypeRef,
} from "../compiler/ast";
import { moduleNameFromFilename } from "../compiler/parser";
import { tokenizeV3, type V3Token } from "./lexer";

export interface V3Result {
  readonly program?: Program;
  readonly errors: string[];
}

/** Слова-действия, у которых аргумент — ВЫРАЖЕНИЕ, а не операнд. */
const ДЕЙСТВИЯ_С_ВЫРАЖЕНИЕМ = new Set(["вывести", "поднять"]);

/** Операции v3 → системный вызов v2 (полный список — в lexer.ts). */
import { BUILTIN_CALLS } from "./lexer";

class ОшибкаРазбора extends Error {}

export function parseV3(source: string, filename?: string): V3Result {
  const лекс = tokenizeV3(source);
  const ошибки: string[] = [...лекс.errors];
  const имяМодуля = moduleNameFromFilename(filename);
  const файл = filename ?? "вход.osnova";

  let p = 0;
  const токены = лекс.tokens;

  const пик = (n = 0): V3Token => токены[Math.min(p + n, токены.length - 1)]!;
  const съесть = (): V3Token => токены[p++]!;
  const эт = (k: string): boolean => пик().kind === k;
  const лексемаЭт = (с: string): boolean => пик().lexeme === с;

  /**
   * Отказ разбора. Объявлена `function`, а не стрелкой: только у такого
   * объявления TypeScript видит, что вызов не возвращает управление, и не требует
   * «return в конце» в каждой ветви. Это не стилистика — без этого проверка типов
   * считает достижимым код после отказа.
   */
  function беда(сообщение: string): never {
    throw new ОшибкаРазбора(`${файл}:${пик().line}: ${сообщение}`);
  }
  const ждём = (k: string, что: string): V3Token => {
    if (!эт(k)) беда(`ожидается ${что}, получено «${пик().lexeme}»`);
    return съесть();
  };
  const пустые = (): void => { while (эт("новая_строка") || эт(";")) съесть(); };

  /** Точка входа разбора: модуль — это файл целиком. */
  function разобратьПрограмму(): Program {
    const модуль: Module = { name: имяМодуля, imports: [], typeDeclarations: [], procedures: [] };
    пустые();
    while (!эт("конец_файла")) {
      if (эт("тип")) модуль.typeDeclarations.push(тип());
      else if (эт("экспорт") || эт("чистый") || эт("процедура") || (эт("идентификатор") && (лексемаЭт("действие") || лексемаЭт("чистый") || лексемаЭт("экспорт")))) модуль.procedures.push(процедура());
      else беда(`здесь ожидается «тип», «процедура» или «действие», получено «${пик().lexeme}»`);
      пустые();
    }
    return { modules: [модуль] };
  }

  // ───────────────────────────── типы ─────────────────────────────

  /** Базовые типы: в лексере у них свои виды токенов, для парсера это имена. */
  const БАЗОВЫЕ_ТИПЫ = new Set(["Число", "Строка", "Логическое", "Пусто"]);

  function имяТипа(что: string): string {
    const t = пик();
    if (t.kind === "идентификатор" || БАЗОВЫЕ_ТИПЫ.has(t.kind)) {
      // У ключевых слов `value` не заполняется — имя берётся из лексемы.
      return String(съесть().value ?? t.lexeme);
    }
    return беда(`ожидается ${что}, получено «${t.lexeme}»`);
  }

  function типСсылка(): TypeRef {
    let nullable = false;
    if (эт("?")) { съесть(); nullable = true; пустые(); }
    if (эт("Может")) {
      съесть(); пустые();
      const внутри = типСсылка();
      if (внутри.nullable) беда("«Может Может Т» — ошибка: тип и так допускает пусто");
      if (внутри.name === "Пусто") беда("«Может Пусто» — ошибка: тип не несёт значения");
      return { ...внутри, nullable: true };
    }
    if (эт("Список")) { съесть(); пустые(); const эл = типСсылка(); return { name: эл.name, nullable, array: true }; }
    if (эт("Словарь")) {
      съесть(); пустые();
      const к = типСсылка(); пустые();
      if (!эт(":")) ждём(":", "«→» между типом ключа и значением");
      съесть(); пустые();
      const з = типСсылка();
      return { name: `Словарь ${к.name} ${з.name}`, nullable };
    }
    return { name: имяТипа("имя типа"), nullable };
  }

  function тип(): TypeDeclaration {
    съесть(); // тип
    const имя = String(ждём("идентификатор", "имя типа").value);
    пустые();
    if (эт("=")) {
      съесть(); пустые();
      const варианты: string[] = [];
      for (;;) {
        варианты.push(String(ждём("идентификатор", "имя варианта").value));
        пустые();
        if (эт("|")) { съесть(); пустые(); continue; }
        break;
      }
      const объявление: TypeDeclaration = { kind: "TypeDeclaration", name: имя, fields: [], variants: варианты };
      if (filename) объявление.origin = filename;
      return объявление;
    }
    if (!эт("{")) беда("ожидается «{» или «=» после имени типа");
    съесть(); пустые();
    const поля: TypeField[] = [];
    while (!эт("}")) {
      const имяПоля = String(ждём("идентификатор", "имя поля").value);
      ждём(":", "«:» после имени поля");
      поля.push({ name: имяПоля, type: типСсылка() });
      пустые();
      if (эт(",")) { съесть(); пустые(); }
    }
    ждём("}", "«}»");
    const объявление: TypeDeclaration = { kind: "TypeDeclaration", name: имя, fields: поля };
    if (filename) объявление.origin = filename;
    return объявление;
  }

  // ─────────────────────────── процедуры ───────────────────────────

  function процедура(): Procedure {
    let exported = false;
    let pure = false;
    for (;;) {
      if (эт("экспорт")) { съесть(); exported = true; continue; }
      if (эт("чистый") || (эт("идентификатор") && лексемаЭт("чистый"))) { съесть(); pure = true; continue; }
      break;
    }
    const действие = эт("идентификатор") && лексемаЭт("действие");
    if (!эт("процедура") && !действие) беда("ожидается «процедура» или «действие»");
    съесть();
    const имя = String(ждём("идентификатор", "имя процедуры").value);
    ждём("(", "«(»");
    const params: string[] = [];
    const paramTypes: Array<TypeRef | undefined> = [];
    while (!эт(")")) {
      params.push(String(ждём("идентификатор", "имя параметра").value));
      if (эт(":")) { съесть(); paramTypes.push(типСсылка()); }
      else paramTypes.push(undefined);
      if (эт(",")) { съесть(); continue; }
      break;
    }
    ждём(")", "«)»");

    let returnType: TypeRef | undefined;
    if (эт(":") && лексемаЭт("→")) { съесть(); returnType = типСсылка(); }
    if (действие && returnType) беда("«действие» не возвращает значение: уберите «→»");
    if (!действие && !returnType) беда("«процедура» возвращает значение: укажите «→ Тип» либо пишите «действие»");

    пустые();
    const тело = блок(new Set(["конец"]));
    закрытие("");
    const п: Procedure = { name: имя, params, body: тело, exported, pure };
    // Оба ключа присутствуют всегда — v2 кладёт `undefined`, и совпадение должно быть структурным.
    п.paramTypes = paramTypes.some((т) => т !== undefined) ? paramTypes : undefined;
    // Ключ `returnType` присутствует ВСЕГДА, даже когда аннотации нет:
    // v2-парсер кладёт его как `undefined`, и AST обязан совпадать по структуре,
    // а не «по смыслу» — иначе сравнение деревьев ловит различие ключей, а не языка.
    п.returnType = returnType;
    if (filename) п.origin = filename;
    return п;
  }

  // ──────────────────────────── блоки ────────────────────────────

  /**
   * Закрытие блока. v3 пишет `конец` и НЕОБЯЗАТЕЛЬНО имя блока: `конец пока`,
   * `конец если`. Лексер уже свёл пары в один токен (`конец_пока`), поэтому здесь
   * остаётся только проверить, что закрывается именно этот блок.
   */
  function закрытие(ожидается: string): void {
    const t = пик();
    if (t.kind === "конец") { съесть(); return; }
    if (t.kind.startsWith("конец_")) {
      const канон: Record<string, string> = {
        конец_если: "если", конец_пока: "пока", конец_для: "для",
        конец_цикла: "цикл", конец_когда: "разбор", конец_попробовать: "защита",
      };
      const назван = канон[t.kind] ?? t.kind;
      if (ожидается !== "" && назван !== ожидается) {
        беда(`блок «${ожидается}» закрывается «конец ${ожидается}», а не «${t.lexeme}»`);
      }
      съесть();
      return;
    }
    беда(`ожидается «конец», получено «${t.lexeme}»`);
  }

  /** Имя закрываемого блока, если оно названо: `конец пока` → «пока». */
  function имяЗакрытия(): string {
    const t = пик();
    if (t.kind === "конец") return "";
    const канон: Record<string, string> = {
      конец_если: "если", конец_пока: "пока", конец_для: "для",
      конец_цикла: "цикл", конец_когда: "разбор", конец_попробовать: "защита",
    };
    return канон[t.kind] ?? "";
  }

  function блок(стоп: Set<string>): Stmt[] {
    const тело: Stmt[] = [];
    пустые();
    for (;;) {
      const k = пик().kind;
      if (k === "конец_файла") беда("блок не закрыт: дошли до конца файла");
      if (typeof k === "string" && стоп.has(k)) return тело;
      if (k === "конец" || k.startsWith("конец_")) {
        const назван = имяЗакрытия();
        if (назван === "" && стоп.has("конец")) return тело;
        if (назван !== "" && стоп.has(назван)) return тело;
        if (назван === "" && !стоп.has("конец")) беда("блок не закрыт: нужно «конец»");
        беда(`этот блок закрывается словом «конец», а не «${пик().lexeme}»`);
      }
      тело.push(инструкция());
      if (!(эт("новая_строка") || эт("конец_файла") || эт(";") || эт("конец") || пик().kind.startsWith("конец_"))) {
        беда(`после инструкции ожидается конец строки, получено «${пик().lexeme}»`);
      }
      пустые();
    }
  }

  // ────────────────────────── инструкции ──────────────────────────

  function инструкция(): Stmt {
    const k = пик().kind;
    switch (k) {
      case "пусть": return пусть();
      case "вернуть": {
        съесть();
        // Значение берётся только если оно ВООБЩЕ начинается: `вернуть` перед
        // `конец` — это пустой возврат, и попытка разобрать `конец` выражением
        // давала «ожидается выражение, получено «конец»».
        const значение = началоОперанда() ? выражение() : undefined;
        // `вернуть(x)` в v3 не существует: скобки — это вызов, а не группировка.
        if (значение && значение.kind === "вызов" && значение.name === "вернуть") {
          беда("возврат пишется «вернуть x», без скобок");
        }
        return { kind: "вернуть", value: значение };
      }
      case "если": return если();
      case "пока": {
        съесть(); пустые();
        const условие = условиеВыражение();
        if (эт("тогда")) съесть();
        пустые();
        const тело = блок(new Set(["пока", "конец"]));
        закрытие("пока");
        return { kind: "пока", condition: условие, body: тело };
      }
      case "для": return дляЦикл();
      case "идентификатор": {
        if (лексемаЭт("повторять")) return повторять();
        if (лексемаЭт("разбор")) return разбор();
        if (лексемаЭт("защита")) return защита();
        if (лексемаЭт("поднять")) { съесть(); пустые(); return { kind: "выбросить", value: выражение() }; }
        break;
      }
      case "цикл": {
        съесть(); пустые();
        const тело = блок(new Set(["цикл", "конец"]));
        закрытие("цикл");
        return { kind: "цикл", body: тело };
      }

      case "прервать": съесть(); return { kind: "прервать" };
      case "продолжить": съесть(); return { kind: "продолжить" };
      default: break;
    }

    // `проверить` — конструкция, а не операция: условие целиком и необязательное
    // сообщение строкой.
    if (k === "идентификатор" && лексемаЭт("проверить")) {
      съесть();
      const условие = условиеВыражение();
      let сообщение: Expr | undefined;
      if (эт(",")) { съесть(); пустые(); сообщение = выражение(); }
      const арг: Expr[] = [условие];
      if (сообщение) арг.push(сообщение);
      return { kind: "выражение", expr: { kind: "вызов", name: "проверить", args: арг } };
    }

    const л = леваяЧасть();
    if (эт("=")) {
      съесть(); пустые();
      const з = выражение();
      if (л.kind === "переменная") return { kind: "присвоить", name: л.name, value: з };
      if (л.kind === "поле") return { kind: "поле_присвоить", object: л.object, field: л.field, value: з };
      // `числа[0] = 9`: чтение по индексу разворачивается в `система.массив.получить`,
      // и запись — это ТОТ ЖЕ узел, но `установить` с третьим аргументом. Так
      // делает и v2-парсер: форма AST одна, иначе кодоген пришлось бы учить заново.
      if (л.kind === "вызов" && л.name === "система.массив.получить" && л.args.length === 2) {
        return {
          kind: "выражение",
          expr: { kind: "вызов", name: "система.массив.установить", args: [...л.args, з] },
        };
      }
      return беда("слева от «=» должно быть имя, поле или элемент");
    }
    return { kind: "выражение", expr: л };
  }

  function пусть(): Stmt {
    съесть();
    const имя = String(ждём("идентификатор", "имя переменной").value);
    let typeAnnotation: TypeRef | undefined;
    if (эт(":")) { съесть(); typeAnnotation = типСсылка(); }
    if (!эт("=")) беда("у «пусть» нет значения: объявление всегда с «= значение»");
    съесть(); пустые();
    const init = выражение();
    const с: Stmt & { kind: "пусть" } = { kind: "пусть", name: имя, init };
    if (typeAnnotation) с.typeAnnotation = typeAnnotation;
    return с;
  }

  function если(): Stmt {
    съесть(); пустые();
    const ветви: Array<{ condition: Expr; body: Stmt[] }> = [];
    let условие = условиеВыражение();
    if (эт("тогда")) съесть();
    пустые();
    ветви.push({ condition: условие, body: блок(new Set(["иначе", "иначе_если", "если", "конец"])) });
    while (эт("иначе_если")) {
      съесть(); пустые();
      условие = условиеВыражение();
      if (эт("тогда")) съесть();
      пустые();
      ветви.push({ condition: условие, body: блок(new Set(["иначе", "иначе_если", "если", "конец"])) });
    }
    let elseBody: Stmt[] | undefined;
    if (эт("иначе")) {
      съесть(); пустые();
      elseBody = блок(new Set(["если", "конец"]));
    }
    закрытие("если");
    const первая = ветви[0]!;
    const с: Stmt & { kind: "если" } = { kind: "если", condition: первая.condition, body: первая.body };
    if (ветви.length > 1) с.elseIfClauses = ветви.slice(1);
    if (elseBody) с.elseBody = elseBody;
    return с;
  }

  /**
   * `для каждого эл в списке` и `для номер от 1 до 10 шаг 3`.
   *
   * Слово `каждого` обязательно: формы `для эл в списке` в языке нет — одна форма
   * на понятие (см. `docs/osnova-spec.md`).
   */
  function дляЦикл(): Stmt {
    съесть(); // для
    пустые();
    // Форма перебора ОДНА: `для каждого <элемент> в <список>`. Формы
    // `для <элемент> в <список>` в языке нет — это названный отказ, а не «ожидается от».
    if (!(эт("идентификатор") && лексемаЭт("каждого"))) {
      if (эт("идентификатор") && пик(1).kind === "в") {
        беда("перебор пишется «для каждого <элемент> в <список>»: слово «каждого» обязательно");
      }
      беда(`после «для» ожидается «каждого», получено «${пик().lexeme}»`);
    }
    съесть();
    пустые();
    const эл = String(ждём("идентификатор", "имя элемента").value);
    let индекс: string | undefined;
    if (эт(",")) { съесть(); пустые(); индекс = String(ждём("идентификатор", "имя индекса").value); }
    if (!эт("в")) беда("в переборе нужно «в <список>»");
    съесть(); пустые();
    const источник = выражение();
    пустые();
    const тело = блок(new Set(["для", "конец"]));
    закрытие("для");
    const с: Stmt & { kind: "для_каждого" } = {
      kind: "для_каждого",
      item: эл,
      source: источник,
      body: тело,
      variable: эл,
      collection: источник,
    };
    if (индекс) с.index = индекс;
    return с;
  }

  function повторять(): Stmt {
    съесть(); пустые();
    const сколько = операнд();
    if (лексемаЭт("раза") || лексемаЭт("раз")) съесть();
    else беда("нужно «повторять <сколько> раза»");
    пустые();
    const тело = блок(new Set(["повторять", "конец"]));
    закрытие("повторять");
    // `повторять` в AST v2 нет: разворачиваем в `для_каждого` по диапазону от 1.
    const источник: Expr = {
      kind: "вызов",
      name: "диапазон",
      args: [{ kind: "число", value: 1 }, сколько],
    };
    return {
      kind: "для_каждого",
      item: "__раз",
      source: источник,
      body: тело,
      variable: "__раз",
      collection: источник,
    };
  }

  function разбор(): Stmt {
    съесть(); пустые();
    const значение = выражение();
    пустые();
    const ветви: Array<{ variant: Expr; body: Stmt[] }> = [];
    let elseBody: Stmt[] | undefined;
    while (эт("есть")) {
      съесть(); пустые();
      const тип = String(ждём("идентификатор", "имя перечня").value);
      ждём(".", "«.»");
      const вариант = String(ждём("идентификатор", "имя варианта").value);
      const вариантExpr: Expr = { kind: "поле", object: { kind: "переменная", name: тип }, field: вариант };
      пустые();
      ветви.push({ variant: вариантExpr, body: блок(new Set(["есть", "иначе", "конец"])) });
    }
    if (эт("иначе")) { съесть(); пустые(); elseBody = блок(new Set(["конец"])); }
    закрытие("разбор");
    const с: Stmt & { kind: "когда" } = { kind: "когда", scrutinee: значение, arms: ветви };
    if (elseBody) с.elseBody = elseBody;
    return с;
  }

  function защита(): Stmt {
    съесть(); пустые();
    const тело = блок(new Set(["при", "конец"]));
    let catchVar = "__ошибка";
    let catchBody: Stmt[] = [];
    пустые();
    if (эт("идентификатор") && лексемаЭт("при")) {
      съесть(); пустые();
      if (!(эт("идентификатор") && лексемаЭт("ошибке"))) беда("обработка пишется «при ошибке как <имя>»");
      съесть(); пустые();
      if (эт("идентификатор") && лексемаЭт("как")) {
        съесть(); пустые();
        catchVar = String(ждём("идентификатор", "имя причины").value);
      }
      пустые();
      catchBody = блок(new Set(["защита", "конец"]));
    }
    закрытие("защита");
    return { kind: "попробовать", body: тело, catchVar, catchBody };
  }

  // ─────────────────────────── выражения ───────────────────────────

  /**
   * Разбор имени инструкции: слева от `=` стоит имя, поле или элемент, поэтому
   * встроенные операции тут не разворачиваются (иначе `длина = 5` стало бы вызовом).
   */
  function леваяЧасть(): Expr {
    const имя = String(ждём("идентификатор", "инструкцию").value);
    let в: Expr = { kind: "переменная", name: имя };
    for (;;) {
      if (эт(".")) {
        съесть();
        const поле = String(ждём("идентификатор", "имя поля").value);
        в = { kind: "поле", object: в, field: поле };
        continue;
      }
      if (эт("[")) { съесть(); пустые(); const и = выражение(); пустые(); ждём("]", "«]»"); в = индекс(в, и); continue; }
      break;
    }
    return в;
  }

  /** Присваивание/чтение по индексу — в AST v2 это системный вызов. */
  function индекс(объект: Expr, и: Expr): Expr {
    return { kind: "вызов", name: "система.массив.получить", args: [объект, и] };
  }

  /** Условие: `=` здесь ЗАПРЕЩЁН (в v2 он молча читался как `==`). */
  function условиеВыражение(): Expr {
    const в = выражение();
    return в;
  }

  /** Тот же вопрос про токен со сдвигом: идёт ли ЗА ним операнд. */
  function началоОперандаПосле(сдвиг: number): boolean {
    const k = пик(сдвиг).kind;
    if (k === "конец" || k.startsWith("конец_")) return false;
    return [
      "число", "строка", "истина", "ложь", "пусто", "идентификатор", "(", "[", "{", "-", "не",
    ].includes(k);
  }

  /** За знаком операции идёт операнд? Иначе знак — не наш. */
  function знакПродолжает(): boolean {
    const следующий = пик(1).kind;
    if (следующий === "конец" || следующий.startsWith("конец_")) return false;
    return [
      "число", "строка", "истина", "ложь", "пусто", "идентификатор", "(", "[", "{", "-", "не",
    ].includes(следующий);
  }

  function выражение(): Expr { return или(); }

  function или(): Expr {
    let л = и();
    while (эт("или")) { съесть(); пустые(); л = { kind: "бинарное", op: "или", left: л, right: и() }; }
    return л;
  }

  function и(): Expr {
    let л = отрицание();
    while (эт("и")) { съесть(); пустые(); л = { kind: "бинарное", op: "и", left: л, right: отрицание() }; }
    return л;
  }

  function отрицание(): Expr {
    if (эт("не")) { съесть(); пустые(); return { kind: "унарное", op: "не", arg: отрицание() }; }
    return сравнение();
  }

  function сравнение(): Expr {
    const л = слагаемое();
    const k = пик().kind;
    if (k === "=") {
      беда("в условии нужно «==», а не «=»: в v3 «=» — только присваивание");
    }
    if (k === "==" || k === "!=" || k === "<" || k === "<=" || k === ">" || k === ">=") {
      съесть(); пустые();
      const п = слагаемое();
      const после = пик().kind;
      if (после === "==" || после === "!=" || после === "<" || после === "<=" || после === ">" || после === ">=") {
        беда("цепочка сравнений запрещена: напишите «a < b и b < c»");
      }
      return { kind: "бинарное", op: k, left: л, right: п };
    }
    return л;
  }

  function слагаемое(): Expr {
    let л = множитель();
    while ((эт("+") || эт("-")) && знакПродолжает()) {
      const op = съесть().kind;
      пустые();
      л = { kind: "бинарное", op, left: л, right: множитель() };
    }
    return л;
  }

  function множитель(): Expr {
    let л = унарный();
    for (;;) {
      const k = пик().kind;
      if ((k === "*" || k === "/" || k === "%" || k === "div") && знакПродолжает()) {
        съесть(); пустые();
        л = { kind: "бинарное", op: k === "div" ? "div" : k, left: л, right: унарный() };
        continue;
      }
      break;
    }
    return л;
  }

  function унарный(): Expr {
    if (эт("-")) { съесть(); пустые(); const а = унарный(); return { kind: "бинарное", op: "-", left: { kind: "число", value: 0 }, right: а }; }
    return первичное();
  }

  /** Операнд — то, что берёт встроенная операция: без знаков, без сравнений. */
  function операнд(): Expr { return унарный(); }

  /**
   * Может ли текущий токен начать ОПЕРАНД в аргументе операции. Нужно, чтобы
   * `длина числа - 1` не уехало в `длина(числа - 1)`, а `вернуть 0` не пыталось
   * взять `конец` как аргумент.
   */
  function началоОперанда(): boolean {
    const k = пик().kind;
    if (k === "конец" || k.startsWith("конец_")) return false;
    return [
      "число", "строка", "истина", "ложь", "пусто", "идентификатор", "(", "[", "{", "-", "не",
    ].includes(k);
  }

  function первичное(): Expr {
    const t = пик();
    if (t.kind === "число") { съесть(); return { kind: "число", value: Number(t.value) }; }
    if (t.kind === "строка") { съесть(); return { kind: "строка", value: String(t.value) }; }
    if (t.kind === "истина") { съесть(); return { kind: "булево", value: true }; }
    if (t.kind === "ложь") { съесть(); return { kind: "булево", value: false }; }
    if (t.kind === "пусто") { съесть(); return { kind: "пусто" }; }

    if (t.kind === "(") {
      съесть(); пустые();
      const в = выражение();
      пустые(); ждём(")", "«)»");
      return хвосты(в);
    }
    if (t.kind === "[") {
      съесть(); пустые();
      const элементы: Expr[] = [];
      while (!эт("]")) {
        элементы.push(выражение());
        пустые();
        if (эт(",")) { съесть(); пустые(); }
      }
      ждём("]", "«]»");
      return { kind: "массив", elements: элементы };
    }
    if (t.kind === "{") {
      съесть(); пустые();
      const entries: Array<{ key: string; value: Expr }> = [];
      while (!эт("}")) {
        const ключ = эт("строка")
          ? String(съесть().value)
          : String(ждём("идентификатор", "имя поля или строку-ключ").value);
        ждём(":", "«:»");
        пустые();
        entries.push({ key: ключ, value: выражение() });
        пустые();
        if (эт(",")) { съесть(); пустые(); }
      }
      ждём("}", "«}»");
      return { kind: "объект", entries };
    }

    if (t.kind === "идентификатор") {
      // Встроенная операция словами: `длина а`, `добавить в а элемент х`.
      const имя = t.lexeme;
      // Слово-операция разворачивается только тогда, когда ЗА НИМ есть операнд:
      // иначе `длина` перед `конец` — это обычное имя (`вернуть длина`).
      if (
        BUILTIN_CALLS[имя] !== undefined &&
        пик(1).kind !== "=" && пик(1).kind !== "+=" && пик(1).kind !== "-=" &&
        пик(1).kind !== "." && пик(1).kind !== "[" && пик(1).kind !== "(" &&
        началоОперандаПосле(1)
      ) {
        return операция(имя);
      }
      съесть();
      // Квалифицированный вызов модуля: `Модуль.имя(…)` — ровно одна точка.
      if (эт(".") && пик(1).kind === "идентификатор" && пик(2).kind === "(") {
        съесть(); const второе = String(съесть().value); съесть();
        return { kind: "вызов", name: `${имя}.${второе}`, args: списокАргументов() };
      }
      let в: Expr = { kind: "переменная", name: имя };
      if (эт("(")) { съесть(); в = { kind: "вызов", name: имя, args: списокАргументов() }; }
      return хвосты(в);
    }

    беда(`ожидается выражение, получено «${t.lexeme}»`);
  }

  /** Хвосты: `.поле` (любой глубины — цепочка ПОЛЕЙ) и `[индекс]`. */
  function хвосты(база: Expr): Expr {
    let в = база;
    for (;;) {
      if (эт(".")) {
        съесть();
        const поле = String(ждём("идентификатор", "имя поля").value);
        в = { kind: "поле", object: в, field: поле };
        continue;
      }
      if (эт("[")) { съесть(); пустые(); const и = выражение(); пустые(); ждём("]", "«]»"); в = индекс(в, и); continue; }
      break;
    }
    return в;
  }

  function списокАргументов(): Expr[] {
    const арг: Expr[] = [];
    пустые();
    while (!эт(")")) {
      арг.push(выражение());
      пустые();
      if (эт(",")) { съесть(); пустые(); }
    }
    ждём(")", "«)»");
    return арг;
  }

  /**
   * Встроенная операция словами. Правило аргумента — то же, что в спецификации:
   * у операции аргумент ОПЕРАНД (`длина числа - 1` = `(длина числа) - 1`),
   * у действий `вывести`/`поднять` — ВЫРАЖЕНИЕ (`вывести "а" + счёт`).
   */
  function операция(имя: string): Expr {
    съесть(); // имя операции
    const канон = BUILTIN_CALLS[имя]!;
    const арг: Expr[] = [];

    if (ДЕЙСТВИЯ_С_ВЫРАЖЕНИЕМ.has(имя)) {
      пустые();
      арг.push(выражение());
      return { kind: "вызов", name: канон, args: арг };
    }

    if (имя === "добавить") {
      if (!лексемаЭт("в")) беда("нужно «добавить в <список> элемент <значение>»");
      съесть(); пустые();
      арг.push(операнд());
      if (!лексемаЭт("элемент")) беда("нужно «добавить в <список> элемент <значение>»");
      съесть(); пустые();
      арг.push(выражение());
      return { kind: "вызов", name: канон, args: арг };
    }
    if (имя === "удалить") {
      if (!лексемаЭт("из")) беда("нужно «удалить из <список> индекс <i>»");
      съесть(); пустые();
      арг.push(операнд());
      if (!лексемаЭт("индекс")) беда("нужно «удалить из <список> индекс <i>»");
      съесть(); пустые();
      арг.push(выражение());
      return { kind: "вызов", name: канон, args: арг };
    }
    if (имя === "содержит" || имя === "найти") {
      пустые();
      арг.push(операнд());
      if (!лексемаЭт("в")) беда(`нужно «${имя} <что> в <где>»`);
      съесть(); пустые();
      арг.push(выражение());
      return { kind: "вызов", name: канон, args: арг };
    }
    if (имя === "остаток") {
      пустые();
      арг.push(операнд());
      if (лексемаЭт("при")) {
        съесть(); пустые();
        if (!лексемаЭт("делении")) беда("нужно «остаток <a> при делении на <b>»");
        съесть(); пустые();
        if (!лексемаЭт("на")) беда("нужно «остаток <a> при делении на <b>»");
        съесть(); пустые();
        арг.push(операнд());
      }
      return { kind: "вызов", name: канон, args: арг };
    }

    // Прочие операции: один операнд.
    пустые();
    арг.push(операнд());
    return { kind: "вызов", name: канон, args: арг };
  }

  try {
    const program = разобратьПрограмму();
    if (ошибки.length > 0) return { errors: ошибки };
    return { program, errors: [] };
  } catch (e) {
    if (e instanceof ОшибкаРазбора) return { errors: [...ошибки, e.message] };
    throw e;
  }
}
