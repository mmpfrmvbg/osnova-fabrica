/**
 * ОРАКУЛ РАННЕРА: модель обязана быть слышна, а не только её код возврата.
 *
 * Повод. Код 134 читался как «модель упала» без причины: раннер собирал вывод модели
 * (`QemuRun.output`), но не отдавал его наружу. Из-за этого «падение» и «отказ» были
 * неразличимы, и выводы делались по коду вместо причины. Измерено 2026-09-27: причина
 * оказалась словами модели — утверждение про полуслог `AAS2` в `decoder.c`.
 *
 * Второе, что здесь закреплено: **программа без возврата значения на цели ПАДАЕТ**
 * (код 134), а не завершается нулём. Это не дефект обвязки выхода: последовательность
 * выхода для такого случая добавляется, и три её формы (без выхода, `adds` с нулём,
 * прямая `movts` нуля) дают один и тот же отказ — значит поток без завершающего `IR.ret`
 * не сходится, и печатающая программа обязана завершаться своим `exit`
 * (`src/e2k/printRuntime.ts`), а не отсутствием возврата.
 * Подпись отказа при этом НЕ устойчива (`AAS2` в `decoder.c` либо `op_descr->is_al`
 * в `translate-lookahead.c`) — потому что поток уходит за свой код и упирается в мусор;
 * поэтому сторож требует утверждение, а не конкретный его текст.
 */
import { describe, expect, it } from "vitest";
import { runOnE2k, shimAvailable, SHIM_REASON } from "./e2kProgramRun";

const available = shimAvailable();

/** Программа без возврата значения: телом работа есть, результата наружу нет. */
const noReturn = `процедура главная()
  пусть а = [7, 8, 9]
  пусть индекс = 0
  пусть сумма = 0
  пока индекс < система.массив.длина(а)
    сумма = сумма + система.массив.получить(а, индекс)
    индекс = индекс + 1
  конец_пока
конец_процедуры
`;

/** Контроль: та же работа с возвратом — заведомо исполняемый случай. */
const withReturn = `процедура главная()
  пусть а = [7, 8, 9]
  пусть индекс = 0
  пусть сумма = 0
  пока индекс < система.массив.длина(а)
    сумма = сумма + система.массив.получить(а, индекс)
    индекс = индекс + 1
  конец_пока
  вернуть сумма
конец_процедуры
`;

describe("раннер цели: вывод модели виден, и он же — причина", () => {
  it("шим доступен — или причина названа", () => {
    if (!available) {
      expect(SHIM_REASON.length).toBeGreaterThan(10);
      return;
    }
    expect(available).toBe(true);
  });

  it("программа с возвратом: код 24 и вывод модели пуст (падения нет)", () => {
    if (!available) return;
    const run = runOnE2k(withReturn, "oracle-runner-with-return.elf");
    expect(run.status, "7 + 8 + 9 = 24").toBe(24);
    expect(run.output.trim(), "у рабочего прогона модель молчит").toBe("");
  });

  it("вывод модели доходит наружу: у падения есть СЛОВА, а не только код", () => {
    if (!available) return;
    const run = runOnE2k(noReturn, "oracle-runner-no-return.elf");
    // Код падения закрепляем: если он изменится, это увидит сторож, а не читатель.
    expect(run.status, "программа без возврата падает").toBe(134);
    // Главное: причина обязана быть доступна текстом. Пустой вывод = канал снова закрыт.
    expect(run.output.trim().length, "модель обязана назвать причину").toBeGreaterThan(0);
    // САМУ подпись НЕ закрепляем, и это измеренный вывод: она НЕ устойчива — в одном прогоне
    // утверждение про полуслог `AAS2` (`decoder.c`), в другом `op_descr->is_al`
    // (`translate-lookahead.c`). Обе — про то, что поток ушёл за свой код и упёрся в мусор,
    // но какую именно команду порт увидит первой, зависит от того, куда провалился поток.
    // Поэтому сторожим признак утверждения, а не его текст: узкая проверка на `AAS2`
    // краснела на верном поведении (поймано этим же оракулом).
    expect(run.output, "модель обязана сказать «Assertion failed»").toContain("Assertion failed");
  });

  it("НЕГАТИВНЫЙ КОНТРОЛЬ канала: у рабочего прогона вывод пуст, у падения — нет", () => {
    if (!available) return;
    // Если бы раннер отдавал один и тот же текст всегда, предыдущая проверка ничего не значила.
    const ok = runOnE2k(withReturn, "oracle-runner-control-ok.elf");
    const bad = runOnE2k(noReturn, "oracle-runner-control-bad.elf");
    expect(ok.output.trim()).not.toBe(bad.output.trim());
    expect(bad.output.trim()).not.toBe("");
  });
});
