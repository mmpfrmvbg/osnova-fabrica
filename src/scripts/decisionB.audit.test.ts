/**
 * ОРАКУЛ РЕШЕНИЯ B: защита от регрессии в документах.
 *
 * ## Зачем тест на документах
 *
 * Решение владельца «идём в B» определяет, что специфицировать в Фазе 3, какой
 * корпус строить и как измерять выигрыш. Пока оно живёт только в тексте, его можно
 * потерять: удалить блок при переписывании памяти, вернуть формулировку «A/B/C не
 * выбран», забыть создать документ требований. Тогда следующий сеанс (в том числе
 * мой собственный) снова начнёт ждать решения, которое уже принято.
 *
 * Это тот же приём, что `sourceAudit.test.ts` для констант модели и
 * `packetPacker.audit.test.ts` для инъекции дефектов: проверяется не «код делает
 * что-то», а **наличие обязательного факта в дереве**.
 *
 * ## Почему текст схлопывается перед проверкой
 *
 * Markdown переносит строки произвольно: одна и та же фраза может оказаться
 * разорванной переводом строки. Поэтому все проверки идут по тексту с
 * схлопнутыми пробелами — иначе тест ловит перенос строки, а не исчезновение
 * формулировки. Побочная выгода: запрещённая формулировка, разорванная переносом,
 * тоже находится.
 *
 * ## Что проверяется
 *
 * 1. `memory/_index.md` содержит блок «Стратегическое решение: B» с датой.
 * 2. В `docs/vliw-phases-plan.md` НЕТ формулировок «A/B/C не выбран».
 * 3. `docs/e2k-subset-requirements.md` существует и содержит разделы 2.1–2.5.
 * 4. `docs/hardware-debt.md` существует и содержит разделы 3.1–3.5.
 * 5. В плане фаз зафиксированы фазы под B: 3 — спецификация, 4 — эмиттер,
 *    5 — симулятор, 6 — валидация на железе, 7 — корпус разноплановых программ.
 * 6. Формулировка цели и следующий шаг присутствуют дословно.
 */

import * as fs from "fs";
import * as path from "path";
import { describe, it, expect } from "vitest";

const ROOT = path.resolve(__dirname, "..", "..");

/** Текст документа со схлопнутыми пробелами (markdown переносит фразы произвольно). */
function read(rel: string): string {
  const full = path.join(ROOT, rel);
  if (!fs.existsSync(full)) throw new Error(`нет файла: ${rel}`);
  return fs.readFileSync(full, "utf-8").replace(/\s+/g, " ");
}

const INDEX = path.join("memory", "_index.md");
const PLAN = path.join("docs", "vliw-phases-plan.md");
const SUBSET = path.join("docs", "e2k-subset-requirements.md");
const DEBT = path.join("docs", "hardware-debt.md");

describe("решение B защищено от регрессии в документах", () => {
  it("в memory/_index.md есть блок «Стратегическое решение: B» с датой", () => {
    const index = read(INDEX);
    expect(index).toContain("## Стратегическое решение: B");
    expect(index).toMatch(/Стратегическое решение: B \(2026-09-15\)/);
  });

  it("формулировка цели зафиксирована дословно", () => {
    const index = read(INDEX);
    expect(index).toContain("Целевой класс — B: специализированные задачи с высоким ILP");
    expect(index).toContain("Кратное ускорение везде не является целью");
    // Уточнение, которое легко потерять при переписывании: низкий ILP — свойство
    // задачи, а не дефект.
    expect(index).toContain("это свойство задачи, а не дефект");
    // И следствие про ширину подмножества: иначе инфраструктура уйдёт под нишу.
    expect(index).toContain("подмножество e2k должно быть ШИРОКИМ");
  });

  it("в плане фаз нет формулировок «A/B/C не выбран»", () => {
    const plan = read(PLAN);
    const forbidden = [
      "A/B/C не выбран",
      "A/B/C пока не выбран",
      "A, B или C не выбран",
      "развилка не выбрана",
      "класс задачи не выбран",
    ];
    for (const phrase of forbidden) expect(plan).not.toContain(phrase);
    expect(plan).toContain("РЕШЕНИЕ ВЛАДЕЛЬЦА (2026-09-15): идём в B");
  });

  it("фазы под B перечислены: 3 спецификация, 4 эмиттер, 5 симулятор, 6 железо, 7 корпус", () => {
    const plan = read(PLAN);
    expect(plan).toMatch(/## Фаза 3\. Спецификация подмножества e2k/);
    expect(plan).toMatch(/## Фаза 4\. Эмиттер e2k/);
    expect(plan).toMatch(/## Фаза 5\. Симулятор e2k/);
    expect(plan).toMatch(/## Фаза 6\. Валидация на реальном железе/);
    expect(plan).toMatch(/## Фаза 7\. Корпус разноплановых программ/);
  });

  it("требования к подмножеству: файл и разделы 2.1–2.5", () => {
    const doc = read(SUBSET);
    for (const section of ["2.1.", "2.2.", "2.3.", "2.4.", "2.5."]) {
      expect(doc, `раздел ${section}`).toContain(`## ${section}`);
    }
    // Это требования, а не спецификация — и это должно быть сказано.
    expect(doc).toContain("ЭТО НЕ СПЕЦИФИКАЦИЯ ISA");
    // Каждое утверждение — со источником или пометкой «НАШЕ РЕШЕНИЕ».
    expect(doc).toContain("НАШЕ РЕШЕНИЕ");
    // Задача внутри B выбрана (DSP), и это зафиксировано здесь же.
    expect(doc).toContain("DSP");
  });

  it("реестр долга перед железом: файл и разделы 3.1–3.5", () => {
    const doc = read(DEBT);
    for (const section of ["3.1.", "3.2.", "3.3.", "3.4.", "3.5."]) {
      expect(doc, `раздел ${section}`).toContain(`## ${section}`);
    }
    // Ключевые факты, которые нельзя потерять.
    expect(doc).toContain("НИ ЖЕЛЕЗА, НИ СИМУЛЯТОРА");
    expect(doc).toContain("шаги VM — не метрика скорости");
  });

  it("решение о задаче внутри B записано: выбран DSP", () => {
    const index = read(INDEX);
    expect(index).toContain("Задача внутри B выбрана: DSP");
    expect(index).toContain("Решение владельца");
    // Следующий шаг после выбора — спецификация под DSP, а не выбор заново.
    expect(index).toMatch(/спецификация подмножества под DSP/i);
  });
});
