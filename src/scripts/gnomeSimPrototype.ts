/**
 * ПРОТОТИП DF: ТИК СИМУЛЯЦИИ НА КОЛЛЕКЦИЯХ — ПЕРВОЕ ЧИСЛО ПРОИЗВОДИТЕЛЬНОСТИ.
 *
 * # Что спрашивается
 *
 * `N` сущностей (гномов) с позициями живут в коллекциях; **тик** обновляет позиции и считает
 * расстояние до соседа. Спрашивается **миллисекунды на тик** для `N = 100`, `1000`, `10000`.
 *
 * # Что здесь НЕ измеряется, и это названо, а не умолчано
 *
 * | граница | почему |
 * |---|---|
 * | это МОДЕЛЬ (`qemu-e2k` под шимом в WSL), а не железо | на железе числа будут другими; здесь — **первое** число и его порядок |
 * | запись гнома = ДВА числа (`X`, `Y`), то есть два массива | элемент коллекции — одно 8-байтовое слово: записи-структуры в языке ещё нет (долг языка, §3.103.2) |
 * | тик ЛИНЕЕН по `N` (обновление + расстояние до СОСЕДА) | коллизии «каждый с каждым» — это `O(N²)`, другой порядок роста и отдельное число; смешивать их нельзя |
 * | ёмкость берётся сразу `N` | рост (удвоение против «+1») — предмет §3.102.4, а не этого замера |
 * | время процесса (WSL + QEMU + загрузка ELF) ВЫЧТЕНО | замер идёт тремя точками: пустая программа → инициализация → инициализация + `T` тиков |
 *
 * # Почему ответу можно верить: ЭТАЛОН СЧИТАЕТСЯ ЗДЕСЬ ЖЕ
 *
 * Число без проверки — не замер, а секундомер. Поэтому та же самая модель тика посчитана в JS (с
 * 32-битной арифметикой, как у цели: `muls`/`adds` пишут младшую половину), и контрольная сумма,
 * напечатанная гостем, обязана совпасть **побитово**. Не совпала — замер недействителен, и скрипт
 * говорит это вслух.
 */
import * as fs from 'fs';
import * as path from 'path';
import { MINIMAL_BASE, buildElfFromCode } from '../e2k/elfMinimal';
import { buildE2kImage } from './e2kProgramRun';
import { runInQemu } from './e2kQemuExec';

const ROOT = path.resolve(__dirname, '..', '..');

/** Модуль в диалекте стенда: точка входа — `главная`, как у всех программ линии e2k. */
const модуль = (тело: string): string => `модуль Гномы\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/**
 * ПРОГРАММА ТИКА — ЦИКЛАМИ ЯЗЫКА, без развёртки: два `пока` (тики и гномы) и два `если`.
 *
 * Гном за тик: прочитать `x`, `y`; сдвинуть позицию с заворотом на 100; записать её; прочитать
 * `x`, `y` СОСЕДА и добавить квадрат расстояния до него. ПЯТЬ обращений к коллекциям на гнома —
 * и именно это число отличает «коллекции работают» от «коллекции успевают».
 *
 * # ЧТО ЗДЕСЬ СТОИЛО ПОПЫТОК, И ЭТО РЕЗУЛЬТАТ, А НЕ ЧЕРНОВИК
 *
 * У точки входа ВОСЕМЬ раскладываемых регистров (`%b[0..7]`): `%b[8]`,`%b[9]` держит рантайм
 * коллекций, `%b[10..15]` — полоса рантайма массивов, и в ней же живут временные сайтов, поэтому
 * программе её отдавать нельзя. Первая редакция прототипа в раскладку НЕ ВЛЕЗЛА:
 *
 * | редакция | наблюдение раскладки |
 * |---|---|
 * | инициализация с `div` (клетка = номер mod 100) + тик | **«в тесный момент живы 14 отрезков, свободных 8»** |
 * | тот же тик с ПРЯМОЙ инициализацией (`X[j] = j`, `Y[j] = j`) | **собирается, 8 регистров из 8** |
 * | тик, где чтение соседа ПОВТОРЕНО в выражении (4 чтения вместо 2) | **отказ: живых 14** |
 *
 * То есть цену платит не тик, а `div` В ИНИЦИАЛИЗАЦИИ (`idiv` разворачивается в `sdivs` плюс
 * развёртку остатка, и её временные живут дольше, чем бюджет позволяет) и ПОВТОРНЫЕ обращения
 * вместо одного чтения в переменную. Тик с расстоянием до соседа укладывается РОВНО в бюджет —
 * и это первое, что упрётся в DF: не скорость, а ЧИСЛО ОДНОВРЕМЕННО ЖИВЫХ ЗНАЧЕНИЙ.
 */
const программа = (N: number, T: number): string =>
  модуль(
    [
      `  пусть X = система.коллекция.выделить(${String(N)})`,
      `  пусть Y = система.коллекция.выделить(${String(N)})`,
      `  пусть номер = ${String(N)}`,
      '  пока номер > 0',
      '    номер = номер - 1',
      '    система.коллекция.положить(X, номер, номер)',
      '    система.коллекция.положить(Y, номер, номер)',
      '  конец_пока',
      `  пусть тик = ${String(T)}`,
      '  пусть сумма = 0',
      '  пока тик > 0',
      `    пусть j = ${String(N)}`,
      '    пока j > 0',
      '      j = j - 1',
      '      пусть x = система.коллекция.взять(X, j)',
      '      пусть y = система.коллекция.взять(Y, j)',
      '      пусть nx = x + 1',
      '      если nx > 99',
      '        nx = 0',
      '      конец_если',
      '      система.коллекция.положить(X, j, nx)',
      '      пусть k = j + 1',
      `      если k >= ${String(N)}`,
      '        k = 0',
      '      конец_если',
      '      пусть x2 = система.коллекция.взять(X, k)',
      '      пусть y2 = система.коллекция.взять(Y, k)',
      '      пусть dx = nx - x2',
      '      пусть dy = y - y2',
      // РАССТОЯНИЕ ДО СОСЕДА — то самое «посчитать простое»: два умножения и два сложения на гнома.
      '      сумма = сумма + dx * dx + dy * dy',
      '    конец_пока',
      '    тик = тик - 1',
      '  конец_пока',
      '  система.лог.вывести(сумма)',
      '  вернуть 0',
    ].join('\n'),
  );

/** ПУСТАЯ программа: только процесс. Вычитается из всего — это цена WSL, QEMU и загрузки ELF. */
const пустая = модуль('  вернуть 0');

/**
 * ЭТАЛОН ТИКА — на JS, и он ОБЯЗАН совпасть с гостем побитово.
 *
 * Арифметика 32-битная (`| 0`), как у цели: `muls`/`adds` пишут младшую половину. Порядок обхода —
 * ТОТ ЖЕ (счёт вниз, запись `X[j]` ДО чтения `X[k]`, где `k = j + 1` с заворотом), иначе эталон
 * разошёлся бы с гостем на пустом месте, а не на дефекте.
 */
function эталонСуммы(N: number, T: number): number {
  const X: number[] = [];
  const Y: number[] = [];
  for (let номер = N; номер > 0; ) {
    номер -= 1;
    X[номер] = номер;
    Y[номер] = номер;
  }
  let сумма = 0;
  for (let тик = T; тик > 0; тик -= 1) {
    for (let j = N; j > 0; ) {
      j -= 1;
      const x = X[j]!;
      const y = Y[j]!;
      let nx = (x + 1) | 0;
      if (nx > 99) nx = 0;
      X[j] = nx;
      let k = j + 1;
      if (k >= N) k = 0;
      const x2 = X[k]!;
      const y2 = Y[k]!;
      const dx = (nx - x2) | 0;
      const dy = (y - y2) | 0;
      сумма = (сумма + ((dx * dx) | 0) + ((dy * dy) | 0)) | 0;
    }
  }
  return сумма;
}

interface Точка {
  readonly ms: number;
  readonly status: number | null | undefined;
  readonly вывод: string;
  readonly отказов: number;
}

/** Один прогон: конвейер — ВНЕ замера (он на хосте), замер — только прогон модели. */
function прогон(source: string, файл: string): Точка {
  let image;
  try {
    image = buildE2kImage(source);
  } catch (error) {
    // ОТКАЗ КОНВЕЙЕРА — ТОЖЕ РЕЗУЛЬТАТ ЗАМЕРА, и он называется, а не падает трейсбеком: раскладка
    // регистров отказывает, когда живых значений больше, чем раскладка готова вытеснить.
    console.log(`   отказ конвейера: ${error instanceof Error ? error.message : String(error)}`);
    return { ms: 0, status: undefined, вывод: '', отказов: -1 };
  }
  const elf = path.join(ROOT, '.tmp', `.gnome-${файл}.elf`);
  fs.writeFileSync(
    elf,
    buildElfFromCode(image.bytes, MINIMAL_BASE, { writable: true, extraMemory: image.extraMemory }).bytes,
  );
  const начало = Date.now();
  const run = runInQemu(elf, { shim: true, timeoutMs: 900_000 });
  const ms = Date.now() - начало;
  return { ms, status: run?.status, вывод: (run?.stdout ?? '').trim(), отказов: image.refused.length };
}

const пустойПрогон = прогон(пустая, 'empty');
console.log(`пустая программа: ${String(пустойПрогон.ms)} мс, код ${String(пустойПрогон.status)}, отказов ${String(пустойПрогон.отказов)}`);
console.log('');

/**
 * МИНИМУМ ИЗ ТРЁХ — потому что замер ЭТО ПОКАЗАЛ, а не потому что «так принято».
 *
 * Первая редакция мерила по одному прогону, и старт процесса (WSL + QEMU + загрузка ELF) гулял на
 * **±1 с**: разность «инициализация − пустая» вышла **−1159 мс**, а «мс на тик» для N=100 — 0.01 мс.
 * Шум старта больше измеряемой работы, и вычитать его по одной точке нельзя. Минимум из трёх берёт
 * НИЖНЮЮ границу стоимости процесса (она воспроизводима), а работа тиков добавляется к ней целиком.
 */
function лучший(source: string, файл: string, повторов = 3): Точка {
  let лучшая = прогон(source, `${файл}-0`);
  for (let повтор = 1; повтор < повторов; повтор++) {
    const точка = прогон(source, `${файл}-${String(повтор)}`);
    if (точка.ms < лучшая.ms) лучшая = точка;
  }
  return лучшая;
}

console.log('N      T       процесс   инициализация  T тиков    мс/тик    обращений/тик  сумма (гость)  эталон  сходится');
console.log('(мс на тик считается как (с тиками − только инициализация) / T, обе точки — минимум из 3)');

let всёСошлось = true;
const пусто = лучший(пустая, 'empty-min').ms;
for (const [N, T] of [
  [100, 80000],
  [1000, 8000],
  [10000, 800],
] as const) {
  const толькоInit = лучший(программа(N, 0), `init-${String(N)}`);
  const сТиками = лучший(программа(N, T), `ticks-${String(N)}`);
  const инициализация = толькоInit.ms - пусто;
  const наТики = сТиками.ms - толькоInit.ms;
  const наТик = наТики / T;
  const эталон = эталонСуммы(N, T);
  const сошлось = Number(сТиками.вывод) === эталон;
  if (!сошлось) всёСошлось = false;
  console.log(
    `${String(N).padEnd(6)} ${String(T).padEnd(7)} ${`${String(пусто)} мс`.padEnd(9)} ` +
      `${`${String(инициализация)} мс`.padEnd(14)} ${`${String(наТики)} мс`.padEnd(10)} ` +
      `${`${наТик.toFixed(3)} мс`.padEnd(9)} ${String(5 * N).padEnd(14)} ` +
      `${сТиками.вывод.padEnd(14)} ${String(эталон).padEnd(7)} ${сошлось ? 'ДА' : 'НЕТ'}`,
  );
}

