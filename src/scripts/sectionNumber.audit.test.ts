/**
 * ОРАКУЛ СТОРОЖА УНИКАЛЬНОСТИ НОМЕРА РАЗДЕЛА — OSN-GATE-SECTION.
 *
 * Предмет — `src/scripts/sectionNumber.audit.ts`. Реестр железа адресуется НОМЕРОМ, поэтому два
 * раздела с одним номером делают адрес неоднозначным молча.
 *
 * # Негативные контроли и их имена
 *
 * | N | что ломается | что обязано покраснеть |
 * |---|---|---|
 * | **1** | два `##` делят номер | «номер X занят 2 раза» |
 * | **2** | буквенный суффикс считается мусором (`3.95.5а` = `3.95.5`) | ЛОЖНОЕ красное — контроль в обратную сторону |
 * | **3** | сторож ищет только `§`, а старый стиль без `§` не видит | «ни одного заголовка не найдено» |
 * | **4** | дубль стоит на РАЗНЫХ уровнях (`##`/`###`) | обязан быть пойман (первая редакция его теряла) |
 *
 * # Почему контроль 2 идёт «в обратную сторону»
 *
 * Обычный негативный контроль доказывает, что сторож КРАСНЕЕТ на дефекте. Но у сторожа есть второй
 * способ быть бесполезным — краснеть на исправном файле: такое красное снимают первым же PR вместе
 * со сторожем (случай 31). `3.95.5а` — настоящий подпункт настоящего файла, и сторож обязан считать
 * его ОТДЕЛЬНЫМ адресом.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import {
  HARDWARE_DEBT,
  SECTION_GATE_CODE,
  auditHardwareDebt,
  findSectionCollisions,
  parseSectionHeadings,
} from './sectionNumber.audit';

const ROOT = path.resolve(__dirname, '..', '..');

/** Заголовки раздела: ровно тот вид, который встречается в реестре. */
describe('сторож номера раздела: разбор заголовков', () => {
  it('берёт оба стиля — со знаком § и без него', () => {
    // Старый стиль `## 3.188.` и новый `## §3.193.` живут в одном файле. Сторож, ищущий только
    // `§`, увидел бы половину файла и отрапортовал «дублей нет» (случай 22).
    const heads = parseSectionHeadings(['## §3.193. Новый стиль', '## 3.188. Старый стиль'].join('\n'));
    expect(heads).toHaveLength(2);
    expect(heads[0]?.number).toBe('3.193');
    expect(heads[0]?.sectionSign).toBe(true);
    expect(heads[1]?.number).toBe('3.188');
    expect(heads[1]?.sectionSign).toBe(false);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 2: кириллический суффикс — ЧАСТЬ номера, а не мусор', () => {
    // Настоящий файл содержит `### 3.95.5а.` и `### 3.95.5б.` рядом с `### 3.95.5.`. Если суффикс
    // отбросить, сторож покраснеет на исправном файле — ложное красное, которое снимают первым PR.
    const heads = parseSectionHeadings(
      ['### 3.95.5. Первый', '### 3.95.5а. ОТОЗВАНО', '### 3.95.5б. Разрешено'].join('\n'),
    );
    expect(heads.map((h) => h.number)).toEqual(['3.95.5', '3.95.5а', '3.95.5б']);
    expect(heads.map((h) => h.suffix)).toEqual(['', 'а', 'б']);
    // И как следствие: три РАЗНЫХ адреса — ноль конфликтов.
    expect(findSectionCollisions(heads)).toEqual([]);
  });

  it('уровень заголовка сохраняется и попадает в отчёт', () => {
    const heads = parseSectionHeadings(['## §3.193. Раздел', '### 3.193.1. Подраздел'].join('\n'));
    expect(heads.map((h) => h.level)).toEqual([2, 3]);
    expect(heads.map((h) => h.parts)).toEqual([2, 3]);
  });

  it('строки без номера и заголовки без номера не берутся', () => {
    const text = ['# Реестр', '## Общее', 'просто текст 3.193', '### §3.7. С номером'].join('\n');
    const heads = parseSectionHeadings(text);
    expect(heads).toHaveLength(1);
    expect(heads[0]?.number).toBe('3.7');
  });
});

describe('сторож номера раздела: поиск конфликтов', () => {
  it('НЕГАТИВНЫЙ КОНТРОЛЬ 1: два раздела делят номер — конфликт назван с обеими строками', () => {
    const heads = parseSectionHeadings(
      ['## §3.193. Первый предмет', '## §3.193. Второй предмет'].join('\n'),
    );
    const found = findSectionCollisions(heads);
    expect(found).toHaveLength(1);
    expect(found[0]?.number).toBe('3.193');
    expect(found[0]?.lines).toEqual([1, 2]);
    expect(found[0]?.titles).toEqual(['Первый предмет', 'Второй предмет']);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 4: дубль на РАЗНЫХ уровнях тоже конфликт', () => {
    // Ровно тот случай, что в настоящем файле: `## §3.193` (L15243) против `### 3.193` (L15550).
    // Первая редакция включала уровень в ключ и на настоящем файле дала НОЛЬ конфликтов —
    // сторож посмотрел не туда и отрапортовал «чисто» (случай 22).
    const heads = parseSectionHeadings(
      ['## §3.193. Раздел', '### 3.193. Совсем другой предмет'].join('\n'),
    );
    const found = findSectionCollisions(heads);
    expect(found, 'разные уровни не спасают от неоднозначного адреса').toHaveLength(1);
    expect(found[0]?.levels).toEqual([2, 3]);
  });

  it('вложенный номер НЕ конфликтует с родительским', () => {
    // `3.187`, `3.187.1`, `3.187.1.1` — разные адреса, и это правильно: они друг другу не мешают.
    const heads = parseSectionHeadings(
      ['## §3.187. Родитель', '### §3.187.1. Дитя', '#### §3.187.1.1. Внук'].join('\n'),
    );
    expect(findSectionCollisions(heads)).toEqual([]);
  });
});

describe('сторож номера раздела: настоящий реестр', () => {
  const audit = auditHardwareDebt();

  it('разбор не вакуумный: заголовков с номером много', () => {
    // «Дублей нет» обязано означать «посмотрел и не нашёл», а не «не смотрел» (случай 22).
    expect(fs.existsSync(path.join(ROOT, HARDWARE_DEBT)), `${HARDWARE_DEBT} существует`).toBe(true);
    expect(audit.headings.length, 'заголовков с номером').toBeGreaterThan(700);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 3: дублей ноль — и это НЕ «не смотрел»', () => {
    // После правки §3.193 конфликтов быть не должно. Проверка держит обе стороны: ноль проблем
    // И непустой разбор. Одно без другого ничего не значит.
    expect(audit.problems, audit.problems.join('\n')).toEqual([]);
    expect(audit.headings.length).toBeGreaterThan(700);
  });

  it('оба стиля нумерации представлены — иначе половина файла не проверена', () => {
    // Если однажды весь файл перепишут в один стиль, это не дефект; дефект — если сторож перестал
    // видеть один из стилей. Проверяется ФАКТ наличия обоих на дату правки.
    const withSign = audit.headings.filter((h) => h.sectionSign).length;
    const withoutSign = audit.headings.length - withSign;
    expect(withSign, 'заголовков со знаком §').toBeGreaterThan(0);
    expect(withoutSign, 'заголовков без знака § (старый стиль)').toBeGreaterThan(0);
  });

  it('кириллические суффиксы в файле есть — и они не считаются дублями', () => {
    // 3.95.5а/3.95.5б и 3.170.2а — настоящие подпункты. Они обязаны разбираться как отдельные
    // адреса, иначе сторож краснеет на исправном файле.
    const suffixed = audit.headings.filter((h) => h.suffix !== '');
    expect(suffixed.length, 'заголовков с буквенным суффиксом').toBeGreaterThan(0);
    for (const h of suffixed) {
      expect(h.number, `${h.number} несёт суффикс`).toBe(`${h.bare}${h.suffix}`);
    }
  });

  it('код отказа — OSN-GATE-SECTION', () => {
    expect(SECTION_GATE_CODE).toBe('OSN-GATE-SECTION');
  });
});
