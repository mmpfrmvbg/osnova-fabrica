describe("исполняемая спецификация синтаксиса Основы", () => {

  // Две пробы держат САМ НАБОР, а не язык: без них набор можно «починить»
  // удалением неудобных проб, и оракул останется зелёным.
  it("в наборе не меньше двадцати положительных проб", () => {
    // Язык существует тогда, когда он что-то УМЕЕТ. Отказы дешёвые: их можно
    // написать сотню. Положительная проба стоит дорого — она прогоняет язык.
    const положительных = примеры.filter((п) => !п.ошибкаСодержит).length;
    expect(положительных).toBeGreaterThanOrEqual(20);
  });

  it("в наборе не меньше пятнадцати названных отказов", () => {
    // Симметрии здесь нет и быть не должно: у языка больше границ, чем
    // возможностей назвать. Важно другое — чтобы каждый отказ был НАЗВАН
    // (поле «ошибкаСодержит» проверяет текст, а не факт падения).
    const отказов = примеры.filter((п) => п.ошибкаСодержит).length;
    expect(отказов).toBeGreaterThanOrEqual(15);
  });

  // Каждая проба — отдельная проверка, чтобы падение называло ИМЯ пробы, а не
  // строку в общем списке.
  for (const п of примеры) {
    it(п.имя, () => {
      const р = исполнить(п.код, `${п.имя.split(" ")[0]}.osnova`);
      if (п.ошибкаСодержит) {
        expect(р.ошибка, "ожидался отказ").toBeTruthy();
        expect(р.ошибка).toContain(п.ошибкаСодержит);
        return;
      }
      expect(р.ошибка ?? "нет ошибки").toBe("нет ошибки");
      if (п.вывод) expect(р.вывод).toEqual(п.вывод);
      if (п.итог !== undefined) expect(р.итог).toEqual(п.итог);
    });
  }
});
