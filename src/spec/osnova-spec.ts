function isLetter(c: string): boolean {
  if (!c) return false;
  const k = c.charCodeAt(0);
  return (
    (k >= 0x41 && k <= 0x5a) || (k >= 0x61 && k <= 0x7a) ||
    (k >= 0x410 && k <= 0x44f) || k === 0x401 || k === 0x451
  );
}

export function tokenize(src: string): Token[] {
  const out: Token[] = [];
  let i = 0, line = 1;
  const push = (kind: Kind, lexeme: string, value?: number | string) =>
    out.push({ kind, lexeme, value, line });
  while (i < src.length) {
    const c = src[i]!;
    if (c === " " || c === "\t" || c === "\r") { i++; continue; }
    if (c === "\n") { push("новая_строка", "\n"); i++; line++; continue; }
    if (c === "/" && src[i + 1] === "/") { while (i < src.length && src[i] !== "\n") i++; continue; }
    if (c === "/" && src[i + 1] === "*") {
      const at = line; i += 2;
      while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) { if (src[i] === "\n") line++; i++; }
      if (i >= src.length) throw new Error(`строка ${at}: незакрытый комментарий /*`);
      i += 2; continue;
    }
    if (c === '"') {
      i++; let v = "";
      while (i < src.length && src[i] !== '"') {
        if (src[i] === "\\") {
          const e = src[i + 1];
          v += e === "n" ? "\n" : e === "t" ? "\t" : e === '"' ? '"' : e === "\\" ? "\\" : e;
          i += 2; continue;
        }
        if (src[i] === "\n") throw new Error(`строка ${line}: строка не закрыта до конца строки`);
        v += src[i]; i++;
      }
      if (i >= src.length) throw new Error(`строка ${line}: незакрытая строка`);
      i++; push("строка", v, v); continue;
    }
    if (c >= "0" && c <= "9") {
      let n = ""; while (i < src.length && src[i]! >= "0" && src[i]! <= "9") n += src[i++];
      if (src[i] === "." && src[i + 1]! >= "0" && src[i + 1]! <= "9") {
        n += src[i++]; while (i < src.length && src[i]! >= "0" && src[i]! <= "9") n += src[i++];
      }
      push("число", n, Number(n)); continue;
    }
    if (isLetter(c) || c === "_") {
      let w = ""; while (i < src.length && (isLetter(src[i]!) || (src[i]! >= "0" && src[i]! <= "9") || src[i] === "_")) w += src[i++];
      push(KEYWORDS[w] ?? "имя", w, w); continue;
    }
    const two = src.slice(i, i + 2);
    if (two === ":=") throw new Error(`строка ${line}: «:=» в языке нет: присваивание — только «=»`);
    if (two === "==" || two === "!=" || two === "<=" || two === ">=") { push(two as Kind, two); i += 2; continue; }
    if (c === "→") { push("→", "→"); i += 1; continue; }
    if ("()[]{},:." .includes(c)) { push(c as Kind, c); i++; continue; }
    if ("+-*/%<>=;|".includes(c)) { push(c as Kind, c); i++; continue; }
    throw new Error(`строка ${line}: в языке нет символа ${JSON.stringify(c)}`);
  }
  push("конец_файла", "<конец файла>");
  return out;
}

// ─────────────────────────────── AST ───────────────────────────────

interface TypeRef { name: string; арг?: TypeRef; может?: boolean; список?: boolean; словарь?: [TypeRef, TypeRef] }

type Expr =
  | { k: "число"; v: number } | { k: "строка"; v: string } | { k: "логическое"; v: boolean }
  | { k: "пусто" } | { k: "имя"; имя: string }
  | { k: "поле"; объект: Expr; поле: string } | { k: "индекс"; объект: Expr; индекс: Expr }
  | { k: "вызов"; имя: string; арг: Expr[] }
  | { k: "список_литерал"; эл: Expr[] } | { k: "словарь_литерал"; пары: [string, Expr][] }
  | { k: "унарное"; op: "-" | "не"; а: Expr }
  | { k: "бинарное"; op: string; л: Expr; п: Expr }
  | { k: "операция"; имя: string; арг: Expr[] };

type Stmt =
  | { k: "пусть"; имя: string; тип?: TypeRef; з: Expr }
  | { k: "присвоить"; цель: Expr; з: Expr }
  | { k: "вызов_инстр"; вызов: Expr }
  | { k: "вернуть"; з?: Expr }
  | { k: "если"; ветви: { усл: Expr; тело: Stmt[] }[]; иначе?: Stmt[] }
  | { k: "пока"; усл: Expr; тело: Stmt[] }
  | { k: "для_каждого"; эл: string; индекс?: string; ист: Expr; тело: Stmt[] }
  | { k: "для_диапазона"; пер: string; от: Expr; до: Expr; шаг?: Expr; тело: Stmt[] }
  | { k: "повторять"; раз: Expr; тело: Stmt[] }
  | { k: "цикл"; тело: Stmt[] }
  | { k: "разбор"; значение: Expr; ветви: { вариант: string; тело: Stmt[] }[]; иначе?: Stmt[] }
  | { k: "защита"; тело: Stmt[]; приОшибке?: { имя?: string; тело: Stmt[] } }
  | { k: "поднять"; з: Expr }
  | { k: "проверить"; усл: Expr; сообщение?: Expr }
  | { k: "прервать" } | { k: "продолжить" };

interface Proc { имя: string; действие: boolean; параметры: { имя: string; тип?: TypeRef }[]; возврат?: TypeRef; тело: Stmt[]; экспорт: boolean }
interface TypeDecl { имя: string; поля?: { имя: string; тип: TypeRef }[]; варианты?: string[] }
interface Program { типы: TypeDecl[]; процедуры: Proc[]; подключения: string[] }

// ─────────────────────────────── ПАРСЕР ───────────────────────────────

const BLOCK_CLOSERS = ["если", "пока", "для", "разбор", "защита", "повторять", "цикл", "цикла", "типа"];

/** «конец цикла» и «конец цикл» — одно и то же слово в разных падежах. */
function созвучно(закрытие: string, ожидается: string): boolean {
  if (закрытие === ожидается) return true;
  if (ожидается === "цикл") return закрытие === "цикла";
  if (ожидается === "тип") return закрытие === "типа";
  return false;
}

/**
 * Ошибка разбора, которую НЕЛЬЗЯ откатывать: запрет цепочки имён.
 * Отличается от обычной ошибки тем, что откат «это не операция, а имя» её не
 * отменяет — иначе `система.массив.длина(а)` молча разбиралось бы как
 * `система.массив` + остаток строки.
 */
class ЦепочкаИмён extends Error {}

export class Parser {
  private p = 0;
  constructor(private t: Token[], private файл = "вход.osnova") {}

  private пик(n = 0): Token { return this.t[Math.min(this.p + n, this.t.length - 1)]!; }
  private съесть(): Token { return this.t[this.p++]!; }
  private эт(k: Kind): boolean { return this.пик().kind === k; }
  private ждём(k: Kind, что: string): Token {
    if (!this.эт(k)) throw this.ошибка(`ожидается ${что}, получено «${this.пик().lexeme}»`);
    return this.съесть();
  }
  private ошибка(сообщение: string): Error {
    return new Error(`${this.файл}:${this.пик().line}: ${сообщение}`);
  }
  private пустые(): void { while (this.эт("новая_строка") || this.эт(";")) this.съесть(); }
  private конецИнструкции(): void {
    if (this.эт("новая_строка") || this.эт("конец_файла") || this.эт(";")) return;
    if (this.эт("конец")) {
      throw this.ошибка(`после инструкции ожидается конец строки: закрытие «конец${this.имяЗакрытия() ? " " + this.имяЗакрытия() : ""}» пишется с новой строки`);
    }
    throw this.ошибка(`после инструкции ожидается конец строки, получено «${this.пик().lexeme}»`);
  }
  /** Необязательное имя закрываемого блока: `если`, `пока`, `разбор`… */
  private имяЗакрытия(): string {
    const л = this.пик(1).lexeme;
    return BLOCK_CLOSERS.includes(л) ? л : "";
  }
  /** Закрытие блока: обязательное слово `конец` и необязательное имя блока. */
  private закрытие(ожидается: string): void {
    this.ждём("конец", "«конец»");
    // Имя закрываемого блока — это ЛЕКСЕМА: `если`, `пока`, `для` — ключевые слова,
    // а `разбор`, `защита`, `типа` — обычные имена. Проверять по kind нельзя.
    const имя = this.пик();
    if (BLOCK_CLOSERS.includes(имя.lexeme)) {
      this.съесть();
      // Имя закрытия пишется как в русском: «конец цикла», «конец типа» —
      // родительный падеж того же слова, а не другое слово.
      if (!созвучно(имя.lexeme, ожидается)) {
        throw this.ошибка(`блок «${ожидается}» закрывается «конец ${ожидается}», а не «конец ${имя.lexeme}»`);
      }
    }
  }

  разобрать(): Program {
    const типы: TypeDecl[] = [], процедуры: Proc[] = [], подключения: string[] = [];
    this.пустые();
    while (this.эт("подключить")) {
      this.съесть();
      подключения.push(String(this.ждём("строка", "путь в кавычках").value));
      if (this.эт("как")) { this.съесть(); this.ждём("имя", "имя модуля"); }
      this.конецИнструкции(); this.пустые();
    }
    while (!this.эт("конец_файла")) {
      if (this.эт("тип")) типы.push(this.объявлениеТипа());
      else if (this.эт("процедура") || this.эт("действие") || this.эт("экспорт")) процедуры.push(this.объявлениеПроцедуры());
      else throw this.ошибка(`здесь ожидается «тип», «процедура» или «действие», получено «${this.пик().lexeme}»`);
      this.пустые();
    }
    if (!процедуры.some((п) => п.имя === "главная")) throw new Error(`${this.файл}: нет процедуры «главная»`);
    return { типы, процедуры, подключения };
  }

  private объявлениеТипа(): TypeDecl {
    this.съесть();
    const имя = String(this.ждём("имя", "имя типа").value);
    if (this.эт("=")) {                        // тип Имя = один из { … } | a | б
      this.съесть(); this.пустые();
      const варианты: string[] = [];
      if (this.эт("имя") && this.пик().lexeme === "один") {
        this.съесть();
        const из = this.ждём("имя", "«из»");
        if (из.lexeme !== "из") throw this.ошибка(`ожидается «из», получено «${из.lexeme}»`);
        this.ждём("{", "«{»"); this.пустые();
        while (!this.эт("}")) {
          варианты.push(String(this.ждём("имя", "имя варианта").value));
          this.пустые();
          if (this.эт(",")) { this.съесть(); this.пустые(); }
        }
        this.ждём("}", "«}»");
      } else {
        варианты.push(String(this.ждём("имя", "имя варианта").value));
        while (this.эт("|")) { this.съесть(); this.пустые(); варианты.push(String(this.ждём("имя", "имя варианта").value)); }
      }
      this.конецИнструкции();
      return { имя, варианты };
    }
    this.ждём("{", "«{» или «=»");
    this.пустые();
    const поля: { имя: string; тип: TypeRef }[] = [];
    while (!this.эт("}")) {
      const имяПоля = String(this.ждём("имя", "имя поля").value);
      this.ждём(":", "«:»");
      поля.push({ имя: имяПоля, тип: this.тип() });
      this.пустые();
      if (this.эт(",")) { this.съесть(); this.пустые(); }
    }
    this.ждём("}", "«}»");
    this.конецИнструкции();
    return { имя, поля };
  }

  private объявлениеПроцедуры(): Proc {
    let экспорт = false;
    if (this.эт("экспорт")) { this.съесть(); экспорт = true; }
    const действие = this.эт("действие");
    if (!this.эт("процедура") && !this.эт("действие")) throw this.ошибка("ожидается «процедура» или «действие»");
    this.съесть();
    const имя = String(this.ждём("имя", "имя процедуры").value);
    this.ждём("(", "«(»");
    const параметры: { имя: string; тип?: TypeRef }[] = [];
    while (!this.эт(")")) {
      const п = String(this.ждём("имя", "имя параметра").value);
      const тип = this.эт(":") ? (this.съесть(), this.тип()) : undefined;
      параметры.push({ имя: п, тип });
      if (this.эт(",")) { this.съесть(); continue; }
      break;
    }
    this.ждём(")", "«)»");
    let возврат: TypeRef | undefined;
    if (this.эт("→")) { this.съесть(); возврат = this.тип(); }
    if (действие && возврат) throw this.ошибка("«действие» не возвращает значение: уберите «→»");
    if (!действие && !возврат) throw this.ошибка("«процедура» возвращает значение: укажите «→ Тип»");
    this.пустые();
    const тело = this.блок(new Set(["конец"]));
    this.закрытие("");
    return { имя, действие, параметры, возврат, тело, экспорт };
  }

  private тип(): TypeRef {
    if (this.эт("Может")) { this.съесть(); const в = this.тип(); if (в.может) throw this.ошибка("«Может Может Т» — ошибка: тип и так допускает пусто"); if (в.name === "Пусто") throw this.ошибка("«Может Пусто» — ошибка: тип не несёт значения"); return { ...в, может: true }; }
    if (this.эт("Список")) { this.съесть(); return { name: "Список", список: true, арг: this.тип() }; }
    if (this.эт("Словарь")) { this.съесть(); const к = this.тип(); this.ждём("→", "«→»"); const з = this.тип(); return { name: "Словарь", словарь: [к, з] }; }
    if (this.эт("Число") || this.эт("Строка") || this.эт("Логическое") || this.эт("Пусто")) {
      return { name: this.съесть().lexeme };
    }
    return { name: String(this.ждём("имя", "имя типа").value) };
  }

  /** Тело блока до одного из слов-завершителей. */
  private блок(стоп: Set<string>): Stmt[] {
    const тело: Stmt[] = [];
    this.пустые();
    for (;;) {
      const k = this.пик().kind;
      if (k === "конец_файла") throw this.ошибка("блок не закрыт: дошли до конца файла");
      if (typeof k === "string" && стоп.has(k)) return тело;
      if (k === "конец") {
        const имяЗакрытия = this.имяЗакрытия();
        if (имяЗакрытия) {
          // Закрытие называет свой блок: чужое имя — ошибка, а не «инструкция».
          if (!стоп.has(имяЗакрытия)) {
            throw this.ошибка(`этот блок закрывается словом «конец», а не «конец ${имяЗакрытия}»`);
          }
          return тело;
        }
        // Одиночное `конец` — закрытие блока-хозяина; сюда попадаем только если
        // «конец» есть в списке завершителей (в остальных случаях это ошибка выше).
        if (стоп.has("конец")) return тело;
        throw this.ошибка(`блок не закрыт: нужно «конец», получено «${this.пик().lexeme}»`);
      }
      тело.push(this.инструкция());
      this.конецИнструкции();
      this.пустые();
    }
  }

  private инструкция(): Stmt {
    const k = this.пик().kind;
    if (["}", "]", ")", ",", ".", ":", "→", "|"].includes(k)) {
      throw this.ошибка(`в начале инструкции не может стоять «${this.пик().lexeme}»: закрытие блока — только словом «конец»`);
    }
    switch (k) {
      case "пусть": {
        this.съесть();
        const имя = String(this.ждём("имя", "имя переменной").value);
        const тип = this.эт(":") ? (this.съесть(), this.тип()) : undefined;
        let з: Expr | undefined;
        if (this.эт("=")) { this.съесть(); з = this.выражение(); }
        if (!з) throw this.ошибка("у «пусть» нет значения: объявление всегда с «= значение»");
        return { k: "пусть", имя, тип, з };
      }
      case "вернуть": {
        this.съесть();
        const з = this.эт("новая_строка") || this.эт("конец_файла") || this.эт(";") ? undefined : this.выражение();
        return { k: "вернуть", з };
      }
      case "если": return this.если();
      case "пока": {
        this.съесть(); const усл = this.условие(); this.пустые();
        const тело = this.блок(new Set(["конец"]));
        this.закрытие("пока");
        return { k: "пока", усл, тело };
      }
      case "для": return this.для();
      case "повторять": {
        // `повторять 3 раза` — счётчик это операнд, слово «раза» его не продолжает.
        this.съесть();
        const было = глубинаАргумента;
        глубинаАргумента++;                 // «раза» — слово счётчика, не продолжение выражения
        let раз: Expr;
        try { раз = this.выражение(); } finally { глубинаАргумента = было; }
        if (this.эт("раз") || this.пик().lexeme === "раза") this.съесть();
        else throw this.ошибка("нужно «повторять <сколько> раза»");
        this.пустые();
        const тело = this.блок(new Set(["конец"]));
        this.закрытие("повторять");
        return { k: "повторять", раз, тело };
      }
      case "цикл": {
        this.съесть(); this.пустые();
        const тело = this.блок(new Set(["цикл", "конец"]));
        this.закрытие("цикл");
        return { k: "цикл", тело };
      }
      case "разбор": return this.разбор();
      case "защита": return this.защита();
      case "поднять": {
        this.съесть();
        return { k: "поднять", з: this.выражение() };
      }
      case "прервать": this.съесть(); return { k: "прервать" };
      case "продолжить": this.съесть(); return { k: "продолжить" };
      default: break;
    }
    // «проверить» — КОНСТРУКЦИЯ со своей грамматикой, а не операция с исключением:
    //   проверить УСЛОВИЕ
    //   проверить УСЛОВИЕ, "сообщение"
    // Условие — полное выражение (в том числе со сравнением), сообщение — строка.
    if (this.эт("имя") && this.пик().lexeme === "проверить") {
      this.съесть();
      const усл = this.условие();
      let сообщение: Expr | undefined;
      if (this.эт(",")) { this.съесть(); сообщение = this.выражение(); }
      return { k: "проверить", усл, сообщение };
    }
    // инструкция-выражение либо присваивание
    if (!this.началоИнструкции()) {
      throw this.ошибка(`ожидается инструкция, получено «${this.пик().lexeme}»`);
    }
    const л = this.леваяЧасть();
    if (this.эт("=")) {
      this.съесть();
      const з = this.выражение();
      if (л.k !== "имя" && л.k !== "поле" && л.k !== "индекс") throw this.ошибка("слева от «=» должно быть имя, поле или элемент");
      return { k: "присвоить", цель: л, з };
    }
    if (["+=", "-=", "*=", "/="].includes(this.пик().kind)) {
      throw this.ошибка(`составного присваивания «${this.пик().lexeme}» в языке нет: пишите «x = x …»`);
    }
    // Инструкция обязана быть действием: имя процедуры-действия, вызов или операция.
    // Слово-операция без аргумента (`длина`) — просто имя: здесь это инструкция-пустышка,
    // и она отвергается на том же основании, что `1 + 1` строкой.
    if (!(л.k === "вызов" || л.k === "операция" || л.k === "имя")) {
      throw this.ошибка(`инструкция «${this.пик().lexeme}» ничего не делает: нужен вызов, действие или присваивание`);
    }
    return { k: "вызов_инстр", вызов: л };
  }

  private если(): Stmt {
    this.съесть();
    const ветви: { усл: Expr; тело: Stmt[] }[] = [];
    let усл = this.условие(); this.пустые();
    ветви.push({ усл, тело: this.блок(new Set(["иначе", "если", "конец"])) });
    while (this.эт("иначе") && this.пик(1).kind === "если") {
      this.съесть(); this.съесть();
      усл = this.условие(); this.пустые();
      ветви.push({ усл, тело: this.блок(new Set(["иначе", "если", "конец"])) });
    }
    let иначе: Stmt[] | undefined;
    if (this.эт("иначе")) { this.съесть(); this.пустые(); иначе = this.блок(new Set(["если", "конец"])); }
    this.закрытие("если");
    return { k: "если", ветви, иначе };
  }

  private для(): Stmt {
    this.съесть();
    // Две формы перебора: `для каждого эл в …` и `для эл в …`. Слово «каждого»
    // необязательно: «в» отличает перебор от диапазона `от … до` однозначно.
    if (this.эт("каждого") || (this.эт("имя") && this.пик(1).kind === "имя" && this.пик(1).lexeme === "в")) {
      if (this.эт("каждого")) this.съесть();
      const эл = String(this.ждём("имя", "имя элемента").value);
      let индекс: string | undefined;
      if (this.эт(",")) { this.съесть(); индекс = String(this.ждём("имя", "имя индекса").value); }
      const в = this.ждём("имя", "«в»");
      if (в.lexeme !== "в") throw this.ошибка(`ожидается «в», получено «${в.lexeme}»`);
      const ист = this.выражение(); this.пустые();
      const тело = this.блок(new Set(["конец"]));
      this.закрытие("для");
      return { k: "для_каждого", эл, индекс, ист, тело };
    }
    const пер = String(this.ждём("имя", "имя переменной цикла").value);
    this.ждём("от", "«от»");
    const от = this.выражение();
    this.ждём("до", "«до»");
    const до = this.выражение();
    let шаг: Expr | undefined;
    if (this.эт("шаг")) { this.съесть(); шаг = this.выражение(); }
    this.пустые();
    const тело = this.блок(new Set(["конец"]));
    this.закрытие("для");
    return { k: "для_диапазона", пер, от, до, шаг, тело };
  }

  private разбор(): Stmt {
    this.съесть();
    const значение = this.выражение();
    this.пустые();
    const ветви: { вариант: string; тело: Stmt[] }[] = [];
    let иначе: Stmt[] | undefined;
    let форма: "строка" | "блок" | null = null;
    while (this.эт("есть")) {
      this.съесть();
      const тип = String(this.ждём("имя", "имя перечня").value);
      this.ждём(".", "«.»");
      const вариант = String(this.ждём("имя", "имя варианта").value);
      if (this.эт("→")) {
        if (форма === "блок") throw this.ошибка("в одном «разбор» нельзя смешивать обе формы веток");
        форма = "строка";
        this.съесть();
        const тело: Stmt[] = [this.инструкция()];
        while (this.эт(";")) { this.съесть(); тело.push(this.инструкция()); }
        ветви.push({ вариант: `${тип}.${вариант}`, тело });
        this.пустые();
      } else {
        if (форма === "строка") throw this.ошибка("в одном «разбор» нельзя смешивать обе формы веток");
        форма = "блок";
        this.пустые();
        ветви.push({ вариант: `${тип}.${вариант}`, тело: this.блок(new Set(["есть", "иначе", "конец"])) });
      }
    }
    if (this.эт("иначе")) {
      this.съесть();
      if (форма === "строка") {
        this.ждём("→", "«→»");
        const тело: Stmt[] = [this.инструкция()];
        while (this.эт(";")) { this.съесть(); тело.push(this.инструкция()); }
        иначе = тело;
        this.пустые();
      } else {
        this.пустые();
        иначе = this.блок(new Set(["конец"]));
      }
    }
    this.закрытие("разбор");
    if (ветви.length === 0) throw this.ошибка("в «разбор» нет ни одной ветки «есть»");
    return { k: "разбор", значение, ветви, иначе };
  }

  private защита(): Stmt {
    this.съесть();
    this.пустые();
    const тело = this.блок(new Set(["при", "конец"]));
    let приОшибке: { имя?: string; тело: Stmt[] } | undefined;
    this.пустые();
    if (this.эт("при")) {
      this.съесть();
      this.ждём("ошибке", "«ошибке»");
      let имя: string | undefined;
      if (this.эт("как")) { this.съесть(); имя = String(this.ждём("имя", "имя причины").value); }
      this.пустые();
      приОшибке = { имя, тело: this.блок(new Set(["конец"])) };
    }
    this.закрытие("защита");
    return { k: "защита", тело, приОшибке };
  }

  // ── выражения ──
  // Правило переноса: выражение продолжается на следующей строке только если
  // строка начинается со ЗНАКА операции. Слова-инструкции (`вернуть`, `если`,
  // `вывести`) перенос не продолжают — иначе `вывести х` съедало бы следующую
  // строку как аргумент.
  private знакОпер(k: Kind): boolean { return ["+", "-", "*", "/", "%", "нацело"].includes(k); }
  private знакСравн(k: Kind): boolean { return ["==", "!=", "<", "<=", ">", ">="].includes(k); }

  private выражение(): Expr { return this.или(); }
  private или(): Expr {
    let л = this.и();
    while (this.эт("или") && this.операцияПохожаПосле(1)) { this.съесть(); л = { k: "бинарное", op: "или", л, п: this.и() }; }
    return л;
  }
  private и(): Expr {
    let л = this.не();
    while (this.эт("и") && this.операцияПохожаПосле(1)) { this.съесть(); л = { k: "бинарное", op: "и", л, п: this.не() }; }
    return л;
  }
  private не(): Expr {
    if (this.эт("не") && this.операцияПохожаПосле(1)) {
      this.съесть();
      return { k: "унарное", op: "не", а: this.не() };
    }
    return this.сравнение();
  }
  /** Тот же вопрос, но про токен со сдвигом (для унарных `не` и `-`). */
  private операцияПохожаПосле(сдвиг: number): boolean {
    const k = this.пик(сдвиг).kind;
    return [
      "число", "строка", "имя", "да", "нет", "пусто", "не", "-", "(", "[", "{", ",",
    ].includes(k);
  }
  private сравнение(): Expr {
    const л = this.слагаемое();
    // Внутри аргумента операции запятая — это РАЗДЕЛИТЕЛЬ аргументов, а не
    // «второй операнд через запятую»: `проверить длина числа == 3, "текст"`.
    if (глубинаАргумента > 0 && this.пик().kind === ",") return л;
    if (глубинаАргумента > 0) return л;      // аргумент операции — операнд, не сравнение
    const k = this.пик().kind;
    // `=` в позиции условия: это почти всегда промах мимо `==`. Говорим прямо.
    if (k === "=") {
      if (this.глубинаУсловия > 0) throw this.ошибка("в условии нужно «==», а не «=»");
      return л;
    }
    if (this.знакСравн(k)) {
      if (!this.операцияПохожаПосле(1)) {
        throw this.ошибка(`после знака «${k}» ожидается выражение, получено «${this.пик(1).lexeme}»`);
      }
      const знак = this.съесть().kind;
      const п = this.слагаемое();
      if (this.знакСравн(this.пик().kind)) {
        throw this.ошибка("цепочка сравнений запрещена: напишите «a < b и b < c»");
      }
      return { k: "бинарное", op: знак, л, п };
    }
    return л;
  }
  private слагаемое(): Expr {
    let л = this.множитель();
    // Внутри аргумента операции «+» и «-» НЕ продолжают операнд: за счёт этого
    // `длина числа - 1` читается как `(длина числа) - 1`, а не `длина(числа - 1)`.
    while (плоскийАргумент === 0 && (this.эт("+") || this.эт("-")) && this.операцияПохожаПосле(1)) {
      const op = this.съесть().kind;
      л = { k: "бинарное", op, л, п: this.множитель() };
    }
    return л;
  }
  private множитель(): Expr {
    let л = this.унарный();
    for (;;) {
      const k = this.пик().kind;
      if (плоскийАргумент === 0 && (k === "*" || k === "/" || k === "%" || k === "нацело") && this.операцияПохожаПосле(1)) {
        this.съесть();
        л = { k: "бинарное", op: k, л, п: this.унарный() };
        continue;
      }
      break;
    }
    return л;
  }
  private унарный(): Expr {
    if (this.эт("-") && this.операцияПохожаПосле(1)) { this.съесть(); return { k: "унарное", op: "-", а: this.унарный() }; }
    return this.первичное();
  }

  private первичное(): Expr {
    const t = this.пик();
    if (t.kind === "число") { this.съесть(); return { k: "число", v: Number(t.value) }; }
    if (t.kind === "строка") { this.съесть(); return { k: "строка", v: String(t.value) }; }
    if (t.kind === "да") { this.съесть(); return { k: "логическое", v: true }; }
    if (t.kind === "нет") { this.съесть(); return { k: "логическое", v: false }; }
    if (t.kind === "пусто") { this.съесть(); return { k: "пусто" }; }
    if (t.kind === "(") {
      this.съесть();
      // Скобки снимают ограничение операнда: внутри — полное выражение.
      // Скобки — полное выражение: `("а=" + а)`, `(а > 3 и а < 10)`.
      const было = глубинаАргумента; глубинаАргумента = 0;
      try { const в = this.выражение(); this.ждём(")", "«)»"); return this.хвосты(в); }
      finally { глубинаАргумента = было; }
    }
    if (t.kind === "|") { // |a, b| — параметры-замыкание (только в позиции аргумента)
      this.съесть();
      const пар: string[] = [];
      while (!this.эт("|")) { пар.push(String(this.ждём("имя", "имя параметра").value)); if (this.эт(",")) this.съесть(); }
      this.ждём("|", "«|»");
      const тело = this.инструкция();
      return { k: "вызов", имя: "__замыкание", арг: [{ k: "строка", v: JSON.stringify({ пар, тело }) }] };
    }
    if (t.kind === "[") {
      this.съесть(); const эл: Expr[] = []; this.пустые();
      while (!this.эт("]")) { эл.push(this.выражение()); this.пустые(); if (this.эт(",")) { this.съесть(); this.пустые(); } }
      this.ждём("]", "«]»");
      return this.хвосты({ k: "список_литерал", эл });
    }
    if (t.kind === "{") {
      this.съесть(); const пары: [string, Expr][] = []; this.пустые();
      while (!this.эт("}")) {
        // Ключом записи может быть имя поля, а словаря — строка: { "хлеб": 40 }.
        const ключ = this.эт("строка")
          ? String(this.съесть().value)
          : String(this.ждём("имя", "имя поля или строку-ключ").value);
        this.ждём(":", "«:»");
        пары.push([ключ, this.выражение()]); this.пустые();
        if (this.эт(",")) { this.съесть(); this.пустые(); }
      }
      this.ждём("}", "«}»");
      return this.хвосты({ k: "словарь_литерал", пары });
    }
    if (t.kind === "имя") {
      this.съесть();
      // Встроенная операция `длина а` / `вывести х`: пробуем разобрать как операцию
      // и ОТКАТЫВАЕМСЯ, если аргумента нет (`длина числа, "текст"` — тут `длина`
      // это операция, а вот `длина = 5` — имя). Откат честнее запрета: язык не
      // зависит от того, каким словом названа переменная.
      if (BUILTIN_OPS.has(t.lexeme)) {
        const назад = this.p;
        try {
          return this.операция(t.lexeme);
        } catch (о) {
          if (о instanceof ЦепочкаИмён) throw о;
          this.p = назад;
        }
      }
      const в: Expr = { k: "имя", имя: t.lexeme };
      if (this.эт("(")) {
        this.съесть();
        return this.хвосты({ k: "вызов", имя: t.lexeme, арг: this.списокАргументов() });
      }
      const естьТочка = this.эт(".");
      const послеТочки = this.пик(1);
      if (естьТочка && послеТочки.kind === "имя" && this.пик(2).kind === "(") {
        // Квалифицированный вызов модуля: `Модуль.имя(…)` — ровно одна точка.
        // Точка после него — отказ: это ИМЯ процедуры, а не значение.
        this.съесть();
        const имя = String(this.съесть().value);
        this.съесть();
        const вызов: Expr = { k: "вызов", имя: `${t.lexeme}.${имя}`, арг: this.списокАргументов() };
        if (this.эт(".")) {
          throw this.ошибка("после «Модуль.имя(…)» точка запрещена: это имя процедуры, а не значение");
        }
        return вызов;
      }
      if (естьТочка) {
        // Цепочка полей начинается ЗДЕСЬ — значит, первое имя обязано быть
        // значением. `система.массив.длина` до сюда доходит, но имени
        // `система` в программе нет: отказ даёт исполнитель.
        const цепь = this.хвосты(в);
        if (this.эт("(")) {
          // Перед «(» накопилась цепочка имён — это чужой способ записи:
          // у модуля нет подмодуля, вызов пишется «имя(…)» или «Модуль.имя(…)».
          throw new ЦепочкаИмён("цепочка имён перед вызовом запрещена: вызов пишется «имя(…)» или «Модуль.имя(…)»");
        }
        return цепь;
      }
      return this.хвосты(в);
    }
    throw this.ошибка(`ожидается выражение, получено «${t.lexeme}»`);
  }

  /**
   * Может ли текущий токен начать выражение. Это не удобство, а граница языка:
   * инструкция кончается там, где следующее слово не может продолжить выражение
   * (например `вернуть`), — и потому `вывести х` + `вернуть 0` на следующей
   * строке разбираются как две инструкции.
   */
  private началоВыражения(): boolean {
    const k = this.пик().kind;
    // Запятая и `)` внутри списка аргументов — это НЕ начало операнда, а его конец:
    // без этого `длина числа, "текст"` уезжало в `,` как в бинарную операцию.
    if (this.границы.length && this.границы[this.границы.length - 1]!.includes(k)) return false;
    return [
      "число", "строка", "имя", "(|)", "[", "{", "не", "-", "да", "нет", "пусто",
      "и", "или", "+", "-", "*", "/", "%", "нацело",
      "==", "!=", "<", "<=", ">", ">=",
    ].includes(k);
  }

  /** Границы выражения: внутри списка аргументов запятая и `)` операндом не бывают. */
  private границы: (string[])[] = [];
  private вГраницах<T>(границы: string[], дело: () => T): T {
    this.границы.push(границы);
    try { return дело(); } finally { this.границы.pop(); }
  }
  /** Список аргументов — граница запятой; список/литерал — нет. */
  private стопНаЗапятой = 0;

  /** Глубина разбора условия: здесь `=` — почти наверняка забытое `==`. */
  private глубинаУсловия = 0;

  /**
   * Аргумент операции — это ОПЕРАНД, а не сравнение: `длина числа == 3` читается
   * как `(длина числа) == 3`. Сравнение стоит НИЖЕ операции по приоритету.
   */
  private условие(): Expr {
    this.глубинаУсловия++;
    try { return this.выражение(); } finally { this.глубинаУсловия--; }
  }

  /**
   * Может ли следующее слово быть аргументом операции. Нужно, чтобы отличить
   * `длина числа` (операция с аргументом) от `числа[0] = 20` и `числа = [1]`
   * (имя переменной, совпавшее словом с операцией).
   *
   * Список — БЕЛЫЙ: начало выражения плюс знаки-операторы. Всё остальное
   * (перевод строки, `=`, `,`, закрывающие скобки, слова-инструкции) означает,
   * что слово-операция стоит там, где аргумента нет.
   */
  private операцияПохожа(): boolean {
    const k = this.пик().kind;
    if (this.стопНаЗапятой > 0 && k === ",") return false;
    return [
      "число", "строка", "имя", "да", "нет", "пусто", "не",
      "(", "[", "{", "|",
    ].includes(k);
  }

  /** Ведущее имя инструкции: левая часть присваивания не становится операцией. */
  private леваяЧасть(): Expr {
    this.стопНаЗапятой++;
    try { return this.выражение(); } finally { this.стопНаЗапятой--; }
  }

  /** Начало инструкции: шире выражения — оператор-знак может начать присваивание. */
  private началоИнструкции(): boolean {
    const k = this.пик().kind;
    if (this.границы.length && this.границы[this.границы.length - 1]!.includes(k)) return false;
    return this.началоВыражения() || k === "=" || k === "," || k === ";";
  }

  /** Фразовые операции: `длина X`, `добавить в X элемент Y`, `содержит <что> в <где>`. */
  private операция(имя: string): Expr {
    const арг: Expr[] = [];
    const взятьДо = (слова: string[], вид: "операнд" | "выражение" = "операнд") => {
      const сдвиг = this.границы.length;
      this.границы.push(слова);
      глубинаАргумента++;
      if (вид === "операнд") плоскийАргумент++;
      try {
        if (!this.началоВыражения()) throw this.ошибка(`у операции «${имя}» не хватает аргумента`);
        арг.push(вид === "операнд" ? this.слагаемое() : this.выражение());
      } finally {
        глубинаАргумента--;
        if (вид === "операнд") плоскийАргумент--;
        this.границы.length = сдвиг;
      }
    };    const взять = () => взятьДо([]);
    switch (имя) {
      case "длина": case "корень": case "округлить": case "пол": case "потолок":
      case "обрезать": case "верхний": case "нижний": case "выделить": case "ввод":
        взять(); break;
      // Действия печати и подъёма берут ВЫРАЖЕНИЕ: `вывести "а" + счёт`.
      case "вывести": case "вывести_строку": case "поднять": взятьДо([], "выражение"); break;
      case "добавить": {
        const в = this.ждём("имя", "«в»"); if (в.lexeme !== "в") throw this.ошибка("нужно «добавить в <список> элемент <значение>»");
        взятьДо(["элемент"]);
        const эл = this.ждём("имя", "«элемент»"); if (эл.lexeme !== "элемент") throw this.ошибка("нужно «добавить в <список> элемент <значение>»");
        взять(); break;
      }
      case "удалить": {
        const из = this.ждём("имя", "«из»"); if (из.lexeme !== "из") throw this.ошибка("нужно «удалить из <список> индекс <i>»");
        взятьДо(["индекс"]);
        const и = this.ждём("имя", "«индекс»"); if (и.lexeme !== "индекс") throw this.ошибка("нужно «удалить из <список> индекс <i>»");
        взять(); break;
      }
      case "остаток": {
        взятьДо(["при"]);
        if (this.эт("при")) {
          this.съесть();
          const д = this.ждём("имя", "«делении»"); if (д.lexeme !== "делении") throw this.ошибка("нужно «остаток <a> при делении на <b>»");
          const на = this.ждём("имя", "«на»"); if (на.lexeme !== "на") throw this.ошибка("нужно «остаток <a> при делении на <b>»");
          взять();
        }
        break;
      }
      case "содержит": {
        взятьДо(["в"]);
        const в = this.ждём("имя", "«в»"); if (в.lexeme !== "в") throw this.ошибка("нужно «содержит <что> в <где>»");
        взять(); break;
      }
      case "найти": {
        взятьДо(["в"]);
        const в = this.ждём("имя", "«в»"); if (в.lexeme !== "в") throw this.ошибка("нужно «найти <что> в <где>»");
        взять(); break;
      }
      default: взять();
    }
    return { k: "операция", имя, арг };
  }

  /** Список аргументов: границы — запятая и `)`. */
  private списокАргументов(): Expr[] {
    return this.вГраницах([",", ")"], () => {
      const арг: Expr[] = [];
      this.пустые();
      this.стопНаЗапятой++;
      try {
        while (!this.эт(")")) {
          арг.push(this.выражение());
          this.пустые();
          if (this.эт(",")) { this.съесть(); this.пустые(); }
        }
      } finally { this.стопНаЗапятой--; }
      this.ждём(")", "«)»");
      return арг;
    });
  }

  /**
   * Хвосты значения: `.` и `[индекс]`.
   *
   * ПРАВИЛО ТОЧКИ (после второй вычитки — переформулировано):
   *   • `выражение.имя` — «взять часть»: поле записи или процедура модуля;
   *   • ЦЕПОЧКА ПОЛЕЙ разрешена: `ж.адрес.город` — первая точка даёт значение
   *     (поле), вторая берёт часть ЭТОГО значения;
   *   • цепочка через ВЫЗОВ модуля запрещена: `Модуль.ф().поле` — потому что
   *     `Модуль.ф` это не значение, а имя процедуры, и «взять часть» от имени
   *     нечего. Так же структурно невозможен `система.массив.длина`: `система`
   *     не модуль и не значение.
   */
  /**
   * Хвосты значения: `.` (поле) и `[индекс]`.
   *
   * ПРАВИЛО ТОЧКИ. Точка — это «взять часть», и цепочка полей разрешена
   * (`ж.адрес.город`): первая точка даёт значение, вторая берёт часть значения.
   * Запрещено другое — цепочка ИМЁН: `система.массив.длина`. У модуля нет
   * подмодуля, а вызов пишется как `имя(…)` или `Модуль.имя(…)` — ровно одна
   * точка. Поэтому база вызова проверяется ДО суффиксов, а после проверки
   * `имя.имя(` хвосты больше не читаются: это имя процедуры, а не значение.
   */
  /**
   * Хвосты значения: `.` (поле) и `[индекс]`.
   *
   * Цепочка ПОЛЕЙ разрешена на любую глубину (`ж.адрес.город`): каждая точка
   * берёт часть ЗНАЧЕНИЯ. Запрет на `система.массив.длина` держится не здесь,
   * а отсутствием имени `система` — см. {@link первичное}.
   */
  private хвосты(база: Expr): Expr {
    let в = база;
    for (;;) {
      if (this.эт(".")) {
        this.съесть();
        const поле = String(this.ждём("имя", "имя поля").value);
        в = { k: "поле", объект: в, поле };
        continue;
      }
      if (this.эт("[")) { this.съесть(); const и = this.выражение(); this.ждём("]", "«]»"); в = { k: "индекс", объект: в, индекс: и }; continue; }
      break;
    }
    return в;
  }
}

