/**
 * ИСПОЛНЯЕМАЯ СПЕЦИФИКАЦИЯ СИНТАКСИСА ОСНОВЫ (проект «Основа», не канон v2).
 *
 * Назначение — не компилятор, а ОРАКУЛ НА ЯЗЫК: каждый пример спецификации
 * обязан через это прогнаться. Пример, который «не компилируется», — красный
 * оракул на документ, а не на реализацию.
 *
 * Что здесь зафиксировано (и почему — см. docs/osnova-spec.md):
 *   • составные слова пишутся через ПРОБЕЛ, а не через «_»: `для каждого`,
 *     `конец пока`, `при ошибке` — дешевле вдвое и читается;
 *   • булевы значения — `да`/`нет` (не `и`: это союз AND);
 *   • у сравнений только знаки, у логики — русские слова `и`/`или`/`не`;
 *   • `%` — только остаток, деление нацело — только слово `нацело`;
 *   • закрытие блока повторяет открывающее слово: `конец если`, `конец пока`,
 *     `конец цикла`, `конец разбор`; у процедуры — просто `конец`;
 *   • точка — «взять часть»: цепочка ПОЛЕЙ разрешена (`ж.адрес.город`),
 *     цепочка ИМЁН запрещена (`система.массив.длина` — такого имени нет);
 *   • `проверить` — не операция, а КОНСТРУКЦИЯ со своей грамматикой;
 *   • аргумент операции — операнд, у действий (`вывести`, `поднять`) — выражение.
 *
 * Запуск оракула: `npx vitest run src/spec/specification.test.ts`
 * (и он же — в общем `npm test`).
 */

/**
 * ОСНОВА (проект): лексер + парсер + исполнитель минимального ядра.
 *
 * Назначение — НЕ компилятор, а исполняемая спецификация синтаксиса: каждый пример
 * из документа обязан через это прогнаться. Если пример не компилируется — это
 * красный оракул на документ.
 *
 * Что закрыто из замечаний ревью:
 *   1. булевы значения — `да`/`нет` (не `и`, не `истина`/`ложь`);
 *   2. `%` — только остаток, деление нацело — только слово `нацело`;
 *   3. у сравнений только знаки `== != < <= > >=` (слов-дублей нет);
 *   4. склейка строк — только `+` (слова `склеить` нет);
 *   5. у процедуры закрытие только `конец` (формы `конец процедуры` нет);
 *   6. квалификация `Модуль.имя` и `объект.поле` разрешена, но точка РОВНО одна;
 *   7. `поднять` вне `защита` — названный сбой программы;
 *   8. `Может` идемпотентно, `Может Пусто` — ошибка.
 */

