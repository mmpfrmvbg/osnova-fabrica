class Возврат { constructor(readonly значение: unknown) {} }
class Сбой { constructor(readonly значение: unknown) {} }
class Прервать {} class Продолжить {}

export interface Результат { вывод: string[]; итог: unknown; ошибка?: string }

interface ПолеЗаписи { [к: string]: unknown }

/** Глубина разбора аргумента операции: там сравнение не начинается. */
let глубинаАргумента = 0;

/** Процедура, чей «вернуть» исполняется сейчас, — для проверки типа возврата. */
let текущаяПроцедура: Proc | null = null;

/**
 * Сколько ПЛОСКИХ аргументов операций разбирается прямо сейчас. Плоский — значит
 * «ровно один операнд»: `длина числа - 1` читается как `(длина числа) - 1`,
 * потому что знаки арифметики в плоский аргумент не входят. У операций-действий
 * (`вывести`, `поднять`) аргумент — выражение, и там счётчик не растёт:
 * `вывести "а" + счёт` склеивает строку.
 */
let плоскийАргумент = 0;

/** Отметка «действие отработало»: значение, которого нельзя присвоить. */
const РЕЗУЛЬТАТ_ДЕЙСТВИЯ = Symbol("действие");

export function исполнить(src: string, файл = "вход.osnova"): Результат {
  const вывод: string[] = [];
  let программа: Program;
  try {
    программа = new Parser(tokenize(src), файл).разобрать();
  } catch (e) {
    return { вывод, итог: undefined, ошибка: (e as Error).message };
  }
  const процедуры = new Map(программа.процедуры.map((п) => [п.имя, п]));
  const типы = new Map(программа.типы.map((т) => [т.имя, т]));

  const стр = (v: unknown): string => {
    if (v === РЕЗУЛЬТАТ_ДЕЙСТВИЯ) throw new Сбой("действие не возвращает значение: его нельзя подставить в выражение");
    return v === null || v === undefined ? "пусто"
      : typeof v === "boolean" ? (v ? "да" : "нет")
      : typeof v === "number" ? String(v)
      : typeof v === "string" ? v
      : Array.isArray(v) ? "[" + v.map(стр).join(", ") + "]"
      : "{" + Object.entries(v as ПолеЗаписи).map(([k, x]) => `${k}: ${стр(x)}`).join(", ") + "}";
  };

  const сумма = (a: unknown, b: unknown): unknown => {
    if (typeof a === "number" && typeof b === "number") return a + b;
    if (typeof a === "string" || typeof b === "string") return стр(a) + стр(b);
    throw new Сбой(`нельзя сложить ${стр(a)} и ${стр(b)}`);
  };

  class Область {
    значения = new Map<string, unknown>();
    constructor(readonly родитель?: Область) {}
    /** Область, где имя объявлено, или undefined. */
    private где(имя: string): Область | undefined {
      // eslint-disable-next-line @typescript-eslint/no-this-alias -- обход цепочки областей начинается с самой области
      let о: Область | undefined = this;
      while (о) {
        if (о.значения.has(имя)) return о;
        о = о.родитель;
      }
      return undefined;
    }
    взять(имя: string): unknown {
      const о = this.где(имя);
      if (!о) throw new Сбой(`нет имени «${имя}»`);
      return о.значения.get(имя);
    }
    есть(имя: string): boolean {
      return this.где(имя) !== undefined;
    }
    задать(имя: string, з: unknown): void {
      const о = this.где(имя);
      if (!о) throw new Сбой(`имя «${имя}» не объявлено: первое присваивание — только через «пусть»`);
      о.значения.set(имя, з);
    }
  }

  function вычислить(e: Expr, обл: Область): unknown {
    switch (e.k) {
      case "число": return e.v;
      case "строка": return e.v;
      case "логическое": return e.v;
      case "пусто": return null;
      case "имя": return обл.взять(e.имя);
      case "поле": {
        // Литерал перечня `Имя.вариант`: имя перечня — не значение, а метка.
        if (e.объект.k === "имя" && !обл.есть(e.объект.имя)) {
          const тд = типы.get(e.объект.имя);
          if (тд?.варианты?.includes(e.поле)) return `${e.объект.имя}.${e.поле}`;
        }
        const о = вычислить((e as Expr & { k: "поле" }).объект, обл);
        if (typeof о === "string" && типы.get(о)?.варианты?.includes(e.поле)) return `${о}.${e.поле}`;
        if (о === null || typeof о !== "object" || Array.isArray(о)) throw new Сбой(`у значения ${стр(о)} нет поля «${e.поле}»`);
        const з = (о as ПолеЗаписи)[e.поле];
        if (з === undefined && !(e.поле in (о as ПолеЗаписи))) throw new Сбой(`нет поля «${e.поле}»`);
        return з ?? null;
      }
      case "индекс": {
        const о = вычислить(e.объект, обл);
        const и = вычислить(e.индекс, обл);
        if (о !== null && typeof о === "object" && !Array.isArray(о)) {
          // Словарь: индекс — КЛЮЧ, а не номер.
          return (о as ПолеЗаписи)[String(и)] ?? null;
        }
        if (typeof и !== "number" || !Number.isInteger(и)) throw new Сбой(`индекс должен быть целым числом, получено ${стр(и)}`);
        if (Array.isArray(о)) {
          if (и < 0 || и >= о.length) return null;
          return о[и] ?? null;
        }
        if (typeof о === "string") {
          const символы = [...о];
          return и < 0 || и >= символы.length ? null : символы[и]!;
        }
        throw new Сбой(`индексировать можно список или строку, не ${стр(о)}`);
      }
      case "список_литерал": return e.эл.map((x) => вычислить(x, обл));
      case "словарь_литерал": {
        const о: ПолеЗаписи = {};
        for (const [k, v] of e.пары) о[k] = вычислить(v, обл);
        return о;
      }
      case "унарное":
        if (e.op === "-") { const з = вычислить(e.а, обл); if (typeof з !== "number") throw new Сбой(`унарный «-» к ${стр(з)}`); return -з; }
        return !правда(вычислить(e.а, обл));
      case "бинарное": return бинарно(e, обл);
      case "вызов": return вызвать(e.имя, e.арг.map((a) => вычислить(a, обл)), обл);
      case "операция": {
        const з = операция(e.имя, e.арг, обл);
        if (з === РЕЗУЛЬТАТ_ДЕЙСТВИЯ) {
          throw new Сбой(`«${e.имя}» — действие: действие не возвращает значение, его нельзя подставить в выражение`);
        }
        return з;
      }
    }
  }

  function правда(v: unknown): boolean {
    if (typeof v === "boolean") return v;
    throw new Сбой(`условие должно быть логическим, получено ${стр(v)}`);
  }

  function бинарно(e: Expr & { k: "бинарное" }, обл: Область): unknown {
    const л = вычислить(e.л, обл);
    if (e.op === "и") return правда(л) ? правда(вычислить(e.п, обл)) : false;
    if (e.op === "или") return правда(л) ? true : правда(вычислить(e.п, обл));
    const п = вычислить(e.п, обл);
    switch (e.op) {
      case "+": return сумма(л, п);
      case "-": return чис(л, "-") - чис(п, "-");
      case "*": return чис(л, "*") * чис(п, "*");
      case "/": { const д = чис(п, "/"); if (д === 0) throw new Сбой("деление на ноль"); return чис(л, "/") / д; }
      case "%": { const д = чис(п, "%"); if (д === 0) throw new Сбой("остаток от деления на ноль"); return чис(л, "%") % д; }
      case "нацело": { const д = чис(п, "нацело"); if (д === 0) throw new Сбой("деление на ноль"); return Math.trunc(чис(л, "нацело") / д); }
      case "==": return равны(л, п);
      case "!=": return !равны(л, п);
      case "<": case "<=": case ">": case ">=": {
        const а = срав(л, п);
        return e.op === "<" ? а < 0 : e.op === "<=" ? а <= 0 : e.op === ">" ? а > 0 : а >= 0;
      }
      default: throw new Сбой(`неизвестная операция ${e.op}`);
    }
  }
  const чис = (v: unknown, op: string): number => {
    if (typeof v !== "number") throw new Сбой(`операция «${op}» требует число, получено ${стр(v)}`);
    return v;
  };
  const равны = (a: unknown, b: unknown): boolean => {
    // `пусто` сравнимо с любым типом: это вопрос «есть ли значение», а не
    // сравнение величин. Иначе проверка `у.след == пусто` не собирается.
    if (a === null || b === null) return (a === null) === (b === null);
    if (typeof a === "number" && typeof b === "number") return a === b;
    if (typeof a === "string" && typeof b === "string") return a === b;
    if (typeof a === "boolean" && typeof b === "boolean") return a === b;
    if (a === null && b === null) return true;
    throw new Сбой(`нельзя сравнить ${стр(a)} и ${стр(b)}: разные типы`);
  };
  const срав = (a: unknown, b: unknown): number => {
    if (typeof a === "number" && typeof b === "number") return a - b;
    if (typeof a === "string" && typeof b === "string") return a < b ? -1 : a > b ? 1 : 0;
    throw new Сбой(`нельзя упорядочить ${стр(a)} и ${стр(b)}`);
  };

  function операция(имя: string, арг: Expr[], обл: Область): unknown {
    const a = () => вычислить(арг[0]!, обл);
    const б = () => вычислить(арг[1]!, обл);
    switch (имя) {
      case "длина": {
        const з = a();
        if (typeof з === "string") return [...з].length;
        if (Array.isArray(з)) return з.length;
        throw new Сбой(`длина берётся у списка или строки, не у ${стр(з)}`);
      }
      case "вывести": вывод.push(стр(a())); return null;
      case "вывести_строку": вывод.push(String(a())); return null;
      case "добавить": { const с = a(); const з = б(); if (!Array.isArray(с)) throw new Сбой(`добавлять можно в список, не в ${стр(с)}`); с.push(з); return null; }
      case "удалить": { const с = a(); const и = б(); if (!Array.isArray(с)) throw new Сбой("удалять можно из списка"); с.splice(Number(и), 1); return null; }
      case "остаток": { const x = a(); const y = б(); if (typeof x !== "number" || typeof y !== "number") throw new Сбой("остаток берётся у чисел"); if (y === 0) throw new Сбой("остаток от деления на ноль"); return x % y; }
      case "корень": { const x = a(); if (typeof x !== "number") throw new Сбой("корень берётся у числа"); return Math.sqrt(x); }
      case "округлить": return Math.round(Number(a()));
      case "пол": return Math.floor(Number(a()));
      case "потолок": return Math.ceil(Number(a()));
      case "содержит": { const что = a(); const где = б(); if (typeof что !== "string" || typeof где !== "string") throw new Сбой("содержит — для строк"); return где.includes(что); }
      case "найти": { const что = a(); const где = б(); if (typeof что !== "string" || typeof где !== "string") throw new Сбой("найти — для строк"); return где.indexOf(что); }
      case "обрезать": { const з = a(); if (typeof з !== "string") throw new Сбой("обрезать — для строки"); return з.trim(); }
      case "верхний": { const з = a(); if (typeof з !== "string") throw new Сбой("верхний — для строки"); return з.toUpperCase(); }
      case "нижний": { const з = a(); if (typeof з !== "string") throw new Сбой("нижний — для строки"); return з.toLowerCase(); }
      case "ввод": return String(a());
      case "выделить": { const з = Number(a()); return з; }
      case "проверить": {
        if (!правда(a())) throw new Сбой(`проверка не выполнена${арг[1] ? ": " + стр(вычислить(арг[1], обл)) : ""}`);
        return null;
      }
      default: throw new Сбой(`неизвестная операция «${имя}»`);
    }
  }

  function вызвать(имя: string, арг: unknown[], обл: Область): unknown {
    const п = процедуры.get(имя);
    if (!п) {
      if (имя.includes(".")) {
        const местное = имя.split(".")[1]!;
        if (процедуры.has(местное)) throw new Сбой(`«${имя}»: подключение модулей в этом ядре не исполняется, вызовите «${местное}» напрямую`);
      }
      throw new Сбой(`нет процедуры «${имя}»`);
    }
    if (арг.length !== п.параметры.length) throw new Сбой(`«${имя}»: ожидается ${п.параметры.length} аргументов, получено ${арг.length}`);
    const внутри = new Область(обл);
    текущаяПроцедура = п;
    п.параметры.forEach((пар, i) => {
      if (пар.тип) проверитьТип(пар.тип, арг[i] ?? null, `аргумент «${пар.имя}» процедуры «${имя}»`);
      внутри.значения.set(пар.имя, арг[i] ?? null);
    });
    try {
      исполнитьБлок(п.тело, внутри);
    } catch (e) {
      if (e instanceof Возврат) return e.значение;
      throw e;
    }
    if (!п.действие) throw new Сбой(`процедура «${имя}» завершилась без «вернуть»: объявлен возврат «${п.возврат?.name ?? "?"}»`);
    return РЕЗУЛЬТАТ_ДЕЙСТВИЯ;
  }

  function исполнитьИнструкцию(s: Stmt, обл: Область): void {
    switch (s.k) {
      case "пусть": {
        const з = вычислить(s.з, обл);
        if (s.тип) проверитьТип(s.тип, з, `«${s.имя}»`);
        обл.значения.set(s.имя, з); return;
      }
      case "присвоить": {
        const з = вычислить(s.з, обл);
        if (s.цель.k === "имя") { обл.задать(s.цель.имя, з); return; }
        if (s.цель.k === "поле") {
          const о = вычислить(s.цель.объект, обл);
          if (о === null || typeof о !== "object" || Array.isArray(о)) throw new Сбой(`нельзя записать поле в ${стр(о)}`);
          (о as ПолеЗаписи)[s.цель.поле] = з; return;
        }
        const цель = s.цель;
        if (цель.k !== "индекс") throw new Сбой("слева от «=» должно быть имя, поле или элемент");
        const о = вычислить(цель.объект, обл);
        const и = вычислить(цель.индекс, обл);
        if (о !== null && typeof о === "object" && !Array.isArray(о)) {
          // Словарь: запись по КЛЮЧУ.
          (о as ПолеЗаписи)[String(и)] = з; return;
        }
        if (!Array.isArray(о)) throw new Сбой(`запись по индексу — только в список или словарь, не в ${стр(о)}`);
        const н = Number(и);
        if (!Number.isInteger(н) || н < 0 || н >= о.length) throw new Сбой(`индекс ${н} вне списка длиной ${о.length}`);
        о[н] = з; return;
      }
      case "вызов_инстр": {
        if (s.вызов.k === "вызов") вызвать(s.вызов.имя, s.вызов.арг.map((a) => вычислить(a, обл)), обл);
        else if (s.вызов.k === "операция") операция(s.вызов.имя, s.вызов.арг, обл);
        else throw new Сбой("инструкция ничего не делает: нужен вызов или присваивание");
        return;
      }
      case "вернуть": {
        const з = s.з ? вычислить(s.з, обл) : null;
        if (з === РЕЗУЛЬТАТ_ДЕЙСТВИЯ) throw new Сбой("действие не возвращает значение: его результат нельзя использовать");
        const п = текущаяПроцедура;
        if (п && !п.действие && п.возврат) проверитьТип(п.возврат, з, `возврат процедуры «${п.имя}»`);
        throw new Возврат(з);
      }
      case "поднять": throw new Сбой(вычислить(s.з, обл));
      case "проверить": {
        if (!правда(вычислить(s.усл, обл))) {
          throw new Сбой(`проверка не выполнена${s.сообщение ? ": " + стр(вычислить(s.сообщение, обл)) : ""}`);
        }
        return;
      }
      case "прервать": throw new Прервать();
      case "продолжить": throw new Продолжить();
      case "если": {
        for (const в of s.ветви) if (правда(вычислить(в.усл, обл))) { исполнитьБлок(в.тело, new Область(обл)); return; }
        if (s.иначе) исполнитьБлок(s.иначе, new Область(обл));
        return;
      }
      case "пока": {
        while (правда(вычислить(s.усл, обл))) {
          try { исполнитьБлок(s.тело, new Область(обл)); }
          catch (e) { if (e instanceof Прервать) break; if (e instanceof Продолжить) continue; throw e; }
        }
        return;
      }
      case "для_каждого": {
        const ист = вычислить(s.ист, обл);
        const эл = Array.isArray(ист) ? ист : typeof ист === "string" ? [...ист] : null;
        if (!эл) throw new Сбой(`перебирать можно список или строку, не ${стр(ист)}`);
        for (let i = 0; i < эл.length; i++) {
          const внутри = new Область(обл);
          внутри.значения.set(s.эл, эл[i] ?? null);
          if (s.индекс) внутри.значения.set(s.индекс, i);
          try { исполнитьБлок(s.тело, внутри); }
          catch (e) { if (e instanceof Прервать) break; if (e instanceof Продолжить) continue; throw e; }
        }
        return;
      }
      case "для_диапазона": {
        const от = чис(вычислить(s.от, обл), "от");
        const до = чис(вычислить(s.до, обл), "до");
        const ш = s.шаг ? чис(вычислить(s.шаг, обл), "шаг") : от <= до ? 1 : -1;
        if (ш === 0) throw new Сбой("шаг цикла не может быть нулём");
        for (let i = от; ш > 0 ? i <= до : i >= до; i += ш) {
          const внутри = new Область(обл);
          внутри.значения.set(s.пер, i);
          try { исполнитьБлок(s.тело, внутри); }
          catch (e) { if (e instanceof Прервать) break; if (e instanceof Продолжить) continue; throw e; }
        }
        return;
      }
      case "повторять": {
        const н = чис(вычислить(s.раз, обл), "повторять");
        for (let i = 0; i < н; i++) {
          try { исполнитьБлок(s.тело, new Область(обл)); }
          catch (e) { if (e instanceof Прервать) break; if (e instanceof Продолжить) continue; throw e; }
        }
        return;
      }
      case "цикл": {
        for (;;) {
          try { исполнитьБлок(s.тело, new Область(обл)); }
          catch (e) { if (e instanceof Прервать) break; if (e instanceof Продолжить) continue; throw e; }
        }
        return;
      }
      case "разбор": {
        const з = вычислить(s.значение, обл);
        if (typeof з !== "string") throw new Сбой(`разбор — по значению перечня, получено ${стр(з)}`);
        // Исчерпание: имя перечня берётся из самой ветки (`Фигура.пешка`).
        const имяПеречня = s.ветви[0]!.вариант.split(".")[0]!;
        const тд = типы.get(имяПеречня);
        if (тд?.варианты && !s.иначе) {
          const неРазобраны = тд.варианты.filter((в) => !s.ветви.some((б) => б.вариант === `${имяПеречня}.${в}`));
          if (неРазобраны.length) {
            throw new Сбой(`разбор не покрывает: ${неРазобраны.map((в) => `${имяПеречня}.${в}`).join(", ")} — добавьте ветку «есть …» или «иначе»`);
          }
        }
        for (const в of s.ветви) if (в.вариант === з) { исполнитьБлок(в.тело, new Область(обл)); return; }
        if (s.иначе) { исполнитьБлок(s.иначе, new Область(обл)); return; }
        throw new Сбой(`разбор не покрывает значение ${з}: нужна ветка «есть …» или «иначе»`);
      }
      case "защита": {
        try { исполнитьБлок(s.тело, new Область(обл)); }
        catch (e) {
          if (!(e instanceof Сбой)) throw e;
          if (!s.приОшибке) throw e;
          const внутри = new Область(обл);
          if (s.приОшибке.имя) внутри.значения.set(s.приОшибке.имя, e.значение);
          исполнитьБлок(s.приОшибке.тело, внутри);
        }
        return;
      }
    }
  }

  function проверитьТип(т: TypeRef, з: unknown, где: string): void {
    if (т.может && (з === null || з === undefined)) return;
    if (т.может) return проверитьТип({ ...т, может: false }, з, где);
    switch (т.name) {
      case "Число": if (typeof з !== "number") throw new Сбой(`${где}: ожидалось Число, получено ${стр(з)}`); return;
      case "Строка": if (typeof з !== "string") throw new Сбой(`${где}: ожидалась Строка, получено ${стр(з)}`); return;
      case "Логическое": if (typeof з !== "boolean") throw new Сбой(`${где}: ожидалось Логическое, получено ${стр(з)}`); return;
      case "Пусто": if (з !== null) throw new Сбой(`${где}: ожидалось Пусто, получено ${стр(з)}`); return;
      case "Список": if (!Array.isArray(з)) throw new Сбой(`${где}: ожидался список, получено ${стр(з)}`); return;
      case "Словарь": if (з === null || typeof з !== "object" || Array.isArray(з)) throw new Сбой(`${где}: ожидался словарь, получено ${стр(з)}`); return;
      default: {
        const тд = типы.get(т.name);
        if (!тд) throw new Сбой(`${где}: неизвестный тип «${т.name}»`);
        if (тд.варианты) {
          if (typeof з !== "string" || !тд.варианты.some((в) => `${т.name}.${в}` === з || в === з)) {
            throw new Сбой(`${где}: значение ${стр(з)} не входит в перечень «${т.name}»`);
          }
          return;
        }
        if (з === null || typeof з !== "object" || Array.isArray(з)) throw new Сбой(`${где}: ожидалась запись «${т.name}»`);
        for (const п of тд.поля ?? []) проверитьТип(п.тип, (з as ПолеЗаписи)[п.имя] ?? null, `${где}.${п.имя}`);
        return;
      }
    }
  }

  function исполнитьБлок(тело: Stmt[], обл: Область): void {
    for (const s of тело) исполнитьИнструкцию(s, обл);
  }

  try {
    const гл = процедуры.get("главная")!;
    const обл = new Область();
    try { исполнитьБлок(гл.тело, обл); }
    catch (e) { if (e instanceof Возврат) return { вывод, итог: e.значение }; throw e; }
    if (!гл.действие) throw new Сбой("процедура «главная» завершилась без «вернуть»");
    return { вывод, итог: null };
  } catch (e) {
    if (e instanceof Сбой) return { вывод, итог: undefined, ошибка: `сбой: ${стр(e.значение)}` };
    if (e instanceof Прервать) return { вывод, итог: undefined, ошибка: "«прервать» вне цикла" };
    if (e instanceof Продолжить) return { вывод, итог: undefined, ошибка: "«продолжить» вне цикла" };
    return { вывод, итог: undefined, ошибка: (e as Error).message };
  }
}
