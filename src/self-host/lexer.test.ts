/**
 * ЛЕКСЕР v3 НА v3 — ОРАКУЛ. НАПИСАН ДО РЕАЛИЗАЦИИ И ДО НЕЁ КРАСНЫЙ.
 *
 * # Что здесь спрашивается
 *
 * Задача 4: маленький лексер (200–300 строк) на самой Основе, читающий программу на v3 и выдающий
 * токены. Эталон — ДЕЙСТВУЮЩИЙ TS-лексер v3 (`src/compiler-v3/lexer.ts`, `tokenizeV3`): сверка
 * ПОБИТОВАЯ, а не «похоже».
 *
 * # Формат ответа выбран так, чтобы сверка была возможна
 *
 * У языка нет записей и структур (`§3.103.2`: элемента коллекции — одно 8-байтовое слово), поэтому
 * лексер отдаёт токены СТРОКОЙ: по строке на токен, `вид|лексема`. Ровно этот формат уже принят в
 * дереве для оракула лексера (`src/self-host/oracle-lexer.ts`: `t.kind + '|' + t.lexeme`) — то есть
 * соглашение не выдумано здесь, а взято у существующего эталона.
 *
 * Сверка идёт со ВСЕМ потоком целиком, включая `новая_строка` и `конец_файла`: сравнение лишь
 * «содержательных» токенов пропустило бы и потерю переводов строк, и лишний токен в конце.
 *
 * # Почему строкой, а не коллекцией
 *
 * Коллекция — это ЧИСЛО-адрес с 8-байтовыми элементами: положить туда пару (вид, лексема) значило бы
 * положить два элемента на токен и держать рядом второй список длин. Строка сравнивается целиком и
 * не требует соглашения о раскладке — а соглашение, которого нет, не может разойтись.
 *
 * # Границы — названы
 *
 * Здесь исполнение на ОБЕИХ VM (стековая — эталон, регистровая — путь к цели). Прогон на e2k
 * сделан отдельным заходом 2026-10-10 и **замерен** (`docs/hardware-debt.md` §3.132): прежняя
 * редакция этого абзаца называла границу словами («строки на цели СТАТИЧЕСКИЕ, а лексер строит
 * результат В РАНТАЙМЕ») — и это оказалось неверным в главном: склейка строк в рантайме на цели
 * РАБОТАЕТ, и шаг форматирования токена исполняется в модели и на железе со сверкой против этого
 * файла (`src/self-host/foundationE2k.test.ts`, числа 10 и 25). Настоящие стены другие и названы по
 * имени (`src/e2k/booleanLiterals.test.ts`): индексация `с[и]` (`система.строка.символ`), поиск
 * `содержит`, длина строки-ПАРАМЕТРА в вызываемой и склейка ТРЁХ строк в вызываемой (рантайм держит
 * состояние вне её окна), плюс место образа — код 8064 байта против статических строк на 6938.
 * Заявление без замера здесь и было дефектом: граница обязана быть числом, а не фразой.
 *
 * # Что изменилось 2026-10-23 (и почему оракул переписан)
 *
 * Лексер сравнивал ЗНАКИ СТРОКАМИ (`с == "("`, `содержит с в цифры`) — и перестал собираться,
 * когда решение владельца 2026-10-10 сделало `с[и]` ЧИСЛОМ (код Unicode): **4** диагностики
 * «Несовпадение типа (с_токеном#1): ожидалось Строка, получено Число», **5** проверок из 7 красных.
 * Теперь проверки знаков — ЧИСЛАМИ (таблица кодов в шапке `src/self-host/lexer.osnova`), а ТЕКСТ
 * знака берётся срезом исходника `подстрока(исходник, поз, поз + 1)` — встроенным словом v3,
 * добавленным ровно для этого (`система.строка.подстрока`; после 2026-10-10 у v3 не оставалось ни
 * одного другого способа получить из исходника ТЕКСТ: имя из трёх сегментов v3 не разбирает).
 *
 * Стены цели после переписи — обе ИЗМЕРЕНЫ (§3.133): `подстрока` на цели понижения НЕ имеет (отказ
 * `OSN-LOW-003` по имени), а место образа — код **7472** байта против статических строк на смещении
 * **7099** (замер на теле без срезов: со срезами конвейер останавливается РАНЬШЕ — утверждением об
 * арене «регистры её не закреплены»). Прежние числа 8064/6938 относились к прежней редакции лексера.
 */
import { describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { tokenizeV3 } from '../compiler-v3/lexer';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';
import { FILE_CALLS, createFileInvokeHandler } from '../runtime/vm/fileCalls';

const ROOT = path.resolve(__dirname, '..', '..');
const ЛЕКСЕР = path.join(ROOT, 'src', 'self-host', 'lexer.osnova');

/**
 * ПРОГРАММА ДЛЯ ПРОБЫ — десять строк, и в ней ЕСТЬ всё, что лексер обязан различать:
 * служебные слова и их композиции (`для каждого`, `конец если`), комментарии обоих видов,
 * СТРОКОВЫЙ ЛИТЕРАЛ, число с точкой, знаки сравнения из двух символов (`>=`), `→` в объявлении
 * типа, индексная форма, точка квалификации.
 *
 * Мало строки «пусть x = 1»: на ней прошёл бы и лексер, который не знает ни комментариев, ни
 * склейки слов, — то есть прибор не различал бы то, что должен. Проверка СОСТАВА пробы — отдельная
 * проверка ниже, и она покраснела, когда строкового литерала в пробе не было (первая редакция).
 */
const ПРОГРАММА = `// проба лексера: комментарий до конца строки
процедура сумма(а: Число, б: Число) → Число
  /* блочный
     комментарий */
  пусть итог = а + б * 2
  если итог >= 10 и итог != 12
    для каждого эл в [1, 2.5]
      итог = итог + эл
    конец для
  конец если
  вывести "итог готов"
  вернуть итог
конец
`;

/** Эталон: TS-лексер v3, тот же формат, что у лексера на Основе. */
function эталон(исходник: string): string {
  const { tokens } = tokenizeV3(исходник, 'проба.osnova');
  return tokens.map((t) => `${t.kind}|${t.lexeme}`).join('\n');
}

/** Лексер на v3: исходник → его ответ (строка того же формата). */
async function ответЛексера(исходник: string): Promise<string> {
  return await наОснове(ЛЕКСЕР, 'лексировать', [исходник]);
}

/**
 * ОБРАБОТЧИК ПРОГОНА: файловые операции — портами (они нужны `лексировать_файл`), всё остальное —
 * обычным языковым набором. Композиция ЯВНАЯ, по имени: `закрыть` законно возвращает `null`, и
 * догадка «null значит не моё» отдала бы закрытие базовому обработчику (замер — в `fileOps.test.ts`).
 *
 * Порты — настоящая файловая система: оракул читает ТОТ ЖЕ файл, что положил сам, и сверяет с
 * эталоном по его содержимому.
 */
function обработчик(): (name: string, args: unknown[]) => unknown {
  const открытые = new Map<number, string>();
  let следующий = 3;
  const файловый = createFileInvokeHandler({
    open: (путь: string) => {
      if (!fs.existsSync(путь)) return { error: 2 };
      const дескриптор = следующий++;
      открытые.set(дескриптор, путь);
      return { fd: дескриптор };
    },
    read: (fd: number, длина: number) => {
      const путь = открытые.get(fd);
      if (путь === undefined) return { error: 9 };
      // Длина в КОДОВЫХ ТОЧКАХ — как у `длина` строки.
      return { text: [...fs.readFileSync(путь, 'utf-8')].slice(0, длина).join('') };
    },
    write: () => ({ error: 9 }),
    close: (fd: number) => (открытые.delete(fd) ? null : { error: 9 }),
  });
  const базовый = createDefaultInvokeHandler();
  return (name: string, args: unknown[]) =>
    Object.values(FILE_CALLS).includes(name as (typeof FILE_CALLS)[keyof typeof FILE_CALLS])
      ? файловый(name, args as never)
      : базовый(name, args as never);
}

/**
 * Прогон процедуры из файла `.osnova` на обеих VM: стековая — эталон, регистровая — путь к цели.
 *
 * Компилируется ФАЙЛ, а не строка: лексер — программа на Основе, и он обязан проходить тот же
 * конвейер (`parseV3` → семантика → кодоген), что любая другая.
 */
async function наОснове(файл: string, процедура: string, аргументы: unknown[]): Promise<string> {
  const исходник = fs.readFileSync(файл, 'utf-8');
  const р = parseV3(исходник, path.basename(файл));
  expect(р.errors, `разбор лексера: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м), 'проход разрешения лексера').toEqual([]);
  const стековая = new VM(compile(м), { invoke: обработчик() as never, maxSteps: 20_000_000 });
  const стек = await стековая.runProcedure(стековая.findProcedureIndex(процедура), аргументы);
  const регистровая = new RegVM(compileToReg(м), {
    invoke: обработчик() as never,
    maxSteps: 20_000_000,
  });
  const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex(процедура), аргументы);
  expect(регистры, 'обе VM обязаны дать ОДНО: иначе расхождение эталонов, а не ответ').toBe(стек);
  return String(стек);
}

describe('лексер на v3: сверка с TS-лексером побитово', () => {
  it('ЛЕКСЕР СОБИРАЕТСЯ: файл проходит разбор, семантику и обе VM', () => {
    // Отдельная проверка «собирается» — чтобы красное на сверке не путалось с «не компилируется».
    // Это тот же принцип, что у оракулов цели: провал обязан называть СВОЁ звено.
    expect(fs.existsSync(ЛЕКСЕР), 'файл лексера на месте').toBe(true);
    const исходник = fs.readFileSync(ЛЕКСЕР, 'utf-8');
    const р = parseV3(исходник, 'lexer.osnova');
    expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
    const м = р.program!.modules[0]!;
    expect(validateNamedTypesAndRewrite(м), 'разрешение имён').toEqual([]);
    const строк = исходник.split('\n').length;
    expect(строк, 'размер лексера — от 100 строк: меньше значило бы, что это не лексер').toBeGreaterThan(100);
  });

  it('СВЕРКА ПОБИТОВО: токены совпали с TS-лексером, включая переводы строк и конец файла', async () => {
    const ожидание = эталон(ПРОГРАММА);
    const получено = await ответЛексера(ПРОГРАММА);
    // Сравнение ЦЕЛИКОМ: расхождение называет первое место, где потоки разошлись, — иначе при
    // 60 токенах разбирать пришлось бы глазами.
    if (получено !== ожидание) {
      const а = ожидание.split('\n');
      const б = получено.split('\n');
      let первое = 0;
      while (первое < а.length && первое < б.length && а[первое] === б[первое]) первое++;
      expect.fail(
        `токены разошлись на позиции ${String(первое)}: эталон «${а[первое] ?? "<конец>"}», ` +
          `лексер «${б[первое] ?? "<конец>"}» (всего в эталоне ${String(а.length)}, у лексера ${String(б.length)})`,
      );
    }
    // И число токенов названо числом — это то, что требует отчёт.
    expect(ожидание.split('\n').length, 'токенов в пробе').toBeGreaterThan(40);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: убрать ключевое слово — сверка ОБЯЗАНА покраснеть', async () => {
    // Контроль на САМ ОРАКУЛ: если сверка зеленеет при любом вводе, она ничего не утверждает.
    // Здесь из пробы убирается закрывающее слово `конец если` — поток токенов обязан измениться, и
    // различие обязано быть ВИДНО в сравнении (а не «программа сломалась»).
    const без = ПРОГРАММА.replace('  конец если\n', '');
    const ожидание = эталон(ПРОГРАММА);
    const ожиданиеБез = эталон(без);
    expect(ожиданиеБез, 'эталон РАЗЛИЧАЕТ эти две программы').not.toBe(ожидание);
    const полученоБез = await ответЛексера(без);
    expect(полученоБез, 'лексер тоже различает').not.toBe(ожидание);
    expect(полученоБез).toBe(ожиданиеБез);
  });

  it('КОНТРОЛЬ ПРИБОРА: эталон не пуст и содержит все виды, которые лексер обязан различать', () => {
    // Прибор обязан различать то, что должен (признак 1 линии). Проверяется СОСТАВ пробы, а не её
    // длина: иначе «60 токенов» могло бы оказаться 60 переводами строк.
    const { tokens } = tokenizeV3(ПРОГРАММА, 'проба.osnova');
    const виды = new Set(tokens.map((t) => t.kind));
    for (const обязательный of ['число', 'строка', 'имя', 'новая_строка', 'конец_файла', 'процедура', 'если', 'для', 'каждого', '→', '>=', '!=']) {
      expect(виды, `проба обязана содержать «${обязательный}»`).toContain(обязательный);
    }
  });
});

describe('лексер на v3: чтение файла и границы', () => {
  it('ЧИТАЕТ ФАЙЛ: `лексировать_файл` даёт то же, что `лексировать` по содержимому', async () => {
    // Вторая половина задачи 4 («читает файл»): она опирается на файловые слова задачи 1. Проверка
    // разделена с лексированием нарочно — красное обязано называть, ЧТО сломалось: чтение или разбор.
    const файл = path.join(ROOT, '.tmp', 'lexer-probe.osnova');
    fs.mkdirSync(path.dirname(файл), { recursive: true });
    fs.writeFileSync(файл, ПРОГРАММА, 'utf-8');
    const изФайла = await наОснове(ЛЕКСЕР, 'лексировать_файл', [файл]);
    expect(изФайла, 'то же, что по строке').toBe(эталон(ПРОГРАММА));
  });

  it('ПУСТАЯ ПРОГРАММА: один токен `конец_файла`, а не пустая строка', async () => {
    // Крайняя точка: без неё «лексер всегда что-то возвращает» прошло бы на всех прочих проверках.
    const пусто = await наОснове(ЛЕКСЕР, 'лексировать', ['']);
    expect(пусто).toBe('конец_файла|<конец файла>');
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: убрать ключевое слово — сверка обязана покраснеть ##2', () => {
    // Второй контроль, на ДРУГОМ слове: `и` (логическое). Он различает случай «лексер знает слова
    // из одного списка» от «лексер знает все» — один контроль этого не показывает.
    const сИ = эталон(ПРОГРАММА);
    const безИ = эталон(ПРОГРАММА.replace(' и ', ' '));
    expect(безИ).not.toBe(сИ);
    const виды = tokenizeV3(ПРОГРАММА, 'п.osnova').tokens.map((t) => t.kind);
    expect(виды, 'в пробе есть логическое «и»').toContain('и');
  });
});
