/**
 * ДОСТУП К СИМВОЛУ СТРОКИ — ОРАКУЛ. НАПИСАН ДО РЕАЛИЗАЦИИ И ДО НЕЁ КРАСНЫЙ.
 *
 * # Что здесь спрашивается и почему именно это
 *
 * `"абв"[0]` сегодня даёт **`null`** на обеих VM, а `[10,20,30][0]` даёт **10**. Разница не в форме
 * записи (форма одна и та же — `система.массив.получить`, её ставит парсер), а в ТИПЕ операнда:
 * получить элемент у массива VM умеет, у строки — нет. То есть это **дефект**, а не отсутствие
 * syntax: `arr[i]` — форма обращения, и она обязана работать для строки.
 *
 * Лексеру (задача 4) это нужно раньше всего остального: без символа строки токен не собрать.
 *
 * # Как формулируется требование
 *
 * `"абв"[i]` — это СИМВОЛ, и он равен **строке** из одного символа: `"абв"[0] == "а"`. Именно так
 * формулирует владелец, и так же ведёт себя `система.строка.подстрока(с, i, i + 1)`. Отсюда
 * отрицательная половина, без которой положительная ничего не значит:
 *
 * | наблюдение | что различает |
 * |---|---|
 * | `"абв"[0] == "а"` | символ приходит, и он именно тот |
 * | `"абв"[0] + 100` **≠ 100** | прежде `null` вёл себя как ноль — это была ТИХАЯ ЛОЖЬ |
 * | `"абв"[3]` | названный отказ, а не `null` и не пустая строка |
 *
 * # Три состояния, а не два
 *
 * «Есть», «отказ по границе» и «нет вовсе» — разные вещи, и в языке они выглядят по-разному:
 * значение, НАЗВАННЫЙ ОТКАЗ (исключение с текстом) и `null`. Смешать отказ с `null` значило бы
 * сделать выход за границу неотличимым от законного пустого значения — ровно тот класс, из-за
 * которого в проекте уже разбирали `arr[i]` с несуществующим полем.
 *
 * # Границы этого файла
 *
 * Здесь — обе VM (стековая и регистровая). Понижение на e2k спрашивается отдельно и НАЗЫВАЕТСЯ:
 * строки на цели статические, и символ по РАНТАЙМОВОМУ индексу — отдельная работа
 * (`src/self-host/stringIndexE2k.test.ts`).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';

const ФАЙЛ = 'строка.osnova';

/** v3-исходник → модуль, прошедший разрешение имён (то же, что делает общий конвейер). */
function модуль(источник: string) {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м), 'проход разрешения').toEqual([]);
  return м;
}

/** Обе VM: стековая — эталон языка, регистровая — нативная цель. */
async function обеVM(источник: string): Promise<{ стек: unknown; регистры: unknown }> {
  const м = модуль(источник);
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = await стековая.runProcedure(стековая.findProcedureIndex('главная'), []);
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []);
  return { стек, регистры };
}

/** Один и тот же вопрос обеим VM: значения обязаны совпасть, и оба — с эталоном. */
async function значение(источник: string): Promise<unknown> {
  const { стек, регистры } = await обеVM(источник);
  expect(регистры, 'регистровая VM обязана дать то же, что стековая').toBe(стек);
  return стек;
}

/** Названный отказ: обе VM отказывают, и текст отказа не пуст. */
async function отказ(источник: string): Promise<string> {
  let сообщение = '';
  try {
    await обеVM(источник);
  } catch (ошибка) {
    сообщение = (ошибка as Error).message;
  }
  expect(сообщение, 'обе VM обязаны ОТКАЗАТЬ, а не вернуть значение').not.toBe('');
  return сообщение;
}

describe('символ строки по индексу: `"абв"[i]`', () => {
  it('ПОЛОЖИТЕЛЬНАЯ СТОРОНА: "абв"[0] — это символ «а», а не null', async () => {
    // Требование владельца дословно: `"абв"[0] == "а"`. Возвращается СТРОКА из одного символа —
    // так же, как её вернула бы `система.строка.подстрока("абв", 0, 1)`.
    const значениеПервого = await значение(`действие главная()
  пусть с = "абв"
  если с[0] == "а"
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(значениеПервого, '"абв"[0] == "а"').toBe(1);
  });

  it('ПОСЛЕДНИЙ символ: "абв"[2] == "в" — граница с обеих сторон', async () => {
    // Второе наблюдение, и оно обязательно: «нулевой символ совпал» ничего не говорит о том, что
    // индекс вообще участвует в вычислении — реализация «всегда первый символ» прошла бы первую
    // проверку. Здесь индекс другой, и ответ другой.
    const последний = await значение(`действие главная()
  пусть с = "абв"
  если с[2] == "в"
    вернуть 7
  конец если
  вернуть 0
конец
`);
    expect(последний, '"абв"[2] == "в"').toBe(7);
  });

  it('НЕ НОЛЬ: "абв"[0] + 100 ≠ 100 — прежде null вёл себя как ноль', async () => {
    // Это и есть различающая проба тихой лжи. До правки `"абв"[0] + 100` давало **100**: `null`
    // складывался с числом как ноль. Лексер на такой строке «прочитал» бы символы как нули и выдал
    // поток пустых токенов МОЛЧА. Здесь проверяется, что символ — не ноль.
    const сумма = await значение(`действие главная()
  пусть с = "абв"
  вернуть с[0] + 100
конец
`);
    expect(сумма, 'символ + 100 не может быть 100: это значило бы, что символ нулевой').not.toBe(100);
  });

  it('ИНДЕКС — ВЫРАЖЕНИЕ, а не только литерал: с[поз + 1] == "в"', async () => {
    // В лексере позиция почти всегда вычисляется (`позиция + 1`), поэтому проверять доступ
    // литералом было бы проверкой не того случая.
    //
    // Имя счётчика — `поз`, а НЕ `и`: `и` в v3 — ключевое слово (логическое «и»), и первая
    // редакция этой проверки краснела на разборе («ожидается имя переменной, получено «и»») —
    // то есть проверяла зарезервированность слова, а не доступ по индексу. Это названо здесь,
    // потому что то же спотыкание ждёт всякого, кто пишет на v3.
    const вычисленный = await значение(`действие главная()
  пусть с = "абв"
  пусть поз = 1
  если с[поз + 1] == "в"
    вернуть 3
  конец если
  вернуть 0
конец
`);
    expect(вычисленный, 'с[поз + 1] == "в"').toBe(3);
  });

  it('СРАВНЕНИЕ С ЭТАЛОНОМ: символ — ровно один знак, и склейка это подтверждает', async () => {
    // Независимый свидетель, доступный В v3. Прежняя редакция сверялась с
    // `система.строка.подстрока(с, 1, 2)` — и это была ошибка ПРОВЕРКИ, а не находка: в v3
    // цепочка имён перед вызовом запрещена (долг §3.105.5), поэтому такой эталон в v3 не
    // выражается вовсе. Эталон взят из СВОЙСТВ значения, а не из другой операции:
    //   • символ склеивается со строкой как один знак: `с[1] + "!"` = «б!»;
    //   • длина символа — 1 КОДОВАЯ ТОЧКА (согласовано с `длина`, у которой «🙂» = 1).
    const склейка = await значение(`действие главная()
  пусть с = "абв"
  пусть знак = с[1]
  если знак + "!" == "б!"
    вернуть 5
  конец если
  вернуть 0
конец
`);
    expect(склейка, 'с[1] + "!" == "б!"').toBe(5);

    const длина = await значение(`действие главная()
  пусть с = "абв"
  пусть знак = с[1]
  вернуть длина знак
конец
`);
    expect(длина, 'символ — одна кодовая точка').toBe(1);
  });

  it('КОДОВЫЕ ТОЧКИ, А НЕ БАЙТЫ: "🙂"[0] == "🙂" — иначе длина и индекс разошлись бы', async () => {
    // Единицы — то, на чём легко ошибиться молча: у «🙂» ОДИН кодпоинт и ЧЕТЫРЕ байта UTF-8.
    // Если бы индекс считался в единицах UTF-16, `"🙂"[0]` вернул бы половину суррогатной пары
    // (невалидный текст), а если в байтах — отказ на нулевом индексе. Обе ошибки ловятся здесь.
    const смайл = await значение(`действие главная()
  пусть с = "🙂"
  если с[0] == "🙂"
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(смайл, '"🙂"[0] == "🙂"').toBe(1);

    const длина = await значение(`действие главная()
  пусть с = "🙂"
  пусть знак = с[0]
  вернуть длина знак
конец
`);
    expect(длина, 'длина символа-смайла — 1 кодовая точка').toBe(1);
  });

  it('КОНТРОЛЬ: список по-прежнему индексируется — правка не сломала соседнее', async () => {
    const список = await значение(`действие главная()
  пусть с = [10, 20, 30]
  вернуть с[0] + с[2]
конец
`);
    expect(список, 'список индексируется как раньше').toBe(40);
  });
});

describe('символ строки: выход за границу — НАЗВАННЫЙ отказ', () => {
  it('"абв"[3] — отказ, а не null и не пустая строка', async () => {
    // Граница названа с ОБЕИХ сторон: [2] выше даёт «в», [3] здесь обязан отказать. Одного
    // наблюдения мало: «[3] отказывает» ничего не говорит о том, что [2] работает.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[3]
конец
`);
    expect(сообщение.length, 'причина отказа названа словами').toBeGreaterThan(10);
  });

  it('"абв"[-1] — тоже отказ: отрицательный индекс не заворачивается', async () => {
    // Второе наблюдение, и другой край: реализация «отказ только для слишком больших» прошла бы
    // первую проверку. Отрицательный индекс — не «с конца», а отказ: в языке такого правила нет.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[0 - 1]
конец
`);
    expect(сообщение.length).toBeGreaterThan(10);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: отказ НАЗЫВАЕТ индекс и длину, а не «не получилось»', async () => {
    // Иначе отказ неотличим от любого другого: «что-то пошло не так» — не диагноз. Проверяются
    // ЧИСЛА из программы: индекс 3 и длина 3.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[3]
конец
`);
    expect(сообщение, 'в отказе назван индекс').toContain('3');
  });

  it('КОНТРОЛЬ ОТКАЗА: пустая строка — отказ на нулевом индексе, а не пустое значение', async () => {
    // Крайняя точка: у пустой строки нет ни одного символа, поэтому `[0]` — выход за границу.
    // Без этой точки «отказ по границе» мог бы оказаться «отказом всегда».
    const сообщение = await отказ(`действие главная()
  пусть с = ""
  вернуть с[0]
конец
`);
    expect(сообщение.length).toBeGreaterThan(10);
  });
});
