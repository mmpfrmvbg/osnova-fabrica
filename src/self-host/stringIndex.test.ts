/**
 * КОД СИМВОЛА СТРОКИ ПО ИНДЕКСУ — ОРАКУЛ. НАПИСАН ДО РЕАЛИЗАЦИИ И ДО НЕЁ КРАСНЫЙ.
 *
 * # Что здесь спрашивается и почему именно это
 *
 * `"абв"[0]` сегодня даёт **`null`** на обеих VM, а `[10,20,30][0]` даёт **10**. Разница не в форме
 * записи (форма одна и та же — `система.массив.получить`, её ставит парсер), а в ТИПЕ операнда:
 * получить элемент у массива VM умеет, у строки — нет. То есть это **дефект**, а не отсутствие
 * syntax: `arr[i]` — форма обращения, и она обязана работать для строки.
 *
 * Лексеру (задача 4) это нужно раньше всего остального: без кода символа токен не собрать.
 *
 * # РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-10-10: это ЧИСЛО — код символа (отменяет редакцию 2026-10-04)
 *
 * Прежняя редакция этого файла требовала СТРОКУ из одного символа («`"абв"[0] == "а"`», так было
 * сформулировано владельцем 2026-10-04) и на этом стояла. Решение отменено по ЗАМЕРУ, а не по
 * вкусу: строковая модель цели требует, чтобы длина строки была известна НА СБОРКЕ, а символ по
 * РАНТАЙМОВОМУ индексу — это 1–4 байта, известных только в рантайме (`docs/hardware-debt.md`
 * §3.132). Значит символом-строкой `с[и]` на цели невыразим в принципе, а держать строку в VM и
 * число на цели проект запрещает: расхождение VM и цели — тот самый класс «тихой лжи».
 *
 * Поэтому спрашивается КОД:
 *
 * | наблюдение | что различает |
 * |---|---|
 * | `"абв"[0] == 1072` (U+0430) | код приходит, и он именно тот |
 * | `"abc"[0] == 97` | латиница и кириллица не перепутаны местами |
 * | `"абв"[2] == 1074` | индекс УЧАСТВУЕТ в вычислении: «всегда первый» краснеет здесь |
 * | `"абв"[0] + 100 == 1172` | код — ЧИСЛО: прежде здесь была склейка «а100» |
 * | `"🙂"[0] == 128578` | единица — КОДОВАЯ ТОЧКА, а не единица UTF-16 и не байт |
 * | `"абв"[3]`, `"абв"[-1]` | названный отказ, а не `null` и не пустая строка |
 *
 * # Три состояния, а не два
 *
 * «Есть», «отказ по границе» и «нет вовсе» — разные вещи, и в языке они выглядят по-разному:
 * значение, НАЗВАННЫЙ ОТКАЗ (исключение с текстом) и `null`. Смешать отказ с `null` значило бы
 * сделать выход за границу неотличимым от законного пустого значения.
 *
 * # Границы этого файла
 *
 * Здесь — обе VM (стековая и регистровая). Цель спрашивается отдельно: у неё исключений нет, и
 * выход за границу даёт **−1** (`src/e2k/stringSymbol.test.ts`, §3.133) — это расхождение названо,
 * а не замолчано.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';

const ФАЙЛ = 'строка.osnova';

/** Коды, а не литералы: эталон считает JavaScript, а не наша выписка. */
const А = 'а'.codePointAt(0)!;
const В = 'в'.codePointAt(0)!;
const СМАЙЛ = '🙂'.codePointAt(0)!;

/** v3-исходник → модуль, прошедший разрешение имён (то же, что делает общий конвейер). */
function модуль(источник: string) {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м), 'проход разрешения').toEqual([]);
  return м;
}

/** Обе VM: стековая — эталон языка, регистровая — нативная цель. */
async function обеVM(источник: string): Promise<{ стек: unknown; регистры: unknown }> {
  const м = модуль(источник);
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = await стековая.runProcedure(стековая.findProcedureIndex('главная'), []);
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []);
  return { стек, регистры };
}

/** Один и тот же вопрос обеим VM: значения обязаны совпасть, и оба — с эталоном. */
async function значение(источник: string): Promise<unknown> {
  const { стек, регистры } = await обеVM(источник);
  expect(регистры, 'регистровая VM обязана дать то же, что стековая').toBe(стек);
  return стек;
}

/** Названный отказ: обе VM отказывают, и текст отказа не пуст. */
async function отказ(источник: string): Promise<string> {
  let сообщение = '';
  try {
    await обеVM(источник);
  } catch (ошибка) {
    сообщение = (ошибка as Error).message;
  }
  expect(сообщение, 'обе VM обязаны ОТКАЗАТЬ, а не вернуть значение').not.toBe('');
  return сообщение;
}

describe('код символа строки по индексу: `"абв"[i]`', () => {
  it('ПОЛОЖИТЕЛЬНАЯ СТОРОНА: "абв"[0] — код «а» (1072), а не null и не строка', async () => {
    const первый = await значение(`действие главная()
  пусть с = "абв"
  если с[0] == ${А}
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(первый, '"абв"[0] == 1072').toBe(1);
  });

  it('ЛАТИНИЦА: "abc"[0] == 97 — код берётся из Unicode, а не «как в кириллице»', async () => {
    // Второе наблюдение и другая половина алфавита: лексер проверяет знак по диапазонам, и «латиница
    // считается кириллицей» — это ровно тот дефект, который такой проверкой и ловится.
    const латиница = await значение(`действие главная()
  пусть с = "abc"
  если с[0] == 97 и с[2] == 99
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(латиница, '"abc"[0] == 97 и "abc"[2] == 99').toBe(1);
  });

  it('ПОСЛЕДНИЙ символ: "абв"[2] == 1074 — граница с обеих сторон', async () => {
    // «Нулевой символ совпал» ничего не говорит о том, что индекс вообще участвует в вычислении:
    // реализация «всегда первый символ» прошла бы первую проверку. Здесь индекс другой, и ответ другой.
    const последний = await значение(`действие главная()
  пусть с = "абв"
  если с[2] == ${В}
    вернуть 7
  конец если
  вернуть 0
конец
`);
    expect(последний, '"абв"[2] == 1074').toBe(7);
  });

  it('ЭТО ЧИСЛО: `с[0] + 100` — 1172, а не «а100» (и не 100, как было до 2026-10-04)', async () => {
    // Различающая проба сразу двух прежних дефектов: до 2026-10-04 здесь было **100** (`null`
    // складывался с числом как ноль), после — склейка «а100». Теперь код — ЧИСЛО, и сложение обязано
    // быть арифметическим: 1072 + 100.
    const сумма = await значение(`действие главная()
  пусть с = "абв"
  вернуть с[0] + 100
конец
`);
    expect(сумма, '1072 + 100').toBe(А + 100);
  });

  it('ИНДЕКС — ВЫРАЖЕНИЕ, а не только литерал: с[поз + 1] == 1074', async () => {
    // В лексере позиция почти всегда вычисляется (`позиция + 1`), поэтому проверять доступ
    // литералом было бы проверкой не того случая.
    //
    // Имя счётчика — `поз`, а НЕ `и`: `и` в v3 — ключевое слово (логическое «и»), и первая
    // редакция этой проверки краснела на разборе («ожидается имя переменной, получено «и»»).
    const вычисленный = await значение(`действие главная()
  пусть с = "абв"
  пусть поз = 1
  если с[поз + 1] == ${В}
    вернуть 3
  конец если
  вернуть 0
конец
`);
    expect(вычисленный, 'с[поз + 1] == 1074').toBe(3);
  });

  it('ТИП ВЫВЕДЕН: код можно вернуть из процедуры с типом Число', async () => {
    // Прежде это была бы ошибка «Несовпадение типа: ожидалось Число, получено Строка» — и именно она
    // мешала лексеру. Проверка спрашивает ТИП, а не значение: возврат из `Число`-процедуры без
    // приведения типов.
    const код = await значение(`действие главная()
  пусть с = "абв"
  вернуть с[1]
конец
`);
    expect(код, 'код «б»').toBe('б'.codePointAt(0));
  });

  it('КОДОВЫЕ ТОЧКИ, А НЕ БАЙТЫ: "🙂"[0] == 128578 — иначе длина и индекс разошлись бы', async () => {
    // Единицы — то, на чём легко ошибиться молча: у «🙂» ОДИН кодпоинт и ЧЕТЫРЕ байта UTF-8.
    // Если бы индекс считался в единицах UTF-16, вернулась бы половина суррогатной пары, а если в
    // байтах — отказ на нулевом индексе. Обе ошибки ловятся здесь.
    const смайл = await значение(`действие главная()
  пусть с = "🙂"
  если с[0] == ${СМАЙЛ}
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(смайл, '"🙂"[0] == 128578').toBe(1);
  });

  it('КОНТРОЛЬ: список по-прежнему индексируется — правка не сломала соседнее', async () => {
    const список = await значение(`действие главная()
  пусть с = [10, 20, 30]
  вернуть с[0] + с[2]
конец
`);
    expect(список, 'список индексируется как раньше').toBe(40);
  });
});

describe('код символа строки: выход за границу — НАЗВАННЫЙ отказ (у VM)', () => {
  it('"абв"[3] — отказ, а не null и не пустая строка', async () => {
    // Граница названа с ОБЕИХ сторон: [2] выше даёт код, [3] здесь обязан отказать. Одного
    // наблюдения мало: «[3] отказывает» ничего не говорит о том, что [2] работает.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[3]
конец
`);
    expect(сообщение.length, 'причина отказа названа словами').toBeGreaterThan(10);
  });

  it('"абв"[-1] — тоже отказ: отрицательный индекс не заворачивается', async () => {
    // Второе наблюдение, и другой край: реализация «отказ только для слишком больших» прошла бы
    // первую проверку. Отрицательный индекс — не «с конца», а отказ: в языке такого правила нет.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[0 - 1]
конец
`);
    expect(сообщение.length).toBeGreaterThan(10);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: отказ НАЗЫВАЕТ индекс и длину, а не «не получилось»', async () => {
    // Иначе отказ неотличим от любого другого: «что-то пошло не так» — не диагноз. Проверяются
    // ЧИСЛА из программы: индекс 3 и длина 3.
    const сообщение = await отказ(`действие главная()
  пусть с = "абв"
  вернуть с[3]
конец
`);
    expect(сообщение, 'в отказе назван индекс').toContain('3');
  });

  it('КОНТРОЛЬ ОТКАЗА: пустая строка — отказ на нулевом индексе, а не пустое значение', async () => {
    // Крайняя точка: у пустой строки нет ни одного символа, поэтому `[0]` — выход за границу.
    // Без этой точки «отказ по границе» мог бы оказаться «отказом всегда».
    const сообщение = await отказ(`действие главная()
  пусть с = ""
  вернуть с[0]
конец
`);
    expect(сообщение.length).toBeGreaterThan(10);
  });
});
