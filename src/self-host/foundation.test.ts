/**
 * ГРАНИЦА ФУНДАМЕНТА: ЧТО КОМПИЛЯТОРУ НУЖНО И ЧЕГО В ЯЗЫКЕ v3 НЕТ.
 *
 * # Зачем этот файл рядом с `foundationE2k.test.ts`
 *
 * `foundationE2k.test.ts` отвечает на вопрос «стоит ли фундамент на ЦЕЛИ» — и отвечает прогонами:
 * `open`/`read`/`close` работают, буфер обязан лежать в сегменте данных, отказ приходит `-errno`.
 * Этот файл отвечает на ДРУГОЙ вопрос, и он не менее важен: **выражается ли та же способность
 * средствами языка v3**. Разница принципиальная: способность может стоять на цели и быть
 * недостижимой из языка — тогда self-host на v3 не пишется, и это надо знать ДО того, как начат
 * лексер.
 *
 * # Как здесь устроены проверки
 *
 * Три состояния, и все три названы:
 *
 * | состояние | как записано |
 * |---|---|
 * | работает | проверка значения (две независимые стороны: семантика и VM) |
 * | названный отказ | проверка ТОЧНОГО текста отказа |
 * | нет вовсе | проверка отсутствия имени в реестре (`SYSCALLS_V01`) |
 *
 * # Чего здесь нет
 *
 * Здесь нет предложений «как надо». Изобретать синтаксис языка — не дело плоскости self-host;
 * каждый пробел назван долгом перед языком (`docs/hardware-debt.md`), а не закрыт выдумкой.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from '../e2k/programImage';
import { compileSource, validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';
import { LANGUAGE_REGISTRY } from '../compiler/language-registry';

const ФАЙЛ = 'фундамент.osnova';

/**
 * Опции фронтенда v3 для общего конвейера.
 *
 * Нужны КАЖДЫЙ раз, когда программа в написании v3 идёт в `loweredProgram`: по умолчанию конвейер
 * разбирает исходник каноном v2, и написание v3 в нём — синтаксическая ошибка. Замер: без опций
 * программа `действие главная() … конец` даёт «программа не компилируется», и это НЕ свойство
 * программы.
 */
const опцииV3 = (источник: string) => {
  const р = parseV3(источник, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Разбор + семантика v3: то, что язык принимает и отвергает. */
function собрать(источник: string): { ошибкиРазбора: string[]; ошибкиСемантики: string[] } {
  const р = parseV3(источник, ФАЙЛ);
  if (р.errors.length > 0) return { ошибкиРазбора: р.errors, ошибкиСемантики: [] };
  return { ошибкиРазбора: [], ошибкиСемантики: validateNamedTypesAndRewrite(р.program!.modules[0]!) };
}

/** Две независимые стороны языка: стековая VM (эталон) и регистровая (нативная цель). */
async function значениеНаVM(источник: string): Promise<{ стек: unknown; регистры: unknown }> {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = await стековая.runProcedure(стековая.findProcedureIndex('главная'), []);
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []);
  return { стек, регистры };
}

/** Имена системных вызовов, которые язык знает (реестр — единственный источник). */
const ИМЕНА_РЕЕСТРА = new Set(LANGUAGE_REGISTRY.syscalls.map((вызов) => вызов.name));

describe('1. ФАЙЛЫ: способность стоит на цели, но в языке её НЕТ', () => {
  it('в реестре языка НЕТ ни `open`, ни `read`, ни `close` — и это проверяется как отсутствие', () => {
    // Проверка «нет» нужна так же, как проверка «есть»: без неё пробел заметили бы только тогда,
    // когда кто-то попробует написать лексер, — то есть на самом дорогом шаге.
    expect(ИМЕНА_РЕЕСТРА.has('система.файл.открыть'), 'имени `открыть` в языке нет').toBe(false);
    expect(ИМЕНА_РЕЕСТРА.has('система.файл.читать'), 'имени `читать` в языке нет').toBe(false);
    expect(ИМЕНА_РЕЕСТРА.has('система.файл.закрыть'), 'имени `закрыть` в языке нет').toBe(false);
    // А высокоуровневые имена файлов в реестре ЕСТЬ — и это другое: они описаны как
    // `experimental` и живут в хостовой VM. Отсутствие НИЗКОУРОВНЕВЫХ видно на их фоне.
    expect(ИМЕНА_РЕЕСТРА.has('система.файлы.прочитать_все')).toBe(true);
    expect(ИМЕНА_РЕЕСТРА.has('система.файлы.записать_все')).toBe(true);
  });

  it('высокоуровневое имя до ЦЕЛИ не доходит: понижение отказывает с причиной', async () => {
    // Это не «ещё не сделано»: имя есть в реестре и работает в хостовой VM, но понижение e2k его
    // не знает — отказ назван именем и списком того, что рантайм умеет.
    //
    // Форма ЗДЕСЬ v2 (`модуль Ф` + `конец`): `система.файлы.прочитать_все` — полное имя из трёх
    // частей, и в написании v3 его не выразить вовсе (см. ниже про цепочку имён). Спрашивается
    // ровно одно: доходит ли это имя до ЦЕЛИ хоть в каком-нибудь написании. Ответ — нет.
    const источник = `модуль Ф
процедура главная()
  пусть т = система.файлы.прочитать_все("вход.osnova")
  вернуть 0
конец
конец
`;
    const образ = loweredProgram(источник, {});
    expect(образ.refused.length, 'отказ обязан быть, и он назван').toBeGreaterThan(0);
    expect(образ.refused[0]!.reason).toContain('система.файлы.прочитать_все');
  });
});

describe('2. СТРОКИ: длина и склейка стоят, посимвольного доступа НЕТ', () => {
  it('длина строки и склейка: значение на ДВУХ VM — 6, и обе стороны согласны', async () => {
    const { стек, регистры } = await значениеНаVM(`действие главная()
  пусть с = "абв" + "где"
  вернуть длина с
конец
`);
    expect(стек).toBe(6);
    expect(регистры).toBe(6);
  });

  it('ПОСИМВОЛЬНЫЙ ДОСТУП: `с[0]` на строке — СИМВОЛ «а» (долг §3.105.4 ЗАКРЫТ 2026-10-04)', async () => {
    // ПРЕЖНЯЯ РЕДАКЦИЯ ЭТОЙ ПРОВЕРКИ УТВЕРЖДАЛА `null` — и была права: так вело себя дерево. Но
    // `null` здесь не свойство языка, а ДЕФЕКТ: `arr[i]` — форма ОБРАЩЕНИЯ, одна для списка и для
    // строки, а `null` складывался с числом как ноль, то есть буквы «читались» бы как нули молча.
    // Долг закрыт разворотом по типу операнда (`resolveStringIndex`, `система.строка.символ`);
    // утверждение о `null` СНЯТО, а не подогнано под новый ответ (§2.5), и заменено на то, что
    // обязано быть верным: символ приходит, и он именно тот.
    //
    // Второе наблюдение — СПИСОК: он индексировался и раньше, и обязан индексироваться теперь.
    // Без него проверка не отличала бы «строка починена» от «индексация сломана вовсе».
    const строка = await значениеНаVM(`действие главная()
  пусть с = "абв"
  если с[0] == "а"
    вернуть 1
  конец если
  вернуть 0
конец
`);
    expect(строка.стек, 'строка индексируется: с[0] == "а"').toBe(1);
    expect(строка.регистры, 'и на регистровой стороне — то же').toBe(1);

    const список = await значениеНаVM(`действие главная()
  пусть с = [10, 20, 30]
  вернуть с[0]
конец
`);
    expect(список.стек, 'СПИСОК индексируется — форма записи та же').toBe(10);
    expect(список.регистры).toBe(10);
  });

  it('`+` на символе строки — СКЛЕЙКА: «а100», а не число 100 (прежде давало 100)', async () => {
    // Различающая проба тихой лжи в её прежнем виде: `с[0] + 100` давало **100**, потому что
    // `null` вёл себя как ноль. Лексер на такой строке «прочитал» бы буквы как нули и выдал поток
    // пустых токенов МОЛЧА. Теперь символ — строка, и `+` со строкой склеивает (канон §2.1:
    // «+ тоже склеивает, если есть строка»), поэтому ответ — «а100», а не 100.
    //
    // Возвращается ДЛИНА, а не сама строка: процедура объявлена `→ Число`, и вернуть из неё строку
    // семантика обязана отказать — «ожидалось Число, получено Строка». Это верный отказ, и он
    // проверяется отдельной проверкой `stringIndex.test.ts`.
    const { стек, регистры } = await значениеНаVM(`действие главная()
  пусть с = "абв"
  вернуть длина (с[0] + 100)
конец
`);
    expect(стек, '«а100» — четыре знака: склейка, а не сложение с нулём').toBe(4);
    expect(регистры).toBe(4);
  });

  it('сравнение строк `==` работает — это ОТДЕЛЬНАЯ способность, и её достаточно для токенов-слов', async () => {
    // Важное различие для лексера: собрать слово посимвольно нельзя, но СРАВНИТЬ строку целиком
    // можно. Значит форма «лексер без посимвольного чтения» обсуждаема, а не запрещена целиком.
    const { стек, регистры } = await значениеНаVM(`действие главная()
  пусть а = "абв"
  если а == "абв"
    вывести 1
  конец если
  вернуть 7
конец
`);
    expect(стек).toBe(7);
    expect(регистры).toBe(7);
  });

  it('`для каждого` по строке — НАЗВАННЫЙ отказ понижения (в языке цикл есть, в цели — нет)', async () => {
    const источник = `действие главная()
  пусть н = 0
  для каждого б в "абв"
    н = н + 1
  конец для
  вернуть н
конец
`;
    const образ = loweredProgram(источник, опцииV3(источник));
    expect(образ.refused.length, 'отказ обязан быть').toBeGreaterThan(0);
    expect(образ.refused[0]!.reason).toContain('система.итератор.из');
  });
});

describe('3. КОЛЛЕКЦИИ: на цели стоят, из v3 недостижимы — ЦЕПОЧКА ИМЁН', () => {
  it('вызов `система.коллекция.выделить(4)` в v3 отвергается РАЗБОРОМ, и причина названа', () => {
    // Это ключевое различие для self-host: коллекции — то, чем компилятор держит AST и таблицу
    // символов. На цели они работают (`src/e2k/collectionsBrkQemu.test.ts`), но v3 запрещает
    // цепочку имён перед вызовом: `система.коллекция` — это ДВА имени, а вызов пишется
    // «имя(…)» или «Модуль.имя(…)».
    const { ошибкиРазбора } = собрать(`действие главная()
  пусть к = система.коллекция.выделить(4)
  вернуть к
конец
`);
    expect(ошибкиРазбора.join(' ')).toContain('цепочка имён перед вызовом запрещена');
  });

  it('`подключить "система.коллекция" как система` + `система.выделить(4)` — тоже не проходит', () => {
    // Вторая форма, которая кажется обходом: подключить модуль с псевдонимом. Разбор её ПРИНИМАЕТ
    // (значит дело не в `подключить`), семантика тоже молчит — отказ приходит позже, на сборке:
    // короткого имени `выделить` в модуле нет, а импорт система-модулей не разрешается.
    // Здесь важно именно «разобралось ≠ работает»: иначе следующая сессия сочла бы обход найденным.
    const источник = `подключить "система.коллекция" как система
действие главная()
  пусть к = система.выделить(4)
  вернуть к
конец
`;
    const р = parseV3(источник, ФАЙЛ);
    expect(р.errors, 'разбор эту форму принимает').toEqual([]);
    expect(
      validateNamedTypesAndRewrite(р.program!.modules[0]!),
      'семантика тоже молчит — отказ придёт НИЖЕ',
    ).toEqual([]);
    const собран = compileSource(источник, опцииV3(источник));
    expect(собран.compilerSuccess, 'а собрать программу нечем: вызов не разрешается').toBe(false);
    // И НАЗВАННЫЙ ОТКАЗ ниже: понижение тоже не возьмётся за неё.
    expect(() => loweredProgram(источник, опцииV3(источник))).toThrow(/не компилируется/);

    // КОНТРОЛЬ: без `подключить` отказ приходит РАНЬШЕ и называет имя — значит разница именно
    // в импорте, а не в природе вызова.
    const безИмпорта = `действие главная()
  пусть к = система.выделить(4)
  вернуть к
конец
`;
    expect(
      compileSource(безИмпорта, опцииV3(безИмпорта)).semanticErrors.map((ошибка) => ошибка.message).join(' '),
    ).toContain("системный вызов 'система.выделить' не существует");
  });

  it('НА ЦЕЛИ коллекции работают — то есть пробел именно в языке, а не в бэкенде', async () => {
    // Доказательство «дело в языке»: та же способность описана в v2-форме и понижается без отказов.
    const v2 = `модуль Кол
процедура главная()
  пусть первая = система.коллекция.выделить(4)
  пусть вторая = система.коллекция.выделить(4)
  вернуть вторая - первая
конец
конец
`;
    const образ = loweredProgram(v2, {});
    expect(образ.refused, 'отказов понижения нет: коллекции на цели стоят').toEqual([]);
    expect(образ.bytes.length).toBeGreaterThan(100);
  });
});

describe('4. ПЕЧАТЬ И ВЫВОД: чем компилятор скажет о своей работе', () => {
  it('`вывести` понижается без отказов — канал отчёта есть', async () => {
    const источник = `действие главная()
  вывести 7
  вернуть 0
конец
`;
    const образ = loweredProgram(источник, опцииV3(источник));
    expect(образ.refused).toEqual([]);
  });

  it('`ввод` есть в языке как слово, но цели не достигает: тип не выводится', () => {
    // Ввод — второй возможный канал для чтения файла (через stdin). Проверяем честно: слово
    // разбирается, но без аннотации типа семантика отказывает, а с аннотацией — до цели не
    // доходит (проверяется в `foundationE2k.test.ts` опытом с файлами).
    const без = собрать(`действие главная()
  пусть с = ввод("> ")
  вернуть длина с
конец
`);
    expect(без.ошибкиСемантики.join(' ')).toContain('требует известного типа операнда');
  });
});
