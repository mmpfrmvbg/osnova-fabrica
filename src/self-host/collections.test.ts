/**
 * КОЛЛЕКЦИИ ИЗ v3 — ОРАКУЛ. НАПИСАН ДО РЕАЛИЗАЦИИ И ДО НЕЁ КРАСНЫЙ.
 *
 * # Долг, который здесь закрывается (§3.105.5)
 *
 * Коллекции на цели РАБОТАЮТ: `система.коллекция.выделить/положить/взять/расширить` понижаются без
 * отказов, сквозной прогон 100 записей даёт 5050 (`src/e2k/collectionsBrkQemu.test.ts`). Но из v3
 * они НЕДОСТИЖИМЫ: `система.коллекция.выделить(4)` — цепочка из двух точек, а канон v3 разрешает
 * ровно одну (`Модуль.имя(…)`). Это пробел ЯЗЫКА, а не бэкенда: та же программа в написании v2
 * понижается без отказов.
 *
 * Владелец решил форму: ВСТРОЕННЫЕ СЛОВА. `выделить`, `положить`, `взять`, `расширить`,
 * `расширить_удвоением`.
 *
 * # Расширение удвоением — СТРАТЕГИЯ, а не рантайм
 *
 * `расширить_удвоением(база)` не добавляется в e2k-рантайм: она разворачивается во фронтенде v3 в
 * «взять текущую ёмкость, удвоить, вызвать `расширить`». Смысл в том, что дешёвая по памяти
 * стратегия роста (замер: удвоение — 1.00× потерь, «+1» — 5000×, §3.102.4) должна быть ЛЁГКОЙ:
 * иначе программист напишет `расширить(база, текущая + 1)` и потеряет память незаметно.
 *
 * Отсюда — проверка ЧИСЛА ПЕРЕЕЗДОВ: 4 → 8 → 16 это ровно два переезда, а не шесть.
 *
 * # Три состояния
 *
 * | состояние | как проверяется |
 * |---|---|
 * | работает | сумма всех элементов совпала с эталоном |
 * | названный отказ | индекс за границей, ёмкость меньше текущей |
 * | нет вовсе | отсутствие имени в реестре до правки — проверка ОТСУТСТВИЯ |
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { createDefaultInvokeHandler, VM, CollectionRefusal } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';
import { LANGUAGE_REGISTRY } from '../compiler/language-registry';
import { INVOKE_ARG_COUNT } from '../runtime/vm/invokeRegistry';
import { COLLECTION_ARITY, COLLECTION_INVOKES } from '../runtime/vm/collectionCalls';

const ФАЙЛ = 'коллекции.osnova';

function модуль(источник: string) {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м), 'проход разрешения').toEqual([]);
  return м;
}

/** Обе VM: стековая — эталон языка, регистровая — нативная цель. */
async function обеVM(источник: string): Promise<unknown> {
  const м = модуль(источник);
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = await стековая.runProcedure(стековая.findProcedureIndex('главная'), []);
  const регистровая = new RegVM(compileToReg(м), {
    invoke: createDefaultInvokeHandler(),
    maxSteps: 2_000_000,
  });
  const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []);
  expect(регистры, 'регистровая VM обязана дать то же, что стековая').toBe(стек);
  return стек;
}

async function отказ(источник: string): Promise<string> {
  let сообщение = '';
  try {
    await обеVM(источник);
  } catch (ошибка) {
    сообщение = (ошибка as Error).message;
  }
  expect(сообщение, 'операция обязана ОТКАЗАТЬ, а не вернуть значение').not.toBe('');
  return сообщение;
}

describe('коллекции из v3: встроенные слова вместо цепочки имён', () => {
  it('СЛОВА РАЗБИРАЮТСЯ И ДОХОДЯТ ДО РЕЕСТРА: арность в трёх местах — одно число', () => {
    // Согласованность трёх списков — та же проверка, что у файлов, и по той же причине: VM читает
    // INVOKE_ARG_COUNT, оракулы и понижение — COLLECTION_ARITY, семантика — реестр языка.
    const словa: Array<[string, string]> = [
      ['выделить', 'система.коллекция.выделить'],
      ['положить', 'система.коллекция.положить'],
      ['взять', 'система.коллекция.взять'],
      ['расширить', 'система.коллекция.расширить'],
    ];
    for (const [слово, канон] of словa) {
      const вРеестре = LANGUAGE_REGISTRY.syscalls.find((с) => с.name === канон);
      expect(вРеестре, `${канон} объявлено в реестре языка (слово «${слово}»)`).toBeDefined();
      expect(INVOKE_ARG_COUNT[канон], `${канон} в реестре VM`).toBeDefined();
      expect(COLLECTION_ARITY[канон], `${канон} в модуле коллекций`).toBeDefined();
      expect(
        [вРеестре!.argc, INVOKE_ARG_COUNT[канон], COLLECTION_ARITY[канон]],
        `${канон}: арность в трёх местах`,
      ).toEqual([вРеестре!.argc, вРеестре!.argc, вРеестре!.argc]);
    }
  });

  it('СКВОЗНОЙ: выделить(4) → положить все 4 → взять все 4 — сумма совпала', async () => {
    // Столько же, сколько спрашивает оракул корпуса на 100 записях, но здесь — через СЛОВА v3.
    const сумма = await обеVM(`действие главная()
  пусть к = выделить(4)
  положить(к, 0, 10)
  положить(к, 1, 20)
  положить(к, 2, 30)
  положить(к, 3, 40)
  пусть итог = 0
  для н от 0 до 3
    итог = итог + взять(к, н)
  конец для
  вернуть итог
конец главная
`);
    expect(сумма, '10+20+30+40').toBe(100);
  });

  it('ПРЕЖНЯЯ ФОРМА ОТВЕРГАЕТСЯ: `система.коллекция.выделить(4)` — по-прежнему отказ разбора', () => {
    // Это НЕ регресс, а канон: v3 запрещает цепочку имён, и закрытие долга через встроенные слова
    // его не отменяет. Проверка нужна, чтобы «одна точка» осталась правилом, а не пожеланием.
    const р = parseV3(`действие главная()
  пусть к = система.коллекция.выделить(4)
  вернуть к
конец главная
`, ФАЙЛ);
    expect(р.errors.join(' ')).toContain('цепочка имён перед вызовом запрещена');
  });
});

describe('расширить_удвоением: РАЗВИЛКА НАЗВАНА, а не обойдена молча', () => {
  it('ОТКАЗ С ПРИЧИНОЙ: слово разбирается, но выразить его НЕЧЕМ — и это сказано', () => {
    // Владелец решил: `расширить_удвоением` — СТРАТЕГИЯ РОСТА, разворачиваемая фронтендом
    // («новая ёмкость = текущая × 2, минимум 4, вызвать расширить»). Чтобы это выразить, ёмкость
    // надо ПРОЧИТАТЬ, а чтения ёмкости в языке нет: она лежит в ЗАГОЛОВКЕ БЛОКА В ПАМЯТИ
    // (`src/e2k/collectionsRuntime.ts:14-17`), и операция чтения нужна новая И на цели.
    //
    // Сессия разрешила правки в e2k ТОЛЬКО для символа строки, а `collectionsRuntime.ts` запрещён
    // прямо («коллекции e2k уже работают, только имена в реестр»). Значит честный исход — НАЗВАННЫЙ
    // ОТКАЗ с причиной, а не тихая подстановка.
    //
    // Почему НЕ подставить «новая ёмкость = 8»: программа, выделившая 100 элементов, получила бы
    // блок МЕНЬШЕ прежнего, и первый же `положить` за границей ушёл бы в чужую память. Это тот самый
    // класс «тихой лжи», ради которого в проекте и заведены названные отказы (§2.3).
    const р = parseV3(`действие главная()
  пусть к = выделить(4)
  к = расширить_удвоением(к)
  вернуть к
конец главная
`, ФАЙЛ);
    expect(р.errors.length, 'разбор обязан ОТКАЗАТЬ, а не разобрать молча').toBeGreaterThan(0);
    const текст = р.errors.join(' ');
    expect(текст, 'отказ называет причину').toContain('удвоить');
    expect(текст, 'и говорит, что писать сегодня').toContain('расширить(база, новая_ёмкость)');
  });

  it('ЧЕГО НЕ ХВАТАЕТ — названо ИМЕНЕМ: чтения ёмкости в реестре нет', () => {
    // Проверка ОТСУТСТВИЯ, и она — суть развилки: не «руки не дошли», а «нужной операции нет».
    // Появится имя — эта проверка покраснеет, и тогда `расширить_удвоением` станет выразимой:
    // решение придёт КРАСНЫМ, а не догадкой.
    const имена = LANGUAGE_REGISTRY.syscalls.map((с) => с.name);
    expect(имена, 'ёмкость в языке не читается').not.toContain('система.коллекция.ёмкость');
    expect(имена).not.toContain('система.коллекция.размер');
    expect(имена).not.toContain('система.коллекция.длина');
    // И в рантайме цели её тоже нет: четыре операции, и все — с явной ёмкостью на входе.
    expect(
      COLLECTION_INVOKES.map((в) => в.name),
      'в рантайме цели четыре операции, и удвоения среди них нет',
    ).toEqual([
      'система.коллекция.выделить',
      'система.коллекция.положить',
      'система.коллекция.взять',
      'система.коллекция.расширить',
    ]);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: без роста запись по индексу 7 — ОТКАЗ (проверка прибора)', async () => {
    // Контроль к опыту ниже: он показывает, что блок ёмкости 4 индекса 7 НЕ вмещает. Без него
    // «после роста индекс 7 прошёл» ничего не доказывало бы — возможно, он проходит всегда.
    const сообщение = await отказ(`действие главная()
  пусть к = выделить(4)
  положить(к, 7, 77)
  вернуть взять(к, 7)
конец главная
`);
    expect(сообщение, 'отказ называет индекс').toContain('7');
  });

  it('СЕГОДНЯШНИЙ ПУТЬ РАБОТАЕТ: `расширить(к, 8)` — и индекс 7 вмещается', async () => {
    // Обход назван, а не оставлен читателю: пока удвоения нет, рост пишется ЯВНЫМ числом. Проверка
    // нужна затем, чтобы отказ удвоения не читался как «рост коллекций недоступен вовсе».
    const прошло = await обеVM(`действие главная()
  пусть к = выделить(4)
  к = расширить(к, 8)
  положить(к, 7, 77)
  вернуть взять(к, 7)
конец главная
`);
    expect(прошло, 'после явного расширения до 8 индекс 7 вмещается').toBe(77);
  });
});
describe('коллекции: отказы НАЗВАНЫ, а не проглочены', () => {
  it('ВЗЯТЬ ЗА ГРАНИЦЕЙ — отказ с индексом и ёмкостью в тексте', async () => {
    const сообщение = await отказ(`действие главная()
  пусть к = выделить(2)
  пусть х = взять(к, 5)
  вернуть х
конец главная
`);
    expect(сообщение, 'назван индекс').toContain('5');
    expect(сообщение, 'названа ёмкость').toContain('2');
  });

  it('РАСШИРИТЬ С МЕНЬШЕЙ ЁМКОСТЬЮ — отказ, а не тихое сужение', async () => {
    const сообщение = await отказ(`действие главная()
  пусть к = выделить(8)
  к = расширить(к, 4)
  вернуть 0
конец главная
`);
    expect(сообщение.length, 'причина названа словами').toBeGreaterThan(10);
  });

  it('ПОЛОЖИТЬ ЗА ГРАНИЦЕЙ — отказ, и он ДРУГОЙ, чем у взять', async () => {
    // Второе наблюдение по границам: запись и чтение — разные операции, и «отказ есть» у одной не
    // доказывает отказа у другой. Проверяется, что отказ приходит от НАШЕГО класса, а не от
    // неожиданного места.
    let пойман: unknown;
    try {
      await обеVM(`действие главная()
  пусть к = выделить(2)
  положить(к, 9, 1)
  вернуть 0
конец главная
`);
    } catch (ошибка) {
      пойман = ошибка;
    }
    expect(пойман, 'запись за границей — названный отказ коллекций').toBeInstanceOf(CollectionRefusal);
  });
});
