/**
 * ФАЙЛОВЫЕ ОПЕРАЦИИ В ЯЗЫКЕ — ОРАКУЛ. НАПИСАН ДО РЕАЛИЗАЦИИ И ДО НЕЁ КРАСНЫЙ.
 *
 * # Что здесь спрашивается
 *
 * Долг §3.105.3: способность ЧИТАТЬ И ПИСАТЬ ФАЙЛ стоит на цели (номера `open` 5, `read` 3,
 * `write` 4, `close` 6 — измерены прогоном, `src/self-host/foundationE2k.test.ts`), но из языка
 * недостижима: имён нет ни в реестре, ни в разборе. Владелец решил форму: ВСТРОЕННЫЕ СЛОВА
 * `открыть`, `читать`, `писать`, `закрыть`, потому что `система.файл.открыть` в v3 — цепочка из
 * двух точек, а её канон запрещает.
 *
 * # Три состояния, а не два
 *
 * | состояние | как проверяется |
 * |---|---|
 * | работает | значение: содержимое файла совпало с тем, что положили |
 * | названный отказ | ТОЧНЫЙ текст отказа: файла нет, режим не слово |
 * | нет вовсе | отсутствие имени в реестре — как проверка ОТСУТСТВИЯ |
 *
 * # Чем это исполняется
 *
 * Портами (`src/runtime/vm/fileCalls.ts#FilePorts`): «что значит операция» и «чем она исполняется»
 * разведены, поэтому здесь проверяется ЯЗЫК (разбор, семантика, обе VM), а не файловая система
 * хоста. Прогон на цели — отдельным оракулом и отдельным разбором: у цели строки статические, и
 * `читать`, возвращающий Строку РАНТАЙМОВОЙ длины, — это отдельная работа, а не «то же самое».
 */
