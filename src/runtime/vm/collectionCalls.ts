/**
 * КОЛЛЕКЦИИ НА `brk` В VM: АРНОСТЬ ОБЪЯВЛЕНА ЗДЕСЬ, А НЕ В РЕЕСТРЕ ЯЗЫКА — И ВОТ ПОЧЕМУ.
 *
 * # Замер, из которого вырос этот модуль
 *
 * Первая редакция добавила четыре операции в `INVOKE_ARG_COUNT` (`src/runtime/vm/invokeRegistry.ts`) —
 * то есть туда, где арность системных вызовов живёт по общему правилу. `npm test` **покраснел**, и
 * покраснел по делу: оракул согласованности (`src/compiler/registryAgreement.test.ts` →
 * `checkRegistryAgreement`) требует, чтобы КАЖДОЕ имя из `INVOKE_ARG_COUNT` было объявлено в реестре
 * языка (`src/compiler/language-registry.ts`, `SYSCALLS_V01`). То есть объявление операции в VM —
 * это **звено «язык + VM + схема»**, атомарная правка языка; ровно так в дереве и появился
 * `система.память.выделить` — коммит `6884b7d` («звено „язык + VM + схема“»), ОДНИМ изменением в
 * обоих реестрах.
 *
 * Реестр языка — ЧУЖАЯ плоскость этого захода (`src/compiler/**`), и трогать его нельзя. Значит
 * объявить операции в каноне я не вправе, а эталон языка посчитать надо.
 *
 * # Что для этого есть в самом языке
 *
 * Механизм `extraInvokes` объявлен в ОБЕИХ VM и назван ровно для этого случая: «Хост-вызовы **вне
 * реестра** `система.*` … **не пишутся в language-registry**» (`src/runtime/vm/interpreter.ts`,
 * `src/runtime/vm/reginterpreter.ts`). Это не обход сторожа, а его вторая половина: сторож держит
 * КАНОН в согласии с VM, а `extraInvokes` — законное место для того, что каноном ещё не объявлено.
 * Разница видна в одном: `getInvokeArgCount('система.коллекция.выделить')` по-прежнему 0, то есть
 * язык этих операций НЕ знает; знает их только тот прогон, который список передал явно.
 *
 * # Что это значит для честности отчёта
 *
 * Коллекции сегодня — **не язык, а рантайм**: программа компилируется (фронтенд разрешает
 * `система.*` по имени), цель их исполняет, эталон считает — но канон их не объявляет. Первый шаг к
 * объявлению — четыре строки в `SYSCALLS_V01` плюс запись в схему; это работа чужой плоскости, и она
 * названа, а не сделана молча.
 */
import type { StackValue } from './interpreter';

/**
 * НАЗВАННЫЙ ОТКАЗ КОЛЛЕКЦИЙ — третий статус, а не `null`.
 *
 * Разница существенна: `null` в языке — законное значение, и «взять вне границ» вернуло бы его
 * наравне с записанным `null`. Выход за ёмкость обязан быть отличим от значения, и он отличим:
 * это исключение с текстом, где названы и индекс, и ёмкость.
 */
export class CollectionRefusal extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'CollectionRefusal';
  }
}

/** Арность операции: имя и число аргументов — то, что читают обе VM вместо реестра. */
export interface ExtraInvoke {
  readonly name: string;
  readonly argc: number;
}

/**
 * Подпись владельца (§3.95.3) — четыре операции, и арность берётся ИЗ НЕЁ, а не из головы:
 * `выделить(ёмкость)`, `положить(база, индекс, значение)`, `взять(база, индекс)`,
 * `расширить(база, новая_ёмкость)`.
 */
export const COLLECTION_INVOKES: readonly ExtraInvoke[] = [
  { name: 'система.коллекция.выделить', argc: 1 },
  // ТРИ аргумента, и это не описка: на ЦЕЛИ такой вызов пока отказан по имени — носитель `IR.invoke`
  // несёт не больше двух (`src/e2k/emitterShell.ts#MAX_CALL_ARGS`). Эталон обязан считать все четыре
  // операции: без него сквозной прогон нечем проверить.
  { name: 'система.коллекция.положить', argc: 3 },
  { name: 'система.коллекция.взять', argc: 2 },
  { name: 'система.коллекция.расширить', argc: 2 },
];

/** Арность по имени — для тех, кто проверяет вызов до прогона. `undefined` — имени нет. */
export const COLLECTION_ARITY: Readonly<Record<string, number>> = Object.fromEntries(
  COLLECTION_INVOKES.map((invoke) => [invoke.name, invoke.argc]),
);

/**
 * Значение аргумента как целое — одна проверка на все четыре операции.
 *
 * Отказ НАЗЫВАЕТСЯ, а не округляется молча: `NaN` от нечислового аргумента, приведённый к нулю,
 * выглядел бы как законный индекс 0 — то есть как тихая ложь.
 */
export function collectionInteger(value: StackValue, operation: string, role: string): number {
  const number = Number(value);
  if (!Number.isFinite(number)) {
    throw new CollectionRefusal(`коллекция.${operation}: ${role} = ${String(value)} — не число`);
  }
  return Math.trunc(number);
}
