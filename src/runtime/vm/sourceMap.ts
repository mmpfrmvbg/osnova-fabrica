/**
 * КАРТА ИСТОЧНИКА: IR → AST → ТОКЕН, и ОТКАЗ, НАЗЫВАЮЩИЙ ИСХОДНИК, А НЕ ВНУТРЕННЕЕ ИМЯ.
 *
 * # Зачем
 *
 * Отказ понижения сейчас называет ВНУТРЕННЕЕ имя: `система.массив.получить`,
 * «операнд 6 носителя», «отрицательное смещение». Человек, написавший `лента[индекс]`, не
 * написал ни одного из этих слов — значит отказ отправляет его искать не туда. Это измерено не
 * рассуждением: у `OSN-LOW-004` текст «раскладка не выдала базу блока рантайма (операнд 6
 * носителя)» соответствует строке `а[0] = 7`, а «операнд 6» в исходнике не встречается вовсе.
 *
 * Карта источника восстанавливает цепочку **IR → AST → токен**, чтобы отказ мог сказать
 * `лента[индекс], строка 5, колонка 3`.
 *
 * # Почему это отдельный модуль, а не поле в AST
 *
 * 1. **AST v2 полей не имеет вовсе** — ни позиций, ни номеров узлов (`src/compiler/ast.ts`).
 *    Добавить их туда значило бы обязать ОБА разборщика (v2 и v3) их заполнять, иначе краснеет
 *    `src/compiler-v3/astEquivalence.test.ts` (он сверяет деревья `toEqual` и наборы ключей).
 * 2. **Тождество узла НЕ доживает до кодогена.** `validateNamedTypesAndRewrite` →
 *    `rewriteVariantLiteralsInExpr` ПЕРЕСОБИРАЕТ каждый `поле`/`бинарное`/`унарное`/`вызов`/
 *    `массив`/`объект` свежим литералом объекта (`src/compiler/compiler.ts:604-644`). Побочная
 *    таблица по тождеству такого узла была бы мертва с рождения.
 * 3. Зато **листья тождество СОХРАНЯЮТ**: ветка `default` возвращает `expr` как есть, поэтому
 *    `переменная`, `число`, `строка`, `булево`, `пусто` — те же самые объекты, что создал разбор.
 *    На этом карта и стоит: ключ — БАЗА выражения (`лента` в `лента[индекс]`), а не сам `вызов`,
 *    который пересоберут.
 *
 * # Границы (названы, а не спрятаны)
 *
 * - **Ключ — тождество объекта.** Где база не лист (`ф(х)[0]`, `(а + б)[0]`) или где узел
 *   пересобрали, источника НЕТ. Это не потеря: `sourceRef` необязателен, и отказ честно
 *   возвращается к прежнему тексту.
 * - **Текст узла — склейка ЛЕКСЕМ**, а не срез исходника: разборщик получает поток токенов, а не
 *   строку. Пробелы внутри узла поэтому нормализованы (`лента[индекс]` совпадает с исходником,
 *   `ф(а, б)` — нет). Для отказа этого достаточно, и это записано, а не выдано за точный срез.
 * - **Реестр `astNodeId → запись` живёт на процесс.** Номера выдаются счётчиком и не
 *   переиспользуются, поэтому запись нельзя перепутать с чужой; но и освободить её нечем —
 *   карта аддитивна, как `RegModule.atoms`.
 * - **Плоскость.** Модуль лежит в `src/runtime/vm/`, потому что его читают ТРИ стороны:
 *   `src/compiler-v3/parser.ts` (пишет), `src/compiler/regcodegen.ts` (переносит в IR) и
 *   `src/e2k/**` (читает в отказе). Обратный импорт `compiler → compiler-v3` был бы петлёй
 *   (`src/compiler/compiler.ts:108`), а `runtime/vm` не импортирует ни ту, ни другую.
 */

/**
 * Ссылка на источник у инструкции IR: номер узла AST и номер токена.
 *
 * Оба поля — ЧИСЛА, а не строки: отказ не должен зависеть от того, как узел напечатан.
 * Расшифровка живёт в реестре этого модуля ({@link источникПоНомеру}).
 */
export interface IRSourceRef {
  /** Номер узла AST. Выдаётся здесь, уникален на процесс, `0` не встречается. */
  readonly astNodeId: number;
  /** Номер токена в потоке `tokenizeV3` (0-based) — НАЧАЛО выражения. */
  readonly tokenIndex: number;
}

/** Что за узел назван источником. Вид, а не текст: по нему строятся формулировки отказа. */
export type ВидИсточника = "индексация" | "вызов" | "литерал" | "переменная";

/** Запись карты: всё, что нужно отказу, чтобы назвать исходник человеку. */
export interface ИсточникУзла {
  /** Номер узла; тот же, что в {@link IRSourceRef.astNodeId}. */
  readonly astNodeId: number;
  /** Первый токен выражения (0-based). */
  readonly tokenIndex: number;
  /** Токен ЗА последним токеном выражения (исключающая граница). */
  readonly конец: number;
  readonly вид: ВидИсточника;
  /** Лексемы узла, склеенные без пробелов: `лента[индекс]`. */
  readonly текст: string;
  /** Строка первого токена, 1-based. */
  readonly строка: number;
  /** Колонка первого токена, 1-based. */
  readonly колонка: number;
}

/** Минимум токена, который нужен карте: номер, текст и место. Ничего из лексера целиком. */
export interface ТокенДляКарты {
  readonly lexeme: string;
  readonly line: number;
  readonly column: number;
}

/** Узел AST: ключ карты — сам объект (тождество), поэтому больше ничего не нужно. */
type Узел = object;

/**
 * Начало узла: номер его первого токена. Заполняется разбором там, где начало ИЗВЕСТНО.
 *
 * Отдельная карта, а не поле записи: запись появляется только у индексации, а начало нужно
 * ещё и для того, чтобы её описать.
 */
const начало = new WeakMap<Узел, number>();

/** Ключ — БАЗА выражения. Значение — запись, которую увидит кодоген и отказ. */
const поУзлу = new WeakMap<Узел, ИсточникУзла>();

/** Реестр для тех, у кого на руках только числа (отказ в `src/e2k/**`): номер → запись. */
const поНомеру = new Map<number, ИсточникУзла>();

/** Счётчик номеров узлов. `0` не выдаётся: он читался бы как «источника нет». */
let следующийНомер = 1;

/** Запомнить, с какого токена начинается узел. Повторная запись — та же величина. */
export function запомнитьНачало(узел: Узел, tokenIndex: number): void {
  начало.set(узел, tokenIndex);
}

/** Начало узла, если разбор его назвал. */
export function началоУзла(узел: Узел): number | undefined {
  return начало.get(узел);
}

/**
 * Собрать запись карты по промежутку токенов.
 *
 * Текст — СКЛЕЙКА лексем, потому что исходной строки у разборщика нет (границу см. в шапке).
 * За границами потока — `undefined`, а не «примерно там»: источник не выдумывается.
 */
export function собратьИсточник(
  токены: readonly ТокенДляКарты[],
  вид: ВидИсточника,
  от: number,
  до: number,
): Omit<ИсточникУзла, "astNodeId"> | undefined {
  const первый = токены[от];
  if (первый === undefined) return undefined;
  const конецГраница = Math.min(до, токены.length);
  const лексемы: string[] = [];
  for (let i = от; i < конецГраница; i++) лексемы.push(токены[i]!.lexeme);
  return {
    tokenIndex: от,
    конец: конецГраница,
    вид,
    текст: лексемы.join(""),
    строка: первый.line,
    колонка: первый.column,
  };
}

/**
 * Записать источник в карту. Номер узла выдаётся здесь, и только здесь.
 *
 * Возвращает запись с номером: вызывающий вправе сразу положить `astNodeId` в отказ.
 */
export function запомнитьИсточник(
  узел: Узел,
  запись: Omit<ИсточникУзла, "astNodeId">,
): ИсточникУзла {
  const полная: ИсточникУзла = { astNodeId: следующийНомер++, ...запись };
  поУзлу.set(узел, полная);
  поНомеру.set(полная.astNodeId, полная);
  return полная;
}

/** Источник узла, если он записан (ключ — БАЗА выражения, а не пересобранный `вызов`). */
export function источникУзла(узел: Узел | undefined): ИсточникУзла | undefined {
  return узел === undefined ? undefined : поУзлу.get(узел);
}

/** Источник по номеру — для отказов, которым досталась только ссылка из IR. */
export function источникПоНомеру(astNodeId: number): ИсточникУзла | undefined {
  return поНомеру.get(astNodeId);
}

/**
 * Ссылка для инструкции IR — или `undefined`, если источник не записан.
 *
 * Именно `undefined`, а не «нулевая ссылка»: потребитель обязан уметь отличить «источника нет» и
 * вернуться к прежнему тексту отказа (§3 брифа: старый текст — запасной путь, а не поломка).
 */
export function ссылкаНаИсточник(узел: Узел | undefined): IRSourceRef | undefined {
  const запись = источникУзла(узел);
  return запись === undefined
    ? undefined
    : { astNodeId: запись.astNodeId, tokenIndex: запись.tokenIndex };
}

/**
 * Человеческое описание источника: `лента[индекс], строка 5, колонка 3`.
 *
 * Ровно та форма, которую требует §3 брифа: СНАЧАЛА то, что человек написал, ЗАТЕМ место.
 */
export function описаниеИсточника(запись: ИсточникУзла): string {
  return `${запись.текст}, строка ${String(запись.строка)}, колонка ${String(запись.колонка)}`;
}

/**
 * Описание источника по ссылке из IR.
 *
 * `undefined` — если ссылки нет ИЛИ реестр её не знает (чужой процесс, рукописный носитель).
 * Оба случая обязан обработать вызывающий: отказ без источника остаётся прежним.
 */
export function описаниеПоСсылке(ссылка: IRSourceRef | undefined): string | undefined {
  if (ссылка === undefined) return undefined;
  const запись = поНомеру.get(ссылка.astNodeId);
  return запись === undefined ? undefined : описаниеИсточника(запись);
}

/**
 * Описание источника для ОТКАЗА: то, чем заменяется внутреннее имя.
 *
 * Отдельная функция, а не `описаниеПоСсылке(...) ?? "…"`, чтобы запасной путь был виден в одном
 * месте: `undefined` здесь означает «говори как раньше», и это решение вызывающего.
 */
export function источникДляОтказа(ссылка: IRSourceRef | undefined): string | undefined {
  return описаниеПоСсылке(ссылка);
}

/** Только для сторожей: сколько записей накопилось. Не влияет на работу конвейера. */
export function размерКартыИсточника(): number {
  return поНомеру.size;
}
