/**
 * СИМВОЛ СТРОКИ ПО ИНДЕКСУ: `"абв"[0]` — ЭТО «а», И ЭТО НЕ `null`.
 *
 * # Зачем модуль, а не три строки в обработчике
 *
 * Отказ обязан быть ОДИН на обе VM и на понижение. Сделай его в обработчике VM — пришлось бы
 * повторять и в регистровой, и на цели, а расхождение текста отказа между сторонами в этом проекте
 * уже разбирали (случай 34 реестра: у арены и коллекций был один код и разные строки). Здесь
 * лежат: имя операции, разбор индекса и САМ отказ.
 *
 * # Почему СТРОКА, а не «код символа»
 *
 * `с[0]` в языке — элемент строки, а элемент строки есть СТРОКА из одного символа: ровно то же
 * значение, что у `система.строка.подстрока(с, 0, 1)`. Так это и сформулировано владельцем
 * (`"абв"[0] == "а"`), и так же ведёт себя список: `[10,20,30][0]` — элемент, а не «представление
 * элемента». Код символа — другая операция, и вводить её здесь значило бы решать за язык.
 *
 * # Почему отказ, а не `null`
 *
 * До этой правки `"абв"[0]` давал `null`, и `null + 100` давало **100** — то есть символ вёл себя
 * как ноль. Для лексера это худший из возможных исходов: он «прочитал» бы буквы как нули и выдал
 * поток пустых токенов МОЛЧА. Выход за границу обязан быть виден (§2.3), и он виден: исключение с
 * индексом и длиной в тексте.
 *
 * # Единицы
 *
 * Индекс — в КОДОВЫХ ТОЧКАХ, как и `длина` (`система.строка.длина`: `длина("🙂")` = 1). Иначе
 * `с[длина с - 1]` не был бы последним символом: у «🙂» длина 1, а байтов 4.
 */
import type { StackValue } from './interpreter';

/**
 * Каноническое имя операции. Объявлено в реестре языка (`система.строка.символ`), потому что
 * вызывается она не только из `с[i]`: формулировка владельца — «`arr[i]` — форма обращения», и
 * разворачивает её СЕМАНТИКА по типу операнда (как `длина`), а имя должно существовать в каноне,
 * иначе разрешение имён отвергнет дерево.
 */
export const STRING_CHAR_SYSCALL = 'система.строка.символ';

/** Арность операции: `символ(строка, индекс)`. */
export const STRING_CHAR_ARGC = 2;

/**
 * НАЗВАННЫЙ ОТКАЗ СТРОКИ — третий статус, а не `null`.
 *
 * Отдельный класс, а не общий с коллекциями: у строки и у блока коллекции РАЗНЫЕ причины отказа
 * (индекс вне длины против индекса вне ёмкости блока), и наблюдателю нужно их различать. Тот же
 * урок, что у строк отказа арены и коллекций (случай 34).
 */
export class StringIndexRefusal extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'StringIndexRefusal';
  }
}

/**
 * Символ по индексу в КОДОВЫХ ТОЧКАХ — одна реализация на обе VM.
 *
 * @param value значение операнда: строка (у VM) либо что-то иное — тогда это дефект вызывающего
 * @param index индекс в кодовых точках
 * @returns строка из одного символа
 * @throws StringIndexRefusal индекс не целое, отрицателен или не меньше длины
 */
export function stringCharAt(value: StackValue, index: StackValue): string {
  const s = typeof value === 'string' ? value : String(value ?? '');
  const raw = Number(index);
  if (!Number.isFinite(raw)) {
    throw new StringIndexRefusal(
      `символ строки: индекс ${String(index)} — не число; индекс обязан быть целым в кодовых точках`,
    );
  }
  const i = Math.trunc(raw);
  // Точки, а не единицы UTF-16: `[...s]` разбирает строку по кодовым точкам, поэтому «🙂» — один
  // элемент, и `длина` с этим согласна.
  const points = [...s];
  if (i < 0 || i >= points.length) {
    throw new StringIndexRefusal(
      `символ строки: индекс ${String(i)} вне длины ${String(points.length)} — ` +
        'выход за границу обязан быть виден, а не вернуть null (иначе null сложился бы с числом как ноль)',
    );
  }
  return points[i]!;
}
