/** Сообщение о вызове, которого нет: особое, если причина известна. */
export function unknownSyscallMessage(name: string): string {
  const reason = SYSCALL_NO_CANON[name];
  if (reason) return `'${name}': ${reason}`;
  return `системный вызов '${name}' не существует`;
}

/**
 * Каноническое имя системного вызова: известный синоним сводится к канону,
 * остальное возвращается как есть. Применяется там, где имя вызова попадает в
 * AST, — чтобы семантика, кодогенерация и обе VM видели одно имя.
 */
export function resolveSyscallAlias(name: string): string {
  return SYSCALL_ALIASES[name] ?? name;
}