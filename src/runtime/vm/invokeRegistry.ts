/** Число аргументов для известных системных вызовов. Неизвестный invoke → 0. */
export function getInvokeArgCount(name: string): number {
  return INVOKE_ARG_COUNT[name] ?? 0;
}

/** Проверка, известен ли invoke. Для неизвестных — throw вместо stack corruption. */
export function isKnownInvoke(name: string): boolean {
  return name in INVOKE_ARG_COUNT;
}

/**
 * Реестр синонимов системных вызовов: что пишет модель → каноническое имя.
 *
 * Пункт 1.5 требований (41 случай `unknown_syscall`): модель почти не изобретает
 * конструкции — она подставляет синоним. Лечится словарь, а не грамматика: приём
 * не меняет язык и не открывает новых способов ошибиться.
 *
 * Карта — по ПОЛНОМУ имени, а не по последнему сегменту: `система.массив.получить`
 * и `система.сеть.получить` — канонические имена, и сегментная замена
 * `получить` → `прочитать` их бы сломала.
 */
export const SYSCALL_ALIASES: Readonly<Record<string, string>> = {
  "система.хранилище.получить": "система.хранилище.прочитать",
  "система.хранилище.сохранить": "система.хранилище.записать",
  "система.окно.вывод": "система.лог.вывести",
  "система.строка.срез": "система.строка.подстрока",
};

/**
 * Каноническое имя системного вызова: известный синоним сводится к канону,
 * остальное возвращается как есть. Применяется там, где имя вызова попадает в
 * AST, — чтобы семантика, кодогенерация и обе VM видели одно имя.
 */
export function resolveSyscallAlias(name: string): string {
  return SYSCALL_ALIASES[name] ?? name;
}