/**
 * Записи каталога и выведенные из них объединения имён.
 *
 * Разделение то же, что у самих списков: `blocking` решает, входит ли вид в
 * блокирующий список, `debt` — отнесён ли он вообще к какой-нибудь половине.
 * Виды с долгом (`IndebtedEntry`) стоят **вне** обоих списков — см.
 * `semanticKinds.ts`. Судьба сборки (`buildRefused`) в типах не участвует: это
 * замер, а не классификация.
 */
export type DiagnosticEntry = (typeof DIAGNOSTIC_KINDS)[number];
/** Все виды каталога — 15 штук. */
export type DiagnosticKind = DiagnosticEntry["kind"];
/** Виды блокирующего списка (`blocking: true`) — 6 штук. */
export type BlockingEntry = Extract<DiagnosticEntry, { blocking: true }>;
/** Виды с названным долгом: в списках их нет намеренно. */
export type IndebtedEntry = Extract<DiagnosticEntry, { debt: string }>;
/** Виды, отнесённые к неблокирующим: не блокируют и долга за ними нет. */
export type NonBlockingEntry = Exclude<DiagnosticEntry, BlockingEntry | IndebtedEntry>;
export type BlockingDiagnosticKind = BlockingEntry["kind"];
export type IndebtedDiagnosticKind = IndebtedEntry["kind"];
export type NonBlockingDiagnosticKind = NonBlockingEntry["kind"];

