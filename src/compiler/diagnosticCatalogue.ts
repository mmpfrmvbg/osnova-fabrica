const BY_KIND = new Map<string, DiagnosticKindInfo>(DIAGNOSTIC_KINDS.map((k) => [k.kind, k]));

/** Запись каталога по имени вида; `undefined` — вид не каталогизирован (дефект, а не норма). */
export function diagnosticKindInfo(kind: string | undefined): DiagnosticKindInfo | undefined {
  return kind === undefined ? undefined : BY_KIND.get(kind);
}

/**
 * Машинный код вида. Для некаталогизированного вида возвращается `undefined`
 * намеренно: подставлять «похожий» код значило бы соврать в журнале.
 */
export function diagnosticCodeOf(kind: string | undefined): string | undefined {
  return diagnosticKindInfo(kind)?.code;
}

/**
 * Состояние вида; `undefined` — вид не каталогизирован (дефект каталога, а не
 * свойство программы: подставлять «похожее» состояние значило бы соврать тем же
 * правилом, что и с кодом).
 */
export function diagnosticStateOf(kind: string | undefined): DiagnosticState | undefined {
  return diagnosticKindInfo(kind)?.state;
}

/** Блокирует ли вид сборку. Неизвестный вид не блокирует — как и было до каталога. */
export function isBlockingKind(kind: string | undefined): boolean {
  return diagnosticStateOf(kind) === "блокирующий";
}

/**
 * Мёртв ли вид: исходный текст его не порождает. Неизвестный вид мёртвым **не**
 * считается — неизвестность это дефект каталога, и называть её смертью значило бы
 * прятать дефект за состоянием.
 */
export function isUnreachableKind(kind: string | undefined): boolean {
  return diagnosticStateOf(kind) === "недостижимый";
}
