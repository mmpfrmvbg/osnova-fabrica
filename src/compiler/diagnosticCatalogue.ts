/**
 * ЕДИНЫЙ КАТАЛОГ ВИДОВ ОШИБОК — источник правды об их личности.
 *
 * **Зачем.** До этого каталога виды ошибок жили **тремя несогласованными
 * списками**: `semantic.ts` (объединение из 15 видов в типе `SemanticError.kind`),
 * `semanticKinds.ts` (6 блокирующих + 3 неблокирующих = 9) и канон
 * `docs/language-v2.md` §12 (6 + 5 = 11). Шесть видов — `arg_count_mismatch`,
 * `chained_compare`, `keyword_param`, `sentinel_pattern`, `unknown_module`,
 * `export_collision` — не входили **ни в один** список, то есть были
 * невидимы для всех, кто спрашивает «блокирует ли это сборку»
 * (`compiler.ts:1496`, `gateChecker.ts:64`, `orchestrator.ts:82`). Замер
 * 2026-09-28: неверное число аргументов процедуры (`arg_count_mismatch`)
 * собирается и в пайплайне не блокирует ничего.
 *
 * **Что здесь есть.** Одна запись на вид: имя в коде (`kind`), **стабильный
 * машинный код**, признак блокировки и описание одной строкой. Потребители
 * (`semanticKinds.ts`, сторожа, журнал, CLI) обязаны брать виды отсюда, а не
 * заводить свои перечни. Отражение таблицы в каноне — `docs/language-v2.md`
 * §12.1; расходится канон с этой таблицей — дефект канона, и он назван в
 * `diagnosticCatalogue.test.ts`.
 *
 * **Три поля — три разных смысла, и путать их нельзя** (на каждом стоит замер,
 * таблица замеров — в `diagnosticCatalogue.test.ts`):
 *
 * - `blocking` — вид **входит в блокирующий список**: по нему пайплайн
 *   маршрутизирует в repair-цикл, а шлюз G2 отказывает. Это **не** «программа с
 *   этим видом не собирается»: замер 2026-09-28 — у `break_outside_loop` стоит
 *   `blocking: false`, а программа с единственным `прервать` вне цикла не
 *   собирается вовсе, потому что отказывает кодоген (см. `buildRefused`).
 * - `debt` — вид **не отнесён ни к одному списку**: его нет ни в блокирующем, ни
 *   в неблокирующем. Это не «плохой вид», а названная нерешённость.
 * - `buildRefused` — **замер**: программа с этим видом сегодня не собирается.
 *   К спискам отношения не имеет и в их выводе не участвует.
 *
 * **Списки выводятся отсюда, а не переписываются.** `semanticKinds.ts` берёт
 * `BLOCKING_SEMANTIC_KINDS` по признаку `blocking`, а `NON_BLOCKING_SEMANTIC_KINDS` —
 * по «не блокирует **и** долга нет». Шесть видов с долгом не входят **ни в один**
 * список: это сегодняшнее состояние, названное, а не спрятанное. Снять долг —
 * значит расширить неблокирующий список, а с ним поведение `DiagnosticAgent`,
 * `RepairEngineer` и схемы записей журнала: решение владельца, а не правка текста.
 *
 * **Правила кодов.** Пространство имён — ASCII, потому что коды читают машины:
 * `OSN-<ФАЗА>-<НОМЕР>`, где фаза — `LEX`, `PAR`, `SEM`, `CG`, `RT`, `CLI`.
 * Код выдаётся один раз и **не переиспользуется**: вид, ушедший из языка,
 * оставляет код за собой (в журналах прошлых прогонов он уже есть). Новый вид
 * получает следующий свободный номер, а не «красивый» по алфавиту.
 *
 * **Чего здесь намеренно нет.** Версии `since` у видов: их негде взять из кода,
 * а выдуманная версия — ложный факт в каноне. Позиции (`line`/`column`) тоже не
 * здесь: это свойство конкретной ошибки, а не вида (`SemanticError.line`
 * объявлено и не заполняется — AST не несёт номеров строк, канон §12.3).
 */

/** Уровень записи. Слово, а не латиница: так его печатает CLI, так его видит человек. */
export type DiagnosticSeverity = "ошибка" | "предупреждение";

/**
 * Фаза, назвавшая причину.
 *
 * Перечень фаз — здесь и только здесь: на него смотрят запись (`DiagnosticRecord`),
 * журнал (`src/trace/**`) и разбор по фазам. `вызов` — отказ **до** компиляции
 * (не указан или не найден входной файл, см. {@link CLI_CODES}); `исполнение` —
 * отказ VM на уже собранной программе.
 *
 * Замер 2026-09-28: `src/compiler/compileDiagnostics.ts` держит **своё**
 * объединение тех же фаз, но с `вызов` вместо `исполнение`. Расхождение названо,
 * а не сглажено: два перечня одной личности — тот же класс, ради которого заведён
 * каталог.
 */
export type DiagnosticPhase = "лексер" | "парсер" | "семантика" | "сборка" | "вызов" | "исполнение";

/** Одна запись каталога: личность вида ошибки. */
export interface DiagnosticKindInfo {
  /** Имя вида в коде компилятора (`SemanticError.kind`). */
  kind: string;
  /** Стабильный машинный код: `OSN-SEM-001`. Не переиспользуется. */
  code: string;
  /**
   * Входит ли вид в **блокирующий список** — тот, по которому пайплайн
   * маршрутизирует в repair-цикл, а шлюз G2 отказывает
   * (`BLOCKING_SEMANTIC_KINDS`), и через который вид попадает в
   * `BuildReport.success` (`compiler.ts`).
   *
   * Смысл **у́же**, чем «блокирует сборку вообще», и это не придирка к словам:
   * замер 2026-09-28 — программа с единственной диагностикой
   * `break_outside_loop` (`blocking: false`) не собирается вовсе
   * (`BuildReport.success = false`, `compilerSuccess = false`, модуля нет),
   * потому что отказывает кодоген. Судьбу сборки описывает поле `buildRefused`,
   * а не это.
   */
  blocking: boolean;
  /** Одна строка для канона, журнала и подсказки. */
  description: string;
  /**
   * Названный долг: вид попал в язык, но не был отнесён ни к блокирующим, ни к
   * неблокирующим. Пока поле заполнено, `blocking` описывает **сегодняшнее**
   * вхождение в список, а не решение владельца. Здесь же называются замеры
   * достижимости вида из исходного текста — там, где проба не строится.
   *
   * **Поле несущее: на нём держится вывод списков.** Вид с долгом не попадает ни
   * в `BLOCKING_SEMANTIC_KINDS`, ни в `NON_BLOCKING_SEMANTIC_KINDS`, поэтому
   * заполнить долг — значит изменить списки, а с ними поведение потребителей
   * (`DiagnosticAgent`, `RepairEngineer`, схема записей журнала). Сторож —
   * `diagnosticCatalogue.test.ts`: он краснеет и на снятый долг, и на выдуманный.
   */
  debt?: string;
  /**
   * **Замер:** программа с единственной такой диагностикой сегодня **не
   * собирается** — `BuildReport.success = false`, `compilerSuccess = false`,
   * модуля нет. Отказывает кодоген, а не блокирующий список, поэтому поле живёт
   * отдельно от `blocking` и **в выводе списков не участвует**.
   *
   * Заполнено там, где это расходится с ожиданием «`blocking: false` — значит
   * собирается»: замер 2026-09-28 (независимый проверяющий T5, перемерено
   * владельцем и T1) — `break_outside_loop`, `continue_outside_loop`.
   */
  buildRefused?: string;
}

