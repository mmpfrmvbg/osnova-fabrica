/**
 * ЕДИНЫЙ КАТАЛОГ ВИДОВ ОШИБОК — источник правды об их личности.
 *
 * **Зачем.** До этого каталога виды ошибок жили **тремя несогласованными
 * списками**: `semantic.ts` (объединение из 15 видов в типе `SemanticError.kind`),
 * `semanticKinds.ts` (6 блокирующих + 3 неблокирующих = 9) и канон
 * `docs/language-v2.md` §12 (6 + 5 = 11). Шесть видов — `arg_count_mismatch`,
 * `chained_compare`, `keyword_param`, `sentinel_pattern`, `unknown_module`,
 * `export_collision` — не входили **ни в один** список, то есть были
 * невидимы для всех, кто спрашивает «блокирует ли это сборку»
 * (`compiler.ts:1496`, `gateChecker.ts:64`, `orchestrator.ts:82`). Замер
 * 2026-09-28: неверное число аргументов процедуры (`arg_count_mismatch`)
 * собирается и в пайплайне не блокирует ничего.
 *
 * **Что здесь есть.** Одна запись на вид: имя в коде (`kind`), **стабильный
 * машинный код**, признак блокировки и описание одной строкой. Потребители
 * (`semanticKinds.ts`, сторожа, журнал, CLI) обязаны брать виды отсюда, а не
 * заводить свои перечни. Отражение таблицы в каноне — `docs/language-v2.md`
 * §12.1; расходится канон с этой таблицей — дефект канона, и он назван в
 * `diagnosticCatalogue.test.ts`.
 *
 * **Состояние вида — ровно одно, и оно названо** (решение владельца 2026-09-28,
 * задача T12). Прежде было три поля с пересекающимися смыслами и «долг» как
 * состояние «не отнесён ни к одному списку»; долг снят, потому что он описывал
 * нерешение, а не вид. Теперь состояний четыре, и каждое называет ФАКТ:
 *
 * - `state: "блокирующий"` — вид в блокирующем списке: по нему пайплайн
 *   маршрутизирует в repair-цикл, шлюз G2 отказывает, и через него вид попадает
 *   в `BuildReport.success` (`compiler.ts`). **Ставится по замеру:** вид, при
 *   котором программа не собирается, обязан стоять здесь. Ровно поэтому
 *   `break_outside_loop` и `continue_outside_loop` переведены в блокирующие
 *   2026-09-28: программа с единственным `прервать` вне цикла не собирается.
 * - `state: "неблокирующий"` — жив (порождается исходным текстом), сборку
 *   проходит и **отдан потребителям**: входит в `NON_BLOCKING_SEMANTIC_KINDS`.
 * - `state: "неблокирующий-вне-списка"` — жив и сборку проходит, но потребителям
 *   **не отдан**. Сюда попали три вида, стоявшие с долгом (`arg_count_mismatch`,
 *   `sentinel_pattern`, `unknown_module`): они достижимы и безвредны для сборки,
 *   но **расширение неблокирующего списка отклонено владельцем**, и цена этого
 *   решения измерена, а не скрыта. Замер `.tmp/diag-consumers-probe.ts`: если
 *   отдать их потребителям, `DiagnosticAgent` начнёт рождать **+3** записи
 *   (видимых видов 9 → 12 из 15, молча отброшенных 6 → 3), а `RepairEngineer`
 *   положит **+3** вида в промпт ремонта (9 → 12). Это поведение замороженного
 *   пайплайна, поэтому решение о нём — владельца, а не следствие уборки перечней.
 *   Состояние называет и природу вида, и решение: «не отнесён ни к одному» здесь
 *   больше нет.
 * - `state: "недостижимый"` — вид **мёртв**: исходный текст его не порождает
 *   (замер — поле `unreachable`, у каждого свой). Код вида остаётся
 *   **зарезервированным навсегда**: он выдан и в журналах прошлых прогонов уже
 *   есть. В списки потребителей мёртвый вид не входит — маршрутизировать нечего.
 *
 * Состояния складываются в 15 без остатка: **8 блокирующих + 1 неблокирующий +
 * 3 неблокирующих вне списка + 3 недостижимых**. Сторож
 * (`diagnosticCatalogue.test.ts`) краснеет, если вид окажется вне состояний, если
 * состояние разойдётся с замером (жив/мёртв, блокирует/нет) или если мёртвый вид
 * останется без названного замера.
 *
 * **Поведение потребителей не изменилось — и это проверено, а не обещано.**
 * Замер до и после правки одним и тем же вызовом
 * (`.tmp/diag-consumers-probe.ts`): `DiagnosticAgent` видит **9** видов из 15 и
 * молча отбрасывает **6**, `RepairEngineer` пускает **9** видов в промпт — и
 * ровно те же числа после. Списки остались 8 + 1 = 9 отнесённых из 15; изменилось
 * только то, что у шести «вне списков» теперь названное состояние, а не долг.
 *
 * `buildRefused` — **названное расхождение** замера с состоянием: программа с
 * видом не собирается, а вид не блокирующий. Заполнено ⟺ замер это показывает —
 * и пусто сегодня у всех пятнадцати, потому что расхождений нет (сторож краснеет
 * и на расхождение без записи, и на запись без расхождения).
 *
 * **Списки выводятся отсюда, а не переписываются.** `semanticKinds.ts` берёт
 * `BLOCKING_SEMANTIC_KINDS` по состоянию «блокирующий», а
 * `NON_BLOCKING_SEMANTIC_KINDS` — по состоянию «неблокирующий»; мёртвые и
 * неотданные не входят ни туда, ни туда.
 *
 * **Мёртвых видов три, и недостижимость каждого доказана своим замером.**
 * `chained_compare` — проверка снята 2026-09-28 (коммит `f4f5165`): цепочку
 * разворачивает в `и` **парсер** по канону §2.1, и она считается верно
 * (дискриминатор даёт 10); `keyword_param` — **33 из 33** неблочных ключевых слов
 * в позиции параметра отвергает парсер (`.tmp/diag-keyword-param-sweep.ts`);
 * `export_collision` — из исходного текста не построить, четыре файловые формы
 * проходят молча (`.tmp/diag-export-collision-probe.ts`), а ручной `Program`
 * через `analyzeProgram` вид порождает. Коды `OSN-SEM-008`/`009`/`013` остаются
 * за ними навсегда — правило «код не переиспользуется». Сторож краснеет и на
 * возвращение такого вида к жизни, и на живой вид, названный мёртвым.
 *
 * **Правила кодов.** Пространство имён — ASCII, потому что коды читают машины:
 * `OSN-<ФАЗА>-<НОМЕР>`, где фаза — `LEX`, `PAR`, `SEM`, `CG`, `RT`, `CLI`.
 * Код выдаётся один раз и **не переиспользуется**: вид, ушедший из языка,
 * оставляет код за собой (в журналах прошлых прогонов он уже есть). Новый вид
 * получает следующий свободный номер, а не «красивый» по алфавиту.
 *
 * **Чего здесь намеренно нет.** Версии `since` у видов: их негде взять из кода,
 * а выдуманная версия — ложный факт в каноне. Позиции (`line`/`column`) тоже не
 * здесь: это свойство конкретной ошибки, а не вида (`SemanticError.line`
 * объявлено и не заполняется — AST не несёт номеров строк, канон §12.3).
 */

/** Уровень записи. Слово, а не латиница: так его печатает CLI, так его видит человек. */
export type DiagnosticSeverity = "ошибка" | "предупреждение";

/**
 * Фаза, назвавшая причину.
 *
 * Перечень фаз — здесь и только здесь: на него смотрят запись (`DiagnosticRecord`),
 * журнал (`src/trace/**`) и разбор по фазам. `вызов` — отказ **до** компиляции
 * (не указан или не найден входной файл, см. {@link CLI_CODES}); `исполнение` —
 * отказ VM на уже собранной программе.
 *
 * Замер 2026-09-28: `src/compiler/compileDiagnostics.ts` держит **своё**
 * объединение тех же фаз, но с `вызов` вместо `исполнение`. Расхождение названо,
 * а не сглажено: два перечня одной личности — тот же класс, ради которого заведён
 * каталог.
 */
export type DiagnosticPhase = "лексер" | "парсер" | "семантика" | "сборка" | "вызов" | "исполнение";

/**
 * СОСТОЯНИЕ ВИДА — ровно одно на вид, и оно названо (решение владельца
 * 2026-09-28, задача T12: состояние `debt` снято).
 *
 * Три состояния, и они складываются в 15 без остатка: **8 + 4 + 3**. Смысл
 * каждого назван ниже; сторож (`diagnosticCatalogue.test.ts`) требует, чтобы
 * состояние совпадало с замером: живой вид порождается исходным текстом, мёртвый
 * — нет, блокирующий — не собирается.
 */
export type DiagnosticState =
  /** В блокирующем списке: сборка не проходит, отказ идёт в repair-цикл. */
  | "блокирующий"
  /** Жив, сборку проходит и **отдан потребителям** (неблокирующий список). */
  | "неблокирующий"
  /**
   * Жив и сборку проходит, но **потребителям не отдан**: в неблокирующий список
   * не входит. Это не «не отнесён ни к одному»: состояние называет и природу вида
   * (неблокирующий, достижим), и решение владельца (расширение списка отклонено),
   * и цену этого решения — она измерена и названа ниже.
   */
  | "неблокирующий-вне-списка"
  /** Мёртв: исходный текст его не порождает. Код зарезервирован навсегда. */
  | "недостижимый";

/** Одна запись каталога: личность вида ошибки. */
export interface DiagnosticKindInfo {
  /** Имя вида в коде компилятора (`SemanticError.kind`). */
  kind: string;
  /** Стабильный машинный код: `OSN-SEM-001`. Не переиспользуется. */
  code: string;
  /**
   * Состояние вида — см. {@link DiagnosticState}. Одно поле вместо прежних
   * `blocking` + `debt`: два поля допускали третье, безымянное состояние
   * («не отнесён ни к одному»), и именно оно оказалось дороже всего — замер
   * `.tmp/diag-consumers-probe.ts`: шесть видов с долгом молча выпадали из
   * `DiagnosticAgent` (6 из 15 записей не рождалось) и не попадали в промпт
   * `RepairEngineer`.
   *
   * **Ставится по замеру, а не по желанию:** «блокирующий» ⟺ сборка не проходит;
   * «неблокирующий» ⟺ вид порождается и сборку проходит; «недостижимый» ⟺ вид не
   * порождается ни одной площадкой и это доказано замером в `unreachable`.
   */
  state: DiagnosticState;
  /** Одна строка для канона, журнала и подсказки. */
  description: string;
  /**
   * **Замер недостижимости** — обязателен ровно у состояния «недостижимый» и
   * запрещён у остальных (сторож краснеет в обе стороны). Здесь называется не
   * «мнение, что вид мёртв», а чем это проверено: снятая проверка, свип по
   * реестру, недостижимость из языка при живой ветке API.
   */
  unreachable?: string;
  /**
   * **Названное расхождение:** программа с единственной такой диагностикой **не
   * собирается** (`BuildReport.success = false`, `compilerSuccess = false`,
   * модуля нет), а состояние вида — не «блокирующий».
   *
   * Поле — не отписка, а имя: сторож (`diagnosticCatalogue.test.ts`) выводит его
   * из исполняемой таблицы замеров, поэтому краснеют обе стороны — «расхождение
   * без записи» и «запись без расхождения».
   *
   * **Сегодня пусто у всех пятнадцати видов — и это результат правки
   * 2026-09-28.** Прежде здесь стояли `break_outside_loop` и
   * `continue_outside_loop`: программа с ними не собиралась (отказ называют
   * семантика видом и кодоген — «оператор 'прервать' допустим только внутри
   * цикла»), а вид числился неблокирующим. Состояние переведено в «блокирующий»
   * — вид, при котором сборка не проходит, обязан идти в repair-цикл, — и
   * расхождение закрылось вместе с записью. Замер: `.tmp/diag-break.osnova`,
   * `.tmp/diag-continue.osnova` (код возврата команды 1).
   */
  buildRefused?: string;
}

