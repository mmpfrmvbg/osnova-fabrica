/**
 * КАНОН-ОРАКУЛ: шесть проверок языковой плоскости.
 *
 * # Закон этого файла
 *
 * Канон не пишется раньше проверки. Здесь собраны проверки, которые РЕШАЮТ, что
 * можно записать в `docs/language-v2.md`:
 *
 * | статус | что значит |
 * |---|---|
 * | проверено прогоном | утверждение канона без оговорок |
 * | не проверено | пометка «не проверено» — валидный постоянный статус |
 *
 * Третьего статуса нет. Поэтому проверки живут В ОДНОМ файле: канон меняется —
 * оракул падает, пока изменение не проверено. Это защита от дрейфа.
 *
 * # Что здесь утверждается
 *
 * Утверждается **ИЗМЕРЕННОЕ**, а не желаемое. Там, где измеренное расходится с
 * намерением канона, расхождение названо в комментарии и в `docs/language-v2.md`
 * стоит пометка, а не тихая подмена факта ожиданием. Иначе оракул закрепил бы
 * желание вместо действительности и мешал бы это исправить.
 *
 * # Как перемерить
 *
 * Проба: `.tmp/canon-probes.ts` (запуск `npx tsx .tmp/canon-probes.ts`).
 * Числа ниже — её вывод. Проба не входит в прогон: она инструмент, а не оракул.
 *
 * # Негативные контроли
 *
 * У каждой группы — сценарий, при котором она краснеет (назван в комментарии
 * группы). Контроли выполнялись МУТАЦИЕЙ исходников VM с восстановлением по
 * sha256; файлы и хеши — в отчёте сессии. Оракул, который не может покраснеть,
 * не оракул.
 *
 * # Чужая плоскость
 *
 * `src/e2k/**`, `docs/e2k-*` и `docs/hardware-debt.md` здесь только ЦИТИРУЮТСЯ:
 * машинная плоскость измеряется своими пробами и в этом файле не проверяется.
 * Где поведение e2k не измерено — стоит «не проверено», а не догадка.
 */
import { describe, it, expect } from "vitest";
import { compileSource } from "./compiler";
import { OsVbcVM } from "../runtime/vm";
import { InterpreterError } from "../runtime/vm/interpreter";
import { tokenize } from "./lexer";
import { parse } from "./parser";

/** Модуль с процедурой `главная`, возвращающей результат выражений. */
function wrap(body: string[]): string {
  return ["модуль Т", "процедура главная()", ...body.map((l) => "  " + l), "конец_процедуры"].join("\n");
}

/**
 * Скомпилировать и исполнить. Ошибка компиляции — тоже ошибка прогона: молча
 * вернуть `undefined` значило бы принять несобравшуюся программу за результат.
 */
async function run(src: string): Promise<unknown> {
  const c = compileSource(src, { filename: "канон.osnova" });
  if (!c.module) {
    const errs = [...c.lexerErrors, ...c.parserErrors, ...c.compilerErrors].map((e) => e.message);
    throw new Error("не скомпилировалось: " + errs.join("; "));
  }
  return new OsVbcVM(c.module, { maxSteps: 10000 }).execute();
}

