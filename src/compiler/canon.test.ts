describe("канон: длина строки считается в единицах UTF-16 (не в кодовых точках)", () => {
  // Намерение канона — кодовые точки. ИЗМЕРЕНО: `система.строка.длина` возвращает
  // JS `.length`, то есть единицы UTF-16. Для BMP расхождения нет (привет=6, ёж=2),
  // для астральных символов есть: 👍 даёт 2, а кодовых точек 1.
  // Значит «кодовые точки» — не запись в каноне, а РАБОТА. Пока не сделано,
  // канон обязан говорить «единицы UTF-16».
  // Негативный контроль: заменить `s.length` на `[...s].length` в case
  // "система.строка.длина" — краснеют проверки с 👍 и с семьями.

  it("длина(\"привет\") = 6 — BMP, расхождения нет", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("привет")']))).toBe(6);
  });

  it("длина(\"ёж\") = 2", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("ёж")']))).toBe(2);
  });

  it("длина(\"👍\") = 2 — ЭТО UTF-16, кодовых точек 1", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("👍")']))).toBe(2);
    // Обе единицы названы рядом: если реализация когда-нибудь перейдёт на кодовые
    // точки, вторая строка останется верной, а первая покраснеет — и это будет
    // осознанное изменение канона, а не тихий дрейф.
    expect([..."👍"].length, "кодовых точек в 👍").toBe(1);
  });

  it("длина(семья 👨‍👩‍👧) = 8 — ни кодовые точки (5), ни графемы (1)", async () => {
    // Графемы каноном не считаются: 👨‍👩‍👧 — одна графема, но не наша единица.
    expect(await run(wrap(['вернуть система.строка.длина("👨‍👩‍👧")']))).toBe(8);
    expect([..."👨‍👩‍👧"].length, "кодовых точек в семье").toBe(5);
  });

  it("NFD-разложение учитывается по единицам: «е + U+0308 + ж» = 3", async () => {
    // «ё» в NFD — это е + комбинирующая диакритика: 3 единицы, а не 2.
    // Канон обязан сказать, что нормализация не выполняется.
    expect(await run(wrap(['вернуть система.строка.длина("е\u0308ж")']))).toBe(3);
  });
});

