// 6a. ОСТАТОК ПРИ НУЛЕВОМ ДЕЛИТЕЛЕ — ДВА ПРАВИЛА, А НЕ ОДНО
// ─────────────────────────────────────────────────────────────────────────────

describe("канон: ноль в делителе — отдельное правило для деления и для остатка", () => {
  // Канону нужны ДВА правила: у деления и у остатка отказ свой.
  // VM: и `div`, и `%` отказывают, тексты разные — это и зафиксировано.
  // Негативный контроль: свести оба случая к одному сообщению (или к одному
  // опкоду) — краснеет проверка «тексты различаются».

  it("VM: div и % при нуле дают РАЗНЫЕ тексты отказа", async () => {
    const divMsg = await run(wrap(["вернуть 1 div 0"])).catch((e: Error) => e.message);
    const remMsg = await run(wrap(["вернуть 1 % 0"])).catch((e: Error) => e.message);
    expect(divMsg).toBe("Integer division by zero");
    expect(remMsg).toBe("Remainder by zero");
    expect(divMsg, "правила разные — сообщения тоже").not.toBe(remMsg);
  });

  it("/ при нуле даёт свой текст, отличный от div", async () => {
    const slash = await run(wrap(["вернуть 1 / 0"])).catch((e: Error) => e.message);
    expect(slash).toBe("Division by zero");
  });

  /**
   * НЕ ПРОВЕРЕНО (и это валидный статус, а не долг сессии).
   *
   * e2k `SDIVs` при нулевом делителе даёт `exc_div` — измерено машинной
   * плоскостью (`docs/e2k-opcodes-real.md` §:69, `src/e2k/e2kDivisionForms.test.ts`,
   * `src/e2k/e2kRealRun.ts`). Для `SMODX` (остаток) такого измерения НЕТ: прогон
   * требует QEMU-e2k и живёт в `gate:qemu`, чужая плоскость.
   *
   * Значит канон обязан записать: «VM — проверено; e2k SDIVs — проверено чужой
   * пробой; e2k SMODX — не проверено». Молчать об этом нельзя: правило для
   * остатка на цели не подтверждено ничем.
   */
  it("e2k SMODX при нулевом делителе — не проверено", () => {
    expect(
      "не проверено: exc_div измерен для SDIVs, для SMODX измерения нет",
      "статус назван строкой",
    ).toContain("не проверено");
  });
});
