describe("канон: деление на ноль не ловится попробовать/поймать", () => {
  // Негативный контроль: убрать `throw new InterpreterError` из case "div"/"idiv"/
  // "rem" в src/runtime/vm/interpreter.ts — любая из проверок ниже краснеет, потому
  // что вместо отказа придёт значение (Infinity/NaN).

  it("div при нулевом делителе — отказ VM", async () => {
    await expect(run(wrap(["вернуть 1 div 0"]))).rejects.toThrow(InterpreterError);
  });

  it("/ при нулевом делителе — отказ VM", async () => {
    await expect(run(wrap(["вернуть 1 / 0"]))).rejects.toThrow(InterpreterError);
  });

  it("% при нулевом делителе — отказ VM", async () => {
    await expect(run(wrap(["вернуть 1 % 0"]))).rejects.toThrow(InterpreterError);
  });

  /**
   * Главное утверждение канона. `попробовать` перехватывает ТОЛЬКО `выбросить`
   * (опкод `throw`): обработчик кладётся в `exceptionHandlerStack` и срабатывает
   * на опкоде, а машинная ошибка приходит JS-исключением из тела интерпретатора.
   * Значит поймать её нечем — и это НЕ дефект VM, а свойство: смешивать
   * «ошибку языка» (`выбросить`) и «отказ машины» (деление на ноль) нельзя.
   *
   * Негативный контроль: научить `try_begin`/`throw` перехватывать JS-исключения
   * вокруг арифметики — проверки краснеют, потому что `поймать` вернёт 777.
   */
  for (const [op, expr] of [
    ["div", "1 div 0"],
    ["/", "1 / 0"],
    ["%", "1 % 0"],
  ] as const) {
    it(`${op} внутри попробовать всё равно не ловится`, async () => {
      const src = [
        "модуль Т",
        "процедура главная()",
        "  попробовать",
        `    вернуть ${expr}`,
        "  поймать ошибка",
        "    вернуть 777",
        "  конец_попробовать",
        "конец_процедуры",
      ].join("\n");
      // Именно отказ, а не 777: если бы ловилось, вернулось бы 777.
      await expect(run(src)).rejects.toThrow(InterpreterError);
      const c = compileSource(src, { filename: "канон.osnova" });
      expect(c.compilerSuccess, "программа с попробовать собирается — отказ приходит в рантайме").toBe(true);
    });
  }

  it("контроль: попробовать/поймать ЛОВИТ выбросить — механизм перехвата жив", async () => {
    // Без этой проверки предыдущие ничего не доказывали бы: «не ловится» было бы
    // верно и для сломанного перехвата вообще.
    const src = [
      "модуль Т",
      "процедура главная()",
      "  попробовать",
      '    выбросить "беда"',
      "  поймать ошибка",
      "    вернуть 777",
      "  конец_попробовать",
      "  вернуть 0",
      "конец_процедуры",
    ].join("\n");
    expect(await run(src)).toBe(777);
  });
});

