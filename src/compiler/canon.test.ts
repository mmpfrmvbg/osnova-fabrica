describe("канон: длина строки считается в КОДОВЫХ ТОЧКАХ", () => {
  // История в одной строке, чтобы дрейф был виден: канон §13.6 говорил «единицы UTF-16»
  // (это было ИЗМЕРЕНО 2026-09-26), владелец 2026-09-28 решил считать КОДОВЫЕ ТОЧКИ —
  // как Python и как думает человек. Для BMP расхождения нет (привет=6, ёж=2) — потому
  // переход и не ломал существующие программы; для астральных есть: 👍 было 2, стало 1.
  // Негативный контроль: вернуть `s.length` в case "система.строка.длина" — краснеют
  // проверки с 👍 и с семьями (они и есть различающие).

  it("длина(\"привет\") = 6 — BMP, расхождения между единицами нет", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("привет")']))).toBe(6);
  });

  it("длина(\"ёж\") = 2", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("ёж")']))).toBe(2);
  });

  it("длина(\"👍\") = 1 — КОДОВАЯ ТОЧКА, а единиц UTF-16 две", async () => {
    expect(await run(wrap(['вернуть система.строка.длина("👍")']))).toBe(1);
    // Обе единицы названы рядом: вторая строка — свидетель того, что величины РАЗНЫЕ,
    // поэтому проверка различает реализацию, а не подтверждает любую.
    expect("👍".length, "единиц UTF-16 в 👍").toBe(2);
  });

  it("длина(семья 👨‍👩‍👧) = 5 — кодовые точки, но не графемы (1)", async () => {
    // Графемы каноном не считаются: 👨‍👩‍👧 — одна графема, но пять кодовых точек
    // (три символа и два ZWJ). Это и есть граница решения владельца.
    expect(await run(wrap(['вернуть система.строка.длина("👨‍👩‍👧")']))).toBe(5);
    expect("👨‍👩‍👧".length, "единиц UTF-16 в семье").toBe(8);
  });

  it("NFD-разложение не нормализуется: «е + U+0308 + ж» = 3 кодовые точки", async () => {
    // Нормализация (NFC/NFD) не выполняется — как в Python: две кодовые точки у «е + U+0308».
    expect(await run(wrap(['вернуть система.строка.длина("е\u0308ж")']))).toBe(3);
  });

  it("подстрока не рвёт суррогатную пару: подстрока(\"👍\", 0, 1) = \"👍\"", async () => {
    // До правки здесь возвращалась половина пары (невалидный текст).
    expect(await run(wrap(['вернуть система.строка.подстрока("👍", 0, 1)']))).toBe("👍");
    expect(await run(wrap(['вернуть система.строка.подстрока("👍x", 1, 2)']))).toBe("x");
  });

  it("индекс поиска — в кодовых точках: найти(\"👍x\", \"x\") = 1, а не 2", async () => {
    expect(await run(wrap(['вернуть система.строка.найти("👍x", "x")']))).toBe(1);
  });

  it("порядок строк — по кодовым точкам: \"👍\" > \"\\uFFFD\" (в UTF-16 было наоборот)", async () => {
    // Класс расхождения не про длину: суррогаты в UTF-16 стоят НИЖЕ 0xE000–0xFFFF, а кодовые
    // точки астральных символов — ВЫШЕ. Поэтому пара «эмодзи против U+FFFD» различает единицы.
    expect(await run(wrap(['вернуть "👍" > "\uFFFD"']))).toBe(true);
    expect(await run(wrap(['вернуть "👍" < "\uFFFD"']))).toBe(false);
  });
});

