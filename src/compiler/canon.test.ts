describe("канон: смешение типов — аннотации зарезервированы, арифметика одна (float64)", () => {
  // Матрицу нельзя было записать до измерения. ИЗМЕРЕНО: аннотация типа не
  // участвует в арифметике вовсе — `Целое32 + Число` даёт 7.5, `Целое32 / Целое32`
  // даёт 3.5 (вещественное деление), `Целое32 div Целое32` даёт 3.
  // Негативный контроль: заставить `div`/`add` смотреть на аннотации (обёртка
  // Целое32 перед сложением) — краснеют строки сложения и деления.

  it("Целое32 + Число = 7.5 (аннотация не сужает)", async () => {
    expect(await run(wrap(["пусть а: Целое32 = 5", "пусть б: Число = 2.5", "вернуть а + б"]))).toBe(7.5);
  });

  it("Число + Целое32 = 7.5 (порядок не важен)", async () => {
    expect(await run(wrap(["пусть а: Число = 2.5", "пусть б: Целое32 = 5", "вернуть а + б"]))).toBe(7.5);
  });

  it("Целое32 < Число = истина (сравнение числовое, без приведения к целому)", async () => {
    expect(await run(wrap(["пусть а: Целое32 = 5", "пусть б: Число = 5.5", "вернуть а < б"]))).toBe(true);
  });

  it("Целое32 / Целое32 = 3.5 — `/` вещественное даже для целых", async () => {
    expect(await run(wrap(["пусть а: Целое32 = 7", "пусть б: Целое32 = 2", "вернуть а / б"]))).toBe(3.5);
  });

  it("Целое32 div Целое32 = 3 — `div` целочисленное", async () => {
    expect(await run(wrap(["пусть а: Целое32 = 7", "пусть б: Целое32 = 2", "вернуть а div б"]))).toBe(3);
  });

  it("Целое64 — АННОТАЦИЯ, сводящаяся к Число: байткод совпадает с программой без неё", async () => {
    // Решение владельца: Целое64 вводится тем же способом, каким существует
    // Целое32 — аннотацией к Число. Отдельной 64-битной арифметики нет.
    //
    // Проверяется РАВЕНСТВОМ БАЙТКОДА, а не чтением списка типов: если бы
    // аннотация участвовала в кодогене, байткод разошёлся бы. Тем же приёмом
    // проверен Целое32 — иначе «сводится к Число» осталось бы утверждением из
    // комментария.
    //
    // Негативный контроль: убрать Целое64 из PRIMITIVE_FIELD_TYPES
    // (`src/compiler/compiler.ts:477`) — компиляция падает с «Тип не объявлен»,
    // и проверка краснеет.
    const withAnn = compileSource(wrap(["пусть а: Целое64 = 5", "вернуть а + 1"]), {
      filename: "ц64.osnova",
    });
    expect(withAnn.compilerSuccess, "аннотация Целое64 принимается").toBe(true);
    const without = compileSource(wrap(["пусть а = 5", "вернуть а + 1"]), { filename: "без.osnova" });
    const strip = (m: unknown) => JSON.stringify({ ...(m as object), moduleName: "" });
    expect(strip(withAnn.module), "байткод тот же — аннотация в кодоген не входит").toBe(
      strip(without.module),
    );
  });

  it("Целое64 и Целое32 неразличимы по байткоду — обе аннотации к Число", async () => {
    const a64 = compileSource(wrap(["пусть а: Целое64 = 5", "вернуть а * 2"]), { filename: "a64.osnova" });
    const a32 = compileSource(wrap(["пусть а: Целое32 = 5", "вернуть а * 2"]), { filename: "a32.osnova" });
    const strip = (m: unknown) => JSON.stringify({ ...(m as object), moduleName: "" });
    expect(strip(a64.module)).toBe(strip(a32.module));
  });

  it("аннотация Целое64 не включает обёртку — числа по-прежнему float64", async () => {
    // Обещание «64 бита» не должно читаться как «есть 64-битная арифметика».
    const src = wrap(["пусть а: Целое64 = 2000000000", "пусть б: Целое64 = 2000000000", "вернуть а + б"]);
    expect(await run(src)).toBe(4000000000);
  });

  it("аннотация Целое32 сводится к Число (заявленная замена)", async () => {
    // `src/compiler/compiler.ts:480`: Целое32 → Число. Проверяется через то, что
    // программа с Целое32 и без аннотации даёт ОДИН И ТОТ ЖЕ байткод.
    const withAnn = compileSource(wrap(["пусть а: Целое32 = 5", "вернуть а + 1"]), { filename: "a.osnova" });
    const without = compileSource(wrap(["пусть а = 5", "вернуть а + 1"]), { filename: "b.osnova" });
    const strip = (m: unknown) => JSON.stringify({ ...(m as object), moduleName: "" });
    expect(strip(withAnn.module)).toBe(strip(without.module));
  });
});

