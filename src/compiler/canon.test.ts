describe("канон: знак остатка — по делимому, частное — отсечение к нулю", () => {
  // Числа, не слова: канон обязан называть знак числом.
  // Негативный контроль: заменить `a % b` на `((a % b) + b) % b` (знак по
  // делителю, как в Python) — краснеют строки с отрицательным делимым.

  const CASES: ReadonlyArray<readonly [string, number]> = [
    ["7 % 3", 1],
    ["(0 - 7) % 3", -1],
    ["7 % (0 - 3)", 1],
    ["(0 - 7) % (0 - 3)", -1],
    // Частное — отсечение к нулю (не пол вниз): -7/3 даёт -2, а не -3.
    ["(0 - 7) div 3", -2],
    ["7 div (0 - 3)", -2],
    ["(0 - 6) div 3", -2],
  ];

  for (const [expr, expected] of CASES) {
    it(`${expr} = ${expected}`, async () => {
      expect(await run(wrap([`вернуть ${expr}`]))).toBe(expected);
    });
  }

  /**
   * ОТРИЦАТЕЛЬНЫЙ НОЛЬ — измеренный факт, а не деталь.
   *
   * Когда делимое отрицательно и делится нацело, остаток равен **−0**:
   * `(0 - 6) % 3` → `-0`. Это JS-семантика `%`, и она доходит до языка.
   * Практические следствия, названные числом:
   *   `-0 === 0` истинно (обычные сравнения его не различают),
   *   `Object.is(-0, 0)` ложно (различает),
   *   `String(-0)` даёт "0" — при выводе неотличим.
   * Канон обязан это сказать: «остаток при нацело делящемся отрицательном
   * делимом равен −0, и это неотличимо от 0 во всех операциях языка».
   * Негативный контроль: добавить `if (r === 0) r = 0` в case "rem" — краснеет
   * проверка Object.is ниже.
   */
  it("(0 - 6) % 3 даёт ОТРИЦАТЕЛЬНЫЙ ноль", async () => {
    const v = await run(wrap(["вернуть (0 - 6) % 3"]));
    expect(Object.is(v, -0), "это именно -0").toBe(true);
    expect(v === 0, "при этом -0 == 0 — обычные сравнения не различают").toBe(true);
  });

  it("тождество a div b * b + a % b == a выполняется при любых знаках", async () => {
    for (const [a, b] of [
      [7, 3],
      [-7, 3],
      [7, -3],
      [-7, -3],
    ] as const) {
      const src = wrap([
        `пусть а = ${a < 0 ? `(0 - ${-a})` : a}`,
        `пусть б = ${b < 0 ? `(0 - ${-b})` : b}`,
        "вернуть а div б * б + а % б",
      ]);
      expect(await run(src), `тождество при a=${a}, b=${b}`).toBe(a);
    }
  });

  /**
   * РАСХОЖДЕНИЕ VM ↔ e2k — названо, не спрятано.
   *
   * VM даёт остаток со знаком делимого (−1), и это совпадает с руководством МЦСТ
   * §10.3.3. Рантайм остатка e2k (`smodx`) на измеренных случаях даёт ДРУГОЕ:
   * `(-7) % 3` → **0**. Измерено и записано машинной плоскостью:
   * `docs/hardware-debt.md` §3.21, проба `.tmp/math-probe.ts`, оракул
   * `src/e2k/e2kMathQemu.test.ts`. Причина — форма операнда `SMODX`
   * (`ARGS_DSS`, 64-битное делимое), не разложена.
   *
   * Здесь это НЕ проверяется (чужая плоскость, прогон требует QEMU-e2k) и потому
   * помечено «не проверено» в этом файле: канон обязан сказать, что паритет
   * VM↔e2k по знаку остатка НЕ подтверждён.
   */
  it("паритет знака остатка с e2k — не проверяется здесь (пометка для канона)", () => {
    expect(
      "не проверено: e2k smodx для отрицательных делимых расходится с VM (§3.21)",
      "статус зафиксирован строкой, а не молчанием",
    ).toContain("не проверено");
  });
});

