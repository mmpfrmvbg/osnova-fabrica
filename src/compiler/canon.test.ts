describe("канон: кодировка исходника — LF/CRLF/CR принимаются, BOM отвергается", () => {
  // Негативный контроль: научить лексер пропускать U+FEFF — краснеет проверка
  // «BOM отвергается»; убрать обработку \r — краснеют CRLF/CR.

  const base = ["модуль Т", "процедура главная()", "  вернуть 42", "конец_процедуры"].join("\n");

  it("LF принимается и исполняется", async () => {
    expect(await run(base)).toBe(42);
  });

  it("CRLF принимается и исполняется", async () => {
    expect(await run(base.replace(/\n/g, "\r\n"))).toBe(42);
  });

  it("одиночный CR принимается", async () => {
    const src = base.replace(/\n/g, "\r");
    const c = compileSource(src, { filename: "cr.osnova" });
    expect(c.lexerErrors, "лексер не спотыкается на CR").toEqual([]);
    expect(c.compilerSuccess).toBe(true);
  });

  it("BOM в начале отвергается — и это ОТКАЗ, а не тихое игнорирование", async () => {
    const src = "\uFEFF" + base;
    const { errors } = tokenize(src);
    expect(errors.length, "лексер сообщает о неизвестном символе").toBeGreaterThan(0);
    const c = compileSource(src, { filename: "bom.osnova" });
    expect(c.compilerSuccess, "BOM ломает сборку — канон обязан это признать").toBe(false);
  });

  it("BOM+CRLF тоже отвергается (сочетание не спасает)", () => {
    const c = compileSource("\uFEFF" + base.replace(/\n/g, "\r\n"), { filename: "bomcrlf.osnova" });
    expect(c.compilerSuccess).toBe(false);
  });

  it("лексер и парсер на LF/CRLF дают одинаковый разбор", () => {
    const lf = parse(tokenize(base).tokens, { filename: "lf.osnova" });
    const crlf = parse(tokenize(base.replace(/\n/g, "\r\n")).tokens, { filename: "crlf.osnova" });
    expect(lf.errors).toEqual([]);
    expect(crlf.errors).toEqual([]);
    expect(crlf.ast!.modules[0]!.procedures.map((p) => p.name)).toEqual(
      lf.ast!.modules[0]!.procedures.map((p) => p.name),
    );
  });
});

