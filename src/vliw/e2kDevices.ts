/**
 * Класс операции e2k для опкода Основа.
 *
 * ЭТО НАШЕ ОТОБРАЖЕНИЕ. В руководстве перечислены классы операций e2k
 * (`muls`, `shls`, `adds`, `fadd`, `fmul`, `ld`, `st`, `andp`, `ct` …), а не
 * опкоды Основа — их там нет вовсе. Соответствие выведено из описаний:
 * целочисленные add/sub — класс Int; mul отнесён к Fp, потому что документ
 * прямо говорит: «Fp вещественные операции сложения и умножения fadd, fmul, **а
 * также целочисленные операции mul**» (стр. 71); деление — Fdiv.
 */
export function opClassOf(op: string): OpClass {
  switch (op) {
    case "add":
    case "sub":
    case "and":
    case "or":
    case "not":
      return "int";
    case "mul":
      // Стр. 71: «Fp … а также целочисленные операции mul».
      return "fp";
    case "div":
    case "rem":
      // Стр. 71: Fdiv; для remainder отдельной строки в таблице нет —
      // консервативно относим к тому же классу деления (см. отчёт).
      return "fdiv32";
    case "eq":
    case "ne":
    case "lt":
    case "le":
    case "gt":
    case "ge":
      return "cmp_to_logic";
    case "const":
    case "const.true":
    case "const.false":
    case "const.null":
      return "int";
    case "local.get":
      // Чтение локальной переменной процедуры — НЕ обращение к памяти: у
      // стековой VM локали лежат в массиве кадра (`frame.locals`). Для e2k это
      // операция над регистром/слотом кадра, а не `ld`.
      return "int";
    case "obj.get":
      // Обращение к полю объекта — настоящее чтение из памяти (объект в куче).
      // Уровень кэша в байткоде Основа не выражен, поэтому планировщик по
      // умолчанию считает попадание в L1 — ровно то, что документ обещает про
      // реальный планировщик: «Планировщик всегда будет планировать чтение из
      // L1, если только от программиста не было подсказки не обращаться по
      // чтению в L1» (стр. 71).
      return "ld_l1";
    case "local.set":
      // ВАЖНО: это НЕ запись в память. `local.set` в Основе — присваивание
      // локальной переменной процедуры, а у стековой VM локали живут в массиве
      // кадра (`frame.locals`), к памяти отношения не имеющего. Отнести его к
      // классу `store` было бы ложной аналогией: это сломало упаковку, потому
      // что слот памяти в формате Основа один, а `local.set` в коде частый.
      return "int";
    case "obj.set":
      // А вот это — настоящая запись в память: объект живёт в куче, и запись
      // поля требует устройства с возможностью ST (только АЛУ2 и АЛУ5, стр. 56).
      return "store";
    case "jmp":
    case "jmp_if":
    case "jmp_if_not":
      return "disp_to_ct";
    case "ret":
      return "return_to_ct";
    case "call":
    case "invoke":
      return "to_ct";
    default:
      return "int";
  }
}

/** Умеет ли канал исполнить класс операции. */
export function channelCanRun(ch: ChannelId, cls: OpClass): boolean {
  const alu = (CHANNELS.ALU as readonly string[]).includes(ch)
    ? UNITS[ch as AluId]
    : undefined;
  if (!alu) {
    // Не-АЛУ каналы: передача управления — только СТ; предикаты — только PL.
    if (ch === CHANNELS.CT) {
      return (
        cls === "to_ct" ||
        cls === "disp_to_ct" ||
        cls === "return_to_ct" ||
        cls === "movtd_to_ct"
      );
    }
    if ((CHANNELS.PL as readonly string[]).includes(ch)) {
      return cls === "cmp_to_logic" || cls === "logic_to_logic";
    }
    return false;
  }
  switch (cls) {
    case "int":
    case "int_combined":
      return alu.int;
    case "store":
      // Стр. 56: запись в память — только АЛУ2 и АЛУ5.
      return alu.store;
    case "fp":
    case "fp_combined":
      return alu.fp;
    case "fdiv32":
    case "fdiv64":
      // Стр. 56: деление и корень — только в АЛУ5.
      return alu.divsqrt;
    case "ld_l1":
    case "ld_l2":
    case "ld_l3":
    case "ld_mem":
      // Стр. 56: чтение — АЛУ0, АЛУ2, АЛУ3, АЛУ5 (в АЛУ1/АЛУ4 его нет).
      return alu.load;
    case "cmp_to_logic":
    case "logic_to_logic":
      return alu.cmp;
    case "qual":
      // Предикатное устройство, не АЛУ.
      return false;
    default:
      return false;
  }
}

/** Каналы, способные исполнить операцию, в детерминированном порядке. */
export function channelsFor(op: string): ChannelId[] {
  return channelsForClass(opClassOf(op));
}

/**
 * Каналы для **класса** операции.
 *
 * Нужен там, где класс уже известен напрямую (регистровый кодоген,
 * `reorderScheduler`), — чтобы не проходить через имя стекового опкода.
 *
 * @param preferCluster желаемый кластер: каналы этого кластера идут первыми.
 *   Так планировщик держит зависимые операции в одном кластере, где байпас
 *   работает (стр. 194). Если `undefined` — порядок естественный.
 */
export function channelsForClass(
  cls: OpClass,
  preferCluster?: AluCluster,
): ChannelId[] {
  const out: ChannelId[] = [];
  if (
    cls === "to_ct" ||
    cls === "disp_to_ct" ||
    cls === "return_to_ct" ||
    cls === "movtd_to_ct"
  ) {
    // Стр. 57: «В одной команде можно исполнить не более одной операции передачи
    // управления и не более одной операции подготовки перехода.»
    return [CHANNELS.CT];
  }
  for (const ch of ALL_CHANNELS) {
    if (channelCanRun(ch, cls)) out.push(ch);
  }
  if (preferCluster === undefined) return out;
  // Стабильная сортировка: предпочитаемый кластер вперёд, порядок внутри групп
  // сохраняется (детерминизм расписания).
  const preferred = out.filter((ch) => clusterOf(ch) === preferCluster);
  const other = out.filter((ch) => clusterOf(ch) !== preferCluster);
  return [...preferred, ...other];
}

