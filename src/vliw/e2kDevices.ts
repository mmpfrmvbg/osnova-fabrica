/** Возможности одного канала: что он умеет исполнять. */
export interface UnitCapability {
  /** Целочисленная арифметика/побитовые/сдвиги (Int). */
  int: boolean;
  /** Вещественная арифметика (FP). */
  fp: boolean;
  /** Сравнения (Cmp). */
  cmp: boolean;
  /** Чтение из памяти (LD). */
  load: boolean;
  /** Запись в память (ST). */
  store: boolean;
  /** Упакованные векторы (Vect). */
  vect: boolean;
  /** Деление и квадратный корень (Div/Sqrt). */
  divsqrt: boolean;
}

