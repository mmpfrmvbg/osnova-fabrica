/**
 * Задержка операции с учётом типа потребителя.
 *
 * Это ответ на прямое требование документа (стр. 71): «при размещении очередной
 * операции в широкой команде выдержать длительности операций-предшественников,
 * которые вырабатывают ее аргументы».
 *
 * @param cls класс операции-производителя
 * @param consumer вид потребителя (для Cmp/логических задержка зависит от него)
 */
export function latencyFor(cls: OpClass, consumer: ConsumerKind = "arith"): number {
  switch (cls) {
    case "cmp_to_logic":
      if (consumer === "logic") return LATENCY.cmp_to_logic;
      if (consumer === "qualified") return LATENCY.qual;
      if (consumer === "ct") return LATENCY.to_ct;
      return LATENCY.cmp_to_logic;
    default:
      return LATENCY[cls];
  }
}

