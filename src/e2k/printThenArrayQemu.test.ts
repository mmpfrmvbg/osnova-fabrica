/**
 * D12: ЧТЕНИЕ ЭЛЕМЕНТА СПИСКА ПОСЛЕ ПЕЧАТИ — оракул на модели (и предмет, который на ней НЕВИДИМ).
 *
 * # Предмет
 *
 * Репро атома — шесть строк: список, `вывести 99`, `а[0]`, `а[1]`, `длина а`. На ЖЕЛЕЗЕ (E8C2,
 * 2026-11-08) оно давало `99 3 10 3` вместо `99 10 20 3`: каждое чтение после печати сдвигалось на
 * элемент, потому что системный вызов зануляет `%b[12..15]` вызывающего (механизм и прямой
 * инструкционный зонд — `src/e2k/arrayBlockRestore.test.ts`, `src/e2k/arrayRuntime.ts#arrayBlockRestore`).
 * `создать`/`добавить` после печати падали кодом **139** (потерян адрес ячейки кучи).
 *
 * # ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ И ЧЕГО НЕ ДОКАЗЫВАЕТСЯ
 *
 * Модель этот закон НЕ воспроизводит (замер: один и тот же вендорский asm-зонд даёт на модели `8`,
 * на железе `0`), поэтому оракул на модели зелен **и до правки, и после** — он сторож ПОВЕДЕНИЯ
 * (печать не должна менять чтение), а не сторож дефекта. Дефект стережёт структурный
 * `src/e2k/arrayBlockRestore.test.ts` (N = 1), а исполнение на цели — `docs/hardware-debt.md` §3.187:
 * 5/5 проб-репро и полный лексер (342 токена) совпали с эталоном модели побайтово.
 *
 * Названо, а не сглажено: если однажды модель начнёт занулять окно вызываемого так же, как железо
 * (правка порта = пересборка = перемер всех чисел), этот файл покраснеет на СТАРОЙ редакции сайта и
 * станет сторожем самого дефекта — и это будет хорошая новость.
 *
 * Файл зависит от внешнего ресурса (`qemu-e2k` под шимом) и живёт в шлюзе `npm run gate:qemu`
 * (`docs/verification-debt.md`, случай 12).
 */
import { beforeAll, describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu, type QemuRun } from '../scripts/e2kQemuExec';

const КЭШ = fs.mkdtempSync(path.join(os.tmpdir(), 'osnova-d12-'));

/** Один прогон: программа на v3 → байты → ELF → QEMU. Возврат — вывод и код. */
function прогон(строки: readonly string[]): QemuRun {
  const исходник = `${строки.join('\n')}\n`;
  const разбор = parseV3(исходник, 'проба.osnova');
  expect(разбор.errors, `разбор: ${JSON.stringify(разбор.errors.slice(0, 2))}`).toHaveLength(0);
  const итог = loweredProgram(исходник, {
    filename: 'проба.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (!итог.ок) throw new Error(`понижение отказало: ${итог.отказ.причина}`);
  const elf = path.join(КЭШ, `проба-${String(исходник.length)}.elf`);
  fs.writeFileSync(elf, buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
    writable: true,
    extraMemory: WRITE_ZONE_EXTRA_MEMORY,
  }).bytes);
  return runInQemu(elf, { shim: true, timeoutMs: 60_000 });
}

const СТРОКИ = (тело: readonly string[]): readonly string[] => ['действие главная()', ...тело, 'конец'];

describe('D12: печать не смещает чтение элемента списка', () => {
  beforeAll(() => buildShim());

  it('шесть строк: 99, 10, 20, 3 — печать перед первым чтением', () => {
    const итог = прогон(СТРОКИ([
      '  пусть а: Список Число = [10, 20, 30]',
      '  вывести 99',
      '  вывести а[0]',
      '  вывести а[1]',
      '  вывести длина а',
    ]));
    expect(итог.status).toBe(0);
    expect(итог.stdout).toBe('99\n10\n20\n3\n');
  });

  it('контроль: те же чтения БЕЗ печати перед ними', () => {
    const итог = прогон(СТРОКИ([
      '  пусть а: Список Число = [10, 20, 30]',
      '  вывести а[0]',
      '  вывести а[1]',
      '  вывести длина а',
    ]));
    expect(итог.status).toBe(0);
    expect(итог.stdout).toBe('10\n20\n3\n');
  });

  it('печать перемежается с чтениями: каждый сайт возвращает блок заново', () => {
    const итог = прогон(СТРОКИ([
      '  пусть а: Список Число = [10, 20, 30]',
      '  вывести 99',
      '  вывести а[0]',
      '  вывести 98',
      '  вывести а[1]',
      '  вывести 97',
      '  вывести а[2]',
    ]));
    expect(итог.status).toBe(0);
    expect(итог.stdout).toBe('99\n10\n98\n20\n97\n30\n');
  });

  it('второй список после печати: адрес ячейки кучи цел (на железе было 139)', () => {
    const итог = прогон(СТРОКИ([
      '  пусть а: Список Число = [10, 20, 30]',
      '  вывести 99',
      '  пусть б: Список Число = [7, 8]',
      '  вывести б[0]',
      '  вывести б[1]',
      '  вывести длина б',
    ]));
    expect(итог.status).toBe(0);
    expect(итог.stdout).toBe('99\n7\n8\n2\n');
  });
});
