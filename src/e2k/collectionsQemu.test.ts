/**
 * ОРАКУЛ КОЛЛЕКЦИЙ НА `brk` — НАПИСАН ПЕРВЫМ И ОБЯЗАН БЫТЬ КРАСНЫМ (§2.1, §3.95.3).
 *
 * Предмет: **растущий массив записей** — первая и единственная коллекция под DF (тысячи гномов:
 * массив, который пополняется и не имеет фиксированной длины). Память берётся у `brk`: он ИЗМЕРЕН и
 * работает (§3.94: `brk(0)` → `brk(+8192)` → запись/чтение = 43), а `mmap`, создающий отображение,
 * виснет в шиме модели и в этот заход не входит.
 *
 * # Что спрашивается (подпись владельца, §3.95.3)
 *
 * | операция | ожидание |
 * |---|---|
 * | `выделить(ёмкость) → Число` | базовый адрес, по нему пишется и читается |
 * | `положить(база, индекс, значение)` | элемент записан |
 * | `взять(база, индекс) → значение` | прочитано ровно записанное |
 * | `расширить(база, новая_ёмкость) → Число` | переезд через `brk`, копирование, НОВЫЙ адрес |
 * | **сквозной: 100 записей**, чтение каждой, сумма | **замеренное число** |
 *
 * # Почему в сквозном прогоне значения выбраны именно так
 *
 * Канал возврата — 8-битный (код возврата процесса несёт младший байт, `AGENTS.md`), поэтому сумму
 * надо ВЫБИРАТЬ, а не брать как придётся: она обязана различать «100 записей прочитаны» и «99».
 * Берём элемент записи `1 + (номер mod 7)` — то есть 1..7; сумма 100 записей известна точно, а
 * пропуск последнего элемента меняет её на 1..7, и по модулю 256 это видно.
 *
 * # ЭТАЛОН СЧИТАЕТСЯ, А НЕ ЗАПИСАН ЧИСЛОМ
 *
 * Сумма 100 записей считается ЗДЕСЬ ЖЕ из того же правила (`1 + (номер mod 7)`), а не берётся из
 * головы: разойдись правило и ожидание — это находка, а не совпадение.
 *
 * # Где спрашивается
 *
 * И у РЕГИСТРОВОЙ VM (эталон языка), и у МОДЕЛИ e2k — путь до цели обязателен: коллекция, которая
 * работает только на VM, цели не достигает (§3.30: не измеримо — не считается).
 */
import { describe, it, expect } from 'vitest';
import { regModuleOf } from '../vliw/regOracle';
import { RegVM } from '../runtime/vm/reginterpreter';
import { createDefaultInvokeHandler } from '../runtime/vm/interpreter';
import { resolveEntryIndex } from '../oracle/parity';
import { runOnE2k } from '../scripts/e2kProgramRun';
import { buildShim } from '../scripts/e2kQemuExec';
import { COLLECTION_INVOKES } from '../runtime/vm/collectionCalls';
import { COLLECTION_BRK_REFUSAL_TEXT } from './collectionsRuntime';
import { REFUSAL_CODE } from './refusalBlock';

const shim = buildShim();

/**
 * Правило записи: значение элемента по номеру — `номер + 1`, то есть 1..100.
 *
 * ОДНО правило на программу, эталон и ожидание: программа пишет `номер + 1`, эталон считает сумму
 * той же формулой, и разойдись они — это находка, а не совпадение.
 *
 * Числа выбраны так, чтобы 8-битный канал возврата РАЗЛИЧАЛ потерю записи: сумма 1..100 = 5050,
 * по модулю 256 это **186**, а без последней записи (1..99 = 4950) — **86**.
 */
const значение = (номер: number): number => номер + 1;

/** То же правило в виде текста программы — чтобы правило было одно, а не два похожих. */
const значениеВыражение = 'номер + 1';
const правилоСловами = '`номер + 1` (1..100)';

/** Эталон сквозного прогона: сумма 100 записей — вычисляется, а не берётся числом. */
function эталонСуммы(записей: number): number {
  let сумма = 0;
  for (let номер = 0; номер < записей; номер++) сумма += значение(номер);
  return сумма;
}

/** Модуль: заголовок программы в диалекте, которым пользуется стенд (`regModuleOf`). */
const модуль = (тело: string): string => `модуль Кол\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/** Значение на РЕГИСТРОВОЙ VM — эталон языка. */
async function наVM(source: string): Promise<number> {
  const built = regModuleOf(source);
  expect(built, 'программа обязана компилироваться').not.toBeNull();
  const entry = resolveEntryIndex(built!.module.procedures, undefined) ?? 0;
  const vm = new RegVM(built!.module, {
    invoke: createDefaultInvokeHandler(),
    // АРНОСТЬ ПЕРЕДАЁТСЯ ЯВНО, И ЭТО НАЗВАНО, А НЕ СПРЯТАНО. `система.коллекция.*` в реестре языка
    // (`src/compiler/language-registry.ts`) ещё НЕ объявлены, поэтому `getInvokeArgCount` их не
    // знает и VM отказала бы «Unknown invoke». Механизм для ровно этого случая в языке есть:
    // `extraInvokes` — «хост-вызовы вне реестра `система.*`, не пишутся в language-registry»
    // (`src/runtime/vm/interpreter.ts`). Арность приходит из того же источника, что у ЦЕЛИ
    // (`src/e2k/collectionsRuntime.ts` читает её оттуда же), поэтому двух эталонов не заводится.
    // Когда канон объявит операции, эту строку можно убрать — она станет избыточной, а не неверной.
    extraInvokes: COLLECTION_INVOKES,
    maxSteps: 2_000_000,
  });
  return Number(await vm.runProcedure(entry, []));
}

/** Ответ МОДЕЛИ: код возврата, отказы и вывод — три канала, а не один. */
function наМодели(
  source: string,
  файл: string,
): { status: number | undefined; refused: readonly string[]; output: string } {
  const прогон = runOnE2k(source, файл);
  return {
    status: прогон.status,
    refused: прогон.refused.map((item) => `${item.code} ${item.reason}`),
    // ВЫВОД — ОТДЕЛЬНЫМ ПОЛЕМ. Названный отказ ПРОГОНА наблюдается кодом и строкой (как у арены,
    // `src/e2k/arenaQemu.test.ts`), а `refused` — канал СТАТИЧЕСКИХ отказов понижения. Смешение
    // этих двух каналов и было дефектом контроля 1 (случай 33 реестра проверяемости).
    output: прогон.output,
  };
}

describe('коллекции на brk: оракул владельца (написан до реализации — красный)', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('выделить(ёмкость): база возвращается, по ней пишется и читается', async () => {
    const source = модуль(
      ['  пусть база = система.коллекция.выделить(4)', '  система.коллекция.положить(база, 0, 42)', '  вернуть система.коллекция.взять(база, 0)'].join('\n'),
    );
    expect(await наVM(source), 'эталон языка').toBe(42);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-alloc.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, 'модель обязана дать то же').toBe(42);
  });

  it('положить и взять: элемент читается ровно записанным, на любом месте', async () => {
    const source = модуль(
      [
        '  пусть база = система.коллекция.выделить(8)',
        '  система.коллекция.положить(база, 0, 11)',
        '  система.коллекция.положить(база, 7, 99)',
        '  вернуть система.коллекция.взять(база, 0) + система.коллекция.взять(база, 7)',
      ].join('\n'),
    );
    expect(await наVM(source), 'эталон языка: 11 + 99').toBe(110);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-put-get.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, 'модель: 110 mod 256').toBe(110);
  });

  it('расширить: НОВЫЙ адрес, старые элементы целы', async () => {
    const source = модуль(
      [
        '  пусть база = система.коллекция.выделить(2)',
        '  система.коллекция.положить(база, 0, 5)',
        '  система.коллекция.положить(база, 1, 6)',
        '  пусть новая = система.коллекция.расширить(база, 4)',
        '  система.коллекция.положить(новая, 3, 7)',
        '  вернуть система.коллекция.взять(новая, 0) + система.коллекция.взять(новая, 3)',
      ].join('\n'),
    );
    expect(await наVM(source), 'эталон языка: 5 + 7').toBe(12);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-grow.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, 'модель: 12').toBe(12);
  });

  it('СКВОЗНОЙ: 100 записей ЦИКЛОМ языка, чтение каждой, сумма — и на VM, и на модели', async () => {
    // ЦИКЛ ЗДЕСЬ НАСТОЯЩИЙ, и это исправление: первая редакция этой проверки генерировала 200
    // развёрнутых строк, потому что «цикл не компилируется». Факт был НЕВЕРЕН: падали мои пробы, а
    // не цикл — переменная в них называлась `и`, а `и` это ключевое слово (логическое «и»).
    // Замер: `.tmp/osnova-loop-isolate.ts` — v2 собирает `пока … конец_пока` (и пример
    // `47-факториал-итерацией` работает на модели именно так), v3 собирает тот же цикл с закрытием
    // `конец пока` (написание v2 он отвергает с указанием). Прибор показывал не то, что я думал.
    const ЗАПИСЕЙ = 100;
    const source = модуль(
      [
        `  пусть база = система.коллекция.выделить(${String(ЗАПИСЕЙ)})`,
        '  пусть номер = 0',
        `  пока номер < ${String(ЗАПИСЕЙ)}`,
        `    система.коллекция.положить(база, номер, ${значениеВыражение})`,
        '    номер = номер + 1',
        '  конец_пока',
        '  пусть сумма = 0',
        '  пусть чтение = 0',
        `  пока чтение < ${String(ЗАПИСЕЙ)}`,
        '    сумма = сумма + система.коллекция.взять(база, чтение)',
        '    чтение = чтение + 1',
        '  конец_пока',
        '  вернуть сумма',
      ].join('\n'),
    );

    const эталон = эталонСуммы(ЗАПИСЕЙ);
    expect(await наVM(source), `эталон языка: сумма ${String(ЗАПИСЕЙ)} записей по правилу ${правилоСловами}`).toBe(эталон);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-100.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    // Канал возврата 8-битный: сравниваем через модуль, и различие 100 против 99 он сохраняет.
    expect(status, `модель: сумма ${String(ЗАПИСЕЙ)} записей, эталон ${String(эталон)}`).toBe(эталон % 256);
    expect(эталон % 256, 'эталон обязан различать 100 и 99 записей').not.toBe(эталонСуммы(99) % 256);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 1: индекс >= ёмкости — НАЗВАННЫЙ ПРОГОННЫЙ отказ (код и строка)', () => {
    // КАНАЛ ИСПРАВЛЕН (решение владельца, 2026-10-02). Прежняя редакция читала `refused` — отказы
    // ПОНИЖЕНИЯ, то есть СТАТИЧЕСКИЙ канал, — тогда как комментарий самой проверки описывает факт
    // ПРОГОНА: «ёмкость лежит в заголовке и читается на исполнении». Проверка, читающая не свой
    // канал, не могла позеленеть иначе как при ОТСУТСТВИИ реализации: это случай 33 реестра
    // проверяемости, и он же — класс «прибор не различает то, что должен».
    //
    // Теперь спрашивается тем же каналом, что контроль 3 и что арена: КОД возврата и СТРОКА.
    // Формулировка проверки не ослаблена — она стала исполнимой.
    const source = модуль(
      ['  пусть база = система.коллекция.выделить(2)', '  вернуть система.коллекция.взять(база, 5)'].join('\n'),
    );
    const { status, output } = наМодели(source, 'collections-oob.elf');
    expect(status, 'код отказа — тот же, что у арены (231)').toBe(231);
    expect(output, 'выход за ёмкость обязан быть НАЗВАН, а не проглочен').toMatch(/ёмкост|индекс/u);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 2 (ПЕРЕМЕРЕН): `brk` не дал запрошенную границу — НАЗВАННЫЙ отказ с кодом', () => {
    // ПРЕЖНЯЯ РЕДАКЦИЯ ЗДЕСЬ НЕ ПРОВЕРЯЛА ТО, ЧТО ЗАЯВЛЯЛА, и дефектов было два:
    //
    // 1. Проба умирала РАНЬШЕ `brk` — на кодировке литерала: `movts` не несёт 2^40 (случай 35
    //    реестра проверяемости). Отказ ядра не наступал вовсе.
    // 2. Даже дойдя до `brk`, запрос 2^40 до ядра НЕ ДОХОДИТ ЦЕЛИКОМ: граница кладётся в оконный
    //    регистр командой `adds` (форма S — младшие 32 бита), так что выше 4 ГиБ запрос усечён.
    //    Прежнее «ядро отвечает -ENOMEM» — это замер `mmap` (§3.94.1), к `brk` не отнесённый: §2.5,
    //    замер против — утверждение снимается.
    //
    // ЧТО ИЗМЕРЕНО ВМЕСТО ЭТОГО (2026-10-03, `.tmp/probe-huge-alloc.ts` — прогон настоящих программ):
    //
    // | ёмкость | сдвиг границы | наблюдение |
    // |---|---|---|
    // | `2^24` | 128 МиБ | отказа НЕТ: программа кончается своим выходом |
    // | `2^28` | 2 ГиБ | отказ ЕСТЬ: код 231 и текст «куча не выросла — brk не дал запрошенную границу» |
    // | `2^31−1` | (запрос усечён) | на пути `выделить` — исключение модели (ip `0x100108`), на пути `расширить` — проходит; слой назван, разбор — долг |
    //
    // То есть проверка ответа `brk` НАБЛЮДАЕМА настоящей программой, и спрашивается она здесь —
    // ДВУМЯ наблюдениями: отказ при 2^28 и его отсутствие при 2^24. Без второго «231» не отличалось
    // бы от «отказывает всегда».
    if (shim === undefined) return;
    const отказ = наМодели(
      модуль(['  пусть база = система.коллекция.выделить(268435456)', '  вернуть 7'].join('\n')),
      'collections-brk-refused.elf',
    );
    expect(отказ.refused, `отказы понижения: ${отказ.refused.join('; ')}`).toEqual([]);
    expect(отказ.status, 'отказ ядра обязан стать НАЗВАННЫМ').toBe(REFUSAL_CODE);
    expect(отказ.output, 'и назвать ПАМЯТЬ, а не индекс и не ёмкость').toContain(COLLECTION_BRK_REFUSAL_TEXT);
    const прошла = наМодели(
      модуль(['  пусть база = система.коллекция.выделить(16777216)', '  вернуть 7'].join('\n')),
      'collections-brk-ok.elf',
    );
    expect(прошла.status, 'ёмкость 2^24 проходит — программа идёт своим выходом').toBe(7);
    expect(прошла.output, 'и отказа памяти при ней нет').not.toContain(COLLECTION_BRK_REFUSAL_TEXT);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 3: пропуск последнего элемента при копировании — сумма ДРУГАЯ', () => {
    // Контроль на САМ оракул: он обязан различать 100 и 99 записей в 8-битном канале. Если это
    // равенство когда-нибудь станет истинным, сквозная проверка перестанет что-либо доказывать,
    // и её надо будет переделать (другое правило значений или усилитель).
    const полная = эталонСуммы(100) % 256;
    const безПоследней = эталонСуммы(99) % 256;
    expect(полная, 'сумма 100 записей по модулю 256').not.toBe(безПоследней);
  });
});
