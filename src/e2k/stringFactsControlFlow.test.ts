/**
 * TD-0003: СТРОКОВЫЕ ФАКТЫ В ПРОЦЕДУРАХ С ПЕРЕХОДАМИ (план по графу потока управления).
 *
 * ЗАЧЕМ. Случай 76 поставил факт «сайт вызова → значение пула» НА САЙТЕ, но ТОЛЬКО для процедур БЕЗ
 * переходов: доказательство обходит процедуру ОДНИМ путём, а на ветке порядок носителей ≠ порядок
 * исполнения, поэтому линейная подстановка давала ЧУЖОЙ текст (замер В1/В2: `пусть т = "х"`, две
 * сквозные процедуры в разных ветвях — печаталось значение ДО ветви). Сторож честно отказывал в факте.
 *
 * ЦЕНА СТОРОЖА БЫЛА НАЗВАНА СРАЗУ: процедуры с переходами (весь лексер, 17 отказов вида «строковая
 * операция в вызываемой») факта не получают вовсе, и рантайм-цикл среза/склейки (06-02) в них не
 * живёт. Этот оракул спрашивает ровно то, что должно измениться: в процедуре С ПЕРЕХОДАМИ строковая
 * операция по доказанному значению обязана получить факт, а РАЗНЫЕ значения на разных путях — по-прежнему
 * НЕ иметь факта (иначе сторож снимается вместе с ложью, ради которой он поставлен).
 *
 * СУТЬ ПРАВКИ — СВЁРТКА ПО ПУТЯМ, А НЕ ОДИН ПУТЬ: факт остаётся в силе там и только там, где значение
 * ОДНО И ТО ЖЕ на ВСЕХ путях, ведущих в точку. Сходящиеся пути с разными значениями дают «не знаю» —
 * прежнюю границу (адрес), а не чужой текст.
 *
 * ЧИСЛА ВЛАДЕЛЬЦА (2026-11-05): процедура с `если`/`пока` + строковая операция по `Строка`-параметру
 * с доказанным значением — должно быть `с[0]` → **1072** (кодовая точка «а», U+0430) и `длина с` → **3**.
 *
 * ЗАМЕР ДО ПРАВКИ (модель, этот файл): состояния ДВА, и это важно.
 *   • `длина с` / `с[0]` под `если`/`пока` — НАЗВАННЫЙ ОТКАЗ, образ не собирается (не ложь): строковая
 *     ОПЕРАЦИЯ в процедуре с переходами факта не получает, и план честно отказывает;
 *   • `вывести т`, где `т` — результат вызова, в процедуре с переходами — ТИХАЯ ЛОЖЬ **1114104**
 *     (адрес вместо текста): печать адресом не отказывает, поэтому молчит.
 *   • `К1` (тот же вопрос без переходов) — **3** ✓; `Б5`/`Б6` (разные значения на путях) — адрес,
 *     чужого текста нет ✓.
 * Правка обязана снять И отказ (Б1-Б3), И ложь (Б4), НЕ тронув границу (Б5/Б6).
 *
 * ЗАМЕР ПОСЛЕ ПРАВКИ (2026-11-05, модель): `К1` = **3**, `Б1` = **3**, `Б2` = **1072**, `Б5`/`Б6` = адрес
 * **1114110** — отказ снят, ложь не заведена. ОСТАТОК ДОЛГА (закреплён пробами ниже, краснеет при
 * закрытии): `Б3` — строка в теле ЦИКЛА ещё ОТКАЗЫВАЕТ (возврат по обратному ребру не сходится);
 * `Б4` — значения, ОДИНАКОВЫЕ на всех путях, пока ГАСЯТСЯ вместе с разными, потому что план гасит на
 * сходении по клетке, а не по значению. Обе половины правки названы: доказательство — `joinedCallStates`
 * (`src/e2k/stringValueProof.ts`), план — `mergeKills` (`src/e2k/stringPlan.ts`).
 *
 * Модель отвечает только в шлюзе (`OSNOVA_GATE_QEMU=1`): полный прогон обязан быть детерминированным
 * (случай 12 реестра). Быстрые половины — «отказов понижения нет» — идут и в полном прогоне.
 *
 * ═══ ГРАНИЦА СДВИНУТА 2026-11-05: «АДРЕС ЧИСЛОМ» СТАЛ НАЗВАННЫМ ОТКАЗОМ ═══════════════════════════════
 *
 * Прежняя редакция считала достаточным, что чужого ТЕКСТА не печатается: `вывести т` при недоказанном
 * значении `т` печатало АДРЕС блоба ЧИСЛОМ (`1114110`), и это было закреплено пробами Б4/Б5/Б6. Замер
 * показал, что это ТА ЖЕ тихая ложь, что одиннадцатая (`2228212` суммой адресов), только мягче: программа
 * просила напечатать СТРОКУ, получала ЧИСЛО, отказов ПРИ ЭТОМ НОЛЬ. Правило владельца — «правильная
 * склейка ЛИБО названный отказ; тихая ложь обязана исчезнуть» — оставляет здесь ОТКАЗ
 * (`src/e2k/stringPlan.ts`, ветвь печати: при известном типе `Строка` и неизвестном значении).
 *
 * ПОБОЧНАЯ НАХОДКА, БЕЗ КОТОРОЙ ПРАВКА ЛОМАЛА РАБОТАЮЩЕЕ (поймана пробами Б1/Б2 сразу): числовой
 * результат `длина`/`символ` снимал у клетки ЗНАЧЕНИЕ, но не ТИП — в `reg[2]` лежала сначала строка
 * (аргумент вызова), потом в ту же клетку ложилась ДЛИНА, а тип «Строка» оставался, и печать ЧИСЛА
 * отказывала как печать строки. Заведён `killTyped` (числовой результат стирает и тип), применён в
 * четырёх местах `длина`/`символ`.
 *
 * ОСТАТОК ДОЛГА (пробы ниже краснеют, когда его закроют, и тогда их надо переписать на ЧИСЛО):
 * `Б3` — строка в теле ЦИКЛА ещё ОТКАЗЫВАЕТ (обратное ребро не сходится);
 * `Б4` — значения, ОДИНАКОВЫЕ на всех путях, ГАСЯТСЯ вместе с разными: печатается не «абв», а отказ.
 * Обе половины правки названы: доказательство — `joinedCallStates` (`src/e2k/stringValueProof.ts`),
 * план — `mergeKills` (`src/e2k/stringPlan.ts`, гасит по КЛЕТКЕ, а не по значению).
 *
 * НЕГАТИВНЫЙ КОНТРОЛЬ: снятие свёртки (однопутевой обход) краснит Б5 и Б6 — они начинают печатать
 * ЧУЖОЙ текст. А снятие новой ветви печати возвращает `1114110` числом — краснят Б4/Б5/Б6.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { SHIM_REASON } from '../scripts/e2kProgramRun';
import type { CompileOptions } from '../compiler/compiler';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'факты-с-переходами.osnova';

/** Сквозная процедура: возвращает СВОЙ параметр (значение доказано на единственном сайте). */
const СКВОЗНАЯ = ['процедура ф(а: Строка) -> Строка', '  вернуть а', 'конец ф', ''].join('\n');

const ГЛАВНАЯ = (тела: readonly string[]): string =>
  ['действие главная()', ...тела.map((тело) => `  ${тело}`), '  вернуть 0', 'конец главная', ''].join('\n');

// ── Пробы: прямолинейная (контроль), с `если`, с `пока`, и сходящиеся пути ───────────────────────

/** К1 — КОНТРОЛЬ прямолинейности: тот же вопрос без единого перехода (работает и до правки). */
const К1 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть с = ф("абв")', 'вывести длина с']);

/** Б1 — `длина с` под `если` (число владельца: 3). */
const Б1 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть с = ф("абв")', 'если 1 == 1', '  вывести длина с', 'конец если']);

/** Б2 — `с[0]` под `если` (число владельца: 1072 — кодовая точка «а»). */
const Б2 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть с = ф("абв")', 'если 1 == 1', '  вывести с[0]', 'конец если']);

/** Б3 — `длина с` в теле ЦИКЛА: счётчик рантаймовый, поэтому переходы настоящие. */
const Б3 = СКВОЗНАЯ + ГЛАВНАЯ([
  'пусть сч = 0',
  'пусть с = ф("абв")',
  'пока сч < 1',
  '  вывести длина с',
  '  сч = сч + 1',
  'конец пока',
]);

/** Б4 — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ свёртки: на ОБОИХ путях одно и то же значение → факт обязан остаться. */
const Б4 = СКВОЗНАЯ + ГЛАВНАЯ([
  'пусть т = "х"',
  'если 1 == 1',
  '  пусть т = ф("абв")',
  'иначе',
  '  пусть т = ф("абв")',
  'конец если',
  'вывести т',
]);

/** Б5 — ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ свёртки: значения на путях РАЗНЫЕ → факта нет, печатается адрес. */
const Б5 = СКВОЗНАЯ + ГЛАВНАЯ([
  'пусть т = "х"',
  'если 1 == 1',
  '  пусть т = ф("абв")',
  'иначе',
  '  пусть т = ф("где")',
  'конец если',
  'вывести т',
]);

/** Б6 — тот же отрицательный контроль В ЦИКЛЕ (форма, на которой сторож и был найден). */
const Б6 = СКВОЗНАЯ + ГЛАВНАЯ([
  'пусть сч = 0',
  'пусть т = "х"',
  'пока сч < 1',
  '  если сч == 0',
  '    пусть т = ф("абв")',
  '  иначе',
  '    пусть т = ф("где")',
  '  конец если',
  '  сч = сч + 1',
  'конец пока',
  'вывести т',
]);

// ── Помощники ────────────────────────────────────────────────────────────────────────────────────

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

interface Итог {
  readonly вывод: string;
  readonly код: number | null;
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

function прогон(имя: string, источник: string): Итог {
  const { options } = прогонФронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'образ обязан собраться: в процедуре с переходами строковый факт ОБЯЗАН работать (TD-0003)').toBe(true);
  if (!итог.ок) return { вывод: '', код: null };
  if (шим() === undefined) throw new Error(`шим не собран: ${SHIM_REASON}`);
  const elf = path.join(ROOT, '.tmp', `td3-${имя}.elf`);
  fs.mkdirSync(path.dirname(elf), { recursive: true });
  fs.writeFileSync(
    elf,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY })
      .bytes,
  );
  const прогонЦели = runInQemu(elf, { shim: true, timeoutMs: 30_000 });
  if (прогонЦели === undefined) throw new Error(`модель не ответила на пробу «${имя}»`);
  return { вывод: (прогонЦели.stdout ?? '').replace(/\n$/u, ''), код: прогонЦели.status };
}

/** Разбор отделён, чтобы `прогон` не терял проверку чистоты фронтенда. */
function прогонФронтенд(источник: string): { readonly options: CompileOptions } {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  return { options };
}

const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';

// ── Проверки ─────────────────────────────────────────────────────────────────────────────────────

describe('TD-0003: строковые факты в процедурах с переходами (свёртка по путям)', () => {
  it('К1/Б1-Б6: разбор чист; отказы понижения, если есть, НАЗВАНЫ', () => {
    for (const [имя, источник] of [
      ['К1', К1],
      ['Б1', Б1],
      ['Б2', Б2],
      ['Б3', Б3],
      ['Б4', Б4],
      ['Б5', Б5],
      ['Б6', Б6],
    ] as const) {
      const { ошибки, options } = фронтенд(источник);
      expect(ошибки, `разбор ${имя}`).toEqual([]);
      const итог = loweredProgram(источник, options);
      if (!итог.ок) {
        const текст = итог.отказ.отказы.map((з) => `${з.код ?? '—'}: ${з.причина}`).join(' | ');
        console.log(`[TD-0003] ${имя}: ОТКАЗ ПОНИЖЕНИЯ — ${текст}`);
      }
    }
    // Контроль прямолинейности обязан собираться и ДО, и ПОСЛЕ правки.
    expect(loweredProgram(К1, фронтенд(К1).options).ок, 'К1 обязана собираться').toBe(true);
  });

  it('К1: контроль прямолинейности — `длина с` = 3 (работает до правки, обязан остаться)', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    expect(прогон('к1', К1).вывод).toBe('3');
  });

  it('Б1: `длина с` ПОД `если` = 3 (сейчас адрес)', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б1', Б1);
    expect(итог.вывод, 'адрес вместо длины — долг TD-0003').toBe('3');
    expect(итог.код).toBe(0);
  });

  it('Б2: `с[0]` ПОД `если` = 1072 (кодовая точка «а»)', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    expect(прогон('б2', Б2).вывод, 'адрес вместо кодовой точки — долг TD-0003').toBe('1072');
  });

  // ── ОСТАТОК ДОЛГА TD-0003 ЗАКРЕПЛЁН ПРОБАМИ НИЖЕ — НО УЖЕ НЕ «АДРЕСОМ», А ТРЕБОВАНИЕМ ОТКАЗА ───────
  //
  // ПРЕЖНЯЯ РЕДАКЦИЯ закрепляла здесь ЧИСЛО (адрес блоба: Б4 — адрес, Б5/Б6 — 1114110) как «чужого текста
  // нет». Это закрепление оказалось ТИХОЙ ЛОЖЬЮ того же класса, что одиннадцатая: программа просила
  // напечатать СТРОКУ, а получала ЧИСЛО, и отказов при этом НОЛЬ. Правило владельца («правильная склейка
  // ЛИБО названный отказ; тихая ложь обязана исчезнуть») выбирает ОТКАЗ. Поэтому пробы ниже требуют
  // НАЗВАННОГО ОТКАЗА, а желаемое значение «абв» остаётся открытым остатком: для него нужна свёртка
  // значений ПО ПУТЯМ (Б4) и сходимость обратного ребра (Б3) — это `mergeKills` в плане и `joinedCallStates`
  // в доказательстве. Когда остаток закроют, эти пробы обязаны покраснеть и быть переписаны на ЧИСЛО.
  const отказПечати = (имя: string, источник: string): void => {
    const итог = loweredProgram(источник, фронтенд(источник).options);
    expect(итог.ок, `${имя}: печать недоказанной строки обязана ОТКАЗАТЬ, а не печатать адрес`).toBe(false);
    if (итог.ок) return;
    const текст = итог.отказ.отказы.map((з) => з.причина).join(' | ');
    expect(текст, `${имя}: отказ обязан назвать причину, а не «аргумент не строка»`).toContain('не доказано');
    expect(текст, `${имя}: и НАЗВАТЬ СВОЮ ПРОЦЕДУРУ`).toContain('главная');
  };

  it('Б3 (ОСТАТОК ДОЛГА): `длина с` в теле ЦИКЛА пока ОТКАЗЫВАЕТ — не 3', () => {
    const итог = loweredProgram(Б3, фронтенд(Б3).options);
    expect(итог.ок, 'когда долг закроют, здесь обязано быть `3`, и это закрепление придётся снять').toBe(false);
  });

  it('Б4 (ОСТАТОК ДОЛГА): ОДИНАКОВЫЕ значения на путях пока теряются — НАЗВАННЫЙ ОТКАЗ, не адрес', () => {
    отказПечати('Б4', Б4);
  });

  it('Б5: РАЗНЫЕ значения на путях — НАЗВАННЫЙ ОТКАЗ, а не чужой текст и не адрес', () => {
    отказПечати('Б5', Б5);
  });

  it('Б6: то же в цикле — НАЗВАННЫЙ ОТКАЗ', () => {
    отказПечати('Б6', Б6);
  });
});
