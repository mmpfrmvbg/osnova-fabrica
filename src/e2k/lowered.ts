/**
 * ПУБЛИЧНАЯ ДВЕРЬ ПОНИЖЕНИЯ (D11, вариант Г): `Результат<Образ, Отказ>` — и в `Отказе` БАЙТОВ НЕТ.
 *
 * # Что изменилось и почему
 *
 * До 5е дверь отдавала `{ bytes, refused, … }`: байты лежали в ответе ВСЕГДА, в том числе под несущим
 * отказом. А под отказом наши байты ЛГУТ — это измерено дважды: шестая тихая ложь (случай 60, утечка
 * равна `а`) и седьмая (случай 62: под названным отказом «склейка … в вызываемой процедуре» модель даёт
 * **9** при эталонах **1** и **7**). Значит «отказ есть, а байты вот» — не удобство, а канал лжи:
 * потребитель, забывший посмотреть `refused`, получал лживый образ и не мог этого заметить.
 *
 * Теперь у {@link Отказ} поля `bytes` нет — не «пустое», а ОТСУТСТВУЮЩЕЕ: взять байты под отказом
 * нельзя даже случайно, `tsc` не пропустит. Кто хочет смотреть под отказом (сторож), идёт в
 * `src/e2k/guards/loweredUnchecked.ts` и делает это явно.
 *
 * # Что здесь есть
 *
 * - {@link loweredProgram} — единственный публичный вход понижения;
 * - {@link Образ} — то, что дверь отдаёт при успехе (`bytes`, `used`, `arena`);
 * - {@link Отказ} — диагностика при отказе: `причина`, `процедуры`, `отказы[{причина, процедура, шаг}]`;
 * - {@link Результат} — «либо образ, либо отказ», третьего нет.
 *
 * # Границы
 *
 * Дверь — БАРЬЕР, а не абсолютная защита: `loweredProgramUnchecked` в неподходящем месте остаётся
 * красным флагом на ревью, а ESLint ловит обычные способы обойти дверь (правило по пути и правило по
 * идентификатору). Что дверь НЕ делает: не чинит ложь под отказом (это срез 5е, задача 3) и не решает,
 * что считать «честным отказом» — она лишь перестаёт отдавать лживые байты.
 */
import { loweredProgramUnchecked, type ОпцииСырогоПути } from './guards/loweredUnchecked';
import type { Образ, Отказ, Результат, СыройОбраз } from './loweredTypes';

export type { Образ, Отказ, ОтказЗапись, Результат, СыройОбраз } from './loweredTypes';
export type { ОпцииСырогоПути } from './guards/loweredUnchecked';

/**
 * Понизить программу на цель e2k. Отдаёт ЛИБО образ, ЛИБО отказ с диагностикой.
 *
 * `throw` остаётся ровно один и тот же, что был: программа, которая не компилируется, — это не отказ
 * понижения, а несостоявшийся вход (у него свой канал, `OSN-PAR-*`/`OSN-SEM-*`).
 */
export function loweredProgram(
  source: string,
  options: ОпцииСырогоПути = {},
): Результат<Образ, Отказ> {
  const сырой = loweredProgramUnchecked(source, options);
  if (сырой.refused.length > 0) return { ок: false, отказ: отказИз(сырой) };
  return { ок: true, значение: { bytes: сырой.bytes, used: сырой.used, arena: сырой.arena } };
}

/**
 * Отказ ИЗ сырого ответа: переносится ТОЛЬКО диагностика. Байты не переносятся намеренно — здесь и
 * проходит граница D11. Список процедур собирается без повторов и в порядке появления: он и есть
 * «кого коснулся отказ».
 */
function отказИз(сырой: СыройОбраз): Отказ {
  return {
    причина: сырой.отказы[0]?.причина ?? 'причина не названа',
    процедуры: [...new Set(сырой.отказы.map((запись) => запись.процедура))],
    отказы: сырой.отказы,
    // ЧИСЛО байтов — да, САМИ байты — нет (D11). Так закреплённые размеры кода под отказом остаются
    // воспроизводимыми, а собрать из числа образ нельзя.
    кодовБайт: сырой.bytes.length,
  };
}
