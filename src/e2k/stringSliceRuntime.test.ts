/**
 * ОРАКУЛ РАНТАЙМ-СРЕЗА `подстрока`: КРАЯ ПРИНОСИТ САЙТ, А НЕ СВЁРТКА (ATOM-06-02-02, шаг 6).
 *
 * Пробы идут ДВУМЯ дверями, и обе обязательны:
 *
 * 1. **Сборка** (`loweredProgram`) — вне шлюза. Проверяется не только «отказов нет», но и КАКОЙ ПУТЬ
 *    ВЫБРАН: у пробы с РАНТАЙМОВЫМИ краями образ обязан завести арену (`arena.used === true`), у
 *    контроля с КОНСТАНТНЫМИ краями — нет (`false`). Арена у этих программ — ЕДИНСТВЕННЫЙ её
 *    потребитель (явного `система.память.выделить` и склейки сверх буфера в них нет), поэтому слово
 *    `used` говорит ровно про срез: понизился рантайм-путь или края свернулись.
 *
 * 2. **Число на модели** (`OSNOVA_GATE_QEMU=1`) — `parseV3 → loweredProgram → buildElfFromCode →
 *    runInQemu`, без ручной сборки. Файл образа кладётся в `.tmp` и удаляется вместе с каталогом.
 *
 * КРАЯ БЕРУТСЯ У ВЫЗОВА ПРОЦЕДУРЫ НАМЕРЕННО: свёртка арифметики у сборки есть (`1 + 3` свернётся),
 * поэтому «просто выражение» доказало бы свёртку, а не рантайм-путь. Значение, вернувшееся из
 * вызываемой, сборке неизвестно — и `arena.used` подтверждает это ФАКТОМ.
 *
 * ЧИСЛА ЭТАЛОНА (н … к → длина среза): Р1 `1…4` → **3**; Р2 `1…12` на 11 кодпоинтах → **11**;
 * Р3 `−2…6` (нормализация от конца) → **2**; Р4 `3…1` (начало за концом) → **0**.
 */
