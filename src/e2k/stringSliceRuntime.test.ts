// ── Обвязка ──────────────────────────────────────────────────────────────────────────────────────

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

/** Сборка: отказов нет И арена заведена ровно там, где срез идёт рантайм-путём. */
function собраноСАреной(источник: string, арена: boolean): void {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  const итог = loweredProgram(источник, options);
  if (!итог.ок) {
    throw new Error(`отказ: ${итог.отказ.отказы.map((запись) => запись.причина).join(' | ')}`);
  }
  expect(
    итог.значение.arena.used,
    арена
      ? 'края из рантайма: образ ОБЯЗАН завести арену (иначе срез свернулся, и проба не про рантайм-путь)'
      : 'края константны: арене тут взяться не от чего — признак обязан различать пути',
  ).toBe(арена);
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

/** Признак шлюза: числа спрашиваются ТОЛЬКО там, где модель обязана быть (случай 12 реестра). */
const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';
const ОБРАЗЫ: string[] = [];

function кодНаМодели(источник: string, файл: string): number | null {
  if (!В_ШЛЮЗЕ_QEMU) return null;
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'у этих проб отказов быть не должно — иначе число не спросить').toBe(true);
  if (!итог.ок) return null;
  const имя = шим();
  expect(имя, SHIM_REASON).toBeDefined();
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  ОБРАЗЫ.push(путь);
  return runInQemu(путь, { shim: true, timeoutMs: 30_000 })?.status ?? null;
}

/** ШАГ 7: тот же путь, но наблюдение — БАЙТЫ stdout, а не код возврата. */
function печатьНаМодели(
  источник: string,
  файл: string,
): { readonly status: number | null; readonly stdout: string } | null {
  if (!В_ШЛЮЗЕ_QEMU) return null;
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'у печатающих проб отказов быть не должно').toBe(true);
  if (!итог.ок) return null;
  const имя = шим();
  expect(имя, SHIM_REASON).toBeDefined();
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  ОБРАЗЫ.push(путь);
  const прогон = runInQemu(путь, { shim: true, timeoutMs: 30_000 });
  return прогон === undefined ? null : { status: прогон.status, stdout: прогон.stdout };
}

