/**
 * ОРАКУЛ РАНТАЙМ-СРЕЗА `подстрока`: КРАЯ ПРИНОСИТ САЙТ, А НЕ СВЁРТКА (ATOM-06-02-02, шаг 6).
 *
 * Пробы идут ДВУМЯ дверями, и обе обязательны:
 *
 * 1. **Сборка** (`loweredProgram`) — вне шлюза. Проверяется не только «отказов нет», но и КАКОЙ ПУТЬ
 *    ВЫБРАН: у пробы с РАНТАЙМОВЫМИ краями образ обязан завести арену (`arena.used === true`), у
 *    контроля с КОНСТАНТНЫМИ краями — нет (`false`). Арена у этих программ — ЕДИНСТВЕННЫЙ её
 *    потребитель (явного `система.память.выделить` и склейки сверх буфера в них нет), поэтому слово
 *    `used` говорит ровно про срез: понизился рантайм-путь или края свернулись.
 *
 * 2. **Число на модели** (`OSNOVA_GATE_QEMU=1`) — `parseV3 → loweredProgram → buildElfFromCode →
 *    runInQemu`, без ручной сборки. Файл образа кладётся в `.tmp` и удаляется вместе с каталогом.
 *
 * КРАЯ БЕРУТСЯ У ВЫЗОВА ПРОЦЕДУРЫ НАМЕРЕННО: свёртка арифметики у сборки есть (`1 + 3` свернётся),
 * поэтому «просто выражение» доказало бы свёртку, а не рантайм-путь. Значение, вернувшееся из
 * вызываемой, сборке неизвестно — и `arena.used` подтверждает это ФАКТОМ.
 *
 * ЧИСЛА ЭТАЛОНА (н … к → длина среза): Р1 `1…4` → **3**; Р2 `1…12` на 11 кодпоинтах → **11**;
 * Р3 `−2…6` (нормализация от конца) → **2**; Р4 `3…1` (начало за концом) → **0**.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { SHIM_REASON } from '../scripts/e2kProgramRun';
import type { CompileOptions } from '../compiler/compiler';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'срез-рантайм.osnova';

/**
 * ОБЩАЯ ФОРМА ПРОБЫ: края приходят ИЗ ВЫЗЫВАЕМЫХ (`целое_*` возвращают нужное число).
 *
 * Так края остаются рантаймовыми (`1 + A` и т.п. свернулись бы), а бюджет клеток точки входа не
 * тратится на петлю: сайт рантайм-среза забирает ТРИ клетки программы (`%b[1..3]`) и арена три
 * (`%b[4..6]`), поэтому у программы остаётся ЧЕТЫРЕ (`%b[0]`, `%b[7..9]`) — ровно столько, сколько
 * нужно вызову с двумя краями и приёмником (замер ERR-0007: с петлёй или с арифметикой над краем
 * живых значений 5…7, и раскладка отказывает «свободных регистров 3»).
 */
const проба = (источник: string, начало: string, финиш: string): string =>
  [
    'процедура целое_начало() → Число',
    `  вернуть ${начало}`,
    'конец',
    '',
    'процедура целое_финиш() → Число',
    `  вернуть ${финиш}`,
    'конец',
    '',
    'действие главная()',
    `  пусть с = "${источник}"`,
    '  пусть начало = целое_начало()',
    '  пусть финиш = целое_финиш()',
    '  вернуть длина подстрока(с, начало, финиш)',
    'конец',
  ].join('\n');

/** Р1: `с = "абвгде"` (6 кодпоинтов), края `1` и `4` — эталон **3**. */
const Р1_ТРИ = проба('абвгде', '1', '4');

/** Р2: `с = "абвгдеёжзийкл"` (11 кодпоинтов), края `1` и `12` — эталон **11** (широкий срез). */
const Р2_ОДИННАДЦАТЬ = проба('абвгдеёжзийкл', '1', '12');

/** Р3: ОТРИЦАТЕЛЬНЫЙ край из рантайма (`−2`), второй `6` — эталон **2** («де»). */
const Р3_МИНУС = проба('абвгде', '-2', '6');

/** Р4: НАЧАЛО ЗА КОНЦОМ (`3` и `1`) из рантайма — эталон **0** (пустой срез, а не мусор). */
const Р4_ПУСТО = проба('абвгде', '3', '1');

/**
 * КОНТРОЛЬ (различающий): те же края, но КОНСТАНТНЫЕ — эталон **3**, и арена НЕ заводится.
 *
 * Без этой пробы «arena.used === true» ничего не значило бы: она показывает, что признак различает
 * пути, а не горит всегда.
 */
const КОНТРОЛЬ_КОНСТАНТНЫЕ_КРАЯ = [
  'действие главная()',
  '  пусть с = "абвгде"',
  '  вернуть длина подстрока(с, 1, 4)',
  'конец',
].join('\n');

// ── Обвязка ──────────────────────────────────────────────────────────────────────────────────────

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

/** Сборка: отказов нет И арена заведена ровно там, где срез идёт рантайм-путём. */
function собраноСАреной(источник: string, арена: boolean): void {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  const итог = loweredProgram(источник, options);
  if (!итог.ок) {
    throw new Error(`отказ: ${итог.отказ.отказы.map((запись) => запись.причина).join(' | ')}`);
  }
  expect(
    итог.значение.arena.used,
    арена
      ? 'края из рантайма: образ ОБЯЗАН завести арену (иначе срез свернулся, и проба не про рантайм-путь)'
      : 'края константны: арене тут взяться не от чего — признак обязан различать пути',
  ).toBe(арена);
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

/** Признак шлюза: числа спрашиваются ТОЛЬКО там, где модель обязана быть (случай 12 реестра). */
const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';
const ОБРАЗЫ: string[] = [];

function кодНаМодели(источник: string, файл: string): number | null {
  if (!В_ШЛЮЗЕ_QEMU) return null;
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'у этих проб отказов быть не должно — иначе число не спросить').toBe(true);
  if (!итог.ок) return null;
  const имя = шим();
  expect(имя, SHIM_REASON).toBeDefined();
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  ОБРАЗЫ.push(путь);
  return runInQemu(путь, { shim: true, timeoutMs: 30_000 })?.status ?? null;
}

// ── Проверки ─────────────────────────────────────────────────────────────────────────────────────

describe('рантайм-срез `подстрока`: края приносит сайт, а не свертка', () => {
  it('Р1: края 1…4 из рантайма — арена заведена, длина 3', () => {
    собраноСАреной(Р1_ТРИ, true);
    expect(кодНаМодели(Р1_ТРИ, 'срез-р1.elf')).toBe(В_ШЛЮЗЕ_QEMU ? 3 : null);
  });

  it('Р2: края 1…12 из рантайма на 11 кодпоинтах — длина 11', () => {
    собраноСАреной(Р2_ОДИННАДЦАТЬ, true);
    expect(кодНаМодели(Р2_ОДИННАДЦАТЬ, 'срез-р2.elf')).toBe(В_ШЛЮЗЕ_QEMU ? 11 : null);
  });

  it('Р3: ОТРИЦАТЕЛЬНЫЙ край из рантайма (`−2`) — нормализация от конца, длина 2', () => {
    собраноСАреной(Р3_МИНУС, true);
    expect(кодНаМодели(Р3_МИНУС, 'срез-р3.elf')).toBe(В_ШЛЮЗЕ_QEMU ? 2 : null);
  });

  it('Р4: начало за концом из рантайма — ПУСТОЙ срез (0), а не мусор', () => {
    собраноСАреной(Р4_ПУСТО, true);
    expect(кодНаМодели(Р4_ПУСТО, 'срез-р4.elf')).toBe(В_ШЛЮЗЕ_QEMU ? 0 : null);
  });

  it('КОНТРОЛЬ: те же края КОНСТАНТАМИ — длина 3 и арены НЕТ (признак различает пути)', () => {
    собраноСАреной(КОНТРОЛЬ_КОНСТАНТНЫЕ_КРАЯ, false);
    expect(кодНаМодели(КОНТРОЛЬ_КОНСТАНТНЫЕ_КРАЯ, 'срез-контроль.elf')).toBe(В_ШЛЮЗЕ_QEMU ? 3 : null);
    // ОБРАЗЫ ЖИВУТ ТОЛЬКО РАДИ ЭТОЙ ПРОБЫ: стенд не оставляет за собой файлов, иначе следующий
    // прогон мог бы показать чужую ревизию (ловушка «перезапись артефактов без удаления», A4-5г).
    for (const путь of ОБРАЗЫ) {
      try {
        fs.unlinkSync(путь);
      } catch {
        // Файла нет — это и есть цель уборки.
      }
    }
  });
});
