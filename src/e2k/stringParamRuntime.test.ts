// ── Помощники (те же, что у оракула шага 2.3: один источник правды о двери) ──────────────────────

interface Отказ {
  readonly код: string;
  readonly причина: string;
  readonly шаг: number;
}

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

function отказы(источник: string): readonly Отказ[] {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  if (ошибки.length > 0) return [];
  let итог: ReturnType<typeof loweredProgram>;
  try {
    итог = loweredProgram(источник, options);
  } catch (беда) {
    return [{ код: 'БРОСОК', причина: беда instanceof Error ? беда.message : String(беда), шаг: -1 }];
  }
  if (итог.ок) return [];
  return итог.отказ.отказы.map((запись) => ({ код: запись.код, причина: запись.причина, шаг: запись.шаг }));
}

function названные(записи: readonly Отказ[]): readonly string[] {
  return записи.map((запись) => `${запись.код}: ${запись.причина}`);
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

function прогон(
  источник: string,
  файл: string,
): { readonly отказы: readonly Отказ[]; readonly код: number | null; readonly вывод: string } {
  const причины = отказы(источник);
  if (причины.length > 0) return { отказы: причины, код: null, вывод: '' };
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'после проверки отказов дверь обязана отдать образ').toBe(true);
  if (!итог.ок) return { отказы: причины, код: null, вывод: '' };
  const имя = шим();
  expect(имя, SHIM_REASON).toBeDefined();
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const исполнение = runInQemu(путь, { shim: true, timeoutMs: 30_000 });
  return { отказы: [], код: исполнение?.status ?? null, вывод: (исполнение?.stdout ?? '').trim() };
}

function адресаБайтов(образ: Uint8Array, текст: string): readonly number[] {
  const игла = Buffer.from(текст, 'utf-8');
  const найдено: number[] = [];
  let от = 0;
  for (;;) {
    const at = Buffer.from(образ).indexOf(игла, от);
    if (at < 0) break;
    найдено.push(MINIMAL_BASE + at);
    от = at + 1;
  }
  return найдено;
}

