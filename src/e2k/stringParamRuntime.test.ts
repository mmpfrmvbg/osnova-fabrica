/**
 * TD-0001: ЗНАЧЕНИЕ Строка-ПАРАМЕТРА ИЗВЕСТНО РАНТАЙМУ — ВЫБОРКА ИЗ ДЕСКРИПТОРА.
 *
 * ═══ ЧТО ЭТОТ ФАЙЛ ПРОВЕРЯЕТ ═══════════════════════════════════════════════════════════════════════
 *
 * Шаг 2.3 взял СТРОКОВОСТЬ из объявленного типа параметра, но ЗНАЧЕНИЕ (сколько кодпоинтов, где
 * таблица кодов) — только из доказательства: все прямые сайты вызова обязаны передать ОДНУ И ТУ ЖЕ
 * известную строку. Параметр, которому разные сайты передают РАЗНЫЕ строки, отказывал по имени
 * (`OSN-LOW-003`: «содержимое строки-параметра известно не для всех вызовов»). Это ровно случай
 * лексера: 20 отказов его тела — отсюда (замер `.tmp/td1-замер-до.ts`: видов 19, корень TD-0001 = 20).
 *
 * Приказ владельца (2026-11-05): «1. TD-0001 (рантайм-развёртка) — РАЗРЕШАЮ. O(n) проход по байтам для
 * Строка-параметра с разными сайтами. Специализация раздует код — не надо».
 *
 * ═══ ЧЕМ O(n) ОКАЗАЛСЯ НЕВЫРАЗИМ, И ЧТО СДЕЛАНО ВМЕСТО ════════════════════════════════════════════
 *
 * Проход по байтам требует ПЕРЕХОДА внутри последовательности. Замер (не рассуждение): раскладка
 * размещает только носители `IR.*`, у байтового шага носителя нет (`IR.load` — это `ldd`, восемь байт),
 * а составной носитель строит свои команды и внутреннего перехода выразить не может — переходы
 * существуют ТОЛЬКО как носители, а носители — в `src/e2k/twoPassLayout.ts`, который границами атома
 * закрыт. Поэтому сделана выборка O(1) БЕЗ ветвлений и БЕЗ новых носителей:
 *
 *   ПЕРЕД байтами каждой статической строки лежит ДЕСКРИПТОР — 16 байт, выровненных на 8:
 *     слово 0: число кодпоинтов, слово 1: адрес таблицы кодов этой строки.
 *
 * Рантайм читает его по адресу самого значения (`addr − 16`), то есть знание приходит из ДАННЫХ, а не
 * из сборки. Это и есть «значение известно рантайму»: специализация на каждый сайт не нужна.
 *
 * ═══ ГРАНИЦА: ПАРАМЕТР ГОДИТСЯ, ТОЛЬКО ЕСЛИ КАЖДЫЙ САЙТ ПЕРЕДАЁТ ЛИТЕРАЛ ═══════════════════════════
 *
 * Дескриптор лежит перед БЛОБОМ литерала. Значение, собранное в рантайме (склейка сверх буфера,
 * нагрузка пары), лежит в ДРУГОМ месте — читать `addr − 16` там значило бы читать чужие байты.
 * Поэтому признак «можно» — НЕ «тип Строка», а «КАЖДЫЙ сайт передаёт литерал из пула, и значения
 * РАЗНЫЕ»; во всех прочих случаях остаётся НАЗВАННЫЙ отказ (проба ТД2 и контроль склейки ниже).
 *
 * ═══ ЗАМЕР ДО ПОЧИНКИ (2026-11-05, `.tmp/td1-замер-до.ts`) ══════════════════════════════════════════
 *
 *   ТД1а `с[0]` по параметру, сайты «абв» и «где»      → 2 отказа (OSN-LOW-003 ×2)
 *   ТД1б `длина с`, сайты «аб» и «вгде»                → 2 отказа
 *   ТД2 сайт передаёт параметр внешней процедуры       → 2 отказа
 *   ТД3 один сайт (значение доказано, шаг 2.3)         → 0 отказов (контроль: не сдвинулся)
 *
 * Оракул написан ДО починки и обязан краснеть в день починки: положительные пробы требуют нуля
 * отказов и верных чисел, отрицательные — сохранённого отказа по имени.
 */
