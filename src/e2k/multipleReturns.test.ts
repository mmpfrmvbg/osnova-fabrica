/**
 * ВОЗВРАТ ВНУТРИ `если` НА ЦЕЛИ — ОРАКУЛ СЛУЧАЯ 47 (§3.134).
 *
 * # Что здесь спрашивается
 *
 * Программа вида
 *
 * ```osnova
 * действие главная()
 *   если 1 == 2
 *     вернуть 9
 *   конец если
 *   вернуть 5
 * конец
 * ```
 *
 * обязана вернуть **5**: переход не взят, исполнение идёт на «путь провала» и возвращает 5. До
 * 2026-10-23 такой программы на цель **не существовало**: модель вставала
 * `qemu: unimplemented operation LDCUDW at IP = 0x100110` (код 1). Это и есть случай 47 реестра
 * проверяемости — стена, найденная при написании оракула символа и обоёдённая там одной точкой
 * возврата.
 *
 * # Прежний диагноз ОТОЗВАН
 *
 * В §3.133 и в реестре было записано, что переход «уезжает на СЕРЕДИНУ команды». Замер
 * (`.tmp/osnova-3134-case47.ts`, дамп раскладки против факта) показал обратное: раскладка совпала с
 * фактом **побайтово** (128 = 128), `disp` перехода и его цель лежали на границах команд, а IP
 * падения (`0x100110` = смещение 272) — **за концом кода в 192 байта**. Причина не в переходе:
 * возврат на пути провала (`вернуть 5`) был объявлен **нулевым** (`zeroSize: [7, 8]`) и в образ не
 * попадал ВООБЩЕ, поэтому путь провала уходил из кода в статические данные и модель читала данные
 * как команды.
 *
 * # Чем закрыто
 *
 * `src/e2k/procedureCall.ts#prepareImage`: выходом (`IR.exit`) становится **каждый** возврат точки
 * входа со значением, а не только первый. Цена названа там же: ~72 байта на возврат вместо общего
 * выхода с переносом значения (долг места, §3.134).
 *
 * # Сторож
 *
 * Негативный контроль `16.6` в `src/scripts/e2kLayoutNegativeControl.ts` возвращает прежнее условие
 * («выход только у ПЕРВОГО возврата») — и первая же проба этой таблицы краснеет: модель отдаёт 1
 * (`LDCUDW`), а не 5. Оракул без контроля был бы утверждением о коде, а не о поведении цели.
 */
import { describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { MINIMAL_BASE, buildElfFromCode } from '../e2k/elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';

const ROOT = path.resolve(__dirname, '..', '..');
const shim = buildShim();

const опцииV3 = (src: string) => {
  const р = parseV3(src, 'возвраты.osnova');
  return { filename: 'возвраты.osnova', parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Собрать образ: отказы, беда или байты. */
function собрать(src: string): { отказы: string[]; беда?: string; образ?: ReturnType<typeof loweredProgramUnchecked> } {
  try {
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
    const образ = loweredProgramUnchecked(src, опцииV3(src));
    return { отказы: образ.refused.map((item) => `${item.code ?? '—'} ${item.reason}`), образ };
  } catch (error) {
    return { отказы: [], беда: error instanceof Error ? error.message : String(error) };
  }
}

/** Собрать и исполнить в модели: код возврата процесса (или `undefined`, если до прогона не дошло). */
function прогонНаЦели(имя: string, src: string): { код?: number; отказы: string[]; беда?: string } {
  const итог = собрать(src);
  if (итог.беда !== undefined || итог.образ === undefined || итог.отказы.length > 0) {
    return { отказы: итог.отказы, ...(итог.беда === undefined ? {} : { беда: итог.беда }) };
  }
  if (shim === undefined) return { отказы: [] };
  const elf = path.join(ROOT, '.tmp', `возвраты-${имя}.elf`);
  fs.mkdirSync(path.dirname(elf), { recursive: true });
  fs.writeFileSync(
    elf,
    buildElfFromCode(итог.образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: итог.образ.arena.extraMemory }).bytes,
  );
  const результат = runInQemu(elf, { shim: true, timeoutMs: 30_000 });
  return { код: результат?.status ?? undefined, отказы: [] };
}

/**
 * ПРОБЫ. Столбец «код» — то, что обязана отдать цель. Пары различающие: если бы выход ставился
 * только у первого возврата, `ложь-переход-в-конце` дала бы 1 (падение), а `истина-в-конце` — 9
 * (ветвь взята, до провала дело не доходит). Одинаковый ответ у обеих проб означал бы, что путь
 * провала не исполняется вовсе, — поэтому эталоны разные.
 */
const пробы: readonly { имя: string; эталон: number; src: string }[] = [
  {
    имя: 'ложь-переход-в-конце',
    эталон: 5,
    src: `действие главная()
  если 1 == 2
    вернуть 9
  конец если
  вернуть 5
конец главная
`,
  },
  {
    имя: 'истина-в-конце',
    эталон: 9,
    src: `действие главная()
  если 1 == 1
    вернуть 9
  конец если
  вернуть 5
конец главная
`,
  },
  {
    имя: 'ложь-переход-взят',
    эталон: 5,
    src: `действие главная()
  пусть н = 0
  если 1 == 2
    н = 1
  конец если
  вернуть н + 5
конец главная
`,
  },
  {
    имя: 'истина-переход-не-взят',
    эталон: 6,
    src: `действие главная()
  пусть н = 0
  если 1 == 1
    н = 1
  конец если
  вернуть н + 5
конец главная
`,
  },
  {
    имя: 'ложь-пустое-тело',
    эталон: 5,
    src: `действие главная()
  пусть н = 0
  если 1 == 2
  конец если
  вернуть н + 5
конец главная
`,
  },
  {
    имя: 'три-ветви-с-возвратами',
    эталон: 3,
    src: `действие выбрать(х)
  если х == 1
    вернуть 1
  конец если
  если х == 2
    вернуть 2
  конец если
  вернуть 3
конец выбрать

действие главная()
  вернуть выбрать(7)
конец главная
`,
  },
];

describe('возврат внутри `если` на цели: случай 47', () => {
  it('каждая проба понижается без отказов и попадает в образ', () => {
    for (const проба of пробы) {
      const итог = собрать(проба.src);
      expect(итог.беда, `проба «${проба.имя}»: беда сборки`).toBeUndefined();
      expect(итог.отказы, `проба «${проба.имя}»: отказы понижения`).toEqual([]);
      expect((итог.образ?.bytes.length ?? 0) > 0, `проба «${проба.имя}»: пустой образ`).toBe(true);
    }
  });

  it('путь провала не уходит за код: проба «ложь-переход-в-конце» возвращает 5, а не падает', () => {
    const итог = прогонНаЦели('ложь-переход-в-конце', пробы[0]!.src);
    expect(итог.беда).toBeUndefined();
    expect(итог.отказы).toEqual([]);
    if (итог.код === undefined) return; // без шима — только сборка (см. шапку)
    expect(итог.код, 'случай 47: переход, перепрыгивающий `вернуть`').toBe(5);
  });

  it('ветвь взята — ответ ветви, а не пути провала (различающая пара)', () => {
    const итог = прогонНаЦели('истина-в-конце', пробы[1]!.src);
    if (итог.код === undefined) return;
    expect(итог.код).toBe(9);
  });

  it('возвраты нескольких ветвей и путь провала: каждая проба отдаёт свой эталон', () => {
    for (const проба of пробы.slice(2)) {
      const итог = прогонНаЦели(проба.имя, проба.src);
      expect(итог.беда, `проба «${проба.имя}»`).toBeUndefined();
      expect(итог.отказы, `проба «${проба.имя}»`).toEqual([]);
      if (итог.код === undefined) return;
      expect(итог.код, `проба «${проба.имя}»`).toBe(проба.эталон);
    }
  });
});
