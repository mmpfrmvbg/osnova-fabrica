/**
 * СТОРОЖ ДЕФЕКТА ВЫТЕСНЕНИЯ ЧЕРЕЗ ВЫЗОВ (случай 86) — КРАСНЫЙ ПО ПОСТРОЕНИЮ.
 *
 * # Что это за дефект
 *
 * Значение, живое ЧЕРЕЗ вызов процедуры, теряется: раскладка (`regAlloc` + вытеснение) не
 * сохраняет его перед вызовом, а после возврата читает регистр, который вызов уже затёр. Отказов
 * понижения при этом НОЛЬ — программа собирается и отдаёт НЕВЕРНОЕ число. Это не «ещё не
 * доделано», а ТИХАЯ ЛОЖЬ, то есть худший класс из трёх названных в `AGENTS.md`.
 *
 * Лестница (замер `.tmp/08-49-ladder.ts`, 2026-11-07): `N` значений определяются ДО вызова,
 * вызов идёт между определениями и суммой, сумма считается ПОСЛЕ возврата, поэтому все `N`
 * обязаны пережить вызов.
 *
 * | `N` | эталон | модель до правки | факт |
 * |---|---|---|---|
 * | 8  | 36  | 36  | верно |
 * | 9  | 45  | 38  | **дефект** |
 * | 10 | 55  | 48  | дефект |
 * | 11 | 66  | 59  | дефект |
 * | 12 | 78  | 71  | дефект |
 * | 13 | 91  | 84  | дефект |
 * | 14 | 105 | 98  | дефект |
 *
 * Разность во всех неверных строках одна и та же — **7**, и это сбивало с толку: она выглядела как
 * «теряется ровно одно значение, и всегда седьмое». Догадка ОТОЗВАНА замером: теряется не «одно
 * значение» и не седьмое, а ДЕВЯТОЕ — `п8`, — и не теряется, а ПОДМЕНЯЕТСЯ ОТВЕТОМ вызова.
 *
 * # Механизм (найден в коде и подтверждён предсказанием)
 *
 * `src/e2k/liveness.ts#defUseOf`, ветвь `IR.call`/`IR.invoke`, объявляет определением ТОЛЬКО
 * приёмник вызова, а окно вызова порчей не считает вовсе. При `wbs = 4` аргумент и ОТВЕТ идут через
 * клетку ВЫЗЫВАЮЩЕГО `%r(2·wbs) = %r8`, то есть `%b[8]`. Значение, живое через вызов и попавшее в
 * `%b[8]`, затирается ответом вызываемой.
 *
 * Отсюда проверяемое предсказание `эталон − п8 + ОТВЕТ`; оно сошлось на трёх разных ОТВЕТАХ при
 * одном и том же живом наборе (1..9, `п8 = 9`, эталон 45) и на трёх независимых наборах значений:
 *
 * | ОТВЕТ вызываемой | предсказано | модель |
 * |---|---|---|
 * | 2   | 45 − 9 + 2 = 38   | **38** |
 * | 1   | 45 − 9 + 1 = 37   | **37** |
 * | 999 | 45 − 9 + 999 = 1035 | **1035** |
 * | все единицы (`п8 = 1`), ОТВЕТ 2 | 9 − 1 + 2 = 10 | **10** |
 * | степени двойки (`п8 = 256`), ОТВЕТ 2 | 511 − 256 + 2 = 257 | **257** |
 *
 * Поэтому число ниже и названо по эталону: 38 и 98 — это НЕ «потерянные» значения, а подмена клетки.
 *
 * # Почему это НЕ регрессия
 *
 * Тот же прогон на ревизии `65072f6c` (правки сняты, `git stash`) даёт ТЕ ЖЕ 38 / 48 / … / 98:
 * лестница неверна и на базе. Дефект старше задачи про `rsz = 11` и от неё не зависит.
 *
 * # Почему сторож называется КРАСНЫМ, а не «пропускается»
 *
 * Он гоняется шлюзом `npm run gate:qemu` (файл внесён в `vitest.qemu.config.ts`), а не полным
 * прогоном: полный прогон отвечает на вопрос «я что-то сломал?», и постоянный красный в нём
 * стёр бы это различие (тот же довод, что в шапке `vitest.e2k.config.ts`, случай 12 реестра
 * проверяемости). Здесь красный — ЗАЯВЛЕНИЕ: «число неверно, сторож это видит». Как только
 * дефект починят, эти же три проверки станут зелёными без единой правки в файле — в этом и
 * смысл: сторож не подстраивается под дефект, он его фиксирует.
 *
 * # Границы
 *
 * Проверяется ЧИСЛО на модели. «Компилируется без отказов» здесь ничего не значит — отказов и
 * нет, дефект именно в том, что их нет. Что так же поведёт себя железо — отдельная проба; модель
 * по этому классу уже расходилась с целью дважды (случаи 48, 52), поэтому утверждение о железе
 * здесь НЕ делается.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { loweredProgram } from './lowered';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');
const shim = buildShim();

/**
 * Источник с `N` значениями, живыми ЧЕРЕЗ вызов.
 *
 * `помощник` — ЛИСТОВАЯ процедура (без своего окна): этого достаточно, дефект проявляется и на
 * вызове листовой, то есть дело не в ширине кадра вызываемой, а в том, что вызов вообще затёр
 * клетку живого значения.
 */
function лестница(чисел: number): string {
  const строки: string[] = [
    'действие помощник(а)',
    '  вернуть а + 1',
    'конец',
    '',
    'действие главная()',
  ];
  for (let i = 0; i < чисел; i += 1) строки.push(`  пусть п${String(i)} = ${String(i + 1)}`);
  строки.push('  пусть б = помощник(1)');
  строки.push(`  пусть с = ${Array.from({ length: чисел }, (_, i) => `п${String(i)}`).join(' + ')}`);
  строки.push('  вывести с');
  строки.push('  вернуть 0', 'конец', '');
  return строки.join('\n');
}

/** Эталон считается АРИФМЕТИКОЙ ЗДЕСЬ, а не берётся из наших же чисел. */
function эталон(чисел: number): number {
  let сумма = 0;
  for (let i = 1; i <= чисел; i += 1) сумма += i;
  return сумма;
}

function наМодели(чисел: number): { вывод: readonly string[]; код?: number } {
  const текст = лестница(чисел);
  const разбор = parseV3(текст, 'вытеснение.osnova');
  const итог = loweredProgram(текст, {
    filename: 'вытеснение.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  expect(
    итог.ок,
    итог.ок ? '' : `непонижённые носители: ${итог.отказ.отказы.map((з) => з.причина).join('; ')}`,
  ).toBe(true);
  if (!итог.ок) throw new Error(`понижение отказало: ${итог.отказ.причина}`);
  const файл = path.join(ROOT, '.tmp', `spill-across-call-${String(чисел)}.elf`);
  fs.writeFileSync(
    файл,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 25_000 });
  return { вывод: (прогон?.stdout ?? '').split('\n').filter((с) => с !== ''), код: прогон?.status };
}

describe('дефект вытеснения через вызов (случай 86): значение, живое через вызов, обязано пережить его', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL-дистрибутиве нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('8 живых значений — ВЕРНО (36): сторож различает, а не красный всегда', () => {
    const прогон = наМодели(8);
    expect(прогон.вывод, 'восемь живых через вызов: эталон 36').toEqual([String(эталон(8))]);
  });

  it('9 живых значений — ДЕФЕКТ: 38 вместо 45 (клетка %b[8] подменяется ответом вызова: 45 − 9 + 2)', () => {
    const прогон = наМодели(9);
    // Эталон — 45. Пока дефект жив, модель отдаёт 38: `п8` = 9 подменено ОТВЕТОМ вызова (2).
    expect(прогон.вывод, 'девять живых через вызов: эталон 45, дефект даёт 38').toEqual([String(эталон(9))]);
  });

  it('14 живых значений — ДЕФЕКТ: 98 вместо 105 (та же подмена %b[8]: 105 − 9 + 2)', () => {
    const прогон = наМодели(14);
    expect(прогон.вывод, 'четырнадцать живых через вызов: эталон 105, дефект даёт 98').toEqual([String(эталон(14))]);
  });
});

