/**
 * СТОРОЖ ПОРЧИ ОКНА ВЫЗОВОМ (случай 86, решение D35) — ЗЕЛЁНЫЙ; КРАСНЫМ ОН БЫЛ ПО ПОСТРОЕНИЮ ДО ПРАВКИ.
 *
 * # Что это за дефект (был)
 *
 * Значение, живое ЧЕРЕЗ вызов процедуры, терялось: раскладка (`regAlloc` + вытеснение) не
 * сохраняла его перед вызовом, а после возврата читала регистр, который вызов уже затёр. Отказов
 * понижения при этом НОЛЬ — программа собиралась и отдавала НЕВЕРНОЕ число. Это не «ещё не
 * доделано», а ТИХАЯ ЛОЖЬ, то есть худший класс из трёх названных в `AGENTS.md`.
 *
 * Лестница (замер `.tmp/08-49-ladder.ts`, 2026-11-07): `N` значений определяются ДО вызова,
 * вызов идёт между определениями и суммой, сумма считается ПОСЛЕ возврата, поэтому все `N`
 * обязаны пережить вызов.
 *
 * | `N` | эталон | модель ДО правки | модель ПОСЛЕ |
 * |---|---|---|---|
 * | 8  | 36  | 36  | **36** |
 * | 9  | 45  | 38  | **45** |
 * | 10 | 55  | 48  | **55** |
 * | 11 | 66  | 59  | **66** |
 * | 12 | 78  | 71  | **78** |
 * | 13 | 91  | 84  | **91** |
 * | 14 | 105 | 98  | **105** |
 *
 * Разность во всех неверных строках была одна и та же — **7**, и это сбивало с толку: она выглядела
 * как «теряется ровно одно значение, и всегда седьмое». Догадка ОТОЗВАНА замером: теряется не «одно
 * значение» и не седьмое, а ДЕВЯТОЕ — `п8`, — и не теряется, а ПОДМЕНЯЕТСЯ ОТВЕТОМ вызова.
 *
 * # Механизм (найден в коде и подтверждён предсказанием)
 *
 * `src/e2k/liveness.ts#defUseOf`, ветвь `IR.call`/`IR.invoke`, объявляет определением ТОЛЬКО
 * приёмник вызова, а окно вызова порчей не считает вовсе. При `wbs = 4` аргументы и ОТВЕТ идут через
 * клетки ВЫЗЫВАЮЩЕГО `%b[2·wbs …]` = `%b[8 …]`. Значение, живое через вызов и попавшее в `%b[8]`,
 * затирается ответом вызываемой.
 *
 * Отсюда проверяемое предсказание `эталон − п8 + ОТВЕТ`; оно сошлось на трёх разных ОТВЕТАХ при
 * одном и том же живом наборе (1..9, `п8 = 9`, эталон 45) и на двух своих наборах значений — всего
 * пять независимых замеров:
 *
 * | ОТВЕТ вызываемой | предсказано | модель |
 * |---|---|---|
 * | 2   | 45 − 9 + 2 = 38   | **38** |
 * | 1   | 45 − 9 + 1 = 37   | **37** |
 * | 999 | 45 − 9 + 999 = 1035 | **1035** |
 * | все единицы (`п8 = 1`), ОТВЕТ 2 | 9 − 1 + 2 = 10 | **10** |
 * | степени двойки (`п8 = 256`), ОТВЕТ 2 | 511 − 256 + 2 = 257 | **257** |
 *
 * Поэтому 38 и 98 — это НЕ «потерянные» значения, а подмена клетки ответом.
 *
 * # Чем починено (D35)
 *
 * Правило объявлено в `src/e2k/liveness.ts#callClobberedCells`: вызов шириной `wbs` пишет клетки
 * вызывающего `%b[2·wbs …]` — аргументы (эмиттер переносит их `movts`) и клетку ОТВЕТА. Раскладка
 * (`src/e2k/regAlloc.ts#allocateSegments`) не выдаёт эти клетки значению, живущему ЧЕРЕЗ вызов («началось
 * до него, читается после»), а значение, которому клетки не хватило, отдаёт существующему вытеснению —
 * оно уезжает в слот и возвращается, а не теряется молча.
 *
 * Правило применено к `IR.call` и НЕ применено к `IR.invoke`: порчу сайтов системных вызовов уже
 * описывает план сайта (`SHARED_SITE_CLOBBERS`, план печати и строк), и второй запрет поверх него
 * стоил замером FIR **+8 команд** (266 → 274, пакетами 2040 → 2168, +6.3 % — за стоп-границей 5 %)
 * и двух отказов на печати среза строк. Это названо в D35; кто объединит два механизма — отдельный атом.
 *
 * # Почему сторож живёт в шлюзе `gate:qemu`, а не в полном прогоне
 *
 * Число спрашивается у модели (внешний ресурс) — тот же случай 12 реестра проверяемости. Когда сторож
 * был красным по построению, вторая причина была та же: постоянный красный в полном прогоне стёр бы
 * различие «сломали» / «ещё не доделали». Теперь он зелёный и остаётся здесь по первой причине.
 *
 * # Границы
 *
 * Проверяется ЧИСЛО на модели. «Компилируется без отказов» здесь ничего не значит — отказов и не
 * было, дефект именно в том, что их не было. Железо проверено отдельной пробой (см. случай 86 в
 * `docs/verification-debt.md`): модель по этому классу уже расходилась с целью дважды (случаи 48, 52),
 * поэтому утверждение о железе держится на своём прогоне, а не на этом.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { loweredProgram } from './lowered';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');
const shim = buildShim();

/**
 * Источник с `N` значениями, живыми ЧЕРЕЗ вызов.
 *
 * `помощник` — ЛИСТОВАЯ процедура (без своего окна): этого достаточно, дефект проявляется и на
 * вызове листовой, то есть дело не в ширине кадра вызываемой, а в том, что вызов вообще затёр
 * клетку живого значения.
 */
function лестница(чисел: number): string {
  const строки: string[] = [
    'действие помощник(а)',
    '  вернуть а + 1',
    'конец',
    '',
    'действие главная()',
  ];
  for (let i = 0; i < чисел; i += 1) строки.push(`  пусть п${String(i)} = ${String(i + 1)}`);
  строки.push('  пусть б = помощник(1)');
  строки.push(`  пусть с = ${Array.from({ length: чисел }, (_, i) => `п${String(i)}`).join(' + ')}`);
  строки.push('  вывести с');
  строки.push('  вернуть 0', 'конец', '');
  return строки.join('\n');
}

/** Эталон считается АРИФМЕТИКОЙ ЗДЕСЬ, а не берётся из наших же чисел. */
function эталон(чисел: number): number {
  let сумма = 0;
  for (let i = 1; i <= чисел; i += 1) сумма += i;
  return сумма;
}

function наМодели(чисел: number): { вывод: readonly string[]; код?: number } {
  const текст = лестница(чисел);
  const разбор = parseV3(текст, 'вытеснение.osnova');
  const итог = loweredProgram(текст, {
    filename: 'вытеснение.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  expect(
    итог.ок,
    итог.ок ? '' : `непонижённые носители: ${итог.отказ.отказы.map((з) => з.причина).join('; ')}`,
  ).toBe(true);
  if (!итог.ок) throw new Error(`понижение отказало: ${итог.отказ.причина}`);
  const файл = path.join(ROOT, '.tmp', `spill-across-call-${String(чисел)}.elf`);
  fs.writeFileSync(
    файл,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 25_000 });
  return { вывод: (прогон?.stdout ?? '').split('\n').filter((с) => с !== ''), код: прогон?.status };
}

describe('порча окна вызовом (случай 86): значение, живое через вызов, обязано его пережить', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL-дистрибутиве нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('8 живых значений — ВЕРНО (36): сторож различает, а не зелёный при любом ответе', () => {
    const прогон = наМодели(8);
    expect(прогон.вывод, 'восемь живых через вызов: эталон 36').toEqual([String(эталон(8))]);
  });

  it('9 живых значений — 45: было 38, когда `п8` = 9 подменялось ОТВЕТОМ вызова (2)', () => {
    const прогон = наМодели(9);
    // Эталон 45. ДО правки D35 модель отдавала 38: `п8` = 9 подменялось ОТВЕТОМ (2), а само
    // значение сидело в клетке %b[8], которую вызов уничтожает.
    expect(прогон.вывод, 'девять живых через вызов: эталон 45 (до правки — 38)').toEqual([String(эталон(9))]);
  });

  it('14 живых значений — 105: было 98 (та же подмена %b[8]; нехватку клеток закрывает вытеснение)', () => {
    const прогон = наМодели(14);
    expect(прогон.вывод, 'четырнадцать живых через вызов: эталон 105 (до правки — 98)').toEqual([String(эталон(14))]);
  });
});

