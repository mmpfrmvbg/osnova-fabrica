/**
 * ОРАКУЛ АРНОСТИ ВЫЗОВА — ЧАСТЬ БЕЗ МОДЕЛИ: ФОРМА НОСИТЕЛЯ.
 *
 * # Повод — замер, а не пожелание
 *
 * `IR.invoke` нёс **два** аргумента, и оболочка отказывала **исключением** на третьем: программа
 * с таким вызовом не компилировалась вовсе. Измерено 2026-10-02:
 * `EmitterRefusalError: invoke: аргументов 3, носитель несёт не больше 2` — на
 * `система.массив.установить`, `система.массив.срез`, `система.коллекция.положить`.
 *
 * Цена предела больше, чем одна операция: **у цели (DF) действия гномов имеют 3–5 аргументов**,
 * и каждый такой вызов — блокер.
 *
 * # Физика записи: почему «дописать операнд» — не вся работа (ЗАМЕР)
 *
 * Носитель едет в записи оболочки (`src/e2k/encoding.ts#INSTRUCTION_SIZE`), и регистровых полей в
 * ней ровно ТРИ: `dst`, `src1`, `src2` (по 6 бит, старшие два бита — резерв). У `IR.invoke` они
 * заняты: `src1`, `src2` — два аргумента, `dst` — приёмник. Третьему аргументу нужно **четвёртое**
 * регистровое поле, поэтому одной правкой шаблона операндов дело не кончается.
 *
 * # Что здесь, а что в шлюзе
 *
 * Здесь — то, что живёт **на нашем слое** и не требует модели: длина формы и НЕСДВИНУТОСТЬ первых
 * пяти операндов. Модель спрашивает другое — дошёл ли третий аргумент до памяти
 * (`src/e2k/invokeArityQemu.test.ts`, шлюз `gate:qemu`). Разделение не косметическое: оракул,
 * которому нужен внешний ресурс, в полном прогоне стирает различие «сломали» и «машина занята»
 * (случай 12 реестра проверяемости).
 */
import { describe, it, expect } from 'vitest';
import { shellCarriers } from './programImage';
import { carrierSlots } from './shell';
import type { AsmInstruction } from './backend';

const модуль = (тело: string): string => `модуль Кол\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/** Носители `IR.invoke` на слое ОБОЛОЧКИ: там имя уже есть, а форма ещё не потеряна. */
function вызовы(source: string): readonly AsmInstruction[] {
  return shellCarriers(source).filter((carrier) => carrier.mnemonic === 'IR.invoke');
}

/** Программа с трёхаргументным вызовом — та, что до этой работы не компилировалась вовсе. */
const сУстановить = модуль(
  [
    '  пусть а = система.массив.создать()',
    '  система.массив.добавить(а, 1)',
    '  система.массив.добавить(а, 2)',
    '  система.массив.установить(а, 0, 42)',
    '  вернуть 0',
  ].join('\n'),
);

/** Арность носителя по его признакам: `flags = (есть приёмник) | (аргументов << 1)`. */
function арность(carrier: AsmInstruction): number {
  const flags = carrier.operands[0];
  return flags !== undefined && flags.kind === 'imm' ? flags.value >> 1 : -1;
}

describe('арность вызова: форма носителя', () => {
  it('ТРЕТИЙ АРГУМЕНТ ДОХОДИТ ДО НОСИТЕЛЯ: программа с ним компилируется', () => {
    // До правки здесь стояло исключение оболочки — то есть программа не доходила даже до
    // раскладки. Проверка держит именно это: не «число операндов», а «программа собралась».
    expect(() => shellCarriers(сУстановить), 'программа с тремя аргументами обязана собираться').not.toThrow();
    expect(вызовы(сУстановить).filter((carrier) => арность(carrier) === 3).length, 'трёхаргументный вызов есть').toBeGreaterThan(0);
  });

  it('ФОРМА: на два аргумента носитель пятиоперандный, на три — шестиоперандный', () => {
    // Операндов ровно столько, сколько несёт арность, и НИ ОДНИМ БОЛЬШЕ: проверяются обе стороны.
    // Первая редакция проверки требовала шести операндов у ВСЕХ вызовов программы — и падала на
    // `создать()` и `добавить`, которые ни при чём. Прибор показывал не то, что я думал.
    const два = вызовы(модуль('  система.массив.добавить(1, 2)\n  вернуть 0'));
    const три = вызовы(сУстановить);
    expect(два.filter((carrier) => арность(carrier) === 2).length, 'двухаргументный вызов есть').toBeGreaterThan(0);
    expect(три.filter((carrier) => арность(carrier) === 3).length, 'трёхаргументный вызов есть').toBeGreaterThan(0);
    for (const carrier of два) expect(carrier.operands, 'форма на два аргумента').toHaveLength(5);
    for (const carrier of три) {
      expect(carrier.operands.length, `форма на ${String(арность(carrier))} аргументов`).toBe(5 + (арность(carrier) >= 3 ? 1 : 0));
    }
  });

  it('ОБРАТНАЯ СОВМЕСТИМОСТЬ: первые пять операндов НЕ СДВИНУЛИСЬ', () => {
    // Это и есть совместимость, и проверяется она на самом носителе: сдвинься `payload` или
    // `dst` — молча прочли бы чужое все собранные руками оракулы (их около десяти), и доверие
    // к форме вместе с ними.
    const трёхаргументные = вызовы(сУстановить).filter((carrier) => арность(carrier) === 3);
    expect(трёхаргументные.length, 'есть что проверять').toBeGreaterThan(0);
    for (const carrier of трёхаргументные) {
      expect(carrier.operands[0]?.kind, 'flags — первым').toBe('imm');
      expect(carrier.operands[1]?.kind, 'первый аргумент — вторым').toBe('reg');
      expect(carrier.operands[2]?.kind, 'второй аргумент — третьим').toBe('reg');
      expect(carrier.operands[3]?.kind, 'payload — четвёртым, как было').toBe('imm');
      expect(carrier.operands[4]?.kind, 'приёмник — пятым, как было').toBe('reg');
      expect(carrier.operands[5]?.kind, 'третий аргумент — шестым').toBe('reg');
    }
    for (const carrier of вызовы(модуль('  система.массив.добавить(1, 2)\n  вернуть 0'))) {
      expect(carrier.operands[3]?.kind, 'у двухаргументного payload тоже четвёртым').toBe('imm');
      expect(carrier.operands[4]?.kind, 'и приёмник пятым').toBe('reg');
    }
  });

  it('ФИЗИКА ЗАПИСИ: третий аргумент едет СВОИМ полем, а не в резервных битах чужих', () => {
    // Замер, из которого вырос способ. Первая простая мысль — «взять резервные биты `dst`/`src1`/
    // `src2`» — отвергнута: резервные биты введены НАМЕРЕННО как условие негативного контроля
    // (`encoding.ts`), и занять их данными значит отдать контроль за место.
    const slots = carrierSlots('IR.invoke');
    expect(slots, 'у носителя есть шаблон полей').toBeDefined();
    expect(slots!.length, 'полей шесть: flags, src1, src2, imm, dst, src3').toBe(6);
    expect(slots!, 'третий аргумент — своё поле, а не чужое').toContain('src3');
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: пяти операндов на три аргумента НЕ ХВАТАЕТ', () => {
    // Контроль на сам оракул, и он арифметический: если бы форма на три аргумента осталась
    // пятиоперандной, проверки выше зеленели бы на носителе, который физически не может донести
    // третий аргумент, — то есть проверяли бы не то.
    const slots = carrierSlots('IR.invoke')!;
    /** Поля, которые аргументами НЕ являются: признаки, полезная нагрузка, приёмник. */
    const служебных = slots.filter((slot) => slot !== 'src1' && slot !== 'src2' && slot !== 'src3').length;
    expect(служебных, 'flags, imm и dst — три служебных поля').toBe(3);
    expect(slots.length - служебных, 'столько и максимум аргументов').toBe(3);
    expect(slots.length, 'в пяти операндах уместилось бы только два аргумента').toBeGreaterThan(5);
  });
});
