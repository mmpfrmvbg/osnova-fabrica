/**
 * ОРАКУЛ КОЛЛЕКЦИЙ НА `brk` — ШАГ ③: РАСШИРЕНИЕ (ПЕРЕЕЗД) ДОХОДИТ ДО ЦЕЛИ.
 *
 * # Что спрашивается и почему ИМЕННО ЭТО
 *
 * `система.коллекция.расширить(база, новая_ёмкость) → адрес` — единственная операция коллекций,
 * где одной проверкой границы не обойтись: она **выделяет новый блок и КОПИРУЕТ в него старые
 * элементы циклом**, а цикл — это уже поток управления, которого у `положить`/`взять` не было.
 *
 * Отсюда три независимых вопроса, и на каждый — своё наблюдение:
 *
 * | вопрос | чем спрашивается | почему не «что-то одно» |
 * |---|---|---|
 * | старые элементы ПЕРЕЕХАЛИ (а не пропали) | сумма всех значений после переезда | сумма, посчитанная по правилу, различает «все на месте» и «последний пропущен» |
 * | блок НОВЫЙ, старый не освобождён | `новая − база` = шаг СТАРОГО блока | «адрес ненулевой» не отличает переезд от возврата той же базы |
 * | заголовок несёт НОВУЮ ёмкость | запись по индексу `новая_ёмкость − 1` проходит, по `новая_ёмкость` — отказ | старая ёмкость в заголовке сделала бы блок «полным» ровно там, где он пуст |
 *
 * # Почему ожидания СЧИТАЮТСЯ, а не записаны числами
 *
 * Все три величины выводятся здесь из ОДНОГО правила — того же, по которому пишет программа
 * (`значение(индекс) = индекс + 1`), и того же шага блока, что у шага ① (`8 + ёмкость·8`,
 * `src/e2k/collectionsRuntime.ts`). Разойдись правило и ожидание — это находка, а не совпадение.
 *
 * # Негативные контроли — три, и каждый ловит СВОЙ класс
 *
 * 1. **Копирование пропускает последний элемент** — сумма обязана отличаться от полной. Это
 *    контроль на САМ оракул: если равенство когда-нибудь станет истинным (другая арифметика
 *    канала), приёмка перестанет что-либо доказывать, и её надо переделать.
 * 2. **`новая_ёмкость ≤ текущей`** — названный отказ: расширять некуда, и это НЕ выход за границу
 *    блока (у него свой текст, `src/e2k/collectionsRuntime.ts`). Спрашивается тем же каналом, что
 *    контроль 3 оракула владельца: код возврата 231 и строка в выводе.
 * 3. **`brk` не продвинул границу** — тоже названный отказ. Спрашивается ЧЕСТНО: у ядра
 *    запрашивается граница, которой быть не может, и наш рантайм обязан ЗАМЕТИТЬ ответ. До этой
 *    пробы контроль 2 оракула владельца умирал РАНЬШЕ — на кодировке литерала `2^40` (случай 35
 *    реестра проверяемости) — то есть проверял не то, что заявлял.
 *
 * # Чего этот оракул НЕ доказывает
 *
 * Ничего о переезде В ВЫЗЫВАЕМОЙ процедуре: коллекции работают в точке входа, и эта граница не
 * размывается (`src/e2k/collectionsRuntime.ts`, шапка). Ничего об освобождении старого блока —
 * освобождать нечем: арены без возврата (`§4.4`), и старый блок остаётся мёртвым.
 */
import { describe, it, expect } from 'vitest';
import { regModuleOf } from '../vliw/regOracle';
import { RegVM } from '../runtime/vm/reginterpreter';
import { createDefaultInvokeHandler } from '../runtime/vm/interpreter';
import { resolveEntryIndex } from '../oracle/parity';
import { runOnE2k } from '../scripts/e2kProgramRun';
import { buildShim } from '../scripts/e2kQemuExec';
import { COLLECTION_INVOKES } from '../runtime/vm/collectionCalls';

const shim = buildShim();

/** Модуль: заголовок программы в диалекте стенда (`regModuleOf`), как у оракулов шагов ① и ②. */
const модуль = (тело: string): string => `модуль Кол\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/**
 * ПРАВИЛО ЗАПИСИ — ОДНО на программу, эталон и ожидание.
 *
 * `значение(номер) = номер + 1`: 1, 2, 3… Пропуск последнего скопированного элемента меняет сумму
 * на его значение, и в 8-битном канале это видно (проверяет негативный контроль 1).
 */
const значение = (номер: number): number => номер + 1;

/** ШАГ БЛОКА — то же правило, что у шага ①: заголовок плюс элементы. */
const ШАГ = 8;
function шагБлока(ёмкость: number): number {
  return ШАГ + ёмкость * ШАГ;
}

/** Сумма значений по правилу — эталон считается, а не берётся числом. */
function эталонСуммы(сколько: number, смещение = 0): number {
  let сумма = 0;
  for (let номер = 0; номер < сколько; номер++) сумма += значение(номер + смещение);
  return сумма;
}

/** Значение на РЕГИСТРОВОЙ VM — эталон языка. */
async function наVM(source: string): Promise<number> {
  const built = regModuleOf(source);
  expect(built, 'программа обязана компилироваться').not.toBeNull();
  const entry = resolveEntryIndex(built!.module.procedures, undefined) ?? 0;
  const vm = new RegVM(built!.module, {
    invoke: createDefaultInvokeHandler(),
    extraInvokes: COLLECTION_INVOKES,
    maxSteps: 2_000_000,
  });
  return Number(await vm.runProcedure(entry, []));
}

/** Ответ МОДЕЛИ: три канала, а не один (`refused` — статика, `status`+`output` — прогон). */
function наМодели(
  source: string,
  файл: string,
): { status: number | undefined; refused: readonly string[]; output: string } {
  const прогон = runOnE2k(source, файл);
  return {
    status: прогон.status,
    refused: прогон.refused.map((item) => `${item.code} ${item.reason}`),
    output: прогон.output,
  };
}

/** Код возврата и текст отказа: тот же канал, что у арены и у шага ② (`231`). */
const ОТКАЗ_КОД = 231;

describe('коллекции на brk, шаг ③: расширение — переезд в новый блок', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('ПРИЁМКА: расширить(4 → 8) — старые элементы ПЕРЕЕХАЛИ, пятый влезает, сумма сходится', async () => {
    const СТАРАЯ = 4;
    const НОВАЯ = 8;
    const строки = [`  пусть база = система.коллекция.выделить(${String(СТАРАЯ)})`];
    for (let номер = 0; номер < СТАРАЯ; номер++) {
      строки.push(`  система.коллекция.положить(база, ${String(номер)}, ${String(значение(номер))})`);
    }
    строки.push(`  пусть новая = система.коллекция.расширить(база, ${String(НОВАЯ)})`);
    // ПЯТЫЙ ЭЛЕМЕНТ — по индексу, которого в СТАРОМ блоке не было: он доказывает и то, что цикл
    // копирования не тронул новый хвост, и то, что заголовок несёт НОВУЮ ёмкость.
    строки.push(`  система.коллекция.положить(новая, ${String(СТАРАЯ)}, ${String(значение(СТАРАЯ))})`);
    строки.push(
      `  вернуть ${Array.from({ length: СТАРАЯ + 1 }, (_, номер) => `система.коллекция.взять(новая, ${String(номер)})`).join(' + ')}`,
    );
    const source = модуль(строки.join('\n'));
    const эталон = эталонСуммы(СТАРАЯ + 1);
    expect(эталон, `сумма ${String(СТАРАЯ + 1)} значений по правилу «номер + 1»`).toBe(15);
    expect(await наVM(source), 'эталон языка').toBe(эталон);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-resize.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, `модель: сумма после переезда (эталон ${String(эталон)})`).toBe(эталон);
  });

  it('БЛОК НОВЫЙ, СТАРЫЙ НЕ ОСВОБОЖДЁН: `новая − база` равна шагу СТАРОГО блока', async () => {
    // ВТОРОЕ НАБЛЮДЕНИЕ того же свойства — с ДРУГОЙ ёмкостью: «40» могло бы получиться и от
    // жёсткой константы, а шаг зависит от ёмкости (это уже показано на шаге ①, здесь — про переезд).
    for (const [старая, новая] of [
      [4, 8],
      [2, 3],
    ] as const) {
      const source = модуль(
        [
          `  пусть база = система.коллекция.выделить(${String(старая)})`,
          `  пусть новая = система.коллекция.расширить(база, ${String(новая)})`,
          '  вернуть новая - база',
        ].join('\n'),
      );
      const ожидание = шагБлока(старая);
      expect(await наVM(source), `эталон: переезд на шаг старого блока (${String(старая)} → ${String(новая)})`).toBe(
        ожидание,
      );
      if (shim === undefined) continue;
      const { status, refused } = наМодели(source, `collections-resize-step-${String(старая)}.elf`);
      expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
      expect(status, `модель: переезд на шаг старого блока (${String(старая)} → ${String(новая)})`).toBe(ожидание);
    }
  });

  it('ЗАГОЛОВОК НЕСЁТ НОВУЮ ЁМКОСТЬ: последний законный индекс проходит, следующий — отказ', async () => {
    const source = модуль(
      [
        '  пусть база = система.коллекция.выделить(4)',
        '  система.коллекция.положить(база, 0, 11)',
        '  пусть новая = система.коллекция.расширить(база, 8)',
        '  система.коллекция.положить(новая, 7, 22)',
        '  вернуть система.коллекция.взять(новая, 7) + система.коллекция.взять(новая, 0)',
      ].join('\n'),
    );
    expect(await наVM(source), 'эталон: 22 + 11').toBe(33);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-resize-header.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, 'модель: 33').toBe(33);
    // И ОТРИЦАТЕЛЬНАЯ СТОРОНА ТОЙ ЖЕ ГРАНИЦЫ: индекс, равный новой ёмкости, — отказ. Без неё
    // «22 + 11» прошло бы и у реализации, которая просто не проверяет границу нового блока.
    const заГраницей = модуль(
      [
        '  пусть база = система.коллекция.выделить(4)',
        '  пусть новая = система.коллекция.расширить(база, 8)',
        '  система.коллекция.положить(новая, 8, 1)',
        '  вернуть 7',
      ].join('\n'),
    );
    const отказ = наМодели(заГраницей, 'collections-resize-header-oob.elf');
    expect(отказ.status, 'индекс == ёмкости — отказ').toBe(ОТКАЗ_КОД);
    expect(отказ.output, 'текст — про индекс, а не про переезд').toContain('коллекция: индекс вне ёмкости блока');
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 1: пропуск последнего элемента при копировании — сумма ДРУГАЯ', () => {
    // Контроль на САМ оракул: он обязан различать «все четыре переехали» и «последний пропущен»
    // в 8-битном канале. Полная сумма 1+2+3+4+5 = 15; если бы копия потеряла значение 4 (индекс 3),
    // сумма стала бы 11 — и 15 ≠ 11 по модулю 256.
    const полная = эталонСуммы(5);
    const безПоследнего = эталонСуммы(3) + значение(4);
    expect(полная, 'полная сумма').toBe(15);
    expect(безПоследнего, 'сумма при пропущенном последнем СТАРОМ элементе').toBe(11);
    expect(полная % 256, 'канал обязан различать 15 и 11').not.toBe(безПоследнего % 256);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 2: `новая_ёмкость ≤ текущей` — НАЗВАННЫЙ отказ, а не молчание', async () => {
    // Расширять некуда: блок не растёт, и это НЕ выход за границу — у причины свой текст.
    const source = модуль(
      ['  пусть база = система.коллекция.выделить(4)', '  пусть новая = система.коллекция.расширить(база, 4)', '  вернуть 7'].join(
        '\n',
      ),
    );
    // Эталон языка обязан отказать ТЕМ ЖЕ свойством: «не больше текущей» — это семантика операции,
    // а не особенность цели (`src/runtime/vm/interpreter.ts`).
    await expect(наVM(source), 'эталон обязан назвать причину').rejects.toThrow(/ёмкост/u);
    if (shim === undefined) return;
    const { status, refused, output } = наМодели(source, 'collections-resize-same.elf');
    expect(refused, 'это отказ ПРОГОНА, а не понижения').toEqual([]);
    expect(status, 'код отказа — тот же, что у арены').toBe(ОТКАЗ_КОД);
    expect(output, 'причина обязана быть названа своей строкой').toContain('коллекция: новая ёмкость не больше текущей');
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 3: `brk` НЕ ДАЛ запрошенную границу — НАЗВАННЫЙ отказ, а не молчание', async () => {
    // ЗДЕСЬ БЫЛО УТВЕРЖДЕНИЕ, КОТОРОЕ ЗАМЕР СНЯЛ (§2.5), и снято оно дважды:
    //
    // 1. Проба умирала РАНЬШЕ `brk` — на кодировке литерала `2^40`: `movts` его не несёт (случай 35
    //    реестра проверяемости). Событие, о котором спрашивалось, не наступало вовсе.
    // 2. Даже дойдя до `brk`, запрос такой величины до ядра ЦЕЛИКОМ не доходит: граница кладётся в
    //    оконный регистр командой `adds` (форма S — младшие 32 бита). Прежнее «ядро отвечает
    //    -ENOMEM» — замер `mmap` (§3.94.1), к `brk` не отнесённый.
    //
    // ЧТО ИЗМЕРЕНО (2026-10-03, `.tmp/probe-huge-alloc.ts`, настоящие программы): ёмкость `2^24`
    // (сдвиг 128 МиБ) проходит, а `2^28` (сдвиг 2 ГиБ) даёт **код 231 и текст «куча не выросла —
    // brk не дал запрошенную границу»** — то есть отказ ядра ДОСТИЖИМ, и проверка ответа `brk`
    // наблюдаема прогоном. Спрашивается ДВУМЯ наблюдениями, и второе обязательно: без него «231» не
    // отличалось бы от «отказывает всегда».
    const отказ = модуль(
      [
        '  пусть база = система.коллекция.выделить(2)',
        '  пусть новая = система.коллекция.расширить(база, 268435456)',
        '  вернуть 7',
      ].join('\n'),
    );
    const прошла = модуль(
      [
        '  пусть база = система.коллекция.выделить(2)',
        '  пусть новая = система.коллекция.расширить(база, 16777216)',
        '  вернуть 7',
      ].join('\n'),
    );
    // Эталон языка и здесь обязан отказать — но по СВОЕЙ причине: у VM адресов нет, и «куча» там
    // не кончается. Асимметрия НАЗВАНА, а не умолчана: отказ `brk` — свойство ЦЕЛИ.
    if (shim === undefined) return;
    const неудача = наМодели(отказ, 'collections-resize-brk.elf');
    expect(неудача.refused, 'отказ об ответе `brk` — ПРОГОННЫЙ, а не понижения').toEqual([]);
    expect(неудача.status, 'отказ ядра обязан стать НАЗВАННЫМ').toBe(ОТКАЗ_КОД);
    expect(неудача.output, 'и назвать ПАМЯТЬ, а не индекс и не ёмкость').toMatch(/куч|brk|памят/u);
    const удача = наМодели(прошла, 'collections-resize-brk-ok.elf');
    expect(удача.refused, `отказы понижения: ${удача.refused.join('; ')}`).toEqual([]);
    expect(удача.status, 'меньшая ёмкость проходит — программа идёт своим выходом').toBe(7);
    expect(удача.output, 'и отказа памяти при ней нет').not.toMatch(/куч|brk|памят/u);
  });
});
