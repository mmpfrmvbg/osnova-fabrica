const число = (значение: unknown): number | undefined => {
  if (значение === true) return 1;
  if (значение === false) return 0;
  return typeof значение === 'number' ? значение : undefined;
};

/** Эталон ОБЕИХ VM — независимая от цели мерка (тот же приём, что у оракулов плоскости). */
const обеVms = async (текст: string): Promise<{ стек?: number; регистры?: number; беда?: string }> => {
  const разбор = parseV3(текст, ФАЙЛ);
  if (разбор.errors.length > 0) return { беда: `разбор: ${JSON.stringify(разбор.errors)}` };
  const м = разбор.program!.modules[0]!;
  const проход = validateNamedTypesAndRewrite(м);
  if (проход.length > 0) return { беда: `проход: ${JSON.stringify(проход)}` };
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = число(await стековая.runProcedure(стековая.findProcedureIndex('главная'), []));
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = число(await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []));
  return { стек, регистры };
};

/** Исход пробы — РОВНО два вида, и третьего быть не может (образ и отказ не стоят вместе). */
type Исход =
  | { readonly вид: 'собралось'; readonly код: number | undefined; readonly байт: number }
  | { readonly вид: 'отказ'; readonly причина: string; readonly код: string; readonly отказов: number; readonly кодовБайт: number };

/** Одна причина отказа — для сообщений о красном: без неё непонятно, ЧЕМ отказ назван. */
const причиныОтказа = (отказ: Отказ): string =>
  отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`).join(' | ');

/**
 * Замер ПУБЛИЧНОЙ двери и (при исходе-образе) прогон его в модели. Сырая дверь здесь не берётся
 * НАМЕРЕННО: приёмка идёт по публичному контракту, где под отказом байтов нет.
 */
const замеры = new Map<string, Исход>();

const замерить = (проба: Проба): Исход => {
  const уже = замеры.get(проба.имя);
  if (уже !== undefined) return уже;
  const текст = проба.строки.join('\n');
  const разбор = parseV3(текст, ФАЙЛ);
  expect(разбор.errors, `${проба.имя}: разбор программы`).toEqual([]);
  // ПОТРЕБИТЕЛЬ (D11): под отказом байтов нет — дверь отдаёт Результат<Образ, Отказ>.
  const итог = loweredProgram(текст, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  // «РОВНО ОДИН ИСХОД» проверяется явно, а не подразумевается: ветви двери не пересекаются.
  expect('значение' in итог, `${проба.имя}: у ответа двери обязана быть ровно ОДНА ветвь`).toBe(итог.ок);
  expect('отказ' in итог, `${проба.имя}: у ответа двери обязана быть ровно ОДНА ветвь`).toBe(!итог.ок);

  if (!итог.ок) {
    const отказ = итог.отказ;
    if (проба.точкаВхода === true) {
      throw new Error(
        `${проба.имя}: КОНТРОЛЬ ТОЧКИ ВХОДА ОБЯЗАН СОБРАТЬСЯ, а дверь отказала (${причиныОтказа(отказ)}) — ` +
          'значит граница «в плоскости» сломана, и отказ классов A–Д больше не доказывает плоскость',
      );
    }
    // ИСХОД (2): отказ. Публичный контракт: БАЙТОВ ЗДЕСЬ НЕТ — и не может быть.
    expect('bytes' in отказ, `${проба.имя}: D11 нарушен — под отказом просочились БАЙТЫ`).toBe(false);
    expect(Object.keys(отказ), `${проба.имя}: в публичном Отказе появилось поле байтов`).not.toContain('bytes');
    expect(отказ.отказы.length, `${проба.имя}: отказ обязан быть НАЗВАН записью`).toBeGreaterThan(0);
    expect(отказ.процедуры.length, `${проба.имя}: отказ обязан назвать процедуру (четвёртая ложь, случай 58)`).toBeGreaterThan(0);
    expect(отказ.причина, `${проба.имя}: причина обязана назвать ПЛОСКОСТЬ`).toMatch(/вызываемой/iu);
    for (const запись of отказ.отказы) {
      expect(запись.код, `${проба.имя}: код отказа обязан быть кодом причины, а не текстом`).toMatch(/^OSN-LOW-/);
      expect(запись.причина, `${проба.имя}: запись обязана назвать ПЛОСКОСТЬ`).toMatch(/вызываемой/iu);
    }
    const исход: Исход = {
      вид: 'отказ',
      причина: отказ.причина,
      код: отказ.отказы[0]!.код,
      отказов: отказ.отказы.length,
      кодовБайт: отказ.кодовБайт,
    };
    замеры.set(проба.имя, исход);
    return исход;
  }

  // ИСХОД (1): образ. Число спрашивается у модели — и обязано совпасть с эталоном ОБЕИХ VM.
  const образ = итог.значение;
  expect('bytes' in образ, `${проба.имя}: у образа обязаны быть байты`).toBe(true);
  const файл = path.join(ROOT, '.tmp', `callee-plane-${проба.имя}.elf`);
  fs.writeFileSync(
    файл,
    buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: образ.arena.extraMemory }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 20_000 });
  expect(
    прогон?.status,
    `${проба.имя}: ТИХАЯ ЛОЖЬ БЕЗ ОТКАЗА — собралось без отказа, но модель дала ${String(прогон?.status)} ` +
      `против эталона ${String(проба.эталон)} (${проба.рука}). Это СТОП-условие: ожидание не подгонять`,
  ).toBe(проба.эталон);
  // `?? undefined` — не глушение: выше проверено `прогон?.status === эталон`, поэтому `null` (сигнал) и
  // `undefined` (модель не запустилась) сюда дойти не могут, а тип у `runInQemu` шире (`number | null`).
  const исход: Исход = { вид: 'собралось', код: прогон?.status ?? undefined, байт: образ.bytes.length };
  замеры.set(проба.имя, исход);
  return исход;
};

