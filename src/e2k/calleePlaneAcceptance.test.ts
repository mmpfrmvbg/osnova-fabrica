/**
 * ПРИЁМКА СЕДЬМОЙ ТИХОЙ ЛЖИ **МАТРИЦЕЙ КЛАССОВ** (D9) В ПЛОСКОСТИ ВЫЗЫВАЕМОЙ — ЧЕРЕЗ ПУБЛИЧНУЮ ДВЕРЬ.
 *
 * # Что здесь принимается
 *
 * Седьмая тихая ложь (случай 62): «склейка» короткого замыкания ВНУТРИ `процедура` — выпуск ветвления по
 * значению требует клетки, равной нулю ПО ПОСТРОЕНИЮ, а в плоскости вызываемой её нет (`%b[12]` там
 * чужая клетка, а `%b[12]` вызываемой раскладка отдаёт под значения). Причина — `src/e2k/e2kRealRun.ts`,
 * ветка `context.inCallee === true`; решение 5е по задаче 3 — **ЧЕСТНЫЙ ОТКАЗ**: публичная дверь
 * `src/e2k/lowered.ts#loweredProgram` байтов под отказом не отдаёт вовсе (D11).
 *
 * ПОЧЕМУ МАТРИЦЕЙ, А НЕ ТОЧКОЙ (D9). Одна проба не различает «сломан класс» и «сломан этот вход»: ложь
 * случая 62 не зависела от значений (одно и то же **9** при эталонах 1 и 7), а класс «чтение после
 * ветви» (случая 60) отличался от неё ровно тем, что тело ветви ПРОПУЩЕНО, а переменная читается ПОСЛЕ.
 * Поэтому здесь каждый класс спрашивается НЕ МЕНЬШЕ ЧЕМ ДВУМЯ входами, а полнота матрицы проверяется
 * отдельной пробой. **Приёмка одной точкой запрещена**: она пропускает и «другой вход», и «другую
 * форму», и «другую плоскость».
 *
 * # ИЗМЕРЕНО (первый прогон, 2026-10-29; замер — `.tmp/a5e-matrix-probe.ts`)
 *
 * | класс | входы | эталон обеих VM | исход ПУБЛИЧНОЙ двери | байтов у сырого пути |
 * |---|---|---|---|---|
 * | A оба терма истинны | 50, 57 | 7, 7 | **Отказ ×1**, `OSN-LOW-004`, причина о ПЛОСКОСТИ | 456, 456 |
 * | Б первый ложен (замыкание) | 10, 47 | 0, 0 | **Отказ ×1**, то же | 448, 456 |
 * | В первый истинен, второй ложен | 58, 100 | 0, 0 | **Отказ ×1**, то же | 456, 456 |
 * | Г смесь `или` | 0, 50, 10 | 7, 7, 0 | **Отказ ×1**, то же | 488, 496, 488 |
 * | Д чтение после ветви (случай 60) | 10, 100, 50 | 5, 5, 7 | **Отказ ×1**, то же | 424, 432, 432 |
 * | Е КОНТРОЛЬ: та же форма в точке входа | 50, 10 | 1, 0 | **СОБРАЛОСЬ**, модель 1 и 0 (360 и 352 байта) | — |
 *
 * Отсюда и предмет приёмки: **исход-отказ** обязан быть БЕЗ БАЙТОВ (иначе ложь вернулась бы через
 * публичный API), **исход-образ** обязан дать эталон обеих VM (иначе это тихая ложь БЕЗ отказа — самый
 * худший класс, D4), а **третьего исхода быть не может**. Граница — ПЛОСКОСТЬ, а не форма: класс Е
 * собирается и верен, поэтому отказ классов A–Д нельзя списать на «форма не понижается».
 *
 * # Чего оракул НЕ делает
 *
 * Не чинит ложь: закрепление клетки нуля у вызываемой — отдельный долг с планом (§3.149), не эта задача.
 * И не смотрит под отказом: сырую дверь (`src/e2k/guards/loweredUnchecked.ts`) здесь брать нельзя — она
 * для сторожей, а здесь принимается ПУБЛИЧНЫЙ контракт (D11).
 */
