const число = (значение: unknown): number | undefined => {
  if (значение === true) return 1;
  if (значение === false) return 0;
  return typeof значение === 'number' ? значение : undefined;
};

/** Эталон ОБЕИХ VM — независимая от цели мерка (тот же приём, что у оракулов плоскости). */
const обеVms = async (текст: string): Promise<{ стек?: number; регистры?: number; беда?: string }> => {
  const разбор = parseV3(текст, ФАЙЛ);
  if (разбор.errors.length > 0) return { беда: `разбор: ${JSON.stringify(разбор.errors)}` };
  const м = разбор.program!.modules[0]!;
  const проход = validateNamedTypesAndRewrite(м);
  if (проход.length > 0) return { беда: `проход: ${JSON.stringify(проход)}` };
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = число(await стековая.runProcedure(стековая.findProcedureIndex('главная'), []));
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = число(await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []));
  return { стек, регистры };
};

/** Исход пробы — РОВНО два вида, и третьего быть не может (образ и отказ не стоят вместе). */
type Исход =
  | { readonly вид: 'собралось'; readonly код: number | undefined; readonly байт: number }
  | { readonly вид: 'отказ'; readonly причина: string; readonly код: string; readonly отказов: number; readonly кодовБайт: number };

/** Одна причина отказа — для сообщений о красном: без неё непонятно, ЧЕМ отказ назван. */
const причиныОтказа = (отказ: Отказ): string =>
  отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`).join(' | ');

/**
 * Замер ПУБЛИЧНОЙ двери и (при исходе-образе) прогон его в модели. Сырая дверь здесь не берётся
 * НАМЕРЕННО: приёмка идёт по публичному контракту, где под отказом байтов нет.
 */
const замеры = new Map<string, Исход>();

const замерить = (проба: Проба): Исход => {
  const уже = замеры.get(проба.имя);
  if (уже !== undefined) return уже;
  const текст = проба.строки.join('\n');
  const разбор = parseV3(текст, ФАЙЛ);
  expect(разбор.errors, `${проба.имя}: разбор программы`).toEqual([]);
  // ПОТРЕБИТЕЛЬ (D11): под отказом байтов нет — дверь отдаёт Результат<Образ, Отказ>.
  const итог = loweredProgram(текст, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  // «РОВНО ОДИН ИСХОД» проверяется явно, а не подразумевается: ветви двери не пересекаются.
  expect('значение' in итог, `${проба.имя}: у ответа двери обязана быть ровно ОДНА ветвь`).toBe(итог.ок);
  expect('отказ' in итог, `${проба.имя}: у ответа двери обязана быть ровно ОДНА ветвь`).toBe(!итог.ок);

  if (!итог.ок) {
    const отказ = итог.отказ;
    if (проба.точкаВхода === true) {
      throw new Error(
        `${проба.имя}: КОНТРОЛЬ ТОЧКИ ВХОДА ОБЯЗАН СОБРАТЬСЯ, а дверь отказала (${причиныОтказа(отказ)}) — ` +
          'значит граница «в плоскости» сломана, и отказ классов A–Д больше не доказывает плоскость',
      );
    }
    // ИСХОД (2): отказ. Публичный контракт: БАЙТОВ ЗДЕСЬ НЕТ — и не может быть.
    expect('bytes' in отказ, `${проба.имя}: D11 нарушен — под отказом просочились БАЙТЫ`).toBe(false);
    expect(Object.keys(отказ), `${проба.имя}: в публичном Отказе появилось поле байтов`).not.toContain('bytes');
    expect(отказ.отказы.length, `${проба.имя}: отказ обязан быть НАЗВАН записью`).toBeGreaterThan(0);
    expect(отказ.процедуры.length, `${проба.имя}: отказ обязан назвать процедуру (четвёртая ложь, случай 58)`).toBeGreaterThan(0);
    expect(отказ.причина, `${проба.имя}: причина обязана назвать ПЛОСКОСТЬ`).toMatch(/вызываемой/iu);
    for (const запись of отказ.отказы) {
      expect(запись.код, `${проба.имя}: код отказа обязан быть кодом причины, а не текстом`).toMatch(/^OSN-LOW-/);
      expect(запись.причина, `${проба.имя}: запись обязана назвать ПЛОСКОСТЬ`).toMatch(/вызываемой/iu);
    }
    const исход: Исход = {
      вид: 'отказ',
      причина: отказ.причина,
      код: отказ.отказы[0]!.код,
      отказов: отказ.отказы.length,
      кодовБайт: отказ.кодовБайт,
    };
    замеры.set(проба.имя, исход);
    return исход;
  }

  // ИСХОД (1): образ. Число спрашивается у модели — и обязано совпасть с эталоном ОБЕИХ VM.
  const образ = итог.значение;
  expect('bytes' in образ, `${проба.имя}: у образа обязаны быть байты`).toBe(true);
  const файл = path.join(ROOT, '.tmp', `callee-plane-${проба.имя}.elf`);
  fs.writeFileSync(
    файл,
    buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: образ.arena.extraMemory }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 20_000 });
  expect(
    прогон?.status,
    `${проба.имя}: ТИХАЯ ЛОЖЬ БЕЗ ОТКАЗА — собралось без отказа, но модель дала ${String(прогон?.status)} ` +
      `против эталона ${String(проба.эталон)} (${проба.рука}). Это СТОП-условие: ожидание не подгонять`,
  ).toBe(проба.эталон);
  // `?? undefined` — не глушение: выше проверено `прогон?.status === эталон`, поэтому `null` (сигнал) и
  // `undefined` (модель не запустилась) сюда дойти не могут, а тип у `runInQemu` шире (`number | null`).
  const исход: Исход = { вид: 'собралось', код: прогон?.status ?? undefined, байт: образ.bytes.length };
  замеры.set(проба.имя, исход);
  return исход;
};

const пробыКласса = (класс: string): readonly Проба[] => ПРОБЫ.filter((проба) => проба.класс === класс);

describe('A4-5е/5з.4: седьмая ложь И ЦЕПОЧКА «склеек» (случай 68) принимаются МАТРИЦЕЙ классов (D9)', () => {
  it('шим обязан быть: без модели приёмка КРАСНЕЕТ, а не пропускается молча (случай 12)', () => {
    expect(shim, 'шим не собран — прогон в модели невозможен, и «зелено» здесь было бы ложью').toBeDefined();
    if (shim === undefined) return;
    expect(shim.length).toBeGreaterThan(3);
  });

  it('D9: приёмка МАТРИЦЕЙ, а не точкой — у каждого класса не меньше ДВУХ входов, имена проб уникальны', () => {
    for (const класс of [...КЛАССЫ_ЛЖИ, КЛАСС_Е]) {
      expect(
        пробыКласса(класс).length,
        `класс «${класс}» спрашивается одной точкой — D9 запрещает: один вход не отличает «сломан класс» от «сломан вход»`,
      ).toBeGreaterThanOrEqual(2);
    }
    expect(new Set(ПРОБЫ.map((проба) => проба.имя)).size, 'имена проб обязаны быть уникальны').toBe(ПРОБЫ.length);
  });

  it('эталон от руки подтверждён ОБЕИМИ VM независимо от цели — иначе мерка сломана, а не программа', async () => {
    const беды: string[] = [];
    for (const проба of ПРОБЫ) {
      const вм = await обеVms(проба.строки.join('\n'));
      if (вм.беда !== undefined) {
        беды.push(`${проба.имя}: ${вм.беда}`);
        continue;
      }
      if (вм.стек !== проба.эталон) беды.push(`${проба.имя}: стековая ${String(вм.стек)}, эталон ${String(проба.эталон)}`);
      if (вм.регистры !== проба.эталон) беды.push(`${проба.имя}: регистровая ${String(вм.регистры)}, эталон ${String(проба.эталон)}`);
    }
    expect(беды, 'эталон не подтверждён обеими VM').toEqual([]);
  });

  it('МАТРИЦА: каждая проба — РОВНО ОДИН исход, и этот исход есть ОБРАЗ с эталонным числом (7е и 68 починены)', () => {
    // ПЕРЕМЕР 2026-11-04 (атом 5з.4). Прежняя редакция принимала ДВА исхода: образ ЛИБО названный отказ
    // о плоскости (запись KNOWN BAD среза 5е). Оба повода сняты ПРИЧИНОЙ: клетка нуля вызываемой
    // закреплена (ATOM-05-02-01, §3.166), а цепочка «склеек» замкнута (случай 68). Поэтому исход теперь
    // ОДИН — образ с эталоном; ЛЮБОЙ отказ здесь краснеет: он означал бы, что граница в плоскости
    // вернулась, а вместе с ней и класс «собирается и врёт».
    const строки: string[] = [];
    const беды: string[] = [];
    for (const класс of КЛАССЫ_ЛЖИ) {
      for (const проба of пробыКласса(класс)) {
        const исход = замерить(проба);
        if (исход.вид === 'собралось') {
          строки.push(`  ${проба.класс} | ${проба.имя} (вход ${String(проба.вход)}) | СОБРАЛОСЬ ${String(исход.байт)} б | модель ${String(исход.код)} = эталон ${String(проба.эталон)}`);
          if (исход.код !== проба.эталон) {
            беды.push(`${проба.имя}: модель ${String(исход.код)} вместо эталона ${String(проба.эталон)} (${проба.рука}) — ТИХАЯ ЛОЖЬ`);
          }
          continue;
        }
        беды.push(
          `${проба.имя}: отказ ${исход.код} ×${String(исход.отказов)} — граница в ПЛОСКОСТИ ВЕРНУЛАСЬ? ` +
            `Класс A–Д обязан собираться (${исход.причина})`,
        );
      }
    }
    console.log(`матрица классов (публичная дверь D11):\n${строки.join('\n')}`);
    expect(беды, 'матрица классов: исход не тот, каким он измерен').toEqual([]);
    expect(строки.length, 'каждая проба обязана иметь РОВНО ОДИН исход: третьего не бывает').toBe(
      ПРОБЫ.length - пробыКласса(КЛАСС_Е).length,
    );
  });

  it('СЛУЧАЙ 68 (класс Г): истинная конъюнкция даёт 7, ложная — 0, и это РАЗНЫЕ числа одной формы', () => {
    // Класс Г — ровно форма случая 68: `(а >= 48 и а <= 57) или а == 0`. До правки проба
    // «Г-50-конъюнкция-истинна» собиралась и отдавала НЕ ЭТАЛОН (тихая ложь). Здесь закреплено то, чем
    // ложь названа: РАЗНЫЕ входы одной формы дают РАЗНЫЕ числа (7 и 0), поэтому «вернулось совпадение»
    // не пройдёт; и отказов нет ни на одной пробе класса — иначе починка была бы потерей возможности.
    const проба = (имя: string): Проба => пробыКласса(КЛАСС_Г).find((кандидат) => кандидат.имя === имя)!;
    const истинна = замерить(проба('Г-50-конъюнкция-истинна'));
    const ложны = замерить(проба('Г-10-обе-ложны'));
    const спасает = замерить(проба('Г-0-или-спасает'));
    expect(истинна.вид, 'Г-50: цепочка «склеек» снова отказала — замыкание потеряно').toBe('собралось');
    expect(ложны.вид).toBe('собралось');
    expect(спасает.вид).toBe('собралось');
    expect(
      [истинна.вид === 'собралось' ? истинна.код : undefined,
       спасает.вид === 'собралось' ? спасает.код : undefined,
       ложны.вид === 'собралось' ? ложны.код : undefined],
      'одна форма дала не те числа: 7 / 7 / 0 — иначе число не читается, а совпадает',
    ).toEqual([7, 7, 0]);
  });

  it('класс Д (случай 60): эталон ОТЛИЧАЕТСЯ и от значения терма, и от входа — иначе утечка была бы невидна', () => {
    const пробы = пробыКласса(КЛАСС_Д);
    expect(пробы.length, 'контроль обязан спрашиваться не одной точкой (D9)').toBeGreaterThanOrEqual(2);
    for (const проба of пробы) {
      expect(проба.значениеТерма, `${проба.имя}: у контроля обязан быть назван значение терма`).toBeDefined();
      expect(
        проба.эталон,
        `${проба.имя}: эталон совпал со ЗНАЧЕНИЕМ ТЕРМА (${String(проба.значениеТерма)}) — проба не различила бы утечку 62`,
      ).not.toBe(проба.значениеТерма);
      expect(
        проба.эталон,
        `${проба.имя}: эталон совпал со ВХОДОМ (${String(проба.вход)}) — проба не различила бы утечку 60 («равна а»)`,
      ).not.toBe(проба.вход);
    }
  });

  it('класс Е (КОНТРОЛЬ): та же форма в ТОЧКЕ ВХОДА собирается и даёт эталон — починка не плоскостная', () => {
    for (const проба of пробыКласса(КЛАСС_Е)) {
      const исход = замерить(проба);
      expect(
        исход.вид,
        `${проба.имя}: контроль точки входа отказал (${исход.вид === 'отказ' ? исход.причина : ''}) — ` +
          'тогда «в плоскости вызываемой всё сошлось» ничего не доказывает: форма сломана целиком',
      ).toBe('собралось');
    }
  });
});
