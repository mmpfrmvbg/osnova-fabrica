/**
 * СТОРОЖ ГРАНИЦЫ K2: ВЫТЕСНЕНИЕ В ВЫЗЫВАЕМОЙ ПРОЦЕДУРЕ (A4, срез 5).
 *
 * # Зачем и что здесь закреплено
 *
 * Кусок A4-4 разложил 144 отказа лексера по видам: **39** из них — вытеснение в вызываемой
 * (`IR.spill_st` 12 + `IR.spill_ld` 27). Этот файл закрепляет ИЗМЕРЕННОЕ устройство той стены —
 * числами и текстом, а не пересказом в комментарии.
 *
 * Что измерено (числа сняты пробами `.tmp/k2-boundary-numbers.ts` — границы и прогоны в модели,
 * `.tmp/k2-attribution.ts` — атрибуция и носители, `.tmp/k2-entry-spills.ts` — вытеснение в действии,
 * `.tmp/k2-plan-cost.ts` — цена закрепления клетки, `.tmp/negative-k2.ts` — негативный контроль):
 *
 * | что | замер |
 * |---|---|
 * | **чистое репро есть** | `7` одновременно живых значений в ВЫЗЫВАЕМОЙ: 2 отказа (1 `IR.spill_st` + 1 `IR.spill_ld`), образ 536 байт; 8 живых — 4 отказа (576), 9 живых — 6 (616) |
 * | работающая сторона в САМОЙ вызываемой | 5 живых — 0 отказов, модель **20**; 6 живых — 0 отказов, модель **27** (456/496 байт) |
 * | работающая сторона в ДЕЙСТВИИ | двойник 7/8/9/10 живых — 0 отказов, модель **35 / 44 / 54 / 65** (432/472/560/648 байт) |
 * | вытеснение в плоскости точки входа РАБОТАЕТ | по отчёту раскладки `n=9` — `spilled=1` (2 носителя), `n=10` — `spilled=2` (4 носителя), и модель даёт верные числа |
 * | атрибуция 39 | тело лексера: вытесняет РОВНО ОДНА процедура — `лексировать` (`ok used=8 spilled=4`, предел `MAX_SPILLS_PER_PROCEDURE`), у остальных пяти `spilled=0`; носителей в потоке **39 = 27 ld + 12 st** |
 *
 * # Что здесь НЕ доказано (и это свойство отказа, а не пробел)
 *
 * Отказ понижения — это **не образ**: прогонять на модели и на железе нечего. Поэтому железом
 * проверяется только ОБРАТНАЯ сторона границы — двойник в действии (модель 35/44/54/65, те же
 * числа обязана дать машина), а сам отказ проверяется текстом, кодом и числом носителей.
 *
 * # Почему это не «не реализовано» целиком (замер, а не мнение)
 *
 * Генерация, область и триггер вытеснения СУЩЕСТВУЮТ: `src/vliw/spill.ts` (политика и форма
 * носителей), `src/e2k/regAlloc.ts#chooseSpills`/`applySegments` (вставка носителей по числу живых
 * отрезков), `src/e2k/elfMinimal.ts#spillBaseOf` (256 байт под указателем кучи). Раскладка
 * ВЫТЕСНЯЕТ и в вызываемой (`лексировать`: `spilled=4`), носитель понижается в две команды
 * (`movtd` адреса слота + `ldd`/`std`), — и всё же отказ. Причина одна: адрес памяти в e2k — СУММА
 * двух регистров (поля смещения в команде нет), вторым слагаемым обязан быть НОЛЬ, а ноль берётся
 * из `ARRAY_REGISTERS.zero` (`%b[12]`) — клетки, которую в плоскости ВЫЗЫВАЕМОЙ заводит только
 * пролог ОБРАЗА. Свой ноль в окне вызываемой никто не ставит.
 *
 * # Цена плана: почему закрытие отложено (замер `.tmp/k2-plan-cost.ts`)
 *
 * Закрепить в бюджете вызываемой одну клетку под ноль (`reserved: [12]`, любая из `%b[8..15]` —
 * результат тот же) и положить туда `movts 0`:
 *
 * | что | без закрепления | с закреплением |
 * |---|---|---|
 * | чистое репро (7 живых) | `spilled=1`, 2 носителя | `spilled=2`, 4 носителя — ВЛЕЗАЕТ |
 * | `лексировать` | `spilled=4` (ровно предел) | **отказ**: «вытеснение не минимально: значений в память нужно больше 4 … в тесный момент живы 11 отрезков, свободных регистров 7» |
 *
 * То есть закрепление не снимает стену, а ПЕРЕВОЗИТ её на предел `MAX_SPILLS_PER_PROCEDURE = 4`:
 * у `лексировать` пик 11 живых при 8 клетках бюджета (две заняты параметрами). Закрытие 39 требует
 * более ШИРОКОГО кадра вызываемой или полного аллокатора с вытеснением сверх предела — это класс
 * среза 6 (тот же бюджет окна, что у строк), решение владельца 2026-10-29: **отложить с планом**.
 * Здесь стена закреплена целиком, чтобы следующий заход не искал её заново.
 *
 * # Негативный контроль (замер 2026-10-29; обе подмены сняты, откат сверен по sha256)
 *
 * | что подменено | что покраснело |
 * |---|---|
 * | `src/e2k/programImage.ts`: ветвь отказа `calleeLimit` для `IR.spill_ld`/`IR.spill_st` переименована в `IR.spill_ld_NC`/`IR.spill_st_NC` (отказ снят) | **П1, П2, П4** (из 6): П1 — `n=7/8/9` дают 0 отказа вместо 2/4/6; П2 — 0 вместо 2; П4 — отказов вытеснения в теле лексера нет вместо 27 `IR.spill_ld`. Зелёными остались П3, П5, П6 — они от отказа не зависят |
 * | то же снятие, но с ПРОГОНОМ: тот же образ `n=7` собирается (0 отказов, 584 байта) и модель отдаёт **33** вместо эталонных **35** (`.tmp/negative-k2.ts`, sha256 образа `bcc12d99…`) — это НЕ отказ, а тихая ложь класса «исполняется, а число неверное»; отказов тела лексера 141 → 102 | — (это довод, а не проверка: он и есть причина, по которой «просто снять отказ» запрещено) |
 * | `src/vliw/spill.ts`: `MAX_SPILLS_PER_PROCEDURE` 4 → 8 | **ровно П6**: «`лексировать` с закреплённым нулём раскладывается» становится `true` — предел перестаёт быть стеной. П1–П5 зелёные: предел не влияет на число вытеснений, пока они в него влезают |
 *
 * Откат сверен побайтово: `programImage.ts` sha256 `31e464ff…` до и после, `spill.ts` sha256 `3d29815e…`
 * до и после (`git diff` по обоим файлам пуст).
 */
