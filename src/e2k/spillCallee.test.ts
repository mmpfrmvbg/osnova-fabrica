  it('П7 ДЫРА `report[0]`: отказ раскладки ВЫЗЫВАЕМОЙ назван — иначе образ уходил мусором', () => {
    // ТРЕТЬЯ ТИХАЯ ЛОЖЬ (найдена при перепроверке закреплённых чисел, 2026-10-29).
    //
    // ЧТО БЫЛО. `loweredProgram` называл отказ раскладки только у `allocation.report[0]`, а это
    // запись ПЕРВОЙ процедуры, а не точки входа: `entryProcedureIndex` ищет `главная` по имени, и
    // у программы «тривиальная процедура, затем вызываемая, затем главная» `report[0]` — тривиальная.
    // На отказе `allocateProgram` кладёт поток процедуры НЕРАЗЛОЖЕННЫМ (`fail()`), то есть носители
    // сохраняют регистры, которых раскладка не выдавала, и образа из них не выходит. Но носителей
    // вытеснения при этом НОЛЬ (раскладка отказала ДО их вставки), значит и отказа `calleeLimit` нет.
    // Итог: 0 отказов, образ собран, модель считает мусор.
    //
    // ЧИСЛА (мой прогон `.tmp/pins5v-callee-hole.ts`, один инструмент на двух деревьях; эталон
    // подтверждён ОБЕИМИ VM — стек и регистры совпали на каждом n):
    //   до правки:  n=11 → 0 отказов, 776 байт, модель **9** вместо **77**; n=12 → 9 вместо 90;
    //               n=14 → 9 вместо 119; n=16 → 9 вместо 152;
    //   после:      n=11/12/14/16 → **1 названный отказ** `OSN-LOW-004` с именем процедуры `ф`.
    // Дыра ДОпочиночная: на дереве HEAD `d311187` (до починки `liveness.ts`) — те же 0 / 776 / 9.
    // Негативный контроль — сведение проверки назад к `report[0]`: краснеет ЭТА проба, и краснеет
    // ЧИСЛОМ (модель 9 против 77), а также «СТЕНА НАЗВАНА» в `foundationE2k.test.ts` (108 вместо 109).
    //
    // Обе стороны границы — как и положено: n=7/9/10 раскладка ЕЩЁ проходит и отказ называет
    // вытеснение; n=11+ раскладка отказывает целиком, и отказ называет ПРОЦЕДУРУ.
    const дыра = (n: number): string => {
      const строки = ['процедура п() → Число', '  вернуть 1', 'конец', 'процедура ф(а: Число) → Число'];
      for (let k = 1; k <= n; k++) строки.push(`  пусть р${String(k)} = а + ${String(k)}`);
      let выражение = `р${String(n)}`;
      for (let k = n - 1; k >= 1; k--) выражение = `р${String(k)} + (${выражение})`;
      строки.push(`  вернуть ${выражение}`, 'конец', 'действие главная()', '  пусть х = п()', '  вернуть ф(1)', 'конец', '');
      return строки.join('\n');
    };
    for (const [n, отказов] of [[7, 2], [9, 6], [10, 8]] as const) {
      const понижение = понизить(дыра(n));
      expect(понижение.отказы.length, `n=${String(n)}: отказов (сторона «раскладка прошла»)`).toBe(отказов);
      expect(
        [...конструкции(понижение.отказы).keys()].every(
          (ключ) => ключ === 'OSN-LOW-004 IR.spill_st' || ключ === 'OSN-LOW-004 IR.spill_ld',
        ),
        `n=${String(n)}: отказ обязан быть вытеснением, получено ${[...конструкции(понижение.отказы)].map(([к, ч]) => `${к}×${String(ч)}`).join(', ')}`,
      ).toBe(true);
    }
    for (const n of [11, 12, 14, 16] as const) {
      const понижение = понизить(дыра(n));
      expect(понижение.отказы.length, `n=${String(n)}: отказов (было 0 — тихая ложь)`).toBe(1);
      const отказ = понижение.отказы[0]!;
      expect(отказ.code, `n=${String(n)}: код отказа`).toBe('OSN-LOW-004');
      expect(отказ.reason, `n=${String(n)}: отказ обязан НАЗВАТЬ процедуру`).toContain('процедура «ф»');
      expect(отказ.reason, `n=${String(n)}: и её причину`).toContain('вытеснение не минимально');
      expect(отказ.reason, `n=${String(n)}: с числами живых и бюджета`).toContain('больше 4');
    }
    // КОРЕНЬ ДЫРЫ ПРОВЕРЯЕТСЯ СТРУКТУРНО, а не только числом отказов: отказывает НЕ `report[0]`.
    // Именно на это опирается сторож — сведи проверку назад к `report[0]`, и проба выше покраснеет.
    const раскладка = разложить(дыра(11));
    expect(раскладка.имена[0], 'первая процедура — тривиальная `п`').toBe('п');
    expect(раскладка.вход, 'точка входа — НЕ первая процедура').not.toBe(0);
    expect(раскладка.отчёты[0]?.ok, '`report[0]` (`п`) раскладывается').toBe(true);
    const ф = раскладка.отчёты[раскладка.имена.indexOf('ф')]!;
    expect(ф.ok, 'отказ у ВЫЗЫВАЕМОЙ `ф`, а не у `report[0]`').toBe(false);
    expect(ф.reason ?? '', 'причина у вызываемой').toContain('вытеснение не минимально');
  });
