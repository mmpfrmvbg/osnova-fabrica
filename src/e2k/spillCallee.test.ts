    expect(раскладка.носители.filter((н) => н.mnemonic === 'IR.spill_ld').length, 'чтений слота').toBe(0);
    expect(раскладка.носители.filter((н) => н.mnemonic === 'IR.spill_st').length, 'записей в слот').toBe(0);
