interface Отказ {
  readonly code: string;
  readonly reason: string;
}

/**
 * ПРАВОЕ вложение суммы: `р1 + (р2 + (р3 + …))` — так все значения живы ОДНОВРЕМЕННО.
 * Левая свёртка (`((р1 + р2) + р3)`) оставляет живыми два значения и вытеснения не поднимает вовсе:
 * пик задаёт ФОРМА выражения, а не число `пусть` (измерено, `.tmp/k2-find-clean-repro.ts`).
 */
function правый(n: number, вДействии: boolean): string {
  const шапка = вДействии ? ['действие главная()'] : ['процедура ф(а: Число) → Число'];
  const прибавка = вДействии ? '1' : 'а';
  const строки = [...шапка];
  for (let k = 1; k <= n; k++) строки.push(`  пусть р${String(k)} = ${прибавка} + ${String(k)}`);
  let выражение = `р${String(n)}`;
  for (let k = n - 1; k >= 1; k--) выражение = `р${String(k)} + (${выражение})`;
  строки.push(`  вернуть ${выражение}`, 'конец');
  if (!вДействии) строки.push('действие главная()', '  вернуть ф(1)', 'конец');
  строки.push('');
  return строки.join('\n');
}

/**
 * Понизить программу; разбор обязан быть чистым.
 *
 * `assumeArenaReserved` — замерная ручка §3.134, та же, что у оракула A4-4: у тела лексера разведка
 * арены расходится с потоком после раскладки (случай 46), и БЕЗ ручки понижение не отказывает, а
 * бросает «регистры арены не закреплены». Ручка нужна ровно для того, чтобы число отказов
 * (141, из них 39 вытеснения) было воспроизводимо, а не «сколько получилось сегодня».
 */
function понизить(источник: string, assumeArenaReserved = false): { отказы: readonly Отказ[]; байт: number } {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  const r = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    assumeArenaReserved,
  });
  return { отказы: r.refused, байт: r.bytes.length };
}

/** КОНСТРУКЦИЯ отказа — из данных (носитель/операция), а не из текста сообщения. */
function конструкции(отказы: readonly Отказ[]): Map<string, number> {
  const найдено = new Map<string, number>();
  for (const отказ of отказы) {
    const имя = /^(?:#[0-9]+\s+)?(IR\.[A-Za-z_]+|система\.[а-яё.]+)/.exec(отказ.reason)?.[1] ?? '—';
    const ключ = `${отказ.code} ${имя}`;
    найдено.set(ключ, (найдено.get(ключ) ?? 0) + 1);
  }
  return найдено;
}

/** Понизить и исполнить в модели: `undefined` — модели нет (внешний ресурс, случай 12 реестра). */
function исполнить(источник: string, имя: string): number | undefined {
  const понижение = понизить(источник);
  expect(понижение.отказы, `непонижённые носители: ${понижение.отказы.map((о) => о.reason).join('; ')}`).toEqual([]);
  if (shim === undefined) return undefined;
  const разбор = parseV3(источник, ФАЙЛ);
  const bytes = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  }).bytes;
  const файл = path.join(ROOT, '.tmp', имя);
  fs.writeFileSync(
    файл,
    buildElfFromCode(bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  return runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status;
}

/**
 * РАСКЛАДКА НАПРЯМУЮ: тот же путь, что у конвейера (`allocateProgram` с бюджетом процедур), но с
 * ДОСТУПОМ К ОТЧЁТУ — сколько живых отрезков, сколько вытеснено и какие носители раскладка вставила.
 */
function разложить(
  источник: string,
  reserved: readonly number[] = [],
): {
  readonly имена: readonly string[];
  readonly вход: number;
  readonly отчёты: readonly { readonly used: number; readonly spilled: number; readonly ok: boolean; readonly reason: string | undefined }[];
  readonly носители: readonly { readonly mnemonic: string }[];
} {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  const built = regModuleWithRecordPlan(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (built === null) throw new Error('программа не компилируется');
  const annotated = annotateAtomRegions(built.module, [
    { atom: 'A5', procedures: built.module.procedures.map((procedure) => procedure.name) },
  ]);
  const emitted = emitShell(annotated, getEncoder('internal-shell'));
  const procedures = emitted.scheduled.procedures;
  const вход = procedures.findIndex((procedure) => procedure.name === 'главная');
  const allocation = allocateProgram(emitted.instructions, procedures, {
    reserved: [...reserved],
    freeFor: (at) => (at === вход ? undefined : CALLEE_REGISTERS),
  });
  return {
    имена: procedures.map((procedure) => procedure.name),
    вход,
    отчёты: allocation.report.map((item) => ({
      used: item.used,
      spilled: item.spilled.length,
      ok: item.ok,
      reason: item.reason,
    })),
    носители: allocation.instructions
      .filter((instruction) => instruction.mnemonic === 'IR.spill_ld' || instruction.mnemonic === 'IR.spill_st')
      .map((instruction) => ({ mnemonic: instruction.mnemonic })),
  };
}

/** Тело лексера — тот же срез, что у оракула A4-4 (`src/e2k/callWindowRefusals.test.ts`). */
function телоЛексера(): string {
  const текст = fs.readFileSync(path.join(ROOT, 'src', 'self-host', 'lexer.osnova'), 'utf-8');
  return текст.slice(0, текст.indexOf('// ЛЕКСИРОВАТЬ ФАЙЛ'));
}

