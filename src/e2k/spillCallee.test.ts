    // не ослаблена: она стережёт ТУ ЖЕ границу (вытеснение в вызываемой), но с другой стороны —
    // теперь с той, где прибор (раскладка) отказывает по имени, а не молчит.
    // Замер: `.tmp/pins5v-measure.ts`, раздел 6 — один инструмент на двух деревьях; на дереве HEAD
