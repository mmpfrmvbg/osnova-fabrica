/**
 * ОРАКУЛ СТРОК ОТКАЗА: У КАЖДОГО БЛОКА — СВОЙ ТЕКСТ (случай 34 реестра проверяемости).
 *
 * # Что здесь и почему это НЕ косметика
 *
 * Блок отказа у арены и у коллекций — ОДНА машинерия, но причины РАЗНЫЕ, и наблюдатель отличает
 * один отказ от другого **по строке**. Пока строка планировалась одна на программу (`refusalText =
 * collectionsUsed && !arenaUsed ? … : …`), программа, пользующаяся И ареной, И коллекциями, при
 * отказе КОЛЛЕКЦИИ печатала текст АРЕНЫ — то есть называла чужой механизм. Для цели (DF) это не
 * редкость, а норма: арена — строки и склейка, коллекции — растущий массив записей.
 *
 * # Как спрашивается — ДВУМЯ наблюдениями на одном устройстве
 *
 * Одного наблюдения («написано про коллекцию») мало: тот же текст мог бы печататься ВСЕГДА. Поэтому
 * берётся программа, где присутствуют ОБА механизма, и отказ вызывается **дважды по очереди**:
 *
 * | программа | что отказывает | что обязано быть напечатано |
 * |---|---|---|
 * | арена + коллекции, выход за ёмкость блока | коллекции | текст коллекции, и НЕ текст арены |
 * | арена + коллекции, исчерпание арены | арена | текст арены, и НЕ текст коллекции |
 *
 * Плюс две программы с ОДНИМ механизмом — чтобы «различитель» не держался на присутствии второго.
 *
 * # Чего этот оракул НЕ доказывает
 *
 * Ничего о кодах возврата: код у обоих отказов один и тот же (231) намеренно — различие несёт
 * СТРОКА, и второй код развёл бы наблюдателя на два случая там, где случай один
 * (`src/e2k/collectionsRuntime.ts`). Ничего о тексте отказа `brk`: он проверяется там, где рождается
 * (`src/e2k/collectionsResizeQemu.test.ts`, негативный контроль 3).
 */
import { describe, it, expect } from 'vitest';
import { ARENA_REFUSAL_TEXT, ARENA_REFUSAL_CODE } from './arenaRuntime';
import { COLLECTION_REFUSAL_TEXT } from './collectionsRuntime';
import { runOnE2k } from '../scripts/e2kProgramRun';
import { buildShim } from '../scripts/e2kQemuExec';

const shim = buildShim();

const модуль = (тело: string): string => `модуль Отказ\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/** Тексты — КОНТРАКТ, и он назван здесь дословно: молчаливая правка строки обязана покраснеть. */
const ТЕКСТ_АРЕНЫ = 'арена исчерпана: выделение сверх предела';
const ТЕКСТ_КОЛЛЕКЦИИ = 'коллекция: индекс вне ёмкости блока';

/** Вывод модели: причина отказа идёт в stderr, раннер отдаёт объединённый канал. */
function прогон(source: string, файл: string): { status: number | undefined; output: string; refused: readonly string[] } {
  const run = runOnE2k(source, файл);
  return { status: run.status, output: run.output, refused: run.refused.map((item) => `${item.code} ${item.reason}`) };
}

/**
 * АРЕНА И КОЛЛЕКЦИИ В ОДНОЙ ПРОГРАММЕ, отказывают КОЛЛЕКЦИИ.
 *
 * Выделение у арены стоит ПЕРВЫМ и не пустое: без него текст арены не планировался бы вовсе, и
 * «напечатан текст коллекции» доказывало бы только то, что второго текста нет.
 */
const ОБА_ОТКАЗ_КОЛЛЕКЦИИ = модуль(
  [
    '  пусть блок = система.память.выделить(16)',
    '  пусть база = система.коллекция.выделить(2)',
    '  система.коллекция.положить(база, 0, 5)',
    '  вернуть система.коллекция.взять(база, 5)',
  ].join('\n'),
);

/**
 * АРЕНА И КОЛЛЕКЦИИ В ОДНОЙ ПРОГРАММЕ, отказывает АРЕНА.
 *
 * Двенадцать выделений по 512 байт при пределе 4096 — тот же замер, что у `src/e2k/arenaQemu.test.ts`
 * («двенадцатое выделение обязано стать названным отказом»). Коллекции при этом в программе ЕСТЬ —
 * значит планируются оба текста, и различает их только причина.
 */
const ОБА_ОТКАЗ_АРЕНЫ = модуль(
  [
    '  пусть индекс = 0',
    '  пока индекс < 12',
    '    пусть блок = система.память.выделить(512)',
    '    индекс = индекс + 1',
    '  конец_пока',
    '  пусть база = система.коллекция.выделить(2)',
    '  вернуть система.коллекция.взять(база, 0)',
  ].join('\n'),
);

/** ТОЛЬКО АРЕНА: коллекций в программе нет вовсе. */
const ТОЛЬКО_АРЕНА = модуль(
  [
    '  пусть индекс = 0',
    '  пока индекс < 12',
    '    пусть блок = система.память.выделить(512)',
    '    индекс = индекс + 1',
    '  конец_пока',
    '  вернуть 0',
  ].join('\n'),
);

/** ТОЛЬКО КОЛЛЕКЦИИ: арены в программе нет вовсе. */
const ТОЛЬКО_КОЛЛЕКЦИИ = модуль(
  ['  пусть база = система.коллекция.выделить(2)', '  вернуть система.коллекция.взять(база, 5)'].join('\n'),
);

describe('строки отказа: арена и коллекции называют СВОЮ причину', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('ТЕКСТЫ РАЗНЫЕ — различение не может держаться на совпадении', () => {
    // Контроль на сам оракул: если тексты совпадут, все проверки ниже станут мнимыми (зелёными
    // при любой подмене), и их надо будет переделать — например, различать отказы кодом.
    expect(ARENA_REFUSAL_TEXT).toBe(ТЕКСТ_АРЕНЫ);
    expect(COLLECTION_REFUSAL_TEXT).toBe(ТЕКСТ_КОЛЛЕКЦИИ);
    expect(ТЕКСТ_АРЕНЫ, 'два отказа — два разных текста').not.toBe(ТЕКСТ_КОЛЛЕКЦИИ);
  });

  it('АРЕНА + КОЛЛЕКЦИИ: отказ КОЛЛЕКЦИИ называет коллекцию, а не арену', () => {
    if (shim === undefined) return;
    const run = прогон(ОБА_ОТКАЗ_КОЛЛЕКЦИИ, 'refusal-both-collection.elf');
    expect(run.refused, `отказы понижения: ${run.refused.join('; ')}`).toEqual([]);
    expect(run.status, 'код отказа — тот же, что у арены').toBe(ARENA_REFUSAL_CODE);
    expect(run.output, 'отказ обязан быть назван СВОИМ текстом').toContain(ТЕКСТ_КОЛЛЕКЦИИ);
    expect(run.output, 'чужой механизм назван быть не может').not.toContain(ТЕКСТ_АРЕНЫ);
  });

  it('АРЕНА + КОЛЛЕКЦИИ: отказ АРЕНЫ называет арену, а не коллекцию', () => {
    if (shim === undefined) return;
    const run = прогон(ОБА_ОТКАЗ_АРЕНЫ, 'refusal-both-arena.elf');
    expect(run.refused, `отказы понижения: ${run.refused.join('; ')}`).toEqual([]);
    expect(run.status, 'код отказа').toBe(ARENA_REFUSAL_CODE);
    expect(run.output, 'исчерпание арены — свой текст').toContain(ТЕКСТ_АРЕНЫ);
    expect(run.output, 'текст коллекций здесь был бы чужой причиной').not.toContain(ТЕКСТ_КОЛЛЕКЦИИ);
  });

  it('ТОЛЬКО АРЕНА: текст арены — и никакого текста коллекций', () => {
    if (shim === undefined) return;
    const run = прогон(ТОЛЬКО_АРЕНА, 'refusal-arena-only.elf');
    expect(run.status, 'код отказа').toBe(ARENA_REFUSAL_CODE);
    expect(run.output).toContain(ТЕКСТ_АРЕНЫ);
    expect(run.output, 'коллекций в программе нет — их текста быть не может').not.toContain(ТЕКСТ_КОЛЛЕКЦИИ);
  });

  it('ТОЛЬКО КОЛЛЕКЦИИ: текст коллекции — и никакого текста арены', () => {
    if (shim === undefined) return;
    const run = прогон(ТОЛЬКО_КОЛЛЕКЦИИ, 'refusal-collections-only.elf');
    expect(run.status, 'код отказа').toBe(ARENA_REFUSAL_CODE);
    expect(run.output).toContain(ТЕКСТ_КОЛЛЕКЦИИ);
    expect(run.output, 'арены в программе нет — её текста быть не может').not.toContain(ТЕКСТ_АРЕНЫ);
  });
});
