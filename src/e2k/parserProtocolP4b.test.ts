/**
 * ШАГ P4b, ЧАСТЬ 1: `если` / `пока` — ЧТО ИЗМЕРЕНО (2026-11-10).
 *
 * 1. AST = ЭТАЛОН. Эталонная лента обеих программ закреплена ЦЕЛИКОМ (86 и 84 клетки): сверять
 *    порядок событий по кускам — это проверять не порядок. `если` даёт `1 > 0`, ветви `вернуть 1` /
 *    `вернуть 2`, `иначе` — событие БЕЗ полей (6), `если_конец` несёт конец `конец если` (84).
 * 2. ПРОБА ИСПОЛНЯЕТСЯ. Обе программы на МОДЕЛИ печатают эталонную ленту клетка в клетку (0
 *    расхождений) и возвращают 0 — по ДВА прогона кряду.
 * 3. ГРАНИЦЫ ДЕРЖАТСЯ СТРУКТУРНО, а не «на глаз»: у каждого из пяти писателей не больше ПЯТИ
 *    `Списки.установить` (шестая запись в P4a давала пик 17 и базу не выдавала); `разобрать_если`
 *    и `разобрать_пока` не пишут ВОВСЕ (глубина 2 — только чтение, D12-2); `%` в пробе нет ни
 *    одного (он резервирует `%b[9]` и отнимает у входа десятую клетку).
 *
 * Числа бюджета (настоящий конвейер, `.tmp/p4b-run.ts`): отказов 0, вызываемая — пик живых 14/15,
 * точка входа — 11/11. Диспетчер — в `главная` (глубина 0); тег лежит в R, но вход идёт по виду
 * токена: раскодировать R через `%` — это ровно та клетка, которой у входа нет (§22).
 */
import * as fs from "fs";
import * as path from "path";
import { describe, expect, it } from "vitest";
import { parseV3 } from "../compiler-v3";
import { loweredProgram } from "../e2k/lowered";
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from "../e2k/elfMinimal";
import { runInQemu } from "../scripts/e2kQemuExec";
import {
  ИСХОДНИК_P4B_ЕСЛИ,
  ИСХОДНИК_P4B_ПОКА,
  ТЕГИ_P4B_ВСЕ,
  ФАЙЛ_P4B,
  программаПротоколаP4bПоОператорам,
  эталоннаяЛента,
} from "../compiler-v3/parser-protocol-probe";

function опустить(источник: string) {
  const разбор = parseV3(источник, ФАЙЛ_P4B);
  expect(разбор.errors, "проба обязана разбираться").toEqual([]);
  return loweredProgram(источник, {
    filename: ФАЙЛ_P4B,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
}

function запустить(источник: string, имя: string): { код: number | undefined; лента: number[] } {
  const итог = опустить(источник);
  expect(итог.ок, итог.ок ? "" : String(итог.отказ.отказы[0]?.причина)).toBe(true);
  if (!итог.ок) return { код: undefined, лента: [] };
  const файл = path.resolve(".tmp", имя);
  fs.writeFileSync(
    файл,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
      writable: true,
      extraMemory: WRITE_ZONE_EXTRA_MEMORY,
    }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 60_000 });
  const лента = String(прогон?.stdout ?? "")
    .split(/\r?\n/)
    .filter((с) => с.trim() !== "")
    .map((с) => Number(с.trim()));
  return { код: прогон?.status, лента };
}

/** Тело процедуры: от `процедура имя(` до собственной строки `конец` (не `конец если`). */
function телоПроцедуры(источник: string, имя: string): string {
  const начало = источник.indexOf(`процедура ${имя}(`);
  expect(начало, `процедура ${имя} обязана быть`).toBeGreaterThanOrEqual(0);
  const конец = источник.indexOf("\nконец\n", начало);
  expect(конец, `у процедуры ${имя} обязан быть конец`).toBeGreaterThan(начало);
  return источник.slice(начало, конец);
}

describe("шаг P4b, часть 1: `если` / `пока`", () => {
  it("эталон `если` — 86 клеток: условие ДО события, `иначе` без полей, конец 84", () => {
    expect(эталоннаяЛента(ИСХОДНИК_P4B_ЕСЛИ, ФАЙЛ_P4B)).toEqual([
      20261108, 3, 0, 1, 3, 112, 52, 98, 93, 1, 0, 1,
      1, 9, 1, 1087, 3, 0, 1, 1, 5, 1063, 1080, 1089,
      1083, 1086, 12, 30, 31, 2, 8, 1, 1, 49, 12, 34,
      35, 2, 12, 1, 1, 48, 30, 30, 35, 2, 8, 5,
      25, 2, 3, 29, 12, 48, 49, 3, 13, 1, 1, 49,
      8, 40, 3, 5, 49, 1, 6, 12, 70, 71, 5, 13,
      1, 1, 50, 8, 62, 5, 5, 71, 1, 7, 84, 4,
      92, 0,
    ]);
  });

  it("эталон `пока` — 84 клетки: условие ДО `пока_начало`, конец 82", () => {
    expect(эталоннаяЛента(ИСХОДНИК_P4B_ПОКА, ФАЙЛ_P4B)).toEqual([
      20261108, 3, 0, 1, 3, 112, 52, 98, 83, 1, 0, 1,
      1, 9, 1, 1087, 3, 0, 1, 1, 5, 1063, 1080, 1089,
      1083, 1086, 12, 30, 31, 2, 8, 1, 1, 49, 12, 34,
      35, 2, 12, 1, 1, 48, 28, 30, 35, 2, 8, 15,
      25, 2, 3, 12, 48, 49, 3, 13, 1, 1, 49, 8,
      40, 3, 5, 49, 1, 16, 62, 12, 73, 74, 5, 11,
      1, 1, 50, 8, 65, 5, 3, 74, 1, 4, 82, 0,
    ]);
  });

  it("проба `если` печатает эталон (86) и даёт код 0 (модель, 2 прогона)", () => {
    const эталон = эталоннаяЛента(ИСХОДНИК_P4B_ЕСЛИ, ФАЙЛ_P4B);
    for (const прогон of [1, 2]) {
      const итог = запустить(программаПротоколаP4bПоОператорам(ИСХОДНИК_P4B_ЕСЛИ), `p4b-esli-${String(прогон)}.elf`);
      expect(итог.код, `прогон ${String(прогон)}: код возврата`).toBe(0);
      expect(итог.лента, `прогон ${String(прогон)}: лента клетка в клетку`).toEqual(эталон);
    }
  });

  it("проба `пока` печатает эталон (84) и даёт код 0 (модель, 2 прогона)", () => {
    const эталон = эталоннаяЛента(ИСХОДНИК_P4B_ПОКА, ФАЙЛ_P4B);
    for (const прогон of [1, 2]) {
      const итог = запустить(программаПротоколаP4bПоОператорам(ИСХОДНИК_P4B_ПОКА), `p4b-poka-${String(прогон)}.elf`);
      expect(итог.код, `прогон ${String(прогон)}: код возврата`).toBe(0);
      expect(итог.лента, `прогон ${String(прогон)}: лента клетка в клетку`).toEqual(эталон);
    }
  });

  it("писатели не больше пяти записей, разбор не пишет, `%` в пробе нет", () => {
    const источник = программаПротоколаP4bПоОператорам(ИСХОДНИК_P4B_ЕСЛИ);
    for (const имя of [
      "выписать_если_начало",
      "выписать_иначе",
      "выписать_если_конец",
      "выписать_пока_начало",
      "выписать_пока_конец",
    ]) {
      const записей = (телоПроцедуры(источник, имя).match(/Списки\.установить/g) ?? []).length;
      expect(записей, `${имя}: записей`).toBeLessThanOrEqual(5);
    }
    for (const имя of ["разобрать_если", "разобрать_пока"]) {
      expect(телоПроцедуры(источник, имя), `${имя} — только чтение`).not.toMatch(/Списки\.установить/);
    }
    // `%` — это IR.rem: он резервирует `%b[9]` и отнимает у входа десятую клетку (P4a: 11/11).
    expect(источник).not.toMatch(/%/);
    // Диспетчер — в точке входа, зовёт писателей и разбор; `разобрать_*` писателей не зовут.
    const вход = источник.slice(источник.indexOf("действие главная"));
    expect(вход).toMatch(/выписать_если_начало\(/);
    expect(вход).toMatch(/выписать_пока_начало\(/);
    expect(вход).toMatch(/разобрать_если\(/);
    expect(вход).toMatch(/разобрать_пока\(/);
    expect(вход).toMatch(/поз_шага\(/);
    // Теги: 27 занятых слотов P3d, if/while новых не добавили (пять свободны).
    expect(ТЕГИ_P4B_ВСЕ.length).toBe(27);
    expect(ТЕГИ_P4B_ВСЕ.length).toBeLessThanOrEqual(32);
  });
});
