function опустить(источник: string) {
  const разбор = parseV3(источник, ФАЙЛ_P4B);
  expect(разбор.errors, "проба обязана разбираться").toEqual([]);
  return loweredProgram(источник, {
    filename: ФАЙЛ_P4B,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
}

function запустить(источник: string, имя: string): { код: number | undefined; лента: number[] } {
  const итог = опустить(источник);
  expect(итог.ок, итог.ок ? "" : String(итог.отказ.отказы[0]?.причина)).toBe(true);
  if (!итог.ок) return { код: undefined, лента: [] };
  const файл = path.resolve(".tmp", имя);
  fs.writeFileSync(
    файл,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
      writable: true,
      extraMemory: WRITE_ZONE_EXTRA_MEMORY,
    }).bytes,
  );
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 60_000 });
  const лента = String(прогон?.stdout ?? "")
    .split(/\r?\n/)
    .filter((с) => с.trim() !== "")
    .map((с) => Number(с.trim()));
  return { код: прогон?.status, лента };
}

/** Тело процедуры: от `процедура имя(` до собственной строки `конец` (не `конец если`). */
function телоПроцедуры(источник: string, имя: string): string {
  const начало = источник.indexOf(`процедура ${имя}(`);
  expect(начало, `процедура ${имя} обязана быть`).toBeGreaterThanOrEqual(0);
  const конец = источник.indexOf("\nконец\n", начало);
  expect(конец, `у процедуры ${имя} обязан быть конец`).toBeGreaterThan(начало);
  return источник.slice(начало, конец);
}

