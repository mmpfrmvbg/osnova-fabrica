describe('устройство понижения пары: регистры тега и нагрузки названы, а не угаданы', () => {
  it('тег — штатный приёмник вызова `%r(2·wbs)`, нагрузка — ровно на клетку выше', () => {
    // Тег читается ШТАТНЫМ приёмником `IR.call` (операнд 4): отдельного носителя для тега нет и быть
    // не должно — иначе тег и результат вызова разошлись бы по разным регистрам.
    const call = lowerCarrier(callCarrier(1, [7], 5), { callDisplacement: 1 });
    expect(call.ok, call.ok ? '' : call.reason).toBe(true);
    if (!call.ok) return;
    const reads = call.instructions.filter((command) => command.mnemonic === 'movts');
    expect(reads.length, 'приёмник вызова — одна пересылка').toBe(2); // аргумент + результат
    const tagCell = regOf(reads[1]!, 0);
    expect(tagCell, 'откуда читается ТЕГ — `%r(2·wbs)`').toEqual({
      index: CALL_WBS * 2,
      file: 'window',
    });
    expect(regOf(reads[1]!, 1).index, 'куда читается тег').toBe(5);
    // Числа названы явно: при `CALL_WBS = 4` тег вызова из точки входа — `%r8` (§10.2).
    expect(CALL_WBS * 2, 'тег вызова из точки входа — %r8 при CALL_WBS = 4').toBe(8);

    // Нагрузка — СЛЕДУЮЩАЯ клетка канала, и читает её отдельный носитель `IR.result_pick`:
    // операнд 0 — приёмник нагрузки, операнд 1 — ЯКОРЬ ПОРЯДКА (приёмник тега того же вызова).
    const pick = lowerCarrier(carrier('IR.result_pick', [reg(6), reg(5)]), { callWbs: CALL_WBS });
    expect(pick.ok, pick.ok ? '' : `«IR.result_pick» не понижается: ${pick.reason}`).toBe(true);
    if (!pick.ok) return;
    expect(pick.instructions.map((command) => command.mnemonic), 'чтение нагрузки — одна `movts`').toEqual(['movts']);
    expect(regOf(pick.instructions[0]!, 0), 'откуда читается НАГРУЗКА — `%r(2·wbs + 1)`').toEqual({
      index: CALL_WBS * 2 + 1,
      file: 'window',
    });
    expect(regOf(pick.instructions[0]!, 1).index, 'куда читается нагрузка').toBe(6);
    // Связь двух измерений одним числом: нагрузка ровно на клетку выше тега (§10.2).
    expect(regOf(pick.instructions[0]!, 0).index, 'нагрузка — соседняя клетка канала (ровно на 1 выше тега)').toBe(
      tagCell.index + 1,
    );
  });

  it('возврат пары: тег в свою клетку 0, нагрузка в свою клетку 1, возврат — парой `return`+`ct`', () => {
    const lowered = lowerCarrier(carrier('IR.ret_result', [reg(3), reg(4)]), { procedureReturn: true });
    expect(
      lowered.ok,
      lowered.ok ? '' : `«IR.ret_result» не понижается: ${lowered.reason} (контракт: носитель с операндами [тегReg, нагрузкаReg])`,
    ).toBe(true);
    if (!lowered.ok) return;
    expect(lowered.instructions.map((command) => command.mnemonic), 'две пересылки и пара возврата').toEqual([
      'movts',
      'movts',
      'return',
      'ct',
    ]);
    const tagStore = lowered.instructions[0]!;
    const loadStore = lowered.instructions[1]!;
    expect(regOf(tagStore, 0).index, 'источник тега — операнд 0').toBe(3);
    expect(regOf(tagStore, 1), 'ТЕГ — в собственную клетку 0 вызываемой (`%r0`)').toEqual({ index: 0, file: 'window' });
    expect(regOf(loadStore, 0).index, 'источник нагрузки — операнд 1').toBe(4);
    expect(regOf(loadStore, 1), 'НАГРУЗКА — в собственную клетку 1 вызываемой (`%r1`)').toEqual({
      index: 1,
      file: 'window',
    });
    expect(lowered.instructions[2]!.operands, 'возврат — через `%ctpr3`').toEqual([imm(3)]);
    // Пара, а не одна команда: одна `return` валит порт утверждением, одна `ct` — ловушка
    // (`src/e2k/e2kCallWindowQemu.test.ts`).
    expect(lowered.instructions[3]!.mnemonic, 'вторая половина пары — `ct`').toBe('ct');
  });

  it('раскладка ЗНАЕТ формы обоих носителей — иначе они разместились бы как ноль байт', () => {
    // Носитель без формы раскладка размещает как НОЛЬ байт, и адреса всего, что за ним, уезжают
    // (§3.135: форма обязана быть известна заранее и не зависеть от плоскости).
    const retForm = carrierFormOf(carrier('IR.ret_result', [reg(3), reg(4)]), { procedureReturn: true });
    expect(retForm, 'форма `IR.ret_result` обязана быть у раскладки').toBeDefined();
    expect(retForm!.commands.length, 'команд в форме возврата пары').toBe(4);
    const pickForm = carrierFormOf(carrier('IR.result_pick', [reg(6), reg(5)]));
    expect(pickForm, 'форма `IR.result_pick` обязана быть у раскладки').toBeDefined();
    expect(pickForm!.commands.length, 'команд в форме чтения нагрузки').toBe(1);
  });

  it('конвейер ставит `IR.result_pick` СРАЗУ после `IR.call` того же сайта', () => {
    const источник = программа(ОБЩЕЕ_ВЫРАЖЕНИЕ);
    const { ошибки, options } = фронтенд(источник);
    expect(ошибки, `разбор v3: ${ошибки.join('; ')}`).toEqual([]);
    if (ошибки.length > 0) return;
    const carriers = shellCarriers(источник, options);
    // Сайт разбора пары в программе ОДИН — `пусть тег, нагрузка = добыть(ч)`.
    const picks = carriers.map((item, at) => (item.mnemonic === 'IR.result_pick' ? at : -1)).filter((at) => at >= 0);
    expect(picks.length, 'сайтов разбора пары в программе').toBe(1);
    const call = carriers[picks[0]! - 1]!;
    const pick = carriers[picks[0]!]!;
    expect(call.mnemonic, 'нагрузка читается СРАЗУ после вызова').toBe('IR.call');
    // ЯКОРЬ ПОРЯДКА — приёмник ТЕГА того же вызова, а не произвольный регистр: этим и держится
    // «вызов → чтение нагрузки» (тег кладёт приёмник вызова, нагрузку — `IR.result_pick`).
    expect(regOf(pick, 1).index, 'якорь `IR.result_pick` — приёмник тега того же вызова').toBe(regOf(call, 4).index);
    // Нагрузка и тег — ДВА РАЗНЫХ регистра: иначе пара схлопнулась бы в одно значение.
    expect(regOf(pick, 0).index, 'приёмник нагрузки — не тот же регистр, что тег').not.toBe(regOf(call, 4).index);
    // `добыть` отдаёт пару ДВУМЯ возвратами: `Успех(ч)` и `Неудача(7)`.
    const результатВозвратов = carriers.filter((item) => item.mnemonic === 'IR.ret_result');
    expect(результатВозвратов.length, 'носителей возврата пары — по одному на исход `добыть`').toBe(2);
    for (const item of результатВозвратов) {
      expect(item.operands.length, 'операнды `IR.ret_result` — [тегReg, нагрузкаReg]').toBe(2);
      for (const operand of item.operands) {
        expect(operand.kind, 'оба операнда возврата пары — РЕГИСТРЫ').toBe('reg');
      }
    }
  });
});

