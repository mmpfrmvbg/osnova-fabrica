const imm = (value: number): Operand => ({ kind: 'imm', value });
const reg = (index: number): Operand => ({ kind: 'reg', index });
const carrier = (mnemonic: string, operands: readonly Operand[]): AsmInstruction => ({
  mnemonic,
  channel: 0,
  operands,
});

/** Операнд-регистр команды: индекс и файл (`window` — оконная форма `%rN`). */
function regOf(instruction: AsmInstruction, at: number): { index: number; file?: string } {
  const operand = instruction.operands[at];
  if (operand === undefined || operand.kind !== 'reg') {
    throw new Error(`${instruction.mnemonic}: операнд ${at} не регистр`);
  }
  return { index: operand.index, ...(operand.file === undefined ? {} : { file: operand.file }) };
}

/** Носитель вызова так, как его выдаёт эмиттер: `[флаги, arg0, arg1, payload, приёмник]`. */
function callCarrier(argc: number, args: readonly number[], destination?: number, payload = 1): AsmInstruction {
  const flags = (destination === undefined ? 0 : 1) | (argc << 1);
  return carrier('IR.call', [
    imm(flags),
    reg(args[0] ?? 0),
    reg(args[1] ?? 0),
    imm(payload),
    reg(destination ?? 0),
  ]);
}

/** Шим модели собирается ОДИН РАЗ на процесс (как в `src/e2k/e2kArraysQemu.test.ts`). */
let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

/** Разбор v3 и — если он прошёл — опции общего конвейера с подставленным фронтендом (D10). */
function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

/**
 * Собрать образ ПУТЁМ КОМПИЛЯТОРА и исполнить его в модели. `undefined` — прогон не состоялся
 * (причина в этом случае уже названа утверждением, а не проглочена).
 */
function прогон(выражение: string, файл: string): number | undefined {
  const источник = программа(выражение);
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, `разбор v3 («Результат<>» и «пусть тег, нагрузка = …»): ${ошибки.join('; ')}`).toEqual([]);
  if (ошибки.length > 0) return undefined;
  // ПОТРЕБИТЕЛЬ (D11): под отказом байтов нет — дверь отдаёт Результат<Образ, Отказ>.
  const итог = loweredProgram(источник, options);
  expect(
    итог.ок,
    итог.ок ? '' : `отказы понижения: ${итог.отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`).join(' | ')}`,
  ).toBe(true);
  if (!итог.ок) return undefined;
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    // `extraMemory` — область записи образа (страница кучи/площадки): без неё обращение к ней было бы
    // исключением. Берём полную область записи: она НАДмножество собственной границы образа.
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  return runInQemu(путь, { shim: true, timeoutMs: 30_000 })?.status;
}

// ─────────────────────────────────────────────────────────────────────────────
// 1. УСТРОЙСТВО: РЕГИСТРЫ НАЗВАНЫ (БЕЗ МОДЕЛИ)
