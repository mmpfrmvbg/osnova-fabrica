/**
 * ЕДИНСТВЕННЫЙ источник всех проб: `добыть` (возврат пары), `проверить` (разбор пары) и `главная`
 * с подставленным ВЫРАЖЕНИЕМ. Исходники держатся в одном месте намеренно: проба «Успех», проба
 * «Неудача» и общая проба обязаны отличаться ТОЛЬКО последней строкой.
 */
function программа(выражение: string): string {
  return [
    'процедура добыть(ч: Число) → Результат<Число, Число>',
    '  если ч > 0',
    '    вернуть Успех(ч)',
    '  конец если',
    '  вернуть Неудача(7)',
    'конец',
    '',
    'процедура проверить(ч: Число) → Число',
    '  пусть тег, нагрузка = добыть(ч)',
    '  если тег == 1',
    '    вернуть 0 - нагрузка',
    '  конец если',
    '  вернуть нагрузка',
    'конец',
    '',
    'действие главная()',
    `  вернуть ${выражение}`,
    'конец',
    '',
  ].join('\n');
}

