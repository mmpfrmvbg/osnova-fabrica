/**
 * `проверить(5)`: `добыть(5)` → `Успех(5)` — тег **0**, нагрузка **5**; условие `тег == 1` ложно,
 * исполняется запасной путь `вернуть нагрузка` → **5**.
 */
const УСПЕХ = 5;

/**
 * `проверить(0 - 1)`: `добыть(-1)` → `Неудача(7)` — тег **1**, нагрузка **7**; берётся ветвь
 * `вернуть 0 - нагрузка` → **−7**. Именно ЗНАЧЕНИЕ ошибки (D4), а не мусор: если бы нагрузка была
 * мусором, эта проба не отдала бы ни −7, ни 7.
 */
const НЕУДАЧА = 0 - 7;

/** Общая проба: `5 · 100 + (−7)` = **493**. */
const ИТОГ = УСПЕХ * 100 + НЕУДАЧА;

/**
 * МЛАДШИЙ БАЙТ значения — всё, что несёт код возврата процесса (двоичное дополнение, 8 бит).
 * `младшийБайт(−7)` = **249**, `младшийБайт(493)` = **237**.
 */
const младшийБайт = (значение: number): number => значение & 0xff;
const КОД_НЕУДАЧИ = младшийБайт(НЕУДАЧА); // 249
const КОД_ИТОГА = младшийБайт(ИТОГ); // 237

/**
 * РАСХОЖДЕНИЕ С ЧИСЛАМИ, НАЗВАННЫМИ В ЗАДАНИИ, — НАЗВАНО, А НЕ ЗАМОЛЧАНО.
 *
 * В задании названы: проба «Неудача» → 7; итог главной → 507; код → 251. Эти три числа получаются
 * ТОЛЬКО тогда, когда `проверить` отдаёт `нагрузку` в ОБЕИХ ветвях (`вернуть нагрузка` и в `если`,
 * и после него): тогда тег не влияет ни на что, и проба «Неудача» зеленеет ДАЖЕ БЕЗ ЧТЕНИЯ ТЕГА —
 * то есть перестаёт быть различающей, а задание требует от неё именно различения.
 *
 * При ТЕКСТЕ ПРОГРАММЫ, КАК ОН ДАН (`вернуть 0 - нагрузка` в ветви и `вернуть нагрузка` запасным
 * путём, `+` в главной) числа такие: 5 / −7 (код 249) / 493 (код 237). Это же единственное чтение,
 * при котором проба «Успех» даёт 5 (при обратном знаке она дала бы `0 − 5` = −5 → 251).
 *
 * Файл кодирует ТЕКСТ ПРОГРАММЫ (правило проекта: «числа берутся из кода, а не из головы»). Если
 * владелец имел в виду программу с `вернуть нагрузка` в ветви — меняется ОДНА строка источника и
 * три числа (7 / 507 / 237→251), но проба при этом теряет различающую силу, и её придётся заменить.
 */

/**
 * НЕГАТИВНЫЙ КОНТРОЛЬ (МЫСЛЕННЫЙ, БЕЗ ИСПОЛНЕНИЯ): СНЯТЬ ЧТЕНИЕ ТЕГА.
 *
 * Что именно снять: приёмник `IR.call` (`%r(2·wbs)` → регистр `тег`) — то есть шаг, который кладёт
 * тег. Тогда в `тег` остаётся ЧУЖОЕ значение, условие `если тег == 1` перестаёт быть истинным, ветвь
 * `вернуть 0 - нагрузка` НЕ исполняется, и проба «Неудача» уходит запасным путём `вернуть нагрузка`.
 *
 * ЧТО КРАСНЕЕТ: проба «Неудача» — «ожидалось **249**, получено **7**» (запасной путь отдал саму
 * нагрузку). Проба «Успех» при этом остаётся зелёной (её путь тот же запасной), а общая проба краснеет
 * числом **237 → 7**: `5·100 + 7` = 507, то есть проба показывает ровно тот исход, в котором ветвь
 * «Неудача» не распознана. Это и есть различающая сила: без чтения тега красное, с ним — зелёное.
 *
 * Второй негативный контроль, тоже мысленный: снять `IR.result_pick` (чтение нагрузки) — и нагрузка
 * приходит мусором, поэтому КРАСНЕЮТ ОБЕ пробы: «Успех» (5 → мусор) и «Неудача» (249 → мусор).
 */

