/**
 * ОРАКУЛ: ПОНИЖЕНИЕ `Результат<Т, Е>` НА ЦЕЛЬ e2k (ATOM-06-02-01; представление — §10.2 черновика ABI).
 *
 * # Что решено владельцем (контракт, который тест НЕ «улучшает»)
 *
 * Носитель результата — ДВА регистра канала вызова: ТЕГ = `%r(2·wbs)`, НАГРУЗКА = `%r(2·wbs + 1)`
 * (`docs/abi-v3-draft.md` §10.2; при `CALL_WBS = 4` из `src/e2k/twoPassLayout.ts` это `%r8` и `%r9`
 * для вызова из точки входа). Тег: `0` = `Успех`, `1` = `Неудача`. При `Неудаче` нагрузка несёт
 * ЗНАЧЕНИЕ ошибки, а не мусор (D4). В вызываемой тег и нагрузка — её СОБСТВЕННЫЕ `%r0` и `%r1`:
 * `call` сдвигает окно на `2·wbs`, поэтому клетка `N` вызываемой — клетка `N + 2·wbs` вызывающего.
 *
 * # Языковая поверхность v3, на которую написан тест (её ведёт ДРУГАЯ работа, рядом)
 *
 *   • тип возврата `→ Результат<Число, Число>` (угловые скобки с двумя типами);
 *   • возврат `вернуть Успех(выражение)` / `вернуть Неудача(выражение)`;
 *   • разбор пары в вызывающем: `пусть тег, нагрузка = добыть(ч)` (два имени через запятую).
 *
 * ЗАМЕР 2026-11-05 (этим файлом): фронтенд v3 этот текст УЖЕ разбирает (`parseV3` → `errors: []`,
 * узлы `успех`/`неудача`/`распаковать` есть в AST), и кодоген пары тоже выпускает носители. Красное
 * здесь — ЦЕЛЬ: понижения пары в `src/e2k/**` на момент замера ещё нет, и прогон это назвал.
 *
 * Носители, на которые опирается устройство (их вводит реализация; имена названы, не угаданы):
 *   • `IR.ret_result`, операнды `[тегReg, нагрузкаReg]` — оба РЕГИСТРЫ;
 *   • `IR.result_pick`, операнды `[приёмник нагрузки, якорь порядка]` — ставится СРАЗУ после `IR.call`
 *     того же сайта; тег читается штатным приёмником `IR.call` (операнд 4), и ОН ЖЕ едет якорем
 *     порядка у `IR.result_pick` (так форма сходится в трёх местах: кодоген `emitUnpack`, оболочка
 *     `emitterShell` — операнды `[d, a]`, понижение `e2kRealRun` — `[приёмник, якорь]`).
 *     В задании назван один операнд — дерево сошлось на двух: якорь держит порядок «вызов → чтение
 *     нагрузки», а не надежду на планировщик. Оракул закрепляет ФОРМУ ДЕРЕВА, а не черновик.
 *
 * # Чем проверяется
 *
 * 1) УСТРОЙСТВО, без модели: `lowerCarrier` напрямую (как `src/e2k/e2kCallLowering.test.ts`) —
 *    регистры тега/нагрузки и формы раскладки (носитель без формы размещается как НОЛЬ байт, и
 *    адреса уезжают — §3.135, поэтому форма обязана существовать заранее).
 * 2) ПУТЬ КОМПИЛЯТОРА: `loweredProgram` (публичная дверь D11; под отказом БАЙТОВ НЕТ) → ELF →
 *    прогон в модели `qemu-e2k` под шимом. Эталонных плоскостей (стековая и регистровая VM) для
 *    новой конструкции тест НЕ требует: спрашивается ЦЕЛЬ, как в `src/e2k/e2kArraysQemu.test.ts`.
 *
 * # Канал наблюдения (назван, а не обойдён)
 *
 * Код возврата процесса несёт ТОЛЬКО МЛАДШИЙ БАЙТ значения (AGENTS.md, «канал наблюдения»; измерено
 * 2026-09-27). Поэтому: −7 наблюдается как **249**, 493 — как **237**. Шире в дереве наблюдает слой
 * ПЕЧАТИ (`система.лог.вывести` → `write`, записи корпуса `39`–`44` с `via: "вывод"`,
 * `src/e2k/printCall.ts`): он отдаёт число ТЕКСТОМ, без усечения. Здесь он не используется намеренно —
 * программа-минимум отдаёт значение возвратом, и подмена канала изменила бы предмет проверки.
 *
 * # ЧЕГО ЭТОТ ОРАКУЛ НЕ ДЕЛАЕТ
 *
 * Не проверяет железо (QEMU — модель: отдельная проба на машине); не проверяет `Строка.срез`/`склейку`
 * (это ATOM-06-02-02) и структуру (`Ошибка`) в нагрузке (проверено на `Число`); не наблюдает за
 * значением ШИРЕ младшего байта этого канала.
 */

