// ─────────────────────────── D12: число ИЛИ авария ───────────────────────────

type ПрогонМодели = { readonly status: number | null; readonly output: string; readonly exceptionIp?: number };

type ИсходМодели =
  | { readonly вид: 'число'; readonly байт: number; readonly знаковый: number }
  | { readonly вид: 'авария'; readonly код: number | null; readonly ip?: number; readonly строка: string }
  | { readonly вид: 'молчание'; readonly код: number | null };

/**
 * Канал несёт МЛАДШИЙ БАЙТ, поэтому число читается ЗНАКОВЫМ (`status > 127 ? status - 256`). АВАРИЯ
 * порта числом НЕ считается: у аварийного выхода код неотличим от числа гостя (`docs/hardware-debt.md`
 * §3.31.4), и принять его за число — ошибка канала, а не измерение.
 */
function исходМодели(прогон: ПрогонМодели | undefined): ИсходМодели {
  if (прогон === undefined) return { вид: 'молчание', код: null };
  const аварийная = /exception at IP|exception handling is unimplemented/iu.exec(прогон.output);
  if (аварийная !== null || прогон.exceptionIp !== undefined) {
    return {
      вид: 'авария',
      код: прогон.status,
      ...(прогон.exceptionIp === undefined ? {} : { ip: прогон.exceptionIp }),
      строка: аварийная?.[0] ?? 'exceptionIp без строки',
    };
  }
  if (прогон.status === null) return { вид: 'молчание', код: null };
  return { вид: 'число', байт: прогон.status, знаковый: прогон.status > 127 ? прогон.status - 256 : прогон.status };
}

// ─────────────────────────── эталон: ОБЕ VM независимо от цели ───────────────────────────

const какЧисло = (значение: unknown): number | undefined =>
  значение === true ? 1 : значение === false ? 0 : typeof значение === 'number' ? значение : undefined;

type ИсходVms = { readonly стек?: number; readonly регистры?: number; readonly беда?: string };

async function обеVms(текст: string): Promise<ИсходVms> {
  const разбор = parseV3(текст, ФАЙЛ);
  if (разбор.errors.length > 0) return { беда: `разбор: ${разбор.errors.join(' | ')}` };
  const программа = разбор.program;
  if (программа === undefined) return { беда: 'разбор без программы и без ошибок' };
  const м = программа.modules[0];
  if (м === undefined) return { беда: 'в программе нет модуля' };
  const проход = validateNamedTypesAndRewrite(м);
  if (проход.length > 0) return { беда: `проход именованных типов: ${JSON.stringify(проход)}` };
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = какЧисло(await стековая.runProcedure(стековая.findProcedureIndex('главная'), []));
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = какЧисло(await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []));
  return { стек, регистры };
}

// ─────────────────────────── дверь: ровно два исхода (D11) ───────────────────────────

type ИсходДвери =
  | { readonly вид: 'образ'; readonly байт: number; readonly bytes: Uint8Array; readonly extraMemory: number }
  | {
      readonly вид: 'отказ';
      readonly код: string;
      readonly причина: string;
      readonly процедуры: string;
      readonly отказов: number;
      readonly беды: readonly string[];
    }
  | { readonly вид: 'разбор-сломан'; readonly беды: readonly string[] };

function спроситьДверь(проба: Проба): ИсходДвери {
  const текст = текстПробы(проба);
  const разбор = parseV3(текст, ФАЙЛ);
  if (разбор.errors.length > 0) return { вид: 'разбор-сломан', беды: разбор.errors };
  let итог: ReturnType<typeof loweredProgram>;
  try {
    итог = loweredProgram(текст, {
      filename: ФАЙЛ,
      parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    });
  } catch (ошибка) {
    // Дверь БРОСАЕТ только на том, что не компилируется вовсе: это не «честный отказ», а СТОП.
    return { вид: 'разбор-сломан', беды: [`дверь бросила: ${ошибка instanceof Error ? ошибка.message : String(ошибка)}`] };
  }
  if (итог.ок) {
    return { вид: 'образ', байт: итог.значение.bytes.length, bytes: итог.значение.bytes, extraMemory: итог.значение.arena.extraMemory };
  }
  const отказ = итог.отказ;
  const беды: string[] = [];
  if ('bytes' in отказ) беды.push('D11: под отказом просочились БАЙТЫ');
  if (отказ.отказы.length === 0) беды.push('отказ не назван ни одной записью');
  if (отказ.процедуры.length === 0) беды.push('отказ не назвал процедуру (четвёртая ложь, случай 58)');
  for (const запись of отказ.отказы) {
    if (!/^OSN-LOW-/u.test(запись.код)) беды.push(`код «${запись.код}» не похож на код причины`);
    if (!/процедур/iu.test(запись.причина)) беды.push(`причина «${запись.причина}» не называет процедуру`);
  }
  return {
    вид: 'отказ',
    код: отказ.отказы[0]?.код ?? 'НЕТ КОДА',
    причина: отказ.причина,
    процедуры: отказ.процедуры.join(', '),
    отказов: отказ.отказы.length,
    беды,
  };
}

