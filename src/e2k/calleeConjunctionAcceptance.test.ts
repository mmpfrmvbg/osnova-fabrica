/** Те же проверки, что гоняет замерный скрипт: матрица, приманки, пары, чистота плоскостей. */
function бедыУстройства(): readonly string[] {
  const беды: string[] = [];
  const классы = классыПоПорядку();
  for (const класс of классы) {
    const вКлассе = ПРОБЫ.filter((проба) => проба.класс === класс);
    if (вКлассе.length < 2) беды.push(`D9: класс «${класс}» спрашивается одной точкой (${String(вКлассе.length)})`);
  }
  if (new Set(ПРОБЫ.map((проба) => проба.имя)).size !== ПРОБЫ.length) беды.push('имена проб не уникальны');
  const безСовпадений = new Map<string, number>();
  for (const проба of ПРОБЫ) {
    if (проба.взято === проба.неВзято) беды.push(`${проба.имя}: «взято» = «не взято» — исход ветви ненаблюдаем`);
    if (проба.эталон !== проба.взято && проба.эталон !== проба.неВзято) беды.push(`${проба.имя}: эталон не равен ни «взято», ни «не взято» — счёт от руки не сходится`);
    const сломано: string[] = [];
    if (проба.эталон === проба.терм1) сломано.push('первый-терм');
    if (проба.эталон === проба.терм2) сломано.push('второй-терм');
    const объявлено = [...(проба.совпадение ?? [])].sort().join('+');
    if (сломано.length > 0 && объявлено !== [...сломано].sort().join('+')) {
      беды.push(`${проба.имя}: эталон ${String(проба.эталон)} совпал с приманкой «${сломано.join(', ')}» без объявления — прибор не различает`);
    }
    if (сломано.length === 0 && объявлено !== '') беды.push(`${проба.имя}: объявлено совпадение «${объявлено}», а совпадения нет`);
    if (проба.плоскость === 'вызываемая' && !текстПробы(проба).startsWith('процедура ф(')) беды.push(`${проба.имя}: плоскость «вызываемая», а тело не в процедуре`);
    if (проба.плоскость === 'входа' && !текстПробы(проба).startsWith('действие главная()')) беды.push(`${проба.имя}: плоскость «входа», а исходник не начинается с действия`);
    if (текстПробы(проба).includes(ПЕЧАТЬ) || текстПробы(проба).includes('лог.вывести')) беды.push(`${проба.имя}: в пробе есть печать — плоскости смешаются (§3.62, урок 5ж)`);
    if (проба.совпадение === undefined || проба.совпадение.length === 0) безСовпадений.set(проба.класс, (безСовпадений.get(проба.класс) ?? 0) + 1);
  }
  for (const класс of классы) {
    if ((безСовпадений.get(класс) ?? 0) === 0) беды.push(`класс «${класс}»: все пробы с объявленным совпадением — класс не различает ничего`);
  }
  for (const проба of ПРОБЫ) {
    if (проба.пара === undefined) continue;
    const кандидаты = ПРОБЫ.filter((к) => к.имя === проба.пара || к.имя.startsWith(`${проба.пара ?? ''}-`));
    if (кандидаты.length !== 1) {
      беды.push(`${проба.имя}: пара «${проба.пара}» ${кандидаты.length === 0 ? 'не найдена' : 'неоднозначна'}`);
      continue;
    }
    const пара = кандидаты[0]!;
    const обратная = пара.пара !== undefined && (проба.имя === пара.пара || проба.имя.startsWith(`${пара.пара}-`));
    if (!обратная) беды.push(`${проба.имя}: пара «${пара.имя}» не ссылается обратно`);
    const вид = проба.видПары ?? 'плоскость';
    if (вид === 'плоскость') {
      if (пара.плоскость === проба.плоскость) беды.push(`${проба.имя}: пара «${пара.имя}» в той же плоскости`);
      if (пара.эталон !== проба.эталон) беды.push(`${проба.имя}: эталон пары «${пара.имя}» другой`);
      if (пара.тело.join('\n') !== проба.тело.join('\n')) беды.push(`${проба.имя}: тело пары «${пара.имя}» другое`);
    } else if (вид === 'форма') {
      // ПАРА ФОРМ: ОДИН эталон и РАЗНЫЕ тела — иначе контроль «ветвь по значению против обычного
      // перехода» пуст. Требовать разные эталоны здесь НЕЛЬЗЯ: различает раскладка, а не число.
      if (пара.плоскость !== проба.плоскость) беды.push(`${проба.имя}: пара форм «${пара.имя}» в другой плоскости — сравнивались бы плоскости`);
      if (пара.эталон !== проба.эталон) беды.push(`${проба.имя}: эталон пары форм «${пара.имя}» другой — пара обязана спрашивать ОДНО условие`);
      if (пара.тело.join('\n') === проба.тело.join('\n')) беды.push(`${проба.имя}: тело пары форм «${пара.имя}» ТО ЖЕ — раскладка не различается, контроль пуст`);
    } else {
      if (пара.плоскость !== проба.плоскость) беды.push(`${проба.имя}: пара значений «${пара.имя}» в другой плоскости`);
      if (пара.эталон === проба.эталон) беды.push(`${проба.имя}: эталон пары значений «${пара.имя}» тот же — фиксированное число не различить`);
      if (пара.тело.join('\n') === проба.тело.join('\n') && пара.вход === проба.вход && пара.выражение === проба.выражение) {
        беды.push(`${проба.имя}: пара значений «${пара.имя}» ничем не отличается`);
      }
    }
  }
  return беды;
}

