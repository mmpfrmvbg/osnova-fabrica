/**
 * ФАЙЛОВЫЙ ВХОД: УСТРОЙСТВО пробы, а не её прогон (L2 §42/§44).
 *
 * Числа «сколько байт вернул `read`» даёт только машина (`src/e2k/fileReadQemu.test.ts` — модель,
 * кит `bin/b2b-file.elf` — железо). Здесь держится то, что обязано быть верным ДО прогона, и падает
 * на сборке, а не на железе:
 *
 *  • путь в носителе и путь в генераторе — ОДНА строка (`ФАЙЛ_ЛЕНТЫ === FILE_PATH_TEXT`), иначе
 *    прогон молча читал бы не тот файл (список нулей → короткий AST и код 0: тихая ложь);
 *  • программа пятнадцати форм понижается БЕЗ отказов, а её лента — 1 826 ячеек (14 608 байт):
 *    разбор не изменился, изменился ИСТОЧНИК ячеек (было — литералы CJK, стало — `read(3)`);
 *  • `cells`/`astCells` двигают СВОИ величины: выращенную область под чтение и рабочие области
 *    разбора (`С`/`ОП`/`В`) — без второго у программы с большим AST `установить` затёр бы состояние
 *    разбора (замер саморазбора: AST 41 445 ячеек против `ХВОСТ` 1900).
 *
 * ГРАНИЦА, НАЗВАННАЯ ЗДЕСЬ ЖЕ: 54 формы (4 902 ячейки / 39 216 байт) в ките НЕ стоят, и это замер, а
 * не осторожность. Программа, разбирающая ленту всех 54 форм, на ЖЕЛЕЗЕ падает кодом **136**
 * (`Исключение в операции с плавающей точкой`) после шапки — И запечённая, И файловая одинаково, то
 * есть причина в ЛЕНТЕ, а не в носителе файла. Групповые программы (`b2b1p1`…`b2b7pN`) при этом
 * проходят все. Кит поэтому и держит 15 форм — покрытие B2b (шапка `parser-protocol-b2b.ts:10–13`
 * перечисляет, чего в нём нет).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3';
import { ФАЙЛ_ЛЕНТЫ, лентаПротоколаB2b, программаПротоколаB2b } from '../compiler-v3/parser-protocol-b2b';
import { ПРОГРАММЫ_B2B } from '../compiler-v3/parserProtocolB2bForms';
import { loweredProgram } from '../e2k/lowered';
import { FILE_PATH_TEXT } from '../e2k/fileCallRuntime';

/** Ровно те формы, из которых собран `bin/b2b-file.elf` кита. */
const ФОРМЫ_КИТА = [...ПРОГРАММЫ_B2B.b2b1, ...ПРОГРАММЫ_B2B.b2b2, ...ПРОГРАММЫ_B2B.b2b3];
const ИСТОЧНИК = `действие главная()\n  ${ФОРМЫ_КИТА.join('\n  ')}\nконец главная\n`;
const ФАЙЛ = 'b2b-file.osnova';

function понизить(текст: string): { отказ: string | null; длина: number } {
  const разобранный = parseV3(текст, ФАЙЛ);
  if (разобранный.errors.length > 0) return { отказ: разобранный.errors.map(String).join('; '), длина: 0 };
  const итог = loweredProgram(текст, {
    filename: ФАЙЛ,
    allowDeepArrayWrites: true,
    parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }),
  });
  return итог.ок ? { отказ: null, длина: итог.значение.bytes.length } : { отказ: итог.отказ.причина, длина: 0 };
}

describe('файловый вход: устройство программы', () => {
  it('путь носителя и путь генератора — одна строка', () => {
    expect(ФАЙЛ_ЛЕНТЫ).toBe(FILE_PATH_TEXT);
  });

  it('кит: лента 15 форм — 1 826 ячеек / 14 608 байт (для сравнения: 54 формы — 4 902 / 39 216)', () => {
    const ячейки = лентаПротоколаB2b(ИСТОЧНИК, ФАЙЛ);
    expect(ячейки.length).toBe(1826);
    expect(ячейки.length * 8).toBe(14608);
    const все = [...ФОРМЫ_КИТА, ...ПРОГРАММЫ_B2B.b2b4, ...ПРОГРАММЫ_B2B.b2b5, ...ПРОГРАММЫ_B2B.b2b6, ...ПРОГРАММЫ_B2B.b2b7];
    const всеЛента = лентаПротоколаB2b(`действие главная()\n  ${все.join('\n  ')}\nконец главная\n`, ФАЙЛ);
    expect(всеЛента.length).toBe(4902);
  });

  it('программа кита понижается без отказов и берёт ленту из файла', () => {
    const файловая = программаПротоколаB2b(ИСТОЧНИК, ФАЙЛ, { fromFile: true });
    const запечённая = программаПротоколаB2b(ИСТОЧНИК, ФАЙЛ);
    const добавлений = (текст: string): number => текст.split('Списки.добавить(лента,').length - 1;
    // Запечённая несёт ленту СТРОКАМИ CJK (`ч[пт] - 19968` — кодпоинт минус смещение), файловая не
    // несёт её вовсе: ячейки приходят `read`, а `добавить` остаётся только на петли (рост и AST-хвост).
    expect(запечённая).toContain('ч[пт] - 19968');
    expect(файловая).not.toContain('ч[пт] - 19968');
    expect(добавлений(файловая)).toBeLessThan(добавлений(запечённая));
    expect(файловая).toContain(`читать(${JSON.stringify(ФАЙЛ_ЛЕНТЫ)}, лента)`);
    expect(понизить(файловая)).toEqual({ отказ: null, длина: 192512 });
  });

  it('`cells` растит область под чтение, `astCells` сдвигает рабочие области за AST', () => {
    const обычная = программаПротоколаB2b(ИСТОЧНИК, ФАЙЛ, { fromFile: true });
    const большая = программаПротоколаB2b(ИСТОЧНИК, ФАЙЛ, { fromFile: true, cells: 12_345, astCells: 9_000 });
    const число = (текст: string, шаблон: RegExp): number => Number(шаблон.exec(текст)?.[1]);
    // Петля предварительного роста: по умолчанию это ДЛИНА ЛЕНТЫ (`числа.length`), то есть 1 826,
    // добитые нулями до кратности 100 → 1 900. С `cells` — ровно названное число.
    const рост = /пока пт < (\d+)\n {4}Списки\.добавить\(лента, 0, 0\)\n {4}пт = пт \+ 1/;
    expect(число(обычная, рост)).toBe(1900);
    expect(число(большая, рост)).toBe(12345);
    // Рабочая область разбора (`С`) = `начало + astCells + 1200`, где `начало = cells + 1 + шапка`.
    const состояние = /пусть верх = лента\[(\d+)\]/.exec(обычная)?.[1];
    expect(состояние).toBeDefined();
    const сдвиг = число(большая, /пусть верх = лента\[(\d+)\]/) - Number(состояние) - (12_345 - 1_900);
    expect(сдвиг).toBe(9_000);
  });
});
