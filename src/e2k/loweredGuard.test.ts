/**
 * ОРАКУЛ ДВЕРИ D11: у ОТКАЗА НЕТ БАЙТОВ — и это проверяется тремя разными способами.
 *
 * # Что здесь стережётся
 *
 * Решение D11 (вариант Г) разделило понижение на две двери:
 *
 * | дверь | что отдаёт | кому |
 * |---|---|---|
 * | `src/e2k/lowered.ts#loweredProgram` | `Результат<Образ, Отказ>`; в `Отказе` байтов НЕТ | потребителям |
 * | `src/e2k/guards/loweredUnchecked.ts#loweredProgramUnchecked` | байты ЕСТЬ ВСЕГДА, плюс отказы | сторожам |
 *
 * Смысл разделения — измеренный: под несущим отказом байты ЛГУТ (шестая тихая ложь, случай 60; седьмая,
 * случай 62: под названным отказом «склейка … в вызываемой процедуре» модель даёт **9** при эталонах
 * **1** и **7**). Поэтому «отказ есть, а байты вот» — не удобство, а канал лжи.
 *
 * # Чем именно стережётся
 *
 * 1. **Типом** — `@ts-expect-error` в `src/e2k/guards/loweredUnchecked.ts#контрольГраницыD11`:
 *    появится у `Отказа` поле `bytes` — `npm run typecheck` покраснеет.
 * 2. **Во время работы** — здесь: `'bytes' in отказ` обязано быть `false` (тест не типизируется
 *    гейтами, поэтому проверка идёт по факту, а не по объявлению).
 * 3. **Барьером ESLint** — здесь же, через API ESLint и БЕЗ файлов на диске: импорт сырого пути вне
 *    `src/e2k/**` и `tools/**` краснеет (правило по пути), а алиасинг и голое имя — вне
 *    `src/e2k/guards/**` и `src/e2k/*.test.ts` (правило по идентификатору).
 *
 * Плюс согласие дверей: `Отказ` обязан нести ровно те же отказы, что сырой путь, и ШАГ каждого отказа
 * обязан совпасть с номером носителя, который назван в тексте причины (`#N`). Это не украшение: шаг
 * собирается `try/finally` вокруг тела цикла, и ошибка в нём увела бы читателя к ЧУЖОМУ носителю.
 */
import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createRequire } from 'node:module';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram, type ОпцииСырогоПути } from './lowered';
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { LOWERING_CODES } from './loweringRefusal';

const КОРЕНЬ = path.resolve(__dirname, '..', '..');

/** Программа, которая ПОНИЖАЕТСЯ: байты есть, отказа нет. */
const ПРОСТАЯ = 'модуль П\nпроцедура главная()\n  вернуть 7 + 2\nконец\nконец\n';

/** Программа, которая ОТКАЗЫВАЕТ: у `IR.div` нет формы (код `OSN-LOW-002`, класс «нет формы»). */
const ДЕЛЕНИЕ = 'модуль О\nпроцедура главная()\n  вернуть 7 / 2\nконец\nконец\n';

/**
 * СЕДЬМАЯ ТИХАЯ ЛОЖЬ (случай 62): «склейка» короткого замыкания по значению — В ВЫЗЫВАЕМОЙ процедуре.
 * Байты под этим отказом отдаются сырым путём (и дают 9 против эталонов 1 и 7) — публичная дверь
 * обязана их НЕ отдать.
 */
const СЕДЬМАЯ_ЛОЖЬ = [
  'процедура ф(а: Число) → Число',
  '  если а >= 48 и а <= 57',
  '    вернуть 1',
  '  конец если',
  '  вернуть 0',
  'конец',
  'действие главная()',
  '  вернуть ф(10) * 10 + ф(50)',
  'конец',
  '',
].join('\n');

function опцииV3(источник: string, файл = 'проба.osnova'): ОпцииСырогоПути {
  const разобранный = parseV3(источник, файл);
  return { filename: файл, parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }) };
}

describe('D11: публичная дверь отдаёт Результат — и в Отказе НЕТ байтов', () => {
  it('понижение прошло: образ есть, отказа нет', () => {
    const итог = loweredProgram(ПРОСТАЯ);
    expect(итог.ок, 'простая программа обязана понизиться').toBe(true);
    if (!итог.ок) return;
    expect(итог.значение.bytes.length).toBeGreaterThan(0);
    expect('отказ' in итог, 'у успеха нет поля отказа').toBe(false);
  });

  it('понижение отказало: В ОТКАЗЕ НЕТ ПОЛЯ `bytes` — во время работы, а не по обещанию', () => {
    const итог = loweredProgram(ДЕЛЕНИЕ);
    expect(итог.ок, 'у `IR.div` формы нет — отказ обязан быть').toBe(false);
    if (итог.ок) return;
    const отказ = итог.отказ;

    // 1. ГЛАВНОЕ УТВЕРЖДЕНИЕ D11: ключа `bytes` нет вовсе (не «пустой» — ОТСУТСТВУЮЩИЙ).
    expect('bytes' in отказ, 'в Отказе НЕ ДОЛЖНО быть поля bytes').toBe(false);
    expect(Object.keys(отказ).includes('bytes'), 'и в перечислении ключей его нет').toBe(false);

    // 2. Диагностика при этом полная: причина, процедуры и запись на КАЖДЫЙ отказ.
    expect(отказ.причина.length).toBeGreaterThan(0);
    expect(отказ.отказы.length, 'отказ у деления один').toBe(1);
    expect(отказ.процедуры, 'имя процедуры названо, а не опущено').toEqual(['главная']);
    expect(отказ.отказы[0]!.код, 'код — личность отказа, а не текст').toBe(LOWERING_CODES.noForm);
    expect(отказ.отказы[0]!.причина).toContain('IR.div');
    expect(Number.isFinite(отказ.отказы[0]!.шаг), 'шаг — число (индекс носителя)').toBe(true);

    // 3. Число байтов — ДА (иначе закреплённые размеры нечем воспроизвести), сами байты — НЕТ.
    expect(отказ.кодовБайт, 'байты собраны, и их размер назван числом').toBeGreaterThan(0);
  });

  it('СЕДЬМАЯ ЛОЖЬ: под отказом «склейка в вызываемой» байты есть, но дверь их не отдаёт', () => {
    const итог = loweredProgram(СЕДЬМАЯ_ЛОЖЬ, опцииV3(СЕДЬМАЯ_ЛОЖЬ));
    expect(итог.ок, 'ложь обязана быть ПОД ОТКАЗОМ, а не без него').toBe(false);
    if (итог.ок) return;

    expect('bytes' in итог.отказ).toBe(false);
    expect(итог.отказ.кодовБайт, 'сырой путь байты собрал — вот их размер').toBeGreaterThan(0);
    expect(итог.отказ.процедуры, 'отказ назван в вызываемой процедуре').toContain('ф');
    const причина = итог.отказ.отказы.map((запись) => запись.причина).join('\n');
    expect(причина, 'причина — та самая, седьмая').toContain('склейка');
    expect(причина, 'и именно в ВЫЗЫВАЕМОЙ плоскости').toContain('ВЫЗЫВАЕМОЙ');
  });
});

describe('D11: двери согласны, а шаг отказа называет ТОТ ЖЕ носитель, что и текст причины', () => {
  it('отказов ровно столько же, сколько у сырого пути, и причины совпадают по порядку', () => {
    const публичный = loweredProgram(СЕДЬМАЯ_ЛОЖЬ, опцииV3(СЕДЬМАЯ_ЛОЖЬ));
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): здесь нужны ОБЕ стороны — байты и отказы — для сверки.
    const сырой = loweredProgramUnchecked(СЕДЬМАЯ_ЛОЖЬ, опцииV3(СЕДЬМАЯ_ЛОЖЬ));
    expect(публичный.ок).toBe(false);
    if (публичный.ок) return;

    expect(публичный.отказ.отказы.length).toBe(сырой.refused.length);
    expect(публичный.отказ.кодовБайт).toBe(сырой.bytes.length);
    expect(публичный.отказ.отказы.map((запись) => запись.код)).toEqual(сырой.refused.map((отказ) => отказ.code));
    expect(публичный.отказ.отказы.map((запись) => запись.причина)).toEqual(сырой.refused.map((отказ) => отказ.reason));
  });

  it('на ТЕЛЕ ЛЕКСЕРА (101 отказ): шаг каждого отказа совпадает с `#N` в его же причине', () => {
    const ЛЕКСЕР = path.join(КОРЕНЬ, 'src', 'self-host', 'lexer.osnova');
    const текст = fs.readFileSync(ЛЕКСЕР, 'utf-8');
    // ТЕЛО — без обёртки `лексировать_файл` (то же построение, что в `foundationE2k` и в П7), и с
    // ручкой арены: без неё конвейер ОСТАНАВЛИВАЕТСЯ утверждением «регистры арены не закреплены» и
    // переписи отказов не даёт вовсе (случай 46).
    const тело = текст.slice(0, текст.indexOf('// ЛЕКСИРОВАТЬ ФАЙЛ'));
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): стерегу ПЕРЕПИСЬ отказов и шаг каждого.
    const сырой = loweredProgramUnchecked(тело, { ...опцииV3(тело, 'лексер.osnova'), assumeArenaReserved: true });
    expect(сырой.refused.length, 'отказов тела лексера').toBe(101);
    // ШАГ ЕСТЬ У КАЖДОГО ОТКАЗА, включая отказы раскладки: они дописываются ПОСЛЕ цикла носителей, и
    // именно на них согласие ломалось (101 отказ против 100 шагов) — пока это не поймал этот сторож.
    expect(сырой.refusedSteps.length, 'шаг собран у КАЖДОГО отказа').toBe(сырой.refused.length);

    let сверено = 0;
    let доПотока = 0;
    сырой.refused.forEach((отказ, индекс) => {
      const шаг = сырой.refusedSteps[индекс]!;
      if (шаг < 0) {
        // ОТКАЗ ДО ПОТОКА НОСИТЕЛЕЙ: шага нет, и это ВИДНО (`ШАГ_ДО_ПОТОКА`), а не замаскировано нулём.
        доПотока += 1;
        return;
      }
      const названный = /#(\d+)/.exec(отказ.reason);
      if (названный === null) return;
      сверено += 1;
      expect(шаг, `шаг отказа #${String(индекс)} против «${отказ.reason.slice(0, 60)}»`).toBe(Number(названный[1]));
    });
    expect(сверено, 'сверять было что: у большинства отказов носитель назван в тексте').toBeGreaterThan(60);
    expect(доПотока, 'отказы стадий (до потока носителей) видно отдельно, а не как «шаг 0»').toBeGreaterThan(0);
  });
});

describe('D11: барьер ESLint — импорт по пути и по идентификатору (без файлов на диске)', () => {
  type Сообщение = { readonly severity: number; readonly ruleId?: string | null };
  type Итог = { readonly messages: readonly Сообщение[] };
  type Плоский = { lintText(код: string, опции: { filePath: string }): Promise<readonly Итог[]> };

  const ПРОБЫ: readonly { имя: string; путь: string; код: string; ждёмКрасное: boolean }[] = [
    {
      имя: 'потребитель вне src/e2k: импорт сырого пути',
      путь: path.join('src', 'проба-потребителя.ts'),
      код: "import { loweredProgramUnchecked } from './e2k/guards/loweredUnchecked';\nvoid loweredProgramUnchecked;\n",
      ждёмКрасное: true,
    },
    {
      имя: 'потребитель вне src/e2k: АЛИАСИНГ того же импорта',
      путь: path.join('src', 'проба-алиаса.ts'),
      код: "import { loweredProgramUnchecked as иначе } from './e2k/guards/loweredUnchecked';\nvoid иначе;\n",
      ждёмКрасное: true,
    },
    {
      имя: 'внутри src/e2k, но НЕ сторож и НЕ тест: голое имя',
      путь: path.join('src', 'e2k', 'проба-потребителя.ts'),
      код: "import { loweredProgramUnchecked as иначе } from './guards/loweredUnchecked';\nvoid иначе;\n",
      ждёмКрасное: true,
    },
    {
      имя: 'сторож в src/e2k/guards: разрешено',
      путь: path.join('src', 'e2k', 'guards', 'проба-сторожа.ts'),
      код: "import { loweredProgramUnchecked } from './loweredUnchecked';\nvoid loweredProgramUnchecked;\n",
      ждёмКрасное: false,
    },
    {
      имя: 'оракул src/e2k/*.test.ts: разрешено',
      путь: path.join('src', 'e2k', 'проба.test.ts'),
      код: "import { loweredProgramUnchecked } from './guards/loweredUnchecked';\nvoid loweredProgramUnchecked;\n",
      ждёмКрасное: false,
    },
    {
      имя: 'сама публичная дверь: разрешено',
      путь: path.join('src', 'e2k', 'lowered.ts'),
      код: "import { loweredProgramUnchecked } from './guards/loweredUnchecked';\nvoid loweredProgramUnchecked;\n",
      ждёмКрасное: false,
    },
    {
      имя: 'публичный потребитель: разрешено',
      путь: path.join('src', 'проба-двери.ts'),
      код: "import { loweredProgram } from './e2k/lowered';\nvoid loweredProgram;\n",
      ждёмКрасное: false,
    },
  ];

  it('правила краснеют ровно там, где дверь закрыта, и молчат там, где открыта (7/7)', async () => {
    const require_ = createRequire(import.meta.url);
    const { FlatESLint } = require_('eslint/use-at-your-own-risk') as {
      FlatESLint: new (опции: { cwd: string }) => Плоский;
    };
    const eslint = new FlatESLint({ cwd: КОРЕНЬ });

    const расхождения: string[] = [];
    for (const проба of ПРОБЫ) {
      const итоги = await eslint.lintText(проба.код, { filePath: path.join(КОРЕНЬ, проба.путь) });
      const красное = итоги.some((итог) => итог.messages.some((сообщение) => сообщение.severity === 2));
      if (красное !== проба.ждёмКрасное) {
        расхождения.push(`${проба.имя}: ждали ${проба.ждёмКрасное ? 'красное' : 'зелёное'}, получили ${красное ? 'красное' : 'зелёное'}`);
      }
    }
    expect(расхождения, 'барьер D11 ведёт себя не так, как заявлено').toEqual([]);
  });
});
