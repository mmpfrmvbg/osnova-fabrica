const КОРЕНЬ = path.resolve(__dirname, '..', '..');

/** Программа, которая ПОНИЖАЕТСЯ: байты есть, отказа нет. */
const ПРОСТАЯ = 'модуль П\nпроцедура главная()\n  вернуть 7 + 2\nконец\nконец\n';

/** Программа, которая ОТКАЗЫВАЕТ: у `IR.div` нет формы (код `OSN-LOW-002`, класс «нет формы»). */
const ДЕЛЕНИЕ = 'модуль О\nпроцедура главная()\n  вернуть 7 / 2\nконец\nконец\n';

/**
 * СЕДЬМАЯ ТИХАЯ ЛОЖЬ (случай 62) — **ЗАКРЫТА 2026-11-04** (ATOM-05-02-01, §3.166).
 *
 * Её носителем была эта программа: «склейка» короткого замыкания по значению В ВЫЗЫВАЕМОЙ процедуре
 * отказывала, а сырой путь под этим отказом отдавал байты, дававшие **9** против эталонов **1** и **7**.
 * Отказ стоял на том, что в плоскости вызываемой нет клетки, равной нулю ПО ПОСТРОЕНИЮ. Теперь она
 * есть — `%r12` закреплена носителем `IR.callee_zero` (§3.166), — и программа понижается без единого
 * отказа. Константа оставлена как ИМЯ ТОГО СЛУЧАЯ: на ней стоит проверка закрытия.
 */
const СЕДЬМАЯ_ЛОЖЬ = [
  'процедура ф(а: Число) → Число',
  '  если а >= 48 и а <= 57',
  '    вернуть 1',
  '  конец если',
  '  вернуть 0',
  'конец',
  'действие главная()',
  '  вернуть ф(10) * 10 + ф(50)',
  'конец',
  '',
].join('\n');

/**
 * ОСТАВШАЯСЯ СТЕНА — `если б`, где сравнение МАТЕРИАЛИЗОВАНО в переменную: к переходу приходит
 * РЕГИСТР, а не предикат, и пара «сравнение → переход» не составляется. Это НЕ плоскость вызываемой:
 * та же программа отказывает и в точке входа, поэтому правкой клетки нуля она не лечится и остаётся
 * названным долгом этого атома (см. `handoff/ATOM-05-02-01.md`, пункт «если б»).
 */
const ОСТАВШАЯСЯ_СТЕНА = [
  'процедура ф(а: Число) → Число',
  '  пусть б = а >= 48',
  '  если б',
  '    вернуть 1',
  '  конец если',
  '  вернуть 0',
  'конец',
  'действие главная()',
  '  вернуть ф(50)',
  'конец',
  '',
].join('\n');

function опцииV3(источник: string, файл = 'проба.osnova'): ОпцииСырогоПути {
  const разобранный = parseV3(источник, файл);
  return { filename: файл, parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }) };
}

describe('D11: публичная дверь отдаёт Результат — и в Отказе НЕТ байтов', () => {
  it('понижение прошло: образ есть, отказа нет', () => {
    const итог = loweredProgram(ПРОСТАЯ);
    expect(итог.ок, 'простая программа обязана понизиться').toBe(true);
    if (!итог.ок) return;
    expect(итог.значение.bytes.length).toBeGreaterThan(0);
    expect('отказ' in итог, 'у успеха нет поля отказа').toBe(false);
  });

  it('понижение отказало: В ОТКАЗЕ НЕТ ПОЛЯ `bytes` — во время работы, а не по обещанию', () => {
    const итог = loweredProgram(ДЕЛЕНИЕ);
    expect(итог.ок, 'у `IR.div` формы нет — отказ обязан быть').toBe(false);
    if (итог.ок) return;
    const отказ = итог.отказ;

    // 1. ГЛАВНОЕ УТВЕРЖДЕНИЕ D11: ключа `bytes` нет вовсе (не «пустой» — ОТСУТСТВУЮЩИЙ).
    expect('bytes' in отказ, 'в Отказе НЕ ДОЛЖНО быть поля bytes').toBe(false);
    expect(Object.keys(отказ).includes('bytes'), 'и в перечислении ключей его нет').toBe(false);

    // 2. Диагностика при этом полная: причина, процедуры и запись на КАЖДЫЙ отказ.
    expect(отказ.причина.length).toBeGreaterThan(0);
    expect(отказ.отказы.length, 'отказ у деления один').toBe(1);
    expect(отказ.процедуры, 'имя процедуры названо, а не опущено').toEqual(['главная']);
    expect(отказ.отказы[0]!.код, 'код — личность отказа, а не текст').toBe(LOWERING_CODES.noForm);
    expect(отказ.отказы[0]!.причина).toContain('IR.div');
    expect(Number.isFinite(отказ.отказы[0]!.шаг), 'шаг — число (индекс носителя)').toBe(true);

    // 3. Число байтов — ДА (иначе закреплённые размеры нечем воспроизвести), сами байты — НЕТ.
    expect(отказ.кодовБайт, 'байты собраны, и их размер назван числом').toBeGreaterThan(0);
  });

  it('СЕДЬМАЯ ЛОЖЬ ЗАКРЫТА: программа без отказов, и публичная дверь отдаёт образ', () => {
    // ПЕРЕМЕР 2026-11-04 (ATOM-05-02-01): прежняя редакция этой проверки требовала ОТКАЗА и
    // доказывала, что под ним байты не отдаются. Отказ снят вместе с клеткой нуля вызываемой
    // (§3.166), поэтому здесь проверяется ЗАКРЫТИЕ: 0 отказов и образ 568 байт, а обе стороны
    // («1» для ф(50), «0» для ф(10)) считаются раскладкой, а не отказом.
    const итог = loweredProgram(СЕДЬМАЯ_ЛОЖЬ, опцииV3(СЕДЬМАЯ_ЛОЖЬ));
    expect(итог.ок, 'ложь закрыта: программа обязана понизиться').toBe(true);
    if (!итог.ок) return;
    expect(итог.значение.bytes.length, 'образ седьмой лжи').toBe(568);
    expect('отказ' in итог, 'у успеха нет поля отказа').toBe(false);
    // СЫРАЯ ДВЕРЬ СОГЛАСНА: та же программа без отказов и с теми же байтами.
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): здесь нужны ОБЕ стороны — байты и отказы — для сверки.
    const сырой = loweredProgramUnchecked(СЕДЬМАЯ_ЛОЖЬ, опцииV3(СЕДЬМАЯ_ЛОЖЬ));
    expect(сырой.refused, 'отказов нет').toEqual([]);
    expect(сырой.bytes.length).toBe(итог.значение.bytes.length);
  });

  it('ОСТАВШАЯСЯ СТЕНА: `если б` (сравнение в переменной) по-прежнему отказывает — и это НЕ эта ложь', () => {
    // Названо, а не умолчано: атом 05-02-01 закрывает ТОЛЬКО плоскость вызываемой, а материализованное
    // сравнение не понижается ни в одной плоскости. Здесь стережётся, что отказ на месте и что причина
    // названа механизмом, — иначе следующая сессия примет молчание за починку.
    const итог = loweredProgram(ОСТАВШАЯСЯ_СТЕНА, опцииV3(ОСТАВШАЯСЯ_СТЕНА));
    expect(итог.ок, '«если б» обязано остаться отказом').toBe(false);
    if (итог.ок) return;
    const причина = итог.отказ.отказы.map((запись) => запись.причина).join('\n');
    expect(причина, 'причина — предикат, а не клетка нуля').toContain('предикат взять неоткуда');
  });
});

describe('D11: двери согласны, а шаг отказа называет ТОТ ЖЕ носитель, что и текст причины', () => {
  it('отказов ровно столько же, сколько у сырого пути, и причины совпадают по порядку', () => {
    // ПЕРЕМЕР 2026-11-04 (ATOM-05-02-01): седьмая ложь понижается без отказов, поэтому согласие
    // дверей проверяется на ОСТАВШЕЙСЯ стене (`если б`): она отказывает в ОБЕИХ плоскостях, и обе
    // двери обязаны назвать ОДИН И ТОТ ЖЕ отказ.
    const публичный = loweredProgram(ОСТАВШАЯСЯ_СТЕНА, опцииV3(ОСТАВШАЯСЯ_СТЕНА));
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): здесь нужны ОБЕ стороны — байты и отказы — для сверки.
    const сырой = loweredProgramUnchecked(ОСТАВШАЯСЯ_СТЕНА, опцииV3(ОСТАВШАЯСЯ_СТЕНА));
    expect(публичный.ок).toBe(false);
    if (публичный.ок) return;

    expect(публичный.отказ.отказы.length).toBe(сырой.refused.length);
    expect(публичный.отказ.кодовБайт).toBe(сырой.bytes.length);
    expect(публичный.отказ.отказы.map((запись) => запись.код)).toEqual(сырой.refused.map((отказ) => отказ.code));
    expect(публичный.отказ.отказы.map((запись) => запись.причина)).toEqual(сырой.refused.map((отказ) => отказ.reason));
  });

  it('на ТЕЛЕ ЛЕКСЕРА (76 отказов): шаг каждого отказа совпадает с `#N` в его же причине', () => {
    const ЛЕКСЕР = path.join(КОРЕНЬ, 'src', 'self-host', 'lexer.osnova');
    const текст = fs.readFileSync(ЛЕКСЕР, 'utf-8');
    // ТЕЛО — без обёртки `лексировать_файл` (то же построение, что в `foundationE2k` и в П7), и с
    // ручкой арены: без неё конвейер ОСТАНАВЛИВАЕТСЯ утверждением «регистры арены не закреплены» и
    // переписи отказов не даёт вовсе (случай 46).
    const тело = текст.slice(0, текст.indexOf('// ЛЕКСИРОВАТЬ ФАЙЛ'));
    // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): стерегу ПЕРЕПИСЬ отказов и шаг каждого.
    const сырой = loweredProgramUnchecked(тело, { ...опцииV3(тело, 'лексер.osnova'), assumeArenaReserved: true });
    // ПЕРЕМЕРЕНО 2026-11-05 (шаг 2.3, случай 73): 70 → 68 — шаг 2.3 снял два отказа «строковая
    // операция в вызываемой»: значение строки доказано сборкой по всем сайтам вызова, поэтому
    // временные клетки рантайма (`%b[10]`, `%b[11]`, `%b[13]`) закрепляются УСЛОВНО, и две склейки в
    // теле стали выразимы. Причина сдвига названа; число — из прогона, а не подогнано.
    // Прежняя история: было 99 → 70 — и сдвиг сложился из двух измеренных шагов: − 40 фантомных
    // `объединить` (план строк читал МЁРТВУЮ строку из переиспользованного регистра; снято
    // отслеживанием переопределений) + 11 названных отказов рантайм-склейки (одна сторона доказана,
    // вторая известна только в рантайме). История: 101 → 99 — ATOM-05-02-01 (клетка нуля:
    // `лексировать` раскладывается).
    // ПЕРЕМЕР 2026-11-05 (ERR-0002): 68 → 69. Правка даёт приёмнику вызова ТИП по объявленному
    // возврату вызываемой (`stringReturns`, `src/e2k/programImage.ts`), поэтому форма `+`, где обе
    // стороны — РЕЗУЛЬТАТЫ вызова, перестала уходить в АРИФМЕТИКУ и стала НАЗВАННЫМ отказом
    // (`#576 … обе стороны — Строка по типу`). Это не потеря, а находка: прежде форма складывала два
    // АДРЕСА молча — тихая ложь `2228212` (замер `.tmp/td62-модель.ts`, запись `ERR-0002`).
    // ПЕРЕМЕР 2026-11-05 (ATOM-06-02-02, статический срез): 69 → **76**, и это +7 — РОВНО ЧИСЛО
    // `подстрока` в теле лексера. Срез по доказанной строке и константным краям теперь СЧИТАЕТ СБОРКА,
    // но там, где значение или края из рантайма, план называет СВОЮ причину («края среза известны
    // только в рантайме…», «содержимое строки-параметра известно не для всех вызовов…»), а следом
    // звучит прежний отказ таблицы операций. То есть отказ на носитель стал ДВУМЯ строками: причины не
    // дублируются, а дополняются — вторая называет операцию, первая говорит, ЧЕГО не хватает.
    // Программ, которые отказывают, не прибавилось: срез с константными краями и доказанной строкой
    // собирается (`src/e2k/stringSliceStatic.test.ts`), остальные отказывали и прежде.
    expect(сырой.refused.length, 'отказов тела лексера').toBe(76);
    // ШАГ ЕСТЬ У КАЖДОГО ОТКАЗА, включая отказы раскладки: они дописываются ПОСЛЕ цикла носителей, и
    // именно на них согласие ломалось (101 отказ против 100 шагов) — пока это не поймал этот сторож.
    expect(сырой.refusedSteps.length, 'шаг собран у КАЖДОГО отказа').toBe(сырой.refused.length);

    let сверено = 0;
    let доПотока = 0;
    let сНомером = 0;
    сырой.refused.forEach((отказ, индекс) => {
      const шаг = сырой.refusedSteps[индекс]!;
      const названный = /#(\d+)/.exec(отказ.reason);
      // НОМЕР В ТЕКСТЕ — У КАЖДОГО ОТКАЗА (ATOM-06-02-02): прежде здесь стояло «у БОЛЬШИНСТВА», потому
      // что перепись делилась на «шаг есть» и «шага нет». После среза добавился ТРЕТИЙ класс — отказы
      // ПЛАНА строк (имя операции вместо носителя), и «большинство» перестало быть свойством сторожа:
      // оно стало свойством СОСТАВА файла. Свойство же сторожа — «у отказа есть номер, а если есть и
      // шаг, то они СОВПАДАЮТ» — держится у ВСЕХ, и теперь проверяется у всех.
      expect(названный, `отказ без номера #N: «${отказ.reason.slice(0, 60)}»`).not.toBeNull();
      if (названный === null) return;
      сНомером += 1;
      if (шаг < 0) {
        // ОТКАЗ ДО ПОТОКА НОСИТЕЛЕЙ: шага нет, и это ВИДНО (`ШАГ_ДО_ПОТОКА`), а не замаскировано нулём.
        доПотока += 1;
        return;
      }
      сверено += 1;
      expect(шаг, `шаг отказа #${String(индекс)} против «${отказ.reason.slice(0, 60)}»`).toBe(Number(названный[1]));
    });
    // СВЕРЯТЬ БЫЛО ЧТО — и оба числа названы, а не «больше половины»: **37** отказов несут
    // неотрицательный шаг носителя и сверены с `#N` (не сдвинулись ни одним срезом: было 39 из 70,
    // 37 из 68), **39** — отказы стадий (`доПотока`): 19 `символ` + 12 `объединить` + 1 `длина` +
    // **7 плановых причин среза** (`#N система.строка.подстрока: …` — у плана носителя ещё нет, и шага
    // у него быть не может). Гейт «номера нет ни у кого» закрыт ВЫШЕ и на всех 76.
    expect(сНомером, 'номер #N в тексте у КАЖДОГО отказа').toBe(сырой.refused.length);
    expect(сверено, 'отказы потока носителей: шаг сверен с #N').toBe(37);
    expect(доПотока, 'отказы стадий: было 32, +7 плановых причин среза').toBe(39);
  });
});

