/**
 * ОРАКУЛ: ВЫЗЫВАЕМАЯ ПРОЦЕДУРА СОЗДАЁТ МАССИВ САМА (A4, срез 3, §3.137).
 *
 * # Что проверяется
 *
 * До этого среза `создать` в вызываемой отказывало по имени: куча адресуется клеткой `%b[15]`, а
 * `%b[15]` вызываемой — ЧУЖАЯ клетка (закон окна: при `wbs = 4` `%b[n]` вызываемой есть `%b[n + 8]`
 * вызывающего), и адрес кучи в её плоскости никто не клал. Теперь адрес кладёт ПРОЛОГ РОСТА самой
 * процедуры (носитель `IR.array_slot`), и вызываемая умеет выделять массив.
 *
 * Проверяется не «нет отказа», а ЧИСЛО на модели:
 *   • П1 — вызываемая создаёт массив, пишет 7 и читает его обратно → **7**;
 *   • П2 — РАЗЛИЧАЮЩАЯ: массив точки входа (элемент 11) и массив вызываемой (элемент 22) обязаны
 *     лечь в РАЗНЫЕ места ОДНОЙ кучи: после записи 22 в свой массив вызываемая читает `а[0]`
 *     вызывающего → **11**. Совпало бы «22» или мусор — значит адрес ячейки кучи у вызываемой не тот
 *     (её блок лёг бы на чужой либо по мусорному адресу).
 *
 * # Границы, которые тут же и стерегутся (отказ по имени вместо петли — живой замер)
 *
 *   • `создать`/`установить` в плоскости ГЛУБИНЫ 2 (вход в неё идёт `wbs = 16`) — названный отказ
 *     `OSN-LOW-004`, и это НЕ перестраховка: трасса порта 2026-10-29 показала, что МОДЕЛЬ
 *     зацикливается ровно на `std` (pc = 0x1000d0), а тот же образ на ЖЕЛЕЗЕ проходит (код 3) —
 *     то есть стена МОДЕЛИ, а не цели (случай 48 `docs/verification-debt.md`, репро —
 *     `src/e2k/arrayWriteDepthTwo.test.ts`);
 *   • `добавить` в вызываемой — по-прежнему отказ: пяти ролям нужно пять клеток, а бюджет даёт три.
 *
 * Файл зависит от внешнего ресурса (`qemu-e2k` под шимом) и живёт в шлюзе `npm run gate:qemu`.
 *
 * # Чего оракул НЕ доказывает
 *
 * Что так поведёт себя железо (QEMU — модель): это отдельная проба на живой машине; и что куча у
 * процедур общая при ПЕРЕКРЫВАЮЩИХСЯ временах жизни — здесь вложенности вызовов нет, вызываемая
 * читает `а[0]` уже после того, как точка входа закончила `добавить`.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { loweredProgram } from './lowered';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'проба.osnova';
const shim = buildShim();

/** Программа: вызываемая ВЫДЕЛЯЕТ свой массив (то, чего до среза не умела). */
const СОЗДАНИЕ_В_ВЫЗЫВАЕМОЙ = [
  'процедура у_1(а: Список Число) → Число',
  '  пусть м: Список Число = []',
  '  м[0] = 7',
  '  вернуть м[0]',
  'конец',
  '',
  'действие главная()',
  '  пусть с: Список Число = []',
  '  добавить в с элемент 5',
  '  вернуть у_1(с)',
  'конец',
  '',
].join('\n');

/** Различающая: массив вызываемой НЕ должен лечь на массив вызывающего (куча одна на всех). */
const КУЧА_ОБЩАЯ = [
  'процедура у_1(а: Список Число) → Число',
  '  пусть м: Список Число = []',
  '  м[0] = 22',
  '  вернуть а[0]',
  'конец',
  '',
  'действие главная()',
  '  пусть с: Список Число = []',
  '  добавить в с элемент 11',
  '  вернуть у_1(с)',
  'конец',
  '',
].join('\n');

/** Граница: то же выделение, но процедура входит в работу из ГЛУБИНЫ 2. */
const ГЛУБИНА_2 = [
  'процедура у_2(а: Список Число) → Число',
  '  пусть м: Список Число = []',
  '  м[0] = 7',
  '  вернуть м[0]',
  'конец',
  '',
  'процедура у_1(а: Список Число) → Число',
  '  вернуть у_2(а)',
  'конец',
  '',
  'действие главная()',
  '  пусть с: Список Число = []',
  '  добавить в с элемент 5',
  '  вернуть у_1(с)',
  'конец',
  '',
].join('\n');

/** Граница: `добавить` в вызываемой — клеток бюджета на пять ролей нет. */
const ДОБАВИТЬ_В_ВЫЗЫВАЕМОЙ = [
  'процедура у_1(а: Список Число) → Число',
  '  добавить в а элемент 7',
  '  вернуть 1',
  'конец',
  '',
  'действие главная()',
  '  пусть с: Список Число = []',
  '  добавить в с элемент 5',
  '  вернуть у_1(с)',
  'конец',
  '',
].join('\n');

/** Собрать образ ПУТЁМ КОМПИЛЯТОРА и (если отказов нет) исполнить его в модели. */
function образ(источник: string, файл: string): {
  refused: readonly { readonly code: string; readonly reason: string }[];
  код: number | undefined;
} {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  // ПОТРЕБИТЕЛЬ (D11): под отказом байтов нет — дверь отдаёт Результат<Образ, Отказ>.
  // Отказы здесь НАБЛЮДАЮТСЯ (две границы ждут их числом и кодом), но через ПУБЛИЧНУЮ диагностику
  // `отказ.отказы` — код и причина; БАЙТЫ под отказом не нужны ни одной проверке.
  const итог = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (!итог.ок) {
    return {
      refused: итог.отказ.отказы.map((запись) => ({ code: запись.код, reason: запись.причина })),
      код: undefined,
    };
  }
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY })
      .bytes,
  );
  return { refused: [], код: runInQemu(путь, { shim: true, timeoutMs: 20_000 })?.status };
}

describe('A4 §3.137: создание массива из вызываемой процедуры', () => {
  it('П1: вызываемая создаёт массив, пишет 7 и читает → 7', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(СОЗДАНИЕ_В_ВЫЗЫВАЕМОЙ, 'a4s3-callee-create.elf');
    expect(refused, `непонижённые носители: ${refused.map((r) => r.reason).join('; ')}`).toEqual([]);
    expect(код, 'создать в вызываемой, м[0]').toBe(7);
  });

  it('П2 различающая: массив вызываемой не лёг на массив точки входа → 11', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(КУЧА_ОБЩАЯ, 'a4s3-callee-shared-heap.elf');
    expect(refused, `непонижённые носители: ${refused.map((r) => r.reason).join('; ')}`).toEqual([]);
    // 11 — элемент массива ВЫЗЫВАЮЩЕГО, прочитанный ПОСЛЕ того, как вызываемая записала 22 в свой.
    // Ушло бы 22 (блоки совпали) или мусор — значит ячейка кучи у вызываемой не та.
    expect(код, 'а[0] вызывающего после выделения в вызываемой').toBe(11);
  });

  it('граница: выделение из глубины 2 — названный отказ, а не петля', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(ГЛУБИНА_2, 'a4s3-callee-depth2.elf');
    expect(код, 'глубина 2 обязана быть отклонена, а не исполнена').toBeUndefined();
    expect(refused.length, 'отказ обязан быть назван').toBeGreaterThan(0);
    for (const item of refused) {
      expect(item.code, `код отказа: ${item.reason}`).toBe('OSN-LOW-004');
    }
    expect(
      refused.map((item) => item.reason).join(' '),
      'причина обязана называть замер, а не «нельзя»',
    ).toMatch(/2026-10-29/);
  });

  it('граница: `добавить` в вызываемой — отказ по имени (клеток бюджета нет)', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(ДОБАВИТЬ_В_ВЫЗЫВАЕМОЙ, 'a4s3-callee-append.elf');
    expect(код, '`добавить` в вызываемой обязано быть отклонено').toBeUndefined();
    expect(refused.length, 'отказ обязан быть назван').toBe(1);
    expect(refused[0]!.reason, 'причина обязана быть РАЗМЕРНОЙ').toMatch(/ТРИ клетки|пять/);
  });
});
