/**
 * СТОРОЖ КЛАССА D4: КОПИЯ, ЖИВАЯ НА ПУТИ, ОБОЙДЁННОМ ОПРЕДЕЛЕНИЕМ (случай 89).
 *
 * # Что измеряется
 *
 * `copyElim` снимал `IR.move d, a` как МЁРТВУЮ, если после неё не было линейного чтения `d` до
 * первого определения `d`. Но линейный порядок — не порядок исполнения: первое определение может
 * лежать на ОДНОЙ ветви `если`, а чтение — на ДРУГОЙ, куда это определение не исполняется.
 *
 * Минимальное репро: `строки` (соседняя процедура — она задаёт ненулевое смещение потока) и
 * `код_строки` с телом «взять `код = б`, затем в ветви `б = 92` переопределить `код = 10`,
 * иначе только сдвинуть `поз`, и вернуть `Успех(код)`». На HEAD точка входа получает
 * `Успех(0)` вместо `Успех(1072)`: отказов НЕТ, образ собран, число неверное — тихая ложь.
 *
 * # Почему это сторож, а не «ещё один тест»
 *
 * Число даёт только прогон в живом QEMU (`runInQemu`). Без модели файл обязан КРАСНЕТЬ, а не
 * молча пропускать проверку (случай 12 реестра проверяемости), поэтому он стоит только в
 * `vitest.qemu.config.ts`, рядом с `resultLowering.test.ts` и другими оракулами цели.
 *
 * # Контроль отката
 *
 * На HEAD (до правки) — ровно одна красная проверка этого файла, вывод `0` вместо `1072`.
 * После правки — зелёная. Ожидаемое число N = 1.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './lowered';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { runInQemu } from '../scripts/e2kQemuExec';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'd4-copyelim.osnova';

/**
 * Соседняя процедура — не украшение: при смещении 0 дефект маскируется раскладкой, а при
 * ненулевом смещении процедуры `код_строки` первое линейное определение `код` (в ветви `б = 92`)
 * оказывается между копией и чтением на другом пути. Тело `строки` взято из корпуса B, потому что
 * именно его размер/форма воспроизводят раскладку, при которой копия теряется.
 */
const ИСХОДНИК = [
  'процедура строки(текст: Список Число, предел: Число) → Число',
  '  пусть поз = 0',
  '  пусть с = 0',
  '  пока поз < предел',
  '    пусть кс = текст[поз]',
  '    если кс <= 32',
  '      поз = поз + 1',
  '      продолжить',
  '    конец если',
  '    если кс == 47',
  '      если поз + 1 < предел',
  '        пусть вс = текст[поз + 1]',
  '        если вс == 47',
  '          пока поз < предел',
  '            пусть гс = текст[поз]',
  '            если гс == 10',
  '              прервать',
  '            конец если',
  '            поз = поз + 1',
  '          конец пока',
  '          продолжить',
  '        конец если',
  '      конец если',
  '    конец если',
  '    если кс == 34',
  '      с = с + 1',
  '      поз = поз + 1',
  '      пока поз < предел',
  '        пусть б1 = текст[поз]',
  '        если б1 == 34',
  '          поз = поз + 1',
  '          прервать',
  '        конец если',
  '        если б1 == 10',
  '          прервать',
  '        конец если',
  '        если б1 == 92',
  '          поз = поз + 2',
  '        иначе',
  '          поз = поз + 1',
  '        конец если',
  '      конец пока',
  '      продолжить',
  '    конец если',
  '    поз = поз + 1',
  '  конец пока',
  '  вернуть с',
  'конец',
  '',
  'процедура код_строки(текст: Список Число, предел: Число, номер: Число) → Результат<Число, Число>',
  '  пусть поз = 0',
  '  пусть номер_кода = 0',
  '  пока поз < предел',
  '    пусть к = текст[поз]',
  '    если к == 34',
  '      поз = поз + 1',
  '      пока поз < предел',
  '        пусть б = текст[поз]',
  '        пусть код = б',
  '        если б == 92',
  '          код = 10',
  '        иначе',
  '          поз = поз + 1',
  '        конец если',
  '        если номер_кода == номер',
  '          вернуть Успех(код)',
  '        конец если',
  '        номер_кода = номер_кода + 1',
  '      конец пока',
  '      вернуть Неудача(1)',
  '    конец если',
  '    поз = поз + 1',
  '  конец пока',
  '  вернуть Неудача(2)',
  'конец',
  '',
  'действие главная()',
  '  пусть коды: Список Число = [34, 1072, 34]',
  '  пусть т0, к0 = код_строки(коды, 3, 0)',
  '  вывести к0',
  'конец',
  '',
].join('\n');

describe('D4: значение пары не теряется на границе процедуры', () => {
  it('строки + код_строки печатают 1072, а не 0', () => {
    const разбор = parseV3(ИСХОДНИК, ФАЙЛ);
    expect(разбор.errors, 'исходник минимального репро обязан разбираться').toEqual([]);
    const итог = loweredProgram(ИСХОДНИК, {
      filename: ФАЙЛ,
      parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    });
    expect(
      итог.ок,
      итог.ок
        ? ''
        : `понижение отказало: ${итог.отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`).join(' | ')}`,
    ).toBe(true);
    if (!итог.ок) return;

    const путь = path.join(ROOT, '.tmp', 'd4-copyelim-value.elf');
    fs.mkdirSync(path.dirname(путь), { recursive: true });
    fs.writeFileSync(
      путь,
      buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
        writable: true,
        extraMemory: WRITE_ZONE_EXTRA_MEMORY,
      }).bytes,
    );
    const прогон = runInQemu(путь, { shim: true, timeoutMs: 30_000 });
    expect(прогон, 'модель не ответила').toBeDefined();
    expect(прогон?.status, 'код возврата модели').toBe(0);
    expect(прогон?.stdout, 'нагрузка Успеха обязана быть 1072, а не 0').toBe('1072\n');
  });
});
