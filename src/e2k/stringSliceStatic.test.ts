describe('статический срез `подстрока`: значение и края известны сборке', () => {
  it('С1: `подстрока(с, 1, 3)` при `с = "абвгде"` собирается и печатает «бв» (было: отказ по имени)', () => {
    expect(собралось(С1_ПЕРЕМЕННАЯ)).toBe(true);
    верно_или_отказ(С1_ПЕРЕМЕННАЯ, 'срез-с1.elf', 'бв');
  });

  it('С1б: литерал прямо аргументом — «аб»: срез виден и без переменной', () => {
    expect(собралось(С1Б_ЛИТЕРАЛ)).toBe(true);
    верно_или_отказ(С1Б_ЛИТЕРАЛ, 'срез-с1б.elf', 'аб');
  });

  it('С1в: счёт по КОДОВЫМ ТОЧКАМ — кириллица «жз» и суррогатная пара «🙂» целой', () => {
    // Если бы срез считал БАЙТЫ, «ёжзийк» (12 байт) с краями 1…3 дал бы половину «ё» и мусор.
    // Конец ИСКЛЮЧАЮЩИЙ (как у эталона): индексы 1 и 2 — это «ж» и «з», третьей буквы нет.
    expect(собралось(С1В_КОДОВЫЕ_ТОЧКИ)).toBe(true);
    верно_или_отказ(С1В_КОДОВЫЕ_ТОЧКИ, 'срез-с1в.elf', 'жз\n🙂');
  });

  it('ОБ1: начало ЗА концом — ПУСТАЯ строка, а не адрес числом (второй дефект: `isStringPrint`)', () => {
    expect(собралось(ОБ1_НАЧАЛО_ЗА_КОНЦОМ)).toBe(true);
    верно_или_отказ(ОБ1_НАЧАЛО_ЗА_КОНЦОМ, 'срез-об1.elf', '');
    expect(собралось(ОБ1Л_ПУСТОЙ_ЛИТЕРАЛ)).toBe(true);
    верно_или_отказ(ОБ1Л_ПУСТОЙ_ЛИТЕРАЛ, 'срез-об1л.elf', '');
  });

  it('ОБ2: конец ЗА длиной — ОБРЕЗАЕТСЯ («вгде»), а не читает за блобом', () => {
    expect(собралось(ОБ2_КОНЕЦ_ЗА_ДЛИНОЙ)).toBe(true);
    верно_или_отказ(ОБ2_КОНЕЦ_ЗА_ДЛИНОЙ, 'срез-об2.elf', 'вгде');
  });

  it('С1д: результат среза — СТРОКА (её длина 3), а не число-адрес', () => {
    expect(собралось(С1Д_ДЛИНА_СРЕЗА)).toBe(true);
    верно_или_отказ(С1Д_ДЛИНА_СРЕЗА, 'срез-с1д.elf', '3');
  });

  it('П1/П2: пустая строка ЛИТЕРАЛОМ печатается пусто (ложь `1114112` была ДО среза)', () => {
    // Это КОНТРОЛЬ второго дефекта: правка `isStringPrint` обязана была закрыть его и без среза.
    expect(собралось(П1_ПУСТАЯ_ПЕРЕМЕННАЯ)).toBe(true);
    верно_или_отказ(П1_ПУСТАЯ_ПЕРЕМЕННАЯ, 'срез-п1.elf', '');
    expect(собралось(П2_ПУСТОЙ_ЛИТЕРАЛ)).toBe(true);
    верно_или_отказ(П2_ПУСТОЙ_ЛИТЕРАЛ, 'срез-п2.elf', '');
  });

  it('П3: обратная сторона — печать ЧИСЕЛ не сломана (пометки у неё нет)', () => {
    expect(собралось(П3_ЧИСЛА)).toBe(true);
    верно_или_отказ(П3_ЧИСЛА, 'срез-п3.elf', '5\n42');
  });

  it('С2: края из РАНТАЙМА — НАЗВАННЫЙ отказ (рантайм-срез не понижен, §3.138.4)', () => {
    const записи = отказы(С2_КРАЯ_ИЗ_РАНТАЙМА);
    const текст = записи.map((з) => `${з.код}: ${з.причина}`).join(' | ');
    expect(записи.length, 'тишина здесь значила бы число вместо строки').toBeGreaterThan(0);
    expect(текст).toContain(ИМЯ_СРЕЗА);
  });

  it('С3: строка из РАНТАЙМА, края константны — тоже НАЗВАННЫЙ отказ', () => {
    const записи = отказы(С3_СТРОКА_ИЗ_РАНТАЙМА);
    const текст = записи.map((з) => `${з.код}: ${з.причина}`).join(' | ');
    expect(записи.length).toBeGreaterThan(0);
    expect(текст).toContain(ИМЯ_СРЕЗА);
    expect(текст, 'и обязан назвать, ЧЕГО нет: значения строки, а не «не строка»').toContain(
      'содержимое строки-параметра известно не для всех вызовов',
    );
  });

  it('С1г: отрицательный край от конца — ОТКАЗ с названной причиной (эталон умеет, сборка — нет)', () => {
    // Названная граница, а не тишина: `-2` приезжает вычисленным регистром, доказанным краем не виден.
    const записи = отказы(С1Г_ОТРИЦАТЕЛЬНЫЙ_КРАЙ);
    const текст = записи.map((з) => `${з.код}: ${з.причина}`).join(' | ');
    expect(записи.length).toBeGreaterThan(0);
    expect(текст).toContain(КРАЯ_ИЗ_РАНТАЙМА);
  });
});
