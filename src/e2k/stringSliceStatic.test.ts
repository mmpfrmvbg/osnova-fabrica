/**
 * СТАТИЧЕСКИЙ СРЕЗ: `подстрока(строка, начало, конец)` СЧИТАЕТ СБОРКА, КОГДА ЗНАЧЕНИЕ И КРАЯ ИЗВЕСТНЫ.
 *
 * ═══ ЧТО БЫЛО (ЗАМЕР ДО ПОЧИНКИ, 2026-11-05, `.tmp/td62-срез.ts`) ════════════════════════════════════
 *
 *   `подстрока` не понижалась НИ НА КАКОЙ ГЛУБИНЕ. Отказ шёл из таблицы операций рантайма
 *   (`#N IR.invoke: «система.строка.подстрока»: у рантайма массивов нет такой операции`), и он был
 *   честным: рантайм-срез обязан копировать с РАНТАЙМОВОЙ длиной, то есть нужен ЦИКЛ с переходом, а
 *   переходы у цели существуют только как носители, которые строит `src/e2k/twoPassLayout.ts` — та
 *   самая граница, которую владелец закрыл («VLIW/ABI/раскладку не трогать», §3.138.4: понижение
 *   `подстрока` стоит в этом порядке ПОСЛЕДНИМ).
 *
 * ═══ ЧТО СТАЛО ═══════════════════════════════════════════════════════════════════════════════════════
 *
 * Решена часть, которой цикл НЕ нужен: строка доказана (`registerOf`), оба края — константы (литерал,
 * прошедший через пул чисел). Тогда результат известен сборке ЦЕЛИКОМ, и его байты — непрерывный
 * отрезок байтов исходного блоба. Ничего нового в раскладку не добавлено: значение едет тем же путём,
 * что и склейка литералов (регистрируется в `values`, байты кладёт раскладка блобов), а адрес даёт
 * носитель `IR.const` — тот же, которым литерал и был.
 *
 * СЕМАНТИКА ВЗЯТА У ЭТАЛОНА (`codePointSlice`, `src/runtime/vm/stringUnits.ts`), а не придумана: счёт
 * по КОДОВЫМ ТОЧКАМ, выход за границы ОБРЕЗАЕТСЯ, `конец <= начало` даёт ПУСТУЮ строку, суррогатная
 * пара не разрывается. Пробы С1в (кириллица и `🙂`) и ОБ1/ОБ2 держат именно это.
 *
 * ═══ ДВА ДЕФЕКТА, НАЙДЕННЫХ ЭТОЙ ЖЕ ПРОБОЙ (оба — тихая ложь) ═══════════════════════════════════════
 *
 *   • `kind: 'const'` у среза оставлял носитель `IR.invoke` (этот вид правки меняет только ОПЕРАНД) —
 *     вызов уходил в рантайм, который его не знает. Поймано замером `strings.code[#3]`: адрес блоба
 *     готов, а носитель всё ещё вызов. Заведён отдельный вид правки `slice`, он ЗАМЕНЯЕТ носитель.
 *   • `isStringPrint` требовал пометки `> 0`, поэтому ПУСТАЯ строка считалась числом: `вывести ""`
 *     печатало АДРЕС блоба (`1114112`), `вывести подстрока("абвгде", 3, 1)` — `1114100`, при нуле
 *     отказов и коде 0. Ложь ЖИЛА ДО СРЕЗА (проверено на HEAD теми же пробами П1/П2); теперь пометка
 *     ноль — тоже пометка, а П3 держит обратную сторону: печать ЧИСЕЛ пометки не ставит и не сломана.
 *
 * ═══ ГРАНИЦА ОСТАВЛЕНА НАЗВАННОЙ, А НЕ ОБОЙДЕНА ═════════════════════════════════════════════════════
 *
 *   • края из рантайма (С2) и строка из рантайма (С3) — по-прежнему ОТКАЗ, и он называет операцию;
 *   • отрицательный край от конца (С1г) — тоже ОТКАЗ: `-2` приезжает не числом, а вычисленным
 *     регистром, поэтому доказанным краем сборка его не видит. Эталон так умеет, сборка — нет, и
 *     говорит об этом, а не считает наугад;
 *   • рантайм-срез (нужен цикл) остаётся долгом: `plan/phase_06_strings/task_02_runtime_strings/
 *     atom_02_runtime_string_slice_join.yaml`.
 */
