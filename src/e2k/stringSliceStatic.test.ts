// ── Помощники (те же, что у соседних оракулов: один источник правды о двери) ──────────────────────

interface Отказ {
  readonly код: string;
  readonly причина: string;
  readonly шаг: number;
}

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

function отказы(источник: string): readonly Отказ[] {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  if (ошибки.length > 0) return [];
  const итог = loweredProgram(источник, options);
  if (итог.ок) return [];
  return итог.отказ.отказы.map((запись) => ({ код: запись.код, причина: запись.причина, шаг: запись.шаг }));
}

/** Собралось ли: у статических срезов отказов быть НЕ ДОЛЖНО, и это проверяется и вне шлюза. */
function собралось(источник: string): boolean {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист').toEqual([]);
  const итог = loweredProgram(источник, options);
  if (!итог.ок) throw new Error(`отказ: ${итог.отказ.отказы.map((з) => з.причина).join(' | ')}`);
  return true;
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

function прогон(источник: string, файл: string): { readonly код: number | null; readonly вывод: string } {
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'у этих проб отказов быть не должно — иначе число не спросить').toBe(true);
  if (!итог.ок) return { код: null, вывод: '' };
  const имя = шим();
  expect(имя, SHIM_REASON).toBeDefined();
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const исполнение = runInQemu(путь, { shim: true, timeoutMs: 30_000 });
  return { код: исполнение?.status ?? null, вывод: (исполнение?.stdout ?? '').trim() };
}

/** Признак шлюза: числа спрашиваются ТОЛЬКО там, где модель обязана быть (случай 12 реестра). */
const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';

/** «Значение верно ИЛИ отказ назван» — вне шлюза число не спрашивается, но тишина не прощается. */
function верно_или_отказ(источник: string, файл: string, эталон: string): void {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки).toEqual([]);
  const итог = loweredProgram(источник, options);
  if (!итог.ок) {
    const текст = итог.отказ.отказы.map((з) => з.причина).join(' | ');
    expect(текст, 'отказ обязан назвать ОПЕРАЦИЮ: иначе он неотличим от чужого').toContain(ИМЯ_СРЕЗА);
    return;
  }
  if (!В_ШЛЮЗЕ_QEMU) return;
  const { код, вывод } = прогон(источник, файл);
  expect(код, 'код возврата').toBe(0);
  expect(вывод, 'напечатанное обязано совпасть с эталоном ПОБАЙТОВО').toBe(эталон);
}

