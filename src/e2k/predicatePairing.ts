/**
 * Что инструкция пишет и что читает — по раскладке операндов носителя.
 *
 * Раскладка наша и живёт в эмиттере оболочки (`src/e2k/emitterShell.ts`): бинарные операции и
 * сравнения несут `(dst, a, b)`, `move`/`not` — `(dst, a)`, `const` — `(dst, k, type)`,
 * `call`/`invoke` — `(flags, src1, src2, imm, dst)` (приёмник пятый, а источников ровно `flags >> 1`),
 * `ret` — `(флаг, значение)`, `jmp_if`/`jmp_if_not` — `(cond, off)`, `jmp` — `(off)`, вытеснение в
 * память (`src/vliw/spill.ts`) — `spill_ld` `(адрес, приёмник, слот)`, `spill_st` `(значение, адрес, слот)`.
 *
 * `known: false` — операция, у которой приёмник и источники нам неизвестны; такая инструкция в
 * промежутке делает живость недоказанной, и пара отвергается (отказ, а не догадка).
 *
 * Носители вытеснения здесь описаны **обязательно**: они вставляются в поток между сравнением и
 * условным переходом, и пока они были «неизвестны», промежуток обрывался на них, а читателем
 * сравнения начинала считаться любая инструкция с тем же номером регистра дальше по потоку — то
 * есть пара отвергалась по ложной причине (измерено: `корреляция`, `.tmp/pair-refusal-debug.ts`).
 */
export function registersOf(instruction: AsmInstruction): { known: boolean; reads: number[]; writes: number[] } {
  const regs = (operands: readonly { kind: string; index?: number }[]): number[] =>
    operands.filter((operand) => operand.kind === "reg").map((operand) => operand.index!);
  const operands = instruction.operands;
  const known = (reads: number[], writes: number[]): { known: boolean; reads: number[]; writes: number[] } => ({
    known: true,
    reads,
    writes,
  });
  switch (instruction.mnemonic) {
    case "IR.spill_ld":
      // `movtd` + `ldd`: читается регистр адреса, пишется приёмник.
      return known(regs([operands[0]!]), regs([operands[1]!]));
    case "IR.spill_st":
      // `movtd` + `std`: читаются и значение, и регистр адреса; приёмника нет.
      return known(regs([operands[0]!, operands[1]!]), []);
    case "IR.const":
      return known([], regs([operands[0]!]));
    // НОЛЬ САЙТА (`IR.zero [приёмник]`): кладёт ноль в свой регистр, не читает ничего — роли ровно те
    // же, что у `IR.const [приёмник, …]` строкой выше, и по той же причине: это ПЕРЕСЫЛКА значения, а
    // не барьер. Ветвь заведена ИЗМЕРЕНИЕМ, а не для полноты — без неё носитель падал в умолчание
    // (`known: false`), и это давало ДВА разных отказа на одном корне (ATOM-08-01, шаг 1a; §3.183):
    //   · сторож ребра взятого перехода — `IR.zero` в пропущенном промежутке;
    //   · «условие пришло не из сравнения» — барьер ОБРЕЗАЛ окно поиска читателей результата
    //     сравнения, переход-читатель оказывался за барьером, и пара не составлялась.
    // Обе величины — факты носителя (приёмник один, чтений нет), поэтому алгоритм пар здесь не
    // участвует: ветвь отвечает на вопрос «какие регистры трогает носитель», не «как составить пару».
    case "IR.zero":
      return known([], regs([operands[0]!]));
    // АДРЕС ЯЧЕЙКИ КУЧИ В ВЫЗЫВАЕМОЙ (`src/e2k/arrayRuntime.ts#arraySlotPrologue`): ровно одна
    // `movtd` литерала в ПОСТОЯННУЮ клетку `ARRAY_REGISTERS.heapSlot`; чтений нет, приёмник в операндах
    // не назван (операнд 0 — сам адрес). Факт целиком — свойство носителя, поэтому ветвь допустима.
    // СОСЕДИ ПО ЦЕПИ (D33, `docs/decisions.md`): `IR.callee_zero`, `IR.print_write`, `IR.print_text`,
    // `IR.slice_runtime`, `IR.array_values` — СОСТАВНЫЕ (их записи не выводятся из операндов), и
    // ветвь каждому нужна отдельным атомом, а не «добавлением имени в таблицу».
    case ARRAY_SLOT_CARRIER:
      return known([], [ARRAY_REGISTERS.heapSlot]);
    // ХВОСТ `write` (`src/e2k/printPrimitives.ts#writeTextPrimitives`): барьер снят ЧТЕНИЕМ РАЗВЁРТКИ, а не
    // догадкой. Что доказано по коду и замерам:
    //   · свои рабочие клетки — `%b[2]` (адрес текста), `%b[4]` (длина), `%b[6]` (смещение), `%b[9]`
    //     (ноль): хвост пишет их ПЕРВЫМ делом и читает только записанное;
    //   · аргументы системного вызова ложатся в ОКОННЫЕ регистры `base+0..base+3`, а в кадре точки
    //     входа `base = 2·wbs = 8` — это `%b[8]`, `%b[9]`, `%b[10]`, `%b[11]`;
    //   · `call wbs = 4` отдаёт вызываемой `%b[8..15]` вызывающего, и восьмая тихая ложь измерена
    //     ИМЕННО на этом: `%b[4]` вызываемой — та же клетка, что `%b[12]` вызывающего (замер
    //     `src/e2k/printPrimitives.ts#writeTextPrimitives`, комментарий «ВЕРНУТЬ СВОЙ РЕГИСТР ДЛИНЫ»).
    // Поэтому ветвь объявляет ВСЕ клетки, которые носитель может оставить изменёнными в плоскости
    // точки входа: 2, 4, 6, 8, 9, 10, 11, 12, 13, 14, 15. ПЕРЕОЦЕНКА ЗАПИСЕЙ БЕЗОПАСНА (окно пары
    // обрывается раньше), НЕДООЦЕНКА — тихая ложь (D33/D34); чтений у хвоста нет вовсе — все чтения
    // идут по адресам из памяти, а регистры он перед чтением сам же и пишет.
    // `%b[0]`, `%b[1]`, `%b[3]`, `%b[5]`, `%b[7]` хвост НЕ трогает — развёртка числа (`IR.print_text`)
    // живёт отдельным атомом (D33): ветвь для неё была бы другим фактом.
    case PRINT_WRITE_CARRIER:
      return known([], [2, 4, 6, 8, 9, 10, 11, 12, 13, 14, 15]);
    case "IR.move":
    case "IR.not":
      return known(regs([operands[1]!]), regs([operands[0]!]));
    case "IR.add":
    case "IR.sub":
    case "IR.mul":
    case "IR.div":
    case "IR.rem":
    case "IR.eq":
    case "IR.ne":
    case "IR.lt":
    case "IR.le":
    case "IR.gt":
    case "IR.ge":
    case "IR.and":
    case "IR.or":
      return known(regs([operands[1]!, operands[2]!]), regs([operands[0]!]));
    case "IR.jmp_if":
    case "IR.jmp_if_not":
      return known(regs([operands[0]!]), []);
    case "IR.jmp":
      return known([], []);
    case "IR.ret":
      return known(regs([operands[1]!]), []);
    // ПАРА `Результат<Т, Е>` (`docs/abi-v3-draft.md` §10.2). Обе ветви обязательны: без них
    // носители — БАРЬЕРЫ (`known: false`), и сравнение, стоящее перед возвратом пары, получает
    // «читателей» из последующих сайтов — ровно тот отказ `OSN-LOW-004`, что держал восемь заходов
    // на арене (§3.89.3). Здесь же это не теория: без ветви возврат пары отказывал сразу.
    // `IR.ret_result [тег, нагрузка]` — читает оба, не пишет ничего.
    case "IR.ret_result":
      return known(regs([operands[0]!, operands[1]!]), []);
    // `IR.result_pick [приёмник, якорь]` — пишет приёмник, читает якорь (приёмник тега того же
    // вызова); якорь не источник данных, а зависимость порядка, и чтением он всё равно является.
    case "IR.result_pick":
      return known(regs([operands[1]!]), regs([operands[0]!]));
    case "IR.call":
    case "IR.invoke": {      // Аргументов ровно `argc = flags >> 1`: слот НЕсуществующего аргумента эмиттер всё равно несёт
      // (пятый операнд — приёмник, четвёртый — payload), и там лежит заполнитель вида `%b[0]`.
      // Считать его чтением нельзя: именно так сравнение в встроенной свёртке получало «второго
      // читателя» (`#54 IR.invoke` при `argc = 1` читал `%r0` — регистр результата `IR.lt #42`) и
      // пара отвергалась по ложной причине (измерено, `.tmp/convolution-callers.ts`).
      //
      // АРГУМЕНТЫ БЕРУТСЯ ОДНИМ ИСТОЧНИКОМ: третий аргумент лежит в поле `src3`, а не следом за
      // вторым, — прежняя арифметика `1 + index` прочла бы на argc = 3 нагрузку-число.
      const argv = callArgumentOperands(instruction).filter((operand) => operand !== undefined);
      return known(regs(argv), regs([operands[4]!]));
    }
    // АРЕНА (`src/e2k/arenaRuntime.ts`): регистры состояния — физические и в операндах не названы.
    // Без этих ветвей носители арены попадали в `known: false` — то есть в **барьер**, и сравнение
    // сайта получало «читателей» из всех последующих сайтов: предикат не составлялся вовсе
    // (измерено: «результат читают 2 инструкций (#9 IR.jmp_if_not, #18 IR.jmp_if_not)»).
    // ДОСТУП ПО АДРЕСУ-РЕГИСТРУ (`src/e2k/memoryAccess.ts`): роли операндов обратны общему случаю
    // `[d, a, b]`, поэтому умолчание объявило бы адрес определением, а приёмник — чтением.
    case LOAD_CARRIER: // [адрес, приёмник]
      return known(regs([operands[0]!]), regs([operands[1]!]));
    case STORE_CARRIER: // [значение, адрес]
      return known(regs([operands[0]!, operands[1]!]), []);
    // ДОСТУП БАЙТОМ (`ldb`/`stb`, решение владельца D26b): роли те же, что у `IR.load`/`IR.store`.
    // Ветви заведены ИЗМЕРЕНИЕМ, а не для полноты: без них конкретные `ldb`/`stb` — БАРЬЕР, и сторож
    // ребра взятого перехода отказывает на цикле рантайм-среза («между переходом и его целью стоит
    // «ldb» с неизвестными операндами — живость на ребре взятого перехода не доказана»; замер —
    // `docs/verification-debt.md`, случай 78).
    case LOAD_BYTE_CARRIER: // [адрес, приёмник]
      return known(regs([operands[0]!]), regs([operands[1]!]));
    case STORE_BYTE_CARRIER: // [значение, адрес]
      return known(regs([operands[0]!, operands[1]!]), []);
    case "IR.arena_init":
      return known([], [ARENA_POINTER_BASE, ARENA_LIMIT_BASE]);
    case "IR.arena_alloc": {
      const size = operands[0];
      const destination = operands[1];
      const use = size !== undefined && size.kind === "reg" ? [size.index] : [];
      const def = destination !== undefined && destination.kind === "reg" ? [destination.index] : [];
      return known([...use, ARENA_POINTER_BASE], [...def, ARENA_POINTER_BASE]);
    }
    case "IR.arena_pointer":
      return known([ARENA_POINTER_BASE], regs([operands[0]!]));
    case "IR.arena_limit":
      return known([ARENA_LIMIT_BASE], regs([operands[0]!]));
    case REFUSAL_CARRIER:
      return known([], []);
    // ВЫХОД РАБОТЫ (`IR.exit`): читает значение, если оно есть, и не пишет ничего.
    //
    // ЗАЧЕМ ЭТА ВЕТВЬ — ЗАМЕР, А НЕ АККУРАТНОСТЬ. Без неё носитель попадал в умолчание
    // (`known: false`), то есть в **БАРЬЕР**, и окно сравнения ВЫРОЖДАЛОСЬ: конец окна оставался
    // `instructions.length`, и «читателями» результата становились все переходы с тем же ключом
    // дальше по потоку. Замер (2026-10-03): у сайта `расширить` сравнение получило «читателей»
    // `#12 jmp_if` и `#26 jmp_if_not` — вторым был переход ЦИКЛА КОПИРОВАНИЯ, стоящего за выходом
    // точки входа; пара не составилась, и проба отказала `OSN-LOW-004`. Это ровно тот класс, что
    // держал восемь заходов на арене (§3.89.3): там барьером были носители арены, здесь — выход.
    case "IR.exit": {
      const values = operands
        .filter((operand) => operand.kind === "reg")
        .map((operand) => operand.index!);
      return known(values, []);
    }
    // РАСШИРЕНИЕ КУЧИ ПОД КОЛЛЕКЦИЮ (`src/e2k/collectionsRuntime.ts`): носитель называет ДВА
    // регистра-операнда (ёмкость и приёмник), но пишет ещё и регистры кадра системного вызова —
    // ОТВЕТ `brk` и ЗАПРОШЕННУЮ ГРАНИЦУ: их читает следующее за носителем сравнение. Без этой ветви
    // носитель был бы БАРЬЕРОМ (`known: false`), и проверка ответа не составила бы пару с переходом.
    case COLLECTION_ALLOC_CARRIER: {
      const capacity = operands[0];
      const destination = operands[1];
      const use = capacity !== undefined && capacity.kind === "reg" ? [capacity.index] : [];
      const def = destination !== undefined && destination.kind === "reg" ? [destination.index] : [];
      return known([...use, ...COLLECTION_FRAME_REGISTERS], [...def, ...COLLECTION_FRAME_REGISTERS]);
    }
    // СКЛЕЙКА В АРЕНЕ (`src/e2k/stringRuntime.ts`): сайт до расширения `[первая, вторая, приёмник,
    // байтов, байтов]` и копирование после `[первая, вторая, блок, байтов, байтов]`. Без этих ветвей
    // оба носителя стали бы БАРЬЕРОМ (`known: false`) — и сравнение сайта получило бы «читателей» из
    // последующих сайтов: ровно тот отказ, что держал восемь заходов (§3.89.3). Копирование пишет
    // временные `%b[10]`, `%b[11]` и единицу рантайма `%b[13]` — это названо, а не умолчано.
    case "IR.arena_concat":
      return known(regs([operands[0]!, operands[1]!]), regs([operands[2]!]));
    case "IR.string_arena_copy":
      return known(
        regs([operands[0]!, operands[1]!, operands[2]!]),
        [STRING_REGISTERS.first, STRING_REGISTERS.second, ARRAY_REGISTERS.one],
      );
    default:
      return { known: false, reads: [], writes: [] };
  }
}

/** Номер регистра, по которому инструкция читается как условие перехода. */
function conditionRegisterOf(instruction: AsmInstruction): number | undefined {
  if (!CONDITIONAL_JUMPS.includes(instruction.mnemonic)) return undefined;
  const operand = instruction.operands[0];
  return operand !== undefined && operand.kind === "reg" ? operand.index : undefined;
}

/**
 * Составить пары «сравнение → условный переход» и назвать причины, по которым пара не составилась.
 *
 * Каждая инструкция потока получает не больше одного отказа; для инструкций, к паре не
 * относящихся (например, безусловного `IR.jmp`), отказов нет вовсе.
 */
export function pairPredicates(instructions: readonly AsmInstruction[]): PairingResult {
  const pairs: PredicatePair[] = [];
  const refusals: PairingRefusal[] = [];
  const pairedJump = new Set<number>();
  /** Индексы сравнений, значение которых обязано лечь в регистр (см. §«Значение в регистре»). */
  const materialize = new Set<number>();
  /**
   * Отказ сопоставления: КОД один и назван здесь, а не у каждой формулировки.
   *
   * `OSN-LOW-004` — раскладка: предикат-приёмник ставит она, и сопоставление — её проход
   * (`src/e2k/loweringRefusal.ts`). Меняется только текст причины, личность — нет.
   */
  const refuse = (index: number, reason: string): void => {
    refusals.push({ index, code: LOWERING_CODES.layout, reason });
  };

  instructions.forEach((instruction, index) => {
    const comparison = comparisonMnemonicOf(instruction.mnemonic);
    if (comparison === undefined) return;
    const result = registersOf(instruction).writes[0];
    if (result === undefined) {
      refuse(index, `«${instruction.mnemonic}» #${index}: у сравнения нет регистра-результата`);
      return;
    }
    // Конец жизни значения: следующая инструкция, которая пишет тот же регистр.
    let end = instructions.length;
    let barrier: number | undefined;
    for (let next = index + 1; next < instructions.length; next++) {
      const info = registersOf(instructions[next]!);
      if (!info.known) {
        barrier = next;
        break;
      }
      if (info.writes.includes(result)) {
        end = next;
        break;
      }
    }
    const readers: number[] = [];
    for (let next = index + 1; next < end; next++) {
      if (registersOf(instructions[next]!).reads.includes(result)) readers.push(next);
    }
    if (barrier !== undefined && readers.length === 0) {
      refuse(
        index,
        `«${instruction.mnemonic}» #${index}: в промежутке (#${barrier} ${instructions[barrier]!.mnemonic}) ` +
          "операция с неизвестными операндами — живость результата не доказана",
      );
      return;
    }
    if (readers.length === 0) {
      refuse(index, `«${instruction.mnemonic}» #${index}: результат никем не читается — предикат некуда деть`);
      return;
    }
    // ПАРА СОСТАВЛЯЕТСЯ ТОЛЬКО С ОДНИМ ПЕРЕХОДОМ: предикат у пары один. Читатели, которые не
    // условие перехода, значения не отменяют — их обслуживает материализация (см. заголовок).
    const jumpReaders = readers.filter((at) => conditionRegisterOf(instructions[at]!) === result);
    if (jumpReaders.length !== 1) {
      // Ни одного перехода-читателя либо их несколько: пары нет. Сравнение всё равно понижаемо —
      // оно обязано положить значение в регистр. Переходы-читатели (если они есть) получат СВОЙ
      // названный отказ ниже, в общем проходе.
      materialize.add(index);
      return;
    }
    // У результата есть читатель-ЗНАЧЕНИЕ (кроме перехода): одной пары мало — сравнение обязано
    // ещё и положить значение в регистр, иначе цель прочтёт мусор (тихая ложь среза 5).
    if (readers.length > 1) materialize.add(index);
    const jumpIndex = jumpReaders[0]!;
    const jump = instructions[jumpIndex]!;
    const inverted = (jump.mnemonic === "IR.jmp_if_not") !== comparison.flipped;
    pairs.push({
      comparisonIndex: index,
      jumpIndex,
      comparison: instruction.mnemonic,
      jump: jump.mnemonic,
      cmpMnemonic: comparison.mnemonic,
      predicate: PREDICATE_FOR_PAIRS,
      condition: (inverted ? CTCOND_NEG_PRED : CTCOND_PRED) | PREDICATE_FOR_PAIRS,
    });
    pairedJump.add(jumpIndex);
  });

  // ── ЗВУЧНОСТЬ НА РЕБРЕ ВЗЯТОГО ПЕРЕХОДА (K5) ─────────────────────────────────────────────────
  //
  // Составленная пара ещё не значит верная: если цель перехода читает регистр-результат, значение
  // течёт по ребру, а предикат его не несёт. Проверка идёт ПОСЛЕ составления (нужны условия ВСЕХ
  // пар: «склейка» сравнивает два мира) и ДО перехода осиротевших — переход обязан получить свой
  // отказ ниже, а не остаться молча непонижённым.
  //
  // ЦИКЛА ПО ВЕРДИКТУ ЗДЕСЬ БОЛЬШЕ НЕТ, и это свойство, а не пропуск: прежде единственная
  // ветвь СНИМАЛА пару, поэтому пара, опиравшаяся на снятую «склейку», обязана была перепроверяться
  // (замер: цепочка `#256 → #257` глушила проверку `#250 → #251`, `.tmp/k5-precise-impact.ts`).
  // Теперь обе ветви только СТАВЯТ пометки и не трогают ни `pairs`, ни `pairByJump`, а сам вердикт
  // (`takenEdgeProblem`) пометок не читает — значит исход не зависит от порядка обхода, и одного
  // прохода достаточно. Отказ здесь по-прежнему возможен, но приходит он из ДРУГОГО места: носитель,
  // которому понижение не может выдать нужную форму (вызываемая плоскость — `VALUE_BRANCH_JUMP`).
  //
  // ЗАМЫКАНИЕ ПО ЦЕПОЧКЕ «СКЛЕЕК» НИЖЕ — отдельный проход ПО ПОМЕТКАМ, а не второй проход по вердикту,
  // и свойство оно сохраняет: пометка только ДОБАВЛЯЕТСЯ, каждый переход помечается не больше раза,
  // поэтому итоговое множество пометок от порядка обхода не зависит (см. случай 68).
  const pairByJump = new Map(pairs.map((pair) => [pair.jumpIndex, pair]));
  /**
   * Индексы переходов, помеченных «ветвь по значению» **в этом проходе**: по ним идёт замыкание ниже.
   *
   * Список ЛОКАЛЬНЫЙ, а не обход `VALUE_BRANCH_JUMP`: пометка живёт в `WeakSet` и переживает вызов, а
   * замыкание обязано считать ровно то, что решено здесь (иначе второй вызов на том же потоке пошёл бы
   * по чужим решениям).
   */
  const valueBranches: number[] = [];
  for (const pair of [...pairs]) {
    const problem = takenEdgeProblem(instructions, pair, pairByJump);
    if (problem === undefined) continue;
    // ЗНАЧЕНИЕ, нужное КАК ЗНАЧЕНИЕ: пара не снимается — сравнение материализует результат.
    // Иначе на ребре взятого перехода цель читала бы мусор (срез 5: `7` вместо `3`).
    if (problem.kind === "value") {
      materialize.add(pair.comparisonIndex);
      continue;
    }
    // «СКЛЕЙКА» С ДВУМЯ РАЗНЫМИ РЁБРАМИ: пара не снимается и НЕ отказывает — переход ветвится по
    // ЗНАЧЕНИЮ. Оба сравнения обязаны материализоваться: тогда на обоих рёбрах в регистре лежит
    // булево значение ВСЕЙ склейки, и `ct` читает предикат «значение равно нулю» вместо предиката
    // своего сравнения (см. `VALUE_BRANCH_JUMP`).
    const joinJump = instructions[problem.joinPair.jumpIndex];
    if (joinJump === undefined) continue;
    materialize.add(pair.comparisonIndex);
    materialize.add(problem.joinPair.comparisonIndex);
    VALUE_BRANCH_JUMP.add(joinJump);
    valueBranches.push(problem.joinPair.jumpIndex);
  }

  // ── ЗАМЫКАНИЕ ЦЕПОЧКИ «СКЛЕЕК»: ЦЕЛЬ ВЕТВИ ПО ЗНАЧЕНИЮ — СНОВА ВЕТВЬ ПО ЗНАЧЕНИЮ (случай 68) ────
  //
  // ИЗМЕРЕНО (2026-11-04; атом 5з.4, случай 68 реестра; замер Lead'а `.tmp/a5z4-g50-oracle.ts` и
  // НЕЗАВИСИМЫЙ замер `.tmp/a5z4-verify/`, обе плоскости). Программа
  // `если (а >= 48 и а <= 57) или а == 0` при `а = 50` СОБИРАЕТСЯ без единого отказа и отдаёт **5**
  // вместо **7** — тихая ложь худшего класса (D4): тело `если` пропущено, вернулось значение
  // «по умолчанию». Ложь НЕ плоскостная: та же форма врёт и в точке входа.
  //
  // МЕХАНИЗМ (на потоке ПОСЛЕ раскладки; проверен независимо, индекс за индексом):
  //
  //   #7  IR.jmp_if(r10, 11)   <<< ВЕТВЬ-ПО-ЗНАЧЕНИЮ     цель — #11, И ЭТО УСЛОВНЫЙ ПЕРЕХОД
  //   #10 IR.eq(…)                                        сравнение ЦЕЛИ лежит в ПРОПУЩЕННОМ интервале (7, 11)
  //   #11 IR.jmp_if_not(r10, 14)                          пара cmp#10 → jmp#11, код условия 0x60
  //
  // `#7` понижается как `disp; cmpesb значение, НОЛЬ; ct` и пишет **тот же** `%pred0`, который читает
  // `ct` цели `#11`. На взятом ребре `#7` цель `#11` приходит с предикатом «значение равно нулю», а
  // собственное сравнение `#10` **пропущено** — значит код `0x60` у `#11` означает НЕ то, для чего
  // считался: `#11` скачет ровно тогда, когда склейка ИСТИННА, и тело `если` теряется. Дискриминирующий
  // контроль: у формы `а >= 48 и а <= 57` помеченный переход целится в `IR.const` (не в условный
  // переход) — лжи нет, модель верна (7).
  //
  // ПРИЗНАК ОБЩИЙ И СТРУКТУРНЫЙ, а не «эта программа». `ct` читает ПРЕДИКАТ, а не регистр, поэтому
  // ветвить по значению можно только превратив значение в предикат (`cmpesb значение, НОЛЬ`); после
  // этого ЛЮБОЙ переход, достигнутый ПО ВЗЯТОМУ РЕБРУ такой ветви, читает ИМЕННО ЭТОТ предикат. Своё
  // сравнение такого перехода лежит на пропущенном пути (между ветвью и её целью) и на взятом ребре не
  // исполнено, поэтому условие его пары — чужое. Пара «сравнение → переход» выражает одно ребро, а тут
  // на одном `ct` сходятся ДВА ребра с разными предикатами — ровно то, от чего защищает
  // `VALUE_BRANCH_JUMP`; защита обязана идти ПО ЦЕПОЧКЕ, а не на одно звено.
  //
  // ПОЧЕМУ ЗАМЫКАНИЕ, А НЕ ЗАПРЕТ. Запрет («ветвь по значению с целью-переходом — отказ») убил бы
  // целую законную форму: `или` поверх `и` — обычное дело, и она сейчас СОБИРАЕТСЯ и врёт. Пометка
  // только ДОБАВЛЯЕТСЯ (монотонно), каждый переход помечается не больше раза, поэтому замыкание
  // сходится и не зависит от порядка обхода — свойство «вердикт не читает пометок» сохраняется.
  //
  // СРАВНЕНИЕ ЦЕЛИ МАТЕРИАЛИЗУЕТСЯ: на падающем ребре (сравнение исполнилось) значение обязано лежать
  // в регистре — иначе ветвь по значению прочла бы мусор. На взятом ребре в том же регистре уже лежит
  // значение склейки (ради этого и материализованы оба её сравнения выше).
  //
  // РЕГИСТРЫ ОБЯЗАНЫ СОВПАДАТЬ: признак «склейки» — оба звена решают по ОДНОМУ регистру (кодоген
  // ведёт всё выражение в один приёмник `d`). Если они разошлись, признак не выполнен и доказать
  // нечего — названный отказ, а не догадка: молчать здесь значило бы оставить тот же класс лжи.
  for (let at = 0; at < valueBranches.length; at++) {
    const jumpIndex = valueBranches[at]!;
    const jump = instructions[jumpIndex];
    const target = jump?.operands[1];
    if (jump === undefined || target === undefined || target.kind !== "imm") continue;
    const targetPair = pairByJump.get(target.value);
    if (targetPair === undefined) continue; // цель — не условный переход пары: склейки нет
    const targetJump = instructions[targetPair.jumpIndex];
    if (targetJump === undefined) continue;
    const sourceRegister = conditionRegisterOf(jump);
    const targetRegister = conditionRegisterOf(targetJump);
    if (sourceRegister === undefined || targetRegister === undefined) continue;
    if (sourceRegister !== targetRegister) {
      refuse(
        targetPair.comparisonIndex,
        `«${targetPair.comparison}» #${targetPair.comparisonIndex}: цель #${target.value} перехода #${jumpIndex} ` +
          `приходит ПО ВЗЯТОМУ РЕБРУ ветви по значению, но решает по %b[${String(targetRegister)}], а ветвь — ` +
          `по %b[${String(sourceRegister)}]: признак «склейки» не выполнен, и предикат цели уже переписан ` +
          "ветвью — доказать нечего (случай 68 реестра)",
      );
      continue;
    }
    if (VALUE_BRANCH_JUMP.has(targetJump)) continue;
    materialize.add(targetPair.comparisonIndex);
    VALUE_BRANCH_JUMP.add(targetJump);
    valueBranches.push(targetPair.jumpIndex);
  }

  // ── СТОРОЖ ВТОРОЙ ТИХОЙ ЛЖИ: накопитель конъюнкции на РЕБРЕ ВЗЯТОГО ПЕРЕХОДА (A4, срез 5б) ──────
  //
  // ИЗМЕРЕНО (задача 1 среза 5б; 12 проб — `.tmp/a5b-probes.ts`, `.tmp/a5b-diag.ts`, образы
  // `.tmp/a5b-hw/*.elf`; модель и обе VM). ВЕРНО: одно сравнение-значение (ложное и истинное), `или`,
  // `не`, границы-ПЕРЕМЕННЫЕ и ОДНА конъюнкция. ЛОЖЬ: две и более конъюнкции — 58 вместо 10
  // (`1·10 + 48`), 49, 225, 116, отказов при этом НОЛЬ.
  //
  // МЕХАНИЗМ (замер `.tmp/a5b-build-debug.ts` на потоке ПОСЛЕ планирования — том же, что у раскладки).
  // Короткое замыкание `A и B` понижено переходом ВПЕРЁД: `A` → `jmp_if_not` → `B`, а значение
  // конъюнкции читается на ЦЕЛИ перехода (ребро взято — второй терм пропущен). Поэтому на цели обязан
  // лежать результат ПЕРВОГО терма. Это верно ровно тогда, когда оба терма пишут ОДИН регистр:
  //   • одна конъюнкция (`#2 ge → r2`, `#6 le → r2`) — накопитель и есть результат пары, и он
  //     материализован, а значит записан ПЕРЕД переходом; на взятом ребре там `0`/`1` — ВЕРНО;
  //   • вторая конъюнкция — термы разводит РАСКЛАДКА РЕГИСТРОВ (`#4 ge → r4`, `#8 le → r3`), цель `#9`
  //     читает `r3`, куда пишет `#8` НА ПРОПУЩЕННОМ пути; на взятом ребре там остаётся чужое число —
  //     литерал границы `48`. Отсюда 58, 49, 225, 116.
  //
  //     Слово «раскладка» здесь ИЗМЕРЕНО, а не предположено (A4-5б, задача 5): поток ЭМИТТЕРА для той
  //     же программы даёт у обоих термов ОДИН регистр (`#4 IR.ge(r4, …)`, `#8 IR.le(r4, …)`), а
  //     `allocateProgram` на том же входе выдаёт `#4 → r4`, `#8 → r3` — накопитель рвёт раскладка
  //     (`src/e2k/regAlloc.ts`), а не кодоген. Разбор и точное репро — `docs/hardware-debt.md` §3.142.
  //     Это тот же класс, что закрытый случай 17 («раскладка рвёт накопитель»), поэтому сторож здесь —
  //     ЧЕСТНЫЙ ЗАПАС на время, пока причина не снята в 5в, а не окончательное решение.
  //
  // Отсюда сторож — РАЗДЕЛЕНИЕ накопителя, а не совпадение с формой программы: для пары «сравнение →
  // переход ВПЕРЁД» ищем в пропущенном промежутке материализуемое сравнение, которое пишет регистр,
  // ЧИТАЕМЫЙ ЦЕЛЬЮ и НЕ равный результату самой пары. Такой регистр на взятом ребре не записан —
  // значение мусорное по построению, какое бы число туда ни попало. Переход НАЗАД — заголовок цикла,
  // не склейка значения: его стережёт K5 (`takenEdgeProblem`).
  //
  // Границы сторожа названы честно: он ловит РАЗДЕЛЕНИЕ накопителя в этом потоке и НЕ ловит случай,
  // когда цель читает регистр, записанный в пропущенном промежутке НЕ сравнением (переносом), — такой
  // регистр в потоке планирования пишется и до перехода, и отличить «нужное значение» от «чужого»
  // без раскладки нечем (долг среза 5в, `docs/hardware-debt.md` §3.142).
  for (const pair of pairs) {
    const jump = instructions[pair.jumpIndex];
    const target = jump?.operands[1];
    if (target === undefined || target.kind !== "imm") continue;
    const to = target.value;
    if (to <= pair.jumpIndex || to >= instructions.length) continue;
    const targetInfo = registersOf(instructions[to]!);
    if (!targetInfo.known) continue;
    const result = registersOf(instructions[pair.comparisonIndex]!).writes[0];
    const split: string[] = [];
    for (let at = pair.jumpIndex + 1; at < to; at++) {
      const info = registersOf(instructions[at]!);
      if (!info.known) {
        // Операция с неизвестными операндами на пропущенном пути: доказать нечего, но и молчать
        // нельзя — названный отказ того же класса, что у `known: false` выше.
        refuse(
          pair.comparisonIndex,
          `«${pair.comparison}» #${pair.comparisonIndex}: между переходом #${pair.jumpIndex} и его целью ` +
            `#${to} стоит «${instructions[at]!.mnemonic}» с неизвестными операндами — живость на ребре ` +
            "взятого перехода не доказана",
        );
        split.length = 0;
        break;
      }
      if (!materialize.has(at)) continue;
      for (const written of info.writes) {
        if (written === result) continue;
        if (!targetInfo.reads.includes(written)) continue;
        split.push(`#${at} ${instructions[at]!.mnemonic} → %b[${written}]`);
      }
    }
    if (split.length === 0) continue;
    refuse(
      pair.comparisonIndex,
      `«${pair.comparison}» #${pair.comparisonIndex}: на РЕБРЕ ВЗЯТОГО перехода цель #${to} читает ` +
        `накопитель, который пишет ПРОПУЩЕННЫЙ второй терм (${split.join(", ")}), а результат самой пары — ` +
        `%b[${String(result)}]: термы разведены по разным регистрам, и на взятом ребре значения нет ` +
        "(тихая ложь среза 5б: 58 вместо 10). Сторож — src/e2k/predicatePairing.ts",
    );
  }

  // ПОМЕТКА МАТЕРИАЛИЗАЦИИ — отсюда и только отсюда: до этого места судьба пары ещё менялась
  // (цикл неподвижной точки), и пометка на снятой паре разошлась бы с отказом.
  for (const at of materialize) {
    const instruction = instructions[at];
    if (instruction !== undefined) MATERIALIZING.add(instruction);
  }

  // Условный переход без пары: условие пришло не из сравнения — предиката взять неоткуда.
  // Исключение одно и названо: переход, ветвящийся ПО ЗНАЧЕНИЮ (`VALUE_BRANCH_JUMP`), предиката пары
  // не читает вовсе — свой предикат он делает сам (`cmpesb значение, НОЛЬ`), поэтому потеря пары
  // склейки его не обезоруживает.
  instructions.forEach((instruction, index) => {
    if (!CONDITIONAL_JUMPS.includes(instruction.mnemonic) || pairedJump.has(index)) return;
    if (isValueBranchJump(instruction)) return;
    const condition = conditionRegisterOf(instruction);
    refuse(
      index,
      `«${instruction.mnemonic}» #${index}: условие %r${String(condition)} пришло не из сравнения ` +
        "(или сравнение отвергнуто) — предикат взять неоткуда",
    );
  });

  refusals.sort((a, b) => a.index - b.index);
  return { pairs, refusals };
}

/**
 * Чем плоха пара на РЕБРЕ ВЗЯТОГО перехода — или `undefined`, если пара звучит.
 *
 * # Почему линейного окна живости мало
 *
 * Инструкции между переходом и его ЦЕЛЬЮ на взятом ребре **не исполняются**, поэтому на цель регистр
 * приходит со значением, записанным ДО перехода. Линейное окно этого не видит: жизнь значения
 * объявляется конченой на следующей записи — а на ребре эта запись пропущена.
 *
 * # Два случая
 *
 * 1. **Значение нужно как значение** (`kind: "value"`). Цель (или поток от неё) читает регистр не
 *    как условие перехода, а как операнд (`IR.ret`, `IR.exit`, `IR.move`, аргумент вызова…). Пара
 *    **остаётся**, а сравнение помечается материализующим: понижение кладёт значение в регистр
 *    (форма `cmp*` + predicated `movts 0/1`), поэтому мусора здесь больше нет.
 * 2. **«Склейка» короткого замыкания** (`kind: "join"`). Цель сама есть условный переход, состоящий в
 *    паре со СВОИМ
 *    сравнением. Чтение регистра там намеренно (оба ребра сходятся на одном `ct`), и пара звучит
 *    ровно тогда, когда решения двух миров совпадают:
 *
 *    - предикатный мир: сравнение 1 оставило предикат `v` (`0x40` → 1, `0x60` → 0), и `ct` склейки
 *      скачет по НЕМУ;
 *    - мир значений: в регистре лежит БУЛЕВО значение сравнения 1 — `v`, а у «перевёрнутых» условий
 *      (`ge`/`gt`/`ne` — отрицаний в наборе `cmp*` нет) его отрицание; `ct` склейки скачет по НЕМУ.
 *
 *    Расходятся — один и тот же `ct` на двух рёбрах означает РАЗНОЕ. Измерено на модели:
 *    `если A и B` при ложном `A` возвращало `7` вместо `3` (`A` = `IR.ge` → `0x40`, склейка `0x60`),
 *    тогда как `пока A и B` (тот же `0x40`-набор, но `jmp_if_not` с `IR.lt` → `0x60`), `если A или B`
 *    и `пока A или B` — звучат: пять ядер (закреплённые числа) не затронуты, корпус железа тоже.
 *
 *    Расхождение больше не снимается отказом (A4, срез 5г): вызывающий кладёт `joinPair` — пару
 *    склейки, — и переход переводится на ветвление ПО ЗНАЧЕНИЮ (`VALUE_BRANCH_JUMP`). Отказ остался
 *    ровно там, где ветвление по значению доказать нечем: в плоскости ВЫЗЫВАЕМОЙ нет клетки, равной
 *    нулю по построению (`src/e2k/e2kRealRun.ts`).
 */
function takenEdgeProblem(
  instructions: readonly AsmInstruction[],
  pair: PredicatePair,
  pairByJump: ReadonlyMap<number, PredicatePair>,
):
  | { readonly kind: "value"; readonly reason: string }
  | { readonly kind: "join"; readonly reason: string; readonly joinPair: PredicatePair }
  | undefined {
  const result = registersOf(instructions[pair.comparisonIndex]!).writes[0];
  const target = instructions[pair.jumpIndex]!.operands[1];
  if (result === undefined || target === undefined || target.kind !== "imm") return undefined;
  for (let at = target.value; at < instructions.length; at++) {
    const info = registersOf(instructions[at]!);
    // Неизвестные операнды: чтения не видно — за это не отказываем (иначе отказ был бы шире
    // доказательства). Барьер в промежутке ДО перехода закрыт выше, своим отказом.
    if (!info.known) return undefined;
    if (info.writes.includes(result)) return undefined; // значение переписано — на ребре оно мертво
    if (!info.reads.includes(result)) continue;
    const join = at === target.value ? pairByJump.get(at) : undefined;
    if (join === undefined) {
      // ВИД `value`: значение нужно КАК ЗНАЧЕНИЕ. Пара при этом остаётся в силе — понижение обязано
      // ПОЛОЖИТЬ значение в регистр (материализация, `cmp*` + predicated `movts` 0/1).
      return {
        kind: "value",
        reason:
          `значение живо на ребре перехода: цель #${String(at)} (${instructions[at]!.mnemonic}) читает ` +
          `%r${String(result)} как ЗНАЧЕНИЕ — предикат значения не несёт`,
      };
    }
    const predicateValue = pair.condition === CTCOND_PRED ? 1 : 0;
    const inverted = comparisonMnemonicOf(pair.comparison)!.flipped;
    const booleanValue = inverted ? 1 - predicateValue : predicateValue;
    const valueWorldJumps = join.jump === "IR.jmp_if" ? booleanValue !== 0 : booleanValue === 0;
    const predicateWorldJumps = join.condition === CTCOND_PRED ? predicateValue !== 0 : predicateValue === 0;
    if (valueWorldJumps === predicateWorldJumps) return undefined;
    return {
      kind: "join",
      joinPair: join,
      reason:
        `значение живо на ребре перехода: цель #${String(at)} — «склейка» ${join.jump}, и на двух её ` +
        `рёбрах предикат означает РАЗНОЕ (мир значений: скачок=${String(valueWorldJumps)}, ` +
        `предикатный=${String(predicateWorldJumps)}) — один ct не выражает оба ребра; переход переводится ` +
        "на ветвление ПО ЗНАЧЕНИЮ (оба сравнения материализуются, ct читает предикат «значение равно нулю»)",
    };
  }
  return undefined;
}

