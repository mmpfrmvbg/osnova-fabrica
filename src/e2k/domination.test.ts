/**
 * СТОРОЖ ДОМИНИРОВАНИЯ (A4, срез 5д, задача 0). По D4 — сторож раньше причины.
 *
 * # Что стережём
 *
 * Инвариант: **для любого vreg, живого на входе ЦЕЛИ перехода, существует ОДИН отрезок жизни, накрывающий
 * и переход, и цель.** Иначе значение, переносимое через дугу, лежит не в той клетке, которую цель
 * прочтёт: программа соберётся, отказов будет ноль, а число — неверное.
 *
 * Инвариант сформулирован ДЛЯ ЛЮБОГО vreg, а не для результата сравнения: `mergeLoopCarriedSegments`
 * до среза 5д сшивал отрезки прямой дуги только когда ЦЕЛЬ ЧИТАЕТ vreg **на самой целевой команде**
 * (`defUseOf(targetInstruction).use`). Переменная, определённая ВНУТРИ ветви и прочитанная ПОСЛЕ неё,
 * цели не читает — и остаётся разъехавшейся. Найденный случай (60 реестра, проба E
 * `.tmp/a5g-lie5-hunt.ts`) — ровно это: модель **107** при эталоне 100, отказов **0**, утечка равна
 * первому терму `а`.
 *
 * # Чем это отличается от «сторож ловит ложь»
 *
 * Сторож ловит НАРУШЕНИЕ ГАРАНТИИ, а не ложь: он смотрит на отрезки и живость, а не на числа. Нарушение —
 * необходимое условие лжи, но не достаточное: замер задачи 1 (`.tmp/a5d-audit-patterns.ts`) показал
 * четыре нарушающих формы, из которых сегодня лжёт одна (E); в трёх других раскладка случайно отдала
 * разъехавшимся отрезкам ОДНУ клетку, и числа верны (100 = 100). Именно поэтому запись ниже — про место
 * и форму, а числовая запись лжи живёт в `src/e2k/joinValueLie.test.ts` (`ТИХАЯ_ЛОЖЬ`, там же число
 * **107**). Так «случайно повезло» не смешивается с «гарантировано верно».
 *
 * # Что здесь — ЗАПИСЬ ИЗВЕСТНОГО ДЕФЕКТА, а не отсутствие работы
 *
 * Тест «случай 60» записан как `KNOWN BAD`: он обязан КРАСНЕТЬ, когда починка среза 5д сшьёт отрезки
 * (нарушений станет 0). Порядок снятия записи: сначала перемерить случай 60 в модели (обязан стать 100),
 * потом снять запись и перевести пробу в «верно числом».
 *
 * # Контроли (иначе сторож ловил бы «всякий переход»)
 *
 * * `A` — та же конъюнкция, но переменная после ветви НЕ читается: нарушений нет (конъюнкция исправна,
 *   неверно именно ЧТЕНИЕ после ветви);
 * * переменная определена в ОБЕИХ ветвях — нарушений нет (определение доминирует чтение);
 * * цикл — нарушений нет (обратные дуги сшиваются широким правилом; сужение правила ломало FIR, замер
 *   `.tmp/cfg-experiment.ts`: 8 вместо 181).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { shellCarriers } from './programImage';
import { dominationViolations, jumpEdgesOf } from './domination';
import type { AsmInstruction } from './backend';

const ФАЙЛ = 'доминирование.osnova';

const программа = (тело: readonly string[]): string => ['действие главная()', ...тело, 'конец', ''].join('\n');

/**
 * Носители ТЕМ ЖЕ путём, что `src/e2k/programImage.ts#loweredProgram`: разбор `parseV3` подставляется,
 * потому что штатный фронтенд `если` в этой позиции не разбирает (срез 5д, задача 2). Носители — тот же
 * поток, который раскладка получает на вход, поэтому сторож спрашивает ЕЁ структуры.
 */
const носители = (тело: readonly string[]): readonly AsmInstruction[] => {
  const источник = программа(тело);
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор пробы: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  return shellCarriers(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
};

/** Проба E (случай 60): тело ветви пропущено, переменная `н` читается ПОСЛЕ ветви. */
const E: readonly string[] = [
  '  пусть а = 7',
  '  пусть б = 5',
  '  пусть н = 0',
  '  если а < 4 и б < 6',
  '    н = н + 1',
  '  конец если',
  '  пусть т = нет',
  '  если не т',
  '    н = н + 100',
  '  конец если',
  '  вернуть н',
];

/** Контроль A: та же конъюнкция, но чтения после ветви НЕТ. */
const A: readonly string[] = [
  '  пусть а = 7',
  '  пусть б = 5',
  '  пусть н = 0',
  '  если а < 4 и б < 6',
  '    н = н + 1',
  '  конец если',
  '  вернуть н',
];

/** Определение доминирует: переменная определена в ОБЕИХ ветвях, чтение после ветви. */
const ДОМИНИРУЕТ: readonly string[] = [
  '  пусть а = 7',
  '  пусть б = 5',
  '  пусть н = 0',
  '  если а < 4 и б < 6',
  '    н = н + 1',
  '  иначе',
  '    н = н + 2',
  '  конец если',
  '  вернуть н',
];

/** Цикл: значение переносится ОБРАТНОЙ дугой — обязано сшиваться широким правилом. */
const ЦИКЛ: readonly string[] = [
  '  пусть а = 7',
  '  пусть н = 0',
  '  пусть к = 0',
  '  пока к < 3',
  '    н = н + а',
  '    к = к + 1',
  '  конец пока',
  '  вернуть н',
];

describe('сторож доминирования: значение переносится через переход ОДНОЙ клеткой', () => {
  it('случай 60 (ЗАПИСЬ ИЗВЕСТНОГО ДЕФЕКТА): значение `н` разъехалось на две клетки', () => {
    const поток = носители(E);
    const нарушения = dominationViolations(поток);
    // КОГДА ПОЧИНКА 5д СШЬЁТ ОТРЕЗКИ, ЗДЕСЬ СТАНЕТ 0 — тогда перемерить случай 60 в модели
    // (обязан дать 100 вместо 107), снять эту запись и перевести пробу в «верно числом».
    expect(нарушения.length, 'нарушений ровно одно: значение `н`, переносимое мимо тела ветви').toBe(1);
    const [нарушение] = нарушения;
    expect(нарушение!.at).toBe(10);
    expect(нарушение!.target).toBe(15);
    expect(нарушение!.mnemonic).toBe('IR.jmp_if_not');
    expect(нарушение!.backward).toBe(false);
    // Разъехавшиеся отрезки: до определения внутри ветви и после него — если они сшиты, здесь один отрезок.
    expect(нарушение!.segments.map((s) => `${String(s.start)}..${String(s.end)}`)).toEqual(['2..11', '14..24']);
  });

  it('контроль A: без чтения после ветви нарушений нет (конъюнкция исправна)', () => {
    expect(dominationViolations(носители(A))).toEqual([]);
  });

  it('определение доминирует чтение (обе ветви пишут) — нарушений нет', () => {
    expect(dominationViolations(носители(ДОМИНИРУЕТ))).toEqual([]);
  });

  it('цикл: обратная дуга сшивается широким правилом — нарушений нет', () => {
    const поток = носители(ЦИКЛ);
    const дуги = jumpEdgesOf(поток);
    // Не «нет переходов — нет нарушений»: в цикле обязана быть ОБРАТНАЯ дуга (цель раньше перехода).
    expect(дуги.some((edge) => edge.target < edge.at), 'в цикле есть обратная дуга').toBe(true);
    expect(dominationViolations(поток)).toEqual([]);
  });

  it('сторож не пуст: у случая 60 переходы ЕСТЬ, и нарушение именно на переносе значения', () => {
    const поток = носители(E);
    // Не «нет переходов — нет нарушений»: у пробы три перехода, и все цели в пределах потока.
    expect(jumpEdgesOf(поток).map((edge) => `${String(edge.at)}→${String(edge.target)}`)).toEqual(['6→10', '10→15', '19→24']);
    // Нарушение ровно одно — на дуге 10→15; дуги 6→10 и 19→24 чисты.
    expect(dominationViolations(поток).map((н) => н.at)).toEqual([10]);
  });
});
