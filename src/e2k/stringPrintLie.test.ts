/**
 * СЛУЧАЙ 71: ПЕЧАТЬ ЧИСЛА ЛОМАЕТ СТРОКОВЫЙ РАНТАЙМ ЦЕЛИ — сторож (найден 2026-11-04, срез 6).
 *
 * # Что здесь спрашивается
 *
 * На ЦЕЛИ после печати ЧИСЛА следующая строковая операция врёт: `с[1]` по строке «абв» даёт −1 или
 * 9647 там, где канон §13.6 требует 1073 (код «б», U+0431). Обе VM на ТОМ ЖЕ исходнике верны,
 * отказов понижения 0 — то есть программа собирается и отдаёт неверное число. Это ТИХАЯ ЛОЖЬ
 * (девятая), а не отказ.
 *
 * # Наблюдение
 *
 * Код возврата — 8-битный канал (`AGENTS.md`): 1073 mod 256 = 49, то есть широкое число через него
 * не наблюдается ВООБЩЕ. Поэтому пробы ПЕЧАТАЮТ и сравниваются БАЙТЫ вывода целиком, а не
 * `includes`/`trim` (иначе «10» и «100» неразличимы — §3.43).
 *
 * # Различающая сила
 *
 * Пробы держат ОБЕ стороны границы, и это не украшение: без контрольных проб сторож краснел бы и на
 * честном отказе, и на чужой поломке. Контроли — «индекс один без печати» и «печать СТРОКИ, затем
 * индекс»: замером они ВЕРНЫ до правки, поэтому красное на них означало бы, что сломалось что-то
 * другое, а не случай 71.
 */
import { describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { MINIMAL_BASE, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';

const ROOT = path.resolve(__dirname, '..', '..');
// Сторож БЕЗ МОДЕЛИ обязан краснеть, а не пропускать проверку (случай 12): строка ниже падает, если
// шим не собирается, — и это намеренно, иначе «модель недоступна» растворилось бы в зелёном.
buildShim();

const ФАЙЛ = 'печать-ложь.osnova';
const опцииV3 = (src: string) => {
  const р = parseV3(src, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Вывод цели для v3-программы (печать, а не код возврата: числа ≥ 256 в код не влезают). */
function вывод(имя: string, тело: string): string {
  const src = `действие главная()\n  ${тело}\nконец\n`;
  const образ = loweredProgramUnchecked(src, опцииV3(src));
  expect(
    образ.refused.map((item) => `${item.code ?? '—'} ${item.reason}`),
    'отказов быть не должно: ложь тем и опасна, что программа СОБИРАЕТСЯ',
  ).toEqual([]);
  const elf = path.join(ROOT, '.tmp', `печать-ложь-${имя}.elf`);
  fs.mkdirSync(path.dirname(elf), { recursive: true });
  fs.writeFileSync(
    elf,
    buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: образ.arena.extraMemory }).bytes,
  );
  return runInQemu(elf, { shim: true, timeoutMs: 30_000 })?.output ?? '';
}

describe('случай 71: печать числа не смеет ломать строковый рантайм', () => {
  const ПРОБЫ: Array<[string, string, string]> = [
    // Контроль: индекс один, печати числа перед ним нет.
    ['индекс-один', 'пусть с = "абв"\n  вывести с[1]', '1073\n'],
    // Контроль: перед индексом стоит печать СТРОКИ — замером она строковый рантайм не ломает.
    ['печать-строки-затем-индекс', 'пусть с = "абв"\n  вывести с\n  вывести с[1]', 'абв\n1073\n'],
    // ЛОЖЬ: печать числа ЛИТЕРАЛОМ (никакой строки в печати нет — значит, дело в сайтe печати числа).
    ['печать-числа-затем-индекс', 'пусть с = "абв"\n  вывести 5\n  вывести с[1]', '5\n1073\n'],
    // ЛОЖЬ: тот же индекс после печати ДЛИНЫ.
    ['печать-длины-затем-индекс', 'пусть с = "абв"\n  вывести длина с\n  вывести с[1]', '3\n1073\n'],
    // ЛОЖЬ: длина посчитана ЗАРАНЕЕ и лежит в переменной — печатается уже переменная, а не операция.
    ['печать-переменной-затем-индекс', 'пусть с = "абв"\n  пусть д = длина с\n  вывести д\n  вывести с[1]', '3\n1073\n'],
    // ЛОЖЬ: индекс приходит ПЕРЕМЕННОЙ (известен только в рантайме) после печати числа.
    ['печать-числа-затем-индекс-переменной', 'пусть с = "абв"\n  пусть н = 1\n  вывести 5\n  вывести с[н]', '5\n1073\n'],
    // ЛОЖЬ КОПИТСЯ: три операции подряд — теряется уже и ВЫВОД строки, а не только число.
    ['три-операции-подряд', 'пусть с = "абв"\n  вывести с[1]\n  вывести длина с\n  вывести с', '1073\n3\nабв\n'],
  ];

  for (const [имя, тело, эталон] of ПРОБЫ) {
    it(`${имя}: вывод побайтово`, () => {
      expect(вывод(имя, тело), `случай 71, проба «${имя}»`).toBe(эталон);
    });
  }
});
