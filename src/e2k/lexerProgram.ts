/**
 * ПРОДАКШЕН-ЛЕКСЕР ЯЗЫКА ОСНОВА НА ЦЕЛИ e2k — одна одно-проходная программа.
 *
 * # Что это, а не «ещё одна проба»
 *
 * До этого атома полный лексер на цели существовал как ТЕСТОВАЯ программа B
 * (`.tmp/b-dispatcher.ts`): семь процедур, каждая ПОВТОРНО сканирует текст и считает токены
 * своего вида. Она доказала раскладку (пик 10, 1 вытеснение, 0 отказов) и печать `tokenizeV3`
 * на модели и железе (D48), но лексером в продакшен-смысле не была: проходов семь, токенов
 * нет, вида «строка» и «комментарий» в одном проходе нет.
 *
 * Здесь — один проход: dispatcher в точке входа читает текст слева направо, на каждом шаге
 * зовёт МАЛЫЙ handler своего вида, тот возвращает конец токена (`Результат<Число, Число>`,
 * ≤3 аргумента), dispatcher дописывает токен и идёт дальше. Ни один байт не читается дважды,
 * кроме подсчёта строк по потреблённому блоку комментария (это учёт, а не повторная лексика).
 *
 * # Токен и его канал
 *
 * `V3Token` (`src/compiler-v3/lexer.ts`) = `{ kind, lexeme, value?, line }`, где у строки
 * `lexeme` — УЖЕ ДЕКОДИРОВАННОЕ содержимое (эталон делает `push("строка", value, value)`).
 * Здесь токен кодируется в ПЛОСКИЙ список чисел, по одному числу на линию канала печати:
 *
 *     <код вида>, <строка>, <длина лексемы>, <кодпоинт> × длина
 *
 * Это ПОЛНАЯ запись токена: вид, номер строки и лексема (для строки — декодированная, для
 * имён/чисел/знаков — как в исходнике). `value` строки в `tokenizeV3` равен `lexeme`, поэтому
 * отдельного поля не нужно; `value` числа выводится из лексемы.
 *
 * # Контракт (D42/D43), выраженный здесь
 *
 *   лексировать(арена: Список Число, текст: Список Число) -> Результат<Список<Токен>, Ошибка>
 *     требует:      арена пуста и жива; текст — кодовые точки (D1: 8 байт на кодпоинт)
 *     обеспечивает: Успех  ⇒ токены идут подряд, последний вид = `конец_файла`,
 *                            у каждого токена вид/строка/лексема совпадают с `tokenizeV3`
 *                   Неудача ⇒ причина названа кодом, список не дописан
 *     эффекты      арена: запись
 *
 * # Названная граница e2k (не гипотеза, а замер этого атома)
 *
 * Публичная функция-ВЫЗЫВАЕМАЯ, строящая список, на цели сегодня невозможна: `добавить` в
 * вызываемой — названный РАЗМЕРНЫЙ отказ (`arrayRuntime.ts`: блоку три клетки, операции нужно
 * пять ролей), `положить`/`выделить` — «коллекции работают только в ТОЧКЕ ВХОДА». Поэтому
 * арена-список строится в ПЛОСКОСТИ ТОЧКИ ВХОДА, которую здесь и занимает `лексировать` — это
 * `действие`, публичная точка модуля. Кто зовёт лексер (парсер) на цели, тот получает токены
 * из этой же плоскости; вызов-функция с собственным списком — отдельный долг кодогена, а не
 * тихо подменённая семантика. Граница записана в `docs/verification-debt.md`, случай 90.
 *
 * # Эталон
 *
 * `tokenizeV3` (`src/compiler-v3/lexer.ts`) — тот же, которым подписаны куски 1–4 среза 7.
 * `эталон()` проецирует его токены в {@link Токен}; сравнение с выводом программы —
 * побайтовое по (вид, лексема, строка), а не по счётчикам.
 */
