/** Эталон: токены `tokenizeV3` без `value` (у строки `value === lexeme`). */
export function эталон(текст: string): Токен[] {
  const { tokens, errors } = tokenizeV3(текст, 'оракул.osnova');
  if (errors.length > 0) throw new Error(`эталон не разобрал вход: ${errors.join('; ')}`);
  return tokens.map((т) => ({ вид: т.kind, лексема: т.lexeme, строка: т.line }));
}

/** Виды, которые считает историческая мера кусков (для столбца «как в §3.182/3.183»). */
export function мераКусков(токены: readonly Токен[]): {
  имена: number;
  числа: number;
  знаки: number;
  ключевые: number;
  строки: number;
  длина: number;
  суммаКодов: number;
  л1: number;
} {
  let имена = 0;
  let числа = 0;
  let знаки = 0;
  let ключевые = 0;
  let строки = 0;
  let длина = 0;
  let суммаКодов = 0;
  let л1 = 0;
  for (const т of токены) {
    if (т.вид === 'имя') имена += 1;
    else if (т.вид === 'число') числа += 1;
    else if (т.вид === 'строка') {
      const коды = [...т.лексема].map((с) => с.codePointAt(0)!);
      if (строки === 0) {
        л1 = коды.length;
        суммаКодов = коды.reduce((а, б) => а + б, 0);
      }
      строки += 1;
      длина += коды.length;
    } else if (ВИДЫ_КЛЮЧЕВЫХ_СЛОВ.has(т.вид)) ключевые += 1;
    else if (т.вид !== 'новая_строка' && т.вид !== 'конец_файла') знаки += 1;
  }
  return { имена, числа, знаки, ключевые, строки, длина, суммаКодов, л1 };
}

/**
 * Разобрать канал программы: первое число — длина плоского списка, затем токены
 * `код вида, строка, кодпоинты…, 0`. Ноль — терминатор токена: кодовой точки `0` в исходнике нет
 * (текст программы не содержит NUL), поэтому формат однозначен и НЕ требует длины впереди — а это
 * экономит точке входа один живой счётчик на токен (бюджет `%b[0..7]`, замер: пик 9 при 8 клетках).
 * Битый канал — ИСКЛЮЧЕНИЕ, а не «пустой список»: иначе сравнение с эталоном прошло бы на пустоте.
 */
export function разобратьВывод(вывод: string): Токен[] {
  const числа = вывод
    .split('\n')
    .map((с) => с.trim())
    .filter((с) => с !== '')
    .map((с) => Number(с));
  if (числа.length === 0) throw new Error('канал пуст: программа ничего не напечатала');
  const всего = числа[0]!;
  if (всего !== числа.length - 1) throw new Error(`канал неполон: обещано ${String(всего)}, пришло ${String(числа.length - 1)}`);
  const токены: Токен[] = [];
  let и = 1;
  while (и < числа.length) {
    const код = числа[и++]!;
    const строка = числа[и++]!;
    const вид = ВИД_ПО_КОДУ[код];
    if (вид === undefined || вид === null) throw new Error(`неизвестный код вида ${String(код)} на позиции ${String(и - 2)}`);
    const коды: number[] = [];
    while (и < числа.length && числа[и] !== 0) коды.push(числа[и++]!);
    if (и >= числа.length) throw new Error(`лексема вида «${вид}» не закрыта терминатором 0`);
    и += 1;
    токены.push({ вид, лексема: String.fromCodePoint(...коды), строка });
  }
  return токены;
}

/** Сравнение побайтово: первое расхождение названо, а не сведено к «не равно». */
export function сравнить(факт: readonly Токен[], эта: readonly Токен[]): string[] {
  const расхождения: string[] = [];
  const дл = Math.max(факт.length, эта.length);
  for (let и = 0; и < дл; и++) {
    const ф = факт[и];
    const э = эта[и];
    if (ф === undefined) {
      расхождения.push(`#${String(и)}: в канале нет токена, эталон «${э!.вид}|${JSON.stringify(э!.лексема)}|${String(э!.строка)}»`);
      continue;
    }
    if (э === undefined) {
      расхождения.push(`#${String(и)}: лишний токен «${ф.вид}|${JSON.stringify(ф.лексема)}|${String(ф.строка)}»`);
      continue;
    }
    if (ф.вид !== э.вид || ф.лексема !== э.лексема || ф.строка !== э.строка) {
      расхождения.push(
        `#${String(и)}: факт «${ф.вид}|${JSON.stringify(ф.лексема)}|${String(ф.строка)}» ≠ эталон «${э.вид}|${JSON.stringify(э.лексема)}|${String(э.строка)}»`,
      );
    }
  }
  return расхождения;
}

