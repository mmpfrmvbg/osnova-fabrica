/**
 * B2b hardware-only (D12): пусть/присваивание/выражения/если/пока на реальной машине.
 *
 * Проверяется РАЗВИЛКА политики и сборка пятнадцати форм (по пять на подэтап):
 *   • без флага `allowDeepArrayWrites` запись из глубины ≥ 2 отказывает (`OSN-LOW-004`, `#180`);
 *   • с флагом формы собираются; AST на железе сверяет КИТ (`e2kHardwareKit` + `gate:hardware`).
 *
 * Эталон — независимый `эталоннаяЛента` (`parseV01` + `лентаИзAst`), а не вывод генератора.
 * QEMU здесь не арбитр: глубина ≥ 2 зацикливает модель (названная стена, см. §33 протокола).
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3';
import { программаПротоколаB2b } from '../compiler-v3/parser-protocol-b2b';
import { loweredProgram } from './lowered';

/** B2b1: `пусть`, присваивание, выражения без приоритета в задании, но с приоритетом эталона. */
const B2B1 = [
  'пусть а = 5',
  'а = 5',
  'пусть а = 1 + 2 * 3',
  'пусть а = (1 + 2) * 3',
  'пусть а = 8 / 2 - 1',
] as const;

/** B2b2: `если`/`пока`, простые сравнения, без `и`/`или`. */
const B2B2 = [
  'если а > 1\n    а = 2\n  конец если',
  'если а > 1\n    а = 2\n  иначе\n    а = 3\n  конец если',
  'если а > 1\n    а = 2\n  иначе если а < 0\n    а = 3\n  иначе\n    а = 4\n  конец если',
  'пока а < 3\n    а = а + 1\n  конец пока',
  'пока а < 3\n    если а == 1\n      а = 2\n    иначе\n      а = а + 1\n    конец если\n  конец пока',
] as const;

/** B2b3: несколько операторов, вложенность, вызов-оператор после `пусть`/в ветвях. */
const B2B3 = [
  'пусть а = 1 + 2\n  а = а * 3\n  если а > 5\n    а = 0\n  конец если',
  'пусть а = 2\n  пусть б = 3\n  если а < б\n    а = б - а\n  конец если\n  пока а < 10\n    а = а + 1\n  конец пока',
  'пусть а = 5\n  ф(а)',
  'если а > 1\n    ф(1)\n  иначе\n    ф(2)\n  конец если',
  'пока а < 3\n    ф(а)\n    а = а + 1\n  конец пока',
] as const;

/**
 * B2b4: L2, шаги 1–3/5–7 — `%`/`нацело`, `и`/`или`, унарные, тип в `пусть`, простые строки,
 * многострочность. Каждая форма проверена на E8C2 (AST=эталон, код 0), см. `.tmp/l2-report.md`.
 */
const B2B4 = [
  'пусть а = 7 % 4',
  'пусть а = 7 нацело 4',
  'пусть а = 2 + 8 % 3 * 2',
  'пусть а = 1 < 2 и 3 > 2',
  'пусть а = 1 < 2 или 3 > 2',
  'пусть а = 1 == 1 и 2 == 3 или 4 == 4',
  'пусть а = -1',
  'пусть а = не 1 < 2',
  'пусть а = - -1',
  'пусть а = -1 + 2 * -3',
  'пусть а = 2 - -3',
  'пусть а: Число = 5',
  'пусть а: Число = 1 + 2',
  'пусть а: Число = 7 % 4',
  'пусть а = "абв"',
  'пусть а = "привет"',
  'пусть а = "а" + "б"',
  'пусть а = 1 +\n    2',
  'пусть а = 1\n    + 2',
  'пусть а = (1 +\n    2) * 3',
] as const;

/** B2b5: вызов в выражении — шаг 4; аргументы — имена/числа, как у B2. */
const B2B5 = [
  'пусть а = ф(1)',
  'пусть а = ф(1) + 2',
  'вернуть ф(1)',
  'пусть а = 1 + ф(2) * 3',
  'если ф(1) > 0\n    а = 1\n  конец если',
] as const;

function опустить(тело: string, allowDeepArrayWrites: boolean) {
  const программа = программаПротоколаB2b(`действие главная()\n  ${тело}\nконец главная\n`, 'b2bh.osnova');
  const разобранный = parseV3(программа, 'b2bh.osnova');
  expect(разобранный.errors, 'B2b: разбор').toEqual([]);
  return loweredProgram(программа, {
    filename: 'b2bh.osnova',
    allowDeepArrayWrites,
    parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }),
  });
}

describe('B2b hardware-only: развилка D12', () => {
  it('без флага запись из глубины ≥ 2 — названный отказ #180', () => {
    const результат = опустить('пусть а = 5', false);
    expect(результат.ок).toBe(false);
    if (результат.ок) return;
    // НОМЕР отказа сдвинулся P1 (2026-11-13): `#180` → `#44`. Причина не в снятии границы, а в
    // ПОРЯДКЕ: отчёт называет ПЕРВЫЙ отказ, а шаги заголовков (`шаг_объявление`/`шаг_параметры`) стоят
    // в программе РАНЬШЕ `шаг_пусть` и пишут в память рантайма массивов из своей плоскости. Граница
    // та же, и проверяется она по СМЫСЛУ: отказ (а не тихая ложь), запись именно `Списки.установить`,
    // в тексте названа глубина. Смена номера названа здесь, а не подогнана молча.
    expect(результат.отказ.причина).toMatch(/#(44|180)\b/u);
    expect(результат.отказ.причина).toContain('Списки.установить');
    expect(результат.отказ.причина).toContain('глубина');
  });

  for (const [этап, программы] of [
    ['B2b1', B2B1],
    ['B2b2', B2B2],
    ['B2b3', B2B3],
    ['B2b4', B2B4],
    ['B2b5', B2B5],
  ] as const) {
    for (const тело of программы) {
      it(`${этап} собирается с флагом: ${тело}`, () => {
        const результат = опустить(тело, true);
        expect(результат.ок, результат.ок ? '' : результат.отказ.причина.slice(0, 500)).toBe(true);
        if (!результат.ок) return;
        expect(результат.значение.bytes.length).toBeGreaterThan(0);
      });
    }
  }

  // Замер МОДЕЛИ и ЦЕЛИ (§43: потолок 126 976 → 192 512). На E8C2 с
  // `dataSegmentBytes: 0x10000` тот же `.text` даёт RC=0 и 2908 байт эталона;
  // с 0x8000 — `si_addr` у конца сегмента данных. Кит: bin/b2b-all.elf.
  it('P4a (модель): все 15 форм — 0 отказов, код 192512; на E8C2 работает с данными 64 КиБ', () => {
    const тело = [...B2B1, ...B2B2, ...B2B3].join('\n  ');
    const программа = программаПротоколаB2b(`действие главная()\n  ${тело}\nконец главная\n`, 'b2ball.osnova');
    const разобранный = parseV3(программа, 'b2ball.osnova');
    expect(разобранный.errors, 'P4a: разбор').toEqual([]);
    const результат = loweredProgram(программа, {
      filename: 'b2ball.osnova',
      allowDeepArrayWrites: true,
      parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }),
    });
    expect(результат.ок, результат.ок ? '' : результат.отказ.причина.slice(0, 500)).toBe(true);
    if (!результат.ок) return;
    expect(результат.значение.bytes.length).toBe(192512);
  });
});
