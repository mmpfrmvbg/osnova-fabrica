/**
 * СТЕНА ГЛУБИНЫ 2 У ЗАПИСИ В МАССИВ — МИНИМАЛЬНОЕ РЕПРО (A4, срез 3; реестр долгов, случай 48).
 *
 * # Что здесь зафиксировано и зачем отдельным файлом
 *
 * В §3.135 граница «запись в массив из вызываемой глубины 2 зацикливает модель» была названа
 * **отказом по имени** (`OSN-LOW-004`) — то есть петли в оракуле не осталось. Но вместе с петлёй
 * исчезло и **репро**: отказ ставится ПО КАРТЕ ГЛУБИН (`src/e2k/programImage.ts#callDepths`, обход
 * графа вызовов в ширину), а карта считает **кратчайший** путь. Значит программу можно составить так,
 * что запись стоит на глубине 2 ПО ИСПОЛНЕНИЮ, а карта называет глубину 1 — тогда отказа нет, и
 * настоящая последовательность записи исполняется на цели.
 *
 * Это и есть минимальное репро: **недостижимая** ветвь `если длина с > 100` делает `у_2` достижимой
 * напрямую из точки входа (кратчайший путь длины 1), а исполняется реальная цепочка
 * `главная → у_1 → у_2`. Ветвь — не украшение: без неё тот же текст даёт ровно один отказ (проверка 1).
 *
 * # Что измерено (модель QEMU-e2k, 2026-10-29,
 * # источник — `.tmp/osnova-a4s3-low004-ОТЧЕТ.md`, пробы `.tmp/osnova-a4s3-matrix.ts`)
 *
 * | проба | отказов | что делает модель |
 * |---|---|---|
 * | запись на глубине 1 (`а`) | 0 | код **7** — путь записи ИСПРАВЕН сам по себе |
 * | запись на глубине 2 БЕЗ обхода (`б0`) | 1 | `OSN-LOW-004` (названный отказ, петли нет) |
 * | запись на глубине 2 С обходом (`к`) | 0 | **петля**: ни выхода, ни исключения за 5 000 мс |
 * | чтение на глубине 2 (`д`) | 0 | код **5** — из ТЕХ ЖЕ клеток чтение проходит |
 *
 * Чтение здесь — не второй опыт, а **различающий контроль**: оно исполняет тот же путь (тот же блок
 * `%b[12..14]`, то же окно, тот же вход в вызываемую из выращенного кадра) и доходит до выхода.
 * Без него «нет кода за 5 секунд» неотличимо от «машина медленная»: проверка петли — отрицание, а
 * отрицание без положительного соседа ничего не значит.
 *
 * # Что известно о классе (и что НЕ известно)
 *
 * Единственное, что зависит от глубины В БАЙТАХ, — вход в вызываемую: `call wbs = INNER_CALL_WBS`
 * (= 16, `src/e2k/procedureCall.ts`) вместо `wbs = 4` из точки входа, плюс порядок возврата
 * `returnAfterCall` (`src/e2k/programImage.ts:1538`). Исключено замером и кодом: кадр системного
 * вызова (в последовательности записи системного вызова нет вовсе), клетки блока (база `12` — одна и
 * та же в работающей и в петлящей пробах), разрешение имён (отказ ставится по имени ДО понижения, а
 * после обхода то же имя понижается в ту же последовательность), порча клеток точки входа возвратом
 * (после возврата из выращенного кадра точка входа пишет и читает верно).
 *
 * **Причина, по которой именно `std` зацикливает модель, а `ldd` из тех же клеток — нет, НЕ
 * УСТАНОВЛЕНА.** Критерий закрытия стены — в `docs/verification-debt.md` (случай 48): минимальное
 * репро обязано дать код 7 на модели И на железе, и тогда проверка 4 ниже переписывается на «код 7».
 *
 * # Чего этот файл НЕ делает
 *
 * Не чинит стену (его задача — держать репро в дереве) и не говорит о железе: QEMU — модель.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { HEAP_OFFSET, loweredProgram } from './programImage';
import { buildElfFromCode, MINIMAL_BASE } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
// Пробы написаны на v3-диалекте (`действие главная()`, `Список Число`) — тем же фронтендом, что
// оракулы §3.131–§3.136: компилятор о синтаксисе не знает, фронтенд подставляется опцией `parse`.
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');
const HEAP = MINIMAL_BASE + HEAP_OFFSET;
/** 5 000 мс: петля обязана НЕ уложиться в это время. Тот же предел у различающих проб отчёта. */
const TIMEOUT_MS = 5_000;

const shim = buildShim();

/**
 * Программа с записью в массив из вызываемой плоскости 2.
 *
 * `обход` — недостижимая ветвь, делающая `у_2` достижимой напрямую из точки входа (глубина по карте
 * становится 1, отказа нет, а исполняется цепочка глубины 2). Без обхода — обычная К2.
 */
function записьВПлоскости2(обход: boolean): string {
  return [
    'процедура у_2(а: Список Число) → Число',
    '  а[0] = 7',
    '  вернуть 3',
    'конец',
    '',
    'процедура у_1(а: Список Число) → Число',
    '  вернуть у_2(а)',
    'конец',
    '',
    'действие главная()',
    '  пусть с: Список Число = []',
    '  добавить в с элемент 5',
    ...(обход ? ['  если длина с > 100', '    пусть ж = у_2(с)', '  конец если'] : []),
    '  вернуть у_1(с)',
    'конец',
    '',
  ].join('\n');
}

/** Та же форма, но на глубине 1: запись в вызываемой, которую зовёт ТОЧКА ВХОДА. */
function записьВПлоскости1(): string {
  return [
    'процедура у_1(а: Список Число) → Число',
    '  а[0] = 7',
    '  вернуть а[0]',
    'конец',
    '',
    'действие главная()',
    '  пусть с: Список Число = []',
    '  добавить в с элемент 5',
    '  вернуть у_1(с)',
    'конец',
    '',
  ].join('\n');
}

/** Различающий контроль: на глубине 2 ИЗ ТЕХ ЖЕ КЛЕТОК читают, а не пишут. */
function чтениеВПлоскости2(): string {
  return [
    'процедура у_2(а: Список Число) → Число',
    '  вернуть а[0]',
    'конец',
    '',
    'процедура у_1(а: Список Число) → Число',
    '  вернуть у_2(а)',
    'конец',
    '',
    'действие главная()',
    '  пусть с: Список Число = []',
    '  добавить в с элемент 5',
    '  вернуть у_1(с)',
    'конец',
    '',
  ].join('\n');
}

/**
 * Собрать образ ПУТЁМ КОМПИЛЯТОРА и спросить модель. Тот же путь, что у оракула массивов
 * (`src/e2k/e2kArraysQemu.test.ts`): `loweredProgram` → `buildElfFromCode` → `runInQemu`.
 */
function образ(
  источник: string,
  файл: string,
): { readonly refused: readonly { readonly code: string; readonly reason: string }[]; readonly код: number | undefined } {
  const разбор = parseV3(источник, 'глубина2.osnova');
  expect(разбор.errors, 'разбор программы').toEqual([]);
  const { bytes, refused, arena } = loweredProgram(источник, {
    filename: 'глубина2.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (refused.length > 0) return { refused, код: undefined };
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(bytes, MINIMAL_BASE, { writable: true, extraMemory: arena.extraMemory }).bytes,
  );
  return { refused, код: runInQemu(путь, { shim: true, timeoutMs: TIMEOUT_MS })?.status };
}

describe('§3.137: запись в массив из вызываемой глубины 2 — минимальное репро петли', () => {
  it('1. без обхода карты глубин та же программа ОТВЕРГАЕТСЯ по имени (OSN-LOW-004)', () => {
    const { refused, код } = образ(записьВПлоскости2(false), 'a4s3-k2-refusal.elf');
    // Отказ — тот же, что в оракуле массивов (К2): здесь он нужен как ВЕРХНЯЯ половина различения —
    // «отказ» и «петля» обязаны быть разными исходами ОДНОГО текста.
    expect(refused.map((r) => r.code), 'отказ записи из плоскости 2').toContain('OSN-LOW-004');
    expect(код, 'до понижения образа нет — прогонять нечего').toBeUndefined();
  });

  it('2. запись на глубине 1 = 7: сам путь записи исправен', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(записьВПлоскости1(), 'a4s3-write1.elf');
    expect(refused, `непонижённые носители: ${refused.map((r) => r.reason).join('; ')}`).toEqual([]);
    expect(код, 'запись в плоскости 1').toBe(7);
  });

  it('3. чтение на глубине 2 = 5: из тех же клеток, тем же входом — доходит до выхода', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(чтениеВПлоскости2(), 'a4s3-read2.elf');
    expect(refused, `непонижённые носители: ${refused.map((r) => r.reason).join('; ')}`).toEqual([]);
    // РАЗЛИЧАЮЩИЙ КОНТРОЛЬ к проверке 4: без него «нет кода» читалось бы как «машина медленная».
    expect(код, 'чтение в плоскости 2').toBe(5);
  });

  it('4. запись на глубине 2 = ПЕТЛЯ модели: ни выхода, ни исключения за 5 000 мс', () => {
    if (shim === undefined) return;
    const { refused, код } = образ(записьВПлоскости2(true), 'a4s3-write2-loop.elf');
    expect(refused, `непонижённые носители: ${refused.map((r) => r.reason).join('; ')}`).toEqual([]);
    // СТЕНА, ЗАФИКСИРОВАННАЯ ИСПОЛНЕНИЕМ, А НЕ РАССУЖДЕНИЕМ. Причина не установлена (см. шапку);
    // критерий закрытия — `docs/verification-debt.md`, случай 48: когда стену снимут, здесь обязан
    // стоять код 7, и правка оракула — часть снятия.
    expect(код, 'запись из плоскости 2: ожидается петля (нет кода за 5 000 мс)').toBeUndefined();
  });
});
