/**
 * ОРАКУЛ КОЛЛЕКЦИЙ НА `brk` — ШАГ ①: ВЫДЕЛЕНИЕ ДОХОДИТ ДО ЦЕЛИ.
 *
 * # Что спрашивается — и почему ИМЕННО ЭТО
 *
 * Первая операция коллекций отвечает на один вопрос, от которого зависят все остальные: **встают ли
 * два выделения подряд врозь, ровно на `8 + ёмкость·8`**. Если шаг меньше — блоки наложатся, и
 * `положить` одного затрёт элемент другого; если больше — между блоками дыра, и «ёмкость в заголовке»
 * перестанет быть правдой о памяти. Поэтому здесь проверяется **разность адресов**, а не «адрес
 * ненулевой»: ненулевой адрес ничего не доказывает.
 *
 * # Почему разность наблюдаема в 8-битном канале
 *
 * Код возврата процесса несёт младший байт (`AGENTS.md`), а разность — маленькое число (40), а не
 * адрес: она влезает в канал целиком. Это и есть приём «усилителя» из правила линии: адрес широк,
 * но спросить надо не адрес, а **расстояние между двумя адресами**.
 *
 * # Эталон и ответ — две стороны, и обе обязательны
 *
 * Регистровая VM (`RegVM`) — эталон языка; модель e2k — ответ. Числа обязаны совпасть. Плюс сверка
 * арифметики адресов: у обеих сторон одно правило `8 + ёмкость·8`, и оно записано ОДИН раз
 * (`src/e2k/collectionsRuntime.ts`, `src/runtime/vm/interpreter.ts`), а не двумя похожими формулами.
 *
 * # Чего этот оракул НЕ доказывает
 *
 * Ничего о `положить`, `взять` и `расширить`: их в рантайме ещё нет, и отказ на них — названный
 * (`src/e2k/collectionsRuntime.ts`). Сквозной прогон 100 записей ждёт их (оракул владельца,
 * `src/e2k/collectionsQemu.test.ts`).
 */
import { describe, expect, it } from 'vitest';
import { regModuleOf } from '../vliw/regOracle';
import { RegVM } from '../runtime/vm/reginterpreter';
import { createDefaultInvokeHandler } from '../runtime/vm/interpreter';
import { resolveEntryIndex } from '../oracle/parity';
import { runOnE2k } from '../scripts/e2kProgramRun';
import { buildShim } from '../scripts/e2kQemuExec';
import { COLLECTION_INVOKES } from '../runtime/vm/collectionCalls';

const shim = buildShim();

const модуль = (тело: string): string => `модуль Кол\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/** Значение на РЕГИСТРОВОЙ VM — эталон языка. */
async function наVM(source: string): Promise<number> {
  const built = regModuleOf(source);
  expect(built, 'программа обязана компилироваться').not.toBeNull();
  const entry = resolveEntryIndex(built!.module.procedures, undefined) ?? 0;
  const vm = new RegVM(built!.module, {
    invoke: createDefaultInvokeHandler(),
    // Арность объявлена ЯВНО: канон языка (`SYSCALLS_V01`) этих операций ещё не несёт, поэтому
    // `extraInvokes` — законный путь для хост-вызовов вне реестра. Источник арности ОДИН и тот же,
    // что у цели и у оракула владельца (`src/runtime/vm/collectionCalls.ts`).
    extraInvokes: COLLECTION_INVOKES,
    maxSteps: 2_000_000,
  });
  return Number(await vm.runProcedure(entry, []));
}

/** Ответ МОДЕЛИ: код возврата и отказы понижения — два разных канала, а не один. */
function наМодели(source: string, файл: string): { status: number | undefined; refused: readonly string[] } {
  const прогон = runOnE2k(source, файл);
  return { status: прогон.status, refused: прогон.refused.map((item) => `${item.code} ${item.reason}`) };
}

/**
 * ПРАВИЛО ШАГА БЛОКА — одно на программу, эталон и ожидание.
 *
 * Выведено из констант рантайма, а не записано числом 40 «потому что посчитали»: разойдись правило и
 * ожидание — это находка, а не совпадение.
 */
const ШАГ = 8;
function шагБлока(ёмкость: number): number {
  return ШАГ + ёмкость * ШАГ;
}

describe('коллекции на brk, шаг ①: выделение доходит до цели', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('ДВА ВЫДЕЛЕНИЯ ПО 4 СТОЯТ РОВНО НА 8 + 4·8 = 40 — и на эталоне, и на модели', async () => {
    const source = модуль(
      [
        '  пусть первая = система.коллекция.выделить(4)',
        '  пусть вторая = система.коллекция.выделить(4)',
        '  вернуть вторая - первая',
      ].join('\n'),
    );
    const ожидание = шагБлока(4);
    expect(ожидание, 'правило шага: заголовок плюс четыре элемента').toBe(40);
    expect(await наVM(source), 'эталон языка: то же правило адресов, что у цели').toBe(ожидание);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-step1-two-allocs.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, `модель: шаг блока ${String(ожидание)}`).toBe(ожидание);
  });

  it('шаг ЗАВИСИТ от ёмкости: 2 и 8 дают разные расстояния, и оба — по правилу', async () => {
    // Одно наблюдение не различает свойство и способ измерения: «40» могло бы получиться и от
    // жёсткой константы. Второе наблюдение с другой ёмкостью различает.
    for (const ёмкость of [2, 8]) {
      const source = модуль(
        [
          `  пусть первая = система.коллекция.выделить(${String(ёмкость)})`,
          `  пусть вторая = система.коллекция.выделить(${String(ёмкость)})`,
          '  вернуть вторая - первая',
        ].join('\n'),
      );
      const ожидание = шагБлока(ёмкость);
      expect(await наVM(source), `эталон: шаг для ёмкости ${String(ёмкость)}`).toBe(ожидание);
      if (shim === undefined) continue;
      const { status, refused } = наМодели(source, `collections-step1-cap-${String(ёмкость)}.elf`);
      expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
      expect(status, `модель: шаг для ёмкости ${String(ёмкость)}`).toBe(ожидание);
    }
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 1: оракул ОБЯЗАН различать 40 и 32 в 8-битном канале', () => {
    // Контроль на сам оракул. Разность без слова заголовка — 32; это ровно тот дефект, который
    // вносит запись 14.3 стола негативных контролей. Если 40 и 32 когда-нибудь сравняются по модулю
    // 256, проверка перестанет что-либо доказывать, и её надо переделать (другая ёмкость).
    expect(шагБлока(4), 'с заголовком').toBe(40);
    expect(4 * ШАГ, 'без слова заголовка — ДЕФЕКТ').toBe(32);
    expect(шагБлока(4) % 256, 'канал обязан различать эти два числа').not.toBe((4 * ШАГ) % 256);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ 2: выделение НУЛЕВОЙ ёмкости — только заголовок, шаг 8', async () => {
    // Крайняя точка правила: ёмкость 0 обязана дать шаг ровно в слово заголовка. Это отличает
    // «шаг считается по правилу» от «шаг всегда сорок»: без этой точки обе прежние проверки
    // прошли бы и у реализации с жёсткой константой.
    const source = модуль(
      [
        '  пусть первая = система.коллекция.выделить(0)',
        '  пусть вторая = система.коллекция.выделить(0)',
        '  вернуть вторая - первая',
      ].join('\n'),
    );
    expect(await наVM(source), 'эталон: шаг нулевой ёмкости').toBe(8);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'collections-step1-cap-0.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, 'модель: шаг нулевой ёмкости').toBe(8);
  });
});
