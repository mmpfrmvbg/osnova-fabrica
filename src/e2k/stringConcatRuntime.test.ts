    const текст = названные(записи).join(' | ');
    expect(записи.length, 'недоказанное значение нельзя ни подставить, ни сложить адресами').toBeGreaterThan(0);
    expect(текст, 'отказ обязан назвать ОПЕРАЦИЮ').toContain('система.строка.объединить');
