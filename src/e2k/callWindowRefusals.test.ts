/**
 * ОРАКУЛ: РАЗЛОЖЕНИЕ 43 ОТКАЗОВ «ОКНО ВЫЗЫВАЕМОЙ» ПО ВИДАМ (A4, срез 4).
 *
 * # Зачем
 *
 * Владелец назвал стену числом: **43 отказа «окно вызываемой»** у лексера. Число — не разложение:
 * решение «начинать ли строки» требует знать, ЧТО это за отказы. Здесь они разложены по КОНСТРУКЦИЯМ
 * (код отказа + носитель/операция, взятые ИЗ ДАННЫХ, а не из текста сообщения: группировка по тексту
 * запрещена указанием владельца), и у каждого вида — МИНИМАЛЬНОЕ РЕПРО и обе стороны границы.
 *
 * # Что проверяется
 *
 *   • П1..П5 — пять видов по частоте в лексере, у каждого: минимальное репро, код отказа,
 *     КОНСТРУКЦИЯ (не текст), вердикт «начинать ли строки» — и контроль РАБОТАЮЩЕЙ стороны границы
 *     (то же на глубине 0 проходит), иначе «отказывает» не отличить от «сломано всё»;
 *   • П6 — тело лексера целиком: 141 отказ, из них **43** — `система.строка.объединить`, и эти 43
 *     распадаются на ДВА подвида (17 «строковая операция в вызываемой» + 26 «склейка сверх
 *     статического буфера в вызываемой») — смешанный вид, разбит по указанию владельца;
 *   • П7 — работающая сторона границ на МОДЕЛИ: 3 / 1 / 11 / 21 (числа сверены с железом
 *     2026-10-29: k1 → 3, k3 → 1, k5 → 11, k1b → 21; замер `.tmp/osnova-a4s4-iron.ts`).
 *
 * # Чего здесь НЕТ и почему
 *
 * Отказ понижения прогонять нечего (образа нет) — поэтому «железо» для самих отказов не проверяется
 * в принципе, и это не пробел, а свойство отказа. Проверяется ОБРАТНАЯ сторона: то, что проходит,
 * обязано проходить и на модели, и на цели (П7; на цели сверено тем же файлом, что писался в `.tmp`).
 *
 * # Находка, лежащая ВНЕ этих 43 (2026-10-29, железо)
 *
 * При прогоне границ на железе оказалось: **образы СО СТАТИКОЙ (то есть любая программа со строковым
 * литералом) падают на цели** (код 139), а модель исполняет их верно — в том числе записи корпуса 02 и
 * 04, объявленные «работает». Причина найдена различающей пробой и подтверждена железом: сегмент кода
 * `filesz = memsz = 65625` кончается на `0x110059`, а сегмент данных начинается на `0x110000` —
 * ПЕРЕКРЫТИЕ 89 байт, и это ровно метаданные ELF (`symtab` 48 + `strtab` 10 + `shstrtab` 31).
 * Зажатие сегмента кода ровно по коду (`fix_p4` → **2**, `fix_p1` → **0** при выводе «привет») снимает
 * падение; модель при этом не меняется. Это долг ОБРАЗА, отдельный от строк и от 43 (запись в
 * `docs/verification-debt.md`).
 */
import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { loweredProgram } from './programImage';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'проба.osnova';
const shim = buildShim();

interface Отказ {
  readonly code: string;
  readonly reason: string;
}

/** КОНСТРУКЦИЯ отказа: носитель (`IR.*`) или операция (`система.*`) — из данных, не из текста. */
function конструкция(отказ: Отказ): string {
  const найдено = /^(?:#[0-9]+\s+)?(IR\.[A-Za-z_]+|система\.[а-яё.]+)/.exec(отказ.reason);
  return найдено?.[1] ?? '—';
}

/** Понизить программу; `assumeArenaReserved` — замерная ручка §3.134 (арена не закреплена). */
function понизить(источник: string, assumeArenaReserved = false): readonly Отказ[] {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  return loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    assumeArenaReserved,
  }).refused;
}

/** Понизить и (если отказов нет) исполнить в модели. */
function исполнить(источник: string, файл: string): { refused: readonly Отказ[]; код: number | undefined; вывод: string } {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  const { bytes, refused } = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (refused.length > 0) return { refused, код: undefined, вывод: '' };
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const прогон = runInQemu(путь, { shim: true, timeoutMs: 20_000 });
  return { refused, код: прогон?.status, вывод: прогон?.output ?? '' };
}

/** Тело лексера без процедуры чтения файла — ровно то, что мерит §3.134. */
function телоЛексера(): string {
  const текст = fs.readFileSync(path.join(ROOT, 'src', 'self-host', 'lexer.osnova'), 'utf-8');
  return текст.slice(0, текст.indexOf('// ЛЕКСИРОВАТЬ ФАЙЛ'));
}

