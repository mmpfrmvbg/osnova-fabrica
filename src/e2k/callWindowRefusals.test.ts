describe('A4 §3.138: 43 отказа «окно вызываемой» — виды, репро, границы', () => {
  it('П1 вид K1a: склейка в вызываемой — отказ по конструкции, контроль на глубине 0 проходит', () => {
    const отказы = понизить(K1A);
    expect(отказы.length, `отказы: ${отказы.map((о) => о.reason).join('; ')}`).toBe(1);
    expect(отказы[0]!.code, 'код отказа строкового рантайма').toBe('OSN-LOW-003');
    expect(конструкция(отказы[0]!), 'КОНСТРУКЦИЯ (а не текст сообщения)').toBe('система.строка.объединить');
    // Работающая сторона границы: то же в ДЕЙСТВИИ (плоскость точки входа) — склейки нет в отказе.
    const контроль = понизить([
      'действие главная()',
      '  пусть а = "а"',
      '  пусть б = "б"',
      '  пусть в = а + б',
      '  вернуть длина в',
      'конец',
      '',
    ].join('\n'));
    expect(контроль, `контроль обязан проходить: ${контроль.map((о) => о.reason).join('; ')}`).toEqual([]);
  });

  it('П2 подвид K1b: склейка СВЕРХ статического буфера в вызываемой — та же конструкция, другая причина', () => {
    const отказы = понизить(K1B);
    expect(отказы.length, `отказы: ${отказы.map((о) => о.reason).join('; ')}`).toBe(1);
    expect(отказы[0]!.code).toBe('OSN-LOW-003');
    expect(конструкция(отказы[0]!)).toBe('система.строка.объединить');
    // Подвид отличается УСЛОВИЕМ (сверх буфера → блок арены → системный вызов), а не формулировкой:
    // минимальное репро подвида обязано называть именно буфер.
    expect(отказы[0]!.reason, 'причина подвида K1b').toContain('сверх статического буфера');
    // Контроль: та же склейка в ДЕЙСТВИИ — буфер мал, но арена доступна.
    expect(понизить(K1_КОНТРОЛЬ), 'склейка сверх буфера в действии').toEqual([]);
  });

  it('П3 вид K2: вытеснение в вызываемой — репро смешанное (печать поднимает вытеснение)', () => {
    const отказы = понизить(K2);
    const коды = new Set(отказы.map((о) => `${о.code} ${конструкция(о)}`));
    expect([...коды].some((к) => к.includes('IR.spill_st')), `вытеснение обязано быть названо: ${[...коды].join(' | ')}`).toBe(true);
    expect([...коды].some((к) => к.includes('IR.spill_ld')), 'чтение вытесненного обязано быть названо').toBe(true);
    // Причина вытеснения — системный вызов, которого у вызываемой нет (§3.51). Чистого репро нет:
    // вытеснение поднимает именно печать, и это записано, а не спрятано (в репро видно и вторую
    // зафиксированную границу — `IR.print_write` из выращенного кадра, §3.62).
    expect(
      отказы.map((о) => о.reason).join(' '),
      'причина обязана называть рантайм и системный вызов',
    ).toContain('без системного вызова');
  });

  it('П4 вид K3: символ по значению, известному только в рантайме', () => {
    const отказы = понизить(K3);
    expect(отказы.length, `отказы: ${отказы.map((о) => о.reason).join('; ')}`).toBeGreaterThan(0);
    expect(
      отказы.some((о) => конструкция(о) === 'система.строка.символ'),
      `конструкция обязана быть названа: ${отказы.map((о) => `${о.code} ${конструкция(о)}`).join(' | ')}`,
    ).toBe(true);
    // Контроль: символ ЛИТЕРАЛА (значение статично) — таблица кодов есть, отказа нет.
    expect(понизить(K3_КОНТРОЛЬ), 'символ литерала').toEqual([]);
  });

  it('П5 вид K4: `подстрока` — понижения нет на ЛЮБОЙ глубине (это не «окно вызываемой»)', () => {
    const отказы = понизить(K4);
    expect(отказы.length, 'отказ обязан быть').toBeGreaterThan(0);
    // Отказ приходит и в плоскости точки входа — значит глубина тут ни при чём, и вид обязан быть
    // отличён от K1/K2, иначе «окно вызываемой» объясняло бы то, что им не является.
    expect(
      отказы.map((о) => о.reason).join(' '),
      'рантайм обязан назвать, чего он не умеет',
    ).toContain('нет такой операции');
  });

  it('П6 вид K5: предикат конъюнкции, читаемый возвратом (кодоген, не рантайм)', () => {
    const отказы = понизить(K5);
    const коды = отказы.map((о) => о.code);
    expect(коды.length, 'отказ обязан быть').toBeGreaterThan(0);
    expect(new Set(коды), 'предикат — это РАСКЛАДКА (004), а не рантайм (003)').toEqual(new Set(['OSN-LOW-004']));
    expect(
      отказы.some((о) => конструкция(о) === 'IR.le' || конструкция(о) === 'IR.jmp_if_not'),
      `конструкция обязана быть названа: ${отказы.map((о) => конструкция(о)).join(' | ')}`,
    ).toBe(true);
    // Контроль: ОДНО сравнение в условии — предикат составляется (и это число 11 на модели, см. П7).
    expect(понизить(K5_КОНТРОЛЬ), 'одно сравнение').toEqual([]);
  });

  it('П7 тело лексера: 141 отказ, из них 43 — `система.строка.объединить` (17 + 26 подвида)', () => {
    const отказы = понизить(телоЛексера(), true);
    expect(отказы.length, 'отказов тела лексера').toBe(141);
    const объединить = отказы.filter((о) => конструкция(о) === 'система.строка.объединить');
    expect(объединить.length, 'стена «окно вызываемой», названная владельцем числом 43').toBe(43);
    // СМЕШАННЫЙ вид разбит на подвиды по УСЛОВИЮ, и у каждого есть своё минимальное репро (П1, П2).
    const сверхБуфера = объединить.filter((о) => о.reason.includes('сверх статического буфера'));
    expect(сверхБуфера.length, 'подвид K1b (арена → системный вызов)').toBe(26);
    expect(объединить.length - сверхБуфера.length, 'подвид K1a (носитель строкового рантайма)').toBe(17);
    // Все 43 — отказа РАНТАЙМА, а не раскладки: это не та же категория, что вытеснение и предикаты.
    expect(new Set(объединить.map((о) => о.code))).toEqual(new Set(['OSN-LOW-003']));
    // Остальные конструкции — названы, чтобы «43» не читалось как «всё»: вытеснение 39, строковые
    // значения 40, подстрока 7, предикат 11, содержит 1.
    const поКонструкциям = new Map<string, number>();
    for (const о of отказы) {
      const ключ = `${о.code} ${конструкция(о)}`;
      поКонструкциям.set(ключ, (поКонструкциям.get(ключ) ?? 0) + 1);
    }
    expect(поКонструкциям.get('OSN-LOW-004 IR.spill_ld'), 'вытеснение, чтение').toBe(27);
    expect(поКонструкциям.get('OSN-LOW-004 IR.spill_st'), 'вытеснение, запись').toBe(12);
    expect(поКонструкциям.get('OSN-LOW-003 система.строка.символ'), 'символ по рантайм-значению').toBe(19);
    expect(поКонструкциям.get('OSN-LOW-004 IR.jmp_if_not'), 'предикат перехода').toBe(7);
  });

  it('П8 работающая сторона границ: 3 / 1 / 11 / 21 (модель = железо, замер 2026-10-29)', () => {
    if (shim === undefined) return;
    const k1 = исполнить(
      ['действие главная()', '  пусть а = "аб"', '  пусть б = а + "!"', '  вернуть длина б', 'конец', ''].join('\n'),
      'a4s4-k1.elf',
    );
    expect(k1.refused, `непонижённые носители: ${k1.refused.map((о) => о.reason).join('; ')}`).toEqual([]);
    expect(k1.код, 'склейка в действии: "аб"+"!" = 3').toBe(3);

    const k3 = исполнить(
      ['действие главная()', '  пусть с = "ба"', '  если с[1] == 1072', '    вернуть 1', '  конец если', '  вернуть 0', 'конец', ''].join('\n'),
      'a4s4-k3.elf',
    );
    expect(k3.refused, `непонижённые носители: ${k3.refused.map((о) => о.reason).join('; ')}`).toEqual([]);
    expect(k3.код, 'код символа "а" в "ба"').toBe(1);

    const k5 = исполнить(K5_КОНТРОЛЬ, 'a4s4-k5.elf');
    expect(k5.refused, `непонижённые носители: ${k5.refused.map((о) => о.reason).join('; ')}`).toEqual([]);
    expect(k5.код, 'одно сравнение в условии').toBe(11);

    const k1b = исполнить(K1_КОНТРОЛЬ, 'a4s4-k1b.elf');
    expect(k1b.refused, `непонижённые носители: ${k1b.refused.map((о) => о.reason).join('; ')}`).toEqual([]);
    expect(k1b.код, 'склейка сверх буфера в действии (арена): 21 знак').toBe(21);
  });
});
