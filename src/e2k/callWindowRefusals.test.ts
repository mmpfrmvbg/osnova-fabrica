interface Отказ {
  readonly code: string;
  readonly reason: string;
}

/** КОНСТРУКЦИЯ отказа: носитель (`IR.*`) или операция (`система.*`) — из данных, не из текста. */
function конструкция(отказ: Отказ): string {
  const найдено = /^(?:#[0-9]+\s+)?(IR\.[A-Za-z_]+|система\.[а-яё.]+)/.exec(отказ.reason);
  return найдено?.[1] ?? '—';
}

/** Понизить программу; `assumeArenaReserved` — замерная ручка §3.134 (арена не закреплена). */
function понизить(источник: string, assumeArenaReserved = false): readonly Отказ[] {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
  return loweredProgramUnchecked(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    assumeArenaReserved,
  }).refused;
}

/** Понизить и (если отказов нет) исполнить в модели. */
function исполнить(источник: string, файл: string): { refused: readonly Отказ[]; код: number | undefined; вывод: string } {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
  const { bytes, refused } = loweredProgramUnchecked(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (refused.length > 0) return { refused, код: undefined, вывод: '' };
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const прогон = runInQemu(путь, { shim: true, timeoutMs: 20_000 });
  return { refused, код: прогон?.status, вывод: прогон?.output ?? '' };
}

/** Тело лексера без процедуры чтения файла — ровно то, что мерит §3.134. */
function телоЛексера(): string {
  const текст = fs.readFileSync(path.join(ROOT, 'src', 'self-host', 'lexer.osnova'), 'utf-8');
  return текст.slice(0, текст.indexOf('// ЛЕКСИРОВАТЬ ФАЙЛ'));
}

