type Измерение = {
  readonly проба: Проба;
  readonly отказы: readonly { readonly code: string; readonly reason: string }[];
  readonly sha: string;
  readonly код: number | undefined;
};

const кэш = new Map<string, Измерение>();

/** Один замер на пробу: понижение (отказы + образ) и код на модели. Кэш держит порядок проверок свободным. */
function измерить(проба: Проба): Измерение {
  const готово = кэш.get(проба.имя);
  if (готово !== undefined) return готово;
  const источник = программа(проба.тело);
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор ${проба.имя}: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
  const собран = loweredProgramUnchecked(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  const sha = crypto.createHash('sha256').update(собран.bytes).digest('hex');
  let код: number | undefined;
  if (собран.refused.length === 0 && shim !== undefined) {
    const elf = buildElfFromCode(собран.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
    const файл = path.join(ROOT, '.tmp', `conjunction-value-${проба.имя}.elf`);
    fs.writeFileSync(файл, elf.bytes);
    код = runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status ?? undefined;
  }
  const измерение: Измерение = {
    проба,
    отказы: собран.refused.map((отказ) => ({ code: отказ.code, reason: отказ.reason })),
    sha,
    код,
  };
  кэш.set(проба.имя, измерение);
  return измерение;
}

/** Итог формы по замеру: «зелёная» (значение верно), «честный отказ», «ТИХАЯ ЛОЖЬ», «нет модели». */
function итог(измерение: Измерение): string {
  if (измерение.отказы.length > 0) return 'честный отказ';
  if (измерение.код === undefined) return 'нет модели';
  return измерение.код === измерение.проба.эталон ? 'зелёная' : 'ТИХАЯ ЛОЖЬ';
}

/** Одна проба одной формы: отказ обязан быть назван, состоявшееся понижение — верно ЧИСЛОМ и sha. */
function проверитьПробу(форма: string, проба: Проба): string {
  const измерение = измерить(проба);
  const вердикт = итог(измерение);
  if (вердикт === 'честный отказ') {
    for (const отказ of измерение.отказы) {
      expect(isLoweringRefusalCode(отказ.code), `${форма} / ${проба.имя}: отказ без кода понижения (${отказ.code})`).toBe(true);
      expect(отказ.reason.length, `${форма} / ${проба.имя}: причина отказа пуста`).toBeGreaterThan(20);
    }
    expect(измерение.отказы[0]!.reason, `${форма} / ${проба.имя}: отказ не называет механизм`).toMatch(МЕХАНИЗМ);
    return `честный отказ: ${измерение.отказы[0]!.code} — ${измерение.отказы[0]!.reason.slice(0, 64)}…`;
  }
  if (вердикт === 'нет модели') return 'нет модели (шим недоступен) — значение не спрошено';
  expect(
    измерение.код,
    `${форма} / ${проба.имя}: модель ${String(измерение.код)}, эталон ${String(проба.эталон)} (${проба.рука}) — ТИХАЯ ЛОЖЬ`,
  ).toBe(проба.эталон);
  const закреплено = ЗАКРЕПЛЁННЫЕ.get(проба.имя);
  expect(
    закреплено,
    `${форма} / ${проба.имя}: понижение перестало отказывать — форма ЗАРАБОТАЛА, перенесите замер sha256 = ${измерение.sha}`,
  ).toBeDefined();
  expect(
    измерение.sha,
    `${форма} / ${проба.имя}: sha256 образа сдвинулся — перенесите замер (было ${String(закреплено)}, стало ${измерение.sha})`,
  ).toBe(закреплено);
  return `зелёная: код ${String(измерение.код)}, sha256 ${измерение.sha.slice(0, 16)}…`;
}

