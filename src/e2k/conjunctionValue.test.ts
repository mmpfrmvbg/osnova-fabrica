/**
 * ВТОРАЯ ТИХАЯ ЛОЖЬ (срез A4-5б): НАКОПИТЕЛЬ КОНЪЮНКЦИИ НА РЕБРЕ ВЗЯТОГО ПЕРЕХОДА.
 *
 * # Что здесь стережётся
 *
 * Короткое замыкание `A и B` понижается переходом **вперёд**: `A` → `jmp_if_not` → `B`, а значение
 * конъюнкции читается на **цели** перехода — то есть на ребре, где второй терм ПРОПУЩЕН. Значит, на
 * цели обязан лежать результат ПЕРВОГО терма. Это верно ровно тогда, когда оба терма пишут ОДИН
 * регистр (тогда накопитель и есть результат пары) — и ложно, когда планировщик разводит термы по
 * разным регистрам: на цель приходит регистр, который пишет только пропущенный второй терм, и там
 * остаётся ЧУЖОЕ число. Отказов при этом ноль — то есть тихая ложь, худший класс по `AGENTS.md`.
 *
 * # Замер (срез 5б, задача 1; 12 проб + диагноз)
 *
 * | форма | что делает модель |
 * |---|---|
 * | одно сравнение-значение (ложное и истинное) | верно |
 * | ОДНА конъюнкция с ЛИТЕРАЛЬНЫМИ границами (`код >= 48 и код <= 57`) | верно, в том числе при ложном первом терме |
 * | `или`, `не` | верно |
 * | границы-ПЕРЕМЕННЫЕ (`код >= н и код <= м`) при ЛОЖНОМ первом терме | **10 вместо 0** (`.tmp/a5b-k7b.ts`) |
 * | ДВЕ конъюнкции | **58 вместо 10** (`1·10 + 48`), на железе те же 58 |
 *
 * Проба «границы-переменные» в первой редакции таблицы стояла как «верно» и **не различала**: она
 * мерилась только при истинном первом терме. Урок 5а повторён буквально — «проходит» без
 * различающей пробы значит «проходит ровно тот случай, который проверяли».
 *
 * # Границы сторожа (названы, а не умолчаны)
 *
 * Сторож ловит РАЗДЕЛЕНИЕ накопителя и НЕ ловит случай, когда цель читает регистр, записанный в
 * пропущенном промежутке НЕ сравнением (обычным переносом): такой регистр в потоке планирования
 * пишется и до перехода, и отличить «нужное значение» от «чужого» без раскладки нечем. Это долг
 * среза 5в — `docs/hardware-debt.md` §3.142.
 */
import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './programImage';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import type { AsmInstruction, Operand } from './backend';
import { pairPredicates } from './predicatePairing';

const ФАЙЛ = 'проба.osnova';
const ROOT = path.resolve(__dirname, '..', '..');
const shim = buildShim();

const reg = (index: number): Operand => ({ kind: 'reg', index });
const imm = (value: number): Operand => ({ kind: 'imm', value });
const ir = (mnemonic: string, operands: readonly Operand[]): AsmInstruction => ({ mnemonic, channel: 0, operands });

/** Исходник пробы: тело действия + `конец`. */
const программа = (тело: readonly string[]): string => ['действие главная()', ...тело, 'конец', ''].join('\n');

/** Причины отказов понижения — как их увидит конвейер (без модели). */
function причины(тело: readonly string[]): readonly string[] {
  const src = программа(тело);
  const разбор = parseV3(src, ФАЙЛ);
  expect(разбор.errors, `разбор пробы: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  const собран = loweredProgram(src, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  return собран.refused.map((отказ) => отказ.reason);
}

const ДВЕ_КОНЪЮНКЦИИ = [
  '  пусть код = 50',
  '  пусть другой = 10',
  '  пусть пер = код >= 48 и код <= 57',
  '  пусть вт = другой >= 48 и другой <= 57',
  '  вернуть пер * 10 + вт',
];

const ГРАНИЦЫ_ПЕРЕМЕННЫЕ_ЛОЖЬ = [
  '  пусть код = 10',
  '  пусть н = 48',
  '  пусть м = 57',
  '  пусть пер = код >= н и код <= м',
  '  вернуть пер',
];

describe('вторая тихая ложь: накопитель конъюнкции на ребре взятого перехода', () => {
  it('две конъюнкции: отказ на КАЖДОЙ паре, причина называет ребро и цель', () => {
    const отказы = причины(ДВЕ_КОНЪЮНКЦИИ);
    expect(отказы.length, 'сторож не сработал — программа снова собирается лживой').toBe(2);
    for (const отказ of отказы) {
      expect(отказ, 'причина не называет механизм').toContain('РЕБРЕ ВЗЯТОГО перехода');
      expect(отказ, 'причина не называет накопитель').toContain('накопитель');
    }
  });

  it('границы-ПЕРЕМЕННЫЕ при ложном первом терме: отказ (замерено 10 вместо 0)', () => {
    const отказы = причины(ГРАНИЦЫ_ПЕРЕМЕННЫЕ_ЛОЖЬ);
    expect(отказы.length, 'сторож не сработал — переменные границы снова лгут').toBe(1);
    expect(отказы[0]!).toContain('РЕБРЕ ВЗЯТОГО перехода');
  });

  it('различающий контроль: тот же поток с ОДНИМ накопителем не отвергается', () => {
    // Два потока отличаются РОВНО номером регистра второго терма. Сторож обязан отвергнуть
    // разделение и промолчать там, где накопитель — результат самой пары. Иначе он «ловит всё».
    const поток = (регистрВторого: number): readonly AsmInstruction[] => [
      ir('IR.ge', [reg(2), reg(5), reg(6)]),
      ir('IR.jmp_if_not', [reg(2), imm(3)]),
      ir('IR.le', [reg(регистрВторого), reg(5), reg(6)]),
      ir('IR.ret', [imm(1), reg(регистрВторого)]),
    ];
    const общий = pairPredicates(поток(2));
    expect(общий.refusals.map((отказ) => отказ.reason), 'звучащий поток отвергнут').toEqual([]);
    expect(общий.pairs.length, 'пара не составилась — контроль не о том').toBe(1);

    const разделённый = pairPredicates(поток(3));
    expect(разделённый.refusals.length, 'разделённый накопитель НЕ отвергнут').toBe(1);
    expect(разделённый.refusals[0]!.reason).toContain('ПРОПУЩЕННЫЙ второй терм');
  });

  it('звучащие формы не задеты: одно сравнение, одна конъюнкция, `или`, `не`', () => {
    const звучащие: readonly (readonly string[])[] = [
      ['  пусть код = 50', '  пусть пер = код >= 48', '  вернуть пер'],
      ['  пусть код = 50', '  пусть пер = код >= 48 и код <= 57', '  вернуть пер'],
      ['  пусть код = 10', '  пусть пер = код >= 48 и код <= 57', '  вернуть пер'],
      ['  пусть код = 48', '  пусть пер = код == 48 или код == 57', '  вернуть пер'],
      ['  пусть код = 50', '  пусть пер = не (код < 48)', '  вернуть пер'],
    ];
    for (const тело of звучащие) {
      expect(причины(тело), `звучащая проба отвергнута: ${тело.join(' ')}`).toEqual([]);
    }
  });

  it('ПЕРЕМЕННЫЕ границы отвергаются при ЛЮБОМ входе: форма незвучна, а не «этот вход плох»', () => {
    // Разделение накопителя — свойство ФОРМЫ, а не значения: проба с истинным первым термом
    // (код = 50) собиралась и давала верное 1, но с ложным (код = 10) — 10 вместо 0. Сторож обязан
    // отказать обеим, иначе он «сторожит вход», а не форму.
    for (const код of [50, 10]) {
      const отказы = причины([
        `  пусть код = ${String(код)}`,
        '  пусть н = 48',
        '  пусть м = 57',
        '  пусть пер = код >= н и код <= м',
        '  вернуть пер',
      ]);
      expect(отказы.length, `код = ${String(код)}: разделённый накопитель не отвергнут`).toBe(1);
    }
  });
});

describe('сторож: звучащая сторона по-прежнему считает верно (эталон — счёт от руки)', () => {
  /** Образ кода без отказов. */
  function образ(тело: readonly string[]): Uint8Array | undefined {
    const src = программа(тело);
    const разбор = parseV3(src, ФАЙЛ);
    if (разбор.errors.length > 0) return undefined;
    const собран = loweredProgram(src, {
      filename: ФАЙЛ,
      parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    });
    if (собран.refused.length > 0) return undefined;
    return собран.bytes;
  }

  function модель(код: Uint8Array, имя: string): number | null | undefined {
    const файл = path.join(ROOT, '.tmp', `conjunction-value-${имя}.elf`);
    fs.writeFileSync(файл, buildElfFromCode(код, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes);
    return runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status;
  }

  const пробы: readonly { readonly имя: string; readonly тело: readonly string[]; readonly ожидание: number }[] = [
    { имя: 'одно-сравнение-истинно', тело: ['  пусть код = 50', '  пусть пер = код >= 48', '  вернуть пер'], ожидание: 1 },
    { имя: 'одно-сравнение-ложно', тело: ['  пусть код = 10', '  пусть пер = код >= 48', '  вернуть пер'], ожидание: 0 },
    { имя: 'конъюнкция-оба-истинны', тело: ['  пусть код = 50', '  пусть пер = код >= 48 и код <= 57', '  вернуть пер'], ожидание: 1 },
    { имя: 'конъюнкция-первый-ложен', тело: ['  пусть код = 10', '  пусть пер = код >= 48 и код <= 57', '  вернуть пер'], ожидание: 0 },
    { имя: 'или', тело: ['  пусть код = 48', '  пусть пер = код == 48 или код == 57', '  вернуть пер'], ожидание: 1 },
    { имя: 'не', тело: ['  пусть код = 50', '  пусть пер = не (код < 48)', '  вернуть пер'], ожидание: 1 },
  ];

  it('шесть звучащих проб: значения посчитаны от руки, а не «модель согласна с моделью»', () => {
    if (shim === undefined) {
      console.log('сторож 5б: шим модели недоступен — прогонные проверки пропущены');
      return;
    }
    const беды: string[] = [];
    for (const проба of пробы) {
      const собран = образ(проба.тело);
      if (собран === undefined) {
        беды.push(`${проба.имя}: не собралась — сторож задел звучащую форму`);
        continue;
      }
      const код = модель(собран, проба.имя);
      if (код !== проба.ожидание) беды.push(`${проба.имя}: модель ${String(код)}, эталон ${String(проба.ожидание)}`);
    }
    expect(беды, 'звучащая сторона конъюнкции сломана сторожем').toEqual([]);
  });
});
