describe('эталон языка: обе VM (стековая и регистровая) — сверка с рукой', () => {
  /** Значение VM: булево → 1/0, иначе как есть. Считается ОТДЕЛЬНО от цели — это независимый эталон. */
  const число = (значение: unknown): number | undefined => {
    if (значение === true) return 1;
    if (значение === false) return 0;
    return typeof значение === 'number' ? значение : undefined;
  };

  it('23 пробы: и стековая, и регистровая VM дают ровно посчитанное от руки', async () => {
    const беды: string[] = [];
    for (const форма of ФОРМЫ) {
      for (const проба of форма.пробы) {
        const источник = программа(проба.тело);
        const разбор = parseV3(источник, ФАЙЛ);
        if (разбор.errors.length > 0) {
          беды.push(`${проба.имя}: разбор ${JSON.stringify(разбор.errors)}`);
          continue;
        }
        const м = разбор.program!.modules[0]!;
        const проход = validateNamedTypesAndRewrite(м);
        if (проход.length > 0) {
          беды.push(`${проба.имя}: проход ${JSON.stringify(проход)}`);
          continue;
        }
        const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
        const стек = await стековая.runProcedure(стековая.findProcedureIndex('главная'), []);
        const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
        const регистры = await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []);
        if (число(стек) !== проба.эталон) беды.push(`${проба.имя}: стековая ${JSON.stringify(стек)}, эталон ${String(проба.эталон)} (${проба.рука})`);
        if (число(регистры) !== проба.эталон) беды.push(`${проба.имя}: регистровая ${JSON.stringify(регистры)}, эталон ${String(проба.эталон)}`);
      }
    }
    expect(беды, 'эталон от руки не подтверждён обеими VM').toEqual([]);
  });
});

