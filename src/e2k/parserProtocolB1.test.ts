/**
 * ШАГ B1: ВОСЕМЬ ПИСАТЕЛЕЙ — ЭТАЛОН В EVENT TAPE.
 *
 * Каждый сценарий строит token tape из `ИСХОДНИК_B1`, зовёт ОДИН писатель и печатает ровно записанные
 * клетки AST. Ожидание считается из позиций токенов, а не из вывода пробы: та же форма, что у
 * `лентаИзAst`, поэтому «проба согласна с собой» здесь не считается проверкой.
 *
 * Восемь сценариев, девять процедур: `список_начало` и `список_конец` — одна пара (один сценарий),
 * поэтому N = 8, а не 9. Имя сценария — это и есть писатель; `параметр` пишет заголовок события, а
 * имя/тип дописывает вызывающий (как `пусть`: `конец` события не живёт в одном листе).
 *
 * Эти прогоны спрашивают у живого QEMU и потому исключены из `npm test` (`gate:qemu`, случай 12).
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { КОД_СОБЫТИЯ } from '../compiler-v3/astFormat';
import { parseV3 } from '../compiler-v3';
import { программаПротоколаB1, токеныB1, type СценарийB1 } from '../compiler-v3/parser-protocol-probe';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { loweredProgram } from './lowered';
import { runInQemu } from '../scripts/e2kQemuExec';

const СЦЕНАРИИ: readonly СценарийB1[] = [
  'нацело',
  'остаток',
  'вызов_оператор',
  'список',
  'иначе_если',
  'параметр',
  'действие_начало',
  'конец',
];

function коды(текст: string): number[] {
  return [...текст].map((символ) => символ.codePointAt(0)!);
}

function найти(лексема: string) {
  const токен = токеныB1().find((кандидат) => кандидат.лексема === лексема);
  if (токен === undefined) throw new Error(`B1: в исходнике нет «${лексема}»`);
  return токен;
}

/** Ожидаемая лента считается ТОЛЬКО из позиций токенов и кодов `КОД_СОБЫТИЯ`. */
function ожидаемая(сценарий: СценарийB1): number[] {
  switch (сценарий) {
    case 'нацело': {
      const т = найти('нацело');
      return [КОД_СОБЫТИЯ.бинарный_нацело, т.начало, т.начало + т.длина];
    }
    case 'остаток': {
      const т = найти('%');
      return [КОД_СОБЫТИЯ.бинарный_остаток, т.начало, т.начало + т.длина];
    }
    case 'вызов_оператор': {
      const т = найти('фф');
      return [КОД_СОБЫТИЯ.вызов_оператор, т.начало, т.строка, т.колонка];
    }
    case 'список': {
      const начало = найти('[');
      const конец = найти(']');
      return [
        КОД_СОБЫТИЯ.список_начало,
        начало.начало,
        начало.строка,
        начало.колонка,
        КОД_СОБЫТИЯ.список_конец,
        2,
        конец.начало + конец.длина,
      ];
    }
    case 'иначе_если': {
      const т = найти('иначе');
      return [КОД_СОБЫТИЯ.иначе_если, т.начало, т.строка, т.колонка];
    }
    case 'параметр': {
      const имя = найти('а');
      const тип = найти('Число');
      return [
        КОД_СОБЫТИЯ.параметр,
        имя.начало,
        имя.строка,
        имя.колонка,
        имя.длина,
        ...коды('а'),
        1,
        тип.длина,
        ...коды('Число'),
        тип.начало + тип.длина,
      ];
    }
    case 'действие_начало': {
      const т = найти('действие');
      return [КОД_СОБЫТИЯ.действие_начало, т.начало, т.строка, т.колонка, т.начало + 8];
    }
    case 'конец':
      return [КОД_СОБЫТИЯ.конец];
  }
}

function запустить(сценарий: СценарийB1): number[] {
  const источник = программаПротоколаB1(сценарий);
  const разобранный = parseV3(источник, `b1-${сценарий}.osnova`);
  expect(разобранный.errors, `B1 ${сценарий}: разбор`).toEqual([]);
  const понижен = loweredProgram(источник, {
    filename: `b1-${сценарий}.osnova`,
    parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }),
  });
  expect(понижен.ок, `B1 ${сценарий}: понижение`).toBe(true);
  if (!понижен.ок) return [];

  const каталог = mkdtempSync(join(tmpdir(), 'b1-'));
  const файл = join(каталог, 'b1.elf');
  try {
    writeFileSync(
      файл,
      buildElfFromCode(понижен.значение.bytes, MINIMAL_BASE, {
        writable: true,
        extraMemory: WRITE_ZONE_EXTRA_MEMORY,
      }).bytes,
    );
    const прогон = runInQemu(файл, { shim: true, timeoutMs: 60_000 });
    expect(прогон.status, `B1 ${сценарий}: код QEMU`).toBe(0);
    return String(прогон.stdout)
      .split(/\r?\n/)
      .filter((строка) => строка.trim() !== '')
      .map((строка) => Number(строка.trim()));
  } finally {
    rmSync(каталог, { recursive: true, force: true });
  }
}

describe('B1: писатели событий AST (N=8)', () => {
  for (const сценарий of СЦЕНАРИИ) {
    it(`${сценарий}: одна запись события = эталон`, () => {
      expect(запустить(сценарий)).toEqual(ожидаемая(сценарий));
    });
  }
});
