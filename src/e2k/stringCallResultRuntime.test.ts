/**
 * СЛУЧАЙ 76, ПУТЬ (а) (TD-0005): ЗНАЧЕНИЕ, ВОЗВРАЩЁННОЕ ВЫЗОВОМ, ДОХОДИТ ДО ПЕЧАТИ КАК СТРОКА.
 *
 * ═══ ЧТО БЫЛО (ЗАМЕР ДО ПРАВКИ, 2026-11-05, `.tmp/td76-базовая.ts`, модель) ═════════════════════════
 *
 *   `процедура ф(а: Строка) → Строка / вернуть а` + `пусть т = ф("абв")` + `вывести т`
 *     → **1114106** — АДРЕС байтов, а не текст. Отказов 0, образ исполняется: это тихая ложь.
 *
 * Причина (измерена, а не объявлена): факт «эта клетка — строка» доезжал до плана ТОЛЬКО для
 * ПАРАМЕТРОВ и для нагрузки пары. Клетка-РЕЗУЛЬТАТ вызова в фактах не участвовала, а сам сайт печати
 * (`src/e2k/stringPlan.ts`) читает ИСКЛЮЧИТЕЛЬНО `byRegister` — ни `typedValues` (`provenValueOf`), ни
 * множеств (`typedChoices`), ни ветви «тип есть, значения нет» там нет. Поэтому значение обязано
 * ставиться НА САЙТЕ ВЫЗОВА — ровно так, как это сделано для нагрузки пары (`resultValues` +
 * `IR.result_pick`), а не «на старте процедуры».
 *
 * ═══ СТОРОЖ ПРЯМОЛИНЕЙНОСТИ — И ПОЧЕМУ ОН ОБЯЗАТЕЛЕН ════════════════════════════════════════════
 *
 * План подставляет значения ЛИНЕЙНО, а на ребре взятого перехода команды между переходом и целью НЕ
 * исполняются: состязательная проба В1/В2 (та же клетка, две сквозные процедуры в РАЗНЫХ ветвях)
 * напечатала значение, записанное ДО ветви, — **чужой текст, то есть НОВАЯ тихая ложь**. Поэтому факт
 * ставится только для процедур БЕЗ `IR.jmp`/`IR.jmp_if`/`IR.jmp_if_not`; тогда В1/В2 возвращаются к
 * ПРЕЖНЕЙ границе (адрес, как до правки), а не к чужой строке. Цена названа честно: процедуры с
 * переходами (весь лексер) факта не получают — расширение требует плана по графу потока управления,
 * это отдельный атом (TD-0003).
 *
 * ═══ ЧТО ЗДЕСЬ СПРАШИВАЕТСЯ ═══════════════════════════════════════════════════════════════════════
 *
 *   Б1 один сайт с литералом — оракул владельца: печатается ТЕКСТ `абв`;
 *   Б2/Б3 два РАЗНЫХ сайта (две локали и одна клетка) — `абв`, затем `где`;
 *   Б4 сквозной возврат ВТОРОГО параметра — `абв`;
 *   Б5 контроль: `пусть т = "абв"` (литерал) — `абв` (печать локальной строки не сломана);
 *   Б6 ГРАНИЦА, уже работавшая: печать ПАРАМЕТРА из процедуры при двух сайтах — названный отказ
 *      `OSN-LOW-005` («разделённая печать из процедуры»), и он ОБЯЗАН остаться на месте;
 *   В1/В2 состязательный сторож: ветка с разными сквозными процедурами — прежняя граница (адрес),
 *      а НЕ чужой текст; В3 контроль без ветки: две записи подряд — `где`.
 *
 * Модельные проверки спрашиваются только в шлюзе (`OSNOVA_GATE_QEMU=1`): ответ даёт прогон в живом
 * QEMU, а полный прогон обязан быть детерминированным (случай 12 реестра проверяемости). Быстрые
 * половины — «отказов понижения нет» и текст отказа Б6 — идут и в полном прогоне.
 *
 * НЕГАТИВНЫЙ КОНТРОЛЬ: откат правки (факт из вызова не ставится) краснит Б1-Б4 и В3 — печатается
 * адрес вместо текста; Б5, Б6, В1/В2 остаются ЗЕЛЁНЫМИ в обоих состояниях: они сторожа ГРАНИЦЫ.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { SHIM_REASON } from '../scripts/e2kProgramRun';
import type { CompileOptions } from '../compiler/compiler';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'результат-вызова-строка.osnova';

// ── Формы процедур (те же, что в замерах `.tmp/td76-*.ts`: менять нельзя) ────────────────────────

/** Сквозная процедура: возвращает СВОЙ первый параметр. */
const СКВОЗНАЯ = ['процедура ф(а: Строка) → Строка', '  вернуть а', 'конец', ''].join('\n');

/** Сквозной возврат ВТОРОГО параметра — различает «параметр вообще» и «нужный параметр». */
const ВТОРОЙ = ['процедура ф2(а: Строка, б: Строка) → Строка', '  вернуть б', 'конец', ''].join('\n');

/** Печать ПАРАМЕТРА из процедуры: форма границы `OSN-LOW-005`. */
const ПЕЧ = ['процедура печ(а: Строка) → Число', '  вывести а', '  вернуть 0', 'конец', ''].join('\n');

const ГЛАВНАЯ = (тела: readonly string[]): string =>
  ['действие главная()', ...тела.map((тело) => `  ${тело}`), '  вернуть 0', 'конец', ''].join('\n');

/** Ветка внутри цикла: счётчик рантаймовый, первая итерация берёт «тогда». */
const ВЕТКА = (тогда: string, иначе: string): string =>
  [
    'действие главная()',
    '  пусть сч = 0',
    '  пусть т = "х"',
    '  пока сч < 1',
    '    если сч == 0',
    `      пусть т = ${тогда}`,
    '    иначе',
    `      пусть т = ${иначе}`,
    '    конец',
    '    сч = сч + 1',
    '  конец',
    '  вывести т',
    '  вернуть 0',
    'конец',
    '',
  ].join('\n');

// ── Пробы ────────────────────────────────────────────────────────────────────────────────────────

const Б1 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть т = ф("абв")', 'вывести т']);
const Б2 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть т1 = ф("абв")', 'вывести т1', 'пусть т2 = ф("где")', 'вывести т2']);
const Б3 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть т = ф("абв")', 'вывести т', 'пусть т = ф("где")', 'вывести т']);
const Б4 = ВТОРОЙ + ГЛАВНАЯ(['пусть т = ф2("хх", "абв")', 'вывести т']);
const Б5 = ГЛАВНАЯ(['пусть т = "абв"', 'вывести т']);
const Б6 = ПЕЧ + ГЛАВНАЯ(['вывести печ("абв")', 'вывести печ("где")']);
const В1 = СКВОЗНАЯ + ВЕТКА('ф("абв")', 'ф("где")');
const В2 = СКВОЗНАЯ + ВЕТКА('ф("где")', 'ф("абв")');
const В3 = СКВОЗНАЯ + ГЛАВНАЯ(['пусть т = ф("абв")', 'пусть т = ф("где")', 'вывести т']);

// ── Помощники ────────────────────────────────────────────────────────────────────────────────────

interface Отказ {
  readonly код?: string;
  readonly причина: string;
}

interface Итог {
  readonly вывод: string;
  readonly код: number | null;
}

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

function отказы(источник: string): readonly Отказ[] {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, 'разбор обязан быть чист: иначе проба не про понижение').toEqual([]);
  if (ошибки.length > 0) return [];
  const итог = loweredProgram(источник, options);
  if (итог.ок) return [];
  return итог.отказ.отказы.map((запись) => ({ код: запись.код, причина: запись.причина }));
}

function названные(записи: readonly Отказ[]): readonly string[] {
  return записи.map((запись) => `${запись.код ?? '—'}: ${запись.причина}`);
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

function прогон(имя: string, источник: string): Итог {
  const { options } = фронтенд(источник);
  const итог = loweredProgram(источник, options);
  expect(итог.ок, 'образ обязан собраться: ложь случая 76 тем и опасна, что отказов 0').toBe(true);
  if (!итог.ок) return { вывод: '', код: null };
  if (шим() === undefined) throw new Error(`шим не собран: ${SHIM_REASON}`);
  const elf = path.join(ROOT, '.tmp', `td76-${имя}.elf`);
  fs.mkdirSync(path.dirname(elf), { recursive: true });
  fs.writeFileSync(
    elf,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY })
      .bytes,
  );
  const прогонЦели = runInQemu(elf, { shim: true, timeoutMs: 30_000 });
  if (прогонЦели === undefined) throw new Error(`модель не ответила на пробу «${имя}»`);
  return { вывод: (прогонЦели.stdout ?? '').replace(/\n$/u, ''), код: прогонЦели.status };
}

const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';

// ── Проверки ─────────────────────────────────────────────────────────────────────────────────────

describe('случай 76: результат вызова, возвращающий Строку, доходит до печати', () => {
  it('Б1: отказов понижения НЕТ — иначе проба не про тихую ложь', () => {
    expect(названные(отказы(Б1))).toEqual([]);
    expect(названные(отказы(Б2))).toEqual([]);
    expect(названные(отказы(Б4))).toEqual([]);
  });

  it('Б1: `пусть т = ф("абв")` + `вывести т` печатает ТЕКСТ, а не адрес 1114106 (оракул владельца)', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б1', Б1);
    expect(итог.вывод, 'адрес вместо текста — тихая ложь случая 76').toBe('абв');
    expect(итог.код).toBe(0);
  });

  it('Б2: два РАЗНЫХ сайта, две локали — `абв` и `где`', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б2', Б2);
    expect(итог.вывод, 'разные сайты обязаны дать РАЗНЫЕ строки: значение берётся с САЙТА').toBe('абв\nгде');
    expect(итог.код).toBe(0);
  });

  it('Б3: два разных сайта в ОДНУ клетку — `абв` и `где`', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б3', Б3);
    expect(итог.вывод, 'вторая запись в ту же клетку обязана победить').toBe('абв\nгде');
    expect(итог.код).toBe(0);
  });

  it('Б4: сквозной возврат ВТОРОГО параметра — `абв`, а не первый параметр', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б4', Б4);
    expect(итог.вывод).toBe('абв');
    expect(итог.код).toBe(0);
  });

  it('Б5: контроль — печать ЛОКАЛЬНОЙ строки не сломана', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('б5', Б5);
    expect(итог.вывод).toBe('абв');
    expect(итог.код).toBe(0);
  });

  it('Б6: граница `OSN-LOW-005` (разделённая печать из процедуры) НЕ сдвинулась', () => {
    const записи = отказы(Б6);
    const текст = названные(записи).join(' | ');
    expect(записи.length, 'печать параметра из процедуры при двух сайтах — ЗАФИКСИРОВАННАЯ граница').toBeGreaterThan(0);
    expect(текст, 'граница обязана называться своим кодом').toContain('OSN-LOW-005');
    expect(текст, 'и своей причиной, иначе она неотличима от чужой').toContain('разделённ');
  });

  it('В1/В2: ветка с двумя сквозными — прежняя граница (адрес), а НЕ чужой текст', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    // Сторож прямолинейности: линейный проход плана взял бы значение НЕ ТОЙ ветви. Замер с наивной
    // редакцией: В1 печатала `х` (значение ДО ветви) — новая тихая ложь. С прежней границей здесь
    // стоит АДРЕС блоба `"х"`, тот же, что был до правки вовсе без механизма.
    const в1 = прогон('в1', В1);
    const в2 = прогон('в2', В2);
    expect(в1.вывод, 'чужой текст здесь был бы НОВОЙ ложью').toBe('1114110');
    expect(в2.вывод, 'чужой текст здесь был бы НОВОЙ ложью').toBe('1114110');
  });

  it('В3: контроль без ветки — две записи подряд дают `где` (факт ставится и в этом случае)', () => {
    if (!В_ШЛЮЗЕ_QEMU) return;
    const итог = прогон('в3', В3);
    expect(итог.вывод, 'прямолинейная процедура обязана получить факт').toBe('где');
  });
});
