/**
 * ПОЛНЫЙ ОДНО-ПРОХОДНЫЙ ЛЕКСЕР (D49) — оракул на цели и сторож N = 4.
 *
 * # Предмет
 *
 * Срез 7 сдавал лексер кусками: идентификаторы (§3.180), числа/знаки/ключевые (§3.182), строки
 * (§3.183), комментарии (кусок 4). Здесь — ОДНА программа (`src/e2k/lexerProgram.ts`) на ВСЁ:
 * dispatcher в точке входа плюс семь handler'ов-сканов и две классификации, один проход, все виды
 * токенов, сверка с `tokenizeV3` ПОКАЖДОМУ токену на всех входах кусков. Решение владельца D49:
 * полный лексер — продакшен-программа, а не должник VLIW; D48 снял потолок фактом (B на модели и
 * на железе).
 *
 * # Что именно доказывается (и чем)
 *
 * | столбец | откуда |
 * |---|---|
 * | «токены верны» | прогон в модели QEMU (здесь) + прогон на E8C2 (`docs/hardware-debt.md` §3.187) |
 * | отказов понижения 0 | `loweredProgram` — дверь отвечает «образ или отказ», третьего нет |
 * | пик живых 9 ≤ 10, вытеснений 1 ≤ 8 | отчёт раскладки (числа сняты замером и записаны в D49) |
 * | N = 4 | откат каждого handler'а по одному: РОВНО 4 режима красные, полный — зелёный |
 *
 * Без столбца «токены верны vs `tokenizeV3`» результат недействителен (D4): программа собирается и
 * печатает — этого мало, числа обязаны совпасть по токенам, включая вид, строку и лексему.
 *
 * # Сторож N = 4 — самопокраснение
 *
 * `программа(текст, режим)` умеет гасить каждый handler (`имена`, `числа`, `строки`, `комментарии`).
 * Гашение — не «имитация отката», а ровно то, что делает откат ветви: эта ветвь исчезает из
 * dispatcher'а, а остальные остаются. Прогон в модели: полный режим совпадает с эталоном, каждый из
 * четырёх гашений — РАСХОДИТСЯ. Это и есть N = 4: четыре независимых handler'а, четыре красных
 * состояния, одно зелёное. Байтовая точность возврата проверяется sha256 программы ДО и ПОСЛЕ
 * генерации гашёных вариантов (генератор — чистая функция текста; если бы режим «протекал», хеш
 * разошёлся бы).
 *
 * # Границы (названы, а не сглажены)
 *
 *  * `:=` эталон НЕ токенизирует (пишет ошибку и пропускает два знака); этот лексер на `:` и `=`
 *    отдаёт два знака и НЕ моделирует канал ошибок — проверенные входы `:=` не содержат. Случай 90
 *    `docs/verification-debt.md`.
 *  * Классификация слова — `(длина, хэш)` по ЗАКРЫТОЙ таблице 43 ключевых слов (инъективность
 *    сторожится отдельно); для не-ключа с той же парой остаётся остаточная граница.
 *  * Строковое декодирование в точке входа написано БЕЗ локальной переменной под вытеснением: форма
 *    `пусть кд = коды[поз]` + `добавить … кд` на этом образе печатала 0 вместо кодовой точки при
 *    НУЛЕ отказов (замер: вход `"аб"` давал 0, 0 вместо 1072, 1073), а та же форма в малой программе
 *    работает. Это класс «значение не переживает вытеснение», и правка `regAlloc`/`liveness`/
 *    `spill.ts` запрещена атомом (VLIW-компоненты, D48: не нужны). Форма программы обходит дефект, а
 *    дефект записан в случай 90 — не спрятан.
 *  * Модель — не железо (D12): железный прогон того же образа — отдельный шаг и отдельный отчёт.
 */
import { beforeAll, describe, expect, it } from 'vitest';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import {
  БАЙТ_СЕГМЕНТА_ДАННЫХ,
  ВИДЫ_ТОКЕНОВ,
  ВХОДЫ_ОРАКУЛА,
  ПОЛНЫЙ_РЕЖИМ,
  ТЕКСТ_B,
  ТАБЛИЦА_КЛЮЧЕВЫХ,
  разобратьВывод,
  сравнить,
  эталон,
  программа,
  type РежимЛексера,
} from './lexerProgram';

const ROOT = path.resolve(__dirname, '..', '..');

/** Модель спрашивается ТОЛЬКО шлюзом: признак задан явно, а не выведен из «есть ли шим» (случай 12). */
const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';

const sha256 = (текст: string): string => createHash('sha256').update(текст, 'utf8').digest('hex');

/**
 * Стековая VM — эталон поведения программы без модели. Канал тот же, что у печати: программа печатает
 * плоский список, `разобратьВывод` собирает из него токены. Так «полный режим верен, гашёный — нет»
 * проверяется и в полном прогоне, где модели нет (случай 12).
 */
async function наСтековой(текст: string, режим: Partial<РежимЛексера>): Promise<string> {
  const исходник = программа(текст, режим);
  const разбор = parseV3(исходник, 'лексер-полный.osnova');
  expect(разбор.errors, `v3 не разобрал программу: ${разбор.errors.join('; ')}`).toEqual([]);
  const модуль = разбор.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(модуль), 'проход разрешения имён').toEqual([]);
  const байткод = compile(модуль);
  const вывод: unknown[] = [];
  const обычный = createDefaultInvokeHandler();
  const vm = new VM(байткод, {
    maxSteps: 20_000_000,
    invoke: async (имя, аргументы) => {
      if (имя === 'система.лог.вывести') {
        вывод.push(аргументы[0]);
        return null;
      }
      return обычный(имя, аргументы);
    },
  });
  await vm.runProcedure(vm.findProcedureIndex('главная'), []);
  return вывод.map((значение) => String(значение)).join('\n');
}

/**
 * Образ цели: фронтенд v3 подставлен в общую дверь понижения (`options.parse`), а не переписан
 * вторым путём. Отказ здесь — БРОСОК с причиной: «тихие пустые байты» запрещены (ERR-0004).
 */
function образЦели(текст: string, режим: Partial<РежимЛексера>): Uint8Array {
  const исходник = программа(текст, режим);
  const разбор = parseV3(исходник, 'лексер-полный.osnova');
  expect(разбор.errors, `v3 не разобрал программу: ${разбор.errors.join('; ')}`).toEqual([]);
  const итог = loweredProgram(исходник, {
    filename: 'лексер-полный.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (!итог.ок) throw new Error(`полный лексер обязан понижаться без отказов: ${итог.отказ.причина}`);
  return итог.значение.bytes;
}

/** Цель: сборка полным понижением и прогон в модели; возвращает распечатанный канал как есть. */
function наЦели(имя: string, текст: string, режим: Partial<РежимЛексера>): { код: number; вывод: string } {
  const elf = path.join(ROOT, '.tmp', `lexer-full-${имя}.elf`);
  fs.writeFileSync(
    elf,
    buildElfFromCode(образЦели(текст, режим), MINIMAL_BASE, {
      writable: true,
      extraMemory: WRITE_ZONE_EXTRA_MEMORY,
      dataSegmentBytes: БАЙТ_СЕГМЕНТА_ДАННЫХ,
    }).bytes,
  );
  const прогон = runInQemu(elf, { shim: true, timeoutMs: 60_000 });
  expect(прогон, 'модель не ответила — причина обязана быть красной, а не пропущенной').toBeTruthy();
  return { код: прогон!.status, вывод: прогон!.stdout };
}

const токеныНаЦели = (имя: string, текст: string, режим: Partial<РежимЛексера> = {}) => {
  const { код, вывод } = наЦели(имя, текст, режим);
  expect(код, `печатающая программа завершается своим exit(0) (${имя})`).toBe(0);
  return разобратьВывод(вывод);
};

beforeAll(() => {
  // Шим нужен только шлюзу: полный прогон не ходит в WSL за QEMU (случай 12).
  if (В_ШЛЮЗЕ_QEMU) buildShim();
});

describe('устройство: таблицы закрыты, программа разбирается и понижается', () => {
  it('43 ключевых слова: пары (длина, хэш) инъективны — классификация без коллизий', () => {
    const пары = new Set(ТАБЛИЦА_КЛЮЧЕВЫХ.map(([длина, хэш]) => `${String(длина)}:${String(хэш)}`));
    expect(ТАБЛИЦА_КЛЮЧЕВЫХ.length).toBe(43);
    expect(пары.size, 'две записи с одной парой сделали бы вид неоднозначным').toBe(43);
    for (const [, , вид] of ТАБЛИЦА_КЛЮЧЕВЫХ) expect(ВИДЫ_ТОКЕНОВ).toContain(вид);
  });

  it('все шесть входов оракула разбираются фронтендом v3', () => {
    for (const вход of ВХОДЫ_ОРАКУЛА) {
      const разбор = parseV3(программа(вход.текст), `проба-${вход.имя}.osnova`);
      expect(разбор.errors, вход.имя).toEqual([]);
    }
  });

  it('полный B понижается без отказов (дверь отвечает образом, а не причиной)', () => {
    const байты = образЦели(ТЕКСТ_B, ПОЛНЫЙ_РЕЖИМ);
    expect(байты.length, 'пустой образ — это ERR-0004, а не успех').toBeGreaterThan(0);
  });

  it('генератор — чистая функция текста: sha256 программы ДО и ПОСЛЕ гашёных режимов совпал', () => {
    const до = sha256(программа(ТЕКСТ_B));
    for (const режим of [{ имена: false }, { числа: false }, { строки: false }, { комментарии: false }]) {
      expect(программа(ТЕКСТ_B, режим)).not.toBe(программа(ТЕКСТ_B));
    }
    expect(sha256(программа(ТЕКСТ_B)), 'возврат к полному режиму обязан быть байт-в-байт').toBe(до);
  });
});

describe('N = 4: полный режим верен, каждый из четырёх handler\'ов красит ровно своё', () => {
  const гашения: readonly { readonly имя: string; readonly режим: Partial<РежимЛексера> }[] = [
    { имя: 'без-имён', режим: { имена: false } },
    { имя: 'без-чисел', режим: { числа: false } },
    { имя: 'без-строк', режим: { строки: false } },
    { имя: 'без-комментариев', режим: { комментарии: false } },
  ];

  it('полный режим на стековой VM = `tokenizeV3` по каждому токену', async () => {
    const io = await наСтековой(ТЕКСТ_B, ПОЛНЫЙ_РЕЖИМ);
    expect(сравнить(разобратьВывод(io), эталон(ТЕКСТ_B))).toEqual([]);
  });

  it('каждое гашение РАСХОДИТСЯ с эталоном — ровно 4 красных состояния', async () => {
    const красные: string[] = [];
    for (const { имя, режим } of гашения) {
      const вывод = await наСтековой(ТЕКСТ_B, режим);
      const расхождения = сравнить(разобратьВывод(вывод), эталон(ТЕКСТ_B));
      if (расхождения.length > 0) красные.push(имя);
    }
    expect(красные, 'N = 4: красных обязано быть РОВНО четыре, по одному на handler').toEqual(
      гашения.map(({ имя }) => имя),
    );
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('модель доступна — иначе причина названа', () => {
    expect(buildShim(), 'шим/модель qemu-e2k недоступны: прогон числа невозможен').toBeTruthy();
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('полный режим на ЦЕЛИ = `tokenizeV3` (столбец «токены верны») — зелёный', () => {
    expect(сравнить(токеныНаЦели('полный-B', ТЕКСТ_B), эталон(ТЕКСТ_B))).toEqual([]);
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('четыре гашения на ЦЕЛИ красные — модель различает, а не «чинит»', () => {
    const красные = гашения
      .filter(({ имя, режим }) => сравнить(токеныНаЦели(`гашёный-${имя}`, ТЕКСТ_B, режим), эталон(ТЕКСТ_B)).length > 0)
      .map(({ имя }) => имя);
    expect(красные).toEqual(гашения.map(({ имя }) => имя));
  });
});

describe('все входы кусков: полный лексер сходится с эталоном на модели', () => {
  it.skipIf(!В_ШЛЮЗЕ_QEMU)('шесть входов оракула — «токены верны» по КАЖДОМУ токену', () => {
    for (const вход of ВХОДЫ_ОРАКУЛА) {
      const факт = токеныНаЦели(`оракул-${вход.имя}`, вход.текст);
      expect(сравнить(факт, эталон(вход.текст)), `столбец «токены верны» для ${вход.имя}`).toEqual([]);
    }
  });
});
