const imm = (value: number): Operand => ({ kind: 'imm', value });
const reg = (index: number): Operand => ({ kind: 'reg', index });
const carrier = (mnemonic: string, operands: readonly Operand[]): AsmInstruction => ({
  mnemonic,
  channel: 0,
  operands,
});

function regOf(instruction: AsmInstruction, at: number): { index: number; file?: string } {
  const operand = instruction.operands[at];
  if (operand === undefined || operand.kind !== 'reg') {
    throw new Error(`${instruction.mnemonic}: операнд ${at} не регистр`);
  }
  return { index: operand.index, ...(operand.file === undefined ? {} : { file: operand.file }) };
}

let шимСобран: string | undefined;
let шимСпрошен = false;
function шим(): string | undefined {
  if (!шимСпрошен) {
    шимСпрошен = true;
    шимСобран = buildShim();
  }
  return шимСобран;
}

function фронтенд(источник: string): { readonly ошибки: readonly string[]; readonly options: CompileOptions } {
  const разбор = parseV3(источник, ФАЙЛ);
  return {
    ошибки: разбор.errors,
    options: { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) },
  };
}

/** Собрать образ ПУТЁМ КОМПИЛЯТОРА и исполнить в модели: код возврата и ВЫВОД печати (широкий канал). */
function прогон(
  источник: string,
  файл: string,
): { readonly код: number | null; readonly вывод: string } {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, `разбор v3: ${ошибки.join('; ')}`).toEqual([]);
  if (ошибки.length > 0) return { код: null, вывод: '' };
  const итог = loweredProgram(источник, options);
  expect(
    итог.ок,
    итог.ок ? '' : `отказы понижения: ${итог.отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`).join(' | ')}`,
  ).toBe(true);
  if (!итог.ок) return { код: null, вывод: '' };
  const путь = path.join(ROOT, '.tmp', файл);
  fs.writeFileSync(
    путь,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const исполнение = runInQemu(путь, { shim: true, timeoutMs: 30_000 });
  return { код: исполнение?.status ?? null, вывод: (исполнение?.stdout ?? '').trim() };
}

/**
 * Отказы понижения ПО ИМЕНИ. Компилятор может и бросить (безымянный отказ — тоже факт, он назван
 * отдельно), поэтому бросок ловится и возвращается с пометкой.
 */
function отказы(источник: string): readonly string[] {
  const { ошибки, options } = фронтенд(источник);
  expect(ошибки, `этот текст обязан РАЗБИРАТЬСЯ (отказ ждём от понижения, а не от разбора): ${ошибки.join('; ')}`).toEqual(
    [],
  );
  if (ошибки.length > 0) return [];
  let итог: ReturnType<typeof loweredProgram>;
  try {
    итог = loweredProgram(источник, options);
  } catch (беда) {
    return [`БРОСОК: ${беда instanceof Error ? беда.message : String(беда)}`];
  }
  if (итог.ок) return [];
  return итог.отказ.отказы.map((запись) => `${запись.код}: ${запись.причина}`);
}

