/**
 * ЕДИНСТВЕННАЯ ДВЕРЬ К СЫРОМУ ПОНИЖЕНИЮ: байты ЕСТЬ ВСЕГДА, даже под отказом (D11, вариант Г).
 *
 * # Зачем эта дверь существует
 *
 * Публичный `loweredProgram` (`src/e2k/lowered.ts`) отдаёт `Результат<Образ, Отказ>`, и в `Отказе` нет
 * байтов: под несущим отказом наши байты ЛГУТ (шестая и седьмая тихие лжи — случаи 60 и 62 реестра
 * проверяемости), поэтому публиковать их нельзя. Но СТОРОЖ обязан смотреть именно под отказом — иначе
 * ложь нечем поймать: он и берёт байты здесь.
 *
 * # Почему это не «дырка»
 *
 * `loweredProgramUnchecked` экспортируется ТОЛЬКО отсюда, и импорт этого модуля запрещён ESLint вне
 * `src/e2k/**` и `tools/**` (правило по ПУТИ), а само имя запрещено вне `src/e2k/guards/**` и
 * `src/e2k/*.test.ts` (правило по ИДЕНТИФИКАТОРУ, чтобы алиасинг не обошёл первое). Это БАРЬЕР, а не
 * абсолютная защита: `Unchecked` в неподходящем месте — красный флаг на ревью (D11).
 *
 * # Границы
 *
 * Отсюда НЕ строится ELF и не собирается корпус: киту и оракулам нужен публичный путь. Здесь смотрят
 * ЧИСЛО под отказом и перепись отказов.
 */
