/**
 * Ручки СЫРОГО пути. Та же, что у публичной двери: замерная ручка арены живёт здесь, потому что ею
 * ИЗМЕРЯЕТСЯ следующая стена программы (случай 46 реестра), а измеряет её сторож.
 */
export type ОпцииСырогоПути = CompileOptions & {
  readonly assumeArenaReserved?: true;
};

export function loweredProgramUnchecked(
  source: string,
  options: CompileOptions & {
    /**
     * ЗАМЕРНАЯ ручка: считать, что раскладка ЗАКРЕПИЛА регистры арены, даже если разведка этого не
     * увидела. Только в эту сторону (`true`): закрепить лишнее безопасно, а «не закрепить нужное» —
     * ровно тот дефект, который стережёт утверждение ниже.
     *
     * Зачем она в коде, а не в `.tmp`-пробе: ею ИЗМЕРЯЕТСЯ СЛЕДУЮЩАЯ стена программы, у которой
     * разведка арены расходится с потоком (случай 46 реестра проверяемости) — иначе число «сколько
     * кода и сколько отказов, когда арена не мешает» нечем воспроизвести, а невоспроизводимое число
     * перестаёт быть замером. Так измерен лексер: код **8184** байта, отказов **144**
     * (`docs/hardware-debt.md` §3.134, `src/self-host/foundationE2k.test.ts`).
     */
    readonly assumeArenaReserved?: true;
  } = {},
): СыройОбраз {
  // ОТКАЗ ПОВЕРХНОСТИ НАЗЫВАЕТСЯ (D5, случай 73): прежняя редакция бросала безымянное «программа не
  // компилируется» и теряла диагностики компилятора, у каждой из которых есть свой код каталога.
  // Класс отказа при этом не подменяется: это отказ ЯЗЫКА («язык», канал `OSN-CG-*`/`OSN-PAR-*`/
  // `OSN-SEM-*`), а не понижения, поэтому и канал остаётся броском (`src/e2k/recordPlan.ts`).
  const built = regModuleOrNamedFailure(source, options);
  if (!built.ok) throw new Error(frontendRefusalMessage(built.причины));
  const annotated = annotateAtomRegions(built.module, [
    { atom: 'A5', procedures: built.module.procedures.map((procedure) => procedure.name) },
  ]);
  const emitted = emitShell(annotated, shellEncoder);
  // АРЕНА ЗАБИРАЕТ РЕГИСТРЫ СЕБЕ: указатель, предел и ключ предиката она пишет и читает в обход
  // потока носителей, поэтому раскладка не имеет права их отдать (иначе значение легло бы туда же
  // и было бы затёрто молча). Список резервируется ТОЛЬКО тогда, когда образ ареной пользуется:
  // у прочих программ он пуст, и закреплённые числа пяти ядер не двигаются.
  //
  // Решение принимается ЗДЕСЬ и ДО раскладки, а знает его планирование строк: ареной пользуется не
  // только явный `система.память.выделить`, но и **склейка сверх статического буфера**. Поэтому
  // идёт РАЗВЕДКА тем же проходом (`planStrings`) по потоку ДО раскладки — второй счётчик длин
  // разошёлся бы с планом. Разойдись разведка с потоком после раскладки, `imageOfCarriers` откажет
  // по имени (`arenaReserved`), а не соберёт образ с мусором вместо указателя арены.
  // ГРАНИЦЫ ТОЧКИ ВХОДА — то же слово, что уходит в `imageOfCarriers`: по нему план решает, понижать
  // ли рантайм-срез (его сайт живёт только в плоскости точки входа). Разойдись эти два слова —
  // клетки сайта не были бы закреплены, и образ отказал бы по имени, а не собрался с мусором.
  const sliceEntryRange = ((): { readonly from: number; readonly to: number } => {
    const процедуры = emitted.scheduled.procedures;
    const from = процедуры.length === 0 ? 0 : (процедуры[entryProcedureIndex(процедуры)]?.codeOffset ?? 0);
    const to =
      процедуры
        .map((процедура) => процедура.codeOffset)
        .filter((offset) => offset > from)
        .sort((left, right) => left - right)[0] ?? emitted.instructions.length;
    return { from, to };
  })();
  // РАЗВЕДКА ПЛАНИРОВАНИЯ СТРОК — ОДИН проход на ДВА признака (арена и рантайм-срез). Два прохода
  // дали бы два счётчика, которые обязаны совпадать, но ничем к этому не принуждены: тот же довод,
  // по которому здесь стоит разведка, а не «своё» знание о строках.
  const разведкаСтрок = planStrings(
    emitted.instructions,
    emitted.scheduled.constants,
    emitted.image.invokeNames,
    MINIMAL_BASE + HEAP_OFFSET,
    { sliceEntryRange },
  );
  const arenaReserved =
    options.assumeArenaReserved === true ||
    usesArena(emitted.instructions, emitted.image.invokeNames) ||
    разведкаСтрок.counts.arenaConcats > 0 ||
    // РАНТАЙМ-СРЕЗ ЗОВЁТ АРЕНУ САМ (`counts.slicesRuntime`): пролог `IR.arena_init` нужен образу
    // ровно так же, как при склейке сверх буфера, иначе сайт взял бы мусор вместо указателя арены.
    (разведкаСтрок.counts.slicesRuntime ?? 0) > 0;
  // ОСТАТОК (`IR.rem`) резервирует себе регистр САМ, внутри `allocateProgram`: раскладку зовут и
  // напрямую (оракулы), и «не забыть добавить резерв» был бы контрактом, который забудут молча —
  // `src/e2k/remainderRuntime.ts`.
  //
  // КОЛЛЕКЦИИ резервируют регистры ЗДЕСЬ и УСЛОВНО — только тому образу, который ими пользуется.
  // Условно потому, что безусловный резерв отнял бы у ядер регистр и сдвинул закреплённые числа
  // (458 / 53 / 511 / 8800, FIR 181) — ровно та причина, по которой условен резерв остатка.
  // Здесь, а не в `allocateProgram`, потому что признак — ИМЯ вызова из таблицы образа, а её у
  // раскладки нет. Тихая порча от забытого резерва закрыта отказом в самом рантайме
  // (`collectionsRuntime.ts#checkRegister`), а не надеждой.
  // БЮДЖЕТ РЕГИСТРОВ ПО ПРОЦЕДУРАМ: точка входа распоряжается всем файлом раскладки
  // (`%b[0..9]`; `%b[10..15]` держит рантайм массивов), а ВЫЗЫВАЕМАЯ — только своей половиной кадра
  // (`CALLEE_REGISTERS`). Иначе её `%b[2..7]` — это `%b[10..15]` вызывающего, то есть чужой рантайм,
  // и выход программы (`код = значение + %b[12]`) отдаёт чужое число: «собралось, отказов 0,
  // значение неверное». Замер — `docs/hardware-debt.md` §3.96, проба `.tmp/osnova-reread-which.ts`.
  const entryAt = emitted.scheduled.procedures.length === 0 ? -1 : entryProcedureIndex(emitted.scheduled.procedures);
  // ТИПЫ ПРОЦЕДУР — единственный источник «Строка/Число ИЗ ТИПА» (шаг 2.3, ATOM-06-02-02а). Читаются из
  // AST компиляции (`built.compiled`), а не из `RegModule`: у регистровой плоскости типов нет вовсе, а
  // парсер не трогается — тип уже разобран фронтендом и лежит в `paramTypes`/`returnType`.
  //
  // Считаются ОДИН раз: ими пользуются и разведка нужды в клетках строкового рантайма, и сам образ —
  // второй вызов дал бы два списка, которые обязаны совпадать, но ничем к этому не принуждены.
  const типыПроцедур = procedureTypesOf(built.compiled);
  // АДРЕС ЯЧЕЙКИ КУЧИ В ОКНЕ ВЫЗЫВАЕМОЙ (A4, срез 3, §3.137): процедуры, которые ВЫДЕЛЯЮТ массив
  // (`система.массив.создать`), получают `%b[15]` = адрес ячейки кучи — оттуда его читает `создать`.
  // Резерв УСЛОВНЫЙ, как у арены и коллекций: у программ без выделения в вызываемой клетка 15
  // остаётся рабочей, и закреплённые числа пяти ядер не двигаются.
  //
  // Слово «резерв сделан» уезжает в `imageOfCarriers` (`heapSlotReserved`): там из потока ПОСЛЕ
  // раскладки ещё раз считается тот же список, и разойдись он с резервом — `создать` в вызываемой
  // останется НАЗВАННЫМ отказом, а не прочтёт чужую клетку.
  const heapSlotAt = heapSlotProcedures(
    emitted.instructions,
    emitted.scheduled.procedures,
    emitted.image.invokeNames,
    entryAt,
  );
  const heapSlotReserved = heapSlotAt.size > 0;
  // ВРЕМЕННЫЕ СТРОКОВОГО РАНТАЙМА В ПЛОСКОСТИ ВЫЗЫВАЕМОЙ (шаг 2.3, случай 73) — резерв УСЛОВНЫЙ, по
  // той же логике, что у арены, коллекций и клетки кучи. Строковый рантайм держит смещение, байт и
  // признак продолжения в `%b[10]`, `%b[11]`, `%b[13]` (`STRING_REGISTERS`, `src/e2k/stringRuntime.ts`).
  // В плоскости ВХОДА эти клетки значениям и так недоступны (бюджет входа — `%b[0..9]`), поэтому
  // добавление их в `reserved` не меняет у точки входа НИЧЕГО; а в плоскости ВЫЗЫВАЕМОЙ они входят в
  // её бюджет (`CALLEE_REGISTERS` = `%b[8..23]` без клетки нуля), и без закрепления раскладка отдала бы
  // их значениям программы — рантайм затёр бы их МОЛЧА (класс «отказов 0, число неверное»).
  // Четвёртая клетка — `%b[12]` (ноль вызываемой): она закреплена своим механизмом (`CALLEE_ZERO_CELL`,
  // §3.166), и её рантайм возвращает на место.
  const stringCalleeAt = stringNeedProcedures({
    code: emitted.instructions,
    constants: emitted.scheduled.constants,
    invokeNames: emitted.image.invokeNames,
    procedures: emitted.scheduled.procedures,
    procedureTypes: типыПроцедур,
    heapAddress: MINIMAL_BASE + HEAP_OFFSET,
    entryAt,
  });
  const stringsCalleeReserved = stringCalleeAt.size > 0;
  // КЛЕТКИ САЙТА РАНТАЙМ-СРЕЗА — резерв УСЛОВНЫЙ, и он НУЖЕН ИМЕННО ЗДЕСЬ, ДО РАСКЛАДКИ: сайт
  // берёт четыре клетки из бюджета ПРОГРАММЫ (`STRING_SLICE_DECLARED_CELLS`) и пишет в них байт,
  // счётчик, адрес таблицы продолжений и результат сравнений петли. Разведка — тем же проходом
  // (`planStrings`), что у арены: второй счётчик срезов разошёлся бы с планом. Слово «резерв сделан»
  // уезжает в `imageOfCarriers` (`sliceReserved`), и разойдись они — названный отказ, а не порча.
  const sliceReserved = (разведкаСтрок.counts.slicesRuntime ?? 0) > 0;
  // B-БЛОК: РАСШИРЕННЫЙ ПУЛ `%b[0..15]` — КЛЕТКИ РАНТАЙМА ЗАКРЕПЛЯЮТСЯ УСЛОВНО, ПО НУЖДЕ.
  //
  // Прежняя редакция держала `%b[10..15]` статически (`RESERVED_REGISTERS`), потому что бюджет входа
  // был `%b[0..9]`. С расширенным пулом эти клетки входят в бюджет значений, и статической полосы
  // больше нет: клетки, нужные рантайму, обязан закрепить ТОТ ЖЕ условный резерв, что у строк в
  // вызываемой. Признак расширения — пул адресует `%b[10]`: в прежней конфигурации (бюджет `%b[0..9]`)
  // множество ниже пусто, и закреплённые числа не двигаются ВООБЩЕ.
  //
  // ЧТО ИМЕННО ЗАКРЕПЛЯЕТСЯ (только у точки входа; у вызываемой — свой `CALLEE_REGISTERS`):
  //   • `%b[12]` — НОЛЬ рантайма (его читают печать, строки, массивы и выход), всегда;
  //   • `%b[10]`, `%b[11]`, `%b[13]` — временные строкового рантайма (`STRING_REGISTERS`), если в
  //     программе есть строковая операция (вход ИЛИ вызываемая — список `stringProcedures`);
  //   • `%b[10..15]` — блок рантайма массивов ТОЧКИ ВХОДА (`ENTRY_ARRAY_CELLS` + ячейка кучи), если
  //     точка входа работает с массивом. У вызываемой блок свой (её бюджет), поэтому здесь его нет;
  //   • `%b[0]` — НИЗКИЙ НОЛЬ разделённого сайта печати: без него `planPrintSite` ищет его среди
  //     живых значений и отказывает (`OSN-LOW-005`), как только низ занят;
  //   • `%b[10..15]` — полоса сайта рантайм-среза, если он есть (его клетки 1/2/3/15 закреплены
  //     отдельным механизмом, но 10..14 — тоже его).
  const arrayProcedures = arrayProceduresOf(
    emitted.instructions,
    emitted.scheduled.procedures,
    emitted.image.invokeNames,
  );
  const entryArray = arrayProcedures.includes(entryAt);
  const poolExpanded = ALLOCATABLE_REGISTERS.includes(10);
  const hasPrint = emitted.instructions.some((instruction) => {
    if (instruction.mnemonic !== 'IR.invoke') return false;
    const payload = instruction.operands[3];
    return (
      payload !== undefined &&
      payload.kind === 'imm' &&
      emitted.image.invokeNames[payload.value] === PRINT_CALL
    );
  });
  const entryRuntime = new Set<number>([
    // НОЛЬ — всегда: его читает и выход, и печать, и строки, и массивы.
    12,
    ...(stringsCalleeReserved
      ? [STRING_REGISTERS.first, STRING_REGISTERS.second, STRING_REGISTERS.write]
      : []),
    ...(entryArray
      ? [
          ENTRY_ARRAY_CELLS.zero,
          ENTRY_ARRAY_CELLS.one,
          ENTRY_ARRAY_CELLS.eight,
          ENTRY_ARRAY_CELLS.scratch,
          ENTRY_ARRAY_CELLS.scratch2,
          ARRAY_REGISTERS.heapSlot,
        ]
      : []),
    ...(poolExpanded && hasPrint ? [0] : []),
    ...(poolExpanded && sliceReserved ? [10, 11, 12, 13, 14, 15] : []),
  ]);
  // КАНАЛ ПАРЫ `Результат<Т, Е>` — РЕЗЕРВ УСЛОВНЫЙ, как у арены, коллекций и ячейки кучи.
  //
  // Почему он вообще нужен. Возврат пары кладёт нагрузку в СВОЮ клетку `1`, а её клетка `1` — это
  // клетка `2·wbs + 1` окна ВЫЗЫВАЮЩЕГО (`docs/abi-v3-draft.md` §10.2). В плоскости точки входа
  // бюджет значений — `%b[0..9]` (`ALLOCATABLE_REGISTERS`), то есть клетки канала `%b[8]`/`%b[9]`
  // входят в него. Значение, прожившее в `%b[9]` через такой вызов, было бы затёрто возвратом —
  // и это класс «тихая ложь»: отказов ноль, число неверное.
  //
  // Почему УСЛОВНЫЙ. Безусловный отнял бы у ядер две клетки и сдвинул закреплённые числа (458 / 53 /
  // 511, образ 6856, FIR 181) — ровно та цена, из-за которой условны резервы арены, коллекций и
  // ячейки кучи. Признак — носитель `IR.result_pick`: он есть ровно у программ с вызовом, отдающим
  // пару, и ни у одной другой.
  const pairChannel = emitted.instructions.some(
    (instruction) => instruction.mnemonic === 'IR.result_pick',
  );
  const reserved = [
    ...(arenaReserved ? arenaReservedRegisters() : []),
    ...(usesCollections(emitted.instructions, emitted.image.invokeNames) ? collectionReservedRegisters() : []),
    // АДРЕС ЯЧЕЙКИ КУЧИ — резерв по той же логике: он закреплён ЗА РАНТАЙМОМ МАССИВОВ, а не за
    // значениями программы (иначе пролог роста положил бы адрес, а раскладка отдала бы ту же клетку
    // под значение, и адрес был бы затёрт молча).
    ...(heapSlotReserved ? [ARRAY_REGISTERS.heapSlot] : []),
    // ОБЕ КЛЕТКИ КАНАЛА ПАРЫ: тег (`2·wbs`) и нагрузка (`2·wbs + 1`) — их пишет и вызывающий
    // (аргументы), и вызываемая (возврат), поэтому держать в них значения программы нельзя.
    ...(pairChannel ? [CALL_WBS * 2, CALL_WBS * 2 + 1] : []),
    // ВРЕМЕННЫЕ СТРОКОВОГО РАНТАЙМА — закреплены только у образов, где строка работает в вызываемой.
    // Ноль (`%b[12]`) в этот список НЕ входит: он закреплён у вызываемой своим механизмом (§3.166).
    ...(stringsCalleeReserved
      ? [STRING_REGISTERS.first, STRING_REGISTERS.second, STRING_REGISTERS.write]
      : []),
    // КЛЕТКИ САЙТА РАНТАЙМ-СРЕЗА: без них раскладка отдала бы их значениям программы, и петля
    // копирования затёрла бы эти значения МОЛЧА (сайт живёт в плоскости точки входа, где шесть
    // остальных его клеток — полоса `%b[10..15]` и одна клетка арены, уже закреплённые).
    ...(sliceReserved ? STRING_SLICE_DECLARED_CELLS : []),
  ];
  const allocation = allocateProgram(emitted.instructions, emitted.scheduled.procedures, {
    reserved,
    freeFor: (at) =>
      at === entryAt
        ? ALLOCATABLE_REGISTERS.filter((cell) => !entryRuntime.has(cell))
        : CALLEE_REGISTERS,
    // Блок рантайма массивов — по процедурам, которые с массивами работают (§3.128).
    arrayProcedures,
  });
  const report = allocation.report[0]!;
  // БУКВА D13 ИСПОЛНЕНА (PHASE-05/TASK-05-01): на отказе раскладки контрактный поток `instructions`
  // ПУСТ, а неразложенный поток лежит в отдельном поле `allocation.diagnostic`. Поэтому образ здесь
  // собирается по ДИАГНОСТИЧЕСКОМУ потоку: он ровно тот же, что прежде приходил в `instructions`
  // (те же носители, те же смещения процедур), — значит перепись носительных отказов, причины и шаги
  // остаются ТЕМИ ЖЕ числами, а «пусто» на контракте не превращается в «пусто в диагностике».
  // Наружу байты этого образа не уходят: ниже их гасит страж `отказРаскладки`.
  const диагностика = allocation.diagnostic;
  const поток = диагностика?.instructions ?? allocation.instructions;
  const процедурыПотока = диагностика?.procedures ?? allocation.procedures;
  // ОТКАЗ РАСКЛАДКИ ЛЮБОЙ ПРОЦЕДУРЫ ОБЯЗАН БЫТЬ НАЗВАН, а не только у `report[0]` (A4-5в, 2026-10-29).
  //
  // Почему это дефект, а не придирка. На отказе `allocateProgram` кладёт неразложенный поток
  // процедуры в ОТДЕЛЬНОЕ поле `diagnostic` (буква D13; прежде он уходил в `instructions`): носители
  // сохраняют регистры, которых раскладка не выдавала, и образ из них собирается ТОЛЬКО здесь, под
  // отказом ЯВНО. Значит образ с такой процедурой — мусор. Прежняя редакция читала ОДНУ запись
  // (`report[0]`), а она совпадает с точкой входа только тогда, когда точка входа объявлена первой:
  //
  // ЗАМЕР (2026-10-29; `.tmp/pins5v-callee-hole.ts`, `.tmp/pins5v-hole-diag.ts`): репро из
  // тривиальной первой процедуры `п` и вызываемой `ф` с 11 одновременно живыми отрезками давало
  // **0 отказов**, образ 776 байт и модель **9 вместо эталонных 77** (эталон подтверждён ОБЕИМИ VM:
  // стек и регистры 77); при этом `ф: ok=false`, «вытеснение не минимально: значений в память нужно
  // больше 4 … живы 14 отрезков, свободных 8», а `report[0]` = `п: ok=true`. На дереве HEAD `d311187`
  // (ДО починки распределителя `liveness.ts`) — те же 0 / 776 / 9: дыра ДОпочиночная, срез 5в её
  // только вскрыл. Сторож — `src/e2k/spillCallee.test.ts` П7.
  //
  // Канал — ЗАПИСЬ в `refused` (как у отказа раскладки вызываемой по имени, `calleeLimit`), а не
  // исключение: личность одна (`OSN-LOW-004`), а читателю не нужно ловить исключение, чтобы узнать,
  // что процедура не разложена. Записи о раскладке идут ПОСЛЕ отказов носителей: они называют
  // процедуру целиком, и порядок «сначала место, потом причина целиком» сохранён.
  const layoutRefusals = allocation.report
    .filter((item) => !item.ok)
    .map((item) =>
      refusalOf(
        LOWERING_CODES.layout,
        `раскладка отказала: процедура «${item.procedure}»: ${item.reason ?? 'причина не названа'}`,
      ),
    );
  const image = imageOfCarriers(поток, emitted.scheduled.constants, emitted.image.invokeNames, {
    // Адреса слотов вытеснения — своим ходом: сайты печати кладут сохранённое в ВЕРХ области
    // слотов, и пересечение обязано быть названным отказом, а не порчей значения.
    spilledAddresses: allocation.report.flatMap((item) => item.spilled.map((spilled) => spilled.address)),
    // Смещения процедур ПОСЛЕ раскладки: снятие копий и вытеснение их двигают, а адрес вызова
    // считается по ним — тем же способом, что цель перехода (docs/hardware-debt.md §3.35).
    procedures: процедурыПотока.map((procedure) => ({
      name: procedure.name,
      codeOffset: procedure.codeOffset,
    })),
    // БАЗЫ БЛОКОВ РАНТАЙМА МАССИВОВ — из раскладки: она решала, чьи клетки процедура занимает.
    arrayBases: allocation.arrayBases,
    // Слово о закреплении регистров — тому, кто раскладывал: разойдись оно с нуждой образа,
    // конвейер откажет по имени, а не соберёт образ с мусором вместо указателя арены.
    arenaReserved,
    // Слово о закреплении `%b[15]` за адресом ячейки кучи — по той же причине (A4 §3.137).
    heapSlotReserved,
    // Слово о закреплении ВРЕМЕННЫХ СТРОКОВОГО РАНТАЙМА в плоскости вызываемой (шаг 2.3, случай 73).
    stringsCalleeReserved,
    // ТИПЫ ПРОЦЕДУР — «Строка/Число ИЗ ТИПА» (шаг 2.3, ATOM-06-02-02а) — тот же список, что у разведки.
    procedureTypes: типыПроцедур,
    // ПОТОК НЕРАЗЛОЖЕН (отказ раскладки): носители сохраняют ВИРТУАЛЬНЫЕ регистры, поэтому сайт
    // рантайм-среза собирается, но его клетки НЕ сверяются — иначе проверка судила бы виртуальные
    // номера (замер шага 5: `%b[6]` выдан ролью «from»). Байты этого образа наружу не уходят (D13).
    diagnosticFlow: диагностика !== undefined,
    // СЛОВО О ЗАКРЕПЛЕНИИ КЛЕТОК САЙТА РАНТАЙМ-СРЕЗА (D24): разойдись оно с нуждой образа — конвейер
    // отказывает по имени, а не собирает образ, в котором петля копирования затирает значения программы.
    sliceReserved,
  });
  // ── D13: ЧИСЛА ПОД ОТКАЗОМ НЕ СУЩЕСТВУЕТ — БАЙТЫ НЕ ОТДАЮТСЯ ────────────────────────────────
  //
  // Отказ раскладки означает: поток остался НЕРАЗЛОЖЕННЫМ (носители сохраняют регистры, которых
  // раскладка не выдавала), поэтому образ из него — мусор, а число, посчитанное по такому образу, —
  // седьмая ложь (`src/e2k/calleeJoinLie.test.ts`). Здесь образ под отказом раскладки НЕ ОТДАЁТСЯ:
  // `bytes` пусты, и исполнить под отказом нечего.
  //
  // ПОЧЕМУ БАЙТЫ, А НЕ ВЕСЬ ОБРАЗ: отказы — сведения о ФОРМАХ, а не числа. Разложение 101 отказа тела
  // лексера (43 `объединить` + 39 вытеснение + 38 значения строк + 11 предикаты + 7 `подстрока`,
  // §3.138.4) считается здесь же и есть измерительный прибор плана среза 6. Замер
  // (`.tmp/a5z3-d13-cost-before.out.txt`): тело лексера = раскладка 1 + стадия 100, файл = 1 + 131 —
  // то есть у лексера раскладка ОТКАЗЫВАЕТ, и «пустой поток» на уровне `regAlloc.ts` унёс бы с собой
  // все 100/131 записи (замер редакции (A): тело 1, файл 1).
  //
  // БУКВА D13 ИСПОЛНЕНА (PHASE-05/TASK-05-01): `allocateProgram` отдаёт пустой контрактный поток и
  // неразложенный — отдельным полем (`diagnostic`); названная цена выше снята тем, что образ
  // собирается по диагностическому потоку (`поток` выше), а не по контракту: перепись осталась
  // целой (101/132/75), и ни одна из двух прежних цен (A и B2) не выплачивается.
  const отказРаскладки = allocation.report.some((item) => !item.ok);
  const образ: ReturnType<typeof imageOfCarriers> = отказРаскладки
    ? { ...image, bytes: new Uint8Array(0) }
    : image;
  // ДИАГНОСТИКА ОТКАЗА (D11) — то, чем публичная дверь (`src/e2k/lowered.ts`) отвечает ВМЕСТО байтов:
  // причина, список процедур и по записи на каждый отказ с именем процедуры и ШАГОМ. Ни одного байта
  // здесь не отдаётся: байты остаются в этом модуле и доступны только сторожу.
  //
  // Имя процедуры берётся у ЕЁ ПЕРВОГО носителя (`codeOffset`), а не из текста причины: текст — не
  // контракт, и переписанная формулировка молча ослепила бы читателя (`src/e2k/loweringRefusal.ts`).
  /** Место отказа по шагу: имя процедуры, в чей промежуток носителей попал шаг. */
  const место = (шаг: number): { процедура: string; шаг: number } => {
    // ОТКАЗ ДО ПОТОКА НОСИТЕЛЕЙ: имени процедуры у него нет, и выдумывать его нельзя — «шаг 0» указал
    // бы на ПЕРВУЮ процедуру потока, а причина стадии может называть носитель из другой (сторож поймал
    // это на теле лексера: 20 отказов стадий, у всех шаг 0). Поэтому честный ответ — «до потока».
    if (шаг < 0) return { процедура: '(до потока носителей)', шаг: 0 };
    const найдена = процедурыПотока.find(
      (процедура, индекс) =>
        шаг >= процедура.codeOffset &&
        (индекс + 1 >= процедурыПотока.length || шаг < процедурыПотока[индекс + 1]!.codeOffset),
    );
    return { процедура: найдена?.name ?? '(поток без процедур)', шаг };
  };
  const отказы: ОтказЗапись[] = [
    ...image.refused.map((отказ, индекс) => ({
      код: отказ.code,
      причина: отказ.reason,
      ...место(image.refusedSteps[индекс] ?? 0),
    })),
    ...allocation.report
      .filter((item) => !item.ok)
      .map((item) => ({
        код: LOWERING_CODES.layout,
        причина: `раскладка отказала: процедура «${item.procedure}»: ${item.reason ?? 'причина не названа'}`,
        процедура: item.procedure,
        шаг: процедурыПотока.find((п) => п.name === item.procedure)?.codeOffset ?? 0,
      })),
  ];
  return {
    ...образ,
    refused: [...image.refused, ...layoutRefusals],
    // ШАГ ЕСТЬ У КАЖДОГО ОТКАЗА, и у отказов раскладки тоже: они дописываются ЗДЕСЬ, уже после
    // `imageOfCarriers`, поэтому массив шагов приходится продолжить — иначе на один отказ приходилось
    // бы на один шаг меньше, и читатель молча свернул бы не туда (сторож поймал ровно это: 101 отказ,
    // 100 шагов на теле лексера). Шаг берётся из той же диагностики, что уезжает наружу, — значит
    // разойтись они не могут.
    refusedSteps: [...image.refusedSteps, ...отказы.slice(image.refused.length).map((запись) => запись.шаг)],
    отказы,
    used: report.used,
  };
}

