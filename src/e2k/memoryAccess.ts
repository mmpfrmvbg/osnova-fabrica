/**
 * ДОСТУП К ПАМЯТИ ПО АДРЕСУ-РЕГИСТРУ: `IR.load` И `IR.store`.
 *
 * # Зачем они нужны — замер, а не вкус
 *
 * В языке уже есть носители памяти — `IR.spill_ld`/`IR.spill_st` (`src/vliw/spill.ts`), — но они
 * адресуют **СЛОТ**, а не смещение: понижение (`src/e2k/e2kRealRun.ts`) сначала кладёт ЛИТЕРАЛЬНЫЙ
 * адрес слота в регистр-адрес (`movtd #слот, регистр`) и только потом делает `ldd регистр, ноль,
 * приёмник`. То есть регистр-адрес **затирается литералом**, и выразить `[база + индекс·8]` ими
 * нельзя. Годятся они ровно для одного случая — обращение по адресу, уже лежащему в регистре, со
 * смещением-нулём.
 *
 * Поэтому здесь два носителя с ОДНОЙ командой каждый:
 *
 * | носитель | понижение | что значит |
 * |---|---|---|
 * | `IR.load [адрес, приёмник]` | `ldd адрес, %b[12], приёмник` | прочитать по адресу |
 * | `IR.store [значение, адрес]` | `std значение, адрес, %b[12]` | записать по адресу |
 *
 * # Почему смещение — РЕГИСТР нуля, а не литерал
 *
 * Адрес в e2k — **сумма двух регистров** (`qemu/target/e2k/tcg/translate-al-c11.c:26-34`), поля
 * смещения в команде нет. Ноль берётся у рантайма массивов (`ARRAY_REGISTERS.zero` = `%b[12]`):
 * он зарезервирован от раскладки и заведён прологом ОБРАЗА у любой программы, то есть читать его
 * можно, не заводя (замер — §3.98.1). Литерала смещения не нужно, и `IR.const` для нуля тоже не
 * нужен.
 *
 * # Закон формы памяти соблюдён ПО ПОСТРОЕНИЮ
 *
 * Два регистра, считающие адрес, обязаны быть **разными** — иначе модель взводит исключение при
 * входе в блок, и обращение не исполняется вовсе (механизм и замер — шапка `ldd` в
 * `src/e2k/arrayRuntime.ts`). Здесь адрес считает один регистр, смещение — `%b[12]`, и это разные
 * регистры всегда. Сторож `memoryOperandPairProblems` это проверяет, и он же — материал
 * негативного контроля.
 *
 * # Адресация — 32-битная, и это НАЗВАННЫЙ долг, а не умолчание
 *
 * Адрес сюда приходит уже посчитанным, и считается он в `%b`-регистрах. Рантайм массивов считает
 * адреса `addd` (форма `D`, 64 бита) с 2026-09-27 — потому что `adds` (`S`) пишет только младшую
 * половину (§3.27). Здесь арифметики нет вовсе: приходит готовый адрес. Тот, кто его считает,
 * обязан считать `addd`; для коллекций это названо долгом в `docs/hardware-debt.md` §3.98.7.
 */

import type { AsmInstruction, Operand } from './backend';
import { ARRAY_REGISTERS } from './arrayRuntime';

const reg = (index: number): Operand => ({ kind: 'reg', index });

/** Носитель чтения по адресу-регистру. */
export const LOAD_CARRIER = 'IR.load';
/** Носитель записи по адресу-регистру. */
export const STORE_CARRIER = 'IR.store';

/** Команды чтения — ОДИН источник для раскладки (байты) и понижения (образ). */
export function loadInstructions(address: number, destination: number): AsmInstruction[] {
  return [
    {
      mnemonic: 'ldd',
      channel: 0,
      operands: [reg(address), reg(ARRAY_REGISTERS.zero), reg(destination)],
    },
  ];
}

/** Команды записи — тот же источник, что у чтения: разойтись нечем. */
export function storeInstructions(value: number, address: number): AsmInstruction[] {
  return [
    {
      mnemonic: 'std',
      channel: 2, // `st*` разрешены только в каналах 2 и 5 (opcodes/e2k-opc.h:969-984)
      operands: [reg(value), reg(address), reg(ARRAY_REGISTERS.zero)],
    },
  ];
}
