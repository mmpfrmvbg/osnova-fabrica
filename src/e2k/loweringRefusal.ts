/**
 * КОНТРАКТ КОДОВ ОТКАЗА ПОНИЖЕНИЯ `OSN-LOW-*`: ПРИЧИНА СТАНОВИТСЯ ЛИЧНОСТЬЮ, А НЕ СТРОКОЙ.
 *
 * # Зачем
 *
 * Конвейер цели собирает образ и **выбрасывает** носители, которые понизить не удалось: причины
 * уезжают в `refused`. До этого модуля они были СТРОКАМИ — а строка не различает причины: текст
 * несёт ЗНАЧЕНИЕ (`константа пула #0 = Аня`), поэтому один и тот же отказ на разных данных даёт
 * разные строки, а разные отказы могут совпасть по формулировке. Измерено наблюдателем
 * (`src/scripts/e2kLoweringDiagnostics.ts`): класс отказа приходилось выводить по ТЕКСТУ таблицей
 * регулярок — то есть переписанная формулировка молча ослепляла наблюдателя.
 *
 * Теперь отказ — запись {@link LoweringRefusal}: **код** плюс причина для человека. Код выбирает
 * тот, кто отказ ПРИНЯЛ (стадия конвейера или вид нарушения), а не тот, кто читает текст.
 *
 * # Пространство кодов — по ПРИЧИНЕ, не по носителю
 *
 * Один и тот же носитель отказывает по разным причинам: `IR.invoke` — и за отсутствие операции в
 * рантайме (003), и за неподъёмную константу (002), и за нарушенную форму самого носителя (007).
 * Поэтому код выдаётся причине, и `IR.rem` («формы нет») и `IR.const` со строкой («константа
 * невыразима») — разные коды, хотя оба про один и тот же конвейер.
 *
 * | код | причина | кто выдаёт |
 * |---|---|---|
 * | `OSN-LOW-001` | у носителя нет формы понижения (нет правила в таблице) | `lowerInstruction`, `layoutOf` |
 * | `OSN-LOW-002` | константа невыразима: литералом e2k кодируются только целые 16/32 бита | `literalOf` |
 * | `OSN-LOW-003` | операция не поддержана рантаймом (массивы/математика) или носителем вызова | `lowerCarrier`, `carrierFormWithReason` |
 * | `OSN-LOW-004` | раскладка: нет адреса/смещения, пара предикатов не составилась, нет регистров | `secondPass`, `pairPredicates`, `allocateProgram` |
 * | `OSN-LOW-005` | печать: сайт не собирается (нет регистра под адрес, слоты заняты, код доходит до площадки) | `src/e2k/printCall.ts` |
 * | `OSN-LOW-006` | обвязка: возвратов со значением больше одного | `src/scripts/e2kProgramRun.ts` |
 * | `OSN-LOW-007` | контракт конвейера нарушен: носитель или контекст не той формы | `lowerCarrier`, `carrierFormWithReason` |
 *
 * **Почему 007, а не «ещё одна форма 001».** 001 означает «язык этого ещё не умеет» — это долг
 * плоскости. 007 означает «конвейер получил инструкцию, нарушающую его же контракт» — это признак
 * ДЕФЕКТА, а не долга. Слить их значило бы спрятать дефект за незнанием языка: например,
 * `IR.invoke` без списка имён вызовов в контексте — не «нет формы», а «контекст не передан».
 * Число кодов поэтому семь, а не шесть предложенных: шестое предложение (§11.3 `docs/diagnostics-v1.md`)
 * названо и обосновано здесь.
 *
 * # Как это держится
 *
 * - **Типом.** {@link LoweringFailure} требует `code`: забыть код нельзя — `tsc` не пропустит.
 * - **Таблицей.** У каждого кода есть человеческое имя и класс ({@link LOWERING_CODE_MEANINGS},
 *   {@link LOWERING_CODE_CLASSES}); сторож `src/e2k/loweringRefusal.test.ts` проверяет, что код
 *   уникален, описан и что подмена ТЕКСТА класса не меняет, а подмена КОДА — меняет.
 * - **Читателем.** Наблюдатель берёт класс ИЗ КОДА (`src/scripts/e2kLoweringDiagnostics.ts`),
 *   таблицы по тексту причины у него больше нет.
 *
 * # Границы
 *
 * - Код описывает ОТКАЗ ПОНИЖЕНИЯ, а не отказ языка: у языка свой канал (`OSN-PAR-*`, `OSN-SEM-*`),
 *   и он приходит из компилятора, а не отсюда.
 * - Носитель и номер в записи не выносятся отдельными полями: они остаются в тексте причины
 *   (`#2 IR.rem: …`), как и было, — это разрешено контрактом (§11.3) и не ломает читателей текста.
 */

import { описаниеПоСсылке, type IRSourceRef } from "../runtime/vm/sourceMap";

/** Коды отказа понижения — единственный источник истины для плоскости `src/e2k/**`. */
export const LOWERING_CODES = {
  /** 001: у носителя нет формы понижения (нет правила в таблице понижения и формы в раскладке). */
  noForm: 'OSN-LOW-001',
  /** 002: константа невыразима — литералом e2k кодируются только целые 16- и 32-битные значения. */
  constant: 'OSN-LOW-002',
  /** 003: операция не поддержана рантаймом (массивы, математика) или носителем вызова. */
  runtime: 'OSN-LOW-003',
  /** 004: раскладка — нет регистров, нет адреса/смещения, пара предикатов не составилась. */
  layout: 'OSN-LOW-004',
  /** 005: печать — сайт печати не собирается (см. `src/e2k/printCall.ts`). */
  print: 'OSN-LOW-005',
  /** 006: обвязка — возвратов со значением больше одного (обход через регистр неверен). */
  wrapper: 'OSN-LOW-006',
  /** 007: контракт конвейера нарушен — носитель или контекст не той формы (признак дефекта). */
  carrier: 'OSN-LOW-007',
} as const;

/** Код отказа понижения. */
export type LoweringRefusalCode = (typeof LOWERING_CODES)[keyof typeof LOWERING_CODES];

/** Все коды списком — для сторожей и для читателей, которым нужен перечень. */
export const LOWERING_CODE_LIST: readonly LoweringRefusalCode[] = Object.values(LOWERING_CODES);

/**
 * Человеческое имя каждого кода. Одна строка на код: код без имени — дырка в контракте,
 * и сторож `src/e2k/loweringRefusal.test.ts` её ловит.
 */
export const LOWERING_CODE_MEANINGS: Readonly<Record<LoweringRefusalCode, string>> = {
  'OSN-LOW-001': 'у носителя нет формы понижения',
  'OSN-LOW-002': 'константа невыразима: литералом e2k кодируются только целые 16/32 бита',
  'OSN-LOW-003': 'операция не поддержана рантаймом (массивы/математика) или носителем вызова',
  'OSN-LOW-004': 'раскладка: нет адреса/смещения, пары предикатов или свободных регистров',
  'OSN-LOW-005': 'печать: сайт печати не собирается',
  'OSN-LOW-006': 'обвязка: возвратов со значением больше одного',
  'OSN-LOW-007': 'контракт конвейера нарушен: носитель или контекст не той формы',
};

/**
 * Класс отказа для человека — ИМЯ КОДА, а не вывод из текста.
 *
 * Читатель (наблюдатель) берёт класс отсюда: подмена текста причины класс не меняет, подмена
 * кода — меняет. Это и есть требуемый негативный контроль контракта.
 */
export const LOWERING_CODE_CLASSES: Readonly<Record<LoweringRefusalCode, string>> = {
  'OSN-LOW-001': 'носитель-без-формы',
  'OSN-LOW-002': 'константа-невыразима',
  'OSN-LOW-003': 'вызов-вне-рантайма',
  'OSN-LOW-004': 'раскладка',
  'OSN-LOW-005': 'печать',
  'OSN-LOW-006': 'обвязка',
  'OSN-LOW-007': 'контракт-конвейера',
};

/**
 * Запись об отказе понижения: код (личность) и причина (для человека).
 *
 * Это КЛАСС, а не просто форма записи, ради одного свойства: строкой запись печатается как
 * `КОД: причина`, а не как `[object Object]`. Отказы печатают и оракулы, и отчёты, и увидеть
 * в сообщении «объект» вместо причины — ровно та немая диагностика, против которой этот контракт.
 */
export class LoweringRefusal {
  constructor(
    readonly code: LoweringRefusalCode,
    /** Текст причины; место отказа (`#2 IR.rem: …`) остаётся в нём, как и было до контракта. */
    readonly reason: string,
  ) {}

  toString(): string {
    return describeRefusal(this);
  }
}

/** Отказ понижения как результат шага конвейера: код обязателен, забыть его нельзя. */
export interface LoweringFailure {
  readonly ok: false;
  readonly code: LoweringRefusalCode;
  readonly reason: string;
}

/** Собрать запись отказа: код выбирает тот, кто отказ принял. */
export function refusalOf(code: LoweringRefusalCode, reason: string): LoweringRefusal {
  return new LoweringRefusal(code, reason);
}

/** Собрать отказ шага конвейера. */
export function failureOf(code: LoweringRefusalCode, reason: string): LoweringFailure {
  return { ok: false, code, reason };
}

/**
 * ОТКАЗ, КОТОРЫЙ БРОСАЮТ, А НЕ ОТДАЮТ ЗАПИСЬЮ: раскладка не удалась — образ не собирается вовсе.
 *
 * Тот же код, что у записи: канал разный (исключение против `refused`), личность одна.
 */
export class LoweringRefusalError extends Error {
  constructor(
    readonly code: LoweringRefusalCode,
    message: string,
  ) {
    super(message);
    this.name = 'LoweringRefusalError';
  }
}

/** Назван ли значением контракта: читатель проверяет ДАННЫЕ, а не доверяет типу. */
export function isLoweringRefusalCode(value: unknown): value is LoweringRefusalCode {
  return typeof value === 'string' && (LOWERING_CODE_LIST as readonly string[]).includes(value);
}

/**
 * Код отказа у брошенного исключения — по ПОЛЮ `code`, а не по имени класса и не по тексту.
 *
 * Так контракт читается единообразно: `PrintCallRefusal` (005), `LoweringRefusalError` (004),
 * `MultiReturnRefusal` (006) несут один и тот же признак, и наблюдателю не нужна таблица классов
 * исключений.
 */
export function codeOfThrown(error: unknown): LoweringRefusalCode | undefined {
  if (typeof error !== 'object' || error === null) return undefined;
  const code = (error as { code?: unknown }).code;
  return isLoweringRefusalCode(code) ? code : undefined;
}

/** Запись отказа строкой — для человека: `OSN-LOW-001: у носителя нет формы понижения`. */
export function describeRefusal(refusal: LoweringRefusal): string {
  return `${refusal.code}: ${refusal.reason}`;
}

/**
 * Отказ, КОТОРЫЙ НАЗЫВАЕТ ИСХОДНИК, а не внутреннее имя.
 *
 * # Зачем именно здесь
 *
 * Отказ собирается на стадии носителя (`src/e2k/programImage.ts`), и до этой правки он говорил
 * словами конвейера: «раскладка не выдала базу блока рантайма (операнд 6 носителя)»,
 * «`система.массив.получить`». Человек, написавший `лента[индекс]`, не писал ни одного из этих
 * слов. Карта источника (`src/runtime/vm/sourceMap.ts`) даёт обратное отображение, и здесь оно
 * ставится ПЕРЕД причиной: `лента[индекс], строка 5, колонка 3 — <прежняя причина>`.
 *
 * # Почему прежняя причина остаётся ЦЕЛИКОМ
 *
 * Потому что она несёт то, чего в исходнике нет: номер носителя, имя операции, число занятых
 * клеток. Заменить её значило бы потерять диагностику; дописать перед ней источник — сложить
 * «что человек написал» и «что случилось в конвейере». Поэтому формат — `источник — причина`,
 * а не «источник вместо причины».
 *
 * # Запасной путь
 *
 * Ссылки нет или реестр её не знает — текст остаётся БАЙТ В БАЙТ прежним. Это не «ухудшение», а
 * условие совместимости: у программ без карты источника (v2-фронтенд, рукописные носители)
 * сообщения не должны меняться, и это проверено сторожем.
 */
export function refusalWithSource(
  code: LoweringRefusalCode,
  reason: string,
  sourceRef: IRSourceRef | undefined,
): LoweringRefusal {
  const описание = описаниеПоСсылке(sourceRef);
  if (описание === undefined) return refusalOf(code, reason);
  // ИСТОЧНИК НЕ ДОБАВЛЯЕТСЯ ДВАЖДЫ. Часть причин приходит уже с источником: их называет тот, кто
  // отказ ПРИНЯЛ, — например рантайм массивов (`src/e2k/arrayRuntime.ts#lowerArrayCall`), где ссылка
  // есть прямо в доводах. Без этой проверки текст стал бы
  // `лента[индекс], строка 6, колонка 10 — лента[индекс], строка 6, колонка 10 — …`.
  if (reason.startsWith(`${описание} — `)) return refusalOf(code, reason);
  return refusalOf(code, `${описание} — ${reason}`);
}
