import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { compileToReg } from '../compiler/regcodegen';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { loweredProgram } from '../e2k/programImage';
import { isRegPacket, type RegCodeElement } from '../runtime/vm/regcode';

const ФАЙЛ = 'булевы.osnova';
const опцииV3 = (src: string) => {
  const р = parseV3(src, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Модуль регистрового кодогена — из того же фронтенда, что и понижение. */
function модуль(src: string) {
  const р = parseV3(src, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  return compileToReg(м);
}

/** Все инструкции модуля: код плоский, пакеты разворачиваются. */
function инструкции(элементы: readonly RegCodeElement[]): RegCodeElement[] {
  return элементы.flatMap((элемент) => (isRegPacket(элемент) ? элемент.slots : [элемент]));
}

/** Собирается ли программа на цель: либо отказы, либо исключение оболочки — оба названы. */
function собрать(src: string): { отказы: string[]; беда: string | undefined; байт: number } {
  try {
    const образ = loweredProgram(src, опцииV3(src));
    return { отказы: образ.refused.map((item) => `${item.code ?? '—'} ${item.reason}`), беда: undefined, байт: образ.bytes.length };
  } catch (error) {
    return { отказы: [], беда: error instanceof Error ? error.message : String(error), байт: 0 };
  }
}

describe('логические литералы v3 идут через пул, а не своей операцией', () => {
  it('кодоген не выдаёт `const.true`/`const.false`/`const.null` — у них нет носителя ни у одной оболочки', () => {
    const м = модуль(`действие главная()
  пусть т = да
  пусть л = нет
  пусть п = пусто
  если т и не л
    вернуть 1
  конец если
  вернуть 0
конец
`);
    const операции = инструкции(м.code).map((инструкция) => инструкция.op);
    expect(операции).not.toContain('const.true');
    expect(операции).not.toContain('const.false');
    expect(операции).not.toContain('const.null');
    // И значения ДЕЙСТВИТЕЛЬНО лежат в пуле: иначе «нет операции» ничего не значит.
    expect(м.constants).toContain(true);
    expect(м.constants).toContain(false);
    expect(м.constants).toContain(null);
    const булевы = инструкции(м.code).filter(
      (инструкция) => инструкция.op === 'const' && инструкция.type === 'bool',
    );
    expect(булевы.length).toBeGreaterThan(0);
  });

  it('программа с `и`, `или`, `нет` и булевыми литералами собирается на цель без отказов', () => {
    const итог = собрать(`действие главная()
  пусть а = 3
  пусть б = 5
  пусть н = 0
  если а < 4 и б < 6
    н = н + 1
  конец если
  если 1 > 2 или б == 5
    н = н + 10
  конец если
  пусть т = нет
  если не т
    н = н + 100
  конец если
  вернуть н
конец
`);
    expect(итог.беда, `оболочка остановилась: ${String(итог.беда)}`).toBeUndefined();
    expect(итог.отказы).toEqual([]);
    expect(итог.байт).toBeGreaterThan(100);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: пул без булевых значений обязан быть виден — проверка различает', () => {
    // Контроль на то, что проверка выше не «зелена всегда»: программа, где булевых литералов НЕТ
    // вовсе, не должна давать ни `const` типа `bool`, ни булевых значений в пуле. Если бы первая
    // проверка ловила любое `const`, она была бы мёртвой — этот опыт это и показывает.
    const м = модуль(`действие главная()
  пусть а = 3
  пусть н = 0
  если а < 4
    н = 1
  конец если
  вернуть н
конец
`);
    const булевы = инструкции(м.code).filter(
      (инструкция) => инструкция.op === 'const' && инструкция.type === 'bool',
    );
    expect(булевы).toEqual([]);
    expect(м.constants).not.toContain(true);
    expect(м.constants).not.toContain(false);
  });
});

describe('стены лексера названы по имени (не чинятся здесь)', () => {
  it('ИНДЕКСАЦИЯ СТРОКИ БОЛЬШЕ НЕ СТЕНА: `с[и]` понижается в код символа', () => {
    // Прежняя редакция этой проверки требовала ОТКАЗА `система.строка.символ`. Стена пала
    // 2026-10-23 (решение владельца: `с[и]` — Число, код Unicode). Здесь остаётся ровно то, что
    // было смыслом прежней проверки — «понижение не останавливает оболочку», но уже с обратным
    // знаком: отказа быть НЕ ДОЛЖНО, а поведение кода символа стережёт `src/e2k/stringSymbol.test.ts`.
    const итог = собрать(`действие главная()
  пусть с = "абв"
  пусть н = 0
  если с[1] == 1073
    н = 1
  конец если
  вернуть н
конец
`);
    expect(итог.беда, 'это понижение, а не останов оболочки').toBeUndefined();
    expect(итог.отказы, 'индексация строки понижается').toEqual([]);
    expect(итог.байт).toBeGreaterThan(100);
  });

  it('поиск подстроки `содержит` не понижается', () => {
    const итог = собрать(`действие главная()
  пусть н = 0
  если содержит "б" в "абв"
    н = 1
  конец если
  вернуть н
конец
`);
    expect(итог.беда, 'эта стена обязана быть ОТКАЗОМ, а не остановом оболочки').toBeUndefined();
    expect(итог.отказы.join('\n')).toContain('система.строка.содержит');
  });

  it('склейка ТРЁХ строк в вызываемой невозможна: рантайм держит состояние вне её окна', () => {
    // Форма взята у лексера дословно (`с_токеном`): три строковых параметра и склейка. Вызываемая
    // обязана быть ВЫЗВАНА — недостижимую процедуру понижение не трогает, и проверка была бы мёртвой.
    const итог = собрать(`процедура с_токеном(поток: Строка, вид: Строка, лексема: Строка) → Строка
  вернуть поток + вид + "|" + лексема + "\\n"
конец

действие главная()
  пусть т = с_токеном("", "имя", "сумма")
  вернуть 0
конец
`);
    const все = `${итог.беда ?? ''}\n${итог.отказы.join('\n')}`;
    expect(все).toMatch(/строковая операция в вызываемой|система\.строка\.объединить/);
  });

  it('КОНТРОЛЬ ГРАНИЦЫ: склейка ДВУХ строк в вызываемой проходит — стена не «на всё»', () => {
    // Этот опыт и делает проверку выше различающей: она красна не оттого, что «в вызываемой
    // строки вообще запрещены», а от числа строковых величин, которые рантайм держит одновременно.
    const итог = собрать(`процедура ф(вид: Строка, лексема: Строка) → Строка
  вернуть вид + "|" + лексема
конец

действие главная()
  пусть т = ф("имя", "сумма")
  вернуть 0
конец
`);
    expect(итог.беда, `оболочка остановилась: ${String(итог.беда)}`).toBeUndefined();
    expect(итог.отказы).toEqual([]);
  });

  it('длина строки-ПАРАМЕТРА не берётся: длина известна только на сборке', () => {
    const итог = собрать(`процедура ф(с: Строка) → Число
  вернуть длина с
конец

действие главная()
  пусть н = ф("абв")
  вернуть н
конец
`);
    expect(итог.отказы.join('\n')).toContain('система.строка.длина');
  });
});
