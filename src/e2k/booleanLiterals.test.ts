import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
import { compileToReg } from '../compiler/regcodegen';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { loweredProgram } from '../e2k/programImage';
import { isRegPacket, type RegCodeElement } from '../runtime/vm/regcode';

const ФАЙЛ = 'булевы.osnova';
const опцииV3 = (src: string) => {
  const р = parseV3(src, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Модуль регистрового кодогена — из того же фронтенда, что и понижение. */
function модуль(src: string) {
  const р = parseV3(src, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  return compileToReg(м);
}

/** Все инструкции модуля: код плоский, пакеты разворачиваются. */
function инструкции(элементы: readonly RegCodeElement[]): RegCodeElement[] {
  return элементы.flatMap((элемент) => (isRegPacket(элемент) ? элемент.slots : [элемент]));
}

/** Собирается ли программа на цель: либо отказы, либо исключение оболочки — оба названы. */
function собрать(src: string): { отказы: string[]; беда: string | undefined; байт: number } {
  try {
    const образ = loweredProgram(src, опцииV3(src));
    return { отказы: образ.refused.map((item) => `${item.code ?? '—'} ${item.reason}`), беда: undefined, байт: образ.bytes.length };
  } catch (error) {
    return { отказы: [], беда: error instanceof Error ? error.message : String(error), байт: 0 };
  }
}

describe('логические литералы v3 идут через пул, а не своей операцией', () => {
  it('кодоген не выдаёт `const.true`/`const.false`/`const.null` — у них нет носителя ни у одной оболочки', () => {
    const м = модуль(`действие главная()
  пусть т = да
  пусть л = нет
  пусть п = пусто
  если т и не л
    вернуть 1
  конец если
  вернуть 0
конец
`);
    const операции = инструкции(м.code).map((инструкция) => инструкция.op);
    expect(операции).not.toContain('const.true');
    expect(операции).not.toContain('const.false');
    expect(операции).not.toContain('const.null');
    // И значения ДЕЙСТВИТЕЛЬНО лежат в пуле: иначе «нет операции» ничего не значит.
    expect(м.constants).toContain(true);
    expect(м.constants).toContain(false);
    expect(м.constants).toContain(null);
    const булевы = инструкции(м.code).filter(
      (инструкция) => инструкция.op === 'const' && инструкция.type === 'bool',
    );
    expect(булевы.length).toBeGreaterThan(0);
  });

  it('СТОРОЖ НАЗЫВАЕТ ПРИЧИНУ: отказ ЧЕСТНЫЙ (было 0 отказов и ЛОЖЬ на 3 из 4 входов)', () => {
    // ── СДВИГ 2026-10-29 (A4-5в): починка распределителя `src/e2k/liveness.ts`
    // (`mergeLoopCarriedSegments` — слияние отрезков через ПРЯМУЮ дугу, sha256 `CCCD4F4F…`) ────────
    //
    // Прежняя редакция этой проверки требовала «собирается без отказов». Это утверждение СТАЛО
    // ЛОЖНЫМ, и заменено оно не ослаблением, а утверждением о ТОЙ ЖЕ границе в новых условиях:
    // сторож обязан НАЗВАТЬ причину, а не молчать.
    //
    // ПОЧЕМУ СДВИНУЛОСЬ, а не «посторонняя правка»: до починки отрезки одного значения, разделённые
    // ребром взятого перехода, раскладка вправе была раздать РАЗНЫМ клеткам — и цель читала клетку,
    // которую пишет пропущенная ветвь. Починка слила такие отрезки, и сторож пар предикатов
    // (`src/e2k/predicatePairing.ts`, включён срезом 5б) увидел ровно то, что раньше было скрыто.
    //
    // ЗАМЕР ДО ПОЧИНКИ — мой прогон на дереве HEAD `d311187` (отдельный worktree
    // `%TEMP%\a5v-prefix-wt`, `liveness.ts` sha256 `6F541F29…`), инструмент `.tmp/pins5v-measure.ts`,
    // разделы 2–3; тот же инструмент на рабочем дереве даёт числа «после»:
    //   ДО:  отказов **0**, образ 504 байта — и матрица четырёх входов дала **три неверных числа из
    //        четырёх** (модель против эталона ОБЕИХ VM, которые совпали на каждом входе):
    //        а=3 б=5 → 111 = 111 (верно); а=3 б=7 → **107 вместо 100**; а=7 б=5 → **117 вместо 110**;
    //        а=7 б=7 → **107 вместо 100**;
    //   ПОСЛЕ: отказов **2**, оба `OSN-LOW-004`, на КАЖДОМ из тех же четырёх входов (проверка ниже).
    // То есть проверка краснеет там, где прежнее утверждение опиралось на тихую ложь; ложь названа
    // числом (107/117/107 против 100/110/100), и вернуть её нельзя — это D4.
    const итог = собрать(`действие главная()
  пусть а = 3
  пусть б = 5
  пусть н = 0
  если а < 4 и б < 6
    н = н + 1
  конец если
  если 1 > 2 или б == 5
    н = н + 10
  конец если
  пусть т = нет
  если не т
    н = н + 100
  конец если
  вернуть н
конец
`);
    expect(итог.беда, `сторож — ОТКАЗ понижения, а не останов оболочки: ${String(итог.беда)}`).toBeUndefined();
    expect(итог.отказы.length, 'отказов сторожа').toBe(2);
    expect(
      итог.отказы.every((о) => о.startsWith('OSN-LOW-004')),
      `оба отказа — раскладки (004), а не рантайма: ${итог.отказы.join(' | ')}`,
    ).toBe(true);
    expect(итог.отказы[0] ?? '', 'первая причина — «склейка» на ребре взятого перехода').toContain('#17 IR.gt');
    expect(итог.отказы[0] ?? '').toContain('склейка');
    expect(итог.отказы[1] ?? '', 'вторая — условие перешло не из сравнения').toContain('#18 IR.jmp_if');
    expect(итог.отказы[1] ?? '').toContain('пришло не из сравнения');
    // Байты при отказе считаются, но годным образом НЕ являются: их никто не исполняет. Это
    // сохранённый признак прежней проверки (образ строился), переставленный на своё место.
    expect(итог.байт).toBeGreaterThan(100);
  });

  it('МАТРИЦА ВХОДОВ: отказ не зависит от значений — и это ОТЛИЧИЕ от прежней тихой лжи', () => {
    // Тот же ЗАМЕР, что нашёл ложь до починки (`.tmp/pins5v-measure.ts`, раздел 3), но теперь
    // предъявленный как сторож: на КАЖДОМ входе отказ один и тот же. Смысл именно в паре:
    //   ДО починки на этих четырёх входах отказов было 0, а числа — 111 / 107 / 117 / 107;
    //   ПОСЛЕ — два отказа на каждом входе, и числа не считаются вовсе (образа нет).
    // Без этой проверки «отказывает» было бы не отличить от «отказывает на одном удачно выбранном входе».
    const матрица = (а: number, б: number): string => `действие главная()
  пусть а = ${String(а)}
  пусть б = ${String(б)}
  пусть н = 0
  если а < 4 и б < 6
    н = н + 1
  конец если
  если 1 > 2 или б == 5
    н = н + 10
  конец если
  пусть т = нет
  если не т
    н = н + 100
  конец если
  вернуть н
конец
`;
    for (const [а, б] of [[3, 5], [3, 7], [7, 5], [7, 7]] as const) {
      const итог = собрать(матрица(а, б));
      expect(итог.беда, `а=${String(а)} б=${String(б)}: отказ, а не останов оболочки`).toBeUndefined();
      expect(итог.отказы.length, `а=${String(а)} б=${String(б)}: отказов`).toBe(2);
      expect(итог.отказы[0] ?? '', `а=${String(а)} б=${String(б)}: первая причина`).toContain('IR.gt');
      expect(итог.отказы[1] ?? '', `а=${String(а)} б=${String(б)}: вторая причина`).toContain('IR.jmp_if');
    }
    // НЕГАТИВНЫЙ КОНТРОЛЬ: отказ не «на всё с `и`/`или`» — программа той же формы с ОДНИМ сравнением
    // в условии собирается без отказов. Иначе «сторож называет причину» ничего не различал бы.
    const контроль = собрать(`действие главная()
  пусть а = 3
  пусть н = 0
  если а < 4
    н = н + 1
  конец если
  вернуть н
конец
`);
    expect(контроль.беда, `оболочка остановилась: ${String(контроль.беда)}`).toBeUndefined();
    expect(контроль.отказы, 'одно сравнение в условии').toEqual([]);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: пул без булевых значений обязан быть виден — проверка различает', () => {
    // Контроль на то, что проверка выше не «зелена всегда»: программа, где булевых литералов НЕТ
    // вовсе, не должна давать ни `const` типа `bool`, ни булевых значений в пуле. Если бы первая
    // проверка ловила любое `const`, она была бы мёртвой — этот опыт это и показывает.
    const м = модуль(`действие главная()
  пусть а = 3
  пусть н = 0
  если а < 4
    н = 1
  конец если
  вернуть н
конец
`);
    const булевы = инструкции(м.code).filter(
      (инструкция) => инструкция.op === 'const' && инструкция.type === 'bool',
    );
    expect(булевы).toEqual([]);
    expect(м.constants).not.toContain(true);
    expect(м.constants).not.toContain(false);
  });
});

