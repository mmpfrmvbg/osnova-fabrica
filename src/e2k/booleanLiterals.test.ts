import { describe, expect, it } from 'vitest';
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { compile } from '../compiler/codegen';
import { compileToReg } from '../compiler/regcodegen';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { loweredProgram } from './programImage';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { RegVM } from '../runtime/vm/reginterpreter';
import { isRegPacket, type RegCodeElement } from '../runtime/vm/regcode';

const ФАЙЛ = 'булевы.osnova';
const ROOT = path.resolve(__dirname, '..', '..');
const shim = buildShim();
const опцииV3 = (src: string) => {
  const р = parseV3(src, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
};

/** Модуль регистрового кодогена — из того же фронтенда, что и понижение. */
function модуль(src: string) {
  const р = parseV3(src, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  return compileToReg(м);
}

/** Все инструкции модуля: код плоский, пакеты разворачиваются. */
function инструкции(элементы: readonly RegCodeElement[]): RegCodeElement[] {
  return элементы.flatMap((элемент) => (isRegPacket(элемент) ? элемент.slots : [элемент]));
}

/** Собирается ли программа на цель: либо отказы, либо исключение оболочки — оба названы. */
function собрать(src: string): { отказы: string[]; беда: string | undefined; байт: number } {
  try {
    const образ = loweredProgram(src, опцииV3(src));
    return { отказы: образ.refused.map((item) => `${item.code ?? '—'} ${item.reason}`), беда: undefined, байт: образ.bytes.length };
  } catch (error) {
    return { отказы: [], беда: error instanceof Error ? error.message : String(error), байт: 0 };
  }
}

/**
 * Тот же сбор, но образ ещё и ИСПОЛНЯЕТСЯ на модели (шим может отсутствовать — тогда `код` не определён).
 *
 * Нужен там, где вопрос не «отказывает ли», а «КАКОЕ ЧИСЛО»: срез 5г снял отказ у двух проб ниже, и
 * без прогона «отказов 0» ничего не значило бы (ровно так эта проверка и была зелёной поверх лжи).
 */
function собратьИПрогнать(src: string): { отказы: string[]; беда: string | undefined; байт: number; код: number | undefined } {
  const итог = собрать(src);
  if (итог.беда !== undefined || итог.отказы.length > 0 || shim === undefined) return { ...итог, код: undefined };
  const образ = loweredProgram(src, опцииV3(src));
  const elf = buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
  const имя = crypto.createHash('sha256').update(src, 'utf8').digest('hex').slice(0, 12);
  const файл = path.join(ROOT, '.tmp', `boolean-literals-${имя}.elf`);
  fs.writeFileSync(файл, elf.bytes);
  return { ...итог, код: runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status ?? undefined };
}

/** Число логической пробы ОБЕИМИ VM языка — независимый эталон (булево → 1/0). */
async function обеVM(src: string): Promise<readonly [number | undefined, number | undefined]> {
  const р = parseV3(src, ФАЙЛ);
  expect(р.errors, `разбор эталона: ${р.errors.join('; ')}`).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  const число = (значение: unknown): number | undefined => {
    if (значение === true) return 1;
    if (значение === false) return 0;
    return typeof значение === 'number' ? значение : undefined;
  };
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  return [
    число(await стековая.runProcedure(стековая.findProcedureIndex('главная'), [])),
    число(await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), [])),
  ];
}

