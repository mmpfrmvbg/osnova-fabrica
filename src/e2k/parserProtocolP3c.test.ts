/**
 * ШАГ P3c: рекурсивный спуск с post-order — ЧТО ИЗМЕРЕНО (2026-11-10).
 *
 * 1. СПУСК РАБОТАЕТ. Три уровня (`выражение` → `слагаемое` → `множитель`) только читают ленту
 *    токенов, и проба `программаСпускаP3c` на МОДЕЛИ возвращает 33 — вид токена `конец`, на
 *    котором кончилось выражение `2 + 3 * 4`. Два прогона, одно число.
 * 2. ПРОТОКОЛ ЗЕЛЁНЫЙ: проба «по событию» (`программаПротоколаP3cПоСобытиям`) собирается БЕЗ
 *    отказов и на МОДЕЛИ печатает ЭТАЛОННУЮ ленту клетка в клетку (69), код возврата 0 — два
 *    прогона кряду.
 * 3. Стена §18 (писатель ГРУППЫ с упаковкой пары) — измеренная граница, а не «не успели»: она
 *    остаётся отказом и закреплена ниже отдельной проверкой. Причина названа замером
 *    (`.tmp/p3c-writer-diagnose.md`): база блока рантайма массивов выдаётся ОДИН раз на процедуру
 *    (`src/e2k/regAlloc.ts#chooseArrayBlock`), поэтому стена — размер ЖИВОГО НАБОРА писателя:
 *    упаковка пары (`нацело 4096` + `% 4096`, а `%` — `IR.rem`, он резервирует регистр) стоила
 *    ~4 клеток из 15, и тройки под базу не оставалось. Протокол пишет ГРУППАМИ по ≤5 клеток
 *    (`.tmp/p3c-writer-diagnose.md` §5), и база выдаётся всем 15 процедурам.
 */
import * as fs from "fs";
import * as path from "path";
import { describe, expect, it } from "vitest";
import { parseV3 } from "../compiler-v3";
import { loweredProgram } from "../e2k/lowered";
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from "../e2k/elfMinimal";
import { runInQemu } from "../scripts/e2kQemuExec";
import {
  ИСХОДНИК_P3C,
  ФАЙЛ_P3C,
  программаПротоколаP3c,
  программаПротоколаP3cПоСобытиям,
  программаСпускаP3c,
  эталоннаяЛента,
} from "../compiler-v3/parser-protocol-probe";

function опустить(источник: string) {
  const разбор = parseV3(источник, ФАЙЛ_P3C);
  expect(разбор.errors, "источник обязан разбираться").toEqual([]);
  return loweredProgram(источник, {
    filename: ФАЙЛ_P3C,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
}

function запустить(источник: string, имя: string): number | undefined {
  const итог = опустить(источник);
  expect(итог.ок, итог.ок ? "" : String(итог.отказ.отказы[0]?.причина)).toBe(true);
  if (!итог.ок) return undefined;
  const файл = path.resolve(".tmp", имя);
  fs.writeFileSync(
    файл,
    buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
      writable: true,
      extraMemory: WRITE_ZONE_EXTRA_MEMORY,
    }).bytes,
  );
  return runInQemu(файл, { shim: true, timeoutMs: 30_000 })?.status;
}

describe("шаг P3c: рекурсивный спуск post-order", () => {
  it("эталон ленты — 69 клеток: post-order `2 3 4 * +` и `вернуть`", () => {
    // Эталон посчитан `эталоннаяЛента` (AST 3.0) по исходнику, а не выписан руками; здесь он
    // закреплён ЦЕЛИКОМ, потому что сверять порядок событий по кускам — это проверять не порядок.
    expect(эталоннаяЛента(ИСХОДНИК_P3C, ФАЙЛ_P3C)).toEqual([
      20261108, 3, 0, 1, 3, 112, 51, 99, 51,
      1, 0, 1, 1, 9, 1, 1087,
      3, 0, 1, 1, 5, 1063, 1080, 1089, 1083, 1086,
      12, 33, 34, 2, 11, 1, 1, 50,
      12, 37, 38, 2, 15, 1, 1, 51,
      12, 41, 42, 2, 19, 1, 1, 52,
      23, 37, 42, 2, 15,
      21, 33, 42, 2, 11,
      8, 25, 2, 3, 42, 1,
      4, 50, 0,
    ]);
  });

  it("спуск 4 уровней читает ленту и находит конец выражения (модель, 2 прогона)", () => {
    expect(запустить(программаСпускаP3c(), "p3c-descent.elf")).toBe(33);
    expect(запустить(программаСпускаP3c(), "p3c-descent.elf")).toBe(33);
  });

  it("проба «по событию» печатает эталонную ленту (69) и даёт код 0 (модель, 2 прогона)", () => {
    const источник = программаПротоколаP3cПоСобытиям();
    const итог = опустить(источник);
    expect(итог.ок, итог.ок ? "" : String(итог.отказ.отказы[0]?.причина)).toBe(true);
    if (!итог.ок) return;
    const файл = path.resolve(".tmp", "p3c-perevent.elf");
    fs.writeFileSync(
      файл,
      buildElfFromCode(итог.значение.bytes, MINIMAL_BASE, {
        writable: true,
        extraMemory: WRITE_ZONE_EXTRA_MEMORY,
      }).bytes,
    );
    const эталон = эталоннаяЛента(ИСХОДНИК_P3C, ФАЙЛ_P3C);
    for (const прогон of [1, 2]) {
      const запуск = runInQemu(файл, { shim: true, timeoutMs: 30_000 });
      expect(запуск?.status, `прогон ${String(прогон)}: код 0`).toBe(0);
      const получено = (запуск?.stdout ?? "")
        .trim()
        .split(/\s+/)
        .map(Number)
        .filter((значение) => Number.isFinite(значение));
      expect(получено, `прогон ${String(прогон)}: лента клетка в клетку`).toEqual(эталон);
    }
  });

  it("форма §18 (писатель группы с упаковкой пары) остаётся за бюджетом — граница названа", () => {
    const итог = опустить(программаПротоколаP3c());
    expect(итог.ок).toBe(false);
    if (итог.ок) return;
    const причины = итог.отказ.отказы.map((запись) => запись.причина).join("\n");
    // Отказ приходит из раскладки ПОСЛЕ отказа выделить базу блока рантайма массивов: упаковка
    // пары оставляет писателю 13–14 клеток из 15, а тройке базы места уже нет. Это и есть стена.
    expect(причины).toMatch(/базу блока рантайма/);
    expect(итог.отказ.отказы.map((запись) => запись.код)).toContain("OSN-LOW-003");
  });
});
