/**
 * ОРАКУЛ 2.2 (D5, `docs/verification-debt.md` случай 73): ОТКАЗ ПОВЕРХНОСТИ НАЗЫВАЕТ ПРИЧИНУ,
 * А НЕ ОТДЕЛЫВАЕТСЯ ФРАЗОЙ «ПРОГРАММА НЕ КОМПИЛИРУЕТСЯ».
 *
 * # Что было и что стало (замер 2026-11-05, `.tmp/a622-message.ts`)
 *
 * `длина нагрузка` (нагрузка пары `Результат<Строка, Число>`) НЕ доходит до понижения: компилятор
 * отдаёт `module = null` вместе с НАЗВАННОЙ диагностикой, а дверь бросала одну и ту же фразу —
 * причину читатель не видел вовсе. Диагностики у причин РАЗНЫЕ и с разными кодами:
 *
 * | проба | код каталога | фаза |
 * |---|---|---|
 * | `длина нагрузка` / `длина а` (тип не выведен) | `OSN-CG-001` | сборка |
 * | `вернуть 1 +` (синтаксис) | `OSN-PAR-001` | парсер |
 * | `нет_такого()` (неизвестная процедура) | `OSN-SEM-003` + `OSN-CG-001` | семантика + сборка |
 *
 * Стало: `программа не компилируется: OSN-CG-001 сборка: «длина» требует известного типа операнда:
 * у «нагрузка» тип не выведен — добавьте аннотацию …`.
 *
 * # Почему это БРОСОК, а не отказ `OSN-LOW-*` — и почему это не уступка
 *
 * Класс этого отказа в дереве назван — **«язык»**, и он ВНЕ контракта понижения: `OSN-LOW-*` описывает
 * отказ ПОНИЖЕНИЯ (`src/e2k/loweringRefusal.ts`), у языка свой канал (`OSN-CG-*`/`OSN-PAR-*`/
 * `OSN-SEM-*`), и прибор `src/scripts/e2kLoweringDiagnostics.ts#classOfCode` называет код вне таблицы
 * `код-вне-контракта`. Понижение до программы не дошло вовсе, поэтому `OSN-LOW-*` здесь был бы ложью о
 * слое. Чинится АНОНИМНОСТЬ: причина с кодом и фазой названа, а прежняя фраза-класс осталась НАЧАЛОМ
 * сообщения — по ней классификатор (`classOfThrown`, `/программа не компилируется/`) узнаёт класс
 * «язык», как и раньше. Оракул прибора при этом не тронут и остаётся зелёным.
 *
 * # Границы
 *
 * Тронуто: `src/e2k/recordPlan.ts` (названный итог конвейера), `src/e2k/guards/loweredUnchecked.ts` и
 * `src/e2k/programImage.ts` (две точки броска). Поверхность (`src/compiler/**`), формы носителей,
 * раскладка, VLIW и ABI НЕ тронуты: чинится только то, ЧТО ВИДИТ ЧИТАТЕЛЬ на отказе языка.
 *
 * # Негативный контроль (20.2)
 *
 * Возврат прежней редакции точки броска (одна фраза без причин) краснит РОВНО **4** проверки — все
 * оракульные на названную причину — и не трогает ни одного контроля: сторож ловит анонимность, а не
 * «отказ вообще». Разделение покрытия при этом ВИДНО: снятие называния в ДВЕРИ краснит четыре проверки
 * двери, а проверка КАНАЛА КИТА остаётся зелёной — она идёт через `src/e2k/programImage.ts`, где своя
 * точка броска. То есть обе половины называния покрыты, и ни одна не покрыта дважды.
 *
 * # Негативный контроль (20.3, TD-0006)
 *
 * Возврат прежней ветви `resolveLength` (одна ветвь «тип не выведен» на оба случая) краснит РОВНО
 * **2** проверки — «ТИП ОБЪЯВЛЕН АННОТАЦИЕЙ…» и «`пусть а = 5` + `длина а`…», то есть те, что
 * требуют НАЗВАТЬ тип. Третий оракул («СОВЕТ ОСТАЛСЯ ТАМ, ГДЕ ОН ВЕРЕН») остаётся ЗЕЛЁНЫМ в обоих
 * состояниях — он сторож ГРАНИЦЫ, а не правки: он и обязан не краснеть, иначе правка снесла бы совет
 * и там, где он верен (тип у пары действительно не выведен).
 *
 * # ЖЕЛЕЗО (2026-11-05, Эльбрус E8C2, Elbrus Linux 8.1)
 *
 * У ОРАКУЛА ОБРАЗА НЕТ НИ НА МОДЕЛИ, НИ НА ЦЕЛИ — и это не «не проверили»: отказ приходит из
 * компилятора до понижения, запускать нечего. На цель ехал КОНТРОЛЬ: `пусть с = "абв"` + `вывести
 * длина с` → **3**, код 0, модель и цель, 3/3 повтора, sha256 сошёлся 1/1 ДО прогона
 * (`.tmp/a622-hw/`, текст отказа — `.tmp/a622-hw/отказ.txt`). Правка не сдвинула ни одного байта
 * прежних трёх образов (sha256 3/3) — она меняет только текст на отказе языка.
 */

import { describe, it, expect } from 'vitest';
import { loweredProgram } from './lowered';
import { regModuleOrNamedFailure, frontendFailureReasons } from './recordPlan';
import { buildE2kImage } from '../scripts/e2kProgramRun';
import { parseV3 } from '../compiler-v3/index';
import type { CompileOptions } from '../compiler/compiler';

const ФАЙЛ = 'проба.osnova';

/** Программа с телом действия: разбор v3 — тот же, что у цели. */
function программа(тело: readonly string[]): string {
  return ['действие главная()', ...тело.map((строка) => `  ${строка}`), 'конец', ''].join('\n');
}

/** Пара `Результат<Строка, Число>`: нагрузка — параметр `Строка`, но тип у неё снаружи не выведен. */
function сПарой(тело: readonly string[]): string {
  return [
    'процедура добыть(с: Строка, ч: Число) → Результат<Строка, Число>',
    '  если ч > 0',
    '    вернуть Успех(с)',
    '  конец если',
    '  вернуть Неудача(7)',
    'конец',
    '',
    программа(тело),
  ].join('\n');
}

function опции(источник: string): CompileOptions {
  const разбор = parseV3(источник, ФАЙЛ);
  return { filename: ФАЙЛ, parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }) };
}

/** Что бросила дверь: `undefined` — не бросила вовсе. */
function бросок(источник: string): string | undefined {
  try {
    loweredProgram(источник, опции(источник));
    return undefined;
  } catch (беда) {
    return беда instanceof Error ? беда.message : String(беда);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// 1. ОРАКУЛ ВЛАДЕЛЬЦА: ПРИЧИНА НАЗВАНА
// ─────────────────────────────────────────────────────────────────────────────

describe('2.2 (D5): отказ поверхности называет причину, а не только класс', () => {
  it('`длина нагрузка` — назван код каталога, фаза и причина (было: одна фраза без причины)', () => {
    const сообщение = бросок(сПарой(['пусть тег, нагрузка = добыть("абв", 5)', 'вернуть длина нагрузка']));
    expect(сообщение, 'отказ поверхности обязан быть броском — класс «язык»').toBeDefined();
    expect(сообщение, 'код каталога назван').toContain('OSN-CG-001');
    expect(сообщение, 'фаза названа').toContain('сборка');
    expect(сообщение, 'причина названа словами компилятора, а не пересказана').toContain(
      '«длина» требует известного типа операнда: у «нагрузка» тип не выведен',
    );
    expect(сообщение, 'прежняя фраза-КЛАСС осталась началом — по ней классификатор узнаёт «язык»').toMatch(
      /^программа не компилируется: /u,
    );
  });

  it('`пусть а = 5` + `длина а` — названо ИМЯ и ВЫВЕДЕННЫЙ тип: совет аннотации тут был ложью', () => {
    // ПРЕЖНЯЯ РЕДАКЦИЯ ЭТОГО ОРАКУЛА (до TD-0006) требовала здесь «у «а» тип не выведен — добавьте
    // аннотацию». Замер показал, что тип у `а` ЕСТЬ (`Число`, выведен из литерала), поэтому совет
    // был бесполезен: с аннотацией `пусть а: Число = 5` отказ приходит ТОТ ЖЕ. Оракул исправлен
    // вместе с текстом, а не подогнан: он по-прежнему требует НАЗВАТЬ причину и имя.
    const сообщение = бросок(программа(['пусть а = 5', 'вернуть длина а']));
    expect(сообщение).toContain('OSN-CG-001');
    expect(сообщение, 'имя названо').toContain('«а»');
    expect(сообщение, 'назван выведенный тип').toContain('«Число»');
    expect(сообщение, 'ложного совета нет').not.toContain('добавьте аннотацию');
  });

  it('ТИП ОБЪЯВЛЕН АННОТАЦИЕЙ — причина называет ТИП, а совета «добавьте аннотацию» НЕТ (TD-0006)', () => {
    const сообщение = бросок(программа(['пусть ч: Число = 5', 'вернуть длина ч']));
    expect(сообщение, 'код каталога назван').toContain('OSN-CG-001');
    expect(сообщение, 'имя операнда названо').toContain('«ч»');
    expect(сообщение, 'назван ОБЪЯВЛЕННЫЙ тип, а не «не выведен»').toContain('«Число»');
    expect(
      сообщение,
      'аннотация УЖЕ стоит — советовать её повторно значит врать о причине (находка TD-0006)',
    ).not.toContain('добавьте аннотацию');
  });

  it('СОВЕТ ОСТАЛСЯ ТАМ, ГДЕ ОН ВЕРЕН: тип НЕИЗВЕСТЕН — причина по-прежнему зовёт аннотацию', () => {
    // Нагрузка пары: тип снаружи не выведен (`inferExprType` её не знает), и здесь совет добавить
    // аннотацию — единственно верное, что можно сказать. Граница TD-0006 проходит ИМЕННО здесь:
    // «тип известен» и «тип неизвестен» — два разных отказа, а не один.
    const сообщение = бросок(сПарой(['пусть тег, нагрузка = добыть("абв", 5)', 'вернуть длина нагрузка']));
    expect(сообщение, 'без аннотации совет уместен и обязан остаться').toContain('добавьте аннотацию');
    expect(сообщение, 'и тип при этом НЕ называется — его и правда нет').toContain('у «нагрузка» тип не выведен');
  });

  it('НАЗЫВАНИЕ НЕ ЧАСТНОЕ: синтаксис даёт свой код и фазу (`OSN-PAR-001`, парсер)', () => {
    const сообщение = бросок(программа(['вернуть 1 +']));
    expect(сообщение).toContain('OSN-PAR-001');
    expect(сообщение).toContain('парсер');
    expect(сообщение).toContain('ожидается выражение');
  });

  it('ПРИЧИН МОЖЕТ БЫТЬ НЕСКОЛЬКО: неизвестная процедура называет и семантику, и сборку', () => {
    const сообщение = бросок(программа(['нет_такого()', 'вернуть 0']));
    expect(сообщение).toContain('OSN-SEM-003');
    expect(сообщение).toContain('OSN-CG-001');
    expect(сообщение, 'причины разделены, а не склеены в одну').toContain(' | ');
  });

  it('КАНАЛ КИТА видит ту же названную причину (не только дверь)', () => {
    const источник = сПарой(['пусть тег, нагрузка = добыть("абв", 5)', 'вернуть длина нагрузка']);
    expect(() => buildE2kImage(источник, опции(источник))).toThrowError(/OSN-CG-001/u);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// 2. КОНТРОЛИ: ПРАВКА НЕ ТРОГАЕТ НИ РАБОЧИХ ПРОГРАММ, НИ ОТКАЗОВ ПОНИЖЕНИЯ
// ─────────────────────────────────────────────────────────────────────────────

describe('2.2: контроль — рабочие программы и отказы понижения не задеты', () => {
  it('`длина с` по ЛОКАЛЬНОЙ строке — работает (броска нет, байты есть)', () => {
    const источник = программа(['пусть с = "абв"', 'вывести длина с', 'вернуть 0']);
    const итог = loweredProgram(источник, опции(источник));
    expect(итог.ок, 'работающая программа не должна попасть в названный отказ языка').toBe(true);
    if (итог.ок) expect(итог.значение.bytes.length).toBeGreaterThan(0);
  });

  it('отказ ПОНИЖЕНИЯ (`а[0]` по числу) остаётся ОТКАЗОМ, а не превращается в бросок', () => {
    const источник = программа(['пусть а = 5', 'вернуть а[0]']);
    expect(бросок(источник), 'называние отказа языка не имеет права съесть канал понижения').toBeUndefined();
    const итог = loweredProgram(источник, опции(источник));
    expect(итог.ок).toBe(false);
    if (!итог.ок) expect(итог.отказ.отказы[0]?.код).toBe('OSN-LOW-003');
  });

  it('итог конвейера различает успех и отказ поверхности по ФАКТУ, а не по пустому модулю', () => {
    const рабочая = regModuleOrNamedFailure(программа(['вернуть 2 + 2']), опции(программа(['вернуть 2 + 2'])));
    expect(рабочая.ok).toBe(true);
    if (рабочая.ok) expect(рабочая.module.procedures.length).toBeGreaterThan(0);
    const сломанная = программа(['вернуть 1 +']);
    const отказ = regModuleOrNamedFailure(сломанная, опции(сломанная));
    expect(отказ.ok).toBe(false);
    if (!отказ.ok) {
      expect(отказ.причины.length, 'причина названа хотя бы одна').toBeGreaterThan(0);
      expect(отказ.причины[0], 'строка причины начинается с кода каталога').toMatch(/^OSN-[A-Z]{3}-\d{3} /u);
    }
  });

  it('ПРИЧИНА ЕСТЬ ВСЕГДА: молчащий отказ компилятора тоже НАЗВАН (гарантия сборщика)', () => {
    // Опора на контракт КАНОНИЧЕСКОГО сборщика: модуля нет и ни одна фаза причину не назвала — он
    // добавляет запись-признак `OSN-CG-002`. Своего запасного текста в понижении поэтому нет: он был бы
    // вторым ответом на один вопрос. Проверка держит именно эту гарантию — если сборщик её потеряет,
    // названный отказ снова станет безымянным, и это обязано покраснеть ЗДЕСЬ.
    const пустой = frontendFailureReasons({
      module: null,
      compilerSuccess: false,
      lexerErrors: [],
      parserErrors: [],
      compilerErrors: [],
      semanticErrors: [],
    } as unknown as Parameters<typeof frontendFailureReasons>[0]);
    expect(пустой.length, 'список причин не пуст — иначе сообщение кончилось бы двоеточием').toBeGreaterThan(0);
    expect(пустой[0]).toContain('OSN-CG-002');
    expect(пустой[0]).toContain('отказ без диагностики');
  });
});
