/**
 * ШАГ P1: заголовок `процедура` в сгенерированном разборщике B2b — ЧТО ИЗМЕРЕНО (2026-11-13).
 *
 * 1. ОРАКУЛ ЗАКРЕПЛЁН ЦЕЛИКОМ (51 клетка), а не «есть событие 1». Форма —
 *    `процедура п()` + `вернуть` + `конец п` и рядом контроль `действие главная()`. В ленте видно,
 *    за что платили: `1 0 1 1 9` (начало, конец ключевого слова 9 — у `действие` он 8), имя,
 *    `3 0 0` (заголовок: 0 параметров, нет возврата), тело, `4 31` — конец ОБЪЯВЛЕНИЯ на конце
 *    закрывающего имени, а не файла.
 * 2. КОНТРОЛЬ НЕ СДВИНУЛСЯ: у `действие`-формы те же 33 клетки, что и до правки. Это и был главный
 *    риск: заголовок `действие` писал `главная` ДО цикла, а теперь его пишет шаг из диспетчера
 *    (иначе объявления ПЕРЕД `действие` не разбирались бы вовсе — цикл начинался с тела действия).
 * 3. ИЗМЕРЕНО НА ЖЕЛЕЗЕ (E8C2, 2026-11-13 19:10 MSK): обе программы печатают эталон клетка в клетку,
 *    код возврата **0** (33 из 33 и 51 из 51). ПРОБА НЕ ИСПОЛНЯЕТСЯ МОДЕЛЬЮ: B2b на QEMU не бежит
 *    вовсе (`код=9`/`undefined` на любой форме, включая прежние 15) — это стена §3.137.5, поэтому
 *    здесь закреплён оракул и понижение, а арбитр — кит `gate:hardware`.
 *
 * Ловушка стенда, которая стоила двух прогонов и записана в коммент генератора: без
 * `dataSegmentBytes: 0x10000` (кит передаёт его всегда) обе программы печатали НОЛЬ байт и падали
 * кодом 139 — куча с лентой выходили за отображённую память. Это был дефект пробы, а не правки.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3';
import { программаПротоколаB2b } from '../compiler-v3/parser-protocol-b2b';
import { эталоннаяЛента } from '../compiler-v3/parser-protocol-probe';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { loweredProgram } from './lowered';

const ФАЙЛ = 'p1.osnova';

/** Контроль: `действие` — форма, которая работала до правки и обязана остаться байт в байт. */
const ДЕЙСТВИЕ = 'действие главная()\n  вернуть\nконец главная\n';

/** P1: процедура БЕЗ параметров и без типа возврата + действие. */
const ПРОЦЕДУРА = 'процедура п()\n  вернуть\nконец п\n\nдействие главная()\n  вернуть\nконец главная\n';

describe('шаг P1: заголовок `процедура` в B2b', () => {
  it('эталон `действие` — 33 клетки, не сдвинулся', () => {
    expect(эталоннаяЛента(ДЕЙСТВИЕ, ФАЙЛ)).toEqual([
      20261108, 3, 0, 1, 2, 112, 49, 43, 17, 0, 1, 1, 8, 7, 1075, 1083, 1072, 1074, 1085, 1072, 1103,
      3, 0, 0, 8, 21, 2, 3, 28, 0, 4, 42, 0,
    ]);
  });

  it('эталон `процедура п()` — 51 клетка: ключ 9, `3 0 0`, конец объявления на `п`', () => {
    expect(эталоннаяЛента(ПРОЦЕДУРА, ФАЙЛ)).toEqual([
      20261108, 3, 0, 1, 2, 112, 49, 76, 1, 0, 1, 1, 9, 1, 1087, 3, 0, 0, 8, 16, 2, 3, 23, 0, 4, 31,
      17, 33, 5, 1, 41, 7, 1075, 1083, 1072, 1074, 1085, 1072, 1103, 3, 0, 0, 8, 54, 6, 3, 61, 0, 4,
      75, 0,
    ]);
  });

  it('лента процедуры отличима от ленты действия ПЕРВЫМ событием, а не длиной', () => {
    const процедура = эталоннаяЛента(ПРОЦЕДУРА, ФАЙЛ);
    const действие = эталоннаяЛента(ДЕЙСТВИЕ, ФАЙЛ);
    // 1 — `процедура_начало`, 17 — `действие_начало`; шапка у обеих 8 клеток (магия, версия, вид,
    // имя модуля «p1» двумя кодпоинтами, конец модуля).
    expect(процедура[8]).toBe(1);
    expect(действие[8]).toBe(17);
  });

  it('генератор собирает программу, которая понижается без отказов и влезает в 192 512 кода', () => {
    for (const источник of [ДЕЙСТВИЕ, ПРОЦЕДУРА]) {
      const программа = программаПротоколаB2b(источник, ФАЙЛ);
      const разбор = parseV3(программа, ФАЙЛ);
      expect(разбор.errors, `генератор обязан разбираться: ${источник}`).toEqual([]);
      const понижен = loweredProgram(программа, {
        filename: ФАЙЛ,
        allowDeepArrayWrites: true,
        parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
      });
      expect(понижен.ок, понижен.ок ? '' : String(понижен.отказ.причина)).toBe(true);
      if (!понижен.ок) continue;
      expect(понижен.значение.bytes.length).toBe(192_512);
      // ELF собирается тем же вызовом, что у кита: без `dataSegmentBytes` проба падала 139-м.
      const elf = buildElfFromCode(понижен.значение.bytes, MINIMAL_BASE, {
        writable: true,
        extraMemory: WRITE_ZONE_EXTRA_MEMORY,
        dataSegmentBytes: 0x10000,
      });
      expect(elf.bytes.length).toBeGreaterThan(0);
    }
  });
});
