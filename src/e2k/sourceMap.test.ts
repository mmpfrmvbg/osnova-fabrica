/**
 * КАРТА ИСТОЧНИКА, ЧАСТЬ 1: `IR.sourceRef` — ССЫЛКА НА УЗЕЛ AST И НОМЕР ТОКЕНА (2026-11-11).
 *
 * # Что здесь доказано и чем
 *
 * 1. **Ссылка ЕСТЬ у инструкции, рождённой `лента[индекс]`.** `лента[индекс]` разбор v3 сворачивает
 *    в вызов `система.массив.получить` (`parser.ts#хвосты`), а кодоген ставит на `IR.invoke` поле
 *    `sourceRef`. Проверяется не «поле непустое», а ОБА числа: номер узла — положительное целое,
 *    номер токена — ВЫЧИСЛЕН заново по потоку `tokenizeV3` (ищется `лента` непосредственно перед
 *    `[`), а не списан из ответа. Так сторож не может «подтвердить» то, что сам же и напечатал.
 * 2. **Ссылка РАСШИФРОВЫВАЕТСЯ в человеческую форму** `лента[индекс], строка N, колонка M`, причём
 *    строка и колонка сверяются с теми, что дал лексер для того же токена.
 * 3. **Ссылка НЕ РАЗМАЗАНА по всему потоку.** У `система.массив.добавить` (его в исходнике нет как
 *    отдельного места) и у `const`/`move` поля нет вовсе: это признак ПРОИСХОЖДЕНИЯ, а не украшение
 *    каждой инструкции. Если бы поле ставилось всюду, отказ называл бы не тот узел.
 * 4. **Номера узлов не совпадают у двух разных мест.** Иначе отказ отправлял бы к чужой строке.
 * 5. **Ссылка переживает `validateNamedTypesAndRewrite`** — тот самый проход, который ПЕРЕСОБИРАЕТ
 *    узлы (`compiler.ts:604-644`). Это и есть причина, по которой ключ карты — БАЗА выражения
 *    (`лента`), а не `вызов`: лист тождество сохраняет, `вызов` — нет.
 *
 * # Граница, названная честно
 *
 * Источник ставится там, где разбор знает НАЧАЛО базы и где база — лист (`переменная`, `строка`,
 * `число`). У базы, которую пересоберут (`ф(х)[0]`), источника НЕТ, и `sourceRef` остаётся
 * `undefined` — это законный исход, а не пробел: отказ тогда говорит по-старому.
 */
import { describe, expect, it } from "vitest";
import { parseV3, tokenizeV3 } from "../compiler-v3/index";
import { compileToReg } from "../compiler/regcodegen";
import { validateNamedTypesAndRewrite } from "../compiler/compiler";
import { isRegModule, REGCODE_VERSION, type RegInstruction, type RegModule } from "../runtime/vm/regcode";
import {
  описаниеИсточника,
  описаниеПоСсылке,
  размерКартыИсточника,
  type IRSourceRef,
} from "../runtime/vm/sourceMap";

const ФАЙЛ = "карта-источника.osnova";

/**
 * Программа-образец: `лента[индекс]` — ЧТЕНИЕ по индексу, а `лента[0]` — второе место, чтобы
 * проверить, что номера узлов РАЗНЫЕ (одна и та же карта не должна отправлять к чужой строке).
 */
const ИСХОДНИК = [
  "действие главная()",
  "  пусть лента: Список Число = []",
  "  добавить в лента элемент 11",
  "  пусть индекс = 0",
  "  пусть первое = лента[0]",
  "  вернуть лента[индекс]",
  "конец главная",
  "",
].join("\n");

/** Модуль регистрового кодогена — тем же проходом, что и понижение на цель. */
function модуль(источник: string): RegModule {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join("; ")}`).toEqual([]);
  const м = р.program!.modules[0]!;
  // Тот самый проход, который пересобирает узлы: если источник его не переживёт, проверка ниже
  // покраснеет — и это будет верный сигнал, а не помеха.
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  return compileToReg(м);
}

/** Все инструкции модуля: код плоский, пакеты разворачиваются. */
function инструкции(м: RegModule): RegInstruction[] {
  return м.code.flatMap((элемент) =>
    "packet" in элемент && элемент.packet === true ? элемент.slots : [элемент as RegInstruction],
  );
}

/**
 * Номер токена, перед которым стоит `[`, — ВЫЧИСЛЕН заново по потоку лексера.
 *
 * Именно `последний` такой `лента`: в образце их два, и проверяется ссылка на ВТОРОЕ место
 * (`вернуть лента[индекс]`). Поиск идёт по `lexeme`, а не по индексу, вписанному руками: иначе
 * проверка подтверждала бы сам ответ.
 */
function номерБазыВТоромМесте(источник: string): number {
  const { tokens, errors } = tokenizeV3(источник, ФАЙЛ);
  expect(errors, "лексер обязан промолчать").toEqual([]);
  const места: number[] = [];
  for (let i = 0; i + 1 < tokens.length; i++) {
    if (tokens[i]!.lexeme === "лента" && tokens[i + 1]!.lexeme === "[") места.push(i);
  }
  expect(места.length, "в образце обязаны быть ДВА места `лента[…]`").toBe(2);
  return места[1]!;
}

describe("карта источника, часть 1: IR.sourceRef", () => {
  it("у `система.массив.получить` есть sourceRef: номер узла и номер токена `лента`", () => {
    const м = модуль(ИСХОДНИК);
    const получения = инструкции(м).filter(
      (и) => и.op === "invoke" && (и as { name?: string }).name === "система.массив.получить",
    ) as Array<RegInstruction & { sourceRef?: IRSourceRef }>;
    // Оба места обязаны дать инструкцию: иначе проверять нечего.
    expect(получения.length, "в образце ДВА чтения по индексу").toBe(2);

    const ожидаемыйТокен = номерБазыВТоромМесте(ИСХОДНИК);
    const ссылки = получения.map((и) => и.sourceRef);
    for (const [номер, ссылка] of ссылки.entries()) {
      expect(ссылка, `чтение №${String(номер + 1)}: sourceRef обязан быть`).toBeDefined();
      expect(Number.isInteger(ссылка!.astNodeId), "номер узла — целое").toBe(true);
      expect(ссылка!.astNodeId).toBeGreaterThan(0);
      expect(Number.isInteger(ссылка!.tokenIndex), "номер токена — целое").toBe(true);
    }
    // Второе чтение — то самое `вернуть лента[индекс]`: номер токена сверяется с потоком, а не с
    // ответом кодогена.
    expect(ссылки[1]!.tokenIndex, "номер токена второго чтения").toBe(ожидаемыйТокен);
    // Разные места — разные узлы: иначе отказ отправил бы ко второй строке.
    expect(ссылки[0]!.astNodeId, "номера узлов РАЗНЫХ мест не совпадают").not.toBe(ссылки[1]!.astNodeId);
  });

  it("ссылка расшифровывается как `лента[индекс], строка N, колонка M` — и место сверено с лексером", () => {
    const м = модуль(ИСХОДНИК);
    const получение = инструкции(м).filter(
      (и) => и.op === "invoke" && (и as { name?: string }).name === "система.массив.получить",
    ) as Array<RegInstruction & { sourceRef?: IRSourceRef }>;
    const второе = получение[1]!;

    const описание = описаниеПоСсылке(второе.sourceRef);
    expect(описание, "описание обязано найтись по ссылке").toBeDefined();
    expect(описание).toMatch(/^лента\[индекс\], строка \d+, колонка \d+$/);

    // Строка и колонка — из ПОТОКА токенов по тому же номеру, что в ссылке.
    const { tokens } = tokenizeV3(ИСХОДНИК, ФАЙЛ);
    const токен = tokens[второе.sourceRef!.tokenIndex]!;
    expect(токен.lexeme, "токен ссылки — это `лента`").toBe("лента");
    expect(описание).toBe(`лента[индекс], строка ${String(токен.line)}, колонка ${String(токен.column)}`);
    expect(токен.line, "строка `вернуть лента[индекс]` — шестая").toBe(6);
  });

  it("поле РАЗМЕЧЕНО, а не размазано: у `добавить` и `move` источника нет, у литерала — есть", () => {
    const м = модуль(ИСХОДНИК);
    const все = инструкции(м);
    const по = (имя: string) =>
      все.filter((и) => и.op === "invoke" && (и as { name?: string }).name === имя) as Array<
        RegInstruction & { sourceRef?: IRSourceRef }
      >;

    // `добавить в лента элемент 11` — тоже вызов рантайма массивов, но отдельного МЕСТА в исходнике
    // у него нет как у индексации: поля быть не должно.
    const добавления = по("система.массив.добавить");
    expect(добавления.length, "добавление в образце одно").toBe(1);
    expect(добавления[0]!.sourceRef, "у добавления источника нет").toBeUndefined();

    // `move` — внутренняя пересылка кодогена: в исходнике её не писали вовсе.
    for (const и of все.filter((инструкция) => инструкция.op === "move")) {
      expect((и as { sourceRef?: IRSourceRef }).sourceRef, "move: источника нет").toBeUndefined();
    }

    // А у `const`, рождённой ЛИТЕРАЛОМ, источник есть — это не «размазывание», а точное указание:
    // литерал человек писал, и именно он невыразим литералом e2k (`OSN-LOW-002`).
    const консты = все.filter((и) => и.op === "const") as Array<RegInstruction & { sourceRef?: IRSourceRef }>;
    expect(консты.length, "в образце есть const").toBeGreaterThan(0);
    const сИсточником = консты.filter((и) => и.sourceRef !== undefined);
    expect(сИсточником.length, "хотя бы одна const несёт источник литерала").toBeGreaterThan(0);
    for (const и of сИсточником) {
      const описание = описаниеПоСсылке(и.sourceRef);
      expect(описание, "источник const расшифровывается").toBeDefined();
      // Литерал в образце — `0`; описание обязано называть его, а не соседний узел.
      expect(описание).toMatch(/^(0|11|\[\]), строка \d+, колонка \d+$/);
    }
  });

  it("карта аддитивна: `REGCODE_VERSION` не поднят, `isRegModule` принимает модуль со ссылкой", () => {
    expect(REGCODE_VERSION, "версия регистрового формата не менялась").toBe(1);
    const м = модуль(ИСХОДНИК);
    expect(isRegModule(м), "модуль со `sourceRef` — тот же формат").toBe(true);
    // И карта действительно наполнилась: две индексации — две записи (номер выдаётся каждой).
    expect(размерКартыИсточника(), "записи карты появились").toBeGreaterThanOrEqual(2);
  });

  it("запасной путь: без источника описание НЕ выдумывается (`undefined`, а не «где-то рядом»)", () => {
    expect(описаниеПоСсылке(undefined), "ссылки нет — описания нет").toBeUndefined();
    // Ссылка на узел, которого реестр не знает (чужой процесс, рукописный носитель): тоже молчим.
    expect(описаниеПоСсылке({ astNodeId: 999_999_999, tokenIndex: 0 })).toBeUndefined();
    // А запись, полученная из карты, описывается — тот же формат, что и у отказа.
    const м = модуль(ИСХОДНИК);
    const получение = инструкции(м).find(
      (и) => и.op === "invoke" && (и as { name?: string }).name === "система.массив.получить",
    ) as (RegInstruction & { sourceRef?: IRSourceRef }) | undefined;
    const описание = описаниеПоСсылке(получение!.sourceRef);
    expect(описание).toBeDefined();
    // `описаниеИсточника` — та же форма, что ушла в отказ (единый формат, а не второй).
    expect(описание!.split(", строка ")[0]).toBe("лента[0]");
    expect(typeof описаниеИсточника).toBe("function");
  });
});
