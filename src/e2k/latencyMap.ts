/**
 * ОТОБРАЖЕНИЕ «НОСИТЕЛЬ IR → КЛАСС ЗАДЕРЖКИ» ДЛЯ СИМУЛЯТОРА НА ОБОЛОЧКЕ.
 *
 * # Паспорт
 *
 * | поле | значение |
 * |---|---|
 * | статус | **ДОПУЩЕНИЕ** |
 * | источник | `docs/vliw-e2k-model.md` (глава 6, таблица стр. 71–72; глава 12, стр. 194), код модели — `src/vliw/e2kDevices.ts` |
 * | ограничение | **не валидировано на железе**: числа тактов взяты из руководства МЦСТ, а не измерены; штраф за переход между кластерами АЛУ принят нулевым (`docs/hardware-debt.md` §3.2) |
 *
 * **Это таблица оболочки проекта, а не e2k.** Носители `IR.*` — наши имена
 * (`src/e2k/shell.ts`), в руководстве их нет и быть не может. Классы `ALU`, `MUL`, `MEM`,
 * `BRANCH` — **наша группировка** строк модели: у документа классы называются иначе (`Int`,
 * `Fp`, `Fdivs/d`, `Ld L1`, `Disp->ct`, …), и группировка в четыре класса задана заказчиком.
 *
 * # Что здесь есть и чего нет
 *
 * - **есть** отображение каждого носителя оболочки на класс и **латентность в тактах**;
 * - **есть** источник у каждого отображения: `ПО ПРИРОДЕ` (класс следует из природы операции),
 *   `НАШЕ РЕШЕНИЕ` (класс или число выбраны нами — с обоснованием), `НЕТ КЛАССА` (у модели
 *   строки для такого носителя нет — с причиной и с тем, как симулятор себя ведёт);
 * - **нет** чтения и записи памяти: носителей `IR.load`/`IR.store` в оболочке не существует
 *   (операции `obj.get`/`obj.set` эмиттер отвергает — `NO_CARRIER` в `src/e2k/emitterShell.ts`).
 *   Поэтому класс `MEM` объявлен, но у него **ноль носителей** — это сказано прямо, а не
 *   умолчано (см. {@link CARRIERS_ABSENT_FROM_SHELL});
 * - **нет** ни одного носителя, которого нет в коде: оракул сверяет таблицу с `IR_CARRIERS`
 *   в обе стороны.
 *
 * # Латентность берётся из строки модели, а не из класса
 *
 * Класс — это **метка группировки**, а не длительность. Внутри `MUL` лежат и умножение
 * (4 такта, `Fp`), и деление с остатком (11 тактов, `Fdivs/d`); внутри `BRANCH` — переход
 * (5), вызов (3) и возврат (6). Поэтому у каждой записи своя `latency`, совпадающая со строкой
 * модели для её операции (`src/vliw/e2kDevices.ts` → `opClassOf` + `latencyFor`), и это
 * проверяется оракулом. {@link CLASS_LATENCY} — номинальная длительность класса; она нужна
 * **только** негативному контролю (подмена класса ALU → MEM) и не участвует в обычном счёте.
 */

