/**
 * Запись таблицы по имени носителя.
 *
 * @throws Error если носителя в таблице нет — «нет класса» это НЕ то же самое, что «нет записи»
 */
export function latencyEntry(carrier: string): LatencyEntry {
  const entry = LATENCY_MAP[carrier];
  if (entry === undefined) {
    throw new Error(
      `носителя «${carrier}» нет в таблице задержек: неизвестный носитель не считается за 1 такт молча`,
    );
  }
  return entry;
}

/** Класс задержки носителя; `null` — у модели строки для него нет. */
export function classOfCarrier(carrier: string): LatencyClass | null {
  return latencyEntry(carrier).latencyClass;
}

/** Сколько тактов берёт носитель. */
export function ticksOfCarrier(carrier: string): number {
  return latencyEntry(carrier).latency;
}

/** Носители без класса — с причиной и поведением симулятора. */
export function classlessCarriers(): readonly LatencyEntry[] {
  return Object.values(LATENCY_MAP).filter((entry) => entry.latencyClass === null);
}

/** Классы, у которых есть хотя бы один носитель (в порядке {@link LATENCY_CLASSES}). */
export function usedClasses(): readonly LatencyClass[] {
  const used = new Set<LatencyClass>();
  for (const entry of Object.values(LATENCY_MAP)) {
    if (entry.latencyClass !== null) used.add(entry.latencyClass);
  }
  return LATENCY_CLASSES.filter((cls) => used.has(cls));
}
