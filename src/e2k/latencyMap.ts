/** Класс задержки — наша группировка строк модели задержек (стр. 71–72). */
export type LatencyClass = 'ALU' | 'MUL' | 'MEM' | 'BRANCH';

/** Откуда взялось отображение. */
export type MappingSource = 'ПО ПРИРОДЕ' | 'НАШЕ РЕШЕНИЕ' | 'НЕТ КЛАССА';

/** Что симулятор делает с носителем, у которого класса нет. */
export type ClasslessBehavior = 'считать за 1 такт' | 'игнорировать' | 'останавливаться';

/** Одна строка таблицы: носитель → класс → такты, с источником и обоснованием. */
export interface LatencyEntry {
  /** Имя носителя IR (`IR.*`) — наше имя, не мнемоника e2k. */
  carrier: string;
  /** Класс задержки; `null` — «НЕТ КЛАССА». */
  latencyClass: LatencyClass | null;
  /** Сколько тактов берёт симулятор. Для класса — строка модели, для «НЕТ КЛАССА» — см. `reason`. */
  latency: number;
  /** Источник отображения. */
  source: MappingSource;
  /** Ссылка на источник: страница руководства либо место в коде проекта. */
  sourceRef: string;
  /** Обоснование. Обязательно для `НАШЕ РЕШЕНИЕ` и `НЕТ КЛАССА`; иначе пусто. */
  reason: string;
  /** Только для `НЕТ КЛАССА`: как симулятор обходится с носителем. */
  behavior?: ClasslessBehavior;
}

/** Все классы задержек в фиксированном порядке (для детерминированных списков). */
export const LATENCY_CLASSES: readonly LatencyClass[] = ['ALU', 'MUL', 'MEM', 'BRANCH'];

/**
 * Номинальная длительность класса — **только для негативного контроля**.
 *
 * Считает симулятор не по этим числам, а по `latency` записи: внутри класса длительности
 * разные (см. шапку файла). Здесь лежат строки модели, к которым класс ближе всего:
 * `ALU` → `Int` (1), `MUL` → `Fp` (4), `MEM` → `Ld L1 hit` (3), `BRANCH` → `Disp->ct` (5).
 */
export const CLASS_LATENCY: Readonly<Record<LatencyClass, number>> = {
  ALU: 1,
  MUL: 4,
  MEM: 3,
  BRANCH: 5,
};

