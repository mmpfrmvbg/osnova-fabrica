function mapped(
  carrier: string,
  latencyClass: LatencyClass,
  latency: number,
  source: Exclude<MappingSource, 'НЕТ КЛАССА'>,
  sourceRef: string,
  reason = '',
): LatencyEntry {
  return { carrier, latencyClass, latency, source, sourceRef, reason };
}

function classless(
  carrier: string,
  latency: number,
  behavior: ClasslessBehavior,
  sourceRef: string,
  reason: string,
): LatencyEntry {
  return { carrier, latencyClass: null, latency, source: 'НЕТ КЛАССА', sourceRef, reason, behavior };
}

