/**
 * ЗАПИСЬ НА ЦЕЛИ: ПОЛЕ ЧИТАЕТСЯ — ОРАКУЛ.
 *
 * # Что спрашивается
 *
 * `тип Точка { х: Число, у: Число }`; `пусть т: Точка = { х: 3, у: 4 }`; `вернуть т.х`. На МОДЕЛИ
 * e2k ответ обязан быть **3** — как и у эталонной VM.
 *
 * # Почему это стало возможно и чем именно является
 *
 * У операций `obj.new`, `obj.get`, `obj.set` на цели носителя нет (`src/e2k/emitterShell.ts`,
 * `NO_CARRIER`), и проба до правки умирала на `obj.new` — то есть `obj.get` даже не достигался.
 * Носителя не завели и теперь: запись разворачивается в **блок элементов** (`src/e2k/recordPlan.ts`),
 * у которого на цели УЖЕ есть рантайм, а поле читается по СТАТИЧЕСКОМУ индексу
 * (`система.массив.получить`). Контроль, что путь живой: `[3, 4]` + `т[0] + т[1]` → код 7, отказов 0.
 *
 * # Два наблюдения вместо одного (правило линии)
 *
 * | наблюдение | что различает |
 * |---|---|
 * | `{ х: 3, у: 4 }` → `т.х` = 3 | поле читается |
 * | `{ у: 4, х: 3 }` → `т.х` = 3 | индекс берётся из ОБЪЯВЛЕНИЯ, а не из порядка литерала |
 *
 * Второе обязательно: реализация «индекс = позиция ключа в литерале» прошла бы первое наблюдение и
 * вернула бы **4** на втором. Именно этот дефект и вносит негативный контроль 16.3.
 *
 * # Границы, названные честно
 *
 * - Читается и пишется ОДИН уровень; вложенная запись разворачивается, но её поведение закреплено
 *   только разбором, не прогоном.
 * - Значение поля — слово (число/адрес). Строка полем на цели не проверялась: элемент блока на цели
 *   не хранит длину.
 * - Запись без ВЫВЕДЕННОГО типа остаётся объектом и получает отказ оболочки `obj.new` — названный,
 *   а не тихий.
 */
