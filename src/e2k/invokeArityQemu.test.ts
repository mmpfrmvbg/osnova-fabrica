/**
 * ОРАКУЛ АРНОСТИ ВЫЗОВА — ЧАСТЬ С МОДЕЛЬЮ: ДОШЁЛ ЛИ ТРЕТИЙ АРГУМЕНТ ДО ПАМЯТИ.
 *
 * Форму носителя держит `src/e2k/invokeArity.test.ts` (полный прогон). Здесь спрашивается то, что
 * формой не доказывается: **аргумент доехал до места**. Носитель может быть шестиоперандным, а
 * третий регистр — не читаться понижением; различить это можно только прогоном.
 *
 * # Почему в шлюзе, а не в полном прогоне
 *
 * Ответ даёт `qemu-e2k` под шимом — внешний ресурс. Оракул, которому он нужен, в полном прогоне
 * стирает различие «сломали» и «машина занята» (случай 12 реестра проверяемости).
 *
 * # Что здесь проверяется
 *
 * | проверка | что доказывает |
 * |---|---|
 * | `установить(а, 0, 42)` → `получить(а, 0)` = 42 | запись перекрыла ПЕРВЫЙ элемент, а не «42 приехало откуда-то ещё» |
 * | положительный контроль рядом: `получить(а, 1)` = 2 | второй элемент ЦЕЛ — запись не уехала по адресу |
 * | `срез(а, 0, 2)` — отказ понижения про ПАМЯТЬ, не про арность | предел снят у всех трёхаргументных вызовов |
 * | `коллекция.положить(...)` — отказ не про арность | это открывает шаг ② коллекций |
 */
import { describe, it, expect } from 'vitest';
import { regModuleOf } from '../vliw/regOracle';
import { RegVM } from '../runtime/vm/reginterpreter';
import { createDefaultInvokeHandler } from '../runtime/vm/interpreter';
import { resolveEntryIndex } from '../oracle/parity';
import { runOnE2k } from '../scripts/e2kProgramRun';
import { buildShim } from '../scripts/e2kQemuExec';
import { COLLECTION_INVOKES } from '../runtime/vm/collectionCalls';

const shim = buildShim();

const модуль = (тело: string): string => `модуль Кол\nпроцедура главная()\n${тело}\nконец\nконец\n`;

/** Значение на РЕГИСТРОВОЙ VM — эталон языка. */
async function наVM(source: string): Promise<number> {
  const built = regModuleOf(source);
  expect(built, 'программа обязана компилироваться').not.toBeNull();
  const entry = resolveEntryIndex(built!.module.procedures, undefined) ?? 0;
  const vm = new RegVM(built!.module, {
    invoke: createDefaultInvokeHandler(),
    extraInvokes: COLLECTION_INVOKES,
    maxSteps: 2_000_000,
  });
  return Number(await vm.runProcedure(entry, []));
}

/** Ответ МОДЕЛИ: код возврата и отказы понижения — два разных канала, а не один. */
function наМодели(source: string, файл: string): { status: number | undefined; refused: readonly string[] } {
  const прогон = runOnE2k(source, файл);
  return { status: прогон.status, refused: прогон.refused.map((item) => `${item.code} ${item.reason}`) };
}

describe('арность вызова: третий аргумент доходит до цели', () => {
  it('шим и модель доступны — или причина названа', () => {
    if (shim === undefined) {
      expect(shim, 'шим не собран: в WSL нет компилятора C (docs/e2k-qemu-run.md §2.5)').toBeUndefined();
      return;
    }
    expect(shim.length).toBeGreaterThan(3);
  });

  it('установить(а, 0, 42): первый элемент перекрыт, второй ЦЕЛ — и на эталоне, и на модели', async () => {
    const source = модуль(
      [
        '  пусть а = система.массив.создать()',
        '  система.массив.добавить(а, 1)',
        '  система.массив.добавить(а, 2)',
        '  система.массив.установить(а, 0, 42)',
        // ОТВЕТ СОБИРАЕТСЯ ИЗ ДВУХ ЧТЕНИЙ, и это не украшение: «42» в одиночку приехало бы и от
        // испорченного `установить`, записавшего не туда, — если бы он затёр оба элемента или
        // вернул константу. Второй элемент доказывает, что запись встала ПО АДРЕСУ.
        '  вернуть система.массив.получить(а, 0) * 100 + система.массив.получить(а, 1)',
      ].join('\n'),
    );
    // 42 * 100 + 2 = 4202; в 8-битном канале это 4202 mod 256 = 106.
    const эталон = 42 * 100 + 2;
    expect(await наVM(source), 'эталон языка').toBe(эталон);
    if (shim === undefined) return;
    const { status, refused } = наМодели(source, 'invoke-arity-3-set.elf');
    expect(refused, `отказы понижения: ${refused.join('; ')}`).toEqual([]);
    expect(status, `модель: ${String(эталон)} mod 256`).toBe(эталон % 256);
    // Канал обязан РАЗЛИЧАТЬ «записано верно» и «записано мимо»: иначе проверка ничего не несёт.
    expect(эталон % 256, 'канал различает 4202 и случай «второй затёрт»').not.toBe((42 * 100) % 256);
  });

  it('срез(а, 0, 2) КОМПИЛИРУЕТСЯ, и отказ понижения — про память, а не про арность', () => {
    // Предел снят у ВСЕХ трёхаргументных вызовов, а не у одного: иначе «расширили носитель»
    // означало бы «научили один вызов». Отказ обязан называть настоящую причину и НЕ смеет
    // поминать арность: это разные причины, и спутать их значит отправить следующую сессию
    // искать не там (случай 33: текст отказа — тоже наблюдаемый выход).
    const source = модуль(
      [
        '  пусть а = система.массив.создать()',
        '  система.массив.добавить(а, 1)',
        '  система.массив.добавить(а, 2)',
        '  пусть б = система.массив.срез(а, 0, 2)',
        '  вернуть система.массив.длина(б)',
      ].join('\n'),
    );
    expect(() => наМодели(source, 'invoke-arity-3-slice.elf'), 'программа обязана СОБРАТЬСЯ').not.toThrow();
    expect(наМодели(source, 'invoke-arity-3-slice.elf').refused.join(' '), 'отказ не про арность').not.toMatch(
      /аргументов 3|несёт не больше/u,
    );
  });

  it('коллекция.положить(база, 0, 100): носитель донести три аргумента обязан', () => {
    const source = модуль(
      [
        '  пусть база = система.коллекция.выделить(4)',
        '  система.коллекция.положить(база, 0, 100)',
        '  вернуть 0',
      ].join('\n'),
    );
    expect(() => наМодели(source, 'invoke-arity-3-collection.elf'), 'программа обязана СОБРАТЬСЯ').not.toThrow();
    expect(наМодели(source, 'invoke-arity-3-collection.elf').refused.join(' '), 'отказ не про арность').not.toMatch(
      /аргументов 3|несёт не больше/u,
    );
  });
});
