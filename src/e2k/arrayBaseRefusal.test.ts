/**
 * ОРАКУЛ 2.1 (D4, `docs/verification-debt.md` случай 73): ИНДЕКСАЦИЯ ПО ЗНАЧЕНИЮ, КОТОРОЕ МАССИВОМ
 * БЫТЬ НЕ МОЖЕТ, — НАЗВАННЫЙ ОТКАЗ ВМЕСТО ЧТЕНИЯ ПАМЯТИ.
 *
 * # Десятый класс тихой лжи, который здесь закрыт
 *
 * Поверхность v3 выбирает вид индексации ПО ТИПУ операнда (`src/compiler-v3/parser.ts`): `Строка` —
 * `система.строка.символ`, массив — `система.массив.получить`. У значения, чей тип НЕ строка и НЕ
 * массив, выбора нет — и ветвь берётся МАССИВНАЯ, а рантайм массивов читает ПАМЯТЬ по тому, что лежит
 * в базе. Отказов при этом **0** — то есть число неверное и никем не названное.
 *
 * ЗАМЕР 2026-11-05 (модель QEMU): `пусть а = 5` + `вернуть а[0]` → код **9**, отказов **0**.
 *
 * # Что теперь (та же проба, тот же поток)
 *
 * `OSN-LOW-003`, конструкция названа (`система.массив.получить`), величина названа («ЧИСЛО, известное
 * на сборке (5)»), и назван ШАГ — номер того самого носителя (D11). Байтов у программы БОЛЬШЕ НЕТ:
 * образ не собирается вовсе — это и есть разница между «честно отказывает» и «молча считает 9».
 *
 * # Почему правило УЗКОЕ — и это замер, а не осторожность
 *
 * Строгое «база обязана быть доказанным массивом» сломало бы РАБОТАЮЩИЕ программы: массив-ПАРАМЕТР
 * (`процедура первый(a: Список Число)` + `a[0]`) понижается верно и даёт 0 отказов, а происхождения у
 * него нет — значение приходит из чужого окна. Обе стороны закреплены ниже контролем.
 *
 * # ШАГ 2.3 ЗАКРЫЛ ЭТУ ГРАНИЦУ (2026-11-05) — СВИДЕТЕЛЬ ПЕРЕПИСАН ПО ФАКТУ
 *
 * Прежняя редакция называла границей `процедура ф(а: Число)` + `а[0]`: программа СОБИРАЛАСЬ (отказов 0)
 * и читала память по адресу-числу (модель: код 9). Теперь массивность берётся ИЗ ТИПА, и это НАЗВАННЫЙ
 * отказ: причина называет тип («Число»), параметр процедуры («ф») и класс (тихая ложь). ИСТОРИЯ прежнего
 * факта («замер до правки: код 9, отказов 0») оставлена в комментарии проверки — свидетель переписан на
 * новый факт, а не удалён.
 *
 * Нагрузка пары `Результат<Строка, …>` по-прежнему без отказа — это ОСТАВШАЯСЯ граница шага 2.3.
 *
 * # Границы правки
 *
 * Тронуто: `src/e2k/arrayRuntime.ts` (план происхождения), `src/e2k/programImage.ts` (заведение отказа
 * в цикл понижения). Формы носителей, раскладка, VLIW и ABI НЕ тронуты — новых носителей и команд нет:
 * отказ стоит ДО понижения, а понижение у отказавшей программы просто не начинается.
 *
 * # Негативный контроль (20.1)
 *
 * Снятие заведения отказа в цикл (`arrayBaseProblem` = `undefined`) краснит РОВНО **4** проверки —
 * все четыре оракульные (литерал, шаг, арифметика, запись) — и НЕ трогает ни одного контроля: сторож
 * ловит именно ложь, а не «всё, что похоже на индексацию». Числа контролей при снятии не сдвинулись.
 *
 * # ЖЕЛЕЗО (2026-11-05, Эльбрус E8C2, Elbrus Linux 8.1)
 *
 * Контроль прошёл на цели как на модели: `пусть с = "абв"` + `с[0]` печатью → **1072**, код 0
 * (`.tmp/a621-hw/`, sha256 3/3 до прогона, по 3 прогона). А на границе модель и цель РАЗОШЛИСЬ, и это
 * записано числом: число ИЗ ПАРАМЕТРА — модель **9**, цель **139** (SIGSEGV), 3/3. То есть на цели
 * чтение памяти по адресу-числу падает, а не отдаёт мусор: «тихая ложь» здесь — свойство МОДЕЛИ, и
 * отказ `OSN-LOW-003` на сборке не даёт получить на цели 139 вместо числа.
 */

import { describe, it, expect } from 'vitest';
import { loweredProgram } from './lowered';
import { parseV3 } from '../compiler-v3/index';
import type { CompileOptions } from '../compiler/compiler';

const ФАЙЛ = 'проба.osnova';

interface Отказ {
  readonly код: string;
  readonly причина: string;
  readonly шаг: number;
}

/** Отказы понижения; БРОСОК компилятора возвращается отдельной записью — он тоже отказ, но безымянный. */
function отказы(источник: string): readonly Отказ[] {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор v3 (отказ ждём от понижения, а не от разбора): ${разбор.errors.join('; ')}`).toEqual([]);
  const options: CompileOptions = {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  };
  let итог: ReturnType<typeof loweredProgram>;
  try {
    итог = loweredProgram(источник, options);
  } catch (беда) {
    return [{ код: 'БРОСОК', причина: `бросок компилятора: ${беда instanceof Error ? беда.message : String(беда)}`, шаг: -1 }];
  }
  if (итог.ок) return [];
  return итог.отказ.отказы.map((запись) => ({ код: запись.код, причина: запись.причина, шаг: запись.шаг }));
}

/** Одна процедура-действие с телом. */
function программа(тело: readonly string[]): string {
  return ['действие главная()', ...тело.map((строка) => `  ${строка}`), 'конец главная', ''].join('\n');
}

// ─────────────────────────────────────────────────────────────────────────────
// 1. ОРАКУЛ ВЛАДЕЛЬЦА: ЧИСЛО В БАЗЕ — НАЗВАННЫЙ ОТКАЗ
// ─────────────────────────────────────────────────────────────────────────────

describe('2.1 (D4): индекс по числу — названный отказ, а не чтение памяти', () => {
  it('`пусть а = 5` + `вернуть а[0]` — отказ ПО ИМЕНИ (замер до правки: код 9, отказов 0)', () => {
    const причины = отказы(программа(['пусть а = 5', 'вернуть а[0]']));
    expect(причины.length, 'ровно один отказ — иначе названо не то').toBe(1);
    const отказ = причины[0]!;
    expect(отказ.код, 'код контракта: операция рантайма не поддержана для такого значения').toBe('OSN-LOW-003');
    expect(отказ.причина, 'конструкция названа').toContain('система.массив.получить');
    expect(отказ.причина, 'величина названа — иначе читатель не отличит литерал от рантайм-значения').toContain(
      'ЧИСЛО, известное на сборке (5)',
    );
    expect(отказ.причина, 'причина называет класс').toContain('тихая ложь');
  });

  it('ШАГ отказа — тот самый носитель (D11): номер в причине и номер шага совпадают', () => {
    const причины = отказы(программа(['пусть а = 5', 'вернуть а[0]']));
    const отказ = причины[0]!;
    const названныйВПричине = /^#(\d+)\s/u.exec(отказ.причина)?.[1];
    expect(названныйВПричине, 'причина начинается с номера носителя').toBeDefined();
    expect(отказ.шаг, 'шаг отказа — номер ТОГО ЖЕ носителя, а не «до потока» и не 0').toBe(Number(названныйВПричине));
  });

  it('число, СОСЧИТАННОЕ на сборке, тоже число: `пусть а = 5 + 2` + `а[0]`', () => {
    const причины = отказы(программа(['пусть а = 5 + 2', 'вернуть а[0]']));
    expect(причины.length).toBe(1);
    expect(причины[0]!.код).toBe('OSN-LOW-003');
    expect(причины[0]!.причина, 'названа СОСЧИТАННАЯ величина — 7, а не литерал 5').toContain('ЧИСЛО, известное на сборке (7)');
  });

  it('`а[0] = 7` по числу — тот же отказ в ветви ЗАПИСИ', () => {
    const причины = отказы(программа(['пусть а = 5', 'а[0] = 7', 'вернуть 1']));
    expect(причины.length).toBe(1);
    expect(причины[0]!.код).toBe('OSN-LOW-003');
    expect(причины[0]!.причина).toContain('система.массив.установить');
    expect(причины[0]!.причина).toContain('ЧИСЛО, известное на сборке (5)');
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// 2. КОНТРОЛИ: СТРОКА И МАССИВ РАБОТАЮТ (правка не отнимает ничего)
// ─────────────────────────────────────────────────────────────────────────────

describe('2.1: контроль — законные базы не задеты', () => {
  it('`пусть с = "абв"` + `с[0]` — отказов НЕТ (код символа берётся, замер: модель печатает 1072)', () => {
    expect(отказы(программа(['пусть с = "абв"', 'вернуть с[0]']))).toEqual([]);
  });

  it('`пусть с = "абв"` + `длина с` — отказов НЕТ', () => {
    expect(отказы(программа(['пусть с = "абв"', 'вернуть длина с']))).toEqual([]);
  });

  it('литерал массива `[1, 2]` + `a[0]` — отказов НЕТ (иначе правило съело бы массивы)', () => {
    expect(отказы(программа(['пусть a = [1, 2]', 'вернуть a[0]']))).toEqual([]);
  });

  it('массив-ПАРАМЕТР `a: Список Число` + `a[0]` — отказов НЕТ; ЭТО И ЕСТЬ причина узкого правила', () => {
    const источник = [
      'процедура первый(a: Список Число) -> Число',
      '  вернуть a[0]',
      'конец первый',
      '',
      'действие главная()',
      '  вернуть первый([1, 2])',
      'конец главная',
      '',
    ].join('\n');
    expect(отказы(источник), 'происхождения у параметра нет, но это ЗАКОННЫЙ массив').toEqual([]);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// 3. НАЗВАННАЯ ГРАНИЦА: НЕИЗВЕСТНОЕ ПРОИСХОЖДЕНИЕ (ШАГ 2.3) — СВИДЕТЕЛЬ, НЕ ЭТАЛОН
// ─────────────────────────────────────────────────────────────────────────────

describe('2.1 + 2.3: база типа «Число» ловится отказом по имени (нагрузка пары — остаток границы)', () => {
  it('`процедура ф(а: Число)` + `а[0]` — отказ ПО ИМЕНИ: причина называет тип «Число» и процедуру «ф»', () => {
    // ИСТОРИЯ (заменена фактом, а не удалена): до шага 2.3 эта же программа СОБИРАЛАСЬ с НУЛЁМ отказов,
    // а модель давала код 9 — чтение ПАМЯТИ по адресу-числу и тихую ложь (случай 73 реестра).
    // Теперь массивность берётся ИЗ ТИПА, поэтому отказ есть, и он назван.
    const источник = [
      'процедура ф(а: Число) -> Число',
      '  вернуть а[0]',
      'конец ф',
      '',
      'действие главная()',
      '  вернуть ф(5)',
      'конец главная',
      '',
    ].join('\n');
    const причины = отказы(источник);
    expect(причины.length, 'ровно один отказ — база-ЧИСЛО названа, а не прочитана память').toBe(1);
    const отказ = причины[0]!;
    expect(отказ.код, 'код контракта: операция рантайма не поддержана для такого значения').toBe('OSN-LOW-003');
    expect(отказ.причина, 'конструкция названа').toContain('система.массив.получить');
    expect(отказ.причина, 'массивность взята ИЗ ТИПА, а не из происхождения значения').toContain('база — ЧИСЛО по ТИПУ');
    expect(отказ.причина, 'назван ТИП — иначе читатель не отличит его от значения').toContain('«Число»');
    expect(отказ.причина, 'назван ПАРАМЕТР процедуры — иначе отказ неотличим от чужого').toContain(
      'параметр процедуры «ф»',
    );
    expect(отказ.причина, 'причина называет класс').toContain('тихая ложь');
    const названныйВПричине = /^#(\d+)\s/u.exec(отказ.причина)?.[1];
    expect(названныйВПричине, 'причина начинается с номера носителя').toBeDefined();
    expect(отказ.шаг, 'шаг отказа — номер ТОГО ЖЕ носителя').toBe(Number(названныйВПричине));
  });

  it('нагрузка пары `Результат<Строка, …>` — остаётся без отказа и после 2.3 (0 отказов, свидетель 73)', () => {
    const источник = [
      'процедура добыть(с: Строка, ч: Число) -> Результат<Строка, Число>',
      '  если ч > 0',
      '    вернуть Успех(с)',
      '  конец если',
      '  вернуть Неудача(7)',
      'конец добыть',
      '',
      'действие главная()',
      '  пусть тег, нагрузка = добыть("абв", 5)',
      '  вернуть нагрузка[0]',
      'конец главная',
      '',
    ].join('\n');
    expect(отказы(источник)).toEqual([]);
  });
});
