/**
 * D13: НА ОТКАЗЕ ПОТОК ПУСТ — ЧИСЛА ПОД ОТКАЗОМ НЕ СУЩЕСТВУЕТ (D13 + D12).
 *
 * Что утверждается и почему именно так:
 *   • ОТКАЗ РАСКЛАДКИ не отдаёт ни носителей, ни байт: прежде `fail()` в `src/e2k/regAlloc.ts` клал
 *     в результат исходный поток, носители сохраняли регистры, которых раскладка не выдавала, и из
 *     этого мусора собирался образ — седьмая ложь (`src/e2k/calleeJoinLie.test.ts`).
 *   • «ПУСТО» — это НОЛЬ байт: на отказе раскладки образ не строится вовсе
 *     (`src/e2k/guards/loweredUnchecked.ts`). Замеры, между которыми эта проверка различает:
 *     **776** байт до D13 (неразложенный поток процедуры), **88** — если пустой поток всё-таки
 *     пропустить через построение образа (образ пустого потока = пролог), **0** — после D13.
 *   • ЧИСЛО ОТКАЗОВ — отдельное утверждение, а не украшение (замер 2026-10-29): на пустом потоке
 *     построение образа синтезирует выход точки входа (`IR.jmp`), цель которого посчитана по ПОЛНОМУ
 *     потоку, и в отказ добавляется ВТОРАЯ, ЛОЖНАЯ запись — `OSN-LOW-007` «цель перехода #4 вне потока
 *     (инструкций 1)», приписанная ЧУЖОЙ процедуре («п»). Читатель же берёт `отказы[0]`
 *     (`src/e2k/lowered.ts#отказИз`) — то есть получил бы ложную причину вместо названной. Поэтому
 *     проверка требует РОВНО ОДИН отказ и что он — раскладочный.
 *   • ОБЕ СТОРОНЫ: та же форма программы, которая влезает, поток ИМЕЕТ; иначе «пусто» ничего не значит.
 *   • ГРАНИЦА: отказ НОСИТЕЛЕЙ (раскладка прошла) поток СОХРАНЯЕТ — D13 чистит только отказ
 *     `allocateProgram`, и это записано проверкой, а не словом.
 *   • БУКВА D13 (PHASE-05/TASK-05-01): сам `allocateProgram` при отказе отдаёт ПУСТОЙ контрактный
 *     поток, а неразложенный — отдельным полем `diagnostic` (с теми же смещениями процедур).
 *
 * Различающая сила доказана замером ДО правки (`.tmp/a5z3-refusalStream-before.out.txt`): этот сторож
 * на непочиненном дереве давал `expected 776 to be 88` — красной была ровно проверка пустоты, а обе
 * стороны (сборка и граница) — зелёными.
 */
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3/index';
// Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { allocateProgram } from './regAlloc';
import { CALLEE_REGISTERS } from './twoPassLayout';
import { entryProcedureIndex } from './procedureCall';
import { regModuleWithRecordPlan } from './recordPlan';
import { annotateAtomRegions } from '../compiler/atomRegions';
import { emitShell } from './emitterShell';
import { getEncoder } from './backend';
import { MAX_SPILLS_PER_PROCEDURE } from '../vliw/spill';

const ФАЙЛ = 'проба-отказа.osnova';

/** Репро перегрузки вызываемой — та же форма, что в `src/e2k/spillCallee.test.ts` П7. */
const дыра = (n: number): string => {
  const строки = ['процедура п() -> Число', '  вернуть 1', 'конец п', 'процедура ф(а: Число) -> Число'];
  for (let k = 1; k <= n; k++) строки.push(`  пусть р${String(k)} = а + ${String(k)}`);
  let выражение = `р${String(n)}`;
  for (let k = n - 1; k >= 1; k--) выражение = `р${String(k)} + (${выражение})`;
  строки.push(`  вернуть ${выражение}`, 'конец ф', 'действие главная()', '  пусть х = п()', '  вернуть ф(1)', 'конец главная', '');
  return строки.join('\n');
};

/**
 * ЛЕСТНИЦА — репро, которому нужно БОЛЬШЕ ВОСЬМИ вытеснений (перемер 2026-11-07, ATOM-07-02).
 *
 * Зачем новая форма. `дыра(n)` исчерпана замером: n ≤ 21 требует не больше 8 вытеснений (при пределе 8
 * раскладывается), а n ≥ 22 упирается в шестибитное поле оболочки (`move: регистр 64 не выражается
 * полем оболочки`) ЕЩЁ ДО раскладки — то есть отказа раскладки там нет вовсе. Контракт D13 обязан
 * наблюдаться при ЛЮБОМ действующем пределе, поэтому репро должно упираться ЗАВЕДОМО выше него.
 *
 * Здесь n значений `а + k` объявлены ДО первого чтения (живы одновременно), а сумма накапливается по
 * одному, поэтому vreg'ов нужно ~n, а не ~2n, и форма доживает до больших вытеснений, не упираясь в
 * поле оболочки. ИЗМЕРЕНО (`08`-прибор, предел 4…24): нужно ровно **10** вытеснений — пределы 4…9
 * отказывают словами «значений в память нужно больше N», предел 10 раскладывается, потратив 10
 * слотов. Неразложенных носителей в `diagnostic` — **188**.
 */
const лестница = (n: number): string => {
  const строки = ['процедура п() -> Число', '  вернуть 1', 'конец п', 'процедура ф(а: Число) -> Число'];
  for (let k = 1; k <= n; k++) строки.push(`  пусть р${String(k)} = а + ${String(k)}`);
  строки.push('  пусть с = 0');
  for (let k = 1; k <= n; k++) строки.push(`  с = с + р${String(k)}`);
  строки.push('  вернуть с', 'конец ф', 'действие главная()', '  пусть х = п()', '  вернуть ф(1)', 'конец главная', '');
  return строки.join('\n');
};

/** Та же форма, но раскладка проходит: обратная сторона проверки. */
const простая = [
  'процедура ф(а: Число) -> Число',
  '  вернуть а + 1',
  'конец ф',
  'действие главная()',
  '  вернуть ф(1)',
  'конец главная',
  '',
].join('\n');

type Итог = ReturnType<typeof loweredProgramUnchecked>;
const понизить = (источник: string): Итог => {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  return loweredProgramUnchecked(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
};

const раскладочные = (итог: Итог): readonly string[] =>
  итог.отказы.filter((отказ) => отказ.причина.startsWith('раскладка отказала')).map((отказ) => отказ.причина);

/**
 * РАСКЛАДКА ПРИ ЗАДАННОМ ПРЕДЕЛЕ — прибор, чтобы контракт D13 НЕ БЫЛ ПОДОБРАН под константу.
 *
 * Проверка «под отказом поток пуст» имеет смысл, только если программа ДЕЙСТВИТЕЛЬНО упирается в
 * предел. Поэтому предел здесь — параметр: сначала измеряется, сколько вытеснений нужно, и только
 * потом проверяется контракт. Если кто-то поднимет `MAX_SPILLS_PER_PROCEDURE` выше нужды, проверка
 * покраснеет с ЧИСЛОМ («нужно 10, а предел 12»), а не станет слепой молча.
 */
function раскладка(источник: string, предел: number): ReturnType<typeof allocateProgram> {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, 'разбор программы').toEqual([]);
  const built = regModuleWithRecordPlan(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (built === null) throw new Error('программа не компилируется');
  const annotated = annotateAtomRegions(built.module, [
    { atom: 'A5', procedures: built.module.procedures.map((процедура) => процедура.name) },
  ]);
  const emitted = emitShell(annotated, getEncoder('internal-shell'));
  const вход = entryProcedureIndex(emitted.scheduled.procedures);
  return allocateProgram(emitted.instructions, emitted.scheduled.procedures, {
    freeFor: (at) => (at === вход ? undefined : CALLEE_REGISTERS),
    spill: { base: 0, maxSlots: предел },
  });
}

/** Наименьший предел, при котором раскладка проходит: СТОЛЬКО вытеснений программе и нужно. */
function нужноВытеснений(источник: string): number {
  for (let предел = 0; предел <= 40; предел++) {
    if (раскладка(источник, предел).report.every((item) => item.ok)) return предел;
  }
  throw new Error('раскладка не проходит даже при пределе 40 — репро сломалось, а не контракт');
}

describe('D13: на отказе поток ПУСТ — числа под отказом не существует', () => {
  // ПЕРЕМЕР 2026-11-07 (ATOM-07-02, «контракт D13»). Прежнее репро `дыра(18)` было подобрано под
  // предел 4 и при подъёме предела до 8 ПЕРЕСТАВАЛО отказывать — сторож становился слепым (замер:
  // поднятая константа краснила РОВНО проверки 1 и 4 этого файла). Замеренная граница `дыра(n)`:
  //
  // | n | что происходит |
  // |---|---|
  // | 14..17 | отказ НОСИТЕЛЕЙ (`IR.spill_st`), раскладка проходит — граница проверки 3 |
  // | 18 | отказ раскладки ТОЛЬКО при пределе 4 (нужно 5) |
  // | 21 | нужно ровно 8 — при пределе 8 РАСКЛАДЫВАЕТСЯ (то есть репро исчерпано) |
  // | 22..30 | отказ ОБОЛОЧКИ до раскладки: `move: регистр 64 не выражается полем оболочки` |
  //
  // Поэтому контракт («ноль байт, ровно один отказ, отказ называет процедуру») переведён на
  // `лестница(22)`: ей нужно **10** вытеснений, и она отказывает при любом пределе 4…9 — то есть
  // проверка не подобрана под одну редакцию константы. Нужда ИЗМЕРЯЕТСЯ здесь же, а не предполагается.
  it('1. ОТКАЗ: ноль байт, РОВНО ОДИН отказ, и он называет ПРОЦЕДУРУ', () => {
    const нужно = нужноВытеснений(лестница(22));
    expect(
      нужно,
      `репро обязано упираться ВЫШЕ действующего предела (нужно ${String(нужно)}, ` +
        `предел ${String(MAX_SPILLS_PER_PROCEDURE)}) — иначе контракт «на отказе» не наблюдается`,
    ).toBeGreaterThan(MAX_SPILLS_PER_PROCEDURE);
    const итог = понизить(лестница(22));
    const отказы = раскладочные(итог);
    // ИМЯ ПРОЦЕДУРЫ — не «что-то отказало»: отказ без имени неотличим от чужого (ловушка `report[0]`).
    expect(отказы.length, 'отказ раскладки назван').toBe(1);
    expect(отказы[0], 'в причине ИМЯ процедуры').toContain('процедура «ф»');
    expect(отказы[0], 'и её причина').toContain('вытеснение не минимально');
    // РОВНО ОДИН: второй записи быть не должно — это была бы ЛОЖНАЯ «цель перехода вне потока»,
    // приписанная чужой процедуре, и она встала бы ПЕРВОЙ (`src/e2k/lowered.ts:58` читает `отказы[0]`).
    expect(итог.отказы.length, 'ложной записи «цель перехода вне потока» нет').toBe(1);
    expect(итог.отказы[0]?.код, 'код отказа').toBe('OSN-LOW-004');
    // ПУСТО: байт нет вовсе. До D13 здесь было 776 — неразложенный поток (мусор по построению), и
    // образ из него считался числом.
    expect(итог.bytes.length, 'под отказом байт нет').toBe(0);
  });

  it('2. СБОРКА: та же форма, которая влезает, поток ИМЕЕТ', () => {
    const итог = понизить(простая);
    expect(итог.отказы.length, 'отказов нет').toBe(0);
    expect(итог.bytes.length, 'поток есть').toBeGreaterThan(0);
  });

  it('3. ГРАНИЦА: `дыра(14..17)` — отказ НОСИТЕЛЕЙ, а НЕ отказ allocateProgram; поток сохранён', () => {
    // ЭТО НЕ ОТКАЗ `allocateProgram`: раскладка ПРОШЛА (в отчёте нет ни одной записи `ok:false`),
    // отказали НОСИТЕЛИ на понижении (`IR.spill_st`: вытеснение из вызываемой невозможно). D13 чистит
    // только отказ раскладки, поэтому здесь поток ОБЯЗАН сохраниться — иначе сторож однажды покраснеет
    // на здоровом образе, а «пусто на отказе» превратится в «пусто всегда».
    for (const n of [14, 15, 16, 17] as const) {
      const итог = понизить(дыра(n));
      expect(раскладочные(итог), `n=${String(n)}: отказа раскладки НЕТ`).toEqual([]);
      expect(итог.отказы.length, `n=${String(n)}: отказы носителей есть`).toBeGreaterThan(0);
      expect(итог.bytes.length, `n=${String(n)}: поток сохранён (не пусто)`).toBeGreaterThan(0);
    }
  });

  it('4. БУКВА D13 в самом allocateProgram: контракт пуст, неразложенный поток — в `diagnostic`', () => {
    // Воспроизводим на уровне API раскладки (ATOM-05-01-01): ДО правки контрактный поток при отказе
    // был НЕПУСТ (замер `.tmp/a501-oracle.ts` на дереве HEAD `941de33` — 64 носителя при отказе `ф`),
    // и любой новый потребитель мог собрать из него образ — мусор по построению. Теперь контракт
    // пуст, а неразложенный поток со СВОИМИ смещениями процедур лежит в `diagnostic`.
    //
    // РЕПРО — `лестница(22)`, а не `дыра(18)`: последней нужно 5 вытеснений, и при поднятом пределе
    // она раскладывается, то есть проверка «на отказе» перестаёт наблюдать отказ (см. перемер в
    // комментарии к первой проверке).
    const источники = лестница(22);
    const разбор = parseV3(источники, ФАЙЛ);
    expect(разбор.errors, 'разбор программы').toEqual([]);
    const built = regModuleWithRecordPlan(источники, {
      filename: ФАЙЛ,
      parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
    });
    if (built === null) throw new Error('программа не компилируется');
    const annotated = annotateAtomRegions(built.module, [
      { atom: 'A5', procedures: built.module.procedures.map((procedure) => procedure.name) },
    ]);
    const emitted = emitShell(annotated, getEncoder('internal-shell'));
    const процедуры = emitted.scheduled.procedures;
    const вход = entryProcedureIndex(процедуры);
    const allocation = allocateProgram(emitted.instructions, процедуры, {
      freeFor: (at) => (at === вход ? undefined : CALLEE_REGISTERS),
    });
    expect(allocation.report.some((item) => !item.ok), 'проба — отказ раскладки').toBe(true);
    // КОНТРАКТ: пусто.
    expect(allocation.instructions, 'контрактный поток при отказе ПУСТ').toEqual([]);
    // ДИАГНОСТИКА: тот же неразложенный поток и оглавление процедур при нём — разойтись им неоткуда,
    // они отдаются одним полем. Число носителей — ЗАМЕР (`07-04-d13-numbers.ts`): 188.
    expect(allocation.diagnostic, 'диагностический поток при отказе ЕСТЬ').toBeDefined();
    expect(allocation.diagnostic?.instructions.length, 'неразложенных носителей').toBe(188);
    expect(
      allocation.diagnostic?.procedures.map((процедура) => процедура.name),
      'смещения процедур при диагностическом потоке',
    ).toEqual(процедуры.map((процедура) => процедура.name));
    // ОТЧЁТ: причина отказа названа с именем процедуры — никуда не делись.
    const отказ = allocation.report.find((item) => !item.ok)!;
    expect(отказ.reason ?? '', 'причина отказа с числами').toContain('вытеснение не минимально');
    // ГРАНИЦА: та же форма, которая влезает, — контрактный поток ЕСТЬ, диагностического НЕТ.
    const успех = понизить(простая);
    expect(успех.отказы.length, 'контроль: отказов нет').toBe(0);
    expect(успех.bytes.length, 'контроль: поток есть').toBeGreaterThan(0);
  });
});
