/**
 * ТИПЫ ДВЕРИ D11: `Результат<Образ, Отказ>` — публичный ответ понижения, и СЫРОЙ образ для сторожей.
 *
 * # Зачем два разных ответа
 *
 * До 5е понижение отдавало ОДИН ответ: `{ bytes, refused, … }`, и байты лежали в нём ВСЕГДА — в том
 * числе под несущим отказом, когда они ЛГУТ (шестая и седьмая тихие лжи, случаи 60 и 62 реестра
 * проверяемости). Потребителю, забывшему посмотреть `refused`, доставались лживые байты, и ни один тип
 * его не останавливал: «отказ есть» и «байтов нет» были не связаны.
 *
 * Теперь связаны ТИПОМ: у {@link Отказ} поля `bytes` нет вовсе, поэтому взять байты под отказом нельзя
 * даже случайно — `tsc` не пропустит. Кто хочет смотреть под отказом (сторож), идёт в отдельную дверь
 * (`src/e2k/guards/loweredUnchecked.ts`) и делает это ЯВНО.
 *
 * # Границы
 *
 * Типы — не защита от злого умысла: `Unchecked` рядом в коде читается как красный флаг на ревью, а
 * ESLint (правило по пути и правило по идентификатору) ловит обычные способы обойти дверь. Это барьер.
 */
import type { LoweringRefusal, LoweringRefusalCode } from './loweringRefusal';

/**
 * ШАГ ОТКАЗА, ПРИНЯТОГО ДО ПОТОКА НОСИТЕЛЕЙ: `-1`.
 *
 * Отказы стадий (планирование строк, разведение арены и кучи, коллекции) рождаются ДО того, как поток
 * носителей обработан, поэтому номера шага у них нет. Раньше здесь стоял `0` — и это было НЕ ОТСУТСТВИЕ,
 * а ложное «шаг нулевой»: `0` — законный индекс первого носителя, поэтому отказ стадии приписывался
 * ПЕРВОЙ процедуре потока, хотя в тексте причины назван, скажем, носитель `#142` из другой. Сторож
 * поймал это на теле лексера (20 отказов стадий называли носители, а `шаг` у всех был `0`).
 *
 * Теперь отсутствие видно отдельным значением, и публичная диагностика отвечает на него честно:
 * `процедура: '(до потока носителей)'`, `шаг: 0`.
 */
export const ШАГ_ДО_ПОТОКА = -1;

/** Одна запись отказа: ЧТО случилось, в КАКОЙ процедуре и на КАКОМ шаге (индексе носителя). */
export interface ОтказЗапись {
  /**
   * КОД причины (`OSN-LOW-*`) — личность отказа, а не текст. Без него наблюдатель выводил бы класс из
   * формулировки, то есть переписанная фраза молча ослепила бы его (`src/e2k/loweringRefusal.ts`,
   * шапка). Поэтому код входит в публичную диагностику наравне с причиной.
   */
  readonly код: LoweringRefusalCode;
  readonly причина: string;
  readonly процедура: string;
  /**
   * Индекс носителя в потоке образа; у отказов ДО ПОТОКА — `0` и `процедура='(до потока носителей)'`.
   */
  readonly шаг: number;
}

/**
 * ОТКАЗ публичной двери. Байтов здесь НЕТ и быть не может: под несущим отказом они лгут.
 *
 * Имя процедуры обязательно (`процедура` в каждой записи и `процедуры` списком): молчаливый отказ без
 * имени — четвёртая тихая ложь, случай 58 реестра («отказ по всем записям, и с именем»).
 */
export interface Отказ {
  /** Первая причина — то, с чего начинается разбор; полный список — в `отказы`. */
  readonly причина: string;
  /** Процедуры, которых отказ коснулся, в порядке появления (без повторов). */
  readonly процедуры: readonly string[];
  readonly отказы: readonly ОтказЗапись[];
  /**
   * СКОЛЬКО БАЙТОВ собрал сырой путь — ЧИСЛО, а не байты. Дверь их не отдаёт (D11: под отказом они
   * лгут), но размер — измерение, и он закреплён оракулами.
   *
   * **ПОД ОТКАЗОМ ЭТО ЧИСЛО — НОЛЬ (D13, 2026-10-29, срез 5з).** Прежде здесь стояло «у лексера с
   * ареной образ 65536 байт при 101 отказах» — и это было ЧИСЛО ИЗ НЕРАЗЛОЖЕННОГО ПОТОКА, то самое
   * «число под отказом», которого не существует: неразложенные носители — мусор по построению (они
   * сохраняют регистры, которых раскладка не выдавала), а стендовый путь читал их как исполняемое
   * (`executableThroughReal: true`, 592 байта). Теперь на отказе раскладки байты гасит И дверь
   * (`bytes` пусты), И второй потребитель (`runKernelThroughRealEncoding` не кодирует вовсе) — оба
   * закрыты замером, а списки отказов при этом ЦЕЛЫ (тело лексера 101, файл 132, файл целиком 75).
   * Остаток ИСПОЛНЕН (буква D13, PHASE-05/TASK-05-01): `allocateProgram` отдаёт пустой контрактный
   * поток, а неразложенный — отдельным полем `diagnostic`; число и диагностику из него берут только
   * сторожа, глядящие под отказом ЯВНО (`src/e2k/guards/loweredUnchecked.ts`).
   *
   * Это не лазейка: байты по-прежнему недоступны, а под отказом недоступно и число.
   */
  readonly кодовБайт: number;
}

/** ОБРАЗ публичной двери: понижение прошло БЕЗ отказов, байты пригодны. */
export interface Образ {
  readonly bytes: Uint8Array;
  readonly used: number;
  readonly arena: { readonly used: boolean; readonly extraMemory: number };
}

/** Результат двери: либо образ, либо отказ — третьего нет. */
export type Результат<T, О> =
  | { readonly ок: true; readonly значение: T }
  | { readonly ок: false; readonly отказ: О };

/**
 * СЫРОЙ образ — только для сторожей. Байты есть ВСЕГДА; отказы лежат и кодом (`refused`), и
 * диагностикой (`отказы`, `refusedSteps`).
 */
export interface СыройОбраз {
  readonly bytes: Uint8Array;
  readonly refused: readonly LoweringRefusal[];
  /** Шаг каждого отказа; длина совпадает с `refused`. */
  readonly refusedSteps: readonly number[];
  readonly отказы: readonly ОтказЗапись[];
  readonly used: number;
  readonly arena: { readonly used: boolean; readonly extraMemory: number };
}
