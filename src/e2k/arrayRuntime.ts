/**
 * Носитель пролога значений: `IR.array_values` с базой блока в операнде 0.
 *
 * Пролог идёт НОСИТЕЛЕМ, а не готовыми командами в потоке, ровно по одной причине: форму регистров
 * выбирает конвейер. У вызываемой весь её понижённый код переводится в оконную форму (`%rN`) одним
 * преобразованием, и вставленная в поток готовая команда осталась бы базовой (`%b[N]`) — то есть
 * писала бы в клетки ЧУЖОЙ плоскости (это и есть механизм §3.127).
 */
export const ARRAY_VALUES_CARRIER = 'IR.array_values';

/**
 * Носитель АДРЕСА ЯЧЕЙКИ КУЧИ в плоскости вызываемой: `IR.array_slot` с адресом в операнде 0.
 *
 * Зачем ОТДЕЛЬНЫМ носителем, а не третьим шагом {@link ARRAY_VALUES_CARRIER}: у шага своя ФОРМА
 * (ровно одна `movtd`), и её длину раскладка обязана знать заранее
 * (`src/e2k/twoPassLayout.ts#carrierFormWithReason`) — а сторож обязан уметь проверить ИМЕННО шаг
 * адреса (`checkArraySequence`). Пролог значений (0 и 8) от этого не меняется ни на команду.
 *
 * Кладёт его ПРОЛОГ РОСТА вызываемой (`windowGrowthAt` в `src/e2k/programImage.ts`) — в ту же
 * группу, что рост окна и значения: адрес обязан лечь ПОСЛЕ `setwd`/`setbn`, иначе `movtd … %b[15]`
 * пишет в негодное окно (измерено: та же ошибка порядка давала ловушку, §3.116).
 */
export const ARRAY_SLOT_CARRIER = 'IR.array_slot';

/**
 * НОЛЬ ВЫЗЫВАЕМОЙ ПО ПОСТРОЕНИЮ: `movts 0 → %r(ARRAY_REGISTERS.zero)` в прологе КАЖДОЙ вызываемой.
 *
 * # Зачем это отдельный носитель, а не строка в прологе роста окна
 *
 * Пролог роста ({@link WINDOW_GROW_CARRIER}) ставится только ТОЙ процедуре, которая сама вызывает
 * (`windowGrowthAt`, §3.56.5): точке входа он не нужен, а **листовой вызываемой — тем более**. Но
 * клетка нуля нужна как раз листовой: `если а >= 48 и а <= 57` внутри процедуры — это переход,
 * ветвящийся ПО ЗНАЧЕНИЮ (`src/e2k/predicatePairing.ts#VALUE_BRANCH_JUMP`), и его `cmpesb значение,
 * НОЛЬ` без клетки нуля считать нечего. Поэтому ноль ставится ВСЕМ вызываемым, а не только
 * вызывающим.
 *
 * # Почему ноль, а не константа в команде
 *
 * `cmpesb` берёт второй операнд регистром (форма ALF7, `src/e2k/twoPassLayout.ts#ARRAY_COMMAND_FORMS`
 * и таблица сравнений): непосредственного литерала у неё нет. Значит клетка, равная нулю, обязана
 * СУЩЕСТВОВАТЬ в плоскости вызываемой — и быть нулём по построению, а не «сейчас там ноль».
 *
 * # Почему номер берётся у `ARRAY_REGISTERS.zero`
 *
 * Понижение перехода по значению читает эту же клетку (`e2kRealRun.ts`,
 * `valueBranchJumpCommands(…, reg(ARRAY_REGISTERS.zero), …)`), а из пула раскладки она выведена
 * там же, где объявлен бюджет (`src/e2k/twoPassLayout.ts#CALLEE_ZERO_CELL`). Разойтись записям
 * «какую клетку зануляем» и «какую читаем» нечем: номер один.
 *
 * # Место в прологе — ПОСЛЕ роста окна
 *
 * `setwd` меняет геометрию окна, то есть переводит `%rN` на другие физические регистры. Ноль,
 * положенный ДО роста, после `setwd` оказался бы не в той клетке, которую прочтёт `cmpesb`. Поэтому
 * носитель встаёт в группу последним (перед первым носителем тела) — `windowGrowthAt`,
 * `src/e2k/programImage.ts`.
 */
export const CALLEE_ZERO_CARRIER = 'IR.callee_zero';

/** Единственная команда носителя {@link CALLEE_ZERO_CARRIER}: `movts 0` в клетку нуля. */
export function calleeZeroInstructions(): [AsmInstruction] {
  return [{ mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 0 }, reg(ARRAY_REGISTERS.zero)] }];
}

/** Размер блока рантайма в клетках: ноль, единица, восемь, временный, второй временный. */
export const ARRAY_BLOCK_SIZE = 5;
export const ARRAY_RESERVED_BYTES = 8 + 14 * 8;

/**
 * РАЗМЕР БЛОКА РАНТАЙМА В ВЫЗЫВАЕМОЙ: три клетки, БЕЗ постоянной единицы (A4, §3.135).
 *
 * # Почему это не «на единицу меньше»
 *
 * Точка входа держит в клетках `%b[12]`, `%b[13]`, `%b[14]` **постоянные** 0, 1, 8 — их читают и
 * другие рантаймы (печать, строки, коллекции), и там они окупаются: константа ставится один раз на
 * программу, а операций много. У вызываемой эта сделка **не работает**: её плоскость — СВОЯ, пролог
 * образа заполняет клетки своей плоскости, поэтому ради пяти клеток отдаётся больше половины
 * бюджета (`%b[8..15]` — восемь клеток), а рядом живут значения записи — и пятёрка в бюджет НЕ
 * ВЛЕЗАЕТ.
 *
 * Замер 2026-10-24 (`.tmp/osnova-3135-k1k2.ts`): **то же самое чтение** `вернуть а[1]` в вызываемой
 * понижается (пятёрка влезает), а `а[0] = 7` + `вернуть а[0]` — НЕТ (не влезает, `OSN-LOW-003`
 * «раскладка не выдала базу блока рантайма»). Стена РАЗМЕРНАЯ.
 *
 * # Что вместо постоянных
 *
 * Сами последовательности операций НЕ меняются (иначе раскладка, берущая длину понижения без
 * плоскости, разошлась бы с понижением — §3.35). Постоянные ставит **пролог значений вызываемой**
 * ({@link arrayValuePrologue}) — два `movts` вместо трёх, потому что единица нужна только
 * `добавить`, а `добавить` в вызываемой отказывает (пяти его ролям нужно пять клеток бюджета).
 * Временных — одно (`scratch`), а не два: второй нужен ровно той же операции `добавить`.
 *
 * Итог: **три клетки вместо пяти**, и в бюджете вызываемой остаётся пять под значения вместо трёх.
 * Постоянные 0/1/8 в точке входа не тронуты: их читают другие рантаймы, и сдвиг этих клеток сдвинул
 * бы закреплённые числа пяти ядер (§3.34.4).
 */
export const CALLEE_ARRAY_BLOCK_SIZE = 3;

/**
 * Клетки блока вызываемой — по РОЛЯМ, как у точки входа, но без единицы и второго временного.
 *
 * `one` и `scratch2` — псевдонимы, а не клетки: их читает только `добавить`, а он в вызываемой
 * отказывает по имени и ИМЕННО ИЗ-ЗА ЭТОГО (пяти различным ролям нужно пять клеток, а бюджет даёт
 * три). Общие имена оставлены, чтобы разбор ролей в `lowerArrayCall` был один и тот же для обеих
 * плоскостей. `создать` этими псевдонимами не пользуется вовсе — ему хватает трёх клеток, и с A4
 * (§3.137) оно в вызываемой работает.
 */
export function calleeArrayCells(base: number): {
  readonly zero: number;
  readonly one: number;
  readonly eight: number;
  readonly scratch: number;
  readonly scratch2: number;
} {
  return { zero: base, one: base, eight: base + 1, scratch: base + 2, scratch2: base + 2 };
}

