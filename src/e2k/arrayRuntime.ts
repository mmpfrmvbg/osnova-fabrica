/**
 * Размер окна (`setbn rsz`), при котором верхние регистры рантайма **адресуемы**.
 *
 * `%b[N]` существует только внутри текущего окна: индекс переводится в физический регистр как
 * `(wd_base_d + idx) % MAXSR_D`, а выход за `size_d` — исключение `exc_window_bounds`
 * (`qemu/target/e2k/reg-index.h:55-81`). Измерено (`.tmp/rsz-sweep.ts`): при `rsz = 5` доступны
 * `%b[0..11]`, при `rsz = 6` — `%b[0..13]`, при `rsz = 7` — `%b[0..15]`.
 *
 * # ЧТО ЗДЕСЬ БЫЛО НЕВЕРНО (замер 2026-11-04, §3.163): «`rsz ≥ 8` не работает ВОВСЕ» — ЛОЖЬ
 *
 * Прежняя редакция объясняла отказ через «начальные `psize_q = 4`, `size_q = 8` квадрослов
 * (`qemu/linux-user/e2k/cpu_loop.c:302-303`) — не больше 16 единиц» и делала вывод, что предел
 * клеток задаёт `rsz`, упёршийся в 16. Предел клеток `rsz` действительно задаёт, но **формула
 * другая: `%b[N]` законны ровно до `N < 2·(rsz + 1)`**, а не «до 16 при любом `rsz ≥ 7`».
 * Различающие строки при `wsz = 12` (`.tmp/a503-window-formula2.ts`, оракул
 * `src/e2k/windowLimits.test.ts`):
 *
 * | `rsz` | предел `2·(rsz+1)` | предел `2·wsz` | `%b[16]` | `%b[17]` | `%b[18]` | `%b[23]` | `%b[24]` |
 * |---|---|---|---|---|---|---|---|
 * | 7  | **16** | 24 | АВАРИЯ | АВАРИЯ | — | — | — |
 * | 8  | **18** | 24 | ОК | ОК | АВАРИЯ | — | — |
 * | 11 | **24** | 24 | ОК | ОК | ОК | ОК | АВАРИЯ |
 *
 * То есть `rsz = 8` РАБОТАЕТ (и 11, и 15), а прежний замер не различал `wsz` и `rsz`: при
 * `wsz = 8` пара `rsz = 8` негодна по ДРУГОЙ причине — нарушено `rsz + 1 ≤ wsz`, и валит не
 * доступ к клетке, а сам `setbn`. Годность пары — `rsz + 1 ≤ wsz`; `wsz` модель принимает до 112
 * (113 валит сам `setwd`), сходится с `MAXSR_Q = 112`.
 *
 * **Почему это важно для бюджета вызываемой.** Восемь клеток `CALLEE_REGISTERS` (`%b[8..15]`) —
 * это `2·(rsz+1) − 2·CALL_WBS` при `rsz = 7`, то есть НАШ выбор, а не предел железа: при `rsz = 11`
 * у вызываемой законны `%b[0..23]`, своих клеток 16. Стена вытеснения K2 поэтому ПОЛИТИЧЕСКАЯ
 * (константа плюс число в прологе) — и снимать её расширением списка клеток БЕЗ подъёма `rsz`
 * запрещено: `%b[16..19]` при `rsz = 7` незаконны, модель на них валит процесс, а раскладка
 * отказа не даёт — это была бы тихая ложь.
 */
export const ARRAY_WINDOW_RSZ = 7;

/**
 * Размер окна (`setwd wsz`) в прологе образа, в квадрословах: `wsz = 16` — это тридцать две
 * регистровые единицы (`2·16`), из них вызываемой достаётся `2·(16 − 4) = 24`.
 *
 * **Измерено на железе 2026-10-09 (§3.116.1–3):** `wsz > 8` не гипотеза, а ежедневно исполняемая
 * форма у МЦСТ — `/bin/bash` открывает окна `0xc` **165 раз**, `0x12` 87 раз, вплоть до `0x2e`;
 * `lcc` — `0xc` 12, `0x10` 14; те же значения у `as`, `ld`, `ld-linux.so.2`, `/bin/true`, `/bin/ls`.
 * Проба в НАШЕЙ форме подтверждает: `setwd wsz=0xc` + `setbn rbs=4, rsz=7` (годность `4+7+1 = 12`)
 * не падает вовсе (код 124 — петля), а наш прежний пролог без `setwd` падал на первом `%b`.
 *
 * **Почему шестнадцать, а не двенадцать (замер 2026-11-04, §3.166).** Клетки ВЫЗЫВАЕМОЙ даёт `wsz`,
 * а НЕ `rsz`. Спецификация (`OpenE2K/relcc2` `spec/abi/registers.md`) даёт предел
 * `min(2·(rsz + 1), 2·(wsz − wbs))`, а у листовой вызываемой первое слагаемое равно `2`: порт
 * **зануляет `%br` на каждом `call`**, поэтому своего `setbn` у неё нет. Предел задаёт ВТОРОЕ
 * слагаемое, то есть при `wbs = 4` — `2·(wsz − 4)`: `wsz = 12` даёт 16 клеток, `wsz = 16` — 24.
 * Каждое `+1` к `wsz` даёт вызываемой ДВЕ клетки; замер лестницей: `wsz` 12/13/14/16 → 16/18/20/24,
 * и первая недоступная клетка равна `2·(wsz − 4)` во всех четырёх строках.
 *
 * Точке входа подъём не даёт НИЧЕГО: её клетки задаёт `rsz` (`setbn rsz = 7` → `%b[0..15]`, §3.163),
 * и замер §3.166 (строка «`rsz` 7 против 15 при `wsz = 16`») подтверждает, что `rsz` не двигает ни
 * одной клетки. Поэтому {@link ARRAY_WINDOW_RSZ} не тронут, а подъём `rsz` до 11 (план 5з.2 в
 * прежней редакции) **отменён** — он не чинил ничего.
 *
 * **Чего это стоит (названный долг, §3.116.4).** Закон `wsz − wbs = 4` требует, чтобы у `call`
 * было `wbs = wsz − 4`. Наш сайт вызова сейчас `wbs = 4` (номер в `%r8`), поэтому при `wsz = 12`
 * ловушка НЕ бралась: проба `za-w12-t3-wbs4` даёт **137** (`SIGKILL`), а `za-w12-t3-wbs8` (номер в
 * `%r16`) — **42**. Подъём до 16 этого вопроса не решает и не ухудшает: сайт вызова — отдельная
 * работа, и числа §3.116.4 остаются в силе для `wsz = 12`.
 */
export const ARRAY_WINDOW_WSZ = 16;

