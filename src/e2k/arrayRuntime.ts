/**
 * ИНДЕКСАЦИЯ ПО ЗНАЧЕНИЮ, КОТОРОЕ МАССИВОМ БЫТЬ НЕ МОЖЕТ, — НАЗВАННЫЙ ОТКАЗ ВМЕСТО ЧТЕНИЯ ПАМЯТИ.
 *
 * # Что здесь ловится (десятый класс тихой лжи, `docs/verification-debt.md` случай 73; D4)
 *
 * Поверхность v3 выбирает вид индексации по ТИПУ операнда (`src/compiler-v3/parser.ts`: `с[и]` по
 * `Строка` — `система.строка.символ`, по массиву — `система.массив.получить`), но у значения, чей
 * тип не `Строка` и не массив, выбора нет — и она молча берёт МАССИВНУЮ ветвь. Дальше рантайм
 * массивов честно считает адрес от того, что лежит в базе, и читает ПАМЯТЬ по этому адресу:
 * **отказов 0, число неверное**.
 *
 * Замер 2026-11-05 (модель QEMU, `.tmp/a621-*`): `пусть а = 5` + `вернуть а[0]` — код **9** без
 * отказа; `пусть тег, нагрузка = добыть("абв", 5)` + `вернуть нагрузка[0]` — **0** без отказа, хотя
 * база равна адресу байтов строки (1114106), а верный ответ — код «а» = 1072.
 *
 * # Почему правило УЗКОЕ, а не «база обязана быть доказанным массивом»
 *
 * Строгое правило сломало бы РАБОТАЮЩИЕ программы: массив-ПАРАМЕТР (`процедура первый(a: Список
 * Число)` + `a[0]`) понижается верно (замер: 0 отказов), а происхождения у него нет — значение
 * приходит из чужого окна. Поэтому отказ называется только там, где на СБОРКЕ ВИДНО, что база —
 * ЧИСЛО: литерал числа, пересылка числа, арифметика над известными числами, `система.массив.длина`.
 * Число массивом быть не может — это факт, а не догадка о клетках; и отказ не отнимает ни у одной
 * работающей программы ничего.
 *
 * # Названная граница (не обойдена молчанием)
 *
 * Значение с НЕИЗВЕСТНЫМ происхождением (нагрузка пары `Результат<Строка, …>`, параметр без типа)
 * здесь НЕ ловится: чтобы отказывать и там, нужна строковость/массивность ИЗ ТИПА — это шаг 2.3 того
 * же условия владельца (`ATOM-06-02-02а`), а не эта правка. До него `нагрузка[0]` остаётся тихой
 * ложью, и сторож её ДЕРЖИТ (`src/e2k/resultStringDepth.test.ts`).
 *
 * @param code носители ПОСЛЕ всех вставок (тот же поток, что понижается: индексы обязаны совпасть)
 * @param constants пул констант образа: у СТРОК в нём лежат адреса, поэтому число признаётся числом
 *   только в ИСХОДНОЙ части пула (`originalPoolLength`) — иначе адрес статики сошёл бы за литерал
 * @param invokeNames имена вызовов образа (пометка носителя — индекс в этой таблице)
 * @param originalPoolLength длина пула ДО планирования строк (адреса строк дописаны в хвост)
 */
export interface ProcedureNumberFacts {
  /** Индекс первого носителя процедуры в том же потоке, что разбирает `arrayBaseProblems`. */
  readonly codeOffset: number;
  /** Имя процедуры — для читаемости отказа (правило проекта: отказ называет процедуру). */
  readonly name?: string;
  /** Клетки-параметры, объявленные `Число`: число массивом быть не может — это факт типа. */
  readonly numbers: readonly number[];
}

export function arrayBaseProblems(
  code: readonly AsmInstruction[],
  constants: readonly unknown[],
  invokeNames: readonly string[],
  originalPoolLength: number = constants.length,
  /**
   * ЧИСЛА ИЗ ТИПА: параметры, объявленные `Число`, по процедурам (шаг 2.3, ATOM-06-02-02а).
   *
   * Зачем отдельным входом, а не выводом из потока: типа в носителе НЕТ (`IR.invoke` несёт только
   * индекс имени), поэтому «параметр 0 — Число» знает лишь конвейер, у которого есть AST. Замер
   * (`.tmp/a230-dump.ts`): параметр `i` после раскладки живёт в клетке `i`, поэтому список — просто
   * набор клеток на процедуру.
   *
   * Пустой список (по умолчанию) сохраняет ПРЕЖНЕЕ поведение байт-в-байт: у программы `ф(а: Число)` +
   * `вернуть а[0]` сегодня 0 отказов и код 9 на модели (139 на железе) — это тихая ложь, и её
   * закрывает именно этот вход. Границы процедур чистятся только при непустом списке — иначе сторож
   * сдвинул бы отказы там, где типов никто не предъявлял.
   */
  typedNumbers: readonly ProcedureNumberFacts[] = [],
  /**
   * НОСИТЕЛИ `IR.result_pick`, ЧЬЯ НАГРУЗКА СТРОКОЙ НЕ ДОКАЗАНА (шаг 2.3, случай 73).
   *
   * На сайте с доказанным Успехом нагрузка пары — `Строка`, и значение её известно: планирование строк
   * заменяет индексацию символом (`система.строка.символ`), и отказ здесь был бы ложным. На сайте с
   * доказанной Неудачей в ТОЙ ЖЕ клетке лежит поле типа `Е` (число), а при недоказанном теге сборка
   * не знает, что там вовсе, — поэтому индексация по такой клетке обязана быть НАЗВАННЫМ отказом.
   * Замер (`.tmp/a230-зонд-пара.ts`, 2026-11-05): `пусть тег, нагрузка = добыть("абв", 0)` +
   * `вывести нагрузка[0]` давало НОЛЬ отказов и код 9 на модели с пустым выводом — то есть обращение
   * в память по адресу 7; на цели тот же класс виден падением (139, §случай 73).
   *
   * Пустой набор (по умолчанию) сохраняет прежнее поведение байт-в-байт для всех прочих программ.
   */
  pairPayloadPicks: ReadonlySet<number> = new Set<number>(),
): readonly ArrayBaseProblem[] {
  /** Регистры, про которые ИЗВЕСТНО, что там число; значение — если оно известно на сборке. */
  const numbers = new Map<number, number | undefined>();
  /** ЧЕМ доказано число, когда доказательство — ТИП, а не литерал: нужно для читаемости отказа. */
  const typeProofs = new Map<number, string>();
  /** КЛЕТКИ-НАГРУЗКИ ПАР, ИСХОД КОТОРЫХ НЕ ДОКАЗАН УСПЕХОМ: индексация по ним — НАЗВАННЫЙ отказ. */
  const pairPayloads = new Map<number, string>();
  const problems: ArrayBaseProblem[] = [];
  let typedAt = 0;
  const seedTyped = (): void => {
    for (const register of typedNumbers[typedAt]?.numbers ?? []) {
      numbers.set(register, undefined);
      typeProofs.set(register, 'Число');
    }
  };
  const registerOf = (operand: Operand | undefined): number | undefined =>
    operand !== undefined && operand.kind === 'reg' ? operand.index : undefined;
  /** Приёмник носителя — по соглашению оболочки (то же правило, что в `src/e2k/stringPlan.ts`). */
  const writtenOf = (carrier: AsmInstruction): number | undefined => {
    if (
      carrier.mnemonic === 'IR.jmp' ||
      carrier.mnemonic === 'IR.jmp_if' ||
      carrier.mnemonic === 'IR.jmp_if_not' ||
      carrier.mnemonic === 'IR.ret'
    ) {
      return undefined;
    }
    if (carrier.mnemonic === 'IR.invoke' || carrier.mnemonic === 'IR.call') {
      const flags = carrier.operands[0];
      if (flags === undefined || flags.kind !== 'imm' || (flags.value & 1) !== 1) return undefined;
      return registerOf(carrier.operands[4]);
    }
    return registerOf(carrier.operands[0]);
  };
  const forget = (register: number | undefined): void => {
    if (register === undefined) return;
    numbers.delete(register);
    typeProofs.delete(register);
    pairPayloads.delete(register);
  };
  const nameOf = (carrier: AsmInstruction): string | undefined => {
    const payload = carrier.operands[3];
    return payload !== undefined && payload.kind === 'imm' ? invokeNames[payload.value] : undefined;
  };

  seedTyped();
  code.forEach((carrier, index) => {
    // ГРАНИЦА ПРОЦЕДУРЫ: клетка соседней процедуры — ЧУЖОЕ значение, и переносить через неё факт
    // нельзя (тот же класс «тихой лжи», что случай 46 у строк). Чистится только тогда, когда типы
    // вообще предъявлены: без них поведение сторожа обязано остаться прежним, байт-в-байт.
    if (typedNumbers.length > 0) {
      while (typedAt + 1 < typedNumbers.length && (typedNumbers[typedAt + 1]!.codeOffset ?? 0) <= index) {
        typedAt += 1;
        numbers.clear();
        typeProofs.clear();
        seedTyped();
      }
    }
    // ЛИТЕРАЛ: число — только из ИСХОДНОЙ части пула (в хвосте лежат адреса строк).
    if (carrier.mnemonic === 'IR.const') {
      const destination = registerOf(carrier.operands[0]);
      const poolIndex = carrier.operands[1];
      forget(destination);
      if (destination === undefined || poolIndex === undefined || poolIndex.kind !== 'imm') return;
      if (poolIndex.value >= originalPoolLength) return;
      const raw = constants[poolIndex.value];
      if (typeof raw === 'number') numbers.set(destination, raw);
      return;
    }
    // ПЕРЕСЫЛКА: число едет вместе с регистром — И ВМЕСТЕ С ДОКАЗАТЕЛЬСТВОМ. Без второго слагаемого
    // `Число`-параметр терял бы тип на первой же копии (`вернуть а[0]` компилируется в копию аргумента),
    // и отказ назвал бы «число, известное на сборке» там, где величины на сборке нет вовсе.
    if (carrier.mnemonic === 'IR.move') {
      const destination = registerOf(carrier.operands[0]);
      const source = registerOf(carrier.operands[1]);
      const value = source === undefined ? undefined : numbers.get(source);
      const proof = source === undefined ? undefined : typeProofs.get(source);
      const pair = source === undefined ? undefined : pairPayloads.get(source);
      forget(destination);
      if (destination !== undefined && source !== undefined && numbers.has(source)) {
        numbers.set(destination, value);
        if (proof !== undefined) typeProofs.set(destination, proof);
      }
      // НАГРУЗКА ПАРЫ ЕДЕТ ВМЕСТЕ С ПЕРЕСЫЛКОЙ: `пусть т = нагрузка` не имеет права терять исход, иначе
      // отказ обходится одной лишней строкой (`пусть а = 5` + `а[0]` — тот же класс, случай 73).
      if (destination !== undefined && pair !== undefined) pairPayloads.set(destination, pair);
      return;
    }
    // АРИФМЕТИКА НАД ИЗВЕСТНЫМИ ЧИСЛАМИ: результат — снова число (строки в `numbers` не попадают,
    // поэтому склейка `"а" + "б"` здесь числом не считается и отказом не грозит).
    //
    // САМА АРИФМЕТИКА ЖИВЁТ В ОДНОМ МЕСТЕ (`src/e2k/numberFacts.ts`): тот же вопрос задаёт план строк
    // (края среза и константный индекс символа), и две свёртки, разошедшись, дали бы разными ответами
    // одно и то же число — а это класс «тихая ложь». Здесь остаётся только дисциплина карты: стереть
    // приёмник и записать результат, если оба слагаемых ИЗВЕСТНЫ.
    if (isNumericCarrier(carrier.mnemonic)) {
      const destination = registerOf(carrier.operands[0]);
      const first = registerOf(carrier.operands[1]);
      const second = registerOf(carrier.operands[2]);
      const known = first !== undefined && second !== undefined && numbers.has(first) && numbers.has(second);
      const left = first === undefined ? undefined : numbers.get(first);
      const right = second === undefined ? undefined : numbers.get(second);
      forget(destination);
      if (!known || destination === undefined) return;
      const computed =
        left === undefined || right === undefined ? undefined : foldNumericCarrier(carrier.mnemonic, left, right);
      numbers.set(destination, computed);
      return;
    }
    // НАГРУЗКА ПАРЫ: исход сайта назван доказательством — недоказанный тег или доказанная Неудача.
    // Клетку помечаем здесь же: `IR.result_pick` и есть тот носитель, что кладёт нагрузку в клетку.
    if (carrier.mnemonic === 'IR.result_pick') {
      const destination = registerOf(carrier.operands[0]);
      forget(destination);
      if (destination !== undefined && pairPayloadPicks.has(index)) {
        pairPayloads.set(
          destination,
          'нагрузка пары, исход которой НЕ доказан как «успех»: в этой клетке лежит поле типа «Е», ' +
            'а не строка и не массив',
        );
      }
      return;
    }
    if (carrier.mnemonic === 'IR.invoke') {
      const name = nameOf(carrier);
      const destination = writtenOf(carrier);
      // НАГРУЗКА ПАРЫ В РОЛИ БАЗЫ: `нагрузка[0]` там, где исход не доказан успехом, — НАЗВАННЫЙ отказ.
      // Проверяется ПЕРВЫМ: клетка нагрузки не попадает в `numbers` вовсе, и без этой ветви программа
      // собиралась бы с нулём отказов (замер 2026-11-05: код 9 на модели).
      const pairBase = registerOf(carrier.operands[1]);
      const pairReason = pairBase === undefined ? undefined : pairPayloads.get(pairBase);
      if (name !== undefined && pairReason !== undefined && ARRAY_BASE_NAMES.includes(name)) {
        problems.push({
          index,
          reason:
            `#${String(index)} ${name}: база — ${pairReason}. Обращение ушло бы в ПАМЯТЬ по этому ` +
            'значению и вернуло мусор БЕЗ отказа (тихая ложь, случай 73 реестра): замер — `добыть("абв", 0)` ' +
            '+ `нагрузка[0]` давало 0 отказов и код 9 на модели, а на цели тот же класс виден падением',
        });
      }
      if (name !== undefined && ARRAY_BASE_NAMES.includes(name)) {
        const base = registerOf(carrier.operands[1]);
        if (base !== undefined && numbers.has(base)) {
          const value = numbers.get(base);
          // ДВА ДОКАЗАТЕЛЬСТВА, ОДИН ОТКАЗ — и причина называет, КАКОЕ именно сработало: литерал
          // («число, известное на сборке») или ТИП параметра. Без второго имени отказ неотличим от
          // чужого, а тип здесь — единственное, что видно (величины на сборке нет вовсе).
          const typed = typeProofs.get(base);
          const head =
            typed === undefined
              ? `#${String(index)} ${name}: база — ЧИСЛО, известное на сборке` +
                `${value === undefined ? '' : ` (${String(value)})`}`
              : `#${String(index)} ${name}: база — ЧИСЛО по ТИПУ (тип «${typed}», параметр процедуры ` +
                `«${typedNumbers[typedAt]?.name ?? `#${String(typedAt)}`}»)`;
          problems.push({
            index,
            reason:
              `${head}, а массивом оно быть не может: ` +
              'обращение ушло бы в ПАМЯТЬ по этому адресу и вернуло мусор БЕЗ отказа (тихая ложь, ' +
              'случай 73 реестра: `пусть а = 5` + `а[0]` давал код 9)',
          });
        }
      }
      forget(destination);
      // ДЛИНА массива — сама число (даже когда величина на сборке неизвестна): индексация по её
      // результату тоже недопустима, и это тот же класс, а не другая догадка.
      if (destination !== undefined && name === 'система.массив.длина') numbers.set(destination, undefined);
      return;
    }
    forget(writtenOf(carrier));
  });
  return problems;
}

/**
 * Проверить операнд: регистр, и **не клетка блока рантайма**.
 *
 * Прежняя редакция отказывала всему, что ≥ `RESERVED_FROM`, и закрывала тихий путь лишь наполовину:
 * у вызываемой бюджет `%b[8..15]`, поэтому её аргументы 8 и 9 проходили сторож, программа собиралась
 * — и считала неверно (замерено §3.127). Теперь отказ называет СОВПАДЕНИЕ с блоком, а не номер: он
 * верен и для точки входа (`%b[10..14]`), и для вызываемой (её собственный блок).
 */
function checkOperand(operand: Operand, name: string, role: string, reserved: readonly number[]): void {
  if (operand.kind !== 'reg') {
    throw new ArrayRuntimeRefusal(`«${name}»: ${role} обязан быть регистром, а не ${operand.kind}`);
  }
  if (reserved.includes(operand.index)) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: ${role} — %b[${operand.index}] — попал в блок рантайма массивов ` +
        `(%b[${reserved[0]!}..%b[${reserved[reserved.length - 1]!}]): операция затёрла бы свои же клетки ` +
        '(src/e2k/arrayRuntime.ts). Прежний сторож пропускал аргументы ниже `RESERVED_FROM`, и они ' +
        'терялись молча — теперь это названный отказ',
    );
  }
}

/**
 * `addd src1, src2, dst` — форма ALF1, операнды `%db` (формат `D`, `opcodes/e2k-opc.h:24`).
 *
 * **Почему не `adds`** (`opcodes/e2k-opc.h:19`, формат `S`): у `S`-форм результат — младшая половина
 * 64-битного регистра, у `D`-форм — регистр целиком (`docs/hardware-debt.md` §3.27, справка по
 * кодировке; порт: `TRANS(ADDS, e2k_sss, tcg_gen_add_i32)` против
 * `TRANS(ADDD, e2k_ddd, tcg_gen_add_i64)` — `qemu/target/e2k/tcg/translate-al-c2.c:59-60`).
 *
 * Здесь считаются **адреса**, а адрес — величина 64-битная: первый адрес ≥ 4 ГиБ (или значение,
 * пришедшее из `ldd`, который пишет регистр целиком) сломал бы `adds`-арифметику молча. Форма `D`
 * снимает это по построению, а не сторожем.
 */
const movts = (value: number, dst: number): AsmInstruction => ({
  mnemonic: 'movts',
  channel: 0,
  operands: [{ kind: 'imm', value }, reg(dst)],
});

const addd = (src1: number, src2: number, dst: number): AsmInstruction => ({
  mnemonic: 'addd',
  channel: 0,
  operands: [reg(src1), reg(src2), reg(dst)],
});

/**
 * ЗАКОН ФОРМЫ ПАМЯТИ: ОСНОВАНИЕ И СМЕЩЕНИЕ — РАЗНЫЕ РЕГИСТРЫ. Механизм назван замером.
 *
 * # Что известно было
 *
 * `.tmp/probe-basis-sweep.ts` и `.tmp/probe-basis-split.ts` дали: `std` с основанием `%b[12]` встаёт
 * исключением, с `%b[11]` — работает; отсюда родилась неверная догадка «`%b[12]` не адресуется».
 * Закон (совпадение регистров, а не их номер) назван в `src/e2k/printRuntime.ts` и закрыт коммитом
 * `eee76ed` — но там честно записано: **почему** совпадение валит порт, в источниках не сказано.
 *
 * # Механизм (измерен 2026-09-27, диагностическая пересборка порта)
 *
 * Три замера, каждый отсекает прежнюю гипотезу:
 *
 * 1. `error_report` в `linux-user/e2k/cpu_loop.c` на месте `EXCP_EXCEPTION`: в момент отказа
 *    `BR = 0x1c0` (`rbs = 0`, `rsz = 7`), `WD = 0x4000800000` (`base_d = 0`, `size_d = 16`) — окно
 *    ШИРЕ, чем требует `%b[12]`, а теги всех регистров нулевые. Значит ни ширина окна, ни значения
 *    не при чём.
 * 2. `error_report` в `target/e2k/tcg/translate-al.c` на обеих ветвях (`e2k_parse_src`/`e2k_parse_dst`):
 *    все проверки индексов проходят — `idx = 12` при `rsz_full_d = 16` исключения не взводит.
 * 3. Дамп микрокоманд порта (`qemu-e2k -d in_asm,op`) показал саму проверку:
 *
 *        ld_i32 loc24,loc7,$0x10   ; тег источника 1 (база)
 *        ld_i32 loc25,loc7,$0x10   ; тег источника 2 (смещение) — ТО ЖЕ СМЕЩЕНИЕ
 *        ld_i32 loc26,loc6,$0x28   ; тег источника 3 (значение)
 *        or_i32  loc23,loc23,loc24
 *        or_i32  loc23,loc23,loc25
 *        or_i32  loc23,loc23,loc26
 *        brcond_i32 loc23,$0x4040404,tsteq,$L2
 *        call e2k_set_have_exception
 *
 *    Порт складывает в одно число вклады **трёх** источников формы и сравнивает результат с
 *    `E2K_TAG_UNPACKED_IS_DT_MASK_QP = 0x04040404` (`target/e2k/cpu.h:107`); при несовпадении
 *    вызывает `e2k_set_have_exception`. Вклад каждого источника — **один байт** из его записи в
 *    файле регистров (`ld8u_i32 …,$0x11`), то есть проверяется «значение определено», а не величина.
 *    `have_exception` взводится **при входе в блок** (`e2k_translate_check_al_common`,
 *    `target/e2k/tcg/translate-al.c:1985-2140`), поэтому `IP` в отчёте порта — начало блока
 *    (`0x100058`/`0x100060`), а не команда, и обращение не исполняется.
 *
 *    **Чего здесь НЕ доказано (проверено 2026-09-27, и это важно не додумывать):** что совпадение
 *    регистров даёт «на байт меньше». Правдоподобно (вклады трёх источников, а источников два), но
 *    **не измерено**: дамп микрокоманд падающего образа обрывается на месте отказа, и проверки с
 *    вызовом исключения в него не попадают, а у рабочего образа таких проверок **пять** против
 *    **одной** у падающего. Значит различие может лежать и не во вкладе байта. До отдельного опыта
 *    (сравнить вклады по каждому из трёх источников) это остаётся **открытым**, и записано как
 *    открытое, а не как причина.
 *
 * # Чем подтверждено (различающий опыт, `.tmp/osnova-operand-law.ts`)
 *
 * Одно тело, меняется только пара регистров; код возврата — прочитанное из области значение:
 *
 * | форма | результат |
 * |---|---|
 * | `std 55, [%b[11] + %b[11]]` | исключение (код возврата 9) |
 * | `std 55, [%b[12] + %b[12]]` | исключение (9) |
 * | `std 55, [%b[13] + %b[13]]` | исключение (9) |
 * | `std 55, [%b[11] + %b[12]]` | **55** — запись исполнена |
 * | `std 55, [%b[12] + %b[11]]` | **55** — запись исполнена |
 *
 * Положительный контроль здесь обязателен и он есть: без строк «разные регистры» опыт не отличал бы
 * «совпадение валит» от «падает всё».
 *
 * # Граница правила: совпадение проверено НЕ для всех пар (`.tmp/osnova-triple-law.ts`)
 *
 * Механизм симметрию **не** обещает, и опыт её не подтверждает — важно не записать лишнего:
 *
 * | опыт | результат |
 * |---|---|
 * | значение ≠ база ≠ смещение (все три разные) | 55 — запись исполнена |
 * | значение = база | исключение |
 * | база = смещение | исключение |
 * | значение = смещение | **исключения НЕТ** |
 * | все три — один регистр | исключение |
 *
 * Отсюда рабочее правило ровно такое: **два регистра, считающие адрес, обязаны быть разными**;
 * значение обязано отличаться от базы, а от смещения — не обязано. Почему асимметрия — в заголовке
 * не сказано, это замер; распространять закон на пару «значение + смещение» оснований нет.
 *
 * # Что из этого следует для кода
 *
 * Догадка «`%b[12]` — это ноль, его нельзя трогать» **снята**: `%b[12]` — обычный вращаемый регистр
 * (`%b[0..15]` при `rsz = 7`), а ноль в нём — удобная константа пролога. Ограничение одно и оно
 * проверяется: {@link memoryOperandPairProblems} — два регистра, считающие адрес, обязаны быть
 * разными. Рантайм ему удовлетворяет по построению (`zero` — смещение, `heap`/`scratch` — база), но
 * проверка нужна: молчаливый отказ модели не отличим от «программа неверна».
 *
 * # Что модель нам говорит про устройство — и почему это тот же корень
 *
 * Стр. 56 руководства (`docs/vliw-e2k-model.md`, «Что важно: АЛУ не равнозначны»): запись в память
 * умеют **только АЛУ2 и АЛУ5**, чтение — АЛУ0/АЛУ2/АЛУ3/АЛУ5. В нашей кодировке это и означает
 * «каналы 2 и 5» для `std` (`opcodes/e2k-opc.h:969-984`) — то есть ограничение формы памяти
 * приходит **не от регистров**, а от устройства, которое эту форму исполняет. Пара регистров и
 * выбор канала — две стороны одного: адрес считает устройство обращения к памяти, и оно же проверяет
 * годность своих операндов.
 */
const ldd = (src1: number, src2: number, dst: number): AsmInstruction => ({
  mnemonic: 'ldd',
  channel: 0,
  operands: [reg(src1), reg(src2), reg(dst)],
});

/**
 * D43b: НОСИТЕЛИ ПРОВЕРКИ ГРАНИЦ. Имена живут здесь, рядом с рантаймом массивов, потому что это его
 * операции; сайт проверки собирает `src/e2k/arrayBounds.ts`, а понижение — `src/e2k/e2kRealRun.ts`.
 *
 * `IR.array_len [длина, база, ноль]` — одно чтение слова длины (`ldd база+ноль`).
 * `IR.array_bounds_trap [приёмник, база, смещение]` — одно деление на ноль (`sdivs`): в модели чтение
 * по нулевому адресу оказалось ЧИТАЕМЫМ, поэтому ловушка — архитектурное исключение `exc_div`, а не
 * обращение к памяти. Приёмник у ловушки не определён: она не возвращается.
 *
 * Почему не `IR.refusal`/`IR.exit`: системный вызов из вызываемой в модели не завершается (вложенный
 * `call`, `src/e2k/e2kCallWindowQemu.test.ts`), а проверка D43b обязана работать и на глубине 1.
 */
export const ARRAY_LENGTH_CARRIER = 'IR.array_len';
export const ARRAY_BOUNDS_TRAP_CARRIER = 'IR.array_bounds_trap';
/** Имя причины ловушки (один код на оба края). */
export const ARRAY_BOUNDS_TRAP_CODE = 'OSN-RT-010';

/** Понижение `IR.array_len`: одно чтение длины блока. */
export function arrayLengthInstructions(base: number, offset: number, dst: number): AsmInstruction[] {
  return [ldd(base, offset, dst)];
}

/**
 * Понижение `IR.array_bounds_trap`: ДЕЛЕНИЕ НА НОЛЬ — архитектурное исключение e2k (`exc_div`).
 *
 * Почему не чтение по нулевому адресу: в модели адрес 0 оказался ЧИТАЕМЫМ (замер D43b: `ldd 0+0`
 * вернул значение, и программа продолжила путь — тихий проход вместо ловушки). Деление на ноль
 * исключение даёт по определению команды, а не по карте памяти.
 */
export function arrayBoundsTrapInstructions(base: number, offset: number, dst: number): AsmInstruction[] {
  return [{ mnemonic: 'sdivs', channel: 5, operands: [reg(base), reg(offset), reg(dst)] }];
}

/**
 * `std значение, база, смещение` — порядок операндов **текстовый** (измерено): у ассемблера текст
 * идёт `(значение, база, смещение)` = `(src3, src1, src2)` (`.tmp/std-order.ts`).
 */
const std = (value: number, src1: number, src2: number): AsmInstruction => ({
  mnemonic: 'std',
  channel: 2, // `st*` разрешены только в каналах 2 и 5 (opcodes/e2k-opc.h:969-984)
  operands: [reg(value), reg(src1), reg(src2)],
});

/** `movtd src, dst` — 64-битная копия регистра: указатель списка/адрес не влезает в `movts`. */
const movtd = (src: number, dst: number): AsmInstruction => ({
  mnemonic: 'movtd',
  channel: 0,
  operands: [reg(src), reg(dst)],
});

/**
 * `×8` удвоением: три `addd` (форма `D`, проверена пробой), результат — в `dst`.
 * Требует, чтобы `src` и `dst` были разными регистрами (иначе первое удвоение затрёт вход).
 */
function timesEight(src: number, dst: number): AsmInstruction[] {
  return [addd(src, src, dst), addd(dst, dst, dst), addd(dst, dst, dst)];
}

/**
 * Понизить вызов массива в настоящие команды e2k.
 *
 * @param name имя хост-вызова (`система.массив.*`) — семантику несёт имя, а не код операции
 * @param args регистры аргументов в порядке вызова
 * @param dst регистр приёмника (у `добавить` результата нет — `undefined`)
 * @param options база блока рантайма (её выдала раскладка, операнд {@link ARRAY_BASE_OPERAND}), признак
 * вызываемой процедуры (у неё обращения идут оконной формой) и слово о том, что АДРЕС ЯЧЕЙКИ КУЧИ в
 * её окне закреплён прологом роста (`heapSlotReady`, A4 §3.137)
 */
export function lowerArrayCall(
  name: string,
  args: readonly Operand[],
  dst: number | undefined,
  options: {
    readonly base?: number;
    readonly inCallee?: boolean;
    readonly forForm?: boolean;
    readonly heapSlotReady?: boolean;
    /**
     * ОТКУДА ВЫЗОВ ВЗЯЛСЯ В ИСХОДНИКЕ (`лента[индекс]`).
     *
     * Не влияет ни на один байт: нужно ТОЛЬКО отказу, чтобы он назвал то, что человек написал, а не
     * `система.массив.получить` и не «операнд 6». Нет ссылки — прежний текст байт в байт.
     */
    readonly sourceRef?: IRSourceRef;
  } = {},
): AsmInstruction[] {
  try {
    return формыВызоваМассива(name, args, dst, options);
  } catch (error) {
    // ОДНО место, а не восемь: причин отказа у рантайма массивов много (`Списки.взять` — пара не
    // влезает, нет базы раскладки, окно вызываемой, арность), и каждая обязана назвать ИСХОДНИК.
    // Оборачивая здесь, я не рискую, что новая причина забудет это: она пройдёт через ту же дверь.
    if (!(error instanceof ArrayRuntimeRefusal)) throw error;
    const описание = описаниеПоСсылке(options.sourceRef);
    if (описание === undefined) throw error;
    throw new ArrayRuntimeRefusal(`${описание} — ${error.message}`);
  }
}

/** Тело {@link lowerArrayCall}: если оно откажет, обёртка добавит источник впереди причины. */
function формыВызоваМассива(
  name: string,
  args: readonly Operand[],
  dst: number | undefined,
  options: {
    readonly base?: number;
    readonly inCallee?: boolean;
    readonly forForm?: boolean;
    readonly heapSlotReady?: boolean;
    readonly sourceRef?: IRSourceRef;
  } = {},
): AsmInstruction[] {
  const forForm = options.forForm === true;
  // D43a: проверка ИМЕНИ и АРНОСТИ ДО приведения. Иначе `Списки.пустой()` без арены после
  // отбрасывания последнего аргумента стал бы «создать()» — отказ превратился бы в тихое согласие.
  if (name === 'Списки.взять') {
    throw new ArrayRuntimeRefusal(
      `«${name}»: D43a не понижает возврат пары Результат<T, Ошибка> — пара в горячем пути точки ` +
        'входа не влезает (D49); подменять её голым система.массив.получить запрещено (D4). ' +
        'Это следующий атом, а не забытая ветвь.',
    );
  }
  const alias = D43_LIST_ALIASES[name];
  if (alias !== undefined && args.length !== alias.арность) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: аргументов ${args.length}, по D43 ${alias.арность} ` +
        `(${name === 'Списки.добавить' ? 'список, элемент, арена' : name === 'Списки.пустой' ? 'арена' : name === 'Списки.установить' ? 'список, индекс, значение' : 'список'})`,
    );
  }
  const возвращаетБазу = alias?.возвращаетБазу === true;
  if (alias !== undefined) {
    args = alias.безАрены ? args.slice(0, -1) : args;
    name = alias.имя;
  }
  const arity = ARITY[name];
  if (arity === undefined) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: у рантайма массивов нет такой операции — он умеет ${SUPPORTED_ARRAY_CALLS.join(', ')}; ` +
        'остальное (установить, удалить, срез, строки, математика) не заменено настоящими обращениями',
    );
  }
  if (args.length !== arity) {
    throw new ArrayRuntimeRefusal(`«${name}»: аргументов ${args.length}, по источнику ${arity} (invokeRegistry.ts:44-50)`);
  }
  // ФОРМА (раскладке нужна ДЛИНА, а не смысл): семантические сторожа ниже не в счёт — их держит
  // понижение, — а базой берётся точка входа. Длины команд от НОМЕРА клетки не зависят: все клетки
  // блока — регистровые операнды одной формы, поэтому форма одна на любую базу. Это утверждение не
  // догадка: формы сверяет оракул раскладки (`src/e2k/layoutWideCrossCheck.test.ts`, §1.2).
  // ТИХИЙ ПУТЬ ЗАКРЫТ ЗДЕСЬ. Прежде отказ знал только «регистр ≥ RESERVED_FROM», поэтому у
  // вызываемой (бюджет `%b[8..15]`) аргументы 8 и 9 проходили сторож, операция уходила в клетки
  // пролога образа — и значение терялось молча (замерено §3.127: `а[1]` давал элемент[0]).
  // Теперь обязательна ВЫДАННАЯ РАСКЛАДКОЙ база: нет её — отказ по имени, а не догадка о клетках.
  if (!forForm && (options.base === undefined || options.base === ARRAY_BASE_UNASSIGNED)) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: раскладка не выдала базу блока рантайма (операнд ${ARRAY_BASE_OPERAND} носителя) — ` +
        'обращение ушло бы в чужие клетки; базу кладёт `allocateProgram` (src/e2k/regAlloc.ts)',
    );
  }
  // Форме база не нужна (длина от номера клетки не зависит), но она обязана быть числом: подставляем
  // точку входа — при `forForm` в дело идут ЕЁ клетки (`blockCells` ниже).
  const base = options.base ?? ENTRY_ARRAY_BASE;
  // ВЫДЕЛЕНИЕ В ВЫЗЫВАЕМОЙ (A4, срез 3, §3.137): кучу адресует `%b[15]`, а у вызываемой это ЕЁ
  // СОБСТВЕННАЯ клетка, поэтому адрес ячейки кладёт её же пролог роста (`arraySlotPrologue`,
  // носитель `IR.array_slot`). Значит `создать` в вызываемой разрешено РОВНО ТОГДА, когда пролог
  // этот у процедуры есть: `heapSlotReady` — слово того, кто собирал поток (он же закрепил `%b[15]`
  // за раскладкой). Нет слова — отказ по имени, а не чтение чужой клетки.
  if (!forForm && options.inCallee === true) {
    if (name === 'система.массив.добавить') {
      throw new ArrayRuntimeRefusal(
        `«${name}»: в вызываемой процедуре — названный отказ, и он РАЗМЕРНЫЙ: её блоку ТРИ клетки, ` +
          'а `добавить` нужно пять РАЗЛИЧНЫХ ролей (ноль, единица, восемь и два временных), причём ' +
          '`one` и `scratch2` там псевдонимы — последовательность посчитала бы новую длину как ' +
          '«прочитанная + 0» и тут же затёрла бы её. Куча при этом уже доступна (адрес ячейки кладёт ' +
          'пролог роста), не хватает КЛЕТОК: пять ролей в бюджет вызываемой вместе со значениями не ' +
          'влезают (замер §3.135) — это следующий срез A4',
      );
    }
    if (name === 'система.массив.создать' && options.heapSlotReady !== true) {
      throw new ArrayRuntimeRefusal(
        `«${name}»: у вызываемой процедуры нет пролога адреса ячейки кучи (носитель ` +
          `«${ARRAY_SLOT_CARRIER}») — без него %b[${String(ARRAY_REGISTERS.heapSlot)}] вызываемой несёт ` +
          'чужое значение (закон окна), и куча у процедур разошлась бы (A4 §3.137)',
      );
    }
  }
  // КЛЕТКИ БЛОКА: у точки входа — ИЗМЕРЕННАЯ раскладка ролей (`ENTRY_ARRAY_CELLS`, §3.126), у
  // вызываемой — ТРИ временных клетки её собственного бюджета (A4, §3.135): постоянных там нет,
  // 0/1/8 материализуются на месте операции.
  const inCallee = !forForm && options.inCallee === true;
  const reservedCells = inCallee
    ? (() => {
        const cells = calleeArrayCells(base);
        // `%b[15]` вызываемой занят АДРЕСОМ ЯЧЕЙКИ КУЧИ — но ТОЛЬКО у той операции, которой он нужен
        // (`создать`): у прочих операций клетка 15 свободна, и запрещать её им значило бы отказывать
        // работающим программам (блок К1 стоит в 12..14, значения берут остальное).
        return [
          cells.zero,
          cells.eight,
          cells.scratch,
          ...(name === 'система.массив.создать' ? [ARRAY_REGISTERS.heapSlot] : []),
        ];
      })()
    : [
        ENTRY_ARRAY_CELLS.zero,
        ENTRY_ARRAY_CELLS.one,
        ENTRY_ARRAY_CELLS.eight,
        ENTRY_ARRAY_CELLS.scratch,
        ENTRY_ARRAY_CELLS.scratch2,
        ...(name === 'система.массив.создать' || name === 'система.массив.добавить' ? [ARRAY_REGISTERS.heapSlot] : []),
      ];
  if (!forForm) {
    args.forEach((operand, index) => checkOperand(operand, name, `аргумент ${index}`, reservedCells));
  }
  const registers = args.map((operand) => (operand as { index: number }).index);

  if (dst !== undefined && !forForm) checkOperand(reg(dst), name, 'приёмник', reservedCells);

  // КЛЕТКИ РОЛЕЙ: у точки входа — ИЗМЕРЕННАЯ раскладка (§3.126), у вызываемой — три её СВОИХ клетки
  // (A4, §3.135), которые заполняет ЕЁ пролог значений. Формы операций от плоскости НЕ зависят —
  // и это не мелочь: раскладка берёт длину понижения ЗАРАНЕЕ и без плоскости
  // (`src/e2k/twoPassLayout.ts#carrierFormWithReason`, `{ forForm: true }`), поэтому разойдись
  // последовательности числом команд — носители после них уехали бы на разницу и программа упала бы
  // не отказом, а исключением модели (это и случилось первым прогоном A4).
  const { zero, one, eight, scratch, scratch2 } = inCallee ? calleeArrayCells(base) : ENTRY_ARRAY_CELLS;
  const heapSlot = ARRAY_REGISTERS.heapSlot;

  switch (name) {
    case 'система.массив.длина':
      // Длина лежит в первом слове блока: адрес = массив + 0.
      return [ldd(registers[0]!, zero, dst!)];
    case 'система.массив.создать':
      // КУЧА — В ПАМЯТИ (A4 §3.136): `%b[15]` несёт только АДРЕС ячейки, значение читается и
      // записывается `ldd`/`std`. ПРИЁМНИК — ЭТО АДРЕС БЛОКА, и он НЕ сдвигается: сдвигается
      // ВРЕМЕННЫЙ, и уже он ложится в ячейку. Ошибка, которая здесь стояла, дала указатель за словом
      // длины: `создать` возвращало куча+8, длина писалась на слово раньше указателя, а каждый
      // следующий блок начинался на 8 байт раньше конца предыдущего — при двух массивах заголовок
      // второго ложился ровно на последний элемент первого (измерено
      // `.tmp/osnova-a4-slot-trace.ts`: указатель 102008 вместо 102000).
      return [
        ldd(heapSlot, zero, dst!),
        std(zero, dst!, zero),
        // РЕЗЕРВ ЁМКОСТИ, А НЕ ТОЛЬКО ЗАГОЛОВКА (TD-0013): иначе следующий `создать` получает ровно
        // `ptr + 8`, и первый элемент предыдущего массива попадает в СЛОВО ДЛИНЫ следующего.
        // Измерено `.tmp/b2a-three.osnova`: `[112, 1, 333, 1, 112, 1]` вместо `[111, 222, 333, 1, 1, 1]`.
        // Формулы адреса (`массив + 8 + индекс*8`) не меняются.
        movts(ARRAY_RESERVED_BYTES, scratch),
        addd(dst!, scratch, scratch),
        std(scratch, heapSlot, zero),
      ];
    case 'система.массив.получить': {
      // Адрес элемента = массив + 8 + индекс*8.
      const steps = timesEight(registers[1]!, scratch);
      return [
        ...steps,
        addd(scratch, eight, scratch),
        addd(scratch, registers[0]!, scratch),
        ldd(scratch, zero, dst!),
      ];
    }
    case 'система.массив.установить': {
      // Тот же адрес, что у `получить`, но последний шаг — ЗАПИСЬ. Развёртка совпадает с ним
      // не «похоже», а по построению: адрес считается теми же тремя шагами, и разойдись они —
      // `установить` писал бы не туда, куда читает `получить` (класс §3.35).
      //
      // ПРИЁМНИК: у D43a `добавить` и у D43b `установить` он несёт ТОТ ЖЕ список. Рантайм
      // `система.массив.установить` результата не имеет, поэтому копия указателя кладётся ДО
      // последовательности — так же, как у `добавить`; без неё `пусть л2 = Списки.установить(...)`
      // читал бы мусор. У ПРЯМОГО `система.массив.установить` приёмник по-прежнему не заполняется.
      const steps = timesEight(registers[1]!, scratch);
      const sequence: AsmInstruction[] = [
        ...steps,
        addd(scratch, eight, scratch),
        addd(scratch, registers[0]!, scratch),
        std(registers[2]!, scratch, zero),
      ];
      if (возвращаетБазу && dst !== undefined && dst !== registers[0]) {
        return [movtd(registers[0]!, dst), ...sequence];
      }
      return sequence;
    }
    case 'система.массив.добавить': {
      // Длина обновляется ДО вычисления адреса (иначе адрес считался бы по новой длине),
      // но адрес считается по СТАРОЙ длине — она остаётся в scratch.
      const steps = timesEight(scratch, scratch2);
      const sequence: AsmInstruction[] = [
        ldd(registers[0]!, zero, scratch),
        addd(scratch, one, scratch2),
        std(scratch2, registers[0]!, zero),
        ...steps.map((instruction) => instruction),
        addd(scratch2, eight, scratch2),
        addd(scratch2, registers[0]!, scratch2),
        std(registers[1]!, scratch2, zero),
        // УКАЗАТЕЛЬ КУЧИ ДВИГАЕТСЯ НА ЭЛЕМЕНТ, и он лежит в ЯЧЕЙКЕ ПАМЯТИ (A4 §3.136): `%b[15]` —
        // только адрес ячейки. Без этого сдвига блок СЛЕДУЮЩЕГО массива ляжет на первый элемент
        // этого (замер: `вход` и `коэффициенты` в FIR перекрывались, `получить(вход, i)` при
        // i = 0…7 давал `[длина(коэф), коэф[0..3], вход[5..7]]`, FIR давал 177 вместо 181 —
        // docs/e2k-regalloc-debt.md §12). Адресация выше считается от ДЛИНЫ массива, поэтому сдвиг
        // кучи на неё не влияет — он нужен следующему `создать`. Второй временный здесь уже свободен:
        // адрес элемента записан, и он переиспользуется под значение кучи.
        ldd(heapSlot, zero, scratch2),
        addd(scratch2, eight, scratch2),
        std(scratch2, heapSlot, zero),
      ];
      // D43a: `Списки.добавить` возвращает ТОТ ЖЕ список. Рантайм `добавить` результата не имеет,
      // поэтому копия указателя кладётся ДО последовательности: `dst` не должен совпасть с `base`.
      if (возвращаетБазу && dst !== undefined && dst !== registers[0]) {
        return [movtd(registers[0]!, dst), ...sequence];
      }
      return sequence;
    }
    default:
      throw new ArrayRuntimeRefusal(`«${name}»: ветвь не описана`);
  }
}


/**
 * Пролог: ноль, размер элемента и указатель кучи.
 *
 * Куча — **внешняя память** (адрес 64-битным литералом, форма 0xdc), а не литерал в команде: она
 * должна быть записываемой и лежать **не в странице кода** — запись в страницу кода кончается
 * `QEMU internal SIGSEGV {code=ACCERR}` (измерено, `src/e2k/e2kMemoryQemu.test.ts`).
 */
/**
 * ЗНАЧЕНИЯ рантайма в плоскости ОДНОЙ ВЫЗЫВАЕМОЙ: ноль и восемь — в её собственный блок (A4, §3.135).
 *
 * Зачем отдельно от {@link arrayPrologue}: `%b[N]` адресуется только внутри **текущего** окна, и у
 * вызываемой процедуры оно своё (`setwd`/`setbn` её пролога роста). Пролог образа заполняет клетки
 * СВОЕЙ плоскости; в плоскости вызываемой те же номера — другие клетки, и там `%b[14]` (`eight`)
 * остаётся нулём, отчего адрес элемента уезжает на слово назад (§3.127, замер М2/М3/М4).
 *
 * Форму регистров выбирает конвейер: у вызываемой весь её понижённый код переводится в оконную
 * (`%rN`) одним преобразованием, поэтому пролог значений обязан идти НОСИТЕЛЕМ (как `IR.window_grow`),
 * а не готовой командой в потоке.
 *
 * ЕДИНИЦЫ ЗДЕСЬ НЕТ, и это не потеря: она нужна только `добавить`, а `добавить` в вызываемой
 * отказывает по имени (пяти его ролям нужно пять клеток — см. {@link CALLEE_ARRAY_BLOCK_SIZE}).
 * Вместе с отказом от второго временного это и даёт блок в ТРИ клетки вместо пяти, который влезает
 * в бюджет вызываемой вместе со значениями записи (случай К1/К2, `src/e2k/e2kArraysQemu.test.ts`).
 * Адрес ячейки кучи ставит ОТДЕЛЬНЫЙ носитель ({@link ARRAY_SLOT_CARRIER}) — он нужен только
 * `создать`, и с A4 §3.137 вызываемая умеет выделять массив.
 */
export function arrayValuePrologue(base: number): AsmInstruction[] {
  const { zero, eight } = calleeArrayCells(base);
  return [
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 0 }, reg(zero)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 8 }, reg(eight)] },
  ];
}

/**
 * АДРЕС ЯЧЕЙКИ КУЧИ — В ОКНО ВЫЗЫВАЕМОЙ (A4, срез 3, §3.137).
 *
 * # Зачем это вызываемой
 *
 * У вызываемой `%b[15]` — её СОБСТВЕННАЯ клетка, а не клетка точки входа (закон окна: при `wbs = 4`
 * `%b[n]` вызываемой — это `%b[n + 8]` вызывающего). Пролог образа кладёт адрес ячейки кучи только
 * в СВОЮ плоскость, поэтому до этого шага `создать` в вызываемой читало бы чужое значение. Теперь
 * адрес кладёт пролог роста САМОЙ вызываемой — и ячейка кучи у всех процедур ОДНА (в этом и смысл:
 * куча общая, а состояние живёт в памяти, §3.136).
 *
 * # Почему 64-битный литерал здесь законен
 *
 * Это единственное место в вызываемой, где литерал адреса уместен: в ПОСЛЕДОВАТЕЛЬНОСТЯХ операций
 * 64-битного литерала нет и быть не может (их форму раскладка берёт заранее и БЕЗ плоскости, §3.135),
 * а здесь носитель, чья форма считается из того же операнда, что и понижение. `movts` для адреса не
 * годится: он несёт не более 21 бита, а адрес кучи — `0x111000`/`0x202000` (правило
 * «адрес в память кладётся `movtd`», AGENTS.md).
 */
export function arraySlotPrologue(heapAddress: number): AsmInstruction[] {
  if (!Number.isInteger(heapAddress) || heapAddress < 0) {
    throw new ArrayRuntimeRefusal(`адрес ячейки кучи обязан быть неотрицательным целым, получено ${String(heapAddress)}`);
  }
  return [
    {
      mnemonic: 'movtd',
      channel: 0,
      operands: [{ kind: 'imm64', value: BigInt(heapAddress) } as Operand, reg(ARRAY_REGISTERS.heapSlot)],
    },
  ];
}

export function arrayPrologue(heapAddress: number): AsmInstruction[] {
  if (!Number.isInteger(heapAddress) || heapAddress < 0) {
    throw new ArrayRuntimeRefusal(`адрес кучи обязан быть неотрицательным целым, получено ${String(heapAddress)}`);
  }
  const { zero, one, eight } = ARRAY_REGISTERS;
  return [
    // ОКНО СТАВИТСЯ `setwd` — и это измерено на железе (§3.116): без `setwd` входное окно
    // `wsz = 4`, а `setbn rbs=0, rsz=7` требует `rbs + rsz + 1 = 8 ≤ wsz` — окно негодно ЦЕЛИКОМ,
    // и падает первое же обращение (`movts … %b[12]` на 0x100008, код 139) — так падали все 38
    // образов кита. Форма сверена с прологами рабочих бинарей МЦСТ: `/bin/true` и `/bin/ls`
    // открываются `setwd wsz = 0x8, nfx = 0x1, dbl = 0x0` + `setbn rbs = 0x4, rsz = 0x3, rcur = 0x0`,
    // а `wsz = 0xc` — обычное дело у `bash`, `lcc`, `as`, `ld` (числа в комментарии константы).
    // `setwd` ДО `setbn` — не стиль: обратный порядок даёт ловушку (§3.56.2).
    { mnemonic: 'setwd', channel: 0, operands: [{ kind: 'imm', value: ARRAY_WINDOW_WSZ }, { kind: 'imm', value: 0 }] },
    {
      mnemonic: 'setbn',
      channel: 0,
      operands: [{ kind: 'imm', value: ARRAY_WINDOW_RSZ }, { kind: 'imm', value: 0 }, { kind: 'imm', value: 0 }],
    },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 0 }, reg(zero)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 1 }, reg(one)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 8 }, reg(eight)] },
    // АДРЕС ЯЧЕЙКИ КУЧИ — ПЕРВОЕ СЛОВО ОБЛАСТИ КУЧИ, ЗНАЧЕНИЕ кучи — со второго слова (A4 §3.136).
    // Пролог — единственное место, где адрес кладётся 64-битным литералом: в последовательностях
    // операций литерала нет (их форму раскладка берёт заранее, без плоскости, §3.135), там работают
    // только `ldd`/`std` через `%b[15]`. Временный `%b[11]` нужен лишь на время пролога.
    {
      mnemonic: 'movtd',
      channel: 0,
      operands: [{ kind: 'imm64', value: BigInt(heapAddress) } as Operand, reg(ARRAY_REGISTERS.heapSlot)],
    },
    {
      mnemonic: 'movtd',
      channel: 0,
      operands: [
        { kind: 'imm64', value: BigInt(heapAddress + ARRAY_HEAP_SLOT_WORDS * 8) } as Operand,
        reg(ARRAY_REGISTERS.scratch),
      ],
    },
    std(ARRAY_REGISTERS.scratch, ARRAY_REGISTERS.heapSlot, zero),
  ];
}

/**
 * ВОССТАНОВЛЕНИЕ БЛОКА РАНТАЙМА ПОСЛЕ СИСТЕМНОГО ВЫЗОВА В ТОЧКЕ ВХОДА (D12, 2026-11-08).
 *
 * ИЗМЕРЕНО прямым инструкционным зондом (`.tmp/d12-asm/probe-*.s`; вендорские `as`/`ld` собрали
 * ОДИН И ТОТ ЖЕ файл, он же прогнан на модели): `%b[12]=0, %b[13]=1, %b[14]=8, %b[15]=0x11`,
 * холостой `write(1, NULL, 0)`, затем `exit(%b[N])` — на ЖЕЛЕЗЕ все четыре клетки читаются **0**
 * (`b12` неотличим: там и должно быть 0), без вызова — **8**; модель даёт **8** в обоих случаях.
 *
 * Механизм — закон окна: `call wbs = 4` сдвигает окно на восемь регистров, поэтому `%b[12..15]`
 * вызывающего — это `%b[4..7]` ВЫЗЫВАЕМОГО (ядра), и ядро их зануляет. Программа с массивом,
 * напечатавшая число, теряла `8` (чтение `а[1]` давало `а[0]`) и адрес ячейки кучи (`создать`
 * падало кодом 139). Так как блок — ЧЕТЫРЕ ПОСТОЯННЫЕ, восстановление дешевле всего положить их
 * заново теми же командами, что и пролог (`movts`/`movtd`), а не хранить в памяти.
 *
 * `%b[12]` (ноль) НЕ восстанавливается намеренно: замер говорит, что после вызова там **0**, а это и
 * есть нужное значение. Платформа, которая положит туда не ноль, обязана будет перемерить это место.
 */
export function arrayBlockRestore(heapAddress: number): AsmInstruction[] {
  if (!Number.isInteger(heapAddress) || heapAddress < 0) {
    throw new ArrayRuntimeRefusal(`адрес кучи обязан быть неотрицательным целым, получено ${String(heapAddress)}`);
  }
  const { one, eight } = ARRAY_REGISTERS;
  return [
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 1 }, reg(one)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 8 }, reg(eight)] },
    {
      mnemonic: 'movtd',
      channel: 0,
      operands: [{ kind: 'imm64', value: BigInt(heapAddress) } as Operand, reg(ARRAY_REGISTERS.heapSlot)],
    },
  ];
}

/**
 * Сторож последовательности: проверяет **смысл** шагов, а не их наличие.
 *
 * Зачем: оракул сравнивает последовательность с ожидаемой, а сторож ловит дефект, если ожидание
 * подменили вместе с реализацией. Он же — материал негативного контроля (снятый сдвиг кучи,
 * потерянная запись длины).
 *
 * `name` — имя хост-вызова (`система.массив.*`) ИЛИ имя НОСИТЕЛЯ пролога
 * ({@link ARRAY_SLOT_CARRIER}): у пролога роста вызываемой свой предмет проверки — что адрес ячейки
 * кучи лёг именно АДРЕСОМ и именно в `%b[15]` (A4 §3.137).
 */
export function checkArraySequence(name: string, instructions: readonly AsmInstruction[]): string[] {
  const problems: string[] = [];
  const kinds = instructions.map((instruction) => instruction.mnemonic);

  // ── ПРОЛОГ РОСТА ВЫЗЫВАЕМОЙ: АДРЕС ЯЧЕЙКИ КУЧИ — 64-битным литералом В `%b[15]` ────────────────
  //
  // Сторож различает ТРИ подмены, каждая из которых «собирается» и молчит:
  //   1) адрес уехал в другую клетку — `создать` прочтёт чужое значение (куча у процедур разойдётся);
  //   2) в `%b[15]` положено ЗНАЧЕНИЕ (регистр), а не адрес — тогда `ldd`/`std` пойдут по мусорному
  //      адресу, и это тихая порча памяти, а не отказ;
  //   3) адрес дан коротким литералом (`movts`) — он столько не несёт, старшие разряды потеряются
  //      молча (правило «адрес кладётся `movtd`»).
  if (name === ARRAY_SLOT_CARRIER) {
    if (instructions.length !== 1 || kinds[0] !== 'movtd') {
      problems.push(
        `«${ARRAY_SLOT_CARRIER}»: шаг адреса ячейки кучи — ровно одна команда \`movtd\` ` +
          `(получено ${instructions.length}: ${kinds.join(', ') || '—'})`,
      );
    }
    const instruction = instructions[0];
    const source = instruction?.operands[0];
    const destination = instruction?.operands[1];
    if (destination === undefined || destination.kind !== 'reg' || destination.index !== ARRAY_REGISTERS.heapSlot) {
      problems.push(
        `«${ARRAY_SLOT_CARRIER}»: адрес ячейки обязан лечь в %b[${String(ARRAY_REGISTERS.heapSlot)}] — ` +
          'в другой клетке его не найдёт ни `создать`, ни `добавить`',
      );
    }
    if (source === undefined || source.kind !== 'imm64') {
      problems.push(
        `«${ARRAY_SLOT_CARRIER}»: адрес ячейки обязан быть 64-битным ЛИТЕРАЛОМ (форма imm64): ` +
          'ни значение из регистра, ни короткий литерал (`movts`) адреса кучи не несут',
      );
    }
    return problems;
  }

  /**
   * Кладёт ли последовательность значение в ЯЧЕЙКУ КУЧИ — то есть двигает ли она указатель кучи.
   *
   * С A4 (§3.136) куча живёт в памяти (первое слово её области), а `%b[15]` (`heapSlot`) несёт только
   * её АДРЕС, поэтому признак сдвига — `std` со ЗНАЧЕНИЕМ-РЕГИСТРОМ в базу `%b[15]`, а не `addd` с
   * регистром кучи. Проверяются ОБЕ операции, выделяющие память: `создать` (слово заголовка) и
   * `добавить` (элемент) — снятие сдвига в любой из них даёт один и тот же дефект: два массива
   * ложатся друг на друга.
   */
  function advancesHeap(sequence: readonly AsmInstruction[]): boolean {
    const slotStore = sequence.find(
      (instruction) =>
        instruction.mnemonic === 'std' &&
        instruction.operands[0]?.kind === 'reg' &&
        instruction.operands[1]?.kind === 'reg' &&
        (instruction.operands[1] as { readonly index: number }).index === ARRAY_REGISTERS.heapSlot,
    );
    if (slotStore === undefined) return false;
    const stored = (slotStore.operands[0] as { readonly index: number }).index;
    // В ячейку обязано лечь «блок + положительный сдвиг», а НЕ сам блок: иначе `создать` вернуло бы
    // программе указатель ЗА словом длины — этот дефект и был измерен пробой
    // `.tmp/osnova-a4-slot-trace.ts` (102008 вместо 102000). Сдвиг задаётся РЕГИСТРОМ, и форм две:
    // роль `восемь` (прежняя: резерв одного заголовка) или величина, материализованная `movts` с
    // `≥ 8` (форма TD-0013: заголовок плюс ёмкость под данные).
    const cellOf = (operand: Operand | undefined): number | undefined =>
      operand !== undefined && operand.kind === 'reg' ? (operand as { readonly index: number }).index : undefined;
    const reserveCell = (cell: number): boolean =>
      sequence.some(
        (instruction) =>
          instruction.mnemonic === 'movts' &&
          instruction.operands[0]?.kind === 'imm' &&
          (instruction.operands[0] as { readonly value: number }).value >= 8 &&
          cellOf(instruction.operands[1]) === cell,
      );
    return sequence.some((instruction) => {
      if (instruction.mnemonic !== 'addd') return false;
      if (cellOf(instruction.operands[2]) !== stored) return false;
      return [instruction.operands[0], instruction.operands[1]].some((operand) => {
        const cell = cellOf(operand);
        if (cell === undefined) return false;
        return cell === ARRAY_REGISTERS.eight || reserveCell(cell);
      });
    });
  }

  switch (name) {
    case 'система.массив.создать': {
      if (!kinds.includes('std')) problems.push('«создать»: длина массива не обнулена (нет записи)');
      // Указатель кучи обязан сдвинуться: иначе два массива лягут на один адрес.
      if (!advancesHeap(instructions)) {
        problems.push('«создать»: указатель кучи не сдвинут — массивы наложатся друг на друга');
      }
      break;
    }
    case 'система.массив.добавить': {
      if (!kinds.includes('ldd')) problems.push('«добавить»: длина не прочитана');
      // ПЕРВАЯ ЗАПИСЬ ОБЯЗАНА БЫТЬ ДЛИНОЙ — именно «прочитанная + 1». Прежний счёт «`std` не меньше
      // двух» с A4 (§3.136) перестал что-либо значить: в последовательности три записи (длина,
      // элемент, ячейка кучи), и снятие записи длины он пропускал — это и поймал негативный контроль
      // `src/e2k/e2kArrays.test.ts`.
      const incrementedLength = instructions.find(
        (instruction) =>
          instruction.mnemonic === 'addd' &&
          instruction.operands[1]?.kind === 'reg' &&
          (instruction.operands[1] as { readonly index: number }).index === ARRAY_REGISTERS.one &&
          instruction.operands[2]?.kind === 'reg',
      )?.operands[2];
      const firstStore = instructions.find((instruction) => instruction.mnemonic === 'std');
      const storesLength =
        incrementedLength !== undefined &&
        incrementedLength.kind === 'reg' &&
        firstStore !== undefined &&
        firstStore.operands[0]?.kind === 'reg' &&
        (firstStore.operands[0] as { readonly index: number }).index ===
          (incrementedLength as { readonly index: number }).index;
      if (!storesLength) {
        problems.push('«добавить»: новая длина не записана — следующий элемент ляжет на тот же адрес');
      }
      if (kinds.filter((kind) => kind === 'std').length < 2) {
        problems.push('«добавить»: длина не записана или значение не записано — нужны обе записи');
      }
      if (kinds.filter((kind) => kind === 'addd').length < 6) {
        problems.push('«добавить»: адрес элемента не досчитан (нужны ×8, заголовок, база и сдвиг кучи)');
      }
      // Указатель кучи обязан сдвинуться и здесь: `создать` выделяет только заголовок, а элементы
      // растут вместе с массивом. Без этого сдвига блок следующего массива ложится на первый элемент
      // этого — измерено (`docs/e2k-regalloc-debt.md` §12: FIR 177 вместо 181).
      if (!advancesHeap(instructions)) {
        problems.push('«добавить»: указатель кучи не сдвинут — следующий массив наложится на этот');
      }
      break;
    }
    case 'система.массив.получить': {
      if (kinds.filter((kind) => kind === 'addd').length < 5) {
        problems.push('«получить»: адрес элемента не досчитан (нужны ×8, заголовок и база)');
      }
      if (kinds.at(-1) !== 'ldd') problems.push('«получить»: последним шагом должно быть чтение');
      break;
    }
    case 'система.массив.установить': {
      // Адрес — тот же, что у `получить` (те же пять `addd`), но последним шагом ЗАПИСЬ.
      // Сторож держит именно это различие: подмени чтение записью — и операция перестанет
      // что-либо записывать, оставаясь при этом «собранной».
      if (kinds.filter((kind) => kind === 'addd').length < 5) {
        problems.push('«установить»: адрес элемента не досчитан (нужны ×8, заголовок и база)');
      }
      if (kinds.at(-1) !== 'std') problems.push('«установить»: последним шагом должна быть запись');
      break;
    }
    case 'система.массив.длина': {
      if (kinds.length !== 1 || kinds[0] !== 'ldd') problems.push('«длина»: это одно чтение слова длины');
      break;
    }
    default:
      problems.push(`«${name}»: сторож для этой операции не описан`);
  }
  return problems;
}

/**
 * Сторож закона формы памяти: в каждой `ldd`/`std` два регистровых операнда-регистра обязаны быть
 * **разными** — иначе модель взводит исключение при входе в блок, и запись (чтение) не исполняется
 * вовсе (механизм и замер — в шапке {@link ldd}).
 *
 * Почему сторож, а не надежда на рантайм: отказ модели **молчаливый** — код возврата 9 и адрес
 * начала блока вместо команды. Такой отказ уже трижды прочитали как «дефект кодировки»; сторож
 * называет причину там, где она возникает.
 *
 * Первый регистровый операнд формы — тот, который считает адрес: у `ldd` это `база`, у `std` —
 * операнд **второй** (первый несёт значение, `(значение, база, смещение)`). Проверка не зависит от
 * того, каким из двух регистров адрес назван: сравниваются оба.
 */
export function memoryOperandPairProblems(instructions: readonly AsmInstruction[]): string[] {
  const problems: string[] = [];
  instructions.forEach((instruction, index) => {
    const registerAt = instruction.mnemonic === 'ldd' ? 0 : instruction.mnemonic === 'std' ? 1 : -1;
    if (registerAt < 0) return;
    const first = instruction.operands[registerAt];
    const second = instruction.operands[registerAt + 1];
    if (first === undefined || second === undefined) {
      problems.push(`#${String(index)} ${instruction.mnemonic}: у формы памяти нет двух регистровых операндов`);
      return;
    }
    if (first.kind !== 'reg' || second.kind !== 'reg') return; // нерегистровые формы проверяет кодировщик
    if (first.index !== second.index) return;
    problems.push(
      `#${String(index)} ${instruction.mnemonic}: адрес считается одним и тем же %b[${String(first.index)}] ` +
        'в обоих операндах — модель взведёт исключение при входе в блок, и обращение не исполнится ' +
        '(src/e2k/arrayRuntime.ts, шапка `ldd`)',
    );
  });
  return problems;
}




