/**
 * Размер окна (`setbn rsz`), при котором верхние регистры рантайма **адресуемы**.
 *
 * `%b[N]` существует только внутри текущего окна: индекс переводится в физический регистр как
 * `(wd_base_d + idx) % MAXSR_D`, а выход за `size_d` — исключение `exc_window_bounds`
 * (`qemu/target/e2k/reg-index.h:55-81`). Измерено (`.tmp/rsz-sweep.ts`): при `rsz = 5` доступны
 * `%b[0..11]`, при `rsz = 6` — `%b[0..13]`, при `rsz = 7` — `%b[0..15]`, а `rsz ≥ 8` не работает
 * вовсе (начальные `psize_q = 4`, `size_q = 8` квадрослов — `qemu/linux-user/e2k/cpu_loop.c:302-303`
 * — дают не больше 16 единиц).
 */
export const ARRAY_WINDOW_RSZ = 7;

/**
 * Размер окна (`setwd wsz`) в прологе образа, в квадрословах: `wsz = 12` — это двадцать четыре
 * регистровые единицы.
 *
 * **Измерено на железе 2026-10-09 (§3.116.1–3):** `wsz > 8` не гипотеза, а ежедневно исполняемая
 * форма у МЦСТ — `/bin/bash` открывает окна `0xc` **165 раз**, `0x12` 87 раз, вплоть до `0x2e`;
 * `lcc` — `0xc` 12, `0x10` 14; те же значения у `as`, `ld`, `ld-linux.so.2`, `/bin/true`, `/bin/ls`.
 * Проба в НАШЕЙ форме подтверждает: `setwd wsz=0xc` + `setbn rbs=4, rsz=7` (годность `4+7+1 = 12`)
 * не падает вовсе (код 124 — петля), а наш прежний пролог без `setwd` падал на первом `%b`.
 *
 * **Почему двенадцать, а не минимум восемь.** Восьми хватает ровно на область вращения
 * (`0 + 7 + 1 = 8`), но вызываемая получает `2·(wsz − wbs)`: при `wbs = SYSCALL_WBS = 4` это
 * `2·(12 − 4) = 16` единиц — ровно тот бюджет, на который рассчитывает раскладка
 * (`CALLEE_REGISTERS` = `%b[8..15]`, `WINDOW_REGISTERS_CALLEE = 16`, патч модели `size_q = 12`).
 * Замер различает два значения прямо: `wsz = 8` даёт на модели **9** вместо 91 (раскладка сшита с
 * шестнадцатью единицами), `wsz = 12` — **91**.
 *
 * **Чего это стоит (названный долг, §3.116.4).** Закон `wsz − wbs = 4` требует, чтобы у `call`
 * было `wbs = wsz − 4 = 8`. Наш сайт вызова сейчас `wbs = 4` (номер в `%r8`), поэтому при `wsz = 12`
 * ловушка НЕ берётся: проба `za-w12-t3-wbs4` даёт **137** (`SIGKILL`), а `za-w12-t3-wbs8` (номер в
 * `%r16`) — **42**. То есть следующий шаг — сайт вызова, и он двигается вместе с этим числом.
 */
export const ARRAY_WINDOW_WSZ = 12;

/** С какого номера регистры заняты рантаймом: чужой операнд отсюда — отказ. */
export const RESERVED_FROM = 10;

