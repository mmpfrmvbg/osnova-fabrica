/**
 * РАНТАЙМ МАССИВОВ e2k: ЗАМЕНА `IR.invoke` РЕАЛЬНЫМИ ОБРАЩЕНИЯМИ К ПАМЯТИ.
 *
 * # Почему это нужно
 *
 * В регистровом IR массивов как типа нет: всё уходит в хост-вызов (`система.массив.*`), а эмиттер
 * оболочки делает из него носитель `IR.invoke`. Пока такие вызовы не заменены настоящими `ldd`/`std`,
 * ядро FIR не собирается: 22 вызова из 111 инструкций (`docs/e2k-opcodes-real.md` §7).
 *
 * # Соглашение (НАШЕ решение, не из источника)
 *
 * Массив — указатель на блок `[длина:8][элемент0:8][элемент1:8]…`. Почему так: адрес в e2k —
 * **сумма двух регистров** (`qemu/target/e2k/tcg/translate-al-c11.c:26-34`), поля смещения в
 * команде нет, поэтому длина должна лежать рядом с элементами и находиться по тому же указателю.
 *
 * | регистр | что держит | кто пишет |
 * |---|---|---|
 * | `%b[15]` | указатель кучи (растёт вверх по 8 байт на массив) | пролог, `создать` (заголовок) и `добавить` (элемент) |
 * | `%b[14]` | 8 — размер элемента и заголовка | пролог |
 * | `%b[12]` | 0 — нулевое смещение адреса | пролог |
 * | `%b[13]` | 1 — прирост длины на элемент | пролог |
 * | `%b[11]`, `%b[10]` | временные (`scratch`, `scratch2`) | рантайм (портит) |
 *
 * Указатель кучи обязаны двигать **обе** выделяющие операции: `создать` — на слово заголовка,
 * `добавить` — на элемент. Пока `добавить` его не двигал, блок второго массива начинался на первом
 * элементе первого: `получить(вход, i)` при i = 0…7 давал `[длина(коэф), коэф[0..3], вход[5..7]]`,
 * и FIR давал 177 вместо 181 (измерено, `docs/e2k-regalloc-debt.md` §12).
 *
 * Чужой код в эти регистры не пишет: операция массива, у которой операнд попал в зарезервированную
 * область, **отказывает** ({@link RESERVED_FROM} и ниже) — иначе она затрёт указатель кучи.
 *
 * # Умножение на 8 — удвоением, а не `shls`
 *
 * `shls` есть в таблице МЦСТ (ALOPF1, `0x18`, `opcodes/e2k-opc.h:139`), но **не проверен прогоном**;
 * `adds` проверен (`src/e2k/e2kWideQemu.test.ts`). Выбор в пользу проверенного: три `adds` дают ×8.
 *
 * # Чего рантайм НЕ делает
 *
 * - **границы не проверяются**: в модели `получить` вне границ даёт `null`
 *   (`src/runtime/vm/interpreter.ts:70`), наш `ldd` прочитает соседнюю память. Для ядер DSP индексы
 *   в границах по построению; проверка границ требует сравнения и ветвления — отдельная работа.
 * - `установить`, `удалить`, `срез`, строки, математика — **отказ с причиной**.
 */

import type { AsmInstruction, Operand } from './backend';

const reg = (index: number): Operand => ({ kind: 'reg', index });

/**
 * Зарезервированные регистры рантайма.
 *
 * `scratch` и `scratch2` рантайм **портит** — это часть контракта, а не случайность.
 */
export const ARRAY_REGISTERS = {
  /**
   * Регистры взяты с **верхнего края окна**, и это вынужденно: `%b[N]` существует только внутри
   * текущего окна (`qemu/target/e2k/reg-index.h:55-81`), а модель при `rsz = 7` даёт всего
   * `%b[0..15]` — измерено (`.tmp/rsz-sweep.ts`). Поэтому территория рантайма — `%b[10..15]`;
   * код, которому этого мало, получает **отказ**, а не тихую порчу указателя кучи.
   */
  /** Ноль: нулевое смещение адреса (`ldd база, ноль, приёмник`). */
  zero: 12,
  /** Единица: длина растёт **на элемент**, а «+1» из ниоткуда не берётся. */
  one: 13,
  /** Восемь: размер элемента и слова заголовка. */
  eight: 14,
  /** Указатель кучи: растёт вверх по 8 байт на массив. */
  heap: 15,
  /** Временный (`×8` и адрес элемента) — рантайм **портит**. */
  scratch: 11,
  /** Второй временный (новая длина и адрес записи) — рантайм **портит**. */
  scratch2: 10,
} as const;

/**
 * Размер окна (`setbn rsz`), при котором верхние регистры рантайма **адресуемы**.
 *
 * `%b[N]` существует только внутри текущего окна: индекс переводится в физический регистр как
 * `(wd_base_d + idx) % MAXSR_D`, а выход за `size_d` — исключение `exc_window_bounds`
 * (`qemu/target/e2k/reg-index.h:55-81`). Измерено (`.tmp/rsz-sweep.ts`): при `rsz = 5` доступны
 * `%b[0..11]`, при `rsz = 6` — `%b[0..13]`, при `rsz = 7` — `%b[0..15]`, а `rsz ≥ 8` не работает
 * вовсе (начальные `psize_q = 4`, `size_q = 8` квадрослов — `qemu/linux-user/e2k/cpu_loop.c:302-303`
 * — дают не больше 16 единиц).
 */
export const ARRAY_WINDOW_RSZ = 7;

/**
 * Размер окна (`setwd wsz`), в 16-байтовых единицах: `wsz = 16` — это 32 двойных слова,
 * то есть `%b[0..31]`. Измерено: без `setwd` доступны только `%b[0..15]`, а с `setwd wsz=16`
 * и `setbn rsz=15` работают `%b[15]`, `%b[20]` и `%b[31]` (`.tmp/setwd-verify.ts`).
 */
export const ARRAY_WINDOW_WSZ = 16;

/** С какого номера регистры заняты рантаймом: чужой операнд отсюда — отказ. */
export const RESERVED_FROM = 10;

/** Вызовы, которые рантайм умеет заменять настоящими обращениями к памяти. */
export const SUPPORTED_ARRAY_CALLS: readonly string[] = [
  'система.массив.создать',
  'система.массив.длина',
  'система.массив.получить',
  'система.массив.добавить',
];

/** Отказ рантайма массивов: причина называется, а не замалчивается. */
export class ArrayRuntimeRefusal extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ArrayRuntimeRefusal';
  }
}

/** Арность вызова по источнику: `src/runtime/vm/invokeRegistry.ts:44-50`. */
const ARITY: Readonly<Record<string, number>> = {
  'система.массив.создать': 0,
  'система.массив.длина': 1,
  'система.массив.получить': 2,
  'система.массив.добавить': 2,
};

/** Проверить, что операнд не попал в зарезервированную область. */
function checkOperand(operand: Operand, name: string, role: string): void {
  if (operand.kind !== 'reg') {
    throw new ArrayRuntimeRefusal(`«${name}»: ${role} обязан быть регистром, а не ${operand.kind}`);
  }
  if (operand.index >= RESERVED_FROM) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: регистр %b[${operand.index}] зарезервирован рантаймом массивов (с %b[${RESERVED_FROM}] ` +
        'и выше: куча, размер элемента, ноль и временные — src/e2k/arrayRuntime.ts); ' +
        'операция зарезервировала бы их',
    );
  }
}

/** `adds src1, src2, dst` — форма ALF1: адрес/арифметика (`opcodes/e2k-opc.h:19`). */
const adds = (src1: number, src2: number, dst: number): AsmInstruction => ({
  mnemonic: 'adds',
  channel: 0,
  operands: [reg(src1), reg(src2), reg(dst)],
});

/**
 * ЗАКОН ФОРМЫ ПАМЯТИ: ОСНОВАНИЕ И СМЕЩЕНИЕ — РАЗНЫЕ РЕГИСТРЫ. Механизм назван замером.
 *
 * # Что известно было
 *
 * `.tmp/probe-basis-sweep.ts` и `.tmp/probe-basis-split.ts` дали: `std` с основанием `%b[12]` встаёт
 * исключением, с `%b[11]` — работает; отсюда родилась неверная догадка «`%b[12]` не адресуется».
 * Закон (совпадение регистров, а не их номер) назван в `src/e2k/printRuntime.ts` и закрыт коммитом
 * `eee76ed` — но там честно записано: **почему** совпадение валит порт, в источниках не сказано.
 *
 * # Механизм (измерен 2026-09-27, диагностическая пересборка порта)
 *
 * Три замера, каждый отсекает прежнюю гипотезу:
 *
 * 1. `error_report` в `linux-user/e2k/cpu_loop.c` на месте `EXCP_EXCEPTION`: в момент отказа
 *    `BR = 0x1c0` (`rbs = 0`, `rsz = 7`), `WD = 0x4000800000` (`base_d = 0`, `size_d = 16`) — окно
 *    ШИРЕ, чем требует `%b[12]`, а теги всех регистров нулевые. Значит ни ширина окна, ни значения
 *    не при чём.
 * 2. `error_report` в `target/e2k/tcg/translate-al.c` на обеих ветвях (`e2k_parse_src`/`e2k_parse_dst`):
 *    все проверки индексов проходят — `idx = 12` при `rsz_full_d = 16` исключения не взводит.
 * 3. Дамп микрокоманд порта (`qemu-e2k -d in_asm,op`) показал саму проверку:
 *
 *        ld_i32 loc24,loc7,$0x10   ; тег источника 1 (база)
 *        ld_i32 loc25,loc7,$0x10   ; тег источника 2 (смещение) — ТО ЖЕ СМЕЩЕНИЕ
 *        ld_i32 loc26,loc6,$0x28   ; тег источника 3 (значение)
 *        or_i32  loc23,loc23,loc24
 *        or_i32  loc23,loc23,loc25
 *        or_i32  loc23,loc23,loc26
 *        brcond_i32 loc23,$0x4040404,tsteq,$L2
 *        call e2k_set_have_exception
 *
 *    Порт складывает в одно число вклады **трёх** источников формы и сравнивает результат с
 *    `E2K_TAG_UNPACKED_IS_DT_MASK_QP = 0x04040404` (`target/e2k/cpu.h:107`); при несовпадении
 *    вызывает `e2k_set_have_exception`. Вклад каждого источника — **один байт** из его записи в
 *    файле регистров (`ld8u_i32 …,$0x11`), то есть проверяется «значение определено», а не величина.
 *    `have_exception` взводится **при входе в блок** (`e2k_translate_check_al_common`,
 *    `target/e2k/tcg/translate-al.c:1985-2140`), поэтому `IP` в отчёте порта — начало блока
 *    (`0x100058`/`0x100060`), а не команда, и обращение не исполняется.
 *
 *    **Чего здесь НЕ доказано (проверено 2026-09-27, и это важно не додумывать):** что совпадение
 *    регистров даёт «на байт меньше». Правдоподобно (вклады трёх источников, а источников два), но
 *    **не измерено**: дамп микрокоманд падающего образа обрывается на месте отказа, и проверки с
 *    вызовом исключения в него не попадают, а у рабочего образа таких проверок **пять** против
 *    **одной** у падающего. Значит различие может лежать и не во вкладе байта. До отдельного опыта
 *    (сравнить вклады по каждому из трёх источников) это остаётся **открытым**, и записано как
 *    открытое, а не как причина.
 *
 * # Чем подтверждено (различающий опыт, `.tmp/osnova-operand-law.ts`)
 *
 * Одно тело, меняется только пара регистров; код возврата — прочитанное из области значение:
 *
 * | форма | результат |
 * |---|---|
 * | `std 55, [%b[11] + %b[11]]` | исключение (код возврата 9) |
 * | `std 55, [%b[12] + %b[12]]` | исключение (9) |
 * | `std 55, [%b[13] + %b[13]]` | исключение (9) |
 * | `std 55, [%b[11] + %b[12]]` | **55** — запись исполнена |
 * | `std 55, [%b[12] + %b[11]]` | **55** — запись исполнена |
 *
 * Положительный контроль здесь обязателен и он есть: без строк «разные регистры» опыт не отличал бы
 * «совпадение валит» от «падает всё».
 *
 * # Граница правила: совпадение проверено НЕ для всех пар (`.tmp/osnova-triple-law.ts`)
 *
 * Механизм симметрию **не** обещает, и опыт её не подтверждает — важно не записать лишнего:
 *
 * | опыт | результат |
 * |---|---|
 * | значение ≠ база ≠ смещение (все три разные) | 55 — запись исполнена |
 * | значение = база | исключение |
 * | база = смещение | исключение |
 * | значение = смещение | **исключения НЕТ** |
 * | все три — один регистр | исключение |
 *
 * Отсюда рабочее правило ровно такое: **два регистра, считающие адрес, обязаны быть разными**;
 * значение обязано отличаться от базы, а от смещения — не обязано. Почему асимметрия — в заголовке
 * не сказано, это замер; распространять закон на пару «значение + смещение» оснований нет.
 *
 * # Что из этого следует для кода
 *
 * Догадка «`%b[12]` — это ноль, его нельзя трогать» **снята**: `%b[12]` — обычный вращаемый регистр
 * (`%b[0..15]` при `rsz = 7`), а ноль в нём — удобная константа пролога. Ограничение одно и оно
 * проверяется: {@link memoryOperandPairProblems} — два регистра, считающие адрес, обязаны быть
 * разными. Рантайм ему удовлетворяет по построению (`zero` — смещение, `heap`/`scratch` — база), но
 * проверка нужна: молчаливый отказ модели не отличим от «программа неверна».
 *
 * # Что модель нам говорит про устройство — и почему это тот же корень
 *
 * Стр. 56 руководства (`docs/vliw-e2k-model.md`, «Что важно: АЛУ не равнозначны»): запись в память
 * умеют **только АЛУ2 и АЛУ5**, чтение — АЛУ0/АЛУ2/АЛУ3/АЛУ5. В нашей кодировке это и означает
 * «каналы 2 и 5» для `std` (`opcodes/e2k-opc.h:969-984`) — то есть ограничение формы памяти
 * приходит **не от регистров**, а от устройства, которое эту форму исполняет. Пара регистров и
 * выбор канала — две стороны одного: адрес считает устройство обращения к памяти, и оно же проверяет
 * годность своих операндов.
 */
const ldd = (src1: number, src2: number, dst: number): AsmInstruction => ({
  mnemonic: 'ldd',
  channel: 0,
  operands: [reg(src1), reg(src2), reg(dst)],
});

/**
 * `std значение, база, смещение` — порядок операндов **текстовый** (измерено): у ассемблера текст
 * идёт `(значение, база, смещение)` = `(src3, src1, src2)` (`.tmp/std-order.ts`).
 */
const std = (value: number, src1: number, src2: number): AsmInstruction => ({
  mnemonic: 'std',
  channel: 2, // `st*` разрешены только в каналах 2 и 5 (opcodes/e2k-opc.h:969-984)
  operands: [reg(value), reg(src1), reg(src2)],
});

/**
 * `×8` удвоением: три `adds` (проверенная форма), результат — в `dst`.
 * Требует, чтобы `src` и `dst` были разными регистрами (иначе первое удвоение затрёт вход).
 */
function timesEight(src: number, dst: number): AsmInstruction[] {
  return [adds(src, src, dst), adds(dst, dst, dst), adds(dst, dst, dst)];
}

/**
 * Понизить вызов массива в настоящие команды e2k.
 *
 * @param name имя хост-вызова (`система.массив.*`) — семантику несёт имя, а не код операции
 * @param args регистры аргументов в порядке вызова
 * @param dst регистр приёмника (у `добавить` результата нет — `undefined`)
 */
export function lowerArrayCall(name: string, args: readonly Operand[], dst: number | undefined): AsmInstruction[] {
  const arity = ARITY[name];
  if (arity === undefined) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: у рантайма массивов нет такой операции — он умеет ${SUPPORTED_ARRAY_CALLS.join(', ')}; ` +
        'остальное (установить, удалить, срез, строки, математика) не заменено настоящими обращениями',
    );
  }
  if (args.length !== arity) {
    throw new ArrayRuntimeRefusal(`«${name}»: аргументов ${args.length}, по источнику ${arity} (invokeRegistry.ts:44-50)`);
  }
  args.forEach((operand, index) => checkOperand(operand, name, `аргумент ${index}`));
  const registers = args.map((operand) => (operand as { index: number }).index);
  const { zero, one, eight, heap, scratch, scratch2 } = ARRAY_REGISTERS;

  if (dst !== undefined && dst >= RESERVED_FROM) {
    throw new ArrayRuntimeRefusal(
      `«${name}»: приёмник %b[${dst}] зарезервирован рантаймом массивов (с %b[${RESERVED_FROM}])`,
    );
  }

  switch (name) {
    case 'система.массив.длина':
      // Длина лежит в первом слове блока: адрес = массив + 0.
      return [ldd(registers[0]!, zero, dst!)];
    case 'система.массив.создать':
      // Указатель кучи — в приёмник, длина = 0, куча сдвинута на слово заголовка.
      return [adds(heap, zero, dst!), std(zero, dst!, zero), adds(heap, eight, heap)];
    case 'система.массив.получить': {
      // Адрес элемента = массив + 8 + индекс*8.
      const steps = timesEight(registers[1]!, scratch);
      return [
        ...steps,
        adds(scratch, eight, scratch),
        adds(scratch, registers[0]!, scratch),
        ldd(scratch, zero, dst!),
      ];
    }
    case 'система.массив.добавить': {
      // Длина обновляется ДО вычисления адреса (иначе адрес считался бы по новой длине),
      // но адрес считается по СТАРОЙ длине — она остаётся в scratch.
      const steps = timesEight(scratch, scratch2);
      return [
        ldd(registers[0]!, zero, scratch),
        adds(scratch, one, scratch2),
        std(scratch2, registers[0]!, zero),
        ...steps.map((instruction) => instruction),
        adds(scratch2, eight, scratch2),
        adds(scratch2, registers[0]!, scratch2),
        std(registers[1]!, scratch2, zero),
        // Указатель кучи двигается на элемент: без этого блок СЛЕДУЮЩЕГО массива ляжет на первый
        // элемент этого (замер: `вход` и `коэффициенты` в FIR перекрывались, `получить(вход, i)` при
        // i = 0…7 давал `[длина(коэф), коэф[0..3], вход[5..7]]`, FIR давал 177 вместо 181 —
        // docs/e2k-regalloc-debt.md §12). Адресация выше считается от ДЛИНЫ массива, поэтому сдвиг
        // кучи на неё не влияет — он нужен следующему `создать`.
        adds(heap, eight, heap),
      ];
    }
    default:
      throw new ArrayRuntimeRefusal(`«${name}»: ветвь не описана`);
  }
}

/**
 * Пролог: ноль, размер элемента и указатель кучи.
 *
 * Куча — **внешняя память** (адрес 64-битным литералом, форма 0xdc), а не литерал в команде: она
 * должна быть записываемой и лежать **не в странице кода** — запись в страницу кода кончается
 * `QEMU internal SIGSEGV {code=ACCERR}` (измерено, `src/e2k/e2kMemoryQemu.test.ts`).
 */
export function arrayPrologue(heapAddress: number): AsmInstruction[] {
  if (!Number.isInteger(heapAddress) || heapAddress < 0) {
    throw new ArrayRuntimeRefusal(`адрес кучи обязан быть неотрицательным целым, получено ${String(heapAddress)}`);
  }
  const { zero, one, eight, heap } = ARRAY_REGISTERS;
  return [
    // Окно НЕ расширяется через `setwd`, хотя это возможно: байты `setwd` сверены с ассемблером, и
    // в модели с `setwd wsz=16` + `setbn rsz=15` доступны `%b[15]`, `%b[20]`, `%b[31]` (замер в
    // docs/e2k-opcodes-real.md §7.7). Причина отказа от расширения: программа с РАСШИРЕННЫМ окном и
    // обращением к памяти в модели **зависает** — измерено, воспроизводимо (два прогона по 123 с,
    // «QEMU не запустился»), а при окне по умолчанию та же программа проходит. Разбирать эту связку —
    // отдельная работа; до тех пор рантайм живёт в окне по умолчанию (`rsz = 7` → `%b[0..15]`).
    {
      mnemonic: 'setbn',
      channel: 0,
      operands: [{ kind: 'imm', value: ARRAY_WINDOW_RSZ }, { kind: 'imm', value: 0 }, { kind: 'imm', value: 0 }],
    },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 0 }, reg(zero)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 1 }, reg(one)] },
    { mnemonic: 'movts', channel: 0, operands: [{ kind: 'imm', value: 8 }, reg(eight)] },
    { mnemonic: 'movtd', channel: 0, operands: [{ kind: 'imm64', value: BigInt(heapAddress) } as Operand, reg(heap)] },
  ];
}

/**
 * Сторож последовательности: проверяет **смысл** шагов, а не их наличие.
 *
 * Зачем: оракул сравнивает последовательность с ожидаемой, а сторож ловит дефект, если ожидание
 * подменили вместе с реализацией. Он же — материал негативного контроля (снятый сдвиг кучи,
 * потерянная запись длины).
 */
export function checkArraySequence(name: string, instructions: readonly AsmInstruction[]): string[] {
  const problems: string[] = [];
  const kinds = instructions.map((instruction) => instruction.mnemonic);

  /**
   * Сдвигает ли последовательность указатель кучи на месте (`adds …, %b[heap]` в приёмник).
   *
   * Проверяются ОБЕ операции, выделяющие память: `создать` (заголовок) и `добавить` (элемент).
   * Общий сторож нужен потому, что снятие сдвига в любой из них даёт один и тот же дефект —
   * два массива ложатся друг на друга, — и раньше `добавить` этого сдвига не делал.
   */
  function advancesHeap(sequence: readonly AsmInstruction[]): boolean {
    return sequence.some(
      (instruction) =>
        instruction.mnemonic === 'adds' &&
        instruction.operands.some(
          (operand) => operand.kind === 'reg' && operand.index === ARRAY_REGISTERS.heap,
        ) &&
        instruction.operands[2]?.kind === 'reg' &&
        (instruction.operands[2] as { index: number }).index === ARRAY_REGISTERS.heap,
    );
  }

  switch (name) {
    case 'система.массив.создать': {
      if (!kinds.includes('std')) problems.push('«создать»: длина массива не обнулена (нет записи)');
      // Указатель кучи обязан сдвинуться: иначе два массива лягут на один адрес.
      if (!advancesHeap(instructions)) {
        problems.push('«создать»: указатель кучи не сдвинут — массивы наложатся друг на друга');
      }
      break;
    }
    case 'система.массив.добавить': {
      if (!kinds.includes('ldd')) problems.push('«добавить»: длина не прочитана');
      if (kinds.filter((kind) => kind === 'std').length < 2) {
        problems.push('«добавить»: длина не записана или значение не записано — нужны обе записи');
      }
      if (kinds.filter((kind) => kind === 'adds').length < 6) {
        problems.push('«добавить»: адрес элемента не досчитан (нужны ×8, заголовок, база и сдвиг кучи)');
      }
      // Указатель кучи обязан сдвинуться и здесь: `создать` выделяет только заголовок, а элементы
      // растут вместе с массивом. Без этого сдвига блок следующего массива ложится на первый элемент
      // этого — измерено (`docs/e2k-regalloc-debt.md` §12: FIR 177 вместо 181).
      if (!advancesHeap(instructions)) {
        problems.push('«добавить»: указатель кучи не сдвинут — следующий массив наложится на этот');
      }
      break;
    }
    case 'система.массив.получить': {
      if (kinds.filter((kind) => kind === 'adds').length < 5) {
        problems.push('«получить»: адрес элемента не досчитан (нужны ×8, заголовок и база)');
      }
      if (kinds.at(-1) !== 'ldd') problems.push('«получить»: последним шагом должно быть чтение');
      break;
    }
    case 'система.массив.длина': {
      if (kinds.length !== 1 || kinds[0] !== 'ldd') problems.push('«длина»: это одно чтение слова длины');
      break;
    }
    default:
      problems.push(`«${name}»: сторож для этой операции не описан`);
  }
  return problems;
}

/**
 * Сторож закона формы памяти: в каждой `ldd`/`std` два регистровых операнда-регистра обязаны быть
 * **разными** — иначе модель взводит исключение при входе в блок, и запись (чтение) не исполняется
 * вовсе (механизм и замер — в шапке {@link ldd}).
 *
 * Почему сторож, а не надежда на рантайм: отказ модели **молчаливый** — код возврата 9 и адрес
 * начала блока вместо команды. Такой отказ уже трижды прочитали как «дефект кодировки»; сторож
 * называет причину там, где она возникает.
 *
 * Первый регистровый операнд формы — тот, который считает адрес: у `ldd` это `база`, у `std` —
 * операнд **второй** (первый несёт значение, `(значение, база, смещение)`). Проверка не зависит от
 * того, каким из двух регистров адрес назван: сравниваются оба.
 */
export function memoryOperandPairProblems(instructions: readonly AsmInstruction[]): string[] {
  const problems: string[] = [];
  instructions.forEach((instruction, index) => {
    const registerAt = instruction.mnemonic === 'ldd' ? 0 : instruction.mnemonic === 'std' ? 1 : -1;
    if (registerAt < 0) return;
    const first = instruction.operands[registerAt];
    const second = instruction.operands[registerAt + 1];
    if (first === undefined || second === undefined) {
      problems.push(`#${String(index)} ${instruction.mnemonic}: у формы памяти нет двух регистровых операндов`);
      return;
    }
    if (first.kind !== 'reg' || second.kind !== 'reg') return; // нерегистровые формы проверяет кодировщик
    if (first.index !== second.index) return;
    problems.push(
      `#${String(index)} ${instruction.mnemonic}: адрес считается одним и тем же %b[${String(first.index)}] ` +
        'в обоих операндах — модель взведёт исключение при входе в блок, и обращение не исполнится ' +
        '(src/e2k/arrayRuntime.ts, шапка `ldd`)',
    );
  });
  return problems;
}
