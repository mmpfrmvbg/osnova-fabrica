/**
 * ОРАКУЛ 2.2 (D5, `docs/verification-debt.md` случай 73): «БАЗЫ БЛОКА НЕ ВЫДАЛИ» НАЗЫВАЕТ ЧИСЛА, А
 * НЕ ТОЛЬКО ФАКТ.
 *
 * # Какую тихую ложь закрывает эта проверка
 *
 * Когда `allocateProgram` не находила для вызываемой процедуры 3 подряд свободные клетки бюджета,
 * понижение говорило: «раскладка не выдала базу блока рантайма (операнд 6 носителя) — обращение ушло
 * бы в чужие клетки». Текст верный, но читается как ДЕФЕКТ ВЫДАЧИ: будто база была, а её потеряли.
 * Из-за этого диагноз ушёл в сторону `regAlloc` и три круга искал «потерянную базу» там, где её не
 * могло быть по построению (`.tmp/atoms/20261111-231500-etap3-l2-blocker.md` §§41–45, 97–98).
 *
 * # Что измерено (2026-11-12, .tmp/rb-n{3..10}.osnova)
 *
 * Проба: 3 параметра, цикл `пока` с `Списки.установить` и N локальных, читаемых в теле, плюс вторая
 * запись после цикла. N локальных = сколько значений ДЕРЖИТСЯ одновременно; блок требует 3 клетки
 * ПОДРЯД, бюджет вызываемой — 15.
 *
 *   N=3..5 → отказов 0 (база есть);
 *   N=6    → 2 отказа: свободно 2 (%b[22], %b[23]) из 15, занято 13, пик отрезков 15;
 *   N=7    → 2 отказа (свободно 1);
 *   N=8    → 2 отказа (свободно 0);
 *   N=9..10→ 8/10 отказов (раскладка уже не влезает сама).
 *
 * # Почему это стена РАЗМЕРНАЯ, а не потеря базы — доказательство, а не осторожность
 *
 * `allocateSegments` всегда берёт НАИМЕНЬШУЮ свободную клетку, значит к моменту первого взятия k-й
 * клетки k−1 меньших ДЕРЖАТСЯ, и число взятых клеток равно пику одновременно занятых. Отсюда: нет
 * трёх свободных подряд ⇒ занято ≥ 13 из 15 ⇒ при бюджете 15−3 = 12 пик 13 не влезает ⇒ нужен
 * `spill`. Вытеснение в вызываемой — названная граница (`src/e2k/programImage.ts#calleeLimit`,
 * §3.140), поэтому «дать базу» здесь можно только сменой алгоритма раскладки — §10.1, СТОП.
 * Проверка это и закрепляет: причина обязана сказать «РАЗМЕРНАЯ стена».
 *
 * # Что проверяется
 *
 * П1 работающая сторона границы: N=5 — 0 отказов.
 * П2 отказывающая сторона: N=6 — ровно 2 отказа, оба `OSN-LOW-003`, и текст КАЖДОГО несёт числа и
 *    слово о размерной стене.
 * П3 отказ — по ВСЕМ записям (ловушка `report[0]`, AGENTS.md): причина у всех отказов одна, и ни один
 *    не остался без причины.
 *
 * # Негативный контроль (20.1)
 *
 * Снятие хвоста «Причина: …» из `src/e2k/arrayRuntime.ts#формыВызоваМассива` краснит РОВНО **2**
 * проверки (П2 и П3) и не трогает П1: работающая сторона от причины не зависит. Числа при снятии не
 * сдвигаются.
 *
 * # Чего здесь НЕТ
 *
 * Проверка НЕ утверждает, что база обязана выдаваться при N=6: она утверждает ОБРАТНОЕ — что при
 * занятости 13/15 причина названа числами. Снятие этой границы (вытеснение в вызываемой или
 * перекраска) — отдельный атом с решением владельца (§10.1), а не правка этой проверки.
 */

import { describe, it, expect } from 'vitest';
import { loweredProgram } from './lowered';
import { parseV3 } from '../compiler-v3/index';
import type { CompileOptions } from '../compiler/compiler';

const ФАЙЛ = 'проба-базы.osnova';

interface Отказ {
  readonly код: string;
  readonly причина: string;
}

/**
 * Проба с N локальными, которые читаются в теле цикла: каждое значение ДЕРЖИТСЯ через
 * `Списки.установить`, поэтому давление на бюджет вызываемой растёт ровно с N.
 */
function проба(n: number): string {
  const локальные = Array.from({ length: n }, (_, at) => `  пусть l${String(at)} = ${String(at)}`);
  const сумма = ['з', ...Array.from({ length: n }, (_, at) => `l${String(at)}`)].join(' + ');
  return [
    'процедура лист(лента: Список Число, состояние: Список Число, з: Число) -> Число',
    ...локальные,
    '  пусть idx = 0',
    '  пока idx < 4',
    `    Списки.установить(лента, idx, ${сумма})`,
    '    idx = idx + 1',
    '  конец пока',
    '  Списки.установить(состояние, 0, idx)',
    '  вернуть 1',
    'конец лист',
    '',
    'действие главная()',
    '  пусть лента: Список Число = []',
    '  пусть сч = 0',
    '  пока сч < 8',
    '    Списки.добавить(лента, 0, 0)',
    '    сч = сч + 1',
    '  конец пока',
    '  пусть состояние: Список Число = [0, 0]',
    '  лист(лента, состояние, 5)',
    '  вывести состояние[0]',
    'конец главная',
    '',
  ].join('\n');
}

/** Отказы понижения; бросок компилятора — тоже отказ, но отдельной записью, чтобы не терялся. */
function отказы(источник: string): readonly Отказ[] {
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор v3: ${разбор.errors.join('; ')}`).toEqual([]);
  const options: CompileOptions = {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  };
  const итог = loweredProgram(источник, options);
  if (итог.ок) return [];
  const внутри = итог.отказ as unknown as { отказы?: readonly Отказ[] };
  return внутри.отказы ?? [{ код: 'БРОСОК', причина: String((итог.отказ as { причина?: string }).причина ?? итог.отказ) }];
}

describe('база блока рантайма массивов: граница названа числами, а не «не выдала»', () => {
  it('П1 работающая сторона: 5 локальных — база есть, отказов 0', () => {
    // Замер 2026-11-12: N=3,4,5 — отказов 0; граница начинается на N=6. Сторона важна не меньше
    // отказа: иначе «причина названа» можно получить, сломав выдачу базы во всех случаях.
    expect(отказы(проба(5))).toEqual([]);
  });

  it('П2 отказывающая сторона: 6 локальных — 2 отказа, и в КАЖДОМ причина с числами и словом о стене', () => {
    const список = отказы(проба(6));
    expect(список.length, 'отказов').toBe(2);
    for (const отказ of список) {
      expect(отказ.код, 'код отказа').toBe('OSN-LOW-003');
      // ЧИСЛА ИЗ ЗАМЕРА 2026-11-12: 2 свободные клетки (%b[22], %b[23]) из 15, занято 13, пик 15.
      // Это не «пример», а граница: при сдвиге бюджета или раскладки проверка обязана покраснеть —
      // тогда её числа ПЕРЕМЕРЯЮТ, а не подгоняют.
      expect(отказ.причина, 'свободные клетки').toContain('свободно 2 (%b[22], %b[23]) из 15');
      expect(отказ.причина, 'занятые клетки').toContain('занято значений 13, пик отрезков 15');
      // СЛОВО, КОТОРОГО НЕ ХВАТАЛО: причина говорит, что стена размерная. Без него отказ читается как
      // «базу потеряли» — и уводит диагноз в алгоритм раскладки (три круга 2026-11-11).
      expect(отказ.причина, 'слой стены').toContain('РАЗМЕРНАЯ стена, а не потеря базы');
      // База не выдана — причина обязана быть, а не пустая строка: иначе отказ снова безымянный.
      expect(отказ.причина).not.toMatch(/Причина: *$/u);
    }
  });

  it('П3 отказ — по ВСЕМ записям: причина есть у всех, и она одна по СМЫСЛУ (ловушка report[0])', () => {
    const список = отказы(проба(6));
    // Причины различаются ПРЕФИКСОМ ИСХОДНИКА (`состояние[0]` против `лента[idx]`) — это часть
    // контракта отказа, а не разные диагнозы. Поэтому сверяется ХВОСТ: он обязан быть у каждого.
    expect(список.length, 'отказов').toBe(2);
    for (const отказ of список) {
      expect(отказ.причина, 'причина названа').toContain('Причина: блок рантайма массивов (3 клетки)');
      expect(отказ.причина, 'числа в каждой причине').toContain('свободно 2 (%b[22], %b[23]) из 15');
    }
  });
});
