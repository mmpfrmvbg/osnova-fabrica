/**
 * ОРАКУЛ АТОМА «МАСКИРОВКА ОТКАЗА» (2026-11-07, docs/hardware-debt.md §3.181).
 *
 * ЧТО БЫЛО. Программа, которой не хватило регистров, падала ИСКЛЮЧЕНИЕМ КОДИРОВЩИКА —
 * `«movts»: базовых регистров 32 … %b[32]` — вместо названного отказа раскладки. Причина: при отказе
 * конвейер честно собирает образ по ДИАГНОСТИЧЕСКОМУ потоку (чтобы не потерять перепись отказов), но
 * кодировал его, а в этом потоке регистры — ВИРТУАЛЬНЫЕ номера.
 *
 * ЧТО ДОЛЖНО БЫТЬ. Кодировщик не видит неразложенный поток: программа получает отказ раскладки с
 * причиной (`вытеснение не минимально …` / `вытеснять больше нечего …`), байт нет.
 *
 * ЗАМЕР ДЛЯ ЛОВУШКИ. Замена литерала (`131 → 3`) сохраняла `%b[32]`, то есть дело было не в ширине
 * литерала; при балласте 64 всплывало уже другое поле (`регистр 70 не выражается полем оболочки`).
 * Поэтому проверка 1 держит НЕ текст исключения, а ФАКТ: под отказом нет ни одного `%b[`.
 *
 * НЕГАТИВНЫЙ КОНТРОЛЬ (снять условие `options.diagnosticFlow === true` в `imageOfCarriers`): краснеют
 * ровно проверки 1, 2 и 4 (балласт 24, балласт 48, прямой сторож), проверка 3 (собирающаяся программа)
 * остаётся зелёной.
 */
import { describe, expect, it } from 'vitest';

import { parseV3 } from '../compiler-v3/index';
import { imageOfCarriers } from './programImage';
import { loweredProgram } from './lowered';
import type { AsmInstruction, Operand } from './equivalences';

/**
 * БАЛЛАСТ — операторы, которые НИЧЕГО не меняют по смыслу, но доводят живость отрезков до отказа
 * раскладки. Порог замерен: 8 — собирается, 16 — отказ «вытеснять больше нечего», 24 и 48 — ровно тот
 * путь, где прежде падал кодировщик (`.tmp/07-02-scale.ts`).
 */
function программаСБалластом(балласт: number): string {
  const вЛитерале = (т: string): string =>
    т.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
  const текст = 'абв 42 гд 77 еёжз 99';
  const строки = [
    'действие главная()',
    `  пусть текст = "${вЛитерале(текст)}"`,
    '  пусть поз = 0',
    '  пусть предел = длина текст',
    '  пусть н = 0',
    '  пока поз < предел',
    '    пусть код = текст[поз]',
    '    если код >= 48',
    '      если код <= 57',
    '        н = н + 1',
    '      конец если',
    '    конец если',
    '    поз = поз + 1',
    '  конец пока',
  ];
  for (let i = 0; i < балласт; i++) строки.push(`  пусть б${String(i)} = ${String(i)}`);
  for (let i = 0; i < балласт; i++) строки.push(`  н = н + б${String(i)}`);
  строки.push('  вывести н', 'конец');
  return строки.join('\n');
}

function сборка(источник: string): ReturnType<typeof loweredProgram> {
  const разбор = parseV3(источник, 'балласт.osnova');
  expect(разбор.errors, 'разбор программы').toEqual([]);
  return loweredProgram(источник, {
    filename: 'балласт.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  } as never);
}

/** Отказ раскладки обязан называть ПРОЦЕДУРУ и причину, а не номер регистра. */
function проверитьОтказРаскладки(балласт: number): void {
  const итог = сборка(программаСБалластом(балласт));
  expect(итог.ок, `балласт ${String(балласт)}: регистров не хватает, сборка обязана ОТКАЗАТЬ`).toBe(false);
  if (итог.ок) return;
  const причины = итог.отказ.отказы.map((запись) => запись.причина);
  const раскладка = причины.filter((причина) => причина.includes('раскладка отказала'));
  expect(раскладка.length, `балласт ${String(балласт)}: причина отказа — РАСКЛАДКА, а не что-то ещё`).toBeGreaterThan(0);
  expect(раскладка[0], 'причина обязана называть процедуру').toContain('процедура «главная»');
  // ГЛАВНОЕ: ни одна причина не смеет быть маской кодировщика.
  //
  // ЛОВУШКА ПРОВЕРКИ (поймана на первом прогоне): причина раскладки ЗАКОННО перечисляет свободные
  // регистры — `свободных регистров 10 (%b[0], … %b[9])`. Поэтому ловится не «`%b[` вообще», а номер
  // ВНЕ базового файла (32 и выше: такого регистра у цели нет) и собственные слова кодировщика.
  const маски = причины.filter((причина) => {
    const вФайле = /%b\[(\d+)\]/gu;
    for (let m = вФайле.exec(причина); m !== null; m = вФайле.exec(причина)) {
      if (Number(m[1]) >= 32) return true;
    }
    return /базовых регистров|не выражается полем/iu.test(причина);
  });
  expect(маски, `балласт ${String(балласт)}: отказ НЕ маскируется полем регистра`).toEqual([]);
}

describe('отказ раскладки называется, а не маскируется кодировщиком', () => {
  it('1. балласт 24: названный отказ раскладки, байт нет, `%b[` нет', () => {
    проверитьОтказРаскладки(24);
  });

  it('2. балласт 48: то же (прежде здесь всплывало ДРУГОЕ поле — не литерал)', () => {
    проверитьОтказРаскладки(48);
  });

  it('3. контроль обратной стороны: балласт 8 собирается и отдаёт байты', () => {
    const итог = сборка(программаСБалластом(8));
    expect(итог.ок, 'в этом составе регистров хватает — отказ был бы ложным').toBe(true);
    if (!итог.ок) return;
    expect(итог.значение.bytes.length, 'у собранной программы байты обязаны быть').toBeGreaterThan(0);
  });

  it('4. прямой сторож: `diagnosticFlow` НЕ кодирует неразложенный поток, обычный путь — кодирует', () => {
    // Носитель, у которого регистр — ВИРТУАЛЬНЫЙ номер вне базового файла (32). Ровно этот случай и
    // давал `%b[32]`: раскладка такой номер не выдаёт никогда, а диагностический поток сохраняет.
    const carrier = (mnemonic: string, operands: readonly Operand[]): AsmInstruction => ({
      mnemonic,
      channel: 0,
      operands,
    });
    const носители = [carrier('IR.move', [{ kind: 'reg', index: 32 }, { kind: 'reg', index: 0 }])];

    // ОБЫЧНЫЙ путь: кодировщик обязан возмутиться — иначе сторож ничего не держит.
    expect(() => imageOfCarriers(носители, [], []), 'без отказа раскладки `%b[32]` обязан падать').toThrow();

    // ПУТЬ ОТКАЗА: не кодируется вовсе, байт нет, исключения нет.
    const подОтказом = imageOfCarriers(носители, [], [], { diagnosticFlow: true });
    expect(подОтказом.bytes.length, 'под отказом байт быть не должно').toBe(0);
  });
});
