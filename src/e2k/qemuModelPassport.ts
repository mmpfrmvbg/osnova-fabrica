/** Что удалось прочитать у живой сборки. */
export interface ModelIdentity {
  version: string;
  sha256: string;
}

/**
 * Причины, по которым измерениям на этой сборке нельзя верить как прежним.
 * Пустой список — модель та же.
 */
export function modelIdentityProblems(actual: ModelIdentity): string[] {
  const problems: string[] = [];
  if (actual.version.trim() !== QEMU_MODEL.version) {
    problems.push(
      `версия модели «${actual.version.trim()}» вместо «${QEMU_MODEL.version}»: ` +
        'закреплённые числа машинной плоскости требуют перемера, а паспорт — обновления',
    );
  }
  if (actual.sha256.trim().toLowerCase() !== QEMU_MODEL.sha256) {
    problems.push(
      `sha256 модели «${actual.sha256.trim()}» вместо «${QEMU_MODEL.sha256}»: ` +
        'модель пересобрана — закреплённые числа (window, коды выхода, байты, такты) ' +
        'требуют перемера, а паспорт — обновления',
    );
  }
  return problems;
}
