/**
 * КОД СИМВОЛА СТРОКИ НА ЦЕЛИ (`с[и]` по строке) — ОРАКУЛ §3.133.
 *
 * # Что здесь спрашивается
 *
 * Решение владельца 2026-10-10: `с[и]` по строке — это ЧИСЛО (код Unicode), а не строка. Прежняя
 * редакция (`stringIndex.test.ts`, 2026-10-04) требовала строку и была отменена ЗАМЕРОМ: строковая
 * модель цели требует известной на СБОРКЕ длины, а символ по рантаймовому индексу — 1–4 байта,
 * известных только в рантайме (§3.132).
 *
 * Здесь спрашивается ЦЕЛЬ: понижается ли операция, считает ли она код, и что бывает за границей.
 *
 * # Наблюдение
 *
 * Код возврата — 8-битный канал (`AGENTS.md`), поэтому программы возвращают МАЛЕНЬКОЕ число-ответ,
 * а не сам код: «если код верен — 33, иначе 7». Так проверка различает не «число вообще», а именно
 * то число, которое обязано прийти.
 *
 * # Три ответа, а не два
 *
 * | случай | ответ цели |
 * |---|---|
 * | индекс в границах | код символа |
 * | индекс за границей, известен на СБОРКЕ | отказ по имени ДО сборки образа |
 * | индекс за границей, известен только в рантайме | **−1** (исключений у цели нет; у VM — названный отказ) |
 * | код символа вне двух байт (эмодзи) | отказ по имени: таблица кодов двухбайтовая |
 *
 * Последние две строки — НАЗВАННЫЕ границы, а не «почти работает»: у VM на выход за границу отказ,
 * у цели −1, и это расхождение записано (§3.133), а не замолчано.
 */
import { describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
