/**
 * КУСОК 4 СРЕЗА 7: КОММЕНТАРИИ В ЛЕКСЕРЕ НА ЦЕЛИ — различающая проба и сторож.
 *
 * # Предмет
 *
 * Срез 7 сдаёт лексер НА ОСНОВЕ, собранный на цель, кусками: идентификаторы (11/11, §3.180),
 * числа/знаки/ключевые (4/10/9, §3.182), строки (4/26/3/3219, §3.183). Кусок 4 — КОММЕНТАРИИ:
 * лексер обязан отбросить оба вида (`//` до конца строки и блочный до закрытия), не сделав их
 * содержимое токенами и не съев код.
 *
 * # Эталон — и расхождение, названное вслух (D19/D21)
 *
 * Синтаксис зафиксирован по эталону, а не по догадке: `tokenizeV3` (`src/compiler-v3/lexer.ts`),
 * исполняемая спецификация (`src/spec/osnova-spec.ts#tokenize`) и лексер v2
 * (`src/compiler/lexer.ts`) согласны — проверено разведкой `.tmp/lexer4-recon.ts` на 11 различающих
 * случаях (оба вида, кавычки и числа внутри, открывающий блочный внутри строки, пустой и «звёздный»
 * блочный, незакрытый блочный). V2 self-host `src/self-host/stage12.osnova` комментариев НЕ знает
 * вовсе (`/` — обычный токен) — это ОСОЗНАННОЕ расхождение: текущий v3 следует канону
 * `docs/language-v2.md` (раздел определений лексера), а не stage12; запись — `docs/decisions.md`.
 *
 * # Почему программа, а не правка `src/compiler-v3/**`
 *
 * В `src/compiler-v3/lexer.ts` распознавание комментариев УЖЕ есть с первого коммита фронтенда
 * (`a46d8f4d`), а его правило закреплено `src/compiler-v3/lexer.test.ts`. Куску 4 здесь подлежит
 * ВТОРАЯ половина: доказать, что правила выражаются и на ЦЕЛИ, и что проба РАЗЛИЧАЕТ «собирается»
 * от «считает верно». До правки (режим `только_строчные` — как у программы куска 3) блочный
 * комментарий не распознан: `/` и `*` считаются знаками, числа и строки ВНУТРИ комментария —
 * кодом, а кавычка внутри блочного открывает строку и съедает код до конца строки. Отказов при
 * этом НОЛЬ — это класс D4 (тихая ложь), а не отказ.
 *
 * # Что именно различается (измерено, а не выведено)
 *
 * | текст | до (только строчные) | после (оба вида) | эталон `tokenizeV3` |
 * |---|---|---|---|
 * | Т1 строчный | 1/1/2 (совпал) | 1/1/2 | 1/1/2 |
 * | Т2 блочный | 4/2/8 | 2/0/2 | 2/0/2 |
 *
 * Проба краснеет ДО правки именно на Т2 (4/2/8 против 2/0/2), и это закреплено проверкой
 * «ДО правки числа ОБЯЗАНЫ расходиться»: без неё сторож был бы зелёным при любой реализации.
 *
 * # N сторожа (самопокраснение)
 *
 * Откат блочной ветви (`если к3 == 42 …`) красит РОВНО 2 проверки: «стековая VM, Т2 = эталон» и
 * «цель, Т2 = эталон». В полном прогоне вторая пропущена по шлюзу, поэтому там красный ОДИН, а в
 * `gate:qemu` — два; строчные проверки и обе пробы «до правки» зелены в обоих случаях. Проверено
 * прогоном (sha256 файла до/после откатa сверен) и записано в `docs/verification-debt.md`.
 *
 * # Границы
 *
 * Модель — не железо (D12): на E8C2 проба не ходила, кит для владельца лежит в `.tmp/lexer4-hw/`
 * (`sha256.txt`, `run.sh`, LF), вынос — отдельное решение. Модельные проверки идут только в шлюзе
 * `gate:qemu` (случай 12): полный прогон обязан быть детерминированным, а отсутствие модели в шлюзе —
 * КРАСНЫМ, а не молча пропущенной проверкой. Кодпоинты, а не UTF-8 байты: текст пробы содержит
 * кириллицу и эмодзи, `текст[поз]` — кодовая точка (D1/§13.6).
 *
 * # Где лежит сама программа
 *
 * `src/e2k/lexerCommentsProgram.ts` — ОДИН источник: его прогоняют и этот сторож, и кит для машины.
 * Две копии builder'а разошлись бы молча, и на железо уехал бы не тот байт, который доказан.
 */
import { beforeAll, describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { validateNamedTypesAndRewrite } from '../compiler/compiler';
import { compile } from '../compiler/codegen';
import { createDefaultInvokeHandler, VM } from '../runtime/vm/interpreter';
import { loweredProgram } from './lowered';
import { MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY, buildElfFromCode } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { Т1, Т2, какСтроки, имяТекста, программа, эталон, type Режим } from './lexerCommentsProgram';

const ROOT = path.resolve(__dirname, '..', '..');

/** Модель спрашивается ТОЛЬКО шлюзом: признак задан явно, а не выведен из «есть ли шим» (случай 12). */
const В_ШЛЮЗЕ_QEMU = process.env.OSNOVA_GATE_QEMU === '1';

/**
 * Стековая VM — эталон поведения программы без модели; вывод снимается тем же каналом, что печать.
 * Так «проба красна до правки» проверяется в ПОЛНОМ прогоне, а не только в шлюзе.
 */
async function наСтековой(текст: string, режим: Режим): Promise<string[]> {
  const исходник = программа(текст, режим);
  const разбор = parseV3(исходник, `кусок4-${режим}.osnova`);
  expect(разбор.errors, `v3 не разобрал программу (${режим}): ${разбор.errors.join('; ')}`).toEqual([]);
  const модуль = разбор.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(модуль), 'проход разрешения имён').toEqual([]);
  const байткод = compile(модуль);
  const вывод: unknown[] = [];
  const обычный = createDefaultInvokeHandler();
  const vm = new VM(байткод, {
    maxSteps: 5_000_000,
    invoke: async (имя, аргументы) => {
      if (имя === 'система.лог.вывести') {
        вывод.push(аргументы[0]);
        return null;
      }
      return обычный(имя, аргументы);
    },
  });
  await vm.runProcedure(vm.findProcedureIndex('главная'), []);
  return вывод.map((значение) => String(значение));
}

/**
 * Образ цели: фронтенд v3 подставлен в общую дверь понижения (`options.parse`), а не переписан
 * второй путь. Дверь отвечает «либо образ, либо отказ» — третьего нет, поэтому отказ здесь БРОСОК
 * с причиной, а не молчаливые пустые байты.
 */
function образЦели(текст: string, режим: Режим): Uint8Array {
  const исходник = программа(текст, режим);
  const имя = `кусок4-${режим}.osnova`;
  const разбор = parseV3(исходник, имя);
  expect(разбор.errors, `v3 не разобрал программу (${режим}): ${разбор.errors.join('; ')}`).toEqual([]);
  const итог = loweredProgram(исходник, {
    filename: имя,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  if (!итог.ок) {
    throw new Error(`на цель программа обязана собираться без отказов (${режим}): ${итог.отказ.причина}`);
  }
  return итог.значение.bytes;
}

/** Цель: сборка полным понижением и прогон в модели; вывод — байты stdout, как у печати. */
function наЦели(текст: string, режим: Режим): string[] {
  const elf = path.join(ROOT, '.tmp', `lexer4-комментарии-${режим}-${имяТекста(текст)}.elf`);
  fs.writeFileSync(
    elf,
    buildElfFromCode(образЦели(текст, режим), MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
  );
  const прогон = runInQemu(elf, { shim: true, timeoutMs: 60_000 });
  expect(прогон, 'модель не ответила — причина обязана быть красной, а не пропущенной').toBeTruthy();
  expect(прогон!.status, 'печатающая программа завершается своим exit(0)').toBe(0);
  return прогон!.stdout.split('\n').filter((строка) => строка !== '');
}

beforeAll(() => {
  // Шим нужен только шлюзу: полный прогон не ходит в WSL за QEMU (случай 12).
  if (В_ШЛЮЗЕ_QEMU) buildShim();
});

describe('эталон куска 4: токены считает `tokenizeV3`, а не «на глаз»', () => {
  it('Т1: строчный комментарий отброшен — число и строка внутри него не токены', () => {
    expect(какСтроки(эталон(Т1)), 'число 1, строка «абв // не строка», два «=»').toEqual(['1', '1', '2']);
  });

  it('Т2: блочный комментарий отброшен — числа/строка/эмодзи внутри не токены', () => {
    expect(какСтроки(эталон(Т2)), 'числа 4 и 5, строк нет, два «=»').toEqual(['2', '0', '2']);
  });
});

describe('проба РАЗЛИЧАЕТ: без распознавания комментариев числа другие (D4, не отказ)', () => {
  it('Т1: без комментариев вовсе — 3/2/4 против эталона 1/1/2', async () => {
    // `//` стал двумя знаками, а 999, «не число» и 777 — токенами. Программа при этом СОБИРАЕТСЯ и
    // печатает — ровно класс D4: отказов ноль, число неверное.
    expect(await наСтековой(Т1, 'нет')).toEqual(['3', '2', '4']);
    expect(await наСтековой(Т1, 'нет')).not.toEqual(какСтроки(эталон(Т1)));
  });

  it('Т2: только строчные комментарии — 4/2/8 против эталона 2/0/2 (блочный не распознан)', async () => {
    // Это состояние лексера ДО куска 4 (программа куска 3 знает только `//`). Различающая деталь:
    // `/` и `*` стали знаками, 111/222/333 — числами, а кавычка в `/* " */` открыла строку и съела
    // `пусть г = 5`. Здесь проба КРАСНАЯ по построению — и остаётся такой, пока правки нет.
    expect(await наСтековой(Т2, 'только_строчные')).toEqual(['4', '2', '8']);
    expect(await наСтековой(Т2, 'только_строчные')).not.toEqual(какСтроки(эталон(Т2)));
  });
});

describe('после правки: программа куска 4 сходится с эталоном и на стековой VM, и на цели', () => {
  it('стековая VM: Т1 (строчный) = эталон', async () => {
    expect(await наСтековой(Т1, 'оба')).toEqual(какСтроки(эталон(Т1)));
  });

  it('стековая VM: Т2 (блочный) = эталон — правка различима здесь', async () => {
    expect(await наСтековой(Т2, 'оба')).toEqual(какСтроки(эталон(Т2)));
  });

  it('цель, сборка: обе программы (Т1/Т2, режим «оба») раскладываются без отказов', () => {
    for (const текст of [Т1, Т2]) {
      const байты = образЦели(текст, 'оба');
      expect(байты.length, `пустой образ на ${имяТекста(текст)}`).toBeGreaterThan(0);
    }
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('модель доступна — иначе причина названа', () => {
    expect(buildShim(), 'шим/модель qemu-e2k недоступны: прогон числа невозможен').toBeTruthy();
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('цель: Т1 (строчный) печатает эталон побайтово', () => {
    expect(наЦели(Т1, 'оба')).toEqual(какСтроки(эталон(Т1)));
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('цель: Т2 (блочный) печатает эталон побайтово — правка различима здесь', () => {
    expect(наЦели(Т2, 'оба')).toEqual(какСтроки(эталон(Т2)));
  });

  it.skipIf(!В_ШЛЮЗЕ_QEMU)('цель: ДО правки те же 4/2/8 — модель повторяет стековую VM, а не «чинит»', () => {
    // Обратная сторона: различие не в модели. На цели вариант БЕЗ блочной ветви обязан напечатать
    // ровно те же неверные числа, что и стековая VM, — иначе проба мерила бы порт, а не программу.
    expect(наЦели(Т2, 'только_строчные')).toEqual(['4', '2', '8']);
    expect(наЦели(Т2, 'только_строчные')).not.toEqual(какСтроки(эталон(Т2)));
  });
});
