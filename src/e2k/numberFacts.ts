/**
 * ЧИСЛОВЫЕ ФАКТЫ: что означает арифметический носитель, когда ОБА его слагаемых уже известны.
 *
 * ═══ ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ ════════════════════════════════════════════════════════════════════════════
 *
 * Две независимые проверки спрашивают одно и то же — «какое ЧИСЛО лежит в регистре»: рантайм массивов
 * (`src/e2k/arrayRuntime.ts`, константный индекс элемента) и план строк (`src/e2k/stringPlan.ts`,
 * константный индекс символа И КРАЯ СРЕЗА). Пока арифметика была свёрнута только в первой, вторая
 * отказывала на ЗАКОННОМ случае языка: `подстрока("абвгде", -2, 6)` — отрицательный край, то есть
 * отсчёт ОТ КОНЦА по эталону `codePointSlice`. Замер `.tmp/td62-край-минус.ts` показал, почему: у
 * `-2` в потоке стоит не литерал, а `IR.sub` над ДВУМЯ КОНСТАНТНЫМИ регистрами (`0 − 2`), поэтому
 * доказанным краем он не виден, если арифметику не свёртывать.
 *
 * Общая функция не даёт двум свёрткам разойтись: правило «что значит `IR.add`/`IR.sub`/`IR.mul`» живёт
 * в ОДНОМ месте, и добавление новой операции (или изменение порядка операндов) не может случиться
 * «в одном из двух мест». Порядок операндов замерен, а не предположен: `IR.sub reg[3] reg[4] reg[5]`
 * при `reg[4] = 0`, `reg[5] = 2` даёт `-2` (тот же замер).
 *
 * ═══ ГРАНИЦА (названа, а не спрятана) ═════════════════════════════════════════════════════════════════
 *
 * У цели арифметика 64-битная, а здесь — числа JavaScript, поэтому переполнение разрядной сетки НЕ
 * моделируется. Обе проверки берут свёртку там, где числа пришли константами самого исходника (индексы
 * и края среза), то есть на величинах, где переполнение не наступает; предположение записано слепым
 * пятном реестра (запись `BS-0006`), а не оставлено в уме.
 *
 * ВЫЗЫВАЮЩИЙ ОБЯЗАН САМ ПРОВЕРИТЬ КОНСТАНТНОСТЬ: функция — чистая арифметика и о значениях регистров не
 * знает ничего (иначе «минус чего-то неизвестного» молча стало бы числом — класс «тихая ложь»).
 */
export type NumericCarrier = 'IR.add' | 'IR.sub' | 'IR.mul';

/** Носитель ли это арифметики над числами: одна точка правды для обоих потребителей. */
export function isNumericCarrier(mnemonic: string): mnemonic is NumericCarrier {
  return mnemonic === 'IR.add' || mnemonic === 'IR.sub' || mnemonic === 'IR.mul';
}

/** Значение арифметики: `слагаемое1 <оп> слагаемое2`, как у цели (порядок операндов замерен). */
export function foldNumericCarrier(mnemonic: NumericCarrier, left: number, right: number): number {
  if (mnemonic === 'IR.add') return left + right;
  if (mnemonic === 'IR.sub') return left - right;
  return left * right;
}
