import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3';
import { loweredProgram } from './lowered';

/**
 * B2 через рекурсию: РАЗБОР рекурсивен и понижается, а ЗАПИСЬ из рекурсивной
 * процедуры — названный отказ `#16` (глубина 2). Это не liveness 16/9: отказ
 * стоит на `Списки.установить` до раскладки, поэтому «рекурсией вместо стека»
 * B2 не собирается. Тест закрепляет границу, чтобы её не приняли за успех.
 */
const ИСТОЧНИК = `процедура записать(лента: Список Число, инд: Число) -> Число
  Списки.установить(лента, инд, 1)
  вернуть инд + 1
конец записать

процедура рекурс(лента: Список Число, инд: Число, п: Число) -> Число
  если п > 0
    инд = рекурс(лента, инд, п - 1)
  конец если
  вернуть записать(лента, инд)
конец рекурс

действие главная()
  пусть лента: Список Число = []
  пусть пт = 0
  пока пт < 20
    Списки.добавить(лента, 0, 0)
    пт = пт + 1
  конец пока
  пусть инд = 0
  инд = рекурс(лента, инд, 2)
конец главная
`;

describe('B2 через рекурсию: запись из рекурсивной процедуры', () => {
  it('понижение отказывает #16 на глубине 2, а не молча собирает', () => {
    const файл = 'b2-rec-writer.osnova';
    const parsed = parseV3(ИСТОЧНИК, файл);
    expect(parsed.errors).toEqual([]);
    const res = loweredProgram(ИСТОЧНИК, {
      filename: файл,
      parse: () => ({ ast: parsed.program ?? null, errors: parsed.errors }),
    });
    expect(res.ок).toBe(false);
    if (res.ок) return;
    expect(res.отказ.причина).toContain('#16');
    const запись = res.отказ.отказы.find((о) => о.процедура === 'записать');
    expect(запись).toBeDefined();
    expect(запись!.причина).toContain('выращенным кадром (глубина 2)');
  });
});
