/**
 * ОРАКУЛ ГРАНИЦ ОКНА РЕГИСТРОВ e2k: `rsz` — предел клеток, `wsz` — размер окна.
 *
 * # Зачем этот файл (задача 3 среза 5з, атом ATOM-05-03-01)
 *
 * Бюджет вызываемой в дереве — `CALLEE_REGISTERS` = `%b[8..15]`, восемь клеток. Стена вытеснения
 * K2 («13 живых отрезков против 8 свободных», `src/e2k/spillCallee.test.ts`) стоит на этом числе.
 * До сих пор **нигде не было измерено**, что восемь — это наш выбор, а не предел железа: в доках
 * `wsz` и `rsz` фигурировали как «размер окна» без разделения ролей.
 *
 * # Что измерено (модель, обе стороны каждой границы)
 *
 * Предел доступных клеток `%b[N]` задаёт **`rsz`**, а не `wsz`: законны ровно `N < 2·(rsz + 1)`.
 * Доказано различающими строками, а не совпадением — при `wsz = 12`:
 *
 * | `rsz` | предел `2·(rsz+1)` | предел `2·wsz` | последняя законная | первая незаконная |
 * |---|---|---|---|---|
 * | 7  | **16** | 24 | `%b[15]` | `%b[16]` |
 * | 8  | **18** | 24 | `%b[17]` | `%b[18]` |
 * | 11 | **24** | 24 | `%b[23]` | `%b[24]` |
 *
 * Строки `rsz = 7` и `rsz = 8` различают формулы прямо: `2·wsz` предсказывает 24 в обоих случаях,
 * а модель пускает клетку 16 при `rsz = 8` и валит её при `rsz = 7`. Значит формула `2·wsz` — ЛОЖНА.
 *
 * Годность ПАРЫ: `rsz + 1 ≤ wsz`. `rsz = 3` негоден всегда (`setbn` валит), `wsz = 113` валит сам
 * `setwd`, `wsz = 112` проходит — сходится с `MAXSR_Q = 112`.
 *
 * # Что это значит для K2
 *
 * Восемь клеток вызываемой — не предел, а следствие нашего `rsz = 7`. При `rsz = 11` у вызываемой
 * законны `%b[0..23]`, то есть своих клеток 16, а не 8. **Стена K2 — политическая: константа
 * `CALLEE_REGISTERS` плюс число `rsz` в прологе, а не геометрия.** Это НЕ снимает стену: расширение
 * бюджета клеток без расширения `rsz` даёт незаконные клетки, а с расширением `rsz` — трогает пролог
 * образа и все закреплённые числа. Решение — за владельцем (срез 5з.2).
 *
 * # Границы файла
 *
 * Модель — не железо. Вопрос «поведёт ли себя так же Эльбрус» — зарегистрированный вопрос кита
 * (`docs/e2k-hardware-access.md`), не этот оракул. И `rsz` здесь правится В БАЙТАХ готового образа:
 * это замер геометрии, а не проверка того, что конвейер ставит правильный `rsz`.
 *
 * Файл зависит от внешнего ресурса (`qemu-e2k` под шимом) и живёт в шлюзе `npm run gate:qemu`
 * (`docs/verification-debt.md`, случай 12): без модели он обязан КРАСНЕТЬ, а не пропускать проверку.
 */

import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { runInQemu, buildShim } from '../scripts/e2kQemuExec';
import { ARRAY_WINDOW_RSZ, ARRAY_WINDOW_WSZ } from './arrayRuntime';
import { CALL_WBS, CALLEE_REGISTERS } from './twoPassLayout';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'проба.osnova';
const shim = buildShim();

/**
 * Голая программа: пролог образа плюс возврат.
 *
 * Почему именно она. Пролог образа — единственное место, которое ставит `setwd`/`setbn` и трогает
 * `%b[12..15]`, поэтому ответ модели здесь зависит ТОЛЬКО от геометрии окна: нет ни строк, ни
 * массивов, ни вытеснения, которые примешали бы своё.
 */
const ИСТОЧНИК = ['действие главная()', '  вернуть 7', 'конец', ''].join('\n');

/** Смещения полей в потоке (снято `src/e2k/backend.ts#getEncoder('e2k')`, см. `.tmp/a503-enc.ts`). */
const СМЕЩЕНИЕ_WSZ = 12; // `setwd`: `wsz` — 9 бит со сдвигом 5, младший байт здесь
const СМЕЩЕНИЕ_RSZ = 20; // `setbn`: `rsz` — 6 бит со сдвигом 6, младший байт здесь
const СМЕЩЕНИЕ_КЛЕТКИ = 28; // `movts 0, %b[12]` — номер клетки в байте 28

const разбор = parseV3(ИСТОЧНИК, ФАЙЛ);
const образ = loweredProgramUnchecked(ИСТОЧНИК, {
  filename: ФАЙЛ,
  parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
});

/** Тот же прогон с правлеными полями пролога; `undefined` — поле не трогать. */
function прогнать(правки: {
  readonly wsz?: number;
  readonly rsz?: number;
  readonly клетка?: number;
}): { readonly код: number | undefined; readonly авария: number | undefined } {
  const код = Uint8Array.from(образ.bytes);
  if (правки.wsz !== undefined) {
    const v = (правки.wsz << 5) & 0x3fff;
    код[СМЕЩЕНИЕ_WSZ] = v & 0xff;
    код[СМЕЩЕНИЕ_WSZ + 1] = (v >> 8) & 0xff;
  }
  if (правки.rsz !== undefined) {
    const v = (правки.rsz << 6) & 0xffff;
    код[СМЕЩЕНИЕ_RSZ] = v & 0xff;
    код[СМЕЩЕНИЕ_RSZ + 1] = (v >> 8) & 0xff;
  }
  if (правки.клетка !== undefined) код[СМЕЩЕНИЕ_КЛЕТКИ] = правки.клетка & 0xff;
  const эльф = buildElfFromCode(код, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
  const имя = `windowLimits-${String(правки.wsz ?? 'x')}-${String(правки.rsz ?? 'x')}-${String(правки.клетка ?? 'x')}.elf`;
  const файл = path.join(ROOT, '.tmp', имя);
  fs.writeFileSync(файл, эльф.bytes);
  const итог = runInQemu(файл, { shim: true, timeoutMs: 20_000 });
  return { код: итог?.status, авария: итог?.exceptionIp };
}

describe('границы окна регистров: что задаёт предел клеток', () => {
  it('П0 модель доступна: без неё файл обязан краснеть, а не пропускать проверку', () => {
    expect(shim, 'шим не собрался — модель недоступна, замер невозможен').toBeDefined();
  });

  it('П1 ПРЕДЕЛ КЛЕТОК ЗАДАЁТ `rsz`, А НЕ `wsz` — различающие строки при wsz = 12', () => {
    // Каждая строка — пара (rsz, клетка), где формулы 2·wsz и 2·(rsz+1) предсказывают РАЗНОЕ.
    // Все строки посчитаны на ЖИВОЙ модели; числа — из замера `.tmp/a503-window-formula2.ts`.
    const СТРОКИ: readonly { rsz: number; клетка: number; ожидание: string }[] = [
      // 2·wsz = 24 предсказывает «пустит», 2·(rsz+1) = 16 предсказывает «упадёт».
      { rsz: 7, клетка: 16, ожидание: 'авария' },
      { rsz: 7, клетка: 17, ожидание: 'авария' },
      // 2·wsz = 24 предсказывает «пустит», 2·(rsz+1) = 18 предсказывает «упадёт» для 18 и «пустит» для 16.
      { rsz: 8, клетка: 16, ожидание: 'ок' },
      { rsz: 8, клетка: 17, ожидание: 'ок' },
      { rsz: 8, клетка: 18, ожидание: 'авария' },
      // Обе формулы согласны: 2·(11+1) = 24 = 2·12.
      { rsz: 11, клетка: 23, ожидание: 'ок' },
      { rsz: 11, клетка: 24, ожидание: 'авария' },
    ];
    for (const строка of СТРОКИ) {
      const итог = прогнать({ wsz: 12, rsz: строка.rsz, клетка: строка.клетка });
      const подпись =
        `rsz=${String(строка.rsz)}, %b[${String(строка.клетка)}]: ` +
        `предел rsz = ${String(2 * (строка.rsz + 1))}, предел wsz = ${String(2 * 12)}`;
      if (строка.ожидание === 'ок') {
        expect(итог.авария, `${подпись} — клетка ОБЯЗАНА быть законной`).toBeUndefined();
        expect(итог.код, `${подпись} — эталон 7`).toBe(7);
      } else {
        expect(итог.авария, `${подпись} — клетка ОБЯЗАНА быть незаконной`).toBeDefined();
      }
    }
  });

  it('П2 ГОДНОСТЬ ПАРЫ: `rsz + 1 ≤ wsz`; `wsz` до 112, с 113 валит сам `setwd`', () => {
    // Нижняя сторона: пара негодна, если окно меньше области вращения.
    const негодные: readonly (readonly [number, number])[] = [
      [8, 3],
      [12, 15],
      [8, 8],
    ];
    for (const [wsz, rsz] of негодные) {
      const итог = прогнать({ wsz, rsz });
      expect(итог.авария, `wsz=${String(wsz)}, rsz=${String(rsz)}: пара обязана быть НЕГОДНОЙ`).toBeDefined();
    }
    // Верхняя сторона — сверено с `MAXSR_Q = 112`: 112 проходит, 113 валит на самом `setwd`.
    expect(прогнать({ wsz: 112, rsz: 7 }).авария, 'wsz=112 обязан проходить').toBeUndefined();
    expect(прогнать({ wsz: 113, rsz: 7 }).авария, 'wsz=113 обязан валить').toBeDefined();
    expect(прогнать({ wsz: 255, rsz: 7 }).авария, 'wsz=255 обязан валить').toBeDefined();
  });

  it('П3 БЮДЖЕТ ВЫЗЫВАЕМОЙ — НАШ ВЫБОР, А НЕ ПРЕДЕЛ: при rsz = 11 своих клеток 16, не 8', () => {
    // Главное утверждение файла, и оно о ПОЛИТИКЕ, а не о геометрии. Восемь клеток вызываемой —
    // это `2·(ARRAY_WINDOW_RSZ + 1) − 2·CALL_WBS` = `2·8 − 8` = 8, то есть прямое следствие `rsz`,
    // который ставит наш пролог. При `rsz = 11` законных клеток вдвое больше.
    expect(CALLEE_REGISTERS.length, 'бюджет вызываемой в дереве').toBe(8);
    expect(CALLEE_REGISTERS[0], 'первая клетка бюджета').toBe(2 * CALL_WBS);
    expect(CALLEE_REGISTERS.at(-1), 'последняя клетка бюджета').toBe(2 * CALL_WBS + 7);
    // Предел клеток при нашем прологе — это ровно `2·(rsz+1)` = 16, и он приходится как раз на конец
    // бюджета: последняя законная клетка — `%b[15]`, первая незаконная — `%b[16]`. Отсюда и стена:
    // «шире бюджета» и «за пределом окна» — ОДНО И ТО ЖЕ число, пока `rsz` равен семи.
    expect(2 * (ARRAY_WINDOW_RSZ + 1), 'предел клеток при нашем rsz').toBe(16);
    expect(2 * CALL_WBS + CALLEE_REGISTERS.length, 'конец бюджета вызываемой').toBe(16);
    // А `wsz` наш пролог ставит 12, то есть 24 регистра — вдвое больше, чем `rsz` делает доступным.
    // Значит `wsz` в нашей форме НЕ ограничивает клетки: он держит область вращения и годность пары.
    expect(2 * ARRAY_WINDOW_WSZ, 'что обещал бы wsz').toBe(24);
    expect(2 * ARRAY_WINDOW_WSZ > 2 * (ARRAY_WINDOW_RSZ + 1), 'wsz не задаёт предел клеток').toBe(true);
  });
});
