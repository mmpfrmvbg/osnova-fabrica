/**
 * КАРТА ИСТОЧНИКА, ЧАСТЬ 3: ОТКАЗ НАЗЫВАЕТ ТО, ЧТО ЧЕЛОВЕК НАПИСАЛ (2026-11-11).
 *
 * # Что было и что стало
 *
 * Было: `«система.массив.получить»: раскладка не выдала базу блока рантайма (операнд 6 носителя)`.
 * Человек, написавший `лента[индекс]`, не писал ни `система.массив.получить`, ни «операнд 6».
 * Стало: **`лента[индекс], строка 6, колонка 10 — <прежняя причина>`**.
 *
 * # Почему прежняя причина остаётся ЦЕЛИКОМ
 *
 * Она несёт то, чего в исходнике нет: имя операции, номер носителя, число занятых клеток. Поэтому
 * проверяется ДВЕ вещи сразу: (1) источник стоит ПЕРЕД причиной и указывает на `лента[индекс]`;
 * (2) прежняя причина НЕ ПОТЕРЯНА. Замена причины источником была бы потерей диагностики, а не
 * улучшением.
 *
 * # Запасной путь — проверяется отдельно
 *
 * У программы, разобранной так, что карта источника пуста, ТЕКСТ ОТКАЗА ОБЯЗАН ОСТАТЬСЯ ПРЕЖНИМ,
 * байт в байт. Иначе правка молча переписала бы сообщения всему v2-фронтенду и рукописным носителям.
 * Это и есть различающая проба: одна и та же причина — с источником и без него.
 */
import { describe, expect, it } from "vitest";
import { parseV3 } from "../compiler-v3/index";
import { compileToReg } from "../compiler/regcodegen";
import { validateNamedTypesAndRewrite } from "../compiler/compiler";
import { refusalWithSource } from "./loweringRefusal";
import { LOWERING_CODES } from "./loweringRefusal";
import { ArrayRuntimeRefusal, lowerArrayCall } from "./arrayRuntime";
import { loweredProgramUnchecked } from "./guards/loweredUnchecked";
import { описаниеПоСсылке, type IRSourceRef } from "../runtime/vm/sourceMap";

const ФАЙЛ = "отказ-по-источнику.osnova";

/**
 * Программа, которая ОТКАЗЫВАЕТ по литералу: `1.5` литералом e2k невыразимо (`OSN-LOW-002`).
 *
 * Выбрана потому, что отказ ЗДЕСЬ и сейчас воспроизводим, а не «в теории»: причина — в самом
 * литерале, и человек писал именно его.
 */
const С_ЛИТЕРАЛОМ = ["действие главная()", "  пусть х = 1.5", "  вернуть х", "конец главная", ""].join("\n");

/** Программа с настоящей индексацией: из неё берётся ЖИВАЯ ссылка на `лента[индекс]`. */
const С_ИНДЕКСАЦИЕЙ = [
  "процедура взять(лента: Список Число, индекс: Число) -> Число",
  "  вернуть лента[индекс]",
  "конец взять",
  "",
  "действие главная()",
  "  пусть с: Список Число = []",
  "  добавить в с элемент 5",
  "  вернуть взять(с, 0)",
  "конец главная",
  "",
].join("\n");

function опции(источник: string) {
  const р = parseV3(источник, ФАЙЛ);
  expect(р.errors, `разбор: ${р.errors.join("; ")}`).toEqual([]);
  return { filename: ФАЙЛ, parse: () => ({ ast: р.program ?? null, errors: р.errors }) };
}

/** Все причины отказов программы — по ВСЕМ записям, а не по первой (ловушка `report[0]`). */
function причины(источник: string): string[] {
  const образ = loweredProgramUnchecked(источник, опции(источник));
  return образ.отказы.map((запись) => `${запись.код}: ${запись.причина}`);
}

/**
 * ЖИВАЯ ссылка на источник `лента[индекс]` — из настоящего разбора, а не собранная руками.
 *
 * Так проверка не может «подтвердить» ссылку, которую сама же и выдумала: номер узла обязан быть
 * тем, который выдала карта источника при разборе этой программы.
 */
function живаяСсылкаНаИндексацию(): IRSourceRef {
  const р = parseV3(С_ИНДЕКСАЦИЕЙ, ФАЙЛ);
  expect(р.errors).toEqual([]);
  const м = р.program!.modules[0]!;
  expect(validateNamedTypesAndRewrite(м)).toEqual([]);
  const модуль = compileToReg(м);
  const все = модуль.code.flatMap((элемент) =>
    "packet" in элемент && элемент.packet === true ? элемент.slots : [элемент],
  );
  const получение = все.find(
    (и) => и.op === "invoke" && (и as { name?: string }).name === "система.массив.получить",
  ) as (IRSourceRef extends never ? never : { sourceRef?: IRSourceRef }) | undefined;
  const ссылка = получение?.sourceRef;
  expect(ссылка, "у `лента[индекс]` обязана быть ссылка на источник").toBeDefined();
  return ссылка!;
}

describe("карта источника, часть 3: отказ называет исходник", () => {
  it("отказ по литералу начинается с `1.5, строка 2, колонка 13`", () => {
    const все = причины(С_ЛИТЕРАЛОМ);
    const литеральные = все.filter((причина) => причина.includes("OSN-LOW-002"));
    expect(литеральные.length, "программа обязана отказать по 002 — иначе проверять нечего").toBe(1);

    // Формат §3 брифа: СНАЧАЛА то, что человек написал, ЗАТЕМ место, и только потом причина.
    expect(литеральные[0]).toMatch(/^OSN-LOW-002: 1\.5, строка 2, колонка \d+ — /);
    // Причина НЕ ПОТЕРЯНА: она несёт то, чего в исходнике нет (номер пула, тип, размер литерала).
    expect(литеральные[0]).toContain("IR.const");
    expect(литеральные[0]).toContain("литералом e2k кодируются только целые");
    // И колонка — не выдуманная: `1.5` стоит в строке 2, начиная с 13-й кодовой точки.
    expect(литеральные[0]).toContain("строка 2, колонка 13");
  });

  it("отказ `OSN-LOW-003` тоже называет исходник — на ЖИВОЙ ссылке из разбора", () => {
    const ссылка = живаяСсылкаНаИндексацию();
    // `Списки.взять` — это D43a: пара Результат<> в горячем пути не влезает (код 003). Ссылка —
    // настоящая, из карты источника этой же программы.
    let поймано: ArrayRuntimeRefusal | undefined;
    try {
      lowerArrayCall("Списки.взять", [], undefined, { sourceRef: ссылка });
    } catch (error) {
      if (error instanceof ArrayRuntimeRefusal) поймано = error;
      else throw error;
    }
    expect(поймано, "`Списки.взять` обязан отказать").toBeDefined();
    expect(поймано!.message, "источник — ПЕРЕД причиной").toMatch(/^лента\[индекс\], строка \d+, колонка \d+ — /);
    expect(поймано!.message, "причина сохранена").toContain("D43a");
  });

  it("источник не дублируется: `…колонка N — «…»`, а не дважды", () => {
    for (const причина of причины(С_ЛИТЕРАЛОМ)) {
      const вхождений = (причина.match(/1\.5, строка/g) ?? []).length;
      expect(вхождений, `источник назван дважды: ${причина}`).toBeLessThanOrEqual(1);
    }
  });

  it("запасной путь: без источника текст прежний, БАЙТ В БАЙТ", () => {
    const причина = "«система.массив.получить»: раскладка не выдала базу блока рантайма (операнд 6 носителя)";
    // Источника нет вовсе — сообщение обязано не измениться ни на символ.
    expect(refusalWithSource(LOWERING_CODES.runtime, причина, undefined).reason).toBe(причина);
    // Ссылка есть, но реестр её не знает (чужой процесс / рукописный носитель) — тоже прежний текст.
    const чужая: IRSourceRef = { astNodeId: 999_999_999, tokenIndex: 0 };
    expect(описаниеПоСсылке(чужая), "реестр чужой ссылки не знает").toBeUndefined();
    expect(refusalWithSource(LOWERING_CODES.runtime, причина, чужая).reason).toBe(причина);
  });

  it("код отказа НЕ меняется от того, назван источник или нет", () => {
    const причина = "причина";
    expect(refusalWithSource(LOWERING_CODES.layout, причина, undefined).code).toBe(LOWERING_CODES.layout);
    expect(refusalWithSource(LOWERING_CODES.layout, причина, { astNodeId: 1, tokenIndex: 0 }).code).toBe(
      LOWERING_CODES.layout,
    );
  });
});
