/**
 * ЗАГЛУШКА РЕАЛЬНОЙ КОДИРОВКИ e2k — СТАТУС **НЕТ В ДОКУМЕНТЕ**.
 *
 * # Почему здесь нечего кодировать
 *
 * Руководство МЦСТ («Руководство по эффективному программированию на платформе „Эльбрус“»,
 * выпуск 1.2, `docs/elbrus-prog-1.2_2024-02-28.pdf`) задаёт **ассемблерную форму** операций
 * (стр. 19), слог и PLS-слог (стр. 41, 168–169), 24 канала выдачи (стр. 54–56), запрет более
 * одной передачи управления в команде (стр. 57), окно в 64 регистра, «определяемое кодировкой
 * операций» (стр. 144), литералы 32 бита (стр. 55) — и **ни одного битового поля команды**.
 *
 * Поиск по **всем формам**, которыми документ пользуется (метаправило проекта): слово,
 * мнемоника, семейство со звёздочкой, сокращение — «формат команды», «формат инструкции»,
 * «формат операции», «опкод», «opcode», «размер команды», «длина команды», «разрядность
 * команды», «формат кодирования», «поле команды», «положение разрядов» — **нулевые вхождения**
 * (`docs/e2k-encoding-raw.md` §1.7).
 *
 * # Следствие, а не свойство e2k
 *
 * Это факт о **доступной документации**, а не об архитектуре: e2k существует и исполняет код,
 * но кодировка не публична в этом руководстве (возможно, есть отдельный ISA-справочник или
 * доступ под NDA). Поэтому здесь **не придумываются** битовые поля: реализация обязана
 * **отказывать**, а не выдавать байты оболочки под именем e2k (статус `НЕТ В ДОКУМЕНТЕ` +
 * выдаваемые байты = «нарушение» в шлюзе `auditEncoder`).
 *
 * # Как выглядит замена
 *
 * Появится ISA-справочник, дизассемблер или железо — **переписывается только этот файл**:
 * статус `ФАКТ`, источник со страницами, размер инструкции, реализация `encode`/`decode`.
 * `backend.ts`, `shell.ts`, эмиттер и оракулы не меняются (`docs/e2k-backend.md` §4.6).
 *
 * Примечание о циклическом импорте: `backend.ts` импортирует этот файл, а этот файл берёт из
 * `backend.ts` только класс ошибки и **только внутри функций** — во время вычисления модуля
 * к его экспортам не обращаются, поэтому цикл безопасен.
 */

import { EncodingRefusedError, type AsmInstruction, type Encoder, type EncoderDescription } from "./backend";

/** Формы, которыми документ пользуется и по которым шёл поиск (метаправило). */
export const E2K_SEARCHES: readonly string[] = [
  "формат команды",
  "формат инструкции",
  "формат операции",
  "опкод",
  "opcode",
  "размер команды",
  "длина команды",
  "разрядность команды",
  "формат кодирования",
  "поле команды",
  "положение разрядов",
];

/** Причина отказа: одна строка, пригодная и для сообщения об ошибке, и для отчёта. */
export const E2K_REFUSAL_REASON =
  "НЕТ В ДОКУМЕНТЕ: бинарная кодировка инструкций в руководстве МЦСТ не описана — " +
  `поиск по формам (${E2K_SEARCHES.join(", ")}) дал нулевые вхождения; ` +
  "см. docs/e2k-encoding-raw.md §1.7. Придумывать битовые поля запрещено правилом проекта";

/** Паспорт заглушки: статус, отсутствие размера, названное ограничение. */
export const E2K_DESCRIPTION: EncoderDescription = {
  id: "e2k",
  title: "Кодировка e2k (руководство МЦСТ, выпуск 1.2)",
  status: "НЕТ В ДОКУМЕНТЕ",
  instructionSize: null,
  source: "руководство МЦСТ, выпуск 1.2, 28.02.2024 — бинарной кодировки нет (docs/e2k-encoding-raw.md §1.7)",
  limitation:
    "реализация отсутствует: нет ни одного документированного битового поля, поэтому выдавать код e2k нечем; заглушка отказывает намеренно",
};

/**
 * Заглушка реальной кодировки.
 *
 * `encode` и `decode` **всегда** бросают `EncodingRefusedError`: это законный исход шлюза
 * (`отказывает`), а не ошибка входных данных. Тихая выдача байтов оболочки здесь была бы
 * подменой — именно её запрещает контракт слоя.
 */
export function createE2kEncoder(): Encoder {
  const refuse = (): never => {
    throw new EncodingRefusedError(E2K_REFUSAL_REASON);
  };
  return {
    description: E2K_DESCRIPTION,
    encode(_instruction: AsmInstruction): Uint8Array {
      return refuse();
    },
    decode(_bytes: Uint8Array): AsmInstruction {
      return refuse();
    },
  };
}
