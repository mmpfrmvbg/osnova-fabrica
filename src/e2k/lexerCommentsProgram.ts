/**
 * ПРОГРАММА-ЛЕКСЕР КУСКА 4 (срез 7): комментарии обоих видов — на Основе, для цели e2k.
 *
 * # Зачем модуль, а не функция внутри теста
 *
 * Одна и та же программа нужна ДВУМ местам: оракулу (`src/e2k/lexerComments.test.ts` — стековая VM
 * и модель) и КИТУ для живой машины (`.tmp/lexer4-kit.ts` → `.tmp/lexer4-hw/`). Две копии builder'а
 * разошлись бы молча — и проба доказывала бы не тот байт, который уезжает на железо. Поэтому
 * источник один, а тест и кит только ПРОГОНЯЮТ его.
 *
 * # Что считает программа
 *
 * Текст пробы сканируется по КОДОВЫМ ТОЧКАМ (`текст[поз]` — код символа, D1/§13.6), и печатает три
 * числа: `ч` (числа), `с` (строки), `з` (знаки). Комментарии отбрасываются ЦЕЛИКОМ: их содержимое
 * не становится ни числом, ни строкой, ни знаком. Порядок ветвей — правило, а не стиль:
 *
 *   1. СТРОКА — до комментариев: `//` внутри литерала не начало комментария;
 *   2. КОММЕНТАРИИ — до числа и знака: иначе содержимое комментария станет токенами;
 *   3. число (цифры подряд), слово (буквы/цифры/`_`), иначе — знак.
 *
 * Логические `и`/`или` в условиях не используются: предикат из двух сравнений — стена пар (случай 81),
 * поэтому диапазоны собираются вложенными `если` во флаги, как в программах кусков 1–3.
 *
 * # Ступени (режим), а не флаг
 *
 * `нет` — комментариев не знает (состояние до куска 4); `только_строчные` — состояние ряда кусков
 * 1–3 (`//` есть, блочного нет); `оба` — правка куска 4. Различающая проба спрашивает ВСЕ три:
 * иначе «до правки красное» было бы утверждением без замера.
 *
 * # Эталон
 *
 * `tokenizeV3` (`src/compiler-v3/lexer.ts`) — тот же, что в исполняемой спецификации
 * (`src/spec/osnova-spec.ts#tokenize`). `эталон()` считает виды ИМ ЖЕ, а не по ожиданию теста.
 */
import { tokenizeV3 } from '../compiler-v3/lexer';

/** Т1: строчный комментарий с литералами внутри и `//` внутри НАСТОЯЩЕЙ строки. */
export const Т1 = ['пусть а = 1 // 999 "не число" 777', 'пусть б = "абв // не строка"', ''].join('\n');

/** Т2: блочный комментарий на двух строках, с эмодзи и кавычкой-ловушкой без пары. */
export const Т2 = ['/* 111 "не строка" 🙂 222', '   333 */ пусть в = 4', '/* " */ пусть г = 5', ''].join('\n');

/** Сколько видов комментариев программа умеет отбрасывать: ступени, а не флаг. */
export type Режим = 'нет' | 'только_строчные' | 'оба';

export interface Счёт {
  readonly ч: number;
  readonly с: number;
  readonly з: number;
}

/** Виды-знаки: считаются как «знак», чтобы отличие комментария от кода было видно числом. */
const ЗНАКИ: ReadonlySet<string> = new Set([
  '=', '==', '!=', '<', '<=', '>', '>=', '+', '-', '*', '/', '%',
  '(', ')', '[', ']', '{', '}', ',', ':', '.', '?', '→', ';', '|',
]);

/** Эталон `tokenizeV3`: комментарии уже отброшены — считаем виды токенов. */
export function эталон(текст: string): Счёт {
  const { tokens, errors } = tokenizeV3(текст, 'проба.osnova');
  if (errors.length > 0) throw new Error(`эталон не разобрал текст пробы: ${errors.join('; ')}`);
  let ч = 0;
  let с = 0;
  let з = 0;
  for (const t of tokens) {
    if (t.kind === 'число') ч += 1;
    else if (t.kind === 'строка') с += 1;
    else if (ЗНАКИ.has(t.kind)) з += 1;
  }
  return { ч, с, з };
}

export const какСтроки = (счёт: Счёт): string[] => [String(счёт.ч), String(счёт.с), String(счёт.з)];

const вЛитерале = (т: string): string =>
  '"' + т.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t') + '"';

/** Имя текста для файлов артефактов: одно и то же в тесте и в ките. */
export const имяТекста = (текст: string): string => (текст === Т1 ? 'т1-строчный' : 'т2-блочный');

