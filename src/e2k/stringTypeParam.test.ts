/** Первый знак строки как кодовая точка — то, что обязан отдать `с[0]` (§13.6: `с[и]` — ЧИСЛО). */
function первыйЗнак(строка: string): number {
  const код = строка.codePointAt(0);
  if (код === undefined) throw new Error(`проба без знаков: «${строка}»`);
  return код;
}

/** Число КОДОВЫХ ТОЧЕК (а не байтов UTF-8): «абв» — 3, «гд» — 2. */
function знаков(строка: string): number {
  return [...строка].length;
}

