const число = (значение: unknown): number | undefined => {
  if (значение === true) return 1;
  if (значение === false) return 0;
  return typeof значение === 'number' ? значение : undefined;
};

/** Собрать исходник пробы. */
const исходник = (проба: Проба): string => [...проба.строки, ''].join('\n');

/** Эталон ЯЗЫКА: обе VM, независимо от цели. Возвращает числа и почему не удалось, если не удалось. */
const обеVms = async (текст: string): Promise<{ стек?: number; регистры?: number; беда?: string }> => {
  const разбор = parseV3(текст, ФАЙЛ);
  if (разбор.errors.length > 0) return { беда: `разбор: ${JSON.stringify(разбор.errors)}` };
  const м = разбор.program!.modules[0]!;
  const проход = validateNamedTypesAndRewrite(м);
  if (проход.length > 0) return { беда: `проход: ${JSON.stringify(проход)}` };
  const стековая = new VM(compile(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const стек = число(await стековая.runProcedure(стековая.findProcedureIndex('главная'), []));
  const регистровая = new RegVM(compileToReg(м), { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
  const регистры = число(await регистровая.runProcedure(регистровая.findProcedureIndex('главная'), []));
  return { стек, регистры };
};

type Замер = { readonly отказы: readonly string[]; readonly код: number | undefined; readonly авария: boolean };

/** Понижение и (при любом исходе) прогон того, что понижение ОТДАЛО: отказ не мешает байтам существовать. */
const замерить = (проба: Проба): Замер => {
  const текст = исходник(проба);
  const разбор = parseV3(текст, ФАЙЛ);
  // Я СТОРОЖ, СМОТРЮ ПОД ОТКАЗОМ (D11): байты нужны ВМЕСТЕ с отказами — это дверь сторожей.
  const образ = loweredProgramUnchecked(текст, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  const elf = buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
  const файл = path.join(ROOT, '.tmp', `callee-join-lie-${проба.имя}.elf`);
  fs.writeFileSync(файл, elf.bytes);
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 20_000 });
  return {
    отказы: образ.refused.map((отказ) => отказ.reason),
    код: прогон?.status,
    // Авария порта — НЕ число: у неё есть IP исключения и текст «exception … aborting» (см. шапку).
    авария: прогон?.exceptionIp !== undefined,
  };
};

describe('A4-5д, задача 6: седьмая тихая ложь — отказ конъюнкции в ВЫЗЫВАЕМОЙ плоскости несёт лживый образ', () => {
  it('эталон от руки подтверждён ОБЕИМИ VM (ложь измеряется против независимого эталона, а не против цели)', async () => {
    const беды: string[] = [];
    for (const проба of ПРОБЫ) {
      const вм = await обеVms(исходник(проба));
      if (вм.беда !== undefined) {
        беды.push(`${проба.имя}: ${вм.беда}`);
        continue;
      }
      if (вм.стек !== проба.эталон) беды.push(`${проба.имя}: стековая ${String(вм.стек)}, эталон ${String(проба.эталон)}`);
      if (вм.регистры !== проба.эталон) беды.push(`${проба.имя}: регистровая ${String(вм.регистры)}, эталон ${String(проба.эталон)}`);
    }
    expect(беды, 'эталон не подтверждён обеими VM — мерка сломана, а не программа').toEqual([]);
  });

  it('КЛАСС ПОЧИНЕН: обе пробы СОБИРАЮТСЯ (отказов ноль) и дают СВОЙ эталон — 1 и 7', () => {
    // ПЕРЕМЕР 2026-11-04 (ATOM-05-02-01). Прежняя редакция требовала ЗДЕСЬ отказа и закрепляла
    // ложь под ним (код 9 — авария порта при эталонах 1 и 7). Клетка нуля вызываемой закреплена
    // настоящим носителем (§3.166), отказ снят ПРИЧИНОЙ, а не глушением, — поэтому утверждение
    // перевёрнуто: пробы обязаны собраться и дать ровно эталон.
    const строки: string[] = [];
    for (const имя of ['3а-конъюнкция-в-вызываемой-ложный-терм', '3а-бис-конъюнкция-в-вызываемой-истинный-терм']) {
      const проба = ПРОБЫ.find((кандидат) => кандидат.имя === имя)!;
      const замер = замерить(проба);
      expect(замер.отказы, `${имя}: отказ ВЕРНУЛСЯ — клетку нуля вызываемой потеряли (см. §3.166)`).toEqual([]);
      expect(
        замер.код,
        `${имя}: модель ${String(замер.код)} вместо эталона ${String(проба.эталон)} — починка не держится`,
      ).toBe(проба.эталон);
      // КАНАЛ: код обязан прийти БЕЗ аварии порта. Иначе «эталон» — совпадение с кодом аварии,
      // а не прочитанное значение (ровно на этом обожглись в 5д, поправка канала выше).
      expect(замер.авария, `${имя}: код пришёл аварией порта, а не значением`).toBe(false);
      строки.push(`  ${проба.имя}: отказов 0, модель ${String(замер.код)}, эталон ${String(проба.эталон)} (${проба.рука})`);
    }
    console.log(`СЕДЬМАЯ ЛОЖЬ ПОЧИНЕНА (клетка нуля вызываемой):\n${строки.join('\n')}`);
  });

  it('ЗНАЧЕНИЕ ЧИТАЕТСЯ: два РАЗНЫХ эталона дают ДВА РАЗНЫХ числа (а не одно, как было под отказом)', () => {
    // Это и есть различающая проверка починки. Под отказом обе пробы давали ОДНО число 9 — признак
    // «значение не читается вовсе». Если починка настоящая, числа обязаны РАЗОЙТИСЬ и совпасть с
    // эталонами: 1 для ложного терма, 7 для истинного. Свести их обратно к одному числу — стоп-условие.
    const ложный = замерить(ПРОБЫ.find((кандидат) => кандидат.имя === '3а-конъюнкция-в-вызываемой-ложный-терм')!);
    const истинный = замерить(ПРОБЫ.find((кандидат) => кандидат.имя === '3а-бис-конъюнкция-в-вызываемой-истинный-терм')!);
    expect(
      [ложный.код, истинный.код],
      'обе пробы снова дали ОДНО число — значение конъюнкции опять не читается',
    ).toEqual([1, 7]);
  });

  it('ГРАНИЦА В ПЛОСКОСТИ, А НЕ В ФОРМЕ: та же форма в точке входа собирается с НУЛЁМ отказов и верна', () => {
    const проба = ПРОБЫ.find((кандидат) => кандидат.имя === '3а-контроль-та-же-форма-в-точке-входа')!;
    const замер = замерить(проба);
    expect(замер.отказы, 'контроль обязан собираться: иначе «граница в плоскости» ничем не доказана').toEqual([]);
    expect(замер.код, `контроль в точке входа: модель ${String(замер.код)}, эталон ${String(проба.эталон)}`).toBe(проба.эталон);
  });

  it('ОБЕ СТОРОНЫ: у отказа бывает и перестраховочная сторона — булевы литералы дают ВЕРНОЕ число', () => {
    const проба = ПРОБЫ.find((кандидат) => кандидат.имя === '4б-конъюнкция-булевых-литералов')!;
    const замер = замерить(проба);
    expect(замер.отказы.length, 'булевы литералы: отказ исчез — перепишите запись').toBeGreaterThan(0);
    expect(
      замер.код,
      `булевы литералы: модель ${String(замер.код)}, эталон ${String(проба.эталон)} — ложь перешла и сюда`,
    ).toBe(проба.эталон);
    // КАНАЛ, обратная сторона: верное число — НАСТОЯЩЕЕ число, а не авария. Здесь образ исполним.
    expect(
      замер.авария,
      'булевы литералы: верное число пришло С аварией порта — тогда «верно» здесь ничего не значит',
    ).toBe(false);
  });
});
