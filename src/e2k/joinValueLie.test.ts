/**
 * СТОРОЖ КЛАССА «СКЛЕЙКА»: НЕВЕРНОЕ ЧИСЛО ПОД НЕСУЩИМ ОТКАЗОМ (A4, срез 5г, задача 0).
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Оракул `conjunctionValue.test.ts` исполняет образ в модели **только когда отказов
 * нет**: `if (собран.refused.length === 0 && shim !== undefined)`. Значит семь проб класса «склейка»
 * (6a/6b/6c, 8a/8b/8c/8d) отказывают — и **ни одна из них числом не проверена**. Отказ несущий: под
 * ним лежат неверные байты, то есть отказ МАСКИРУЕТ тихую ложь. По D4 (тихая ложь — абсолютный
 * приоритет) сторож пишется ПЕРВЫМ, до причины, и обязан спрашивать ЧИСЛО, а не «отказало ли».
 *
 * ЧТО ИЗМЕРЕНО (2026-10-29, `.tmp/a5g-under-refusal.ts`; путь тот же, что у оракула:
 * `parseV3` → `loweredProgram` → `buildElfFromCode` → `runInQemu`; образ берётся ИЗ ОТКАЗАВШЕГО
 * понижения — `loweredProgram` возвращает `bytes` вместе с записями `refused`):
 *
 * | проба | отказов | модель | эталон | вердикт |
 * |---|---|---|---|---|
 * | 6a `или` при ложной конъюнкции        | 2 | 1 | 1 | верно |
 * | 6b `или` при истинной конъюнкции      | 2 | 1 | 1 | верно |
 * | 6c обе части ложны                    | 2 | **1** | **0** | **ТИХАЯ ЛОЖЬ** |
 * | 8a вложенная конъюнкция, 1 и 0        | 2 | 0 | 0 | верно |
 * | 8b вложенная конъюнкция, 1 и 1        | 2 | 1 | 1 | верно |
 * | 8c `если` при истинном условии        | 2 | 7 | 7 | верно (отказ ПЕРЕСТРАХОВОЧНЫЙ) |
 * | 8d `если` при ЛОЖНОМ условии          | 2 | **7** | **0** | **ТИХАЯ ЛОЖЬ** |
 *
 * Отсюда два вывода, которые и закрепляет сторож: (1) отказ этого класса **перестраховочный не
 * всегда** — под ним лежат ДВЕ лжи, и вторая (6c) до этого файла не была названа нигде: срез 5в знал
 * только про 8d; (2) эталоны проб взяты НЕ из этого замера, а посчитаны от руки и подтверждены обеими
 * VM — это делает оракул (`conjunctionValue.test.ts`, раздел «эталон языка: обе VM») для тех же 23 проб.
 *
 * ЗАЧЕМ МОДЕЛЬ ОБЯЗАТЕЛЬНА. Без модели число не спрошено, а сторож, молча пропускающий проверку, —
 * не сторож. Поэтому файл живёт в `npm run gate:qemu` (там модель гарантирована) и первым делом
 * требует шим, а `npm test` его не гоняет (vitest.config.ts → exclude, `EXPECTED_EXCLUSIONS` в
 * `src/scripts/testFiles.audit.ts` с причиной).
 *
 * KNOWN BAD STATE (5г). Две закреплённые лжи ниже — это НЕ эталон и НЕ «так и надо»: это запись
 * известного дефекта с правилом самопокраснения. Как только класс «склейка» починят, набор лгущих
 * проб изменится, и сторож покраснеет с указанием, что переносить в эталон. Ослаблять его нельзя:
 * `expect(число).toBe(эталон)` — цель среза, а не пожелание.
 */
import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseV3 } from '../compiler-v3/index';
import { loweredProgram } from './programImage';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { isLoweringRefusalCode } from './loweringRefusal';

const ROOT = path.resolve(__dirname, '..', '..');
const ФАЙЛ = 'проба.osnova';
const shim = buildShim();

/** Исходник пробы: тело действия + `конец`. Тот же вид, что у оракула. */
const программа = (тело: readonly string[]): string => ['действие главная()', ...тело, 'конец', ''].join('\n');

type Проба = {
  readonly имя: string;
  readonly тело: readonly string[];
  /** ЭТАЛОН — посчитан от руки и подтверждён обеими VM (оракул `conjunctionValue.test.ts`). */
  readonly эталон: number;
  readonly рука: string;
};

/** Семь проб класса «склейка» — ровно те, что оракул держит в `ДОЛГ_5Г` (тот же состав). */
const ПРОБЫ: readonly Проба[] = [
  {
    имя: '6a-или-второй-терм-истинен',
    тело: ['  пусть код = 0', '  пусть пер = (код >= 48 и код <= 57) или код == 0', '  вернуть пер'],
    эталон: 1,
    рука: 'конъюнкция 0, «0==0» да → 1',
  },
  {
    имя: '6b-конъюнкция-истинна',
    тело: ['  пусть код = 50', '  пусть пер = (код >= 48 и код <= 57) или код == 0', '  вернуть пер'],
    эталон: 1,
    рука: 'конъюнкция 1 → 1 (замыкание «или»)',
  },
  {
    имя: '6c-обе-ложны',
    тело: ['  пусть код = 10', '  пусть пер = (код >= 48 и код <= 57) или код == 0', '  вернуть пер'],
    эталон: 0,
    рука: 'конъюнкция 0, «10==0» нет → 0',
  },
  {
    имя: '8a-конъюнкция-в-конъюнкции',
    тело: ['  пусть код = 50', '  пусть другой = 10', '  пусть пер = (код >= 48 и код <= 57) и (другой >= 48 и другой <= 57)', '  вернуть пер'],
    эталон: 0,
    рука: '1 и 0 → 0',
  },
  {
    имя: '8b-обе-вложенные-истинны',
    тело: ['  пусть код = 50', '  пусть другой = 50', '  пусть пер = (код >= 48 и код <= 57) и (другой >= 48 и другой <= 57)', '  вернуть пер'],
    эталон: 1,
    рука: '1 и 1 → 1',
  },
  {
    имя: '8c-в-ветви-если-истинно',
    тело: ['  пусть код = 50', '  пусть рез = 0', '  если код >= 48 и код <= 57', '    рез = 7', '  конец если', '  вернуть рез'],
    эталон: 7,
    рука: 'условие да → рез = 7',
  },
  {
    имя: '8d-в-ветви-если-ложно',
    тело: ['  пусть код = 10', '  пусть рез = 0', '  если код >= 48 и код <= 57', '    рез = 7', '  конец если', '  вернуть рез'],
    эталон: 0,
    рука: 'условие нет → рез = 0',
  },
];

/**
 * ЗАКРЕПЛЁННАЯ ЛОЖЬ ПОД ОТКАЗОМ (KNOWN BAD STATE среза 5г, замер `.tmp/a5g-under-refusal.ts`).
 * Ключ — имя пробы, значение — ЧИСЛО, которое модель даёт сейчас. Эталон рядом (в `ПРОБЫ`) обязан
 * быть другим: совпадение означает, что класс починили и запись надо снять.
 */
const ЛОЖЬ_ПОД_ОТКАЗОМ: ReadonlyMap<string, number> = new Map<string, number>([
  ['6c-обе-ложны', 1],
  ['8d-в-ветви-если-ложно', 7],
]);

/** Класс 5а: причина обязана называть «склейку» и то, почему один `ct` не выражает оба ребра. */
const МЕХАНИЗМ = /склейка/;
const ПОЧЕМУ_ОДИН_CT = /один ct не выражает оба ребра/;

type Замер = {
  readonly имя: string;
  readonly отказы: readonly { readonly code: string; readonly reason: string }[];
  readonly код: number | undefined;
};

const замеры = new Map<string, Замер>();

/**
 * ОДИН ЗАМЕР НА ПРОБУ: понижение (отказы + байты) и код в модели. Отличие от оракула ровно одно и
 * оно главное: образ исполняется **даже когда понижение отказало** — иначе число под отказом не
 * спрошено, и тихая ложь остаётся невидимой.
 */
function замерить(проба: Проба): Замер {
  const готово = замеры.get(проба.имя);
  if (готово !== undefined) return готово;
  const источник = программа(проба.тело);
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор ${проба.имя}: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  const собран = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  let код: number | undefined;
  if (shim !== undefined) {
    const elf = buildElfFromCode(собран.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
    const файл = path.join(ROOT, '.tmp', `join-value-lie-${проба.имя}.elf`);
    fs.writeFileSync(файл, elf.bytes);
    код = runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status ?? undefined;
  }
  const измерение: Замер = {
    имя: проба.имя,
    отказы: собран.refused.map((отказ) => ({ code: отказ.code, reason: отказ.reason })),
    код,
  };
  замеры.set(проба.имя, измерение);
  return измерение;
}

/** Пробы, у которых число ПОД отказом разошлось с эталоном. Пусто = класс больше не лжёт. */
function лгущие(): string[] {
  return ПРОБЫ.filter((проба) => {
    const измерение = замерить(проба);
    return измерение.код !== undefined && измерение.код !== проба.эталон;
  }).map((проба) => проба.имя);
}

describe('сторож класса «склейка»: число ПОД отказом (A4, срез 5г)', () => {
  it('модель обязательна: без неё сторож класса «склейка» — не сторож, а украшение', () => {
    expect(
      shim,
      'нет шима модели: число под отказом не спрошено. Файл обязан жить в `npm run gate:qemu`, где модель гарантирована',
    ).toBeDefined();
  });

  it('все семь проб отказывают ПО ИМЕНИ, и первый отказ называет механизм «склейки» (снимать его нельзя)', () => {
    const строки: string[] = [];
    for (const проба of ПРОБЫ) {
      const измерение = замерить(проба);
      expect(измерение.отказы.length, `${проба.имя}: отказ исчез — класс изменился, сторож надо переписать`).toBeGreaterThan(0);
      for (const отказ of измерение.отказы) {
        expect(isLoweringRefusalCode(отказ.code), `${проба.имя}: отказ без кода понижения (${отказ.code})`).toBe(true);
        expect(отказ.code, `${проба.имя}: отказ перестал быть OSN-LOW-004`).toBe('OSN-LOW-004');
        expect(отказ.reason.length, `${проба.имя}: причина отказа пуста`).toBeGreaterThan(20);
        // Видов ровно два, и оба названы (замер `.tmp/a5g-under-refusal.ts`): «склейка» — причина, а
        // «предикат взять неоткуда» — её СЛЕДСТВИЕ (первая пара не составилась, второму сравнению
        // предиката неоткуда взять). Третий вид = новый класс → сторож обязан покраснеть.
        expect(
          отказ.reason,
          `${проба.имя}: отказ не того вида — ждали «склейку» или её следствие «предикат взять неоткуда»`,
        ).toMatch(/склейка|предикат взять неоткуда/);
      }
      const первый = измерение.отказы[0]!;
      expect(первый.reason, `${проба.имя}: ПЕРВЫЙ отказ не называет класс «склейки»`).toMatch(МЕХАНИЗМ);
      expect(первый.reason, `${проба.имя}: причина не объясняет, почему один ct не выражает оба ребра`).toMatch(ПОЧЕМУ_ОДИН_CT);
      строки.push(`  ${проба.имя}: отказов ${String(измерение.отказы.length)} — ${первый.reason.slice(0, 72)}…`);
    }
    console.log(`КЛАСС «СКЛЕЙКА»: отказ назван (${String(строки.length)} проб)\n${строки.join('\n')}`);
  });

  it('под отказом число сверяется с эталоном: пять проб верны — и это ЗАКРЕПЛЕНО, а не предположено', () => {
    const строки: string[] = [];
    for (const проба of ПРОБЫ) {
      const измерение = замерить(проба);
      if (ЛОЖЬ_ПОД_ОТКАЗОМ.has(проба.имя)) continue;
      expect(
        измерение.код,
        `${проба.имя}: модель ${String(измерение.код)}, эталон ${String(проба.эталон)} (${проба.рука}) — под отказом ТИХАЯ ЛОЖЬ`,
      ).toBe(проба.эталон);
      строки.push(`  ${проба.имя}: код ${String(измерение.код)} = эталон ${String(проба.эталон)} (${проба.рука})`);
    }
    console.log(`КЛАСС «СКЛЕЙКА»: верны под отказом (${String(строки.length)} проб)\n${строки.join('\n')}`);
  });

  it('KNOWN BAD STATE 5г: ровно ДВЕ пробы лгут под отказом — 6c и 8d (запись обязана сняться починкой)', () => {
    const измерено = лгущие().slice().sort();
    expect(
      измерено,
      'набор лгущих проб класса «склейка» изменился: если ложь ПОЧИНИЛИ — снимите запись KNOWN BAD STATE и ' +
        'переведите пробы в «верны под отказом»; если появилась НОВАЯ ложь — это стоп-условие среза 5г',
    ).toEqual([...ЛОЖЬ_ПОД_ОТКАЗОМ.keys()].slice().sort());
    for (const [имя, число] of ЛОЖЬ_ПОД_ОТКАЗОМ) {
      const проба = ПРОБЫ.find((кандидат) => кандидат.имя === имя);
      expect(проба, `${имя}: проба из записи KNOWN BAD STATE пропала из списка`).toBeDefined();
      const измерение = замерить(проба!);
      expect(измерение.код, `${имя}: закреплённая ложь сдвинулась — перемерьте и обновите запись`).toBe(число);
      expect(
        измерение.код,
        `${имя}: число совпало с эталоном — КЛАСС ПОЧИНЕН, снимите запись и оставьте ожидание эталона`,
      ).not.toBe(проба!.эталон);
      expect(проба!.эталон, `${имя}: эталон обязан остаться посчитанным от руки (0)`).toBe(0);
      console.log(`  ЛОЖЬ ПОД ОТКАЗОМ ${имя}: модель ${String(измерение.код)}, эталон ${String(проба!.эталон)} (${проба!.рука})`);
    }
  });
});
