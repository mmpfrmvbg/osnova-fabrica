    const контроль = измеритьИмя('B-тело-пишет-1-код-10');
    expect(контроль.код, 'контроль B: тело исполнилось (1) — ветвление по значению не сработало').toBe(0);
    // Третья: путь ПРОВАЛА второго терма верен (C) — значит дело именно в ребре ВЗЯТОГО перехода.
