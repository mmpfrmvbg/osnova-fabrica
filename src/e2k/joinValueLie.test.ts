/** Класс 5а: причина обязана называть «склейку» и то, почему один `ct` не выражает оба ребра. */
const МЕХАНИЗМ = /склейка/;
const ПОЧЕМУ_ОДИН_CT = /один ct не выражает оба ребра/;

type Замер = {
  readonly имя: string;
  readonly отказы: readonly { readonly code: string; readonly reason: string }[];
  readonly код: number | undefined;
};

const замеры = new Map<string, Замер>();

/**
 * ОДИН ЗАМЕР НА ПРОБУ: понижение (отказы + байты) и код в модели. Отличие от оракула ровно одно и
 * оно главное: образ исполняется **даже когда понижение отказало** — иначе число под отказом не
 * спрошено, и тихая ложь остаётся невидимой.
 */
function замерить(проба: Проба): Замер {
  const готово = замеры.get(проба.имя);
  if (готово !== undefined) return готово;
  const источник = программа(проба.тело);
  const разбор = parseV3(источник, ФАЙЛ);
  expect(разбор.errors, `разбор ${проба.имя}: ${JSON.stringify(разбор.errors)}`).toEqual([]);
  const собран = loweredProgram(источник, {
    filename: ФАЙЛ,
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
  let код: number | undefined;
  if (shim !== undefined) {
    const elf = buildElfFromCode(собран.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY });
    const файл = path.join(ROOT, '.tmp', `join-value-lie-${проба.имя}.elf`);
    fs.writeFileSync(файл, elf.bytes);
    код = runInQemu(файл, { shim: true, timeoutMs: 20_000 })?.status ?? undefined;
  }
  const измерение: Замер = {
    имя: проба.имя,
    отказы: собран.refused.map((отказ) => ({ code: отказ.code, reason: отказ.reason })),
    код,
  };
  замеры.set(проба.имя, измерение);
  return измерение;
}

/** Пробы, у которых число ПОД отказом разошлось с эталоном. Пусто = класс больше не лжёт. */
function лгущие(): string[] {
  return ПРОБЫ.filter((проба) => {
    const измерение = замерить(проба);
    return измерение.код !== undefined && измерение.код !== проба.эталон;
  }).map((проба) => проба.имя);
}

