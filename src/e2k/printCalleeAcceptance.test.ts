type Семейство =
  /** Печатается ч, возвращается ч: эталон РАВЕН последней печати ПО ПОСТРОЕНИЮ (критерий владельца). */
  | 'терм-в-значение'
  /** Значение ОТЛИЧНО от напечатанного: эталон и приманки попарно различимы. */
  | 'значение-иное'
  /** Печати нет: лжи быть неоткуда, проверяется путь возврата. */
  | 'без-печати';

type Проба = {
  readonly имя: string;
  readonly класс: string;
  readonly семейство: Семейство;
  readonly строки: readonly string[];
  /** Эталон ОТ РУКИ; подтверждается ОБЕИМИ VM независимо от цели (проверка ниже). */
  readonly эталон: number;
  /** ОДИН элемент на КАЖДОЕ исполнение `write`: у цикла — повторы, у двух вызовов — разные длины. */
  readonly печатает: readonly number[];
  readonly рука: string;
  /** Имя пары, отличающейся ОДНИМ: плоскостью (A ↔ К) или печатью (A ↔ без печати). */
  readonly пара?: string;
};

const байтСтроки = (значение: number): number => Buffer.byteLength(`${String(значение)}\n`, 'utf-8');
const байтВывода = (проба: Проба): number => проба.печатает.reduce((сумма, з) => сумма + байтСтроки(з), 0);
const ответПоследнегоВызова = (проба: Проба): number =>
  проба.печатает.length === 0 ? 0 : байтСтроки(проба.печатает[проба.печатает.length - 1]!);
/** Закон восьмой лжи (§3.157): модель = эталон + ответ ПОСЛЕДНЕГО исполненного `write`. */
const лживоеЧисло = (проба: Проба): number => проба.эталон + ответПоследнегоВызова(проба);
/** Лживая формула «сумма всего вывода» — её обязан отвергать цикл из 2 и 3 итераций. */
const суммаВывода = (проба: Проба): number => проба.эталон + байтВывода(проба);
/** Вывод, как его склеивает VM: напечатанные строки через перевод строки. */
const выводVm = (проба: Проба): string => проба.печатает.map((з) => String(з)).join('\n');

