/**
 * ОРАКУЛ НОРМАЛИЗАЦИИ КРАЁВ РАНТАЙМ-СРЕЗА (`src/e2k/stringRuntime.ts#stringSliceEdgeCarriers`).
 *
 * # Что здесь утверждается и чем именно
 *
 * 1. **Края совпадают с ЭТАЛОНОМ ЯЗЫКА.** Ожидание берётся НЕ из переписанной здесь формулы, а ИЗ
 *    САМОГО эталона `src/runtime/vm/stringUnits.ts#codePointSlice`: нормализованное начало —
 *    `codePointLength(codePointSlice(текст, 0, н))`, конец — `codePointLength(codePointSlice(текст, 0, к))`.
 *    Так оракул не может «сойтись» с копией собственной ошибки.
 * 2. **Исполняется САМ ПОСТРОЕННЫЙ ПОТОК, а не его пересказ.** Модель клеток идёт по носителям,
 *    построенным `stringSliceEdgeCarriers`, и падает на ЛЮБОМ носителе, которого не знает: молча
 *    пропустить носитель нельзя, иначе оракул мерил бы свою неполноту (случай 78 реестра).
 * 3. **Наружу — строки, как их видит язык.** Нормализованные края сходятся в модель ЦИКЛА (алгоритм
 *    варианта Г: проход по БАЙТАМ с таблицей продолжений, счёт `q` кодовой точки, копирование
 *    `f ≤ q < t`, счёт `cnt` только на НАЧАЛЕ кодовой точки) — и сравниваются и СТРОКА, и её ДЛИНА в
 *    кодовых точках со эталоном. Разбираемые случаи владельца: `("ёжзийк", −2, 6)` → «йк»,
 *    `("ёжзийк", 0, 99)` → «ёжзийк», `("ёжзийк", 3, 1)` → «», `("абвгде", 1, 4)` → «бвг».
 * 4. **Новых форм раскладке не требуется** — все 15 носителей размещаются (`layoutOf`), и разбор пар
 *    даёт 5 пар на 5 условных переходов без отказов.
 *
 * # Границы (названы, а не спрятаны)
 *
 * * Модель ЦИКЛА здесь — АЛГОРИТМ шага 4, а не его носители: сам цикл Г строится отдельно, и у него
 *   будет свой оракул. Здесь он нужен, чтобы ответ был СТРОКОЙ (как у языка), а не парой чисел.
 * * Модель клеток умеет ровно те носители, из которых состоит блок (`IR.lt`, `IR.jmp_if_not`, `IR.add`);
 *   это и есть её негативный контроль: чужой носитель — исключение, а не тишина.
 * * Поток разбирается С ЦЕЛЯМИ ВНУТРИ МАССИВА (случай 78): блок дополняется носителями ПОСЛЕ себя,
 *   иначе переход на «первый за блоком» индекс выключал бы сторожа ребра взятого перехода.
 */
import { describe, expect, it } from 'vitest';
import type { AsmInstruction, Operand } from './backend';
import { pairPredicates } from './predicatePairing';
import { codePointLength, codePointSlice } from '../runtime/vm/stringUnits';
import {
  STRING_SLICE_EDGE_SIZE,
  continuationTable,
  stringSliceEdgeCarriers,
  utf8Bytes,
} from './stringRuntime';
import { layoutOf } from './twoPassLayout';

const reg = (index: number): Operand => ({ kind: 'reg', index });
const imm = (value: number): Operand => ({ kind: 'imm', value });
const a = (mnemonic: string, operands: readonly Operand[]): AsmInstruction => ({
  mnemonic,
  channel: 0,
  operands,
});

/** Клетки блока: имена условные — проверяются ЧИСЛА и СТРОКИ, а не конкретные номера. */
const К = { from: 2, to: 3, count: 1, zero: 5, key: 6, приемник: 10, приемник2: 11 } as const;

type Состояние = Map<number, number>;

const значение = (операнд: Operand | undefined, состояние: Состояние): number => {
  if (операнд === undefined) throw new Error('у носителя нет операнда — модель клеток его не угадывает');
  if (операнд.kind === 'reg') return состояние.get(операнд.index) ?? 0;
  if (операнд.kind === 'imm') return операнд.value;
  throw new Error(`операнд «${операнд.kind}» модель клеток не умеет — молча пропустить его нельзя`);
};

/**
 * МОДЕЛЬ КЛЕТОК: исполняет РОВНО переданный поток носителей, начиная с `base`, до `base + size`.
 * Незнакомый носитель — ИСКЛЮЧЕНИЕ (негативный контроль снизу это и проверяет).
 */
const исполнить = (
  поток: readonly AsmInstruction[],
  base: number,
  состояние: Состояние,
  size = STRING_SLICE_EDGE_SIZE,
): Состояние => {
  const ячейки = new Map(состояние);
  const конец = base + size;
  let pc = base;
  for (let шаг = 0; шаг < 256; шаг++) {
    if (pc >= конец) return ячейки;
    const носитель = поток[pc];
    if (носитель === undefined) throw new Error(`носителя ${String(pc)} нет — цель перехода ушла за поток`);
    const [первый, второй, третий] = носитель.operands;
    if (носитель.mnemonic === 'IR.lt') {
      const приёмник = первый as { index: number };
      ячейки.set(приёмник.index, значение(второй, ячейки) < значение(третий, ячейки) ? 1 : 0);
    } else if (носитель.mnemonic === 'IR.jmp_if_not') {
      if (значение(первый, ячейки) === 0) {
        pc = значение(второй, ячейки);
        continue;
      }
    } else if (носитель.mnemonic === 'IR.add') {
      const приёмник = первый as { index: number };
      ячейки.set(приёмник.index, значение(второй, ячейки) + значение(третий, ячейки));
    } else {
      throw new Error(`модель клеток не знает «${носитель.mnemonic}» — пропустить его молча нельзя`);
    }
    pc += 1;
  }
  throw new Error('блок не завершился за 256 шагов — в переходах петля');
};

/**
 * МОДЕЛЬ ЦИКЛА Г (алгоритм шага 4, а не его носители): проход по БАЙТАМ, номер кодовой точки `q`
 * растёт только на НАЧАЛЕ точки (таблица продолжений), копируются байты с `f ≤ q < t`, `cnt` считает
 * точки. Края сюда приходят УЖЕ нормализованными — их даёт исполненный блок нормализации.
 */
const срезЦикломГ = (текст: string, f: number, t: number): { строка: string; длина: number } => {
  const байты = utf8Bytes(текст);
  const таблица = continuationTable();
  let p = 0;
  let q = -1;
  let cnt = 0;
  const out: number[] = [];
  while (p < байты.length) {
    const byte = байты[p] as number;
    const flag = 1 - (таблица[byte] as number);
    q += flag;
    if (!(q < t)) break;
    if (f <= q) {
      out.push(byte);
      cnt += flag;
    }
    p += 1;
  }
  return { строка: Buffer.from(out).toString('utf8'), длина: cnt };
};

/** Края, нормализованные ИСПОЛНЕНИЕМ ПОСТРОЕННОГО БЛОКА (не пересказом формулы). */
const краяБлоком = (текст: string, н: number, к: number): { from: number; to: number } => {
  const блок = stringSliceEdgeCarriers({ baseIndex: 0, ...К });
  const итог = исполнить(
    блок,
    0,
    new Map<number, number>([
      [К.from, н],
      [К.to, к],
      [К.count, codePointLength(текст)],
      [К.zero, 0],
      [К.key, 0],
    ]),
  );
  return { from: итог.get(К.from) ?? 0, to: итог.get(К.to) ?? 0 };
};

/** СЛУЧАИ ВЛАДЕЛЬЦА — названы отдельно, с ожидаемой строкой. */
const СЛУЧАИ_ВЛАДЕЛЬЦА: readonly (readonly [string, number, number, string])[] = [
  ['ёжзийк', -2, 6, 'йк'],
  ['ёжзийк', 0, 99, 'ёжзийк'],
  ['ёжзийк', 3, 1, ''],
  ['абвгде', 1, 4, 'бвг'],
];

/** Тот же разбор шире: коды владельца плюс края, где ошибается и эталон-клон (ноль, за конец, эмодзи). */
const СЕТКА: readonly (readonly [string, number, number])[] = [
  ...СЛУЧАИ_ВЛАДЕЛЬЦА.map(([текст, н, к]) => [текст, н, к] as const),
  ['ёжзийк', 1, 3],
  ['ёжзийк', 0, 1],
  ['ёжзийк', -99, 2],
  ['ёжзийк', 99, 99],
  ['ёжзийк', -2, -1],
  ['ёжзийк', -99, -99],
  ['🙂', 0, 1],
  ['абв', 0, 3],
  ['абвгде', 0, 0],
];

describe('нормализация краёв: строки совпадают с эталоном языка', () => {
  it('СЛУЧАИ ВЛАДЕЛЬЦА названы поимённо', () => {
    for (const [текст, н, к, ожидаем] of СЛУЧАИ_ВЛАДЕЛЬЦА) {
      const края = краяБлоком(текст, н, к);
      const срез = срезЦикломГ(текст, края.from, края.to);
      expect(срез.строка, `подстрока(«${текст}», ${String(н)}, ${String(к)})`).toBe(ожидаем);
      expect(срез.длина, `длина «${ожидаем}» в кодпоинтах`).toBe(codePointLength(ожидаем));
      expect(срез.строка, 'и то же отвечает эталон языка').toBe(codePointSlice(текст, н, к));
    }
  });

  it('края = эталон на всей сетке, и длина результата — в КОДОВЫХ ТОЧКАХ', () => {
    const расхождения: string[] = [];
    for (const [текст, н, к] of СЕТКА) {
      const N = codePointLength(текст);
      const края = краяБлоком(текст, н, к);
      // Ожидание — ИЗ ЭТАЛОНА: он же и обрезает, и считает от конца.
      const ждёмНачало = codePointLength(codePointSlice(текст, 0, н));
      const ждёмКонец = codePointLength(codePointSlice(текст, 0, к));
      // Обрезки `к` СВЕРХУ у блока нет намеренно (конец блоба ловит граница цикла) — поэтому сверяем
      // с эталоном то, что блок обязан дать: у конца это `min(к', N)`.
      const фактНачало = края.from;
      const фактКонец = Math.min(края.to, N);
      const срез = срезЦикломГ(текст, края.from, края.to);
      const эталон = codePointSlice(текст, н, к);
      if (
        фактНачало !== ждёмНачало ||
        фактКонец !== ждёмКонец ||
        срез.строка !== эталон ||
        срез.длина !== codePointLength(эталон)
      ) {
        расхождения.push(
          `«${текст}» ${String(н)}..${String(к)}: края ${String(фактНачало)}/${String(фактКонец)} ` +
            `(эталон ${String(ждёмНачало)}/${String(ждёмКонец)}), срез «${срез.строка}»/${String(срез.длина)} ` +
            `против «${эталон}»/${String(codePointLength(эталон))}`,
        );
      }
    }
    expect(расхождения, расхождения.join('\n')).toEqual([]);
    expect(СЕТКА.length, 'сетка обязана быть шире кодов владельца').toBeGreaterThanOrEqual(13);
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ: снятая обрезка сверху даёт ДРУГОЙ ответ, а не тот же', () => {
    // Испорченный блок: носитель 8 (`from = N`) заменён на `from = 0` — то есть обрезки сверху нет.
    const целый = stringSliceEdgeCarriers({ baseIndex: 0, ...К });
    const испорченный = целый.map((носитель, номер) =>
      номер === 8 ? a('IR.add', [reg(К.from), reg(К.zero), reg(К.zero)]) : носитель,
    );
    const ячейки = new Map<number, number>([
      [К.from, 99],
      [К.to, 6],
      [К.count, 6],
      [К.zero, 0],
      [К.key, 0],
    ]);
    const целыеКрая = исполнить(целый, 0, ячейки);
    const битыеКрая = исполнить(испорченный, 0, ячейки);
    expect(целыеКрая.get(К.from), 'целый блок обрезает край за концом до длины').toBe(6);
    expect(битыеКрая.get(К.from), 'без обрезки край остаётся за концом — и это ДРУГОЕ число').toBe(0);
    expect(
      срезЦикломГ('ёжзийк', 6, 6).строка,
      'обрезанный край даёт пустую строку (эталон: подстрока("ёжзийк", 99, 99) → "")',
    ).toBe(codePointSlice('ёжзийк', 99, 99));
  });

  it('НЕГАТИВНЫЙ КОНТРОЛЬ модели: чужой носитель — исключение, а не тишина', () => {
    const сЧужим = [...stringSliceEdgeCarriers({ baseIndex: 0, ...К }), a('IR.and', [reg(1), reg(2), reg(3)])];
    expect(() => исполнить(сЧужим, 0, new Map(), STRING_SLICE_EDGE_SIZE + 1), 'IR.and').toThrow(/не знает/);
    const сКонкретной = [...stringSliceEdgeCarriers({ baseIndex: 0, ...К }), a('ldb', [reg(1), reg(2), reg(3)])];
    expect(() => исполнить(сКонкретной, 0, new Map(), STRING_SLICE_EDGE_SIZE + 1), 'ldb').toThrow(/не знает/);
  });
});

describe('нормализация краёв: раскладка и пары предикатов', () => {
  it('ВСЕ 15 НОСИТЕЛЕЙ РАЗМЕЩАЮТСЯ: новых форм раскладке не требуется', () => {
    const блок = stringSliceEdgeCarriers({ baseIndex: 0, ...К });
    expect(блок).toHaveLength(STRING_SLICE_EDGE_SIZE);
    const раскладка = layoutOf(блок);
    expect(раскладка.unplaced, 'неразмещённых быть не должно').toEqual([]);
    expect(раскладка.entries).toHaveLength(STRING_SLICE_EDGE_SIZE);
    // НЕГАТИВНЫЙ КОНТРОЛЬ: конкретная команда в том же потоке НЕ размещается — иначе «размещено»
    // ничего не доказывало бы (случай 78).
    const сКонкретной = [...блок, a('movts', [reg(1), reg(2)])];
    expect(layoutOf(сКонкретной).unplaced.map((не) => не.carrier)).toEqual(['movts']);
  });

  it('ЦЕЛИ ПЕРЕХОДОВ АБСОЛЮТНЫЕ: сдвиг базы сдвигает их, и разбор идёт с целями ВНУТРИ массива', () => {
    const ПОДЛОЖКА = 9;
    const нулевой = stringSliceEdgeCarriers({ baseIndex: 0, ...К });
    const сдвинутый = stringSliceEdgeCarriers({ baseIndex: ПОДЛОЖКА, ...К });
    for (const [номер, носитель] of сдвинутый.entries()) {
      if (носитель.mnemonic !== 'IR.jmp_if_not') continue;
      const цель = носитель.operands[1] as { value: number };
      const цельНулевая = нулевой[номер]?.operands[1] as { value: number };
      expect(цель.value - цельНулевая.value, `носитель ${String(номер)}`).toBe(ПОДЛОЖКА);
    }
    // Поток С ЦЕЛЯМИ ВНУТРИ МАССИВА: подложка + блок + носители ПОСЛЕ него (случай 78 — иначе переход
    // на «первый за блоком» индекс выключал бы сторожа ребра взятого перехода).
    const поток = [
      a('IR.add', [reg(К.приемник), reg(К.zero), reg(К.zero)]),
      ...Array.from({ length: ПОДЛОЖКА - 1 }, () => a('IR.add', [reg(К.приемник), reg(К.zero), reg(К.zero)])),
      ...сдвинутый,
      a('IR.add', [reg(К.приемник), reg(К.from), reg(К.zero)]),
      a('IR.add', [reg(К.приемник2), reg(К.to), reg(К.zero)]),
    ];
    const pairing = pairPredicates(поток);
    expect(pairing.refusals, 'отказов быть не должно: операнды известны, цели внутри массива').toEqual([]);
    expect(pairing.pairs, '5 сравнений — 5 пар').toHaveLength(5);
    // СТОРОЖ ПРОТИВ САМОГО СЕБЯ (случай 78): если бы хоть одна цель лежала за концом массива, разбор
    // молча пропустил бы её ребро, и «отказов нет» ничего не значило бы. Поэтому это проверяется ЧИСЛОМ.
    for (const [номер, носитель] of поток.entries()) {
      if (носитель.mnemonic !== 'IR.jmp_if_not') continue;
      const цель = (носитель.operands[1] as { value: number }).value;
      expect(цель, `носитель ${String(номер)}: цель обязана лежать ВНУТРИ массива`).toBeLessThan(поток.length);
      expect(цель, `носитель ${String(номер)}: и вперёд, а не назад`).toBeGreaterThan(номер);
    }
    // И тот же блок, ЗАПУЩЕННЫЙ со сдвинутой базы, даёт тот же ответ, что с нулевой.
    const ячейки = new Map<number, number>([
      [К.from, -2],
      [К.to, 6],
      [К.count, 6],
      [К.zero, 0],
      [К.key, 0],
    ]);
    const сНуля = исполнить(нулевой, 0, ячейки);
    const сПодложки = исполнить(поток, ПОДЛОЖКА, ячейки);
    expect(сПодложки.get(К.from)).toBe(сНуля.get(К.from));
    expect(сПодложки.get(К.to)).toBe(сНуля.get(К.to));
    expect(сНуля.get(К.from), 'и это измеренный ответ «йк»').toBe(4);
    expect(сНуля.get(К.to)).toBe(6);
  });
});
