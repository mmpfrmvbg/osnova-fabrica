/**
 * D43a: таблица `Списки.*` — это ПОНИЖЕНИЕ, а не исходная подстановка.
 *
 * # Что здесь проверяется
 *
 * 1. Имена `Списки.пустой`, `Списки.длина`, `Списки.добавить` распознаются как вызовы рантайма
 *    массивов ДО раскладки (иначе не зарезервируется куча и не выдастся база блока).
 * 2. Арена — обязательный аргумент D43; без неё отказ по имени, а не «создать()».
 * 3. `Списки.пустой(ар)` и `Списки.длина(л)` дают ровно ту же последовательность, что канонические
 *    `система.массив.создать()` / `система.массив.длина(л)`.
 * 4. `Списки.добавить(л, э, ар)` — каноническая последовательность `добавить` плюс `movtd` в
 *    приёмник: D43 возвращает ТОТ ЖЕ список, а рантайм результата не имеет.
 * 5. `Списки.взять` — НЕ тихая подмена на `получить`: отказ называет пару `Результат` и D49.
 *
 * # Чего здесь НЕТ
 *
 * Исполнения: числа N=5 спрашиваются у модели в `src/e2k/d43ListsQemu.test.ts`, а у железа —
 * отдельным прогоном ELF на E8C2 (отчёт в docs/hardware-debt.md).
 */

import { describe, expect, it } from 'vitest';
import {
  ArrayRuntimeRefusal,
  D43_LIST_CALLS,
  isArrayCreateCall,
  isArrayRuntimeCall,
  lowerArrayCall,
} from './arrayRuntime';

const reg = (index: number): { kind: 'reg'; index: number } => ({ kind: 'reg', index });

const ОСНОВАНИЕ = { base: 12 };

describe('D43a: таблица Списки.*', () => {
  it('имена распознаются как рантайм массивов, а Списки.взять — нет', () => {
    expect(D43_LIST_CALLS).toEqual(['Списки.пустой', 'Списки.добавить', 'Списки.длина']);
    for (const имя of D43_LIST_CALLS) expect(isArrayRuntimeCall(имя), имя).toBe(true);
    expect(isArrayRuntimeCall('Списки.взять')).toBe(false);
    expect(isArrayCreateCall('Списки.пустой')).toBe(true);
    expect(isArrayCreateCall('Списки.длина')).toBe(false);
  });

  it('Списки.пустой(ар): арена проверяется и отбрасывается, последовательность = создать()', () => {
    const сАрeной = lowerArrayCall('Списки.пустой', [reg(7)], 3, ОСНОВАНИЕ);
    const канон = lowerArrayCall('система.массив.создать', [], 3, ОСНОВАНИЕ);
    expect(сАрeной.map((команда) => команда.mnemonic)).toEqual(
      канон.map((команда) => команда.mnemonic),
    );
    expect(() => lowerArrayCall('Списки.пустой', [], 3, ОСНОВАНИЕ)).toThrow(
      /Списки\.пустой.*по D43 1.*арена/,
    );
  });

  it('Списки.длина(л) = система.массив.длина(л)', () => {
    const список = lowerArrayCall('Списки.длина', [reg(1)], 4, ОСНОВАНИЕ);
    const канон = lowerArrayCall('система.массив.длина', [reg(1)], 4, ОСНОВАНИЕ);
    expect(список.map((команда) => команда.mnemonic)).toEqual(
      канон.map((команда) => команда.mnemonic),
    );
  });

  it('Списки.добавить: movtd в приёмник, затем та же запись, что добавить', () => {
    const добавление = lowerArrayCall('Списки.добавить', [reg(1), reg(2), reg(3)], 5, ОСНОВАНИЕ);
    const канон = lowerArrayCall('система.массив.добавить', [reg(1), reg(2)], 5, ОСНОВАНИЕ);
    expect(добавление[0]?.mnemonic).toBe('movtd');
    expect(добавление[0]?.operands).toEqual([reg(1), reg(5)]);
    expect(добавление.slice(1).map((команда) => команда.mnemonic)).toEqual(
      канон.map((команда) => команда.mnemonic),
    );
    // Без арены — не «добавить с двумя», а названный отказ D43.
    expect(() => lowerArrayCall('Списки.добавить', [reg(1), reg(2)], 5, ОСНОВАНИЕ)).toThrow(
      /Списки\.добавить.*по D43 3.*список, элемент, арена/,
    );
  });

  it('Списки.взять — отказ по имени (пара Результат, D49), не получить', () => {
    expect(() => lowerArrayCall('Списки.взять', [reg(1), reg(2)], 5, ОСНОВАНИЕ)).toThrow(
      ArrayRuntimeRefusal,
    );
    expect(() => lowerArrayCall('Списки.взять', [reg(1), reg(2)], 5, ОСНОВАНИЕ)).toThrow(
      /Результат.*D49.*D4/,
    );
  });
});
