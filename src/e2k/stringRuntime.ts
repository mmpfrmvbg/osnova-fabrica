/** Байты строки в UTF-8. */
export function utf8Bytes(text: string): number[] {
  return [...Buffer.from(text, 'utf-8')];
}

/**
 * ДЛИНА В КОДОВЫХ ТОЧКАХ по байтам: продолжение — `0b10xxxxxx`.
 *
 * Это тот же проход, что делает код на цели (`stringLengthInstructions`), только собранный заранее.
 * Он нужен для проверок и для отчёта: сравнивать «сколько насчитал код» с «сколько должно быть»
 * обязан независимый счёт, иначе ошибка в кодогенерации останется незамеченной.
 */
export function codePointCount(bytes: readonly number[]): number {
  let count = 0;
  for (const byte of bytes) {
    if ((byte & 0xc0) !== 0x80) count += 1;
  }
  return count;
}

/** Таблица продолжений: 1 там, где байт — продолжение (`0b10xxxxxx`). */
export function continuationTable(): number[] {
  return Array.from({ length: STRING_TABLE_BYTES }, (_, byte) => ((byte & 0xc0) === 0x80 ? 1 : 0));
}

/**
 * ПОСЧИТАТЬ КОДОВЫЕ ТОЧКИ КОДОМ: `длина(строка)`, развёрнутая по числу байт.
 *
 * Счёт начинается с ЧИСЛА БАЙТОВ (оно известно на сборке) и уменьшается на единицу за каждый байт
 * продолжения — так «сколько кодпоинтов» получается без ветвлений.
 *
 * @param options.base регистр, в котором лежит АДРЕС байтов строки
 * @param options.byteLength сколько байт у этой строки (известно на сборке)
 * @param options.destination регистр результата
 * @param options.tableAddress адрес таблицы продолжений в образе
 */
export function stringLengthInstructions(options: {
  readonly base: number;
  readonly byteLength: number;
  readonly destination: number;
  readonly tableAddress: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const instructions: AsmInstruction[] = [
    a('movts', [imm(options.byteLength), reg(options.destination)]),
    a('movtd', [literal(options.tableAddress), reg(r.base)]),
    a('movts', [imm(0), reg(r.first)]),
  ];
  for (let index = 0; index < options.byteLength; index++) {
    instructions.push(
      // Читаем байт по текущему смещению, затем признак продолжения ИЗ ТАБЛИЦЫ (смещение — сам байт).
      a('ldb', [reg(options.base), reg(r.first), reg(r.second)], 0),
      a('ldb', [reg(r.base), reg(r.second), reg(r.write)], 0),
      // Кодпоинтов = байтов − продолжений.
      a('subs', [reg(options.destination), reg(r.write), reg(options.destination)]),
      a('adds', [reg(r.first), imm(1), reg(r.first)]),
    );
  }
  instructions.push(
    // Постоянные рантайма массивов возвращаются: ноль — на место, единица — на место.
    a('movts', [imm(0), reg(ARRAY_REGISTERS.zero)]),
    a('movts', [imm(1), reg(ARRAY_REGISTERS.one)]),
  );
  return instructions;
}

/**
 * РАЗМЕР ЗАПИСИ ТАБЛИЦЫ КОДОВ: восемь байт на кодпоинт.
 *
 * Почему восемь, а не два или четыре:
 *
 * * **Восемь — потому что читает `ldd`** (загрузка двойного слова): её форма в таблице раскладки уже
 *   есть (`printCommandForm`), а команда `muls` с литералом этой оболочкой не кодируется вовсе
 *   (замер: «литерал в длинной форме (ALS + ALES) не реализован»). Запись на восемь байт позволяет
 *   собрать смещение тремя удвоениями (`adds x, x, x`), не заводя новых форм.
 * * **Не два байта** (как у первой редакции этой таблицы): двух байт хватает только до U+FFFF, и
 *   эмодзи («🙂» = U+1F642) на цели отказали бы, тогда как VM их считает. Таблица на восемь байт
 *   вмещает любую кодовую точку Unicode — и расхождения «VM умеет, цель отказывает» не возникает.
 */
export const STRING_SYMBOL_ENTRY_BYTES = 8;

/**
 * СКОЛЬКО УДВОЕНИЙ СОБИРАЮТ СМЕЩЕНИЕ ЗАПИСИ: восемь байт — это три удвоения (`2³ = 8`).
 *
 * **Замер, а не догадка:** индекс `ldd` — БАЙТОВОЕ СМЕЩЕНИЕ, масштаба по размеру команды у неё нет.
 * Проба `.tmp/osnova-ldd-scale-probe.ts` (таблица `[0x61][0x430]`, читается запись 1): индекс 0 → 97
 * (запись 0), индекс 1 → **0** (байт со смещения 1), индекс 8 → **48** (младший байт записи 1). То
 * есть «номер записи» и «смещение» — РАЗНЫЕ вещи, и вторая редакция этой развёртки читала не то;
 * на нечётном смещении модель вставала исключением выравнивания.
 */
const STRING_SYMBOL_DOUBLINGS = 3;

/**
 * НА СКОЛЬКО СДВИГАТЬ, ЧТОБЫ ПРОЧИТАТЬ ЗНАК: тридцать один.
 *
 * Арифметика цели здесь **32-битная** (у 64-битных команд свой суффикс — `addd`/`subd`), и это
 * измерено, а не выведено из имени: `movts −3; shrs 31` даёт 1 — то есть сдвигается 32-битное
 * `0xFFFFFFFD`, а не 64-битное значение (`docs/hardware-debt.md` §3.133).
 */
const STRING_SIGN_SHIFT = 31;

/**
 * ТАБЛИЦА КОДОВ СТРОКИ: по восемь байт на кодпоинт, младшим байтом вперёд (порядок цели).
 *
 * Почему таблица, а не разбор UTF-8 в рантайме: строки на цели СТАТИЧЕСКИЕ, и «какой код у k-го
 * кодпоинта» — свойство ЗНАЧЕНИЯ, известное на сборке ровно так же, как его длина в байтах. Таблица
 * продолжений (`continuationTable`) устроена так же: её тоже считает сборка, а читает рантайм.
 * Индекс при этом остаётся РАНТАЙМОВЫМ — выбирает рантайм, а не подставляет готовый ответ.
 *
 * Когда появятся строки из памяти (сегодня их нет: третий источник строк — это работа с файлами),
 * таблицу придётся заменить разбором байтов: у неизвестных на сборке байтов таблицы быть не может.
 */
export function symbolTableBytes(text: string): number[] {
  return symbolTableBytesOf(utf8Bytes(text));
}

/**
 * КОДОВЫЕ ТОЧКИ ИЗ БАЙТОВ UTF-8 — разбор НА СБОРКЕ (обратная сторона `utf8Bytes`).
 *
 * Нужен там, где текста значения уже нет, а байты есть: у склейки ключ значения составной
 * (`первая\u0000вторая`), а байты — настоящие. Поэтому коды берутся из байтов, а не из ключа.
 */
export function codePointsOfBytes(bytes: readonly number[]): number[] {
  const points: number[] = [];
  for (let at = 0; at < bytes.length; ) {
    const first = bytes[at]!;
    if ((first & 0x80) === 0) {
      points.push(first);
      at += 1;
      continue;
    }
    const length = (first & 0xe0) === 0xc0 ? 2 : (first & 0xf0) === 0xe0 ? 3 : 4;
    let code = first & (0xff >> (length + 1));
    for (let offset = 1; offset < length; offset++) code = (code << 6) | ((bytes[at + offset] ?? 0) & 0x3f);
    points.push(code);
    at += length;
  }
  return points;
}

/** Та же таблица кодов, но по БАЙТАМ значения (см. {@link codePointsOfBytes}). */
export function symbolTableBytesOf(bytes: readonly number[]): number[] {
  const table: number[] = [];
  for (const point of codePointsOfBytes(bytes)) {
    // Старшие четыре байта записи — НУЛИ: кодовая точка Unicode не выходит за 21 бит. Сдвиг больше
    // 31 в JavaScript заворачивается по модулю 32 (`1072 >> 32` = 1072), поэтому нули пишутся явно,
    // а не «сдвигом, который и так даст ноль» — это и был бы скрытый повтор младших байтов.
    for (let at = 0; at < STRING_SYMBOL_ENTRY_BYTES; at++) table.push(at < 4 ? (point >> (8 * at)) & 0xff : 0);
  }
  return table;
}

/**
 * КОД СИМВОЛА ПО ИНДЕКСУ: `символ(строка, индекс)` — без ветвлений, без разбора UTF-8.
 *
 * # Что делает последовательность
 *
 * 1. **Границы без ветвления.** `в границах = (индекс < кодпоинтов) и (индекс >= 0)` собирается из
 *    ДВУХ логических сдвигов (см. «почему логический»): `(индекс >= кодпоинтов)` — знак от
 *    `кодпоинтов − индекс − 1`, `(индекс < 0)` — знак самого индекса, `в границах = 1 − оба`.
 * 2. **Безопасный индекс:** `индекс · в границах` — при выходе за границу это ноль, и чтение
 *    таблицы остаётся внутри её памяти. Это не «мягкая обработка»: ответ ниже всё равно −1.
 * 3. **Смещение записи:** номер кодпоинта × 8 тремя удвоениями (`ldd` масштаба не имеет — замер
 *    `.tmp/osnova-ldd-scale-probe.ts`: индекс — БАЙТОВОЕ смещение).
 * 4. **Одно чтение таблицы** (`ldd`) по этому смещению.
 * 5. **Вне границ — `−1`**: `код·в границах + в границах − 1`. В границах это код, вне — −1, и
 *    никакое законное значение кода с −1 не спутать (коды неотрицательны). У VM на этот случай
 *    НАЗВАННЫЙ ОТКАЗ; у цели исключений нет, и разница записана (§3.133).
 *
 * # Почему ЗНАК берётся логическим сдвигом, а не арифметическим
 *
 * Замер `.tmp/osnova-symbol-micro-probe.ts`: `movts −3; shrs %b[9], 31, %b[10]` даёт **1**, а не −1.
 * То есть `shrs` этой оболочки заполняет нулями, и «взять знак сдвигом» негодно: прежняя редакция
 * считала `в границах` через знак и получала −1 вместо 1 — в границах отвечала мусором, а вне границ
 * «случайно верно». Разница видна только на различающей паре (индекс в границах и вне), поэтому и
 * записана замером. Сам знак берётся **соглашением**: `x ≥ 0` ⟺ `x >>> 31 = 0`, `x < 0` ⟺ `1`.
 *
 * # Почему это работает на двух временных регистрах
 *
 * Свободных временных у рантайма ДВА (`%b[10]`, `%b[11]`): `%b[12]` и `%b[13]` — постоянные нуля и
 * единицы рантайма массивов, `%b[14]`/`%b[15]` не трогаются вовсе. Здесь этого хватает: пока идёт
 * чтение таблицы, заняты только `%b[11]` (смещение записи) и приёмник, а `%b[10]` (признак границ)
 * живёт через чтение — потому что склейки байтов нет вовсе (запись целиком читается одной `ldd`).
 *
 * @param options.index регистр индекса: только ЧИТАЕТСЯ (в нём может лежать живая переменная)
 * @param options.destination регистр-приёмник
 * @param options.codePoints сколько кодпоинтов в строке (= число записей таблицы)
 * @param options.tableAddress адрес таблицы кодов в образе
 */
export function stringSymbolInstructions(options: {
  readonly index: number;
  readonly destination: number;
  readonly codePoints: number;
  readonly tableAddress: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const one = ARRAY_REGISTERS.one;
  return [
    // ЕДИНИЦА — СВОЯ, А НЕ ЧУЖАЯ ПОСТОЯННАЯ (шаг 2.3, случай 73). Прежде последовательность ЧИТАЛА
    // `%b[13]` как единицу рантайма массивов, и это верно ТОЛЬКО в плоскости точки входа: там единицу
    // ставит пролог образа. В плоскости ВЫЗЫВАЕМОЙ пролог ставит только НОЛЬ (`%b[12]`, §3.166 —
    // носитель `IR.callee_zero`), а `%b[13]` — обычная клетка её бюджета, и чтение «единицы» взяло бы
    // значение программы. Поэтому единица ставится ЗДЕСЬ, до первого использования: в плоскости входа
    // это тождественная запись (там уже 1), в плоскости вызываемой — единственный способ её иметь.
    // Форма от плоскости не зависит (§3.135): список команд один и тот же.
    a('movts', [imm(1), reg(one)]),
    // ГРАНИЦЫ: `в границах` собирается в `%b[10]`, безопасный индекс — в `%b[11]`.
    a('subs', [imm(options.codePoints), reg(options.index), reg(r.first)]),
    a('subs', [reg(r.first), reg(one), reg(r.first)]),
    a('shrs', [reg(r.first), imm(STRING_SIGN_SHIFT), reg(r.first)]),
    a('shrs', [reg(options.index), imm(STRING_SIGN_SHIFT), reg(r.second)]),
    a('adds', [reg(r.first), reg(r.second), reg(r.first)]),
    a('subs', [reg(one), reg(r.first), reg(r.first)]),
    a('muls', [reg(options.index), reg(r.first), reg(r.second)]),
    // СМЕЩЕНИЕ ЗАПИСИ: номер кодпоинта × 8 — тремя удвоениями (у `ldd` масштаба нет, см. выше).
    ...Array.from({ length: STRING_SYMBOL_DOUBLINGS }, () => a('adds', [reg(r.second), reg(r.second), reg(r.second)])),
    // ЧТЕНИЕ: база — приёмник, индекс — БАЙТОВОЕ СМЕЩЕНИЕ записи.
    a('movtd', [literal(options.tableAddress), reg(options.destination)]),
    a('ldd', [reg(options.destination), reg(r.second), reg(options.destination)]),
    // ВНЕ ГРАНИЦ — `−1`; в границах — сам код.
    a('muls', [reg(options.destination), reg(r.first), reg(options.destination)]),
    a('adds', [reg(options.destination), reg(r.first), reg(options.destination)]),
    a('subs', [reg(options.destination), reg(one), reg(options.destination)]),
  ];
}

/**
 * ДЕСКРИПТОР СТРОКИ: ЗНАЧЕНИЕ, КОТОРОЕ СБОРКЕ НЕ ИЗВЕСТНО, ЧИТАЕТСЯ ИЗ ПАМЯТИ (TD-0001).
 *
 * ═══ ЗАЧЕМ ═════════════════════════════════════════════════════════════════════════════════════════
 *
 * Шаг 2.3 берёт СТРОКОВОСТЬ из объявленного типа параметра, но длину и таблицу кодов — из
 * доказательства: все прямые сайты вызова обязаны передать одну и ту же известную строку. Параметр,
 * которому РАЗНЫЕ сайты передают РАЗНЫЕ строки, отказывал по имени. Приказ владельца 2026-11-05 —
 * снять этот отказ (TD-0001): «значение Строка-параметра известно рантайму».
 *
 * ═══ ПОЧЕМУ НЕ ПРОХОД ПО БАЙТАМ, ХОТЯ ПРИКАЗ БЫЛ О НЁМ ═════════════════════════════════════════════
 *
 * Проход по байтам требует ПЕРЕХОДА ВНУТРИ последовательности, а его негде взять — это замер, а не
 * оценка:
 *
 * * раскладка размещает только носители `IR.*`; голая команда без носителя не размещается;
 * * байтового шага среди носителей НЕТ (`IR.load` — это `ldd`, восемь байт), сдвига и маски — тоже;
 * * байтовый шаг выразим только ВНУТРИ составного носителя, а составной носитель строит свои команды
 *   сам и внутреннего перехода выразить не может: переходы существуют ТОЛЬКО как носители;
 * * значит, цикл требует НОВОГО носителя — правки `src/e2k/twoPassLayout.ts`, которые границами атома
 *   закрыты («только `src/e2k/**`» здесь означает «стену раскладки не трогать»: она держит закреплённые
 *   числа пяти ядер и корпус).
 *
 * Вместо прохода сделана выборка O(1) БЕЗ ветвлений: ПЕРЕД байтами каждой статической строки лежит
 * дескриптор из двух восьмибайтовых слов.
 *
 * ═══ ФОРМАТ (он же — договор между раскладкой статики и рантаймом) ═════════════════════════════════
 *
 * ```
 *   адрес байтов строки A (8-кратный):
 *     [A − 16]  слово 0: число КОДПОИНТОВ строки
 *     [A −  8]  слово 1: адрес ТАБЛИЦЫ КОДОВ этой строки (0 — таблицы нет)
 *     [A      ]  байты строки в UTF-8
 * ```
 *
 * Почему ровно так: адрес значения рантайм и так получает (Строка на цели — АДРЕС её байтов, ABI не
 * менялся), поэтому «значение» приходит ДАННЫМИ, а не из сборки, и специализация на каждый сайт не
 * нужна. Выравнивание на восемь обязательно: слова читает `ldd`, а она требует кратности восьми (замер
 * §3.133: невыровненная таблица — исключение выравнивания и таймаут модели).
 *
 * ═══ ГРАНИЦА МЕХАНИЗМА ═══════════════════════════════════════════════════════════════════════════════
 *
 * Дескриптор есть только у БЛОБА, лежащего в статике. У значения, собранного в рантайме (склейка в
 * буфере или в арене, нагрузка пары), его нет — читать `addr − 16` там значило бы читать чужие байты.
 * Поэтому конвейер включает этот путь ТОЛЬКО там, где КАЖДЫЙ сайт вызова передаёт литерал из пула
 * (`src/e2k/stringPlan.ts`); во всех прочих случаях остаётся названный отказ.
 */
export const STRING_DESCRIPTOR_BYTES = 16;

/**
 * ПОМЕТКА НОСИТЕЛЯ «ЗНАЧЕНИЕ ВОЗЬМИ ИЗ ДЕСКРИПТОРА».
 *
 * Числа байтов, кодпоинтов и адреса таблицы неотрицательны, поэтому −1 не может быть настоящей
 * пометкой. Ноль вместо «нет пометки» не годится: тогда исчезла бы разница между «сборка не смогла» и
 * «сборка решила», и отказ «носитель не несёт длину» перестал бы что-либо ловить.
 */
export const STRING_DESCRIPTOR_MARK = -1;

/**
 * СЛОВА ДЕСКРИПТОРА: байты для статики (`['адрес' − 16, 'адрес')`), МЛАДШИМ БАЙТОМ ВПЕРЁД.
 *
 * Порядок тот же, что у таблицы кодов ({@link symbolTableBytesOf}): цель читает слова `ldd`, а она на
 * этой оболочке читает младшим байтом вперёд — проверено таблицей кодов (замер §3.133).
 *
 * ═══ ЛОВУШКА, НА КОТОРОЙ СТОЯЛА ПЕРВАЯ РЕДАКЦИЯ (замер 2026-11-05) ════════════════════════════════
 *
 * Сдвиг на 32 и больше в JavaScript **не сдвигает, а ЗАВОРАЧИВАЕТ** по модулю 32: `3 >>> 32` — это
 * `3`, а не ноль. Первая редакция писала слово циклом `word >>> (8 * at)`, и четырёхбайтовое число
 * ложилось в ОБЕ половины восьмибайтового слова:
 *
 *   слово 0: 02 00 00 00 02 00 00 00   ← число кодпоинтов, повторённое
 *   слово 1: FA FF 10 00 FA FF 10 00   ← адрес таблицы, повторённый
 *
 * Это не рассуждение, а прочитанные байты образа (`.tmp/td1-дескриптор-байты.ts`). Цена: `ldd`
 * приносил длину `0x2_00000002` вместо `2`, а адрес таблицы — `0x10FFFA_00000000` вместо `0x10FFFA`,
 * то есть код символа читал память по чужому (нулевому) адресу. Проба длины при этом **печатала
 * верное `2`**: печать на цели отдаёт ТОЛЬКО младшие 32 разряда (§3.43), и мусор в старших через неё
 * невидим вовсе. Отсюда правило: у этого механизма младшая половина слова — не доказательство, и
 * стеречь его обязан не вывод печати, а ГРАНИЦА (`с[н]` при недоказанном значении: мусор в числе
 * кодпоинтов пропустил бы индекс за конец строки и вернул бы чужой код вместо −1).
 *
 * Пишутся нули ЯВНО (`at < 4`), как и у {@link symbolTableBytesOf}: это тот же дефект, названный там
 * двумя экранами выше, — и повторённый здесь.
 */
export function stringDescriptorBytes(count: number, tableAddress: number): number[] {
  const bytes: number[] = [];
  for (const word of [count, tableAddress]) {
    for (let at = 0; at < STRING_SYMBOL_ENTRY_BYTES; at++) {
      // ЗНАЧЕНИЯ — 32-битные (адрес образа и счёт кодпоинтов вне 32 разрядов не выходят): старшие
      // четыре байта слова — НУЛИ, и пишутся они именно нулями, а не «сдвигом, который и так даст ноль».
      bytes.push(at < 4 ? Math.floor(word / 2 ** (at * 8)) % 256 : 0);
    }
  }
  return bytes;
}

/**
 * ДЛИНА В КОДПОИНТАХ — ИЗ ДЕСКРИПТОРА (шесть команд, без ветвлений и без чтения байтов).
 *
 * Прежний путь ({@link stringLengthInstructions}) считает кодпоинты на СБОРКЕ: он разворачивает по
 * одной команде на каждый байт и потому требует известной длины. Здесь известно только то, что по
 * адресу лежит строка: число кодпоинтов приходит из её дескриптора.
 *
 * Почему шестнадцать кладётся `movts`, а не вычитается литералом: `subs` с литералом больше 15
 * раскладка считает ВОСЬМЬЮ байтами, а кодировщик — шестнадцатью (`printCall.ts` берёт размер `subs`
 * по мнемонике, а `e2k-real.ts` — по значению литерала). Это расхождение в этом механизме
 * недопустимо: у `movts` размер считается по значению (`immediateSize`), и обе стороны сходятся.
 *
 * @param options.base регистр, в котором лежит АДРЕС байтов строки (только читается)
 * @param options.destination регистр результата — число кодпоинтов
 */
export function stringLengthFromDescriptorInstructions(options: {
  readonly base: number;
  readonly destination: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const zero = ARRAY_REGISTERS.zero;
  return [
    // ШЕСТНАДЦАТЬ — в `%b[13]` (своя единица ставится последней; здесь это просто число).
    a('movts', [imm(STRING_DESCRIPTOR_BYTES), reg(ARRAY_REGISTERS.one)]),
    // АДРЕС ДЕСКРИПТОРА: `%b[10] = адрес − 16`.
    a('subs', [reg(options.base), reg(ARRAY_REGISTERS.one), reg(r.first)]),
    // СМЕЩЕНИЕ ЧТЕНИЯ — ноль (`ldd` складывает базу и индекс; смещения в команде не нужно).
    a('movts', [imm(0), reg(zero)]),
    a('ldd', [reg(r.first), reg(zero), reg(options.destination)]),
    // ПОСТОЯННЫЕ РАНТАЙМА МАССИВОВ ВОЗВРАЩАЮТСЯ: ноль — на место, единица — на место.
    a('movts', [imm(0), reg(zero)]),
    a('movts', [imm(1), reg(ARRAY_REGISTERS.one)]),
  ];
}

/**
 * КОД СИМВОЛА ПО ИНДЕКСУ — ИЗ ДЕСКРИПТОРА: длина и таблица приходят из памяти, индекс — рантаймовый.
 *
 * Арифметика границ и чтения — ТА ЖЕ, что у {@link stringSymbolInstructions} (два логических сдвига,
 * безопасный индекс, три удвоения, `−1` вне границ): здесь меняется только ОТКУДА берутся число
 * кодпоинтов и адрес таблицы. Числа кодпоинтов на сборке не знает никто, поэтому последовательность
 * одна и та же для строк любой длины (у доказанного пути она зависела от числа кодпоинтов только
 * первым `subs` с литералом).
 *
 * @param options.base регистр с адресом байтов строки (только читается)
 * @param options.index регистр индекса: только ЧИТАЕТСЯ
 * @param options.destination регистр-приёмник
 */
export function stringSymbolFromDescriptorInstructions(options: {
  readonly base: number;
  readonly index: number;
  readonly destination: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const zero = ARRAY_REGISTERS.zero;
  const one = ARRAY_REGISTERS.one;
  return [
    // ЕДИНИЦА — СВОЯ (шаг 2.3): в плоскости вызываемой `%b[13]` — обычная клетка её бюджета.
    a('movts', [imm(1), reg(one)]),
    // СМЕЩЕНИЕ ЧТЕНИЯ — ноль; шестнадцать кладётся в `%b[10]` и там же становится адресом дескриптора.
    a('movts', [imm(0), reg(zero)]),
    a('movts', [imm(STRING_DESCRIPTOR_BYTES), reg(r.first)]),
    a('subs', [reg(options.base), reg(r.first), reg(r.first)]),
    // СЛОВО 0 — число кодпоинтов (живёт в `%b[11]` до конца арифметики границ).
    a('ldd', [reg(r.first), reg(zero), reg(r.second)]),
    // СЛОВО 1 — адрес таблицы кодов; едет прямо в приёмник, как `movtd` у доказанного пути.
    a('adds', [reg(r.first), imm(STRING_SYMBOL_ENTRY_BYTES), reg(r.first)]),
    a('ldd', [reg(r.first), reg(zero), reg(options.destination)]),
    // ГРАНИЦЫ: `в границах` — в `%b[10]`, безопасный индекс — в `%b[11]`.
    a('subs', [reg(r.second), reg(options.index), reg(r.first)]),
    a('subs', [reg(r.first), reg(one), reg(r.first)]),
    a('shrs', [reg(r.first), imm(STRING_SIGN_SHIFT), reg(r.first)]),
    a('shrs', [reg(options.index), imm(STRING_SIGN_SHIFT), reg(r.second)]),
    a('adds', [reg(r.first), reg(r.second), reg(r.first)]),
    a('subs', [reg(one), reg(r.first), reg(r.first)]),
    a('muls', [reg(options.index), reg(r.first), reg(r.second)]),
    // СМЕЩЕНИЕ ЗАПИСИ: номер кодпоинта × 8 — тремя удвоениями (у `ldd` масштаба нет).
    ...Array.from({ length: STRING_SYMBOL_DOUBLINGS }, () => a('adds', [reg(r.second), reg(r.second), reg(r.second)])),
    // ЧТЕНИЕ: база — приёмник (там адрес таблицы из дескриптора).
    a('ldd', [reg(options.destination), reg(r.second), reg(options.destination)]),
    // ВНЕ ГРАНИЦ — `−1`; в границах — сам код.
    a('muls', [reg(options.destination), reg(r.first), reg(options.destination)]),
    a('adds', [reg(options.destination), reg(r.first), reg(options.destination)]),
    a('subs', [reg(options.destination), reg(one), reg(options.destination)]),
    // ПОСТОЯННЫЕ РАНТАЙМА МАССИВОВ ВОЗВРАЩАЮТСЯ.
    a('movts', [imm(0), reg(zero)]),
    a('movts', [imm(1), reg(one)]),
  ];
}

/**
 * СКЛЕЙКА: байты первой строки, затем второй — в статический буфер; адрес буфера едет в приёмник.
 *
 * Переполнение здесь не проверяется: длины статические, и решение принимает конвейер
 * ({@link concatFitsBuffer}), который обязан отказать ДО сборки образа.
 */
export function stringConcatInstructions(options: {
  readonly first: number;
  readonly second: number;
  readonly destination: number;
  readonly bufferAddress: number;
  readonly firstBytes: number;
  readonly secondBytes: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const copy = (source: number, sourceOffsetStart: number, writeOffsetStart: number, bytes: number): AsmInstruction[] => {
    const instructions: AsmInstruction[] = [
      a('movts', [imm(sourceOffsetStart), reg(r.first)]),
      a('movts', [imm(writeOffsetStart), reg(r.write)]),
    ];
    for (let index = 0; index < bytes; index++) {
      instructions.push(
        a('ldb', [reg(source), reg(r.first), reg(r.second)], 0),
        a('stb', [reg(r.second), reg(r.base), reg(r.write)], 2),
        a('adds', [reg(r.first), imm(1), reg(r.first)]),
        a('adds', [reg(r.write), imm(1), reg(r.write)]),
      );
    }
    return instructions;
  };
  return [
    a('movtd', [literal(options.bufferAddress), reg(r.base)]),
    ...copy(options.first, 0, 0, options.firstBytes),
    ...copy(options.second, 0, options.firstBytes, options.secondBytes),
    // Приёмник — АДРЕС результата (значение строки на цели — адрес её байтов).
    a('movtd', [literal(options.bufferAddress), reg(options.destination)]),
    a('movts', [imm(0), reg(ARRAY_REGISTERS.zero)]),
    a('movts', [imm(1), reg(ARRAY_REGISTERS.one)]),
  ];
}

/**
 * СКЛЕЙКА В ВЫДЕЛЕННЫЙ БЛОК: те же байты, но приёмник — АДРЕС БЛОКА, а не статический буфер.
 *
 * # Чем отличается от статической редакции — и чем НЕ отличается
 *
 * | | статическая | в блоке арены |
 * |---|---|---|
 * | откуда база записи | `movtd` адреса буфера в `%b[12]` | **регистр** с адресом блока: его положило выделение |
 * | куда едет результат | `movtd` адреса буфера | ничего: адрес уже в приёмнике выделения |
 * | постоянные рантайма массивов | возвращаются ноль и единица | возвращается только единица: ноль не тронут |
 *
 * Копирование — те же команды (`ldb`/`stb`/`adds`), потому что и работа та же. База — **регистр
 * приёмника выделения**: `%b[12]` для этого не годится, там ноль рантайма массивов, а его портить
 * и возвращать значило бы делать лишнюю работу.
 *
 * Ожидание исчерпания арены — НЕ здесь: блок выделяет и проверяет предел арена
 * (`src/e2k/arenaRuntime.ts`), и до этой последовательности управление доходит только если предел цел.
 */
export function stringArenaCopyInstructions(options: {
  readonly first: number;
  readonly second: number;
  /** Регистр-приёмник выделения: в нём лежит адрес выделенного блока. */
  readonly base: number;
  readonly firstBytes: number;
  readonly secondBytes: number;
}): AsmInstruction[] {
  const r = STRING_REGISTERS;
  const copy = (source: number, writeOffsetStart: number, bytes: number): AsmInstruction[] => {
    const instructions: AsmInstruction[] = [
      a('movts', [imm(0), reg(r.first)]),
      a('movts', [imm(writeOffsetStart), reg(r.write)]),
    ];
    for (let index = 0; index < bytes; index++) {
      instructions.push(
        a('ldb', [reg(source), reg(r.first), reg(r.second)], 0),
        a('stb', [reg(r.second), reg(options.base), reg(r.write)], 2),
        a('adds', [reg(r.first), imm(1), reg(r.first)]),
        a('adds', [reg(r.write), imm(1), reg(r.write)]),
      );
    }
    return instructions;
  };
  return [
    ...copy(options.first, 0, options.firstBytes),
    ...copy(options.second, options.firstBytes, options.secondBytes),
    // Единица рантайма массивов возвращается: смещение записи заняло её место.
    a('movts', [imm(1), reg(ARRAY_REGISTERS.one)]),
  ];
}

/**
 * ЦИКЛ КОПИРОВАНИЯ БАЙТОВ С РАНТАЙМОВОЙ ДЛИНОЙ — O(n), БЕЗ НОВЫХ НОСИТЕЛЕЙ ПАМЯТИ.
 *
 * # Зачем он, если копирование уже есть
 *
 * `stringArenaCopyInstructions` копирует РАЗВЁРТКОЙ: число байтов известно СБОРКЕ (сумма двух длин из
 * пула). Рантаймовому срезу (`подстрока` по значению, известному только в рантайме) так нельзя: длину
 * знает только цель, значит нужен ПРОХОД, а проход — это ЦИКЛ, то есть ОБРАТНЫЙ переход.
 *
 * # Почему цикл из ЭТИХ носителей и почему это граница, а не удобство
 *
 * Байтового носителя памяти в дереве НЕТ (`IR.load`/`IR.store` — восьмибайтные), а ввести его значило бы
 * тронуть семь файлов, среди них живучесть (`src/e2k/liveness.ts`) и сопоставление предикатов
 * (`src/e2k/predicatePairing.ts`) — это ВНЕ границы, названной владельцем. Поэтому:
 *
 * | шаг | чем | почему так |
 * |---|---|---|
 * | сравнение указателей | `IR.lt` | существующий носитель: раскладка знает его форму, разбор пар — его регистры |
 * | выход из цикла | `IR.jmp_if_not` | то же: сравнение и переход обязаны быть ПАРОЙ предикатов |
 * | сам байт | КОНКРЕТНЫЕ `ldb`/`stb` | их формы раскладка берёт `printCommandForm`, и в потоке они уже есть (развёртка арены) |
 * | шаг указателей | `IR.add` ×2 | существующий носитель |
 * | назад и за цикл | `IR.jmp` ×2 | существующий носитель; абсолютные индексы считает хвост потока |
 *
 * # ГДЕ ОН ЖИВЁТ И ПОЧЕМУ ИМЕННО ТАМ (то же, что у цикла коллекций)
 *
 * ВНУТРИ одного носителя цикл невыразим: цели переходов у нас — АБСОЛЮТНЫЕ индексы потока, и считает их
 * `src/e2k/procedureCall.ts#expandCarriers`, а у группы носителей «своих» индексов нет. Поэтому цикл —
 * это носители В КОНЦЕ ПОТОКА: сайт кончается `IR.jmp [цикл]`, а сам цикл — `IR.jmp [продолжение]` по
 * ИСХОДНОМУ индексу носителя ЗА вызовом, чтобы пересчёт сдвинул цель вместе с потоком.
 * Прецедент — `src/e2k/collectionsRuntime.ts#collectionCopyLoopCarriers`; размер тот же (8), и это не
 * совпадение: сравнение, выход, четыре шага тела, назад, за цикл.
 *
 * # Что цикл НЕ делает (названо, чтобы не приписали)
 *
 * Не выделяет память (это сайт и арена), не знает про кодпоинты (проход «кодпоинт → байтовое смещение» —
 * отдельная работа), не восстанавливает регистры: роли приходят параметрами, и владелец клеток — сайт.
 *
 * Операнды: указатели `source`/`end` (конец — ИСКЛЮЧАЮЩИЙ), приёмник `target`, байт `byte`, единица
 * шага `one`, нулевое смещение `zero` (адресация «база + смещение»), ключ предиката `key`.
 */
export const STRING_COPY_LOOP_SIZE = 8;

export interface StringCopyLoopOptions {
  /** АБСОЛЮТНЫЙ индекс первого носителя цикла в РАЗВЁРНУТОМ хвосте потока. */
  readonly loopIndex: number;
  /** ИСХОДНЫЙ индекс носителя ЗА вызовом: пересчёт сдвинет его вместе с потоком. */
  readonly continuation: number;
  readonly source: number;
  readonly end: number;
  readonly target: number;
  readonly byte: number;
  readonly one: number;
  readonly zero: number;
  readonly key: number;
}

/**
 * Носители цикла копирования — ВОСЕМЬ, ровно как у коллекций (см. таблицу в шапке).
 *
 * Контроль длины здесь не украшение: по `loopIndex + STRING_COPY_LOOP_SIZE - 1` строится цель выхода, и
 * разойдись счёт с телом — выйдет переход В СЕРЕДИНУ цикла (класс §3.35).
 *
 * РОЛИ ПРОВЕРЯЮТСЯ ПО ИМЕНИ И ПО ГРАНИЦЕ РЕГИСТРОВОГО ФАЙЛА. Почему это здесь, а не в типах: тип
 * ловит пропущенную роль только у вызова из TypeScript, а вызов из JS/дата-файла проходит молча и
 * даёт операнд `{kind:'reg'}` **без номера** — замер 2026-11-06 показал, что такой поток доезжает до
 * раскладки и та молча переназначает клетки (`.tmp/string-copy-loop-трасса.ts`). Номер проверяется по
 * `BASE_REGISTER_COUNT` (`src/e2k/e2k-real.ts`) — той же границе, по которой отказывает кодировщик,
 * иначе `%b[999]` прошёл бы молча и уехал в байты как чужая клетка.
 */
export function stringCopyLoopCarriers(options: StringCopyLoopOptions): AsmInstruction[] {
  const { loopIndex, continuation } = options;
  const роли: readonly (readonly [string, number])[] = [
    ['source', options.source],
    ['end', options.end],
    ['target', options.target],
    ['byte', options.byte],
    ['one', options.one],
    ['zero', options.zero],
    ['key', options.key],
  ];
  for (const [имя, клетка] of роли) {
    if (!Number.isInteger(клетка)) {
      throw new StringRuntimeRefusal(
        `роль цикла «${имя}» не задана числом (${String(клетка)}) — клетка не выбрана, и операнд уехал бы ` +
          'в поток без номера; цикл копирования требует ВСЕ семь клеток по имени',
      );
    }
    if (клетка < 0 || клетка >= BASE_REGISTER_COUNT) {
      throw new StringRuntimeRefusal(
        `роль цикла «${имя}» = %b[${String(клетка)}] вне 0..${String(BASE_REGISTER_COUNT - 1)} — базовых ` +
          `регистров ${String(BASE_REGISTER_COUNT)} (E2K_RF_GLOB_IDX_MAX); такой номер кодировщик отверг бы ` +
          'позже и не там, а раскладка успела бы переназначить клетку',
      );
    }
  }
  for (const [имя, индекс] of [
    ['loopIndex', loopIndex],
    ['continuation', continuation],
  ] as const) {
    if (!Number.isInteger(индекс) || индекс < 0) {
      throw new StringRuntimeRefusal(
        `${имя} = ${String(индекс)} — не неотрицательный индекс носителя: переход ушёл бы в середину ` +
          'команды или за поток (класс §3.35)',
      );
    }
  }
  if (options.zero !== ARRAY_REGISTERS.zero) {
    throw new StringRuntimeRefusal(
      `клетка нуля цикла = %b[${String(options.zero)}], а байтовые носители адресуют смещение из ` +
        `%b[${String(ARRAY_REGISTERS.zero)}] (впаяно в форму): с чужим нулём чтение ушло бы по чужому адресу`,
    );
  }
  const loop: AsmInstruction[] = [
    // «источник < конец?» — сравниваются УКАЗАТЕЛИ, а не счётчик: операции «сколько осталось» у нас нет,
    // а указатель конца сайт считает один раз, до входа в цикл.
    a('IR.lt', [reg(options.key), reg(options.source), reg(options.end)]),
    // Скопировано всё — на ПОСЛЕДНИЙ носитель цикла, а он уже ведёт за цикл. Так у петли ОДИН выход, и
    // он не «проваливается» в область блоков отказа (у коллекций та же причина).
    a('IR.jmp_if_not', [reg(options.key), imm(loopIndex + STRING_COPY_LOOP_SIZE - 1)]),
    // БАЙТОВЫЕ НОСИТЕЛИ, А НЕ СЫРЫЕ `ldb`/`stb`: сырая команда не носитель IR, и раскладка её не
    // размещает («не носитель IR: раскладка идёт по потоку носителей оболочки») — сайт собирался бы
    // молча короче, а цели переходов уехали бы. Смещение впаяно в форму носителя и берётся из клетки
    // нуля — потому роль `zero` обязана быть ИМЕННО этой клеткой.
    a('IR.load_byte', [reg(options.source), reg(options.byte)]),
    a('IR.store_byte', [reg(options.byte), reg(options.target)]),
    a('IR.add', [reg(options.source), reg(options.source), reg(options.one)]),
    a('IR.add', [reg(options.target), reg(options.target), reg(options.one)]),
    a('IR.jmp', [imm(loopIndex)]),
    a('IR.jmp', [imm(continuation)]),
  ];
  if (loop.length !== STRING_COPY_LOOP_SIZE) {
    throw new StringRuntimeRefusal(
      `цикл копирования строки длиной ${String(loop.length)}, а счёт обещает ` +
        `${String(STRING_COPY_LOOP_SIZE)} — цели переходов хвоста потока считались бы неверно`,
    );
  }
  return loop;
}

/**
 * СТОРОЖ ВЫБОРА РОЛЕЙ САЙТОМ (владелец, D24): каждая клетка цикла обязана быть либо в полосе, которую
 * раскладка не отдаёт НИКОГДА (`src/e2k/regAlloc.ts#RESERVED_REGISTERS`), либо объявлена сайтом в
 * `reserved` (`regAlloc.reserved`, механизм `collectionReservedRegisters`).
 *
 * Почему именно так, и почему «объявлено» — не то же самое, что «закреплено»: замер 2026-11-06 показал,
 * что `reserved` **вызывает** перенос значения из клетки, а не предотвращает его (`.tmp/string-copy-loop-трасса.ts`:
 * записанные 8/10/11/14 → 0/1/2/3, читаемые 9/12/13 не тронуты). Поэтому объявление — половина дела, а
 * вторая половина — цикл вставляется ПОСЛЕ раскладки (D24), и это проверяет {@link checkStringCopyLoopCells}.
 */
export function checkStringCopyLoopRoles(
  options: StringCopyLoopOptions,
  reserved: readonly number[],
): void {
  const роли: readonly (readonly [string, number])[] = [
    ['source', options.source],
    ['end', options.end],
    ['target', options.target],
    ['byte', options.byte],
    ['one', options.one],
    ['zero', options.zero],
    ['key', options.key],
  ];
  const внеПолосы = роли.filter(
    ([, клетка]) => !RESERVED_REGISTERS.includes(клетка) && !reserved.includes(клетка),
  );
  if (внеПолосы.length > 0) {
    throw new StringRuntimeRefusal(
      'клетки цикла копирования не закреплены: ' +
        внеПолосы.map(([имя, клетка]) => `«${имя}» = %b[${String(клетка)}]`).join(', ') +
        ` — вне полосы ${RESERVED_REGISTERS.map((клетка) => `%b[${String(клетка)}]`).join('/')} и не объявлены ` +
        'в reserved; раскладка отдала бы их значениям программы',
    );
  }
}

/**
 * СТОРОЖ СБОРКИ (владелец, D24): операнды носителей в образе обязаны СОВПАСТЬ с выбранными ролями.
 *
 * Проверка сильнее, чем «есть форма»: она сверяет поток с тем, что построил бы сам построитель по этим
 * ролям, поэтому ЛЮБОЕ переназначение клеток (раскладкой, мутацией, чужой правкой) краснит по имени.
 * Различающий контроль — в оракуле: поток, пропущенный через `allocateProgram`, даёт 0/9/1/2/12/13/3
 * вместо выбранных ролей и обязан быть отвергнут.
 */
export function checkStringCopyLoopCells(
  loop: readonly AsmInstruction[],
  options: StringCopyLoopOptions,
): void {
  const эталон = stringCopyLoopCarriers(options);
  if (loop.length !== эталон.length) {
    throw new StringRuntimeRefusal(
      `в образе ${String(loop.length)} носителей цикла копирования, а построитель строит ` +
        `${String(эталон.length)} — сверять роли не с чем`,
    );
  }
  for (const [номер, носитель] of loop.entries()) {
    const ожидаемый = эталон[номер];
    if (ожидаемый === undefined) continue;
    const получено = JSON.stringify(носитель.operands);
    const ждём = JSON.stringify(ожидаемый.operands);
    if (носитель.mnemonic !== ожидаемый.mnemonic || получено !== ждём) {
      throw new StringRuntimeRefusal(
        `носитель ${String(номер)} цикла копирования в образе не тот, что выбрал сайт: ` +
          `«${носитель.mnemonic}» ${получено}, а роли дают «${ожидаемый.mnemonic}» ${ждём} — ` +
          'клетки переназначены (цикл вставлен ДО раскладки?); копирование читало бы и портило чужие клетки',
      );
    }
  }
}


/**
 * НОРМАЛИЗАЦИЯ КРАЁВ РАНТАЙМ-СРЕЗА: ТО ЖЕ, ЧТО ДЕЛАЕТ ЭТАЛОН ЯЗЫКА, И НИЧЕГО СВЕРХ.
 *
 * # Почему отдельный блок, а не «само получится»
 *
 * Края среза приходят из рантайма (`подстрока(с, н, к)` при разных `н`/`к` на сайтах вызова), а эталон
 * `src/runtime/vm/stringUnits.ts#codePointSlice` (назван в `src/e2k/stringPlan.ts`) с ними делает ТРИ
 * вещи: отрицательный край считается ОТ КОНЦА (`length + край`), край за границей ОБРЕЗАЕТСЯ, а при
 * `к ≤ н` результат ПУСТ. Без этого `подстрока("ёжзийк", -2, 6)` дало бы не «йк», а мусор: `-2` как
 * индекс — это чтение перед блобом. Измерено: механизм нужен ОБОИМ вариантам цикла (Г и В), поэтому
 * он не «потом», а часть подключения.
 *
 * # Что здесь НЕ делается, и это названо, а не забыто
 *
 * 1. **Обрезка `к` СВЕРХУ не нужна вовсе**: конец блоба ловит ГРАНИЦА ЦИКЛА (`p < end`), а число
 *    скопированных кодпоинтов считает сам цикл (`cnt`), поэтому «к больше длины» не может соврать:
 *    замер эталона — `подстрока("ёжзийк", 0, 99)` → «ёжзийк», и цикл даёт ровно это.
 * 2. **`NaN`/`∞` не представимы в клетке**: у эталона они дают 0 и «до конца»; сюда значения приходят
 *    ЦЕЛЫМИ числами языка, и ветвь для не-чисел в рантайме не строится, потому что её нечем получить.
 * 3. **`к` не указан** («до конца») — это решение САЙТА (подстановка длины вместо `к`), а не края.
 *
 * # Числа
 *
 * Ровно {@link STRING_SLICE_EDGE_SIZE} носителей, и все они — носители IR (`IR.lt`, `IR.jmp_if_not`,
 * `IR.add`): новых форм раскладке не требуется (замер: 15/15 размещены, см. оракул
 * `src/e2k/stringSliceEdges.test.ts`). Цели переходов АБСОЛЮТНЫЕ по итоговому потоку — их считает
 * вызывающий через `baseIndex`, ровно как у цикла копирования.
 *
 * КЛЮЧ — ОДНА клетка на весь блок, и это ИЗМЕРЕНО, а не упущено: каждое сравнение ПИШЕТ клетку ключа,
 * поэтому окно живости закрывается на следующем сравнении, и разбор пар даёт 5 пар на 5 условных
 * переходов без единого отказа (`src/e2k/byteCarriers.test.ts`, `.tmp/06-02-цена-Г.ts`).
 */
export interface StringSliceEdgeOptions {
  /** Абсолютный индекс ПЕРВОГО носителя блока в итоговом потоке. */
  readonly baseIndex: number;
  /** Клетка начала среза (кодпоинты) — нормализуется НА МЕСТЕ. */
  readonly from: number;
  /** Клетка конца среза (кодпоинты) — нормализуется НА МЕСТЕ. */
  readonly to: number;
  /** Клетка ЧИСЛА КОДПОИНТОВ ИСТОЧНИКА — КОНСТАНТА СБОРКИ (источник статический, `N` известен). */
  readonly count: number;
  /** Клетка нуля — только чтение. */
  readonly zero: number;
  /** Клетка ключа: сравнение пишет, переход читает. */
  readonly key: number;
}

/** Сколько носителей занимает нормализация краёв: 5 сравнений, 5 переходов, 5 правок. */
export const STRING_SLICE_EDGE_SIZE = 15;

/**
 * Носители нормализации краёв — по порядку исполнения; цели переходов считаются от `baseIndex`.
 *
 * ```text
 *  0  key = from < 0 ?          3  key = from < 0 ?          6  key = N < from ?
 *  1  нет → 3                   4  нет → 6                   7  нет → 9
 *  2  from += N                 5  from = 0                  8  from = N
 *
 *  9  key = to < 0 ?           12  key = to < 0 ?
 * 10  нет → 12                 13  нет → 15 (за блоком)
 * 11  to += N                  14  to = 0
 * ```
 */
export function stringSliceEdgeCarriers(options: StringSliceEdgeOptions): AsmInstruction[] {
  const L = options.baseIndex;
  const шаг = (номер: number): Operand => imm(L + номер);
  const edge: AsmInstruction[] = [
    a('IR.lt', [reg(options.key), reg(options.from), reg(options.zero)]),
    a('IR.jmp_if_not', [reg(options.key), шаг(3)]),
    a('IR.add', [reg(options.from), reg(options.from), reg(options.count)]),
    // ВТОРАЯ проверка нужна: `−99` после прибавления длины всё ещё отрицательно (эталон даёт 0).
    a('IR.lt', [reg(options.key), reg(options.from), reg(options.zero)]),
    a('IR.jmp_if_not', [reg(options.key), шаг(6)]),
    a('IR.add', [reg(options.from), reg(options.zero), reg(options.zero)]),
    // ОБРЕЗКА СВЕРХУ: край за концом — это САМ конец.
    a('IR.lt', [reg(options.key), reg(options.count), reg(options.from)]),
    a('IR.jmp_if_not', [reg(options.key), шаг(9)]),
    a('IR.add', [reg(options.from), reg(options.count), reg(options.zero)]),
    a('IR.lt', [reg(options.key), reg(options.to), reg(options.zero)]),
    a('IR.jmp_if_not', [reg(options.key), шаг(12)]),
    a('IR.add', [reg(options.to), reg(options.to), reg(options.count)]),
    a('IR.lt', [reg(options.key), reg(options.to), reg(options.zero)]),
    a('IR.jmp_if_not', [reg(options.key), шаг(15)]),
    a('IR.add', [reg(options.to), reg(options.zero), reg(options.zero)]),
  ];
  if (edge.length !== STRING_SLICE_EDGE_SIZE) {
    throw new StringRuntimeRefusal(
      `нормализация краёв длиной ${String(edge.length)}, а счёт обещает ` +
        `${String(STRING_SLICE_EDGE_SIZE)} — цели переходов считались бы неверно`,
    );
  }
  return edge;
}

/**
 * ЦИКЛ КОПИРОВАНИЯ РАНТАЙМ-СРЕЗА, ВАРИАНТ Г: проход по БАЙТАМ UTF-8 с таблицей продолжений.
 *
 * # Почему Г, а не восьмёрки на кодпоинт
 *
 * Срез живёт в АРЕНЕ и копирует БАЙТЫ: `н`/`к` — номера кодпоинтов, а байтовое смещение требует
 * прохода по UTF-8 (замер и решение владельца, D26). Поэтому адрес источника и граница копии —
 * БАЙТОВЫЕ, и никаких `× 8` здесь нет; таблица продолжений (256 байт, как у `длина`) отвечает на
 * «этот байт — начало кодпоинта?» одним чтением.
 *
 * # Откуда 17 носителей, а не 16 из оценки
 *
 * В оценке (`.tmp/06-02-цена-Г.ts`) чтение признака шло СЫРОЙ `ldb [таблица, байт, признак]` —
 * у неё ТРИ операнда, и индекс стоит отдельно. Носитель `IR.load_byte` несёт ДВА операнда
 * (`[адрес, приёмник]`), а смещение у него ВПАЯНО нулём (`src/e2k/memoryAccess.ts#loadByteInstructions`
 * берёт его из клетки нуля) — значит «таблица + номер байта» надо сложить САМИМ, лишним `IR.add`.
 * Итог измерен, а не округлён: 17 носителей, и `STRING_SLICE_COPY_LOOP_SIZE` равно именно им.
 *
 * # Два выхода и один обратный переход
 *
 * ```
 *   0  key = p < end ?            9  jmp_if_not key → выход  (остаток ≤ 0)
 *   1  jmp_if_not key → выход    10  key = left ≤ 0 ?
 *   2  byte = [p]                11  jmp_if_not key → 15    (кодпоинт не наш)
 *   3  scratch = table + byte    12  [t] = byte
 *   4  flag = [scratch]          13  t += 1
 *   5  flag = 1 − flag           14  copied += flag
 *   6  rest −= flag              15  p += 1
 *   7  left −= flag              16  jmp → петля
 *   8  key = 0 < rest ?
 * ```
 *
 * ОБА выхода ведут на `continuation` — первый носитель записи дескриптора (у петли ОДИН выход, как
 * у коллекций: «провалиться» в блок отказа она не имеет права). Переходы АБСОЛЮТНЫЕ: цель внутри
 * петли (`15`) считается от `loopIndex`, а не от начала массива.
 *
 * `left` и `rest` — это те же клетки `н`/`к` ПОСЛЕ нормализации, и они же СЧЁТЧИКИ: отдельные
 * клетки под «сколько пройдено» не нужны (цена клетки — вытесненное значение программы). Поэтому
 * длину результата даёт `copied`, а не `к − н`.
 */
export const STRING_SLICE_COPY_LOOP_SIZE = 17;

export interface StringSliceCopyLoopOptions {
  /** АБСОЛЮТНЫЙ индекс первого носителя петли в итоговом потоке. */
  readonly loopIndex: number;
  /** ИСХОДНЫЙ индекс носителя, стоящего ЗА вызовом: пересчёт сдвинет его вместе с потоком. */
  readonly continuation: number;
  /** Указатель по БАЙТАМ источника (начало блоба). */
  readonly source: number;
  /** Конец БАЙТОВ источника — ИСКЛЮЧАЮЩИЙ. */
  readonly end: number;
  /** Приёмник копирования — указатель по байтам арены. */
  readonly target: number;
  readonly byte: number;
  readonly flag: number;
  /** Адрес таблицы продолжений. */
  readonly table: number;
  /** Временная клетка суммы «таблица + байт» (у `IR.load_byte` индекс впаян нулём). */
  readonly scratch: number;
  /** Клетка `н` — счётчик НЕПРОЙДЕННЫХ кодпоинтов среза. */
  readonly left: number;
  /** Клетка `к` — счётчик ОСТАВШИХСЯ кодпоинтов. */
  readonly rest: number;
  /** Счётчик СКОПИРОВАННЫХ кодпоинтов — из него берётся длина результата. */
  readonly copied: number;
  readonly one: number;
  /** Клетка нуля: ею же адресуются байтовые носители (`IR.load_byte`/`IR.store_byte`). */
  readonly zero: number;
  readonly key: number;
}

export function stringSliceCopyLoopCarriers(options: StringSliceCopyLoopOptions): AsmInstruction[] {
  const роли: readonly (readonly [string, number])[] = [
    ['source', options.source],
    ['end', options.end],
    ['target', options.target],
    ['byte', options.byte],
    ['flag', options.flag],
    ['table', options.table],
    ['scratch', options.scratch],
    ['left', options.left],
    ['rest', options.rest],
    ['copied', options.copied],
    ['one', options.one],
    ['zero', options.zero],
    ['key', options.key],
  ];
  for (const [имя, клетка] of роли) {
    if (!Number.isInteger(клетка) || клетка < 0 || клетка >= BASE_REGISTER_COUNT) {
      throw new StringRuntimeRefusal(
        `роль петли Г «${имя}» = %b[${String(клетка)}]: клетка обязана быть числом в 0..` +
          `${String(BASE_REGISTER_COUNT - 1)} — иначе операнд уехал бы в поток без номера либо кодировщик ` +
          'отверг бы его позже и не там',
      );
    }
  }
  if (options.zero !== ARRAY_REGISTERS.zero) {
    throw new StringRuntimeRefusal(
      `клетка нуля петли Г = %b[${String(options.zero)}], а байтовые носители адресуют смещение из ` +
        `%b[${String(ARRAY_REGISTERS.zero)}] (впаяно в форму, см. ` +
        '`src/e2k/memoryAccess.ts#loadByteInstructions`): с чужим нулём чтение ушло бы по чужому адресу',
    );
  }
  for (const [имя, индекс] of [
    ['loopIndex', options.loopIndex],
    ['continuation', options.continuation],
  ] as const) {
    if (!Number.isInteger(индекс) || индекс < 0) {
      throw new StringRuntimeRefusal(
        `${имя} = ${String(индекс)} — не неотрицательный индекс носителя: переход ушёл бы в середину ` +
          'команды или за поток (класс §3.35)',
      );
    }
  }
  const { loopIndex } = options;
  const пропуск = loopIndex + 15;
  const loop: AsmInstruction[] = [
    a('IR.lt', [reg(options.key), reg(options.source), reg(options.end)]),
    a('IR.jmp_if_not', [reg(options.key), imm(options.continuation)]),
    a('IR.load_byte', [reg(options.source), reg(options.byte)]),
    a('IR.add', [reg(options.scratch), reg(options.table), reg(options.byte)]),
    a('IR.load_byte', [reg(options.scratch), reg(options.flag)]),
    a('IR.sub', [reg(options.flag), reg(options.one), reg(options.flag)]),
    a('IR.sub', [reg(options.rest), reg(options.rest), reg(options.flag)]),
    a('IR.sub', [reg(options.left), reg(options.left), reg(options.flag)]),
    a('IR.le', [reg(options.key), reg(options.zero), reg(options.rest)]),
    a('IR.jmp_if_not', [reg(options.key), imm(options.continuation)]),
    a('IR.lt', [reg(options.key), reg(options.left), reg(options.zero)]),
    a('IR.jmp_if_not', [reg(options.key), imm(пропуск)]),
    a('IR.store_byte', [reg(options.byte), reg(options.target)]),
    a('IR.add', [reg(options.target), reg(options.target), reg(options.one)]),
    a('IR.add', [reg(options.copied), reg(options.copied), reg(options.flag)]),
    a('IR.add', [reg(options.source), reg(options.source), reg(options.one)]),
    a('IR.jmp', [imm(loopIndex)]),
  ];
  if (loop.length !== STRING_SLICE_COPY_LOOP_SIZE) {
    throw new StringRuntimeRefusal(
      `петля Г длиной ${String(loop.length)}, а счёт обещает ${String(STRING_SLICE_COPY_LOOP_SIZE)} — ` +
        'цели переходов и место записи дескриптора считались бы неверно',
    );
  }
  return loop;
}

/**
 * КОНСТАНТЫ СБОРКИ, которые сайту нужны в клетках (индексы ПУЛА, а не значения).
 *
 * Почему через пул: `IR.const` — ЕДИНСТВЕННЫЙ носитель, несущий значение, зависящее от сборки, и
 * раскладка берёт его длину по ЗНАЧЕНИЮ из пула (0…15 — короткая форма, 8 байт; прочее — 16),
 * заранее и без плоскости (`src/e2k/twoPassLayout.ts#carrierFormWithReason`). Адреса и число
 * кодпоинтов сайт знать не может — их кладёт план (`src/e2k/stringPlan.ts`, шаг подключения).
 */
export interface StringSliceLiterals {
  /** Индекс пула: адрес БАЙТОВ источника. */
  readonly sourceAddress: number;
  /** Индекс пула: конец байтов источника (исключающий) — адрес ИЗВЕСТЕН сборке. */
  readonly sourceEnd: number;
  /** Индекс пула: число кодпоинтов ИСТОЧНИКА (нужно нормализации краёв). */
  readonly codePoints: number;
  /** Индекс пула: адрес таблицы продолжений. */
  readonly tableAddress: number;
  /** Индекс пула: единица (коллекции затирают `%b[13]` своим ключом — рассчитывать на пролог нельзя). */
  readonly one: number;
  /** Индекс пула: шестнадцать — байт дескриптора впереди байтов. */
  readonly sixteen: number;
}

/**
 * КЛЕТКИ АРЕНЫ: их даёт `src/e2k/arenaRuntime.ts`, и берутся они ОТТУДА — своих номеров сайт не
 * заводит, иначе разошёлся бы с ареной молча.
 *
 * Из трёх клеток арены сайту доступна ОДНА (`flag` — её же пишет сравнение арены перед переходом),
 * а `pointer`/`limit` — ЖИВОЕ состояние арены на всю программу: их трогать нельзя.
 */
export interface StringSliceArenaCells {
  readonly pointer: number;
  readonly limit: number;
  readonly flag: number;
  /** Носитель блока отказа арены: куда уйти при исчерпании. */
  readonly refusalIndex: number;
}

/**
 * САЙТ РАНТАЙМ-СРЕЗА, ВАРИАНТ Г: байты, арена, нормализация краёв — ОДИН сайт, а не пять.
 *
 * Порядок исполнения:
 *   • константы сборки (адрес байтов источника, его конец, число кодпоинтов, ноль, единица, счётчик);
 *   • нормализация краёв (15 носителей) — `н`/`к` переписываются НА МЕСТЕ, поэтому копия идёт по
 *     `[н, к)` ПОСЛЕ нормализации, а не по исходным значениям;
 *   • размер выделения и ВЫДЕЛЕНИЕ В АРЕНЕ (носители арены) — результат ложится в приёмник;
 *   • адрес таблицы продолжений и указатель копирования (`target = destination`);
 *   • переход В ХВОСТ, где лежит петля (её абсолютные индексы известны только там).
 */
export interface StringSliceRuntimeSiteOptions {
  /** Клетка начала среза (кодпоинты) — нормализуется на месте и становится счётчиком `left`. */
  readonly from: number;
  /** Клетка конца среза (кодпоинты) — нормализуется на месте и становится счётчиком `rest`. */
  readonly to: number;
  /** Клетка результата — АДРЕС БАЙТОВ В АРЕНЕ (он же приёмник выделения). */
  readonly destination: number;
  /**
   * КЛЕТКА ВЫЗОВА, В КОТОРУЮ ПЕРЕНОСИТСЯ РЕЗУЛЬТАТ (шаг подключения, ATOM-06-02-02).
   *
   * Зачем отдельная роль: адрес блока живёт в ПОЛОСЕ (`destination`), потому что его пишет арена, а
   * петля двигает по нему указатель копирования; но значение, которое получила ПРОГРАММА, обязано
   * лежать в клетке вызова — её выбрала раскладка из `%b[0..9]`, и именно её читают последующие
   * `длина`/`символ`. Без переноса результат остался бы в полосе, а вызов отдал бы программе мусор.
   */
  readonly result: number;
  readonly literals: StringSliceLiterals;
  readonly cells: {
    readonly source: number;
    readonly end: number;
    readonly target: number;
    readonly byte: number;
    readonly flag: number;
    readonly table: number;
    readonly scratch: number;
    readonly copied: number;
    readonly one: number;
    readonly zero: number;
    readonly key: number;
  };
  readonly arena: StringSliceArenaCells;
  /** Абсолютный индекс ПЕРВОГО носителя петли в итоговом потоке (петля живёт в ХВОСТЕ). */
  readonly loopIndex: number;
}

/**
 * Сколько носителей занимает сайт: 6 констант сборки + 15 нормализации + 6 размера и таблицы +
 * 3 носителя арены + перенос указателя копирования + ПЕРЕНОС РЕЗУЛЬТАТА В КЛЕТКУ ВЫЗОВА + переход.
 */
export const STRING_SLICE_SITE_SIZE = 34;

export function stringSliceRuntimeSite(options: StringSliceRuntimeSiteOptions): AsmInstruction[] {
  const { cells, literals } = options;
  const site: AsmInstruction[] = [
    a('IR.const', [reg(cells.source), imm(literals.sourceAddress), imm(0)]),
    a('IR.const', [reg(cells.end), imm(literals.sourceEnd), imm(0)]),
    // ЧИСЛО КОДПОИНТОВ ИСТОЧНИКА: нужно нормализации. Клетка `table` взята под него НА ВРЕМЯ — после
    // нормализации в ней считается размер выделения, а потом ложится адрес таблицы продолжений.
    a('IR.const', [reg(cells.table), imm(literals.codePoints), imm(0)]),
    a('IR.zero', [reg(cells.zero)]),
    a('IR.const', [reg(cells.one), imm(literals.one), imm(0)]),
    a('IR.zero', [reg(cells.copied)]),
    ...stringSliceEdgeCarriers({
      baseIndex: 6,
      from: options.from,
      to: options.to,
      count: cells.table,
      zero: cells.zero,
      key: cells.key,
    }),
    // РАЗМЕР ВЫДЕЛЕНИЯ: 8 · (к − н) + 16 — по НОРМАЛИЗОВАННЫМ краям, и именно ВОСЕМЬ байт на
    // кодпоинт, а не четыре из оценки: дескриптор читается `ldd` и обязан быть выровнен на 8, а
    // арена двигает УКАЗАТЕЛЬ на размер, не округляя его. `4 · (к − н) + 16` при нечётном `к − н`
    // даёт невыровненный адрес — исключение выравнивания на цели (§3.133).
    a('IR.sub', [reg(cells.table), reg(options.to), reg(options.from)]),
    a('IR.add', [reg(cells.table), reg(cells.table), reg(cells.table)]),
    a('IR.add', [reg(cells.table), reg(cells.table), reg(cells.table)]),
    a('IR.add', [reg(cells.table), reg(cells.table), reg(cells.table)]),
    a('IR.const', [reg(cells.scratch), imm(literals.sixteen), imm(0)]),
    a('IR.add', [reg(cells.table), reg(cells.table), reg(cells.scratch)]),
    // АРЕНА: три носителя, и все три — существующие (`src/e2k/arenaRuntime.ts#arenaSiteCarriers`).
    a(ARENA_ALLOC_CARRIER_NAME, [reg(cells.table), reg(options.destination)]),
    a('IR.le', [reg(options.arena.flag), reg(options.arena.pointer), reg(options.arena.limit)]),
    a('IR.jmp_if_not', [reg(options.arena.flag), imm(options.arena.refusalIndex)]),
    a('IR.const', [reg(cells.table), imm(literals.tableAddress), imm(0)]),
    // УКАЗАТЕЛЬ КОПИРОВАНИЯ: петля двигает ТОЛЬКО его — результат обязан остаться НАЧАЛОМ байтов.
    a('IR.move', [reg(cells.target), reg(options.destination)]),
    // РЕЗУЛЬТАТ — В КЛЕТКУ ВЫЗОВА, и ДО петли: адрес блока уже окончателен (петля его не двигает),
    // а последующие `длина`/`символ` читают именно клетку вызова. Порядок «после проверки арены»
    // обязателен: до неё в клетке вызова лежал бы адрес, которого программа не увидит (отказ).
    a('IR.move', [reg(options.result), reg(options.destination)]),
    a('IR.jmp', [imm(options.loopIndex)]),
  ];
  if (site.length !== STRING_SLICE_SITE_SIZE) {
    throw new StringRuntimeRefusal(
      `сайт Г длиной ${String(site.length)}, а счёт обещает ${String(STRING_SLICE_SITE_SIZE)} — ` +
        'индекс хвоста разошёлся бы с переходом',
    );
  }
  return site;
}

/** Имя носителя выделения — ОДНО с `src/e2k/arenaRuntime.ts#ARENA_ALLOC_CARRIER` (импорт дал бы кольцо). */
const ARENA_ALLOC_CARRIER_NAME = 'IR.arena_alloc';

/**
 * НОСИТЕЛЬ РАНТАЙМ-СРЕЗА: его ставит ПЛАН вместо вызова `подстрока`, а расширяет конвейер
 * (`src/e2k/stringPlan.ts#kind: 'slice_runtime'` → `stringSliceGroups`).
 *
 * Операнды: `[н, к, приёмник вызова, sourceAddress, sourceEnd, codePoints, tableAddress, one, sixteen]`,
 * где последние шесть — ИНДЕКСЫ ПУЛА (`IR.const`). Конвейер обязан заменить его ДО раскладки байтов:
 * у самого носителя формы нет, и «нет формы» было бы отказом не по делу.
 */
export const STRING_SLICE_RUNTIME_CARRIER = 'IR.slice_runtime';

/**
 * КЛЕТКА ФЛАГА АРЕНЫ — ЧИСЛО, ПОВТОРЁННОЕ ЗДЕСЬ, а не импортированное: `src/e2k/arenaRuntime.ts`
 * импортирует отсюда имена носителей, и обратный импорт дал бы КОЛЬЦО. Совпадение с
 * `ARENA_FLAG_REGISTER` проверяется сторожем (`src/e2k/stringSliceGamma.test.ts`), а не словом.
 */
const ARENA_FLAG_CELL = 5;

/**
 * КЛЕТКИ САЙТА РАНТАЙМ-СРЕЗА — ИЗМЕРЕННЫЙ БЮДЖЕТ ОКНА (шаг подключения, ATOM-06-02-02).
 *
 * Окно — 16 клеток, и их делят ТРИ хозяина: полоса `%b[10..15]` (6, диспетчер не отдаёт их программе
 * никогда), арена (`%b[4]` указатель, `%b[5]` флаг, `%b[6]` предел) и программа (остаток). Отсюда
 * раскладка такая:
 *   • `source`/`end`/`zero`/`one`/`target` + приёмник сайта — ШЕСТЬ клеток полосы;
 *   • `flag` — клетка ФЛАГА АРЕНЫ: петля пишет её на каждом байте, а всякий сайт арены пишет её перед
 *     своим сравнением, поэтому значение ни через одну границу не переезжает (`pointer`/`limit` —
 *     ЖИВОЕ состояние, их трогать нельзя);
 *   • `copied`, `table`, `scratch` — ТРИ объявленные клетки (D24): раскладка не отдаёт их программе,
 *     иначе петля затирала бы её значения молча;
 *   • `key` — ТА ЖЕ клетка, что `scratch`: сравнение петли ложится туда, где прежнее значение
 *     (`table + byte`) уже прочитано;
 *   • `byte` — КЛЕТКА ПРИЁМНИКА (`STRING_SLICE_DESTINATION_CELL`, `%b[15]`): до петли в ней лежит адрес
 *     блока арены (его туда пишет само выделение, из неё же берут начало `target` и клетка вызова), а в
 *     петле — очередной байт. Развести их нечем: база нужна ДО петли, байт — В петле, а хвост берёт базу
 *     из КЛЕТКИ ВЫЗОВА (`options.result`), куда её переносит сайт. Это ВТОРАЯ названная пара-совпадение,
 *     и цена её названа числом: без неё программе остаётся ТРИ клетки, а рантайм-краям нужно ЧЕТЫРЕ
 *     (замер шага 5: «в тесный момент живы 4 отрезков, свободных регистров 3`).
 *
 * Первая редакция объявляла СЕМЬ клеток (свои `flag`, `byte`, `copied`, `table`, `scratch`, `key`) —
 * и это не влезало: семь объявленных плюс три арены плюс шесть полосы = все шестнадцать, программе не
 * оставалось НИ ОДНОЙ клетки. Пересчёт по факту БЮДЖЕТА ПРОГРАММЫ: три (`%b[0]`, `%b[7]`, `%b[8]`,
 * `%b[9]` — четыре свободных при трёх объявленных).
 */
export const STRING_SLICE_CELLS = {
  source: 10,
  end: 11,
  zero: ARRAY_REGISTERS.zero,
  one: 13,
  target: 14,
  byte: 15,
  copied: 1,
  table: 2,
  scratch: 3,
  key: 3,
  flag: ARENA_FLAG_CELL,
} as const;

/** ПРИЁМНИК САЙТА (адрес блока арены) — в полосе: его пишет арена, а читает петля (`target`). */
export const STRING_SLICE_DESTINATION_CELL = 15;

/**
 * ОБЪЯВЛЕННЫЕ КЛЕТКИ САЙТА — их обязан закрепить за собой тот, кто раскладывал (D24, `sliceReserved`).
 *
 * `%b[0]` в списке НЕТ намеренно: там был `byte`, а он переехал в клетку приёмника (см. карту выше).
 * Пока `%b[0]` был объявлен, программе оставалось ТРИ клетки, и раскладка отказывала КАЖДОЙ программе
 * с рантайм-краями (замер шага 5, четыре формы проб: живы 4…7 отрезков против трёх свободных).
 */
export const STRING_SLICE_DECLARED_CELLS: readonly number[] = [1, 2, 3];

/** Опции ХВОСТА: те же роли плюс место хвоста и адрес возврата за вызов. */
export interface StringSliceRuntimeTailOptions {
  readonly from: number;
  readonly to: number;
  readonly destination: number;
  readonly literals: Pick<StringSliceLiterals, 'sixteen'>;
  readonly cells: StringSliceRuntimeSiteOptions['cells'];
  /** Абсолютный индекс ПЕРВОГО носителя хвоста — он же первый носитель петли. */
  readonly loopIndex: number;
  /** Абсолютный индекс носителя, СТОЯЩЕГО ЗА ВЫЗОВОМ: хвост возвращает поток на него. */
  readonly successor: number;
  /**
   * КЛЕТКА ВЫЗОВА — та, куда сайт переносит АДРЕС БЛОКА, и ОТКУДА хвост берёт базу дескриптора.
   *
   * Почему не `destination`: приёмник (`%b[15]`) в петле занят БАЙТОМ (это вторая названная пара
   * совпадения, см. `STRING_SLICE_CELLS`), а адрес блока к этому времени уже лежит в клетке вызова —
   * сайт переносит его туда ДО петли, и ни один носитель сайта этой клетки не касается (сторож
   * `checkStringSliceRuntimeSite` требует, чтобы она не была ролью сайта).
   */
  readonly result: number;
}

/** Сколько носителей занимает хвост: петля (17), запись дескриптора (3) и возврат за вызов (1). */
export const STRING_SLICE_TAIL_SIZE = 21;

export function stringSliceRuntimeTail(options: StringSliceRuntimeTailOptions): AsmInstruction[] {
  const { cells } = options;
  const loopIndex = options.loopIndex;
  const descriptorAt = loopIndex + STRING_SLICE_COPY_LOOP_SIZE;
  const loop = stringSliceCopyLoopCarriers({
    loopIndex,
    continuation: descriptorAt,
    source: cells.source,
    end: cells.end,
    target: cells.target,
    byte: cells.byte,
    flag: cells.flag,
    table: cells.table,
    scratch: cells.scratch,
    left: options.from,
    rest: options.to,
    copied: cells.copied,
    one: cells.one,
    zero: cells.zero,
    key: cells.key,
  });
  const tail: AsmInstruction[] = [
    ...loop,
    // СЛОВО ДЛИНЫ: в дескриптор идёт СЧЁТЧИК СКОПИРОВАННЫХ КОДПОИНТОВ, а не `к − н` из клеток краёв:
    // после нормализации края переписаны НА МЕСТЕ, и разность считала бы не то. Клетка `scratch`
    // свободна после петли — в неё ложится адрес слова длины (НАЧАЛО БЛОКА минус шестнадцать), а начало
    // блока берётся из КЛЕТКИ ВЫЗОВА: приёмник после петли держит последний байт, не адрес.
    a('IR.const', [reg(cells.flag), imm(options.literals.sixteen), imm(0)]),
    a('IR.sub', [reg(cells.scratch), reg(options.result), reg(cells.flag)]),
    a('IR.store', [reg(cells.copied), reg(cells.scratch)]),
    // ЗА ВЫЗОВ — ПОСЛЕДНИЙ носитель хвоста (как у коллекций): иначе удачная копия «провалилась» бы
    // в область блоков отказа.
    a('IR.jmp', [imm(options.successor)]),
  ];
  if (tail.length !== STRING_SLICE_TAIL_SIZE) {
    throw new StringRuntimeRefusal(
      `хвост Г длиной ${String(tail.length)}, а счёт обещает ${String(STRING_SLICE_TAIL_SIZE)} — ` +
        'выход петли ушёл бы мимо записи дескриптора',
    );
  }
  return tail;
}

/**
 * СТОРОЖ САЙТА Г: клетки, приёмник в полосе, ноль байтовых носителей и неприкосновенность арены.
 *
 * Каждая проверка — измеренный класс порчи:
 *   • клетка вне полосы и без объявления — раскладка отдала бы её значениям программы (D24);
 *   • `zero` не та клетка, из которой байтовые носители берут смещение, — чтение ушло бы по чужому
 *     адресу (смещение впаяно в форму);
 *   • приёмник ВНЕ полосы `%b[10..15]` — результат уехал бы в клетку программы;
 *   • роль совпала с `pointer`/`limit` арены — живое состояние арены было бы испорчено;
 *   • две роли в одной клетке — молчаливая потеря одного из значений.
 */
export function checkStringSliceRuntimeSite(
  options: StringSliceRuntimeSiteOptions,
  reserved: readonly number[],
): void {
  const роли: readonly (readonly [string, number])[] = [
    ['source', options.cells.source],
    ['end', options.cells.end],
    ['target', options.cells.target],
    ['byte', options.cells.byte],
    ['flag', options.cells.flag],
    ['table', options.cells.table],
    ['scratch', options.cells.scratch],
    ['copied', options.cells.copied],
    ['one', options.cells.one],
    ['zero', options.cells.zero],
    ['key', options.cells.key],
    ['from', options.from],
    ['to', options.to],
    ['destination', options.destination],
  ];
  for (const [имя, клетка] of роли) {
    if (!Number.isInteger(клетка) || клетка < 0 || клетка >= BASE_REGISTER_COUNT) {
      throw new StringRuntimeRefusal(
        `роль сайта Г «${имя}» = %b[${String(клетка)}] вне 0..${String(BASE_REGISTER_COUNT - 1)}`,
      );
    }
  }
  // КРАЯ (`from`/`to`) — ИСКЛЮЧЕНИЕ, И ОНО НАЗВАНО: это клетки ПРОГРАММЫ, их выбрала раскладка, и
  // сайт переписывает их НА МЕСТЕ (копий в сайте нет — бюджет окна измерен). Закрепить их за сайтом
  // значило бы отнять у программы values, которыми она пользуется, а цена уничтожения края названа
  // там, где о ней можно судить по потоку: план отказывает на ПОЗДНЕЙШЕМ чтении
  // (`src/e2k/stringPlan.ts#eatenEdges`). Прочие роли — вне полосы и без объявления — отказ, как было.
  const безПолосы = роли.filter(
    ([имя, клетка]) =>
      имя !== 'from' &&
      имя !== 'to' &&
      !RESERVED_REGISTERS.includes(клетка) &&
      !reserved.includes(клетка),
  );
  if (безПолосы.length > 0) {
    throw new StringRuntimeRefusal(
      `клетки сайта Г вне полосы ${RESERVED_REGISTERS.map((номер) => `%b[${String(номер)}]`).join('/')} и не ` +
        `объявлены в reserved: ${безПолосы.map(([имя, клетка]) => `«${имя}» %b[${String(клетка)}]`).join(', ')} — ` +
        'раскладка отдала бы их значениям программы',
    );
  }
  if (!RESERVED_REGISTERS.includes(options.destination)) {
    throw new StringRuntimeRefusal(
      `приёмник сайта Г = %b[${String(options.destination)}] ВНЕ полосы ` +
        `${RESERVED_REGISTERS.map((номер) => `%b[${String(номер)}]`).join('/')}: результат живёт в клетке, ` +
        'которую раскладка вправе отдать программе',
    );
  }
  if (options.cells.zero !== ARRAY_REGISTERS.zero) {
    throw new StringRuntimeRefusal(
      `клетка нуля сайта Г = %b[${String(options.cells.zero)}], а байтовые носители берут смещение из ` +
        `%b[${String(ARRAY_REGISTERS.zero)}] — с чужим нулём копирование читало бы по чужому адресу`,
    );
  }
  for (const [имя, клетка] of [
    ['pointer', options.arena.pointer],
    ['limit', options.arena.limit],
  ] as const) {
    const занята = роли.find(([, клеткаРоли]) => клеткаРоли === клетка);
    if (занята !== undefined) {
      throw new StringRuntimeRefusal(
        `клетка арены «${имя}» = %b[${String(клетка)}] занята ролью сайта Г «${занята[0]}»: это ЖИВОЕ ` +
          'состояние арены на всю программу — сайт испортил бы выделение следующим операциям',
      );
    }
  }
  const видели = new Map<number, string>();
  for (const [имя, клетка] of роли) {
    const прежняя = видели.get(клетка);
    // ОДНА СОВПАДАЮЩАЯ ПАРА РАЗРЕШЕНА И НАЗВАНА: `key` — результат сравнений петли, и он ложится в
    // клетку `scratch`, когда её прежнее значение (`table + byte`) уже прочитано. Развести их значило
    // бы отнять у программы ещё одну клетку, а бюджет окна измерен: 16 клеток на сайт, арену и
    // программу. Совпадение ЛЮБОЙ другой пары остаётся отказом.
    const параБайтПриёмник =
      options.destination === options.cells.byte &&
      ((имя === 'byte' && прежняя === 'destination') || (имя === 'destination' && прежняя === 'byte'));
    if (прежняя !== undefined && !(клетка === options.cells.scratch && имя === 'key') && !параБайтПриёмник) {
      throw new StringRuntimeRefusal(
        `клетка %b[${String(клетка)}] несёт ДВЕ роли сайта Г: «${прежняя}» и «${имя}» — одно из значений ` +
          'было бы потеряно молча',
      );
    }
    видели.set(клетка, имя);
  }
  // КЛЕТКА ВЫЗОВА: она НЕ в полосе (её даёт раскладка программе) и не совпадает ни с одной ролью —
  // иначе сайт затёр бы собственный результат до того, как его прочтёт программа.
  if (!Number.isInteger(options.result) || options.result < 0 || options.result >= BASE_REGISTER_COUNT) {
    throw new StringRuntimeRefusal(
      `клетка вызова сайта Г = %b[${String(options.result)}] вне 0..${String(BASE_REGISTER_COUNT - 1)}`,
    );
  }
  if (RESERVED_REGISTERS.includes(options.result)) {
    throw new StringRuntimeRefusal(
      `клетка вызова сайта Г = %b[${String(options.result)}] лежит в полосе ` +
        `${RESERVED_REGISTERS.map((номер) => `%b[${String(номер)}]`).join('/')}: раскладка не отдаёт её ` +
        'значениям программы, и результат не доехал бы до вызова',
    );
  }
  if (роли.some(([, клетка]) => клетка === options.result)) {
    throw new StringRuntimeRefusal(
      `клетка вызова сайта Г = %b[${String(options.result)}] занята ролью сайта: результат был бы затёрт ` +
        'собственной работой сайта',
    );
  }
}

/**
 * СТОРОЖ ХВОСТА Г: место петли, ЗНАЧЕНИЕ длины из счётчика, границы копии и возврат за вызов.
 *
 * Две проверки названы владельцем отдельно, потому что обе дают ВЕРНУЮ ДЛИНУ при НЕВЕРНЫХ байтах:
 *   • слово длины берётся из `copied` (после петли), а не из `к − н` (до нормализации);
 *   • границы копии — НОРМАЛИЗОВАННЫЕ `from`/`to` в байтах, а не исходные `н`/`к` в кодпоинтах.
 */
export function checkStringSliceRuntimeTail(
  tail: readonly AsmInstruction[],
  options: StringSliceRuntimeTailOptions,
): void {
  const эталон = stringSliceRuntimeTail(options);
  if (tail.length !== эталон.length) {
    throw new StringRuntimeRefusal(
      `хвост Г длиной ${String(tail.length)}, а построитель строит ${String(эталон.length)} — сверять ` +
        'место петли не с чем',
    );
  }
  // ПЕТЛЯ — НАЧАЛО ХВОСТА, а не `tail[loopIndex]`: хвост ложится в поток ЦЕЛИКОМ, начиная с
  // `loopIndex`, поэтому индекс внутри массива хвоста отсчитывается от НУЛЯ, а цели переходов —
  // АБСОЛЮТНЫЕ по итоговому потоку.
  const loop = tail.slice(0, STRING_SLICE_COPY_LOOP_SIZE);
  if (loop.length !== STRING_SLICE_COPY_LOOP_SIZE) {
    throw new StringRuntimeRefusal(
      `петля Г в хвосте длиной ${String(loop.length)} вместо ${String(STRING_SLICE_COPY_LOOP_SIZE)} — выход ` +
        'петли ушёл бы мимо записи дескриптора',
    );
  }
  // ЦЕЛИ ПЕРЕХОДОВ ВНУТРИ ХВОСТА: промах на один носитель уводит в середину команды (§3.35), а цель
  // «первый носитель за массивом» вообще выключает сторожа ребра взятого перехода (случай 78).
  tail.forEach((carrier, индекс) => {
    if (!carrier.mnemonic.startsWith('IR.jmp')) return;
    const цель = carrier.operands[carrier.operands.length - 1];
    if (цель?.kind !== 'imm') {
      throw new StringRuntimeRefusal(
        `переход хвоста Г #${String(индекс)} несёт цель не числом: индекс носителя неизвестен`,
      );
    }
    const адрес = цель.value;
    const последний = индекс === tail.length - 1;
    if (последний) {
      if (адрес !== options.successor) {
        throw new StringRuntimeRefusal(
          `последний носитель хвоста Г ведёт на ${String(адрес)}, а за вызовом стоит носитель ` +
            `${String(options.successor)} — возврат ушёл бы не туда`,
        );
      }
      return;
    }
    if (адрес < options.loopIndex || адрес >= options.loopIndex + tail.length) {
      throw new StringRuntimeRefusal(
        `переход хвоста Г #${String(индекс)} ведёт на ${String(адрес)} ВНЕ хвоста (` +
          `${String(options.loopIndex)}..${String(options.loopIndex + tail.length - 1)}): цель вне массива ` +
          'не разбирается, и сторож ребра взятого перехода молча выключается (случай 78 реестра)',
      );
    }
  });
  // ДЛИНА — ИЗ СЧЁТЧИКА: последняя запись дескриптора обязана нести `copied`.
  const последняяЗапись = tail.filter((carrier) => carrier.mnemonic === 'IR.store').at(-1);
  const значение = последняяЗапись?.operands[0];
  if (значение?.kind !== 'reg' || значение.index !== options.cells.copied) {
    throw new StringRuntimeRefusal(
      'слово длины хвоста Г берётся НЕ из счётчика скопированных кодпоинтов: после нормализации краёв ' +
        'разность `к − н` считала бы не то число',
    );
  }
  // ГРАНИЦЫ КОПИИ — НОРМАЛИЗОВАННЫЕ клетки краёв (они же счётчики петли).
  for (const [имя, клетка] of [
    ['from', options.from],
    ['to', options.to],
  ] as const) {
    const вПетле = loop.some((carrier) =>
      carrier.operands.some((операнд) => операнд.kind === 'reg' && операнд.index === клетка),
    );
    if (!вПетле) {
      throw new StringRuntimeRefusal(
        `граница копии «${имя}» = %b[${String(клетка)}] в петле Г не участвует: копировались бы байты по ` +
          'ИСХОДНЫМ краям, а не по нормализованным',
      );
    }
  }
  for (const [номер, носитель] of tail.entries()) {
    if (теЖеОперанды(носитель.operands, эталон[номер]!.operands)) continue;
    throw new StringRuntimeRefusal(
      `носитель хвоста Г #${String(номер)} (${носитель.mnemonic}) разошёлся с построителем: поток правили ` +
        'руками, и место петли перестало быть известным',
    );
  }
}


/**
 * СВЕРКА ОПЕРАНДОВ БЕЗ `JSON.stringify`.
 *
 * Среди операндов сайта есть 64-разрядные литералы (`{kind: 'imm64', value: BigInt}`), а `JSON.stringify`
 * на `BigInt` бросает `TypeError: Do not know how to serialize a BigInt` — сторож падал бы на ВЕРНОМ
 * хвосте (поймано оракулом, а не глазом). Поэтому сверка идёт по полям, а значения сравниваются
 * приведением к строке: `BigInt(8)` и `8` дают одну строку «8».
 */
const теЖеОперанды = (первый: readonly Operand[], второй: readonly Operand[]): boolean => {
  if (первый.length !== второй.length) return false;
  return первый.every((операнд, номер) => {
    const другой = второй[номер];
    if (другой === undefined || операнд.kind !== другой.kind) return false;
    const значение = (операнд as { value?: unknown }).value;
    const значениеДругого = (другой as { value?: unknown }).value;
    const клетка = (операнд as { index?: unknown }).index;
    const клеткаДругого = (другой as { index?: unknown }).index;
    return String(значение) === String(значениеДругого) && String(клетка) === String(клеткаДругого);
  });
};

/**
 * СБОРЩИК ГРУПП РАНТАЙМ-СРЕЗА: носители сайта вместо `IR.invoke` и хвост в конце потока.
 *
 * # Откуда берутся абсолютные индексы
 *
 * Раскладка уже прошла, поток `code` — итоговый, но группы расширят его. Индекс носителя в середине
 * потока сдвигается на прирост ВСЕХ групп до него, поэтому:
 *   • группа сайта заменяет ОДИН носитель (`IR.invoke`) на `STRING_SLICE_SITE_SIZE`, то есть даёт
 *     прирост `STRING_SLICE_SITE_SIZE − 1`;
 *   • начало хвоста = `code.length + прирост всех сайтов` — считается ДО сборки, как у коллекций и
 *     арены, и потому абсолютный индекс перехода известен;
 *   • носитель ЗА группой сайта (`successor`) = итоговый индекс самой группы + её длина.
 *
 * # Почему расхождение счётчиков — ОТКАЗ, а не догадка
 *
 * Статические срезы план заменяет на `IR.const` ЦЕЛИКОМ («у среза от вызова не остаётся ничего»),
 * поэтому каждый оставшийся вызов `подстрока` — рантайм-срез, и число носителей обязано совпасть с
 * числом записей плана. Не совпало — значит носитель потерялся или план и поток разошлись; взять
 * «первые N» или «сколько нашлось» значило бы подставить срез не тому вызову.
 */
export interface StringSliceSiteRequest {
  /** Индекс носителя `IR.invoke` в потоке ПОСЛЕ раскладки. */
  readonly index: number;
  /** Клетка начала среза (операнд 2 носителя). */
  readonly from: number;
  /** Клетка конца среза (операнд 5). */
  readonly to: number;
  /** Приёмник (операнд 4) — адрес байтов В АРЕНЕ; он обязан быть в полосе `%b[10..15]`. */
  readonly destination: number;
  /** Клетка вызова: куда переносится адрес результата (её читает программа, `%b[0..9]`). */
  readonly result: number;
  /** Константы сборки — ИНДЕКСЫ ПУЛА (`IR.const`): адреса, число кодпоинтов, единица, шестнадцать. */
  readonly literals: StringSliceLiterals;
  readonly cells: StringSliceRuntimeSiteOptions['cells'];
  readonly arena: StringSliceArenaCells;
  /** Клетки, объявленные сайтом в раскладке — второй уровень закрепления (D24). */
  readonly reserved?: readonly number[];
}

/** Что вернул сборщик: группы по индексам носителей и место хвоста (для отчёта и сторожей). */
export interface StringSliceGroups {
  readonly groups: ReadonlyMap<number, readonly AsmInstruction[]>;
  readonly loopIndex: number;
  readonly tailIndex: number;
  /**
   * ЦЕЛИ ПЕРЕХОДОВ ВНУТРИ САЙТА, ПОСЧИТАННЫЕ ОТ ЕГО НАЧАЛА (`at` — смещение носителя в сайте,
   * `target` — номер носителя ВНУТРИ САЙТА, куда он ведёт).
   *
   * Зачем отдельным списком: `stringSliceRuntimeSite` собирает САМОДОСТАТОЧНЫЙ фрагмент — так его
   * исполняет модель носителей (Γ), и там он начинается с нуля, поэтому относительные цели верны. Но
   * в образе фрагмент ВСТАВЛЯЕТСЯ по своему месту, и номера 9/12/15/18/21 указывали бы на ЧУЖИЕ
   * носители программы: ветви обработки краёв уезжали в начало образа. Замер ERR-0008: Р1…Р4 висели
   * по 30 с при верных размерах (сайт 34, хвост 21) — размеры сходились, а цели нет.
   *
   * Абсолютные цели сайта (клетка отказа арены и `loopIndex`) в список НЕ попадают: их пересчитывает
   * раскрытие (`expandCarriers`), и трогать их значило бы сдвинуть второй раз.
   */
  readonly relativeTargets: readonly { readonly at: number; readonly target: number }[];
}

export function stringSliceGroups(
  code: readonly AsmInstruction[],
  requests: readonly StringSliceSiteRequest[],
  группаOptions: {
    /**
     * ПРОВЕРЯТЬ ЛИ КЛЕТКИ (по умолчанию — да). `false` ставит ТОЛЬКО конвейер и только на
     * НЕРАЗЛОЖЕННОМ потоке: раскладка отказала, номера в носителях — виртуальные, и проверка клеток
     * была бы отказом не по делу. Сайт при этом всё равно собирается: в потоке не должно остаться
     * носителя без формы, а байты такого образа наружу не уходят (буква D13).
     */
    readonly checkCells?: boolean;
  } = {},
): StringSliceGroups {
  const checkCells = группаOptions.checkCells !== false;
  if (requests.length === 0) {
    throw new StringRuntimeRefusal(
      'сборщик групп рантайм-среза позван без сайтов: групп нет, а хвост вставлять некуда',
    );
  }
  // ОДИН САЙТ ЗА РАЗ — названная граница, а не недоделка. Хвост ОДИН: выход цикла ведёт в запись
  // дескриптора, и вернуться он может только к ОДНОМУ носителю за вызовом, а `к − н` считает по клеткам
  // ОДНОГО вызова. Двум сайтам нужны два хвоста и два набора клеток результата — это следующий шаг;
  // пока второй сайт отвергается по имени, чтобы первый не получил чужие края и чужой буфер.
  if (requests.length > 1) {
    throw new StringRuntimeRefusal(
      `сайтов рантайм-среза ${String(requests.length)}, а понижается ОДИН: хвост один, и выход цикла ` +
        'вернулся бы не к тому вызову (нужны два хвоста — это следующий шаг)',
    );
  }
  const site = requests[0]!;
  if (site.index < 0 || site.index >= code.length) {
    throw new StringRuntimeRefusal(
      `сайт рантайм-среза указывает на носитель ${String(site.index)}, а поток длиной ` +
        `${String(code.length)} — заменить нечего`,
    );
  }
  const последний = code.length - 1;
  if (site.index === последний) {
    throw new StringRuntimeRefusal(
      `сайт рантайм-среза стоит на ПОСЛЕДНЕМ носителе потока (${String(последний)}): хвост лёг бы в ` +
        'ту же группу, и его индекс перестал бы быть известным заранее',
    );
  }
  const прирост = STRING_SLICE_SITE_SIZE - 1;
  const loopIndex = code.length + прирост;
  // ВОЗВРАТ ЗА ВЫЗОВ — В НУМЕРАЦИИ ДО РАСКРЫТИЯ, и это не придирка: `expandCarriers` пересчитывает
  // ЛЮБУЮ цель, лежащую ВНУТРИ прежнего потока (`map` знает каждый его индекс), и оставляет как есть
  // только цели ЗА концом прежнего потока (см. его комментарий). Хвост раскрывается ТЕМ ЖЕ зовом, что
  // и сайт, поэтому «индекс за вызовом» обязан быть индексом НАСТОЯЩЕГО носителя потока — тогда сдвиг
  // вставки к нему добавят ровно один раз. Прежняя редакция писала сюда `site.index + САЙТ` (номер
  // ПОСЛЕ раскрытия): он попадал в диапазон `map`, к нему добавляли сдвиг ВТОРОЙ раз, и возврат из
  // копирования уезжал на 33 носителя назад — ВНУТРЬ собственного сайта, то есть в вечную петлю
  // (замер: Р1…Р4 висели по 30 с и давали `null`, ERR-0008).
  const successor = site.index + 1;
  const options: StringSliceRuntimeSiteOptions = {
    from: site.from,
    to: site.to,
    destination: site.destination,
    result: site.result,
    literals: site.literals,
    cells: site.cells,
    arena: site.arena,
    loopIndex,
  };
  // ПРОВЕРКИ КЛЕТОК — ПО СЛОВУ КОНВЕЙЕРА. На НЕРАЗЛОЖЕННОМ потоке (отказ раскладки) номера в
  // носителях ничего не значат: там ещё живут виртуальные регистры, и «клетка арены занята ролью
  // сайта» было бы отказом не по делу. Сайт всё равно собирается — чтобы в потоке не осталось
  // носителя без формы, — а байты такого образа наружу не уходят (буква D13).
  if (checkCells) checkStringSliceRuntimeSite(options, site.reserved ?? []);
  const хвостOptions: StringSliceRuntimeTailOptions = {
    from: site.from,
    to: site.to,
    destination: site.destination,
    result: site.result,
    literals: site.literals,
    cells: site.cells,
    loopIndex,
    successor,
  };
  if (checkCells) checkStringSliceRuntimeTail(stringSliceRuntimeTail(хвостOptions), хвостOptions);
  const носителиСайта = stringSliceRuntimeSite(options);
  // ОТНОСИТЕЛЬНЫЕ ЦЕЛИ — те, что не совпали ни с клеткой отказа арены, ни с `loopIndex`: их обязан
  // дописать конвейер, знающий МЕСТО вставки (`resolveSliceRelativeTargets` ниже).
  const relativeTargets: { at: number; target: number }[] = [];
  носителиСайта.forEach((carrier, at) => {
    if (!carrier.mnemonic.startsWith('IR.jmp')) return;
    const targetAt = carrier.mnemonic === 'IR.jmp' ? 0 : 1;
    const target = carrier.operands[targetAt];
    if (target === undefined || target.kind !== 'imm') return;
    if (target.value === loopIndex || target.value === site.arena.refusalIndex) return;
    relativeTargets.push({ at, target: target.value });
  });
  const группы = new Map<number, readonly AsmInstruction[]>([
    [site.index, носителиСайта],
    // ПОСЛЕДНИЙ НОСИТЕЛЬ ОСТАЁТСЯ НА МЕСТЕ, хвост ДОПИСЫВАЕТСЯ за ним — ровно как у коллекций
    // (`src/e2k/collectionsRuntime.ts`: `[code[last], ...trailing]`). Заменить его хвостом значило бы
    // потерять носитель потока: `loopIndex` считается как `code.length + прирост` и указывал бы на
    // носитель, которого в потоке нет (порча 4 записи ERR-0006).
    [последний, [code[последний]!, ...stringSliceRuntimeTail(хвостOptions)]],
  ]);
  return { groups: группы, loopIndex, tailIndex: successor, relativeTargets };
}

/**
 * ДОПИСАТЬ МЕСТО ВСТАВКИ К ОТНОСИТЕЛЬНЫМ ЦЕЛЯМ САЙТА — сразу после раскрытия групп, ДО раскладки.
 *
 * `expandCarriers` пересчитывает только те цели, что лежат ВНУТРИ прежнего потока (по `map`), а
 * относительные цели сайта таковыми не являются: 9 — это «девятый носитель САЙТА», а не девятый
 * носитель программы. Поэтому их дописывает тот, кто знает `siteIndex`, и дописывает РОВНО ОДИН раз:
 * после этого в потоке стоят настоящие номера носителей, и все последующие раскрытия (коллекции,
 * рост, разделённая печать) пересчитывают их наравне со всеми — как и требует `expandCarriers`.
 */
export function resolveSliceRelativeTargets(
  code: readonly AsmInstruction[],
  siteIndex: number,
  relativeTargets: readonly { readonly at: number; readonly target: number }[],
): readonly AsmInstruction[] {
  if (relativeTargets.length === 0) return code;
  const правки = new Map<number, number>();
  for (const { at, target } of relativeTargets) правки.set(siteIndex + at, target);
  return code.map((carrier, index) => {
    const target = правки.get(index);
    if (target === undefined) return carrier;
    const targetAt = carrier.mnemonic === 'IR.jmp' ? 0 : 1;
    const operands = [...carrier.operands];
    operands[targetAt] = imm(siteIndex + target);
    return { ...carrier, operands };
  });
}


/**
 * ВЛЕЗАЕТ ЛИ СКЛЕЙКА В СТАТИЧЕСКИЙ БУФЕР — и это РЕШЕНИЕ О СПОСОБЕ, а не отказ.
 *
 * Было: «не влезло — названный отказ на сборке». Стало (решение владельца, 2026-09-29): не влезло —
 * склейка идёт **через арену**: блок выделяется в рантайме ровно под сумму байтов, байты копируются
 * в него, а отказ **переезжает на исчерпание** арены (`src/e2k/arenaRuntime.ts` — код 231 и строка
 * в stderr). Граница осталась той же: **20 байт статики**, всё сверх — арена.
 */
export function concatFitsBuffer(firstBytes: number, secondBytes: number): boolean {
  return firstBytes + secondBytes <= STRING_BUFFER_BYTES;
}

/**
 * ВЫВОД СТРОКИ: байты наружу `write`, следом перевод строки — вторым `write`.
 *
 * Второй вызов, а не один, потому что перевод строки лежит ОТДЕЛЬНЫМ статическим байтом: дописать
 * его к строке нельзя — строки константные, и в памяти их портить нечем (буфера для каждой печати
 * нет). Оба вызова видны в журнале модели, и сторож сравнивает БАЙТЫ вывода, а не число вызовов.
 */
export function stringWriteInstructions(options: {
  readonly address: number;
  readonly byteLength: number;
  readonly newlineAddress: number;
  /** Кадр: в точке входа окно ставится своим `setbn`, в выращенном — уже стоит прологом. */
  readonly frame?: SyscallFrame;
}): AsmInstruction[] {
  const frame = options.frame ?? ENTRY_SYSCALL_FRAME;
  const write = (addressRegister: number, length: number): AsmInstruction[] => [
    a('adds', [reg(addressRegister), reg(ARRAY_REGISTERS.zero), window_(syscallWindowOf(frame, 2))]),
    a('movts', [imm(length), window_(syscallWindowOf(frame, 3))]),
    a('movts', [imm(SYS_WRITE), window_(syscallWindowOf(frame, 0))]),
    a('movts', [imm(STDOUT_FD), window_(syscallWindowOf(frame, 1))]),
    ...syscallCallOpen(frame),
    a('sdisp', [imm(1), imm(SYSCALL_TRAP)]),
    a('call', [imm(1), imm(frame.wbs)]),
    ...syscallCallClose(frame),
  ];
  return [
    // Окно ставится как у рантайма массивов — но ТОЛЬКО в кадре точки входа: в выращенном кадре
    // окно уже дал пролог, а повторная `setbn` после `setwd` — ловушка (§3.56.2).
    ...(frame.setbn ? [a('setbn', [imm(ARRAY_WINDOW_RSZ), imm(0), imm(0)])] : []),
    ...write(options.address, options.byteLength),
    a('movtd', [literal(options.newlineAddress), reg(STRING_REGISTERS.first)]),
    ...write(STRING_REGISTERS.first, 1),
  ];
}

/**
 * Куда команда пишет результат — или `undefined`, если не пишет никуда.
 *
 * Нужно сторожу ниже: «трогает» и «портит» — разные вещи. Вывод строки ЧИТАЕТ ноль рантайма
 * массивов (`adds значение, ноль, %r10`) и не портит его — значит и восстанавливать нечего.
 */
function destinationOfInstruction(instruction: AsmInstruction): number | undefined {
  const last = instruction.operands[instruction.operands.length - 1];
  switch (instruction.mnemonic) {
    case 'movts':
    case 'movtd':
      return instruction.operands[1]?.kind === 'reg' ? (instruction.operands[1] as { index: number }).index : undefined;
    case 'adds':
    case 'subs':
    case 'muls':
    case 'sdivs':
    case 'shrs':
    case 'ldb':
    case 'ldd':
      return last?.kind === 'reg' ? (last as { index: number }).index : undefined;
    default:
      return undefined;
  }
}

/**
 * СТОРОЖ СТРУКТУРЫ: что строковый рантайм делает с регистрами.
 *
 * Проверяется то, на чём легко ошибиться молча: `%b[14]` (восемь) и `%b[15]` (куча) рантайма
 * массивов не трогаются вовсе (ни чтением, ни записью), а постоянные `%b[12]` (ноль) и `%b[13]`
 * (единица) возвращаются на место, ЕСЛИ были испорчены. Проверяются имена регистров, а не замысел.
 */
export function stringSequenceProblems(instructions: readonly AsmInstruction[]): string[] {
  const problems: string[] = [];
  const clobbered = new Set<number>();
  for (const [index, instruction] of instructions.entries()) {
    for (const operand of instruction.operands) {
      if (operand.kind !== 'reg') continue;
      if (operand.index === ARRAY_REGISTERS.eight || operand.index === ARRAY_REGISTERS.heapSlot) {
        problems.push(
          `#${String(index)} ${instruction.mnemonic}: тронут %b[${String(operand.index)}] — это ` +
            'постоянные рантайма массивов (восемь и куча), их строковый рантайм не трогает',
        );
      }
    }
    const destination = destinationOfInstruction(instruction);
    if (destination !== undefined) clobbered.add(destination);
  }
  const restoresZero = instructions.some((instruction) => {
    if (instruction.mnemonic !== 'movts') return false;
    const [value, destination] = instruction.operands;
    return value?.kind === 'imm' && value.value === 0 && destination?.kind === 'reg' && destination.index === ARRAY_REGISTERS.zero;
  });
  const restoresOne = instructions.some((instruction) => {
    if (instruction.mnemonic !== 'movts') return false;
    const [value, destination] = instruction.operands;
    return value?.kind === 'imm' && value.value === 1 && destination?.kind === 'reg' && destination.index === ARRAY_REGISTERS.one;
  });
  if (clobbered.has(ARRAY_REGISTERS.zero) && !restoresZero) {
    problems.push('ноль рантайма массивов (%b[12]) испорчен и не возвращён: `movts 0` в конце не найден');
  }
  if (clobbered.has(ARRAY_REGISTERS.one) && !restoresOne) {
    problems.push('единица рантайма массивов (%b[13]) испорчена и не возвращена: `movts 1` в конце не найден');
  }
  return problems;
}
