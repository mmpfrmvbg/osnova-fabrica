// ─────────────────────────── канал: авария порта — НЕ число ───────────────────────────

/**
 * То, что нужно от прогона для ЧЕСТНОГО чтения числа. Структурно (а не `QemuRun`), чтобы правило
 * канала проверялось синтетическим прогоном — без модели и без внешнего ресурса.
 */
type ПрогонМодели = {
  readonly status: number | null;
  readonly output: string;
  readonly exceptionIp?: number;
};

type ИсходМодели =
  | { readonly вид: 'число'; readonly число: number }
  | { readonly вид: 'авария'; readonly код: number | null; readonly ip?: number; readonly строка: string }
  | { readonly вид: 'молчание'; readonly код: number | null };

/**
 * ЧИСЛО ИЛИ АВАРИЯ. Код возврата — число ТОЛЬКО если модель не сказала «exception … aborting»: у
 * аварийного выхода код порта неотличим от числа гостя, и принять его за число — ровно ошибка канала
 * из `docs/hardware-debt.md` §3.31.4 (там `9` с «exception at IP» помечен «не канал»).
 */
function исходМодели(прогон: ПрогонМодели | undefined): ИсходМодели {
  if (прогон === undefined) return { вид: 'молчание', код: null };
  const аварийная = /exception at IP|exception handling is unimplemented/iu.exec(прогон.output);
  if (аварийная !== null || прогон.exceptionIp !== undefined) {
    return {
      вид: 'авария',
      код: прогон.status,
      ...(прогон.exceptionIp === undefined ? {} : { ip: прогон.exceptionIp }),
      строка: аварийная?.[0] ?? 'exceptionIp без строки',
    };
  }
  if (прогон.status === null) return { вид: 'молчание', код: null };
  return { вид: 'число', число: прогон.status };
}

// ─────────────────────────── сборка и эталон обеих VM ───────────────────────────

const сборки = new Map<string, CompileResult>();

/** Сборка ФРОНТЕНДОМ УМОЛЧАНИЯ (тем же, что у печатающего оракула) — и красное, если он не собрал. */
function сборкаПробы(проба: Проба): CompileResult {
  const уже = сборки.get(проба.имя);
  if (уже !== undefined) return уже;
  const собранное = compileSource(проба.текст, { filename: ФАЙЛ });
  const беды = [
    ...собранное.lexerErrors.map((о) => `лексер: ${о.message}`),
    ...собранное.parserErrors.map((о) => `разбор: ${о.message}`),
    ...собранное.semanticErrors.map((о) => `семантика: ${о.message}`),
  ];
  expect(беды, `${проба.имя}: программа обязана собираться фронтендом умолчания (лексика: \`процедура\`, без \`действие\` и без \`→\`)`).toEqual([]);
  сборки.set(проба.имя, собранное);
  return собранное;
}

/** ОДНА VM — со СВОИМ буфером печати (общий буфер на две VM удвоил бы текст и дал ложное расхождение). */
async function однаVm(проба: Проба, регистровая: boolean): Promise<{ число?: number; вывод: string }> {
  const собранное = сборкаПробы(проба);
  const число = (значение: unknown): number | undefined =>
    значение === true ? 1 : значение === false ? 0 : typeof значение === 'number' ? значение : undefined;
  const строки: string[] = [];
  const исходныйЛог = console.log;
  console.log = (...аргументы: unknown[]): void => {
    строки.push(аргументы.map((а) => String(а)).join(' '));
  };
  try {
    if (регистровая) {
      const регистры = new RegVM(compileToReg(собранное.moduleAst!, { arrayLiteralOrder: 'values-first' }), {
        invoke: createDefaultInvokeHandler(),
        maxSteps: 2_000_000,
      });
      return { число: число(await регистры.runProcedure(регистры.findProcedureIndex('главная'), [])), вывод: строки.join('\n') };
    }
    const стековая = new VM(собранное.module!, { invoke: createDefaultInvokeHandler(), maxSteps: 2_000_000 });
    return { число: число(await стековая.runProcedure(стековая.findProcedureIndex('главная'), [])), вывод: строки.join('\n') };
  } finally {
    console.log = исходныйЛог;
  }
}

const эталоны = new Map<string, { стек: number; регистры: number; вывод: string }>();

/** Эталон ОБЕИХ VM. Не сошёлся — КРАСНОЕ с причиной: сломанной меркой мерить нельзя. */
async function эталонПробы(проба: Проба): Promise<{ стек: number; регистры: number; вывод: string }> {
  const уже = эталоны.get(проба.имя);
  if (уже !== undefined) return уже;
  const стек = await однаVm(проба, false);
  const регистры = await однаVm(проба, true);
  expect(стек.число, `${проба.имя}: стековая VM обязана дать число`).toBeDefined();
  expect(регистры.число, `${проба.имя}: регистровая VM обязана дать число`).toBeDefined();
  expect(стек.число, `${проба.имя}: обе VM обязаны дать ОДНО число — иначе эталон не подтверждён`).toBe(регистры.число);
  expect(стек.вывод, `${проба.имя}: обе VM обязаны напечатать ОДИН текст`).toBe(регистры.вывод);
  expect(стек.число, `${проба.имя}: эталон обеих VM разошёлся с записанным от руки — перемерьте замером`).toBe(проба.эталон);
  const итог = { стек: стек.число!, регистры: регистры.число!, вывод: стек.вывод };
  эталоны.set(проба.имя, итог);
  return итог;
}

// ─────────────────────────── замер цели ───────────────────────────

type Замер = {
  readonly байт: number;
  readonly stdout: string;
  readonly hex: string;
  readonly исход: ИсходМодели;
};

const замеры = new Map<string, Замер>();

/**
 * Замер ПУБЛИЧНОЙ двери и прогон в модели. Сырая дверь здесь НЕ берётся: у всех проб отказов ноль, а
 * публичный контракт (D11) при нуле отказов отдаёт образ — брать `guards/loweredUnchecked` незачем.
 */
function замерить(проба: Проба): Замер {
  const уже = замеры.get(проба.имя);
  if (уже !== undefined) return уже;
  сборкаПробы(проба);
  const итог = loweredProgram(проба.текст, { filename: ФАЙЛ });
  expect(
    итог.ок,
    `${проба.имя}: у пробы обязан быть НОЛЬ отказов (иначе это не восьмая ложь, а отказ: ${итог.ок ? '' : итог.отказ.причина})`,
  ).toBe(true);
  if (!итог.ок) throw new Error(`${проба.имя}: дверь отказала`);
  const образ = итог.значение;
  const файл = path.join(ROOT, '.tmp', `print-callee-${проба.имя}.elf`);
  fs.writeFileSync(файл, buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes);
  const прогон = runInQemu(файл, { shim: true, timeoutMs: 20_000 });
  const замер: Замер = {
    байт: образ.bytes.length,
    stdout: прогон?.stdout ?? '',
    hex: [...Buffer.from(прогон?.stdout ?? '', 'utf-8')].map((б) => б.toString(16).padStart(2, '0')).join(' '),
    исход: исходМодели(прогон),
  };
  замеры.set(проба.имя, замер);
  return замер;
}

