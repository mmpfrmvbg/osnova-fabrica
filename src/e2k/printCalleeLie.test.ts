/** Эталонный текст вывода — БАЙТ В БАЙТ; `undefined` — печати нет. */
const выводТекста = (проба: Проба): string => проба.вывод ?? '';

/** Сколько байт уходит в вывод: разряды числа плюс перевод строки (печатающий оракул печатает так же). */
const байтВывода = (проба: Проба): number => Buffer.byteLength(выводТекста(проба), 'utf-8');

/** Эталонный текст вывода — шестнадцатеричными байтами, как в печатающем оракуле. */
const hexТекста = (проба: Проба): string =>
  [...Buffer.from(выводТекста(проба), 'utf-8')].map((б) => б.toString(16).padStart(2, '0')).join(' ');

/** Формы вызываемой плоскости С печатью: ровно те, что были лживыми до починки. */
