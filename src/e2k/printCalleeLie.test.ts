/**
 * СТОРОЖ ВОСЬМОЙ ТИХОЙ ЛЖИ: ПЕЧАТЬ ВНУТРИ ВЫЗЫВАЕМОЙ + ЗНАЧЕНИЕ, ВОЗВРАЩЁННОЕ ЧЕРЕЗ ВЫЗОВ.
 *
 * # Что здесь закреплено
 *
 * Это ВОСЬМАЯ тихая ложь, найденная охотой D7 в срезе 5е (задача 5): прогон 45 форм
 * (`.tmp/a5e-hunt-eighth.ts`), различающая проба (`.tmp/a5e-hunt-42.ts`), подготовка сторожа
 * (`.tmp/a5e-guard-prep.ts`). По правилу владельца («восьмая ложь → сторож, 5ж») ПОЧИНКИ в этом срезе
 * НЕТ: здесь только сторож (D4: сторож первым), а понижение **не тронуто**.
 *
 * Дефект: если `система.лог.вывести` стоит ВНУТРИ вызываемой процедуры, а значение возвращается через
 * вызов, МОДЕЛЬ возвращает «эталон + число напечатанных байт», при этом вывод верный. Отказов — НОЛЬ:
 * это не «отказ без байтов», а тихая ложь (сборка молчит, число врёт) — самый худший класс (D4).
 *
 * # ИЗМЕРЕНО (подготовка сторожа 2026-10-29, `.tmp/a5e-guard-prep.ts`, три прогона на форму; здесь —
 * тот же путь, одна прогонка на форму)
 *
 * | форма | плоскость | эталон обеих VM | печатается | байт | модель | вердикт |
 * |---|---|---|---|---|---|---|
 * | П1 без печати, возврат 42 | вызываемая | 42 | — | 0 | 42 | верно (контроль пути возврата) |
 * | П2 печать «42», возврат 42 | вызываемая | 42 | 42 | 3 | **45** | ЛОЖЬ |
 * | П3 печать «42», возврат 7 | вызываемая | 7 | 42 | 3 | **10** | ЛОЖЬ |
 * | П4 печать «42», возврат 43 | вызываемая | 43 | 42 | 3 | **46** | ЛОЖЬ |
 * | П5 печать «42», возврат 0 | вызываемая | 0 | 42 | 3 | **3** | ЛОЖЬ |
 * | П6 печать «100», возврат 42 | вызываемая | 42 | 100 | 4 | **46** | ЛОЖЬ |
 * | П7 печать «7», возврат 7 | вызываемая | 7 | 7 | 2 | **9** | ЛОЖЬ |
 * | В1 печать «7», возврат 7 | ТОЧКА ВХОДА | 7 | 7 | 2 | 7 | верно |
 * | В2 печать «10», возврат 10 | ТОЧКА ВХОДА | 10 | 10 | 3 | 10 | верно |
 * | В3 печать «3», возврат 3 | ТОЧКА ВХОДА | 3 | 3 | 2 | 3 | верно |
 *
 * Механизм читается из таблицы: **модель = эталон + байт вывода** (3 байта «42\n» → +3; 4 байта
 * «100\n» → +4; 2 байта «7\n» → +2). Поэтому лживое число записано в коде НЕ константой, а ТОЙ ЖЕ
 * формулой: если 5ж починит понижение, проверка покраснеет и скажет, что запись пора перенести в
 * «верно» (самопокраснение записи, а не молчаливое устаревание).
 *
 * # Граница — ПЛОСКОСТЬ, а не печать и не форма
 *
 * КОНТРОЛЬ: та же печать того же значения в ТОЧКЕ ВХОДА даёт ВЕРНОЕ число (В1–В3), а в ВЫЗЫВАЕМОЙ —
 * лживое (П2–П7). Пара П7/В1 различает ровно одно — плоскость: тот же текст «7», тот же эталон 7, но
 * в вызываемой модель говорит 9, а в точке входа 7. Значит «печать сломалась» этой ложью не
 * объясняется, а контроль обязан КРАСНЕТЬ, если понижение починят и он перестанет отличаться.
 *
 * # Канал: авария порта — НЕ число
 *
 * `runInQemu` отдаёт СЫРОЙ вывод (`QemuRun.output`), и сторож им пользуется: если рядом с кодом стоит
 * «qemu: exception at IP = …» или «exception handling is unimplemented - aborting», то код — это КОД
 * АВАРИИ порта (`docs/hardware-debt.md` §3.31.4, «не канал»), а не число гостя. Так `status = 9`
 * известной седьмой лжи (`src/e2k/calleeJoinLie.test.ts`) — аварийный код, а не число. У проб ЭТОГО
 * файла отказов ноль, поэтому аварии быть не может — и это утверждается явно; сама же привычка
 * различений проверяется отдельной пробой на СИНТЕТИЧЕСКОМ прогоне (детерминированно, без модели).
 *
 * # Фронтенд и слово — те же, что у печатающего оракула дерева
 *
 * Печать вызывается словом `система.лог.вывести(…)` и через **фронтенд умолчания** — ровно как
 * `src/e2k/printPrimitivesQemu.test.ts`, иначе числа были бы несравнимы. Лексика этого фронтенда своя:
 * ни `действие`, ни стрелки `→` он не знает (слова v3), а возвращающую процедуру выражает как
 * `процедура ф(ч: Число)` + `вернуть …` — проверено разбором `.tmp/a5e-guard-frontend.ts` (из семи
 * вариантов взят этот). v3-фронтенд, наоборот, цепочку из двух точек (`система.лог.вывести`) не берёт
 * вовсе и требует `действие`/`→`.
 *
 * # Числа — ИЗ ПРОГОНА
 *
 * Эталон каждой формы подтверждается ОБЕИМИ VM (стековая `VM` и регистровая `RegVM`) независимо от
 * цели, и если он не сошёлся — проба КРАСНАЯ, а не пропущенная. Лживые числа — **KNOWN BAD: ЗАМЕР
 * ДЕФЕКТА**, а не приёмка: выдать их за приёмку нельзя, починка — 5ж.
 */
