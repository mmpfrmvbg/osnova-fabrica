/**
 * СТОРОЖ ГРАНИЦ ПРОЦЕДУР В `pairPredicates` (случай 89 реестра проверяемости).
 *
 * # Что доказывает
 *
 * Поток носителей — ОДИН массив на весь образ, и окно живости сравнения обязано кончаться на
 * границе процедуры. До правки `known:false`-барьер (пролог вызываемой: `IR.window_grow`,
 * `IR.callee_zero`, `IR.array_values`) оставлял `end = instructions.length`, окно уходило в
 * следующую процедуру, и переходы-читатели ЧУЖОЙ процедуры делали `jumpReaders.length !== 1`.
 * Сравнение материализовалось, пара не составлялась, и общий проход отказывал:
 *
 *   «IR.jmp_if_not» #90: условие … пришло не из сравнения — предикат взять неоткуда
 *
 * Здесь это МИНИМАЛЬНОЕ репро: `строки` + невызываемая вторая процедура с ТЕМ ЖЕ телом (её
 * переходы читают тот же `%r14`), главная зовёт только `строки`. При k=1 программа понижается,
 * при k≥2 до правки — `#90`. После правки понижаются все k, и k=2 печатает 1 на модели.
 *
 * # Почему это оракул, а не «проверка после»
 *
 * Проба красная по построению на дереве ДО правки: k=2 даёт `#90`. Она различает «границы
 * процедур работают» и «кажется, что работают», и эталон числа берётся не из вывода программы,
 * а из `tokenizeV3` (первая строка `"аб"` — одна строка-литерал).
 *
 * # Границы
 *
 * Модель — не железо (D12). Файл живёт в шлюзе `gate:qemu`: число спрашивает модель, поэтому в
 * полном прогоне ему места нет (случай 12); без модели он обязан КРАСНЕТЬ, а не пропускать.
 */
import { describe, it, expect, beforeAll } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { loweredProgramUnchecked } from './guards/loweredUnchecked';
import { buildElfFromCode, MINIMAL_BASE, WRITE_ZONE_EXTRA_MEMORY } from './elfMinimal';
import { buildShim, runInQemu } from '../scripts/e2kQemuExec';
import { tokenizeV3 } from '../compiler-v3/lexer';
import { parseV3 } from '../compiler-v3/index';

const ROOT = path.resolve(__dirname, '..', '..');

/**
 * ТЕЛО `строки` ИЗ B — дословно (счётчик строковых литералов в списке кодов). Тело не меняется:
 * различает только наличие ВТОРОЙ процедуры, а не её содержимое.
 */
const СТРОКИ = `процедура строки(текст: Список Число, предел: Число) -> Число
  пусть поз = 0
  пусть с = 0
  пока поз < предел
    пусть кс = текст[поз]
    если кс <= 32
      поз = поз + 1
      продолжить
    конец если
    если кс == 47
      если поз + 1 < предел
        пусть вс = текст[поз + 1]
        если вс == 47
          пока поз < предел
            пусть гс = текст[поз]
            если гс == 10
              прервать
            конец если
            поз = поз + 1
          конец пока
          продолжить
        конец если
      конец если
    конец если
    если кс == 34
      с = с + 1
      поз = поз + 1
      пока поз < предел
        пусть б1 = текст[поз]
        если б1 == 34
          поз = поз + 1
          прервать
        конец если
        если б1 == 10
          прервать
        конец если
        если б1 == 92
          поз = поз + 2
        иначе
          поз = поз + 1
        конец если
      конец пока
      продолжить
    конец если
    поз = поз + 1
  конец пока
  вернуть с
конец строки`;

/** Текст, который разбирает программа: одна строка-литерал. */
const ТЕКСТ = '"аб"';
const КОДЫ = [...ТЕКСТ].map((символ) => символ.codePointAt(0)!);
const ЛИТЕРАЛ = '[' + КОДЫ.map((код) => String(код)).join(', ') + ']';
const ГЛАВНАЯ = [
  'действие главная()',
  `  пусть коды = ${ЛИТЕРАЛ}`,
  `  пусть предел = ${String(КОДЫ.length)}`,
  '  вывести строки(коды, предел)',
  'конец главная',
].join('\n');

/** Имена клонов: вторая процедура НЕ вызывается — важно только, что она есть в потоке. */
const КЛОНЫ = ['длина_строк', 'третья', 'четвёртая', 'пятая', 'шестая'];

function источник(k: number): string {
  const клоны = КЛОНЫ.slice(0, k - 1).map((имя) =>
    СТРОКИ.replace('процедура строки(', `процедура ${имя}(`),
  );
  return [СТРОКИ, ...клоны, ГЛАВНАЯ].join('\n');
}

/** Понижение с ЯВНЫМ разбором V3: стрелка `→` есть в каноне, а умолчание двери — не V3. */
function понизить(k: number) {
  const текст = источник(k);
  const разбор = parseV3(текст, 'р.osnova');
  return loweredProgramUnchecked(текст, {
    filename: 'р.osnova',
    parse: () => ({ ast: разбор.program ?? null, errors: разбор.errors }),
  });
}

/** Эталон первой строки: одна строка-литерал. Не «программа сказала», а `tokenizeV3`. */
function эталонСтрок(): number {
  const { tokens } = tokenizeV3(ТЕКСТ, 'оракул.osnova');
  return tokens.filter((токен) => токен.kind === 'строка').length;
}

beforeAll(() => {
  buildShim();
});

describe('границы процедур: окно сравнения не уходит в соседнюю процедуру', () => {
  it('k=1..6 понижаются, k=2 печатает верное число (до правки k=2 даёт #90)', () => {
    for (let k = 1; k <= 6; k++) {
      const образ = понизить(k);
      expect(
        образ.refused.map(
          (отказ, индекс) => `#${String(образ.refusedSteps[индекс] ?? 0)} ${отказ.reason}`,
        ),
        `k=${String(k)}: границы процедур обязаны обрывать окно сравнения, а не отдавать его концу потока`,
      ).toEqual([]);
    }
    const образ = понизить(2);
    expect(образ.refused, 'k=2 обязан понижаться').toEqual([]);
    const elf = path.join(ROOT, '.tmp', 'procedure-boundary-pairing.elf');
    fs.writeFileSync(
      elf,
      buildElfFromCode(образ.bytes, MINIMAL_BASE, { writable: true, extraMemory: WRITE_ZONE_EXTRA_MEMORY }).bytes,
    );
    const прогон = runInQemu(elf, { shim: true, timeoutMs: 30_000 });
    expect(прогон?.status, 'печатающая программа завершается своим exit(0)').toBe(0);
    const строки = (прогон?.stdout ?? '').split('\n').filter((строка) => строка !== '');
    expect(строки, 'строки("аб") — ровно одна строка-литерал').toEqual([String(эталонСтрок())]);
  });
});
