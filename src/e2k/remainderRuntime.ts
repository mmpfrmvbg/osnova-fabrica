/**
 * ОСТАТОК (`IR.rem`) — СЕРИЯ ИЗ ТРЁХ КОМАНД И ОДИН РЕЗЕРВНЫЙ РЕГИСТР.
 *
 * # Почему серия, а не одна команда
 *
 * Документированные формы остатка (`UMODx`, `SMODx`) в таблице опкодов есть, но брать их нельзя:
 * у `SMODX` **свой дефект знака** (пример `09`: отрицательное делимое даёт 0 вместо −1), и он в этой
 * работе не трогается. Остаток считается из ЦЕЛОЧИСЛЕННОГО ДЕЛЕНИЯ, которое уже понижается:
 *
 * ```
 * sdivs  a, b, t   ; t = отсечение к нулю (канал ТОЛЬКО пятый — opcodes/e2k-opc.h:69)
 * muls   t, b, t   ; t = t * b
 * subs   a, t, d   ; d = a − t*b  — остаток СО ЗНАКОМ ДЕЛИМОГО
 * ```
 *
 * Семантика совпадает с обеими VM (`a % b`: `src/runtime/vm/reginterpreter.ts` и
 * `src/runtime/vm/interpreter.ts`), а формы `sdivs`, `muls`, `subs` **измерены на модели** —
 * тем же приёмом уже считается цифра в рантайме печати (`src/e2k/printRuntime.ts`).
 *
 * # Почему отдельный модуль
 *
 * Команды обязаны быть ОДНИМ источником для двух читателей: раскладка считает по ним байты
 * (`src/e2k/twoPassLayout.ts`), понижение выдаёт их в образ (`src/e2k/e2kRealRun.ts`). Разойдись
 * они — адреса уедут молча (класс `docs/hardware-debt.md` §3.35). Импортировать их из
 * `e2kRealRun.ts` нельзя: он сам импортирует `twoPassLayout`, и вышел бы цикл. Поэтому — как у
 * арены (`arenaRuntime.ts`) и математики (`mathRuntime.ts`): свой модуль для своей серии.
 *
 * # Резервный регистр: почему `%b[9]` и почему он резервируется УСЛОВНО
 *
 * `t` — временный регистр под частное, на три команды подряд. Раскладка о нём не знает: у носителя
 * `IR.rem d, a, b` объявлены только `def = [d]` и `use = [a, b]`. Значит `t` обязан быть
 * ЗАРЕЗЕРВИРОВАН — иначе раскладка отдаст его под значение, и значение будет затёрто молча.
 *
 * `%b[9]` выбран по ДВУМ границам, и обе названы:
 *
 * | граница | что даёт |
 * |---|---|
 * | выше `pinned` (входящие и параметры — `%b[0..1]`) | соглашение о передаче аргументов не трогается |
 * | ниже `ARRAY_REGISTERS` (`%b[10..15]`) | рантайм массивов не трогается |
 * | внутри ОБОИХ бюджетов — `ALLOCATABLE_REGISTERS` (`%b[0..9]`) и `CALLEE_REGISTERS` (`%b[8..15]`) | один резерв годится и точке входа, и вызываемой, без ветвлений по процедурам |
 *
 * Резервируется он **только той программе, где `IR.rem` действительно встречается** — и это не
 * «где-то ещё», а та же самая константа: у ядра `фильтр` (занимает `%b[0..9]`, десять регистров)
 * `%` не встречается вовсе, и unconditional-резерв отнял бы у него регистр, сдвинув закреплённые
 * числа 458 / 53 / 511 / 8800 и FIR 181.
 */
import type { AsmInstruction, Operand } from './backend';

const reg = (index: number): Operand => ({ kind: 'reg', index });

/**
 * Регистр под частное `t`. Не входит ни в `pinned`, ни в `ARRAY_REGISTERS`; выбран внутри обоих
 * бюджетов раскладки — см. таблицу в докладе модуля.
 */
export const REMAINDER_SCRATCH_REGISTER = 9;

/** Носитель остатка: его понижение — серия, а не одна команда. */
export const REMAINDER_CARRIER = 'IR.rem';

/**
 * Команды остатка `d = a % b` — ОДИН источник для раскладки (байты) и понижения (образ).
 *
 * Операнды в ассемблерной форме документа: результат последним (`[src1, src2, dst]`).
 */
export function remainderInstructions(
  a: number,
  b: number,
  d: number,
  scratch: number = REMAINDER_SCRATCH_REGISTER,
): readonly AsmInstruction[] {
  return [
    // Частное: канал пятый и только он — `sdivs` вне своего канала кодировщик отвергает
    // (измерено, `.tmp/idiv-channel.ts`).
    { mnemonic: 'sdivs', channel: 5, operands: [reg(a), reg(b), reg(scratch)] },
    { mnemonic: 'muls', channel: 0, operands: [reg(scratch), reg(b), reg(scratch)] },
    { mnemonic: 'subs', channel: 0, operands: [reg(a), reg(scratch), reg(d)] },
  ];
}

/**
 * Есть ли в потоке носитель остатка — по этому признаку конвейер добавляет резервный регистр.
 *
 * Считается по НОСИТЕЛЯМ, а не по тексту программы: имя операции языка ничего не значит для
 * раскладки, а резерв обязан появляться ровно тогда, когда серия действительно попадёт в образ.
 */
export function needsRemainderScratch(carriers: readonly { readonly mnemonic: string }[]): boolean {
  return carriers.some((carrier) => carrier.mnemonic === REMAINDER_CARRIER);
}
