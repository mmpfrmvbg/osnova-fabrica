/**
 * ФАЙЛОВЫЙ ВХОД НА ЦЕЛИ (L2 §42/§44, MVP): `читать(путь, буфер)` читает файл в СПИСОК.
 *
 * # Что здесь спрашивается и почему только прогоном
 *
 * Адрес ячеек списка и ответ ядра живут в регистрах ЦЕЛИ, а не в исходнике: `читать` — это
 * `open` + `read` + возврат блока рантайма массивов (D12), и «дошло ли» иначе как исполнением не
 * спросить. Числа: длина файла 24 байта и содержимое ЕГО ТРЕТЬЕЙ ЯЧЕЙКИ (6). Второе число —
 * различающее: без чтения ячейка 2 осталась бы нулём (предзаполнение списка), поэтому «6» доказывает
 * и адрес (указатель + 8, а не указатель), и порядок байт (8 байт, младшим вперёд), и то, что блок
 * `%b[12..15]` вернулся после системного вызова (иначе поле `лента[2]` не прочиталось бы).
 *
 * # Границы, названные здесь, а не в отчёте
 *
 * • **дескриптор не закрывается**: хранить его между двумя вызовами негде (`%b[12..15]` ядро
 *   зануляет, D12), а вернуть одновременно байты и fd нечем — `close` назван следующим атомом
 *   (`src/e2k/fileCallRuntime.ts`, шапка);
 * • **путь статический** `/tmp/input.osnova`: `argv[1]` — следующий атом, у языка его нет;
 * • **чтение одно**, `count` = 1 МиБ литералом: ядро проверяет весь запрошенный диапазон, поэтому
 *   сегмент данных отображается на `ячейки + 1 МиБ` (`dataSegmentBytes`).
 *
 * # Негативный контроль
 *
 * Второй прогон пишет в тот же путь ДРУГОЙ файл (ячейка 2 = 7) и обязан вернуть 1, а не 42: если
 * проверка читает не файл, а предзаполнение списка, она этого не различит.
 */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseV3 } from '../compiler-v3';
import { MINIMAL_BASE, buildElfFromCode } from './elfMinimal';
import { loweredProgram } from './lowered';
import { buildShim, runInQemu, toWslPath } from '../scripts/e2kQemuExec';

const ROOT = path.resolve(__dirname, '..', '..');
const WSL = 'C:\\Program Files\\WSL\\wsl.exe';
const WSL_DISTRO = 'e2k';
/** Тот же путь, что запекает генератор B2b и что читает носитель: разойтись они не должны. */
const ПУТЬ_В_ФАЙЛЕ = '/tmp/input.osnova';
/**
 * Отображённый сегмент данных: ячейки (их немного) + 1 МиБ запрошенного чтения. Меньше — `EFAULT`
 * (замер: `count` больше отображённого даёт код 242 = −14), и это не «файл короткий».
 */
const ДАННЫЕ = 0x120000;

/** Программа: список из трёх ячеек, чтение файла, ответ по третьей ячейке. */
const ПРОБА = `действие главная()
  пусть лента: Список Число = []
  пусть пт = 0
  пока пт < 3
    Списки.добавить(лента, 9, 0)
    пт = пт + 1
  конец пока
  пусть н = читать(${JSON.stringify(ПУТЬ_В_ФАЙЛЕ)}, лента)
  если н == 24
    если лента[2] == 6
      вернуть 42
    конец если
  конец если
  вернуть 1
конец главная
`;

const shim = buildShim();

/** Собрать ELF пробы: путь тот же, меняется только содержимое файла. */
function образ(): Uint8Array {
  const разобранный = parseV3(ПРОБА, 'fileRead.osnova');
  expect(разобранный.errors, 'разбор пробы').toEqual([]);
  const итог = loweredProgram(ПРОБА, {
    filename: 'fileRead.osnova',
    allowDeepArrayWrites: true,
    parse: () => ({ ast: разобранный.program ?? null, errors: разобранный.errors }),
  });
  expect(итог.ок, итог.ок ? '' : итог.отказ.причина.slice(0, 700)).toBe(true);
  if (!итог.ок) throw new Error('проба не понижена');
  return итог.значение.bytes;
}

const ELF = path.join(ROOT, '.tmp', 'file-read-qemu.elf');

/** Положить файл по статическому пути цели (WSL-сторона — та же машина, что у модели). */
function положить(ячейки: readonly number[]): void {
  const данные = Buffer.alloc(ячейки.length * 8);
  ячейки.forEach((значение, индекс) => данные.writeBigInt64LE(BigInt(значение), индекс * 8));
  const локально = path.join(ROOT, '.tmp', 'file-read-cells.bin');
  fs.writeFileSync(локально, данные);
  execFileSync(WSL, ['-d', WSL_DISTRO, '--', 'cp', toWslPath(локально), ПУТЬ_В_ФАЙЛЕ], { stdio: 'ignore' });
}

/** Прогон образа с подготовленным файлом; `undefined` — модель недоступна. */
function прогнать(ячейки: readonly number[], байты: Uint8Array): number | undefined {
  положить(ячейки);
  fs.writeFileSync(
    ELF,
    buildElfFromCode(байты, MINIMAL_BASE, { writable: true, dataSegmentBytes: ДАННЫЕ }).bytes,
  );
  return runInQemu(ELF, { shim: true, timeoutMs: 30_000 })?.status;
}

describe('файловый вход: `читать(путь, буфер)` на цели', () => {
  it('файл 24 байта: ответ ядра 24, третья ячейка 6 — иначе 1', () => {
    if (shim === undefined) return;
    expect(прогнать([1, 3, 6], образ())).toBe(42);
  });

  it('негативный контроль: ДРУГОЙ файл (ячейка 2 = 7) — ответ 1, а не 42', () => {
    if (shim === undefined) return;
    expect(прогнать([1, 3, 7], образ())).toBe(1);
  });

  it('пустой файл: ответ ядра 0 — ответ 1 (лента не тронута)', () => {
    if (shim === undefined) return;
    expect(прогнать([], образ())).toBe(1);
  });
});
