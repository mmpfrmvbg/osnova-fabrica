#!/bin/sh
# A4-5е, задача 17 (железо-бис): БАЙТЫ ПОД ОТКАЗОМ НА ЖИВОЙ МАШИНЕ.
#
# Вопрос один: те же байты на железе дают то же 9, что модель?
#   да    -> ложь НАША (понижения), не артефакт порта QEMU;
#   иное  -> СТОП-ДОКЛАД, меняется слой долга (как было со случаем 48).
# Здоровая половина (контроль в точке входа, отказов 0) обязана дать 1 — иначе разница не в плоскости.
#
# Порядок жёсткий: СНАЧАЛА сверка sha256 (`LC_ALL=C sha256sum -c`, судья — КОД ВОЗВРАТА, от локали
# не зависит), и только если сошлось — прогон. Ловушка локали из task-16 учтена.
#
# ЛОВУШКА, ПОЙМАННАЯ ПЕРВЫМ ЗАПУСКОМ: КИРИЛЛИЧЕСКИЕ ИМЕНА ПЕРЕМЕННЫХ ЭТОТ sh НЕ ПОНИМАЕТ.
# `код=$?` разбирается как КОМАНДА `код=132`, оболочка печатает «команда не найдена», и отчёт
# выходит с литералами `$код`/`$вердикт`. Имена переменных здесь только ASCII.
set -u
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$DIR" || exit 1

# ---- 1. СВЕРКА sha256 ДО ПРОГОНА -------------------------------------------------
LC_ALL=C sha256sum -c manifest.sha256 > verify.txt 2>&1
rc=$?
ok=$(grep -c ': OK$' verify.txt)
bad=$(grep -c ': FAILED$' verify.txt)
n=$(wc -l < manifest.sha256)
{
  echo ""
  echo "язык вывода принудительно C (LC_ALL=C), иначе coreutils печатает «ЦЕЛ»/«НЕ СОВПАЛО»"
  echo "код возврата sha256sum -c: $rc   <- главный судья, от локали не зависит"
  echo "файлов в манифесте: $n; строк OK: $ok; строк FAILED: $bad"
} >> verify.txt
echo "=== 1. СВЕРКА sha256 (verify.txt) ==="
cat verify.txt
echo ""

if [ "$rc" != "0" ] || [ "$bad" != "0" ] || [ "$ok" != "$n" ]; then
  echo "СТОП: sha256 НЕ СОШЁЛСЯ (OK $ok из $n, провалов $bad, код $rc) — ПРОГОН НЕ ДЕЛАЮ."
  echo "СТОП: прогон не делался; сверка не прошла (OK $ok из $n, провалов $bad, код $rc)." > lie-report.txt
  exit 2
fi
echo "сверка прошла: $ok из $n, провалов 0, код 0 — ПРОГОН РАЗРЕШЁН."
echo ""

# ---- 2. ПОДПИСЬ МАШИНЫ -----------------------------------------------------------
sh machine.sh > machine.txt 2>&1

# ---- 3. ПРОГОН ПРОБ --------------------------------------------------------------
# Форма запуска каноническая, как в run.sh кита: chmod +x, timeout 30, код берём сразу после.
run_elf() {
  chmod +x "$1" 2>/dev/null
  if command -v timeout >/dev/null 2>&1; then
    timeout 30 "$1"
  else
    "$1"
  fi
}

{
  echo "=== БАЙТЫ ПОД ОТКАЗОМ НА ЖЕЛЕЗЕ: седьмая тихая ложь ==="
  echo "хост: $(uname -m) / $(uname -sr)"
  echo "дата: $(date)"
  echo ""
} > lie-report.txt

while read -r elf etalon model; do
  [ -z "$elf" ] && continue
  # ТРИ прогона: код возврата у нас — предмет замера, и одиночный прогон не отличит
  # устойчивое число от случайного.
  codes=""
  first=""
  i=1
  while [ "$i" -le 3 ]; do
    run_elf "./$elf" >/dev/null 2>&1
    c=$?
    [ -z "$first" ] && first="$c"
    codes="$codes $c"
    i=$((i + 1))
  done
  if [ "$first" = "$model" ]; then
    verdict="СОВПАЛО С МОДЕЛЬЮ"
  else
    verdict="РАСХОЖДЕНИЕ С МОДЕЛЬЮ"
  fi
  echo "$elf: коды за 3 прогона:$codes | первый $first (эталон $etalon, модель под отказом $model) — $verdict" >> lie-report.txt
done < plan.txt

echo "=== 3. ПРОГОН ПРОБ (lie-report.txt) ==="
cat lie-report.txt
echo ""
echo "=== СТРОКА ХОСТ ИЗ ОТЧЁТА ==="
grep '^хост:' lie-report.txt || echo "СТРОКИ хост: НЕТ — отчёт не подписан!"
