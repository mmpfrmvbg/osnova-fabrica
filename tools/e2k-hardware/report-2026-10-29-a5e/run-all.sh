#!/bin/sh
# ПРОГОН КИТА НА ЖИВОЙ МАШИНЕ (A4-5е, задача 3). POSIX sh.
#
#   sh run-all.sh
#
# Порядок жёсткий: СНАЧАЛА сверка sha256 всех артефактов (`sha256sum -c`), и только
# если сошлось — прогон. Если sha256 не сошёлся, прогон НЕ делается (стоп-условие
# задачи: «sha256 не сошёлся -> доложить, ничего не доправлять»).
#
# ЛОВУШКА ЛОКАЛИ, ПОЙМАННАЯ ПЕРВЫМ ЗАПУСКОМ: на этой машине GNU coreutils говорит
# по-русски — `sha256sum -c` печатает «<файл>: ЦЕЛ», а не «: OK», и «НЕ СОВПАЛО»
# вместо «FAILED». Разбор ЛОКАЛИЗОВАННОГО текста поэтому и пропускал бы НАСТОЯЩИЙ
# провал, и ложно останавливал успешную сверку. Лечится `LC_ALL=C` (вывод строго
# `OK`/`FAILED`), а главный судья — КОД ВОЗВРАТА `sha256sum -c`, он от локали не
# зависит вовсе.
set -u
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$DIR" || exit 1

echo "каталог на машине: $DIR"
echo ""

# ---- 1. СВЕРКА sha256 ДО ПРОГОНА -------------------------------------------------
LC_ALL=C sha256sum -c manifest.sha256 > verify.txt 2>&1
rc=$?
ok=$(grep -c ': OK$' verify.txt)
bad=$(grep -c ': FAILED$' verify.txt)
n=$(wc -l < manifest.sha256)
{
  echo ""
  echo "язык вывода принудительно C (LC_ALL=C), иначе coreutils печатает «ЦЕЛ»/«НЕ СОВПАЛО»"
  echo "код возврата sha256sum -c: $rc   <- главный судья, от локали не зависит"
  echo "файлов в манифесте: $n; строк OK: $ok; строк FAILED: $bad"
} >> verify.txt

echo "=== 1. СВЕРКА sha256 (verify.txt) ==="
cat verify.txt
echo ""

if [ "$rc" != "0" ] || [ "$bad" != "0" ] || [ "$ok" != "$n" ]; then
  echo "СТОП: sha256 НЕ СОШЁЛСЯ (OK $ok из $n, провалов $bad, код $rc) — ПРОГОН НЕ ДЕЛАЮ."
  echo "СТОП: прогон не делался; сверка не прошла (OK $ok из $n, провалов $bad, код $rc)." > kit-report.txt
  exit 2
fi
echo "сверка прошла: $ok из $n, провалов 0, код 0 — ПРОГОН РАЗРЕШЁН."
echo ""

# ---- 2. ПОДПИСЬ МАШИНЫ -----------------------------------------------------------
sh machine.sh > machine.txt 2>&1
echo "=== 2. ПОДПИСЬ МАШИНЫ (machine.txt): $(wc -l < machine.txt) строк ==="
echo ""

# ---- 3. ПРОГОН КИТА (канонический run.sh) ----------------------------------------
sh run.sh > kit-report.txt 2>&1
rc2=$?
echo "=== 3. ПРОГОН КИТА (kit-report.txt), код возврата run.sh: $rc2 ==="
cat kit-report.txt
echo ""
echo "=== СТРОКА ХОСТ ИЗ ОТЧЁТА (читать прежде, чем ссылаться на числа) ==="
grep '^хост:' kit-report.txt || echo "СТРОКИ хост: В ОТЧЁТЕ НЕТ — отчёт не подписан!"
